set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_TRIGGER_ACTION" 
   (
    M_DEAL_NO           DN_TRN_TRIGGER_ALERT.PORTFOLIO_CODE%TYPE,
    M_ACTION            DN_TRN_TRIGGER_ALERT.SECURITY_CODE%TYPE,
    M_USER              DN_TRN_TRIGGER_ALERT.USER_NAME%TYPE,
    M_SCREAN_NAME       VARCHAR2
   )
   IS
    -- Procedue     : Trigger
    -- Created by   : SVA
    -- Created on   : 22-02-2005

   --M_INT_DATE       DN_REF_SECURITY_INT_PAY_DATES.INT_PAY_DATE%TYPE;
   --M_MATURITY_DATE  DN_REF_SECURITY.MATURITY_DATE%TYPE;
   M_COUNT1            NUMBER;

BEGIN
      INSERT INTO DN_TRN_TRIGGER_ACTION_BACKUP(DEAL_NO,ACTION_TAKE,USER_NAME,ACTION_TAKEN_TIME)
      SELECT DEAL_NO,ACTION_TAKE,USER_NAME,ACTION_TAKEN_TIME
      FROM   DN_TRN_TRIGGER_ALERT
      WHERE  DEAL_NO      = M_DEAL_NO AND ACTION_TAKE IS NOT NULL;

      UPDATE DN_TRN_TRIGGER_ALERT
      SET    ACTION_TAKE        = M_ACTION,
             USER_NAME          = M_USER,
             ACTION_TAKEN_TIME  = SYSDATE
      WHERE  DEAL_NO      = M_DEAL_NO;

       COMMIT;

EXCEPTION
  WHEN OTHERS THEN

RAISE_APPLICATION_ERROR(-20001,'M_DEAL_NO-'||M_DEAL_NO||'- M_ACTION-'||M_ACTION);

END DN_TRIGGER_ACTION;

/
