BEGIN
MS_FACE_VALUE:=M_SELL_AMT;
M_CURRENT:=0;

   FOR CUR_REC IN SALE_CUR
   LOOP

      M_CURRENT:=CUR_REC.FACE_VAL;

      IF(MS_FACE_VALUE>M_CURRENT) THEN----#####################################################


------------------------UPDATE DN_TRN_OUTP_SALE_SEC--------------------------------------------


     IF(M_CURR_CODE<>'SLR')THEN--CURRENCY
              UPDATE DN_TRN_OUTP_SALE_SEC
              SET    FACE_VALUE   = CUR_REC.FACE_VAL*M_CURRENCY_VALUE
              WHERE  DEAL_NO =M_DEAL_NO   AND
                     SECURITY_CODE =CUR_REC.SECURITY_CODE  AND
                     SERIAL_NO     =CUR_REC.SERIAL_NO;

              IF SQL%NOTFOUND THEN
                 INSERT INTO DN_TRN_OUTP_SALE_SEC
                  (DEAL_NO,SECURITY_CODE,SERIAL_NO,FACE_VALUE)
                 VALUES
                   (M_DEAL_NO,CUR_REC.SECURITY_CODE,CUR_REC.SERIAL_NO,CUR_REC.FACE_VAL*M_CURRENCY_VALUE);
              END IF;


       ELSE--CURRENCY
              UPDATE DN_TRN_OUTP_SALE_SEC
              SET    FACE_VALUE   = CUR_REC.FACE_VAL
              WHERE  DEAL_NO =M_DEAL_NO   AND
                     SECURITY_CODE =CUR_REC.SECURITY_CODE  AND
                     SERIAL_NO     =CUR_REC.SERIAL_NO;

              IF SQL%NOTFOUND THEN
                 INSERT INTO DN_TRN_OUTP_SALE_SEC
                  (DEAL_NO,SECURITY_CODE,SERIAL_NO,FACE_VALUE)
                 VALUES
                   (M_DEAL_NO,CUR_REC.SECURITY_CODE,CUR_REC.SERIAL_NO,CUR_REC.FACE_VAL);
              END IF;

        END IF;--CURRENCY
        MS_FACE_VALUE:=MS_FACE_VALUE-M_CURRENT;

   ELSIF(MS_FACE_VALUE=M_CURRENT) THEN----###################################################


  -------------------UPDATE DN_TRN_OUTP_SALE_SEC----------------------------------------------

       IF(M_CURR_CODE<>'SLR')THEN--CURRENCY
              UPDATE DN_TRN_OUTP_SALE_SEC
              SET    FACE_VALUE   = CUR_REC.FACE_VAL*M_CURRENCY_VALUE
              WHERE  DEAL_NO =M_DEAL_NO   AND
                     SECURITY_CODE =CUR_REC.SECURITY_CODE  AND
                     SERIAL_NO     =CUR_REC.SERIAL_NO;

              IF SQL%NOTFOUND THEN
                 INSERT INTO DN_TRN_OUTP_SALE_SEC
                  (DEAL_NO,SECURITY_CODE,SERIAL_NO,FACE_VALUE)
                 VALUES
                   (M_DEAL_NO,CUR_REC.SECURITY_CODE,CUR_REC.SERIAL_NO,CUR_REC.FACE_VAL*M_CURRENCY_VALUE);
              END IF;


       ELSE--CURRENCY
              UPDATE DN_TRN_OUTP_SALE_SEC
              SET    FACE_VALUE   = CUR_REC.FACE_VAL
              WHERE  DEAL_NO =M_DEAL_NO   AND
                     SECURITY_CODE =CUR_REC.SECURITY_CODE  AND
                     SERIAL_NO     =CUR_REC.SERIAL_NO;

              IF SQL%NOTFOUND THEN
                 INSERT INTO DN_TRN_OUTP_SALE_SEC
                  (DEAL_NO,SECURITY_CODE,SERIAL_NO,FACE_VALUE)
                 VALUES
                   (M_DEAL_NO,CUR_REC.SECURITY_CODE,CUR_REC.SERIAL_NO,CUR_REC.FACE_VAL);
              END IF;

       END IF;--CURRENCY
       EXIT;
 END IF;
 END LOOP;--CURSOR
--***SCRIPLESS

END DN_SAVE_NOPART_ALLO_SL;

