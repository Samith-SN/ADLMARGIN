--"DN_SAVE_NOPART_ALLO_SL"  CURSOR AND
-- INVENTORY DETAIL DISPLAY QUERIES IN (FO/BO MODIFICATION,NEW) OPTIONS

SELECT   X.DEAL_NO DEAL_NO,
             X.SERIAL_NO SERIAL_NO,
             X.FACE_VAL FACE_VAL,
             X.DEAL_YIELD YIELD,
             X.YIELD_WITH_BROKERAGE YIELD_WITH_BROKERAGE,
             X.FACE_VAL  FACE_VALUE,
             X.INITIAL_COST  COST,
             X.BROKERAGE  BROKERAGE,
             X.PRICE_INT_ACCR  PRICE_INT_ACCR,
             X.CARR_VAL CARR_VAL,
             X.COUP_INT_PURCH  COUP_INT_PURCH,
             X.COUP_INT_ACCR  COUP_INT_ACCR,
             X.TOT_COUP_INT  TOT_COUP_INT,
             X.EFF_VALDATE   EFF_VALDATE,
             X.SECURITY_CODE SECURITY_CODE ,
             X.DEAL_YIELD DEAL_YIELD,
             NVL(X.ORG_SERNO,'N/A') ORG_SERNO
    FROM    DN_INV_OUTPS_DEAL_SERIAL_NO X,
            DN_TRN_OUTP_SALE A ,
            DN_REF_PORTFOLIO B
    WHERE   A.DEAL_NO=M_DEAL_NO  AND
            A.SELL_PORTFOLIO_CODE=B.PORTFOLIO_CODE  AND
            B.PF_TYPE='P' AND
            A.SELL_PORTFOLIO_CODE=X.PORTFOLIO_CODE  AND
            X.SECURITY_CODE=A.SECURITY_CODE  AND
            X.SCRIP_STATUS='SL' AND
            X.SERIAL_NO_STATUS='INV' AND
            X.FACE_VAL>0 AND
           -- TO_DATE(TO_CHAR(X.EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')AND
            ---- commented by WJ on 24-05-2011 forperformance issue
            X.EFF_VALDATE <= A.EFF_VALDATE AND
           ---------------//////////////////// X.DEAL_YIELD=M_ORG_SERNO AND
            DECODE(DN_GET_INSTRUMENT_YIELD_TYPE(A.INST_TYPE),'W',X.YIELD_WITH_BROKERAGE,X.DEAL_YIELD)=M_ORG_SERNO AND

            DECODE(DN_GET_INSTRUMENT_YIELD_TYPE(A.INST_TYPE),'W',DN_GET_DEAL_INVENTORY_TYPE(X.DEAL_NO,A.INVENTORY_TYPE,A.BUY_PORTFOLIO_CODE),'YES')='YES' AND --ADDED BY SVA ON 23-03-2005 FOR CUSTODIAN INVENTORY
/* ---- commented by WJ on 25-05-2011 forperformance issue
            X.SERIAL_NO NOT IN (SELECT SERIAL_NO
                                FROM   DN_TRN_OUTP_SALE_SEC A,DN_TRN_OUTP_SALE B
                                WHERE  A.DEAL_NO=B.DEAL_NO AND
                                       B.APP_STATUS NOT IN ('CONF','CANCEL')
								UNION
                                SELECT J.SERIAL_NO
                                FROM   DN_TRN_REPO_FRESH_SERIAL_NO J,
                                       DN_TRN_REPO_FRESH B
								WHERE  J.DEAL_NO=B.DEAL_NO AND B.APP_STATUS NOT IN ('CONF','CANCEL')

                                UNION
								SELECT J.SERIAL_NO
								FROM   DN_TRN_REPO_ROLLOVER_SERIAL_NO J,
								       DN_TRN_REPO_ROLLOVER B
							    WHERE  J.DEAL_NO=B.DEAL_NO AND
									   B.APP_STATUS NOT IN ('CONF','CANCEL')

                                       )AND
           RETURN_ALLO_STATUS(X.SERIAL_NO,X.SECURITY_CODE,' ',' ',TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY'),'OR')='Y'
*/
                       (SELECT COUNT(SERIAL_NO)
		                           FROM   DN_TRN_OUTP_SALE_SEC A,DN_TRN_OUTP_SALE B
		                           WHERE  A.DEAL_NO=B.DEAL_NO AND B.APP_STATUS IN ('ENT','VERI','APPRO1','APPRO2','PROC')
                                    AND A.SERIAL_NO=X.SERIAL_NO) =0  
                                      
  ORDER BY  X.EFF_VALDATE,X.FACE_VAL ASC ;


MS_SELL_PORTFOLIO_CODE         DN_INV_OUTPS_DEAL_SERIAL_NO.PORTFOLIO_CODE%TYPE;
MS_EFF_VALDATE                 DN_INV_OUTPS_DEAL_SERIAL_NO.EFF_VALDATE%TYPE;
MS_INST_TYPE                   DN_INV_OUTPS_DEAL_SERIAL_NO.INST_TYPE%TYPE;
MS_SECURITY_CODE               DN_TRN_OUTP_SALE.SECURITY_CODE%TYPE;
MS_YIELD                        DN_TRN_OUTP_SALE.YIELD%TYPE;
MS_YIELD_WITH_BROKERAGE         DN_TRN_OUTP_SALE.YIELD%TYPE;
