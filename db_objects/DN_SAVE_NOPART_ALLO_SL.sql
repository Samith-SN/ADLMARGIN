M_SWAP_SERNO4                   DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
MM_SWAP_SERNO1                  DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
MM_SWAP_SERNO2                  DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
MM_SWAP_SERNO3                  DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
