  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_FIN_BROKE_FEEAMOUNT" 
(
	MN_EFFVALDATE    VARCHAR2,
	MN_FACEVAL       NUMBER,
	MN_MATURITY      VARCHAR2,
	MN_BROKERAGE     NUMBER


)
RETURN NUMBER
AS
M_EFFVALDATE DATE;
M_MATURITY DATE;

BEGIN
M_EFFVALDATE :=TO_DATE(MN_EFFVALDATE,'DD-MM-YYYY');
M_MATURITY :=TO_DATE(MN_MATURITY,'DD-MM-YYYY');

IF (  ADD_MONTHS(M_EFFVALDATE,12) <= M_MATURITY ) THEN

     RETURN ROUND((((MN_FACEVAL*(MN_BROKERAGE/100))/365)*365),2);

ELSE

     RETURN ROUND((((MN_FACEVAL*(MN_BROKERAGE/100))/365)*(M_MATURITY-M_EFFVALDATE)),2);

END IF;
END DN_FIN_BROKE_FEEAMOUNT;

