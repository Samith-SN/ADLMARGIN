set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_A_2_9_CURR" 
(
M_PORTF_CODE      DN_ACC_LICENCEE_GEN_ACCOUNT.PORTFOLIO_CODE%TYPE,
M_DN_PORTF_CODE   DN_ACC_LICENCEE_GEN_ACCOUNT.DN_PORTFOLIO_CODE%TYPE,
M_TRNDATE         DN_ACC_LICENCEE_GEN_ACCOUNT.TRNDATE%TYPE,
M_TRNAMOUNT       DN_ACC_LICENCEE_GEN_ACCOUNT.TRNAMOUNT%TYPE,
M_DOCREFNO        DN_ACC_LICENCEE_GEN_ACCOUNT.DOCREFNO%TYPE,
M_ACC_SYS_REFNO   DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE,
M_DEALNO          DN_TRN_BO_SETTL_RECEIPT.SUS_REF_NO%TYPE
)
AS

/* PROCEDURE  - A_2_9 Receipt of Proceeds on a Security Sold ---FOR CURRENCY
   SYSTEM     - DEALNET
   CREATED BY - NIRMALA FERNANDO
   CREATED ON - 03-01-2002 */

M_COUNT1                              NUMBER;
M_REC_FROM_INT_BAL_AMT_CURR           DN_ACC_SUS_RECEIPT.REC_FROM_INT_BAL_AMT_CURR%TYPE;
M_CURR_CODE                           DN_TRN_DEAL_CURRENCY.CURR_CODE%TYPE;
M_REC_FROM_INT_BAL_AMT                DN_ACC_SUS_RECEIPT.REC_FROM_INT_BAL_AMT_CURR%TYPE;
M_FIRST                               DN_ACC_SUS_RECEIPT.REC_FROM_INT_BAL_AMT_CURR%TYPE;
M_CURRENCY_VALUE                      DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE;
BEGIN

  SELECT REC_FROM_INT_BAL_AMT_CURR
  INTO   M_REC_FROM_INT_BAL_AMT_CURR
  FROM   DN_ACC_SUS_RECEIPT
  WHERE  SUS_REF_NO=M_DEALNO AND
         REC_FROM_INT_BAL_AMT_CURR > 0 AND
         RECEIVER = M_PORTF_CODE AND
         PAYER = M_DN_PORTF_CODE;

   SELECT CURR_CODE
   INTO   M_CURR_CODE
   FROM   DN_TRN_DEAL_CURRENCY
   WHERE  DEAL_NO=M_DEALNO;


  SELECT  CURRENCY_VALUE
  INTO    M_CURRENCY_VALUE
  FROM    DN_REF_EXCHANGE_RATES
  WHERE   CURR_CODE=M_CURR_CODE;

  SELECT REC_FROM_INT_BAL_AMT
  INTO   M_REC_FROM_INT_BAL_AMT
  FROM   DN_ACC_SUS_RECEIPT
  WHERE  SUS_REF_NO=M_DEALNO AND
         RECEIVER = M_PORTF_CODE AND
         PAYER = M_DN_PORTF_CODE;

 M_FIRST :=(M_REC_FROM_INT_BAL_AMT_CURR*M_CURRENCY_VALUE);

 IF ((M_REC_FROM_INT_BAL_AMT_CURR*M_CURRENCY_VALUE)>M_REC_FROM_INT_BAL_AMT)THEN

    INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
      (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,ACC_SYS_REFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'800','DR',M_FIRST,M_DOCREFNO,M_ACC_SYS_REFNO,'Receipt of Proce on a Sec Sold','409');
    INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
      (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'409','CR',M_REC_FROM_INT_BAL_AMT,M_DOCREFNO,'Receipt of Proce on a Sec Sold','800');
    INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
      (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'115','CR',(M_FIRST-M_REC_FROM_INT_BAL_AMT),M_DOCREFNO,'EXCHANGE-GAIN','800');

ELSIF ((M_REC_FROM_INT_BAL_AMT_CURR*M_CURRENCY_VALUE)<M_REC_FROM_INT_BAL_AMT)THEN

    INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
      (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,ACC_SYS_REFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'800','DR',M_FIRST,M_DOCREFNO,M_ACC_SYS_REFNO,'Receipt of Proce on a Sec Sold','409');
    INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
      (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'409','CR',M_REC_FROM_INT_BAL_AMT,M_DOCREFNO,'Receipt of Proce on a Sec Sold','800');
    INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
      (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'116','DR',(M_REC_FROM_INT_BAL_AMT-M_FIRST),M_DOCREFNO,'EXCHANGE-LOSS','800');

END IF;

END DN_ACC_A_2_9_CURR;

