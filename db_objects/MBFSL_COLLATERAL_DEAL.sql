set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_COLLATERAL_DEAL" 
(
 M_COLL_DEALNO          DN_COLLATERAL_DEALS.COLL_DEALNO%TYPE,
 M_DEALNO               DN_COLLATERAL_DEALS.DEALNO%TYPE
)
AS

  --CREATED BY : NIRMALA FERNANDO
  --CREATED ON : 10-10-2002
  --TO SAVE THE COLLATERAL DEAL NUMBERS ALONG WITH THE DEALNO

M_MATURITY_DATE      DN_TRN_REPO_FRESH.MATURITY_DATE%TYPE;
M_LEG1_VALUE         DN_TRN_REPO_FRESH.LEG1_VALUE%TYPE;
 BEGIN


    SELECT A.MATDATE,A.LEG1
    INTO   M_MATURITY_DATE,M_LEG1_VALUE
    FROM
    (SELECT MATURITY_DATE MATDATE ,LEG1_VALUE LEG1
    FROM   DN_TRN_REPO_FRESH
    WHERE  DEAL_NO=M_DEALNO
    UNION
    SELECT MATURITY_DATE,LEG1_VALUE
    FROM   DN_TRN_REPO_ROLLOVER
    WHERE  DEAL_NO=M_DEALNO)A;


    INSERT INTO DN_COLLATERAL_DEALS
    (DEALNO,COLL_DEALNO,ENTER_DATE,MATURITY_DATE,LEG1_VALUE)
    VALUES
    (M_DEALNO,M_COLL_DEALNO,SYSDATE,M_MATURITY_DATE,M_LEG1_VALUE);

 COMMIT;
  END MBFSL_COLLATERAL_DEAL;

/
