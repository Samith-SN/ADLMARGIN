--  DDL for Procedure DN_INV_OUTPS_INTR_SL_TRANSFER
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_INV_OUTPS_INTR_SL_TRANSFER" 

(
M_PROCESS_DATE    DN_SYS_PARAMETER.LAST_DAILY%TYPE
)
AS

CURSOR SERIAL IS

    SELECT
       A.PORTFOLIO_CODE,
       A.EFF_VALDATE, A.INST_TYPE,
       A.SECURITY_CODE,
       A.DEAL_NO,A.SERIAL_NO,
       A.DEAL_YIELD,A.YIELD_WITH_BROKERAGE,
       A.SCRIP_FACE_VAL,A.FACE_VAL,
       A.CARR_VAL,A.COUP_INT_ACCR,
       NVL(DN_FIN_PRICE_INTEREST(A.SECURITY_CODE,A.YIELD_WITH_BROKERAGE,M_PROCESS_DATE+1,FACE_VAL,CARR_VAL,DECODE(A.INST_TYPE,'TBOND','AA','A364')),0),
       NVL(DN_FIN_COUPON_INTEREST(A.SECURITY_CODE,A.YIELD_WITH_BROKERAGE,M_PROCESS_DATE+1,FACE_VAL,COUP_INT_ACCR,DECODE(A.INST_TYPE,'TBOND','AA','A364'),A.COUP_INT_PURCH),0),
       A.SERIAL_NO_STATUS
    FROM
       DN_INV_OUTPS_DEAL_SERIAL_NO A
    WHERE
       A.EFF_VALDATE<=M_PROCESS_DATE
       AND
       (A.SALE_EFF_VALDATE IS NULL OR SALE_EFF_VALDATE>M_PROCESS_DATE)
       --AND
      -- A.DEAL_NO=B.DEAL_NO
       AND
       A.SERIAL_NO_STATUS NOT IN ('SSW','TRF')
       AND
       A.DEAL_NO LIKE 'TS%'       ;


 M_SECURITY_CODE           DN_REF_SECURITY.SECURITY_CODE%TYPE;
 M_PORTFOLIO_CODE          DN_INV_OUTPS_DEAL_SEC.PORTFOLIO_CODE%TYPE;
 M_EFF_VALDATE             DN_INV_OUTPS_DEAL_SEC.EFF_VALDATE%TYPE;
 M_INST_TYPE              DN_INV_OUTPS_DEAL_SEC.INST_TYPE%TYPE;
 M_FACE_VAL                DN_INV_OUTPS_DEAL_SEC.FACE_VAL%TYPE;
 M_TRN_TYPE                DN_INV_OUTPS_DEAL_SEC.TRN_TYPE%TYPE;
 M_DEAL_NO                DN_INV_OUTPS_DEAL_SEC.DEAL_NO%TYPE;

 M_DEAL_YIELD              DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_YIELD%TYPE;
 M_YIELD_WITH_BROKERAGE    DN_INV_OUTPS_DEAL_SERIAL_NO.YIELD_WITH_BROKERAGE%TYPE;
 M_CARR_VAL                DN_INV_OUTPS_DEAL_SERIAL_NO.CARR_VAL%TYPE;
 M_COUP_INT_ACCR           DN_INV_OUTPS_DEAL_SERIAL_NO.COUP_INT_ACCR%TYPE;
 M_PRICE_INT               DN_INV_OUTPS_DEAL_SERIAL_NO.PRICE_INT_ACCR%TYPE;
 M_COUP_INT                DN_INV_OUTPS_DEAL_SEC.COUP_INT_ACCR%TYPE;
 M_SERIAL_NO               DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
 M_SERIAL_NO_STATUS        DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO_STATUS%TYPE;
 M_SCRIP_FACE_VAL          DN_INV_OUTPS_DEAL_SERIAL_NO.SCRIP_FACE_VAL%TYPE;

BEGIN


OPEN SERIAL;

   LOOP

      FETCH  SERIAL INTO

      M_PORTFOLIO_CODE,M_EFF_VALDATE,M_INST_TYPE,
      M_SECURITY_CODE,M_DEAL_NO,M_SERIAL_NO,M_DEAL_YIELD,
      M_YIELD_WITH_BROKERAGE,M_SCRIP_FACE_VAL,M_FACE_VAL,M_CARR_VAL,
      M_COUP_INT_ACCR,M_PRICE_INT,M_COUP_INT,M_SERIAL_NO_STATUS;


      EXIT WHEN SERIAL%NOTFOUND;

      UPDATE DN_INV_INT_OUTPS_DEAL_SERNO
      SET  PRICE_INT  =  M_PRICE_INT,
           COUP_INT   =  (COUP_INT+M_COUP_INT)--modified by nirmala on 04-03-2001 bu adding (COUP_INT+M_COUP_INT)
      WHERE
           PROCESS_DATE=M_PROCESS_DATE
           AND
           PORTFOLIO_CODE=M_PORTFOLIO_CODE
           AND
           EFF_VALDATE=M_EFF_VALDATE
           AND
           INST_TYPE=M_INST_TYPE
           AND
           SECURITY_CODE=M_SECURITY_CODE
           AND
           SERIAL_NO=M_SERIAL_NO
           AND
           DEAL_NO=M_DEAL_NO;

    IF SQL%NOTFOUND THEN

    INSERT INTO DN_INV_INT_OUTPS_DEAL_SERNO
      (PROCESS_DATE, PORTFOLIO_CODE,
       EFF_VALDATE, INST_TYPE,
       SECURITY_CODE,
       DEAL_NO,SERIAL_NO,
       DEAL_YIELD,YIELD_WITH_BROKERAGE,
       SCRIP_FACE_VAL,FACE_VAL,
       CARR_VAL, COUP_INT_ACCR,
       PRICE_INT,COUP_INT,
       SERIAL_NO_STATUS
      )
    VALUES
      (M_PROCESS_DATE,M_PORTFOLIO_CODE,
       M_EFF_VALDATE,M_INST_TYPE,
       M_SECURITY_CODE,
       M_DEAL_NO,M_SERIAL_NO,
       M_DEAL_YIELD,M_YIELD_WITH_BROKERAGE,
       M_SCRIP_FACE_VAL,M_FACE_VAL,
       M_CARR_VAL,M_COUP_INT_ACCR,
       M_PRICE_INT,M_COUP_INT,
       M_SERIAL_NO_STATUS);

    END IF;

     UPDATE DN_INV_OUTPS_DEAL_SERIAL_NO A
     SET  A.PRICE_INT_ACCR=A.PRICE_INT_ACCR+M_PRICE_INT,
          A.CARR_VAL=A.CARR_VAL+M_PRICE_INT,
          A.COUP_INT_ACCR=A.COUP_INT_ACCR+M_COUP_INT,
          A.TOT_COUP_INT=A.TOT_COUP_INT+M_COUP_INT
     WHERE
       PORTFOLIO_CODE=M_PORTFOLIO_CODE
       AND
       EFF_VALDATE=M_EFF_VALDATE
       AND
       INST_TYPE=M_INST_TYPE
       AND
       SECURITY_CODE=M_SECURITY_CODE
       AND
       SERIAL_NO=M_SERIAL_NO
       AND
       DEAL_NO=M_DEAL_NO;


END LOOP;

CLOSE SERIAL;

END DN_INV_OUTPS_INTR_SL_TRANSFER;

/
