  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_F_6_2" 
(
M_INVOICE_NO        DN_TRN_BROKERAGE.INVOICE_NO%TYPE,
M_DOCREFNO          DN_TRN_BROKERAGE.DEAL_NO%TYPE,
M_PORTF_CODE        DN_TRN_BROKERAGE.BROK_CODE%TYPE,
M_DN_PORTF_CODE     DN_TRN_BROKERAGE.CP_CODE%TYPE,
M_TRNAMOUNT         DN_TRN_BROKERAGE.BROK_FEE_AMOUNT%TYPE,
M_TRNAMOUNT2        DN_TRN_BROKERAGE.BROK_GST%TYPE
)
AS

/* PROCEDURE  - F_6_2 BROKERAGE EXPENSE OF PORTFOLIO WHEN PURCHASING A SECURITY
   SYSTEM     - DEALNET
   CREATED BY - LATHIKA
   CREATED ON - 29/DEC/1999
   */

M_PF_TYPE         DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_TRNDATE         DN_TRN_BL_FUND.eff_valdate%TYPE;
M_TRNDATE2        DN_TRN_BL_FUND.eff_valdate%TYPE;

M_INST_TYPE       DN_TRN_SWAP_OUTRIGHT.p1_inst_type%TYPE;
M_INST_TYPE2      DN_TRN_SWAP_OUTRIGHT.p2_inst_type%TYPE;

BEGIN

SELECT PF_TYPE
INTO M_PF_TYPE
FROM DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE=M_DN_PORTF_CODE ;

IF M_PF_TYPE='P' THEN

IF SUBSTR(M_DOCREFNO,1,2)='OR' THEN
    SELECT EFF_VALDATE,inst_type
    INTO M_TRNDATE,M_INST_TYPE
    FROM DN_TRN_OUTP_SALE
    WHERE DEAL_NO=M_DOCREFNO;

ELSIF SUBSTR(M_DOCREFNO,1,2)='SO' THEN
    SELECT P1_EFF_VALDATE,P2_EFF_VALDATE,p1_inst_type,p2_inst_type
    INTO M_TRNDATE,M_TRNDATE2,M_INST_TYPE,M_INST_TYPE2
    FROM DN_TRN_SWAP_OUTRIGHT
    WHERE DEAL_NO=M_DOCREFNO;

END IF;


IF (SUBSTR(M_DOCREFNO,1,2)='OR') THEN

-------(2)-------------------------------------
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'405','DR',M_TRNAMOUNT2,M_DOCREFNO,'SETT OF GST ON BROK-PORT','800');

INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'800','CR',M_TRNAMOUNT2,M_DOCREFNO,'SETT OF GST ON BROK-PORT','405');


ELSIF (SUBSTR(M_DOCREFNO,1,2)='SO') THEN
-------RECORDING GST RECEIVABLE------------------------------------
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'405','DR',M_TRNAMOUNT2,M_DOCREFNO,'SETT OF GST ON BROK-PORT','800');

INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'800','CR',M_TRNAMOUNT2,M_DOCREFNO,'SETT OF GST ON BROK-PORT','405');


INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_DN_PORTF_CODE,M_PORTF_CODE,M_TRNDATE2,'405','DR',M_TRNAMOUNT2,M_DOCREFNO,'SETT OF GST ON BROK-PORT','800');

INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_DN_PORTF_CODE,M_PORTF_CODE,M_TRNDATE2,'800','CR',M_TRNAMOUNT2,M_DOCREFNO,'SETT OF GST ON BROK-PORT','405');


END IF;
END IF;

END DN_ACC_F_6_2;

