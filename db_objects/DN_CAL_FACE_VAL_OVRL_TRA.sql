  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_CAL_FACE_VAL_OVRL_TRA" 
   RETURN  REAL

   IS
    -- Function     : This returns face value from
    -- System       : DEALNET System
    -- Created by   : V.Sukathisvaran
    -- Created on   : 20/12/1999

	  TOTAL		DN_INV_OUTPS_DEAL_SEC.FACE_VAL%TYPE;
    TOTAL_B		DN_INV_OUTPS_DEAL_SEC.FACE_VAL%TYPE;
    TOTAL_S		DN_INV_OUTPS_DEAL_SEC.FACE_VAL%TYPE;
    TOTAL1		DN_INV_OUTPS_DEAL_SEC.FACE_VAL%TYPE;


BEGIN


	SELECT SUM(FACE_VAL) INTO TOTAL_B
		FROM DN_INV_OUTPS_DEAL_SEC
        WHERE EFF_VALDATE <= SYSDATE AND TRN_TYPE ='B' AND SECURITY_CODE IN
		(
		SELECT SECURITY_CODE FROM DN_REF_SECURITY WHERE  MATURITY_DATE < SYSDATE
		);
	SELECT SUM(FACE_VAL) INTO TOTAL_S
		FROM DN_INV_OUTPS_DEAL_SEC
        WHERE EFF_VALDATE <= SYSDATE AND TRN_TYPE='S' AND SECURITY_CODE IN
		(
		SELECT SECURITY_CODE FROM DN_REF_SECURITY WHERE  MATURITY_DATE < SYSDATE
		);
	SELECT SUM(FACE_VAL) INTO TOTAL1
		FROM DN_INV_OUTPS_DEAL_SERIAL_NO
        WHERE EFF_VALDATE <= SYSDATE AND SERIAL_NO_STATUS='INV' AND SECURITY_CODE IN
		(
		SELECT SECURITY_CODE FROM DN_REF_SECURITY WHERE  MATURITY_DATE < SYSDATE
		);

    TOTAL:=TOTAL_B+TOTAL_S+TOTAL1;

RETURN TOTAL;

END DN_CAL_FACE_VAL_OVRL_TRA;

