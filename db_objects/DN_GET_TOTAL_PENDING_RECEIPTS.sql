--  DDL for Function DN_GET_TOTAL_PENDING_RECEIPTS
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_TOTAL_PENDING_RECEIPTS" 
(
 PORT           DN_TRN_BO_SETTL_RECEIPT_TMP.SELL_PORTFOLIO_CODE%TYPE,
 CP_CODE        DN_TRN_BO_SETTL_RECEIPT_TMP.ID_PORTFOLIO_CODE%TYPE,
 EFFDATE        VARCHAR2
)
 RETURN NUMBER
 AS
 M_TOTAL_PENDING       DN_TRN_BO_SETTL_RECEIPT_TMP.REC_AMOUNT%TYPE;


 BEGIN
 
   SELECT SUM(REC_AMOUNT) INTO M_TOTAL_PENDING
   FROM DN_TRN_BO_SETTL_RECEIPT_TMP A
   WHERE SELL_PORTFOLIO_CODE=PORT
   AND EFF_VALDATE=TO_DATE(EFFDATE,'DD/MM/YYYY')
   AND ID_PORTFOLIO_CODE=CP_CODE
   AND APP_STATUS='ENT';
       
                
             



 RETURN  NVL(M_TOTAL_PENDING,0);

END DN_GET_TOTAL_PENDING_RECEIPTS;

