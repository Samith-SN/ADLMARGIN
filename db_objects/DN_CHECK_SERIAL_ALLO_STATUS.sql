set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CHECK_SERIAL_ALLO_STATUS" 
(
M_DEAL_NO    DN_TRN_REPO_FRESH.DEAL_NO%TYPE
)
AS

M_COUNT1                    NUMBER;
M_SERIAL_NO                 DN_TRN_REPO_FRESH_SERIAL_NO.SERIAL_NO%TYPE; ---ADD BY INDITHA 2005-7-19 VC05-012
M_SECURITY_CODE             DN_TRN_REPO_FRESH_SERIAL_NO.SECURITY_CODE%TYPE; ---ADD BY INDITHA 2005-7-19 VC05-012


/********************************************************
     DESCRIPTION:CHECK SERIAL NOS ALLOCATION STATUS FOR DEAL
     CREATE BY:INDITHA
     DATE:2005-7-20
**********************************************************/

BEGIN

----------------------ADD BY INDITHA 2005-7-19 VC05-012---------------------------------

SELECT  COUNT(*)
INTO    M_COUNT1
FROM    DN_TRN_REPO_FRESH A,DN_REF_PORTFOLIO B
WHERE   A.DEAL_NO=M_DEAL_NO  AND
        A.BORR_PORTFOLIO_CODE=B.PORTFOLIO_CODE AND
        B.PF_TYPE='P' AND B.ACTIVE_STATUS='Y';

IF M_COUNT1>0 THEN--CHECK RF

FOR X IN (SELECT A.SECURITY_CODE,A.SERIAL_NO,B.BORR_PORTFOLIO_CODE,A.PREV_DEAL_NO
FROM  DN_TRN_REPO_FRESH_SERIAL_NO A,DN_TRN_REPO_FRESH B
WHERE A.DEAL_NO=B.DEAL_NO AND A.DEAL_NO=M_DEAL_NO AND (SUBSTR(NVL(A.PREV_DEAL_NO,'OR'),1,2)='OR')) LOOP


SELECT  COUNT(*)
INTO    M_COUNT1
FROM    DN_INV_OUTPS_DEAL_SERIAL_NO
WHERE   SERIAL_NO_STATUS IN ('SAD','SND') AND
        SECURITY_CODE=X.SECURITY_CODE AND
        SERIAL_NO=X.SERIAL_NO AND
        --PORTFOLIO_CODE=X.BORR_PORTFOLIO_CODE AND
        DEAL_NO=X.PREV_DEAL_NO;

IF ( M_COUNT1>0) THEN
    RAISE_APPLICATION_ERROR(-20201,'1.RF ALLOCATED SERIAL NUMBERS HAS BEEN ALREADY SOLD ' || ' SECURITY_CODE=' || X.SECURITY_CODE || '  SERIAL_NO=' || X.SERIAL_NO);
ELSE

SELECT COUNT(*)
INTO   M_COUNT1
FROM   DN_TRN_OUTP_SALE_SEC A,DN_TRN_OUTP_SALE B
WHERE  A.DEAL_NO=B.DEAL_NO AND
       A.SERIAL_NO=X.SERIAL_NO AND
       B.SELL_PORTFOLIO_CODE=X.BORR_PORTFOLIO_CODE AND
       B.APP_STATUS NOT IN ('CANCEL','CONF');

IF  (M_COUNT1>0) THEN
    RAISE_APPLICATION_ERROR(-20201,'2.RF ALLOCATED SERIAL NUMBERS HAS BEEN ALREADY SOLD ' || ' SECURITY_CODE=' || X.SECURITY_CODE || '  SERIAL_NO=' || X.SERIAL_NO);
END IF;

END IF;

END LOOP;

END IF;

----------CHECK FOR RR

SELECT  COUNT(*)
INTO    M_COUNT1
FROM    DN_TRN_REPO_ROLLOVER A,DN_REF_PORTFOLIO B
WHERE   A.DEAL_NO=M_DEAL_NO  AND
        A.BORR_PORTFOLIO_CODE=B.PORTFOLIO_CODE AND
        B.PF_TYPE='P' AND B.ACTIVE_STATUS='Y';


IF M_COUNT1>0 THEN

FOR X IN (SELECT A.SECURITY_CODE,A.SERIAL_NO,B.BORR_PORTFOLIO_CODE,A.PREV_DEAL_NO
FROM  DN_TRN_REPO_ROLLOVER_SERIAL_NO A,DN_TRN_REPO_ROLLOVER B
WHERE A.DEAL_NO=B.DEAL_NO AND A.DEAL_NO=M_DEAL_NO AND (SUBSTR(NVL(A.PREV_DEAL_NO,'OR'),1,2)='OR')) LOOP


SELECT  COUNT(*)
INTO    M_COUNT1
FROM    DN_INV_OUTPS_DEAL_SERIAL_NO
WHERE   SERIAL_NO_STATUS IN ('SAD','SND') AND
        SECURITY_CODE=X.SECURITY_CODE AND
        SERIAL_NO=X.SERIAL_NO AND
        --PORTFOLIO_CODE=X.BORR_PORTFOLIO_CODE AND
        DEAL_NO=X.PREV_DEAL_NO;

IF ( M_COUNT1>0) THEN
    RAISE_APPLICATION_ERROR(-20201,'1.RR ALLOCATED SERIAL NUMBERS HAS BEEN ALREADY SOLD ' || ' SECURITY_CODE=' || X.SECURITY_CODE || '  SERIAL_NO=' || X.SERIAL_NO);
ELSE

SELECT COUNT(*)
INTO   M_COUNT1
FROM   DN_TRN_OUTP_SALE_SEC A,DN_TRN_OUTP_SALE B
WHERE  A.DEAL_NO=B.DEAL_NO AND
       A.SERIAL_NO=X.SERIAL_NO AND
       B.SELL_PORTFOLIO_CODE=X.BORR_PORTFOLIO_CODE AND
       B.APP_STATUS NOT IN ('CANCEL','CONF');

IF  (M_COUNT1>0) THEN
    RAISE_APPLICATION_ERROR(-20201,'2.RR ALLOCATED SERIAL NUMBERS HAS BEEN ALREADY SOLD ' || ' SECURITY_CODE=' || X.SECURITY_CODE || '  SERIAL_NO=' || X.SERIAL_NO);
END IF;

END IF;

END LOOP;

END IF;---END OF RR

----------------------------------------------------------------------------------------
END;

