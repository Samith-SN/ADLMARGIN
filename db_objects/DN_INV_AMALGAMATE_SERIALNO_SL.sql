--  DDL for Procedure DN_INV_AMALGAMATE_SERIALNO_SL
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_INV_AMALGAMATE_SERIALNO_SL" 
(
  M_LAST_DAILY         DN_SYS_PARAMETER.LAST_DAILY%TYPE
)
AS
MM_SWAP_SERNO1                  DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
MM_SWAP_DEAL                     DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_NO%TYPE;
M_COUNT_OR                      NUMBER;
M_COUNT_RP                      NUMBER;

CURSOR ALL_CUR_OR IS
     SELECT   PORTFOLIO_CODE,
              EFF_VALDATE,
              INST_TYPE,
              SECURITY_CODE,
              DEAL_NO,
              DEAL_YIELD,
              YIELD_WITH_BROKERAGE,
              SUM(SCRIP_FACE_VAL)SCRIP_FACE_VAL,
              SUM(FACE_VAL)FACE_VAL,
              SUM(INITIAL_COST)INITIAL_COST,
              SUM(BROKERAGE)BROKERAGE,
              SUM(PRICE_INT_ACCR)PRICE_INT_ACCR,
              SUM(CARR_VAL)CARR_VAL,
              SUM(COUP_INT_PURCH)COUP_INT_PURCH,
              SUM(COUP_INT_ACCR)COUP_INT_ACCR,
              SUM(TOT_COUP_INT)TOT_COUP_INT,
              SUM(FWD_SALE)FWD_SALE,
              SUM(FWD_PURCHASE)FWD_PURCHASE,
              LOCATION,
              SUM(ALLO_REPO)ALLO_REPO,
              SUM(ALLO_BL)ALLO_BL,
              SUM(FWD_ALLO_REPO)FWD_ALLO_REPO,
              SUM(FWD_ALLO_BL)FWD_ALLO_BL

    FROM    DN_INV_OUTPS_DEAL_SERIAL_NO

    WHERE   SCRIP_STATUS='SL' AND
            SERIAL_NO_STATUS='INV' AND
            EFF_VALDATE<=TO_DATE(TO_CHAR(M_LAST_DAILY,'DD-MM-YYYY'),'DD-MM-YYYY') AND -- ADDED BY SM ON 07/12/2003
            SERIAL_NO NOT IN (SELECT SERIAL_NO
                                FROM  DN_TRN_OUTP_SALE_SEC A,DN_TRN_OUTP_SALE B
                                WHERE  A.DEAL_NO=B.DEAL_NO AND
                                       B.APP_STATUS NOT IN ('CONF','CANCEL'))AND
            SERIAL_NO NOT IN (SELECT SERIAL_NO
                                FROM   DN_INV_OUTPS_DEAL_SERNO_ALLO
                                WHERE  TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>= TO_DATE(TO_CHAR(M_LAST_DAILY,'DD-MM-YYYY'),'DD-MM-YYYY') )
 --THIS AMALGAMATION SHOULD ONLY BE DONE IF THE COUNT IS GREATER THAN 1


  GROUP BY  PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,SECURITY_CODE,DEAL_NO,DEAL_YIELD,YIELD_WITH_BROKERAGE,LOCATION
  ORDER BY  2,8 ASC;



  CURSOR ALL_CUR_RP IS
     SELECT   PORTFOLIO_CODE,
              EFF_VALDATE,
              INST_TYPE,
              SECURITY_CODE,
              DEAL_NO,
              SUM(SCRIP_FACE_VAL)SCRIP_FACE_VAL,
              SUM(FACE_VAL)FACE_VAL,
              SUM(FWD_RECEIPT)FWD_RECEIPT,
              LOCATION,
              SUM(ALLO_REPO)ALLO_REPO,
              SUM(ALLO_BL)ALLO_BL,
              SUM(FWD_ALLO_REPO)FWD_ALLO_REPO,
              SUM(FWD_ALLO_BL)FWD_ALLO_BL,
              RET_DUE_DATE,
              SWAP_STATUS

    FROM    DN_INV_REPO_DEAL_SERIAL_NO

    WHERE   SCRIPT_STATUS='SL' AND
            RET_DUE_DATE>TO_DATE(TO_CHAR(M_LAST_DAILY,'DD-MM-YYYY'),'DD-MM-YYYY')   AND
           /* SERIAL_NO NOT IN (SELECT SERIAL_NO
                                FROM  DN_TRN_REPO_FRESH_SERIAL_NO A,DN_TRN_REPO_FRESH B
                                WHERE  A.DEAL_NO=B.DEAL_NO AND
                                       B.APP_STATUS NOT IN ('CONF','CANCEL'))AND  */
            SERIAL_NO NOT IN (SELECT SERIAL_NO
                                FROM   DN_INV_REPO_DEAL_SERNO_ALLO
                                WHERE  TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>= TO_DATE(TO_CHAR(M_LAST_DAILY,'DD-MM-YYYY'),'DD-MM-YYYY') )

  GROUP BY  PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,SECURITY_CODE,DEAL_NO, LOCATION,
            RET_DUE_DATE,SWAP_STATUS
  ORDER BY  2,8 ASC;









BEGIN
  --------------------------------FOR OUTRIGHT INVENTORY-------------------------------------
  FOR CUR_REC IN ALL_CUR_OR
  LOOP
     SELECT COUNT(*)
     INTO   M_COUNT_OR
     FROM   DN_INV_OUTPS_DEAL_SERIAL_NO
     WHERE  DEAL_NO=CUR_REC.DEAL_NO ;

     IF M_COUNT_OR > 1 THEN

           SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS_SALE.NEXTVAL),3,'0')
           INTO   MM_SWAP_DEAL
           FROM DUAL;
           MM_SWAP_DEAL:='SS'||MM_SWAP_DEAL;


           SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS.NEXTVAL),4,'0')--$$##SC
           INTO   MM_SWAP_SERNO1
           FROM   DUAL;
           MM_SWAP_SERNO1:='S'||MM_SWAP_SERNO1;



   UPDATE DN_INV_OUTPS_DEAL_SERIAL_NO
   SET    SALE_DEAL_NO=MM_SWAP_DEAL,
          SERIAL_NO_STATUS='AMG',
          ORG_SERNO=MM_SWAP_SERNO1,
          SALE_EFF_VALDATE=TO_DATE(TO_CHAR(M_LAST_DAILY,'DD-MM-YYYY'),'DD-MM-YYYY')
   WHERE  DEAL_NO=CUR_REC.DEAL_NO ;

   INSERT INTO DN_INV_OUTPS_DEAL_SERIAL_NO
   (PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,SECURITY_CODE,DEAL_NO,SERIAL_NO,DEAL_YIELD,
    YIELD_WITH_BROKERAGE,SCRIP_FACE_VAL,FACE_VAL,INITIAL_COST,BROKERAGE,PRICE_INT_ACCR,
    CARR_VAL,COUP_INT_PURCH,COUP_INT_ACCR,TOT_COUP_INT,FWD_SALE,FWD_PURCHASE,LOCATION,
    ALLO_REPO,ALLO_BL,FWD_ALLO_REPO,FWD_ALLO_BL,SALE_DEAL_NO,SERIAL_NO_STATUS,SALE_EFF_VALDATE,
    RET_DUE_DATE,COST_TRANS_STATUS,SCRIP_STATUS,FACE_VAL_CURR,ORG_SERNO)

   VALUES
   (CUR_REC.PORTFOLIO_CODE,CUR_REC.EFF_VALDATE,CUR_REC.INST_TYPE,CUR_REC.SECURITY_CODE,CUR_REC.DEAL_NO,MM_SWAP_SERNO1,CUR_REC.DEAL_YIELD,
    CUR_REC.YIELD_WITH_BROKERAGE,CUR_REC.SCRIP_FACE_VAL,CUR_REC.FACE_VAL,CUR_REC.INITIAL_COST,CUR_REC.BROKERAGE,CUR_REC.PRICE_INT_ACCR,
    CUR_REC.CARR_VAL,CUR_REC.COUP_INT_PURCH,CUR_REC.COUP_INT_ACCR,CUR_REC.TOT_COUP_INT,CUR_REC.FWD_SALE,CUR_REC.FWD_PURCHASE,CUR_REC.LOCATION,
    CUR_REC.ALLO_REPO,CUR_REC.ALLO_BL,CUR_REC.FWD_ALLO_REPO,CUR_REC.FWD_ALLO_BL,NULL,'INV',NULL,
    NULL,NULL,'SL',NULL,NULL);

  END IF;
 END LOOP;
----------------------------------------------------------------------------------------------

---------------------------------FOR REPO INVENTORY-------------------------------------------
 FOR CUR_REC IN ALL_CUR_RP
  LOOP


     SELECT COUNT(*)
     INTO   M_COUNT_OR
     FROM   DN_INV_REPO_DEAL_SERIAL_NO
     WHERE  DEAL_NO=CUR_REC.DEAL_NO ;

     IF M_COUNT_RP > 1 THEN


           SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS_SALE.NEXTVAL),3,'0')
           INTO   MM_SWAP_DEAL
           FROM DUAL;
           MM_SWAP_DEAL:='SS'||MM_SWAP_DEAL;


           SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS.NEXTVAL),4,'0')--$$##SC
           INTO   MM_SWAP_SERNO1
           FROM   DUAL;
           MM_SWAP_SERNO1:='S'||MM_SWAP_SERNO1;



   UPDATE DN_INV_REPO_DEAL_SERIAL_NO
   SET    RET_DUE_DATE=TO_DATE(TO_CHAR(M_LAST_DAILY,'DD-MM-YYYY'),'DD-MM-YYYY'),
          SWAP_STATUS='Y'
   WHERE  DEAL_NO=CUR_REC.DEAL_NO ;

   INSERT INTO DN_INV_REPO_DEAL_SERIAL_NO
   (PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,SECURITY_CODE,DEAL_NO,SERIAL_NO,SCRIP_FACE_VAL,
    FACE_VAL,FWD_RECEIPT,LOCATION,ALLO_REPO,ALLO_BL,FWD_ALLO_REPO,FWD_ALLO_BL,RET_DUE_DATE,
    SCRIPT_STATUS,SWAP_STATUS,FACE_VAL_CURR)

   VALUES
   (CUR_REC.PORTFOLIO_CODE,CUR_REC.EFF_VALDATE,CUR_REC.INST_TYPE,CUR_REC.SECURITY_CODE,
    CUR_REC.DEAL_NO,MM_SWAP_SERNO1,CUR_REC.SCRIP_FACE_VAL,
    CUR_REC.FACE_VAL,CUR_REC.FWD_RECEIPT,CUR_REC.LOCATION,CUR_REC.ALLO_REPO,CUR_REC.ALLO_BL,
    CUR_REC.FWD_ALLO_REPO,CUR_REC.FWD_ALLO_BL,CUR_REC.RET_DUE_DATE,
    'SL',CUR_REC.SWAP_STATUS,NULL);

 END IF;
 END LOOP;





-------------------------------------------------------------------------------------------------


--***SCRIPLESS
END DN_INV_AMALGAMATE_SERIALNO_SL;

