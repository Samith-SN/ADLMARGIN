set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CORPORATE_ACTIONS_DIVIDENDS" 
(
  M_LAST_DAILY      DATE,
  M_USERNAME        VARCHAR2
)
IS
 CURSOR C1 IS
   SELECT A.PORTFOLIO_CODE PORT,A.SECURITY_CODE SEC,A.INST_TYPE INST,
          SUM(A.FACE_VAL) NOOFSHARES,
            --ADD by WARUNA 2012-05-30
 (SELECT ACTI_REF_NO FROM DN_CORPORATE_ACTIONS C
  WHERE
  C.ACTIVITY IN ('DIVIDENDS') 
  AND C.XC_DATE = TRUNC(M_LAST_DAILY,'DD')+1
  AND C.INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT
                      WHERE INST_CAT ='EQUITY') 
  AND C.STATUS = 'ENT' 
  AND C.SECURITY_CODE=A.SECURITY_CODE
  ) ACTI_REF_NO,
  GET_PORT_BROKER(A.PORTFOLIO_CODE,A.DEAL_NO) BROKER
 --ADD by WARUNA 2012-05-30
 
   FROM   DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_REF_SECURITY B
   WHERE  A.SECURITY_CODE=B.SECURITY_CODE AND
          A.SERIAL_NO_STATUS='INV' AND
          A.SECURITY_CODE IN (SELECT SECURITY_CODE
                              FROM   DN_CORPORATE_ACTIONS A
                              WHERE  A.ACTIVITY IN ('DIVIDENDS')  AND
                                     A.XC_DATE =  TRUNC(M_LAST_DAILY,'DD')+1 AND --TO_DATE(M_LAST_DAILY,'DD-MM-YYYY')+1 AND
                                     A.INST_TYPE IN (SELECT INST_TYPE
                                                     FROM   DN_REF_INSTRUMENT
                                                     WHERE  INST_CAT ='EQUITY') AND
                               STATUS = 'ENT'
                              )
   GROUP BY A.PORTFOLIO_CODE,A.SECURITY_CODE,A.INST_TYPE,GET_PORT_BROKER(A.PORTFOLIO_CODE,A.DEAL_NO);



 I             NUMBER;
 M_CNT         NUMBER DEFAULT 0;
 NO_OF_SHARES  NUMBER;
 NR            NUMBER;
 DR            NUMBER;
 SEC_CODE      DN_REF_SECURITY.SECURITY_CODE%TYPE;
 MISSUER_CODE  DN_REF_SECURITY.ISSUER_CODE%TYPE;
 MISSUER_CODE1 DN_REF_PRIMARY_ISSUER.ISSUER_CODE%TYPE;
 MISSUER_NAME  DN_REF_PRIMARY_ISSUER.ISSUER_NAME%TYPE;
 M_DEAL_NO     DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
 M_END_CODE    VARCHAR2(1);
 EDATE         DATE;
 MINST         DN_REF_INSTRUMENT.INST_TYPE%TYPE;
 M_DOCREFNO    DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
M_PAR_VALUE    NUMBER DEFAULT 0;
M_DIVI_AMT     NUMBER DEFAULT 0;
M_PAY_DATE     DN_CORPORATE_ACTIONS.PAY_DATE%TYPE;    --ADD M_PAY_DATE BY WARUNA 2011-06-10

BEGIN
SELECT  TRUNC(M_LAST_DAILY,'DD')+1 INTO EDATE FROM DUAL;

FOR I IN C1 LOOP
M_DEAL_NO :='';
SEC_CODE := I.SEC  ;
MINST := I.INST;

SELECT NVL(PAR_VALUE,0) INTO M_PAR_VALUE FROM DN_REF_SECURITY WHERE SECURITY_CODE=SEC_CODE;


 SELECT   PRICE,PAY_DATE       --ADD RATIO1-->PRICE--, PAY_DATE BY WARUNA 2011-06-10
 INTO     NR,M_PAY_DATE         --ADD M_PAY_DATE BY WARUNA 2011-06-10
 FROM     DN_CORPORATE_ACTIONS
 WHERE    ACTIVITY = 'DIVIDENDS' AND
          SECURITY_CODE=I.SEC AND
          INST_TYPE=I.INST AND
          XC_DATE =  TRUNC(M_LAST_DAILY,'DD')+1 AND --TO_DATE(M_LAST_DAILY,'DD-MM-YYYY')+1 AND
          STATUS = 'ENT' ;
 /*--COMMENT BY WARUNA 2011-06-09 
 SELECT ROUND(((I.NOOFSHARES*M_PAR_VALUE*NR)/100),2)
 INTO  M_DIVI_AMT
 FROM DUAL;
 ---*/
 SELECT ROUND(((I.NOOFSHARES*NR)),2)
 INTO  M_DIVI_AMT
 FROM DUAL;



SELECT 'DI'||TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_DIVIDEND_INCOME.NEXTVAL),3,'0')
INTO M_DOCREFNO    FROM DUAL;

 INSERT INTO DN_TRN_DIVIDEND_INCOME
               (  DOCREFNO,PORTFOLIO_CODE,PROC_DESC,INST_CODE,SEC_CODE,LICENCEE_BRANCH_CODE,
                  LICENEE_ACCOUNT_NO,TRNAMOUNT,DN_USER,TRNDATE,
                  EFF_VAL_DATE,PAYEE_BANK,CHEQUE_NO,NO_OF_SHARES,ACTI_REF_NO)--NO_OF_SHARES add by waruna2012-01-23
                VALUES
                   (  M_DOCREFNO,I.PORT,'DAYENDROUTINE',I.INST,I.SEC,'-',
                      '-',M_DIVI_AMT,M_USERNAME,M_PAY_DATE,--SYSDATE, --SYSDATE-->M_PAY_DATE BY WARUNA  2011-06-10
                       TRUNC(M_LAST_DAILY+1,'DD') --ADD +1 BY WARUNA 2012-10-10 --M_LAST_DAILY--TO_DATE(M_LAST_DAILY,'DD/MM/YYYY') 
                      ,'-', NULL ,I.NOOFSHARES,I.ACTI_REF_NO);
/* remove by waruna 24-01-2012 request from pabc ,acc pass only when dividend receive
DN_ACC_DIV_RECEIVE_ACC('GEN',I.PORT, M_PAY_DATE,--M_LAST_DAILY,--TO_DATE(M_LAST_DAILY,'DD/MM/YYYY')-->M_PAY_DATE BY WARUNA 2011-06-10
M_DIVI_AMT,M_DOCREFNO,NULL,I.INST);
*/

INSERT INTO DN_CORPORATE_ACT_REF ( ACTI_REF_NO, FACILITY_NO, ELIGIBLE_SHARE, OBTAIN_SHARE,OBTAIN_AMMOUNT, OBTAIN_VALUE, ENT_DATE)
VALUES (I.ACTI_REF_NO,I.PORT,I.NOOFSHARES,0,M_DIVI_AMT,NR,SYSDATE);

END LOOP;
--RAISE_APPLICATION_ERROR(-20201,'CHECK DAY END ROUTINE!!'||SEC_CODE||'**'||MINST||'');
 UPDATE  DN_CORPORATE_ACTIONS
 SET     STATUS        = 'PROCESSED'
 WHERE   ACTIVITY      = 'DIVIDENDS' AND
         SECURITY_CODE = SEC_CODE AND
         INST_TYPE     = MINST AND
         XC_DATE       =  TRUNC(M_LAST_DAILY,'DD')+1 AND --TO_DATE(M_LAST_DAILY,'DD-MM-YYYY')+1 AND
         STATUS        = 'ENT';

  INSERT INTO DN_TIME_LOG_SETTLE
          (DOC_REF_NO, DN_USER,
           ENT_DATE,DESCRIPTION)
           VALUES
            ( M_DOCREFNO,M_USERNAME,
              SYSDATE,'PORTFOLIO DIVIDEND RECEIVABLE ');

END DN_CORPORATE_ACTIONS_DIVIDENDS; 

