  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CHECK_OR_CONF_EQUITY" 
(
M_DEAL_NO    DN_TRN_OUTP_SALE.DEAL_NO%TYPE,
M_SECTION    CHAR
)
AS
M_SECURITY_CODE                  DN_TRN_OUTP_SALE.SECURITY_CODE%TYPE;
M_EFF_VALDATE                    DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE;
M_PRICE_CLEAN                    DN_TRN_OUTP_SALE.PRICE_CLEAN%TYPE;
M_FACE_VALUE                     DN_TRN_OUTP_SALE.FACE_VALUE%TYPE;
M_SETTLE_VALUE                   DN_TRN_OUTP_SALE.SETTLE_VALUE%TYPE;
MM_SETTLE_VALUE                  DN_TRN_OUTP_SALE.SETTLE_VALUE%TYPE;
M_STAT1                          VARCHAR2(1);
M_COUNT1                         NUMBER;
M_NO_OF_SETTL_MODES              DN_TRN_OUTP_SALE.NO_OF_SETTL_MODES%TYPE;
M_SETTLE_VALUE1                  NUMBER;
M_SETTLE_VALUE2                  NUMBER;
M_SETTLE_COUNT                      NUMBER;
M_SECTAB_TOT                        DN_TRN_OUTP_SALE.FACE_VALUE%TYPE;
MSL_SCRIPT_STATUS                   DN_TRN_OUTP_SALE.SCRIPT_STATUS%TYPE;
MSL_FACE_VALUE                      DN_TRN_OUTP_SALE.FACE_VALUE%TYPE;
MSL_COUNT                           NUMBER;
MM_PRICE_CLEAN                      DN_TRN_OUTP_SALE.PRICE_CLEAN%TYPE;
M_YIELD                             DN_TRN_OUTP_SALE.YIELD%TYPE;
M_INT_RATE_BASE_CODE                DN_TRN_OUTP_SALE.INT_RATE_BASE_CODE%TYPE;
M_COST                              DN_TRN_OUTP_SALE.COST%TYPE;
MM_COST                             DN_TRN_OUTP_SALE.COST%TYPE;
M_COST1                             DN_TRN_OUTP_SALE.COST%TYPE;
MM_COST1                            DN_TRN_OUTP_SALE.COST%TYPE;
M_PURCHASE_COST                     DN_TRN_OUTP_SALE.COST%TYPE;
M_BROKER_COST                       DN_TRN_OUTP_SALE.COST%TYPE;
M_BROKER_COST1                      DN_TRN_OUTP_SALE.COST%TYPE;
a DN_TRN_OUTP_SALE.COST%TYPE;
b DN_TRN_OUTP_SALE.COST%TYPE;
c DN_TRN_OUTP_SALE.COST%TYPE;

err_num   varchar2(200);
err_msg   varchar2(200);
M_SL_COUNT2 number;
M_NOM  NUMBER;

M_LAST_DAILY                        DATE;-- Added by Shanheetha - 13-07-2006 - VC06-012.
M_BUY_SETLE_DATE                    DATE;-- Added by Shanheetha - 13-07-2006 - VC06-012.
BEGIN

SELECT NOMINAL_VALUE INTO M_NOM FROM
DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO ;

IF M_NOM > 0 THEN

M_STAT1 :='N';
SELECT  FACE_VALUE,COST,SETTLE_VALUE ------------------------1
INTO    a,b,c
FROM    DN_TRN_OUTP_SALE
WHERE   DEAL_NO=M_DEAL_NO /*AND
        FACE_VALUE > 0 AND  COST >0 AND  SETTLE_VALUE > 0*/ ;
--RAISE_APPLICATION_ERROR(-20201,'FACE_VALUE'||a||'COST'||b||'SETTLE_VALUE'||c);
SELECT  'Y'------------------------1
INTO    M_STAT1
FROM    DN_TRN_OUTP_SALE
WHERE   DEAL_NO=M_DEAL_NO AND
        FACE_VALUE > 0 ;--AND  COST >0 AND  SETTLE_VALUE > 0 ;--COMMENTED ON 23-12-2004 BY SA

IF(M_STAT1='N')THEN
        RAISE_APPLICATION_ERROR(-20201,'FACE_VALUE ,COST ,SETTLE_VALUE SHOULD BE GREATER THAN ZERO !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;

----- Added by Shanheetha -----------------------------------------------------------------------
SELECT TO_DATE(TO_CHAR(LAST_DAILY,'DD/MM/YYYY'),'DD/MM/YYYY') INTO M_LAST_DAILY FROM DN_SYS_PARAMETER;
--RAISE_APPLICATION_ERROR(-20201,'M_LAST_DAILY'||M_LAST_DAILY );

IF SUBSTR(M_DEAL_NO,1,2)='OR' THEN

SELECT TO_DATE(TO_CHAR(BUY_SETLE_DATE,'DD/MM/YYYY'),'DD/MM/YYYY')
INTO M_BUY_SETLE_DATE
FROM DN_TRN_OUTP_SALE_SETTLE_EQUITY
WHERE DEAL_NO=M_DEAL_NO;
--RAISE_APPLICATION_ERROR(-20201,'M_BUY_SETLE_DATE'||M_BUY_SETLE_DATE );

--IF SUBSTR(M_DEAL_NO,1,2)='OR' THEN
   IF M_LAST_DAILY >= M_BUY_SETLE_DATE THEN
   RAISE_APPLICATION_ERROR(-20201,'BUYER SETTLEMENT DATE IS NOT GREATER THAN LAST DAY END ROUTINE DATE ! ');
   END IF;  
END IF; 

---- End -----------------------------------------------------------------------------------------

SELECT COUNT(*)------------------------1
INTO   M_COUNT1
FROM   DN_TRN_OUTP_SALE_SETTLE
WHERE  DEAL_NO=M_DEAL_NO;

IF M_COUNT1<=0 THEN
RAISE_APPLICATION_ERROR(-20201,'NO RECORD FOUND IN SETTLE TABLE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

SELECT NO_OF_SETTL_MODES -----------------------2
INTO   M_NO_OF_SETTL_MODES
FROM   DN_TRN_OUTP_SALE
WHERE  DEAL_NO=M_DEAL_NO;

IF M_NO_OF_SETTL_MODES <= 0 THEN
RAISE_APPLICATION_ERROR(-20201,'NO_OF_SETTL_MODES SHOULD BE GREATER THAN ZERO!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

SELECT   SETTLE_VALUE
INTO     M_SETTLE_VALUE1
FROM     DN_TRN_OUTP_SALE
WHERE    DEAL_NO=M_DEAL_NO;

SELECT   SUM(SETTLE_AMOUNT),COUNT(*)
INTO     M_SETTLE_VALUE2,M_SETTLE_COUNT
FROM     DN_TRN_OUTP_SALE_SETTLE
WHERE    DEAL_NO=M_DEAL_NO
GROUP BY DEAL_NO ;

IF M_SETTLE_COUNT=0 THEN
  RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN SETTLE_VALUE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

IF M_SETTLE_VALUE1 <> M_SETTLE_VALUE2 THEN
  RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN SETTLE_VALUE  !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

--------------------------FOR SCRIPLESS------------------------------------------------

SELECT  COUNT(*)--$$##SC
INTO    MSL_COUNT
FROM    DN_TRN_OUTP_SALE A,DN_REF_PORTFOLIO B
WHERE   A.DEAL_NO=M_DEAL_NO  AND
        A.SELL_PORTFOLIO_CODE=B.PORTFOLIO_CODE AND
        B.PF_TYPE='P' AND B.ACTIVE_STATUS='Y';


IF MSL_COUNT>0 THEN

SELECT  SCRIPT_STATUS,FACE_VALUE
INTO    MSL_SCRIPT_STATUS,MSL_FACE_VALUE
FROM    DN_TRN_OUTP_SALE
WHERE   DEAL_NO=M_DEAL_NO   ;

IF MSL_SCRIPT_STATUS='SL' THEN


SELECT COUNT(DEAL_NO)
 INTO   M_SL_COUNT2
 FROM   DN_TRN_OUTP_SALE_SEC
 WHERE  DEAL_NO=M_DEAL_NO;
 --GROUP BY DEAL_NO;

 IF M_SL_COUNT2 >0 THEN
 SELECT SUM(FACE_VALUE)
 INTO   M_SECTAB_TOT
 FROM   DN_TRN_OUTP_SALE_SEC
 WHERE  DEAL_NO=M_DEAL_NO
 GROUP BY DEAL_NO;

   IF MSL_FACE_VALUE <> M_SECTAB_TOT THEN
        RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN TOTAL VALUE OF THE DN_TRN_OUTP_SALE_SEC TABLE AND FACE VALUE IN DN_TRN_OUTP_SALE TABLE!! ');
   END IF;

END IF;
END IF;
SELECT (PRICE_CLEAN * FACE_VALUE )-  BROKER_COST INTO  M_COST
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;
SELECT COST  INTO  MM_COST
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;

IF M_COST <> MM_COST THEN
  RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN THE TOTAL COST  !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;
ELSE
SELECT (PRICE_CLEAN * FACE_VALUE )+ BROKER_COST INTO  M_COST
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;
SELECT COST  INTO  MM_COST
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;

IF M_COST <> MM_COST THEN
  RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN THE TOTAL COST  !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;



END IF;--COUNT
----------------------------------------------------------------------------------------

--------------------------FOR EQUITY------------------------------------------------



SELECT BROKER_COST+PURCHASE_COST  INTO  M_COST1
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;
SELECT SETTLE_VALUE  INTO  MM_COST1
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;

IF M_COST <> MM_COST THEN
  RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN THE SETTLEMETN VALUE !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

SELECT PURCHASE_COST  INTO  M_PURCHASE_COST
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;

SELECT DN_GET_BROKER_COST(M_PURCHASE_COST) INTO  M_BROKER_COST
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;

SELECT BROKER_COST  INTO  M_BROKER_COST1
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;

--RAISE_APPLICATION_ERROR(-20201,'M_BROKER_COST'||M_BROKER_COST||'M_BROKER_COST1'||M_BROKER_COST1);
/*
IF M_BROKER_COST <> M_BROKER_COST1 THEN
    RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN THE BROKERAGE !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;
*/


-------------------------------------------------------------------------------------
--RAISE_APPLICATION_ERROR(-20201,'MIS**************');

END IF;

END DN_CHECK_OR_CONF_EQUITY;

