set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_SAV_BROKERLETTER_DATA1" 
(
 M_BROKER_CODE   DN_REF_PORT_ADV.BROKER_CODE%TYPE,
 M_CLIENT        DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE
)
AS
MM_TRN_DATE DATE;
BEGIN

DELETE DN_TEMP_BROKERLETTER_DATA;

SELECT MAX(TRN_DATE)
INTO MM_TRN_DATE
 FROM DN_REP_MARGIN_CALL;


FOR I IN (SELECT A.PORT_CODE PORT_CODE,B.CDS_ACC_NO CDS_ACC_NO,C.ADV_NAME ADV_NAME
          FROM   DN_REF_PORT_ADV A,DN_REF_PORTFOLIO B,DN_REF_ADVISOR C
          WHERE  A.BROKER_CODE=M_BROKER_CODE AND A.PORT_CODE=B.PORTFOLIO_CODE AND B.PORTFOLIO_CODE=M_CLIENT AND A.ADV_CODE=C.ADV_CODE
          AND B.ACTIVE_STATUS='Y')


LOOP

INSERT INTO DN_TEMP_BROKERLETTER_DATA
(PORT_CODE,CDS_ACC_NO,ADV_NAME,PF_NAME,REPO_LEG2,NET_CASHFLOWS,AMOUNT,INT_AMOUNT)

 SELECT  I.PORT_CODE,I.CDS_ACC_NO,I.ADV_NAME,RETURN_PF_NAME(I.PORT_CODE),REPO_LEG2,--5
        NET_CASHFLOWS,--7
        SUM(NVL(FACE_VAL,0)* NVL(MARKET_RATE,0)),--8
        INT_AMOUNT--9
 FROM     DN_REP_MARGIN_CALL
 WHERE    PORTFOLIO_CODE = I.PORT_CODE AND
          TRN_DATE=MM_TRN_DATE
 GROUP BY RETURN_PF_NAME(I.PORT_CODE),REPO_LEG2,NET_CASHFLOWS,INT_AMOUNT ;

COMMIT;

END LOOP;

END;


