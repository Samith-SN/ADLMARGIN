set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."FA_CR_SAVE_FACTILITY_INT_SLAB" 
(
M_FACILITY_NO              DN_FACILITY_INT_SLAB.FACILITY_NO%TYPE,
M_SLAB_CODE                DN_FACILITY_INT_SLAB.SLAB_CODE%TYPE,
M_FROM_AMOUNT              DN_FACILITY_INT_SLAB.FROM_AMOUNT%TYPE,
M_TO_AMOUNT                DN_FACILITY_INT_SLAB.TO_AMOUNT%TYPE,
M_INT_PERCENTAGE           DN_FACILITY_INT_SLAB.INT_PERCENTAGE%TYPE,
M_USER                     DN_FACILITY_INT_SLAB.ENT_USER%TYPE,
M_SCREEN                   VARCHAR2,
M_NUM                      INT,
M_OVER_PAID_DISCOUNT       DN_FACILITY_INT_SLAB.OVER_PAID_DISCOUNT%TYPE 
)

IS

/*CREATED BY THAMALI JAYATUNGA ON 04/09/2010 FOR FACILITY SLAB*/

M_COUNT             NUMBER(5);

BEGIN

SELECT COUNT(*)
INTO   M_COUNT
FROM   DN_FACILITY_INT_SLAB
WHERE  FACILITY_NO = M_FACILITY_NO;

IF M_COUNT = 0 THEN

INSERT INTO DN_FACILITY_INT_SLAB(FACILITY_NO,SLAB_CODE,FROM_AMOUNT,TO_AMOUNT,INT_PERCENTAGE,
ENT_USER,ENT_DATE,OVER_PAID_DISCOUNT)
VALUES (M_FACILITY_NO,M_SLAB_CODE,M_FROM_AMOUNT,M_TO_AMOUNT,M_INT_PERCENTAGE,M_USER,SYSDATE,M_OVER_PAID_DISCOUNT);

ELSE

IF M_NUM=1 THEN

INSERT INTO DN_FACILITY_INT_SLAB_BK
SELECT * FROM DN_FACILITY_INT_SLAB 
WHERE FACILITY_NO = M_FACILITY_NO;

DELETE FROM DN_FACILITY_INT_SLAB
WHERE FACILITY_NO = M_FACILITY_NO;

END IF;

INSERT INTO DN_FACILITY_INT_SLAB(FACILITY_NO,SLAB_CODE,FROM_AMOUNT,TO_AMOUNT,INT_PERCENTAGE,
ENT_USER,ENT_DATE,OVER_PAID_DISCOUNT)
VALUES (M_FACILITY_NO,M_SLAB_CODE,M_FROM_AMOUNT,M_TO_AMOUNT,M_INT_PERCENTAGE,M_USER,SYSDATE,M_OVER_PAID_DISCOUNT);

END IF;

END; -- PROCEDURE

