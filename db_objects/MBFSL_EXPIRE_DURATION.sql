set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_EXPIRE_DURATION" 
(
M_DURATION               DN_REF_PASSWORD_EXPIRE_DUR.EXPIRE_DURATION%TYPE,
M_REMINDER               DN_REF_PASSWORD_EXPIRE_DUR.REMINDER%TYPE,
M_USERNAME               VARCHAR2,
M_SCREEN_NAME            VARCHAR2
)
AS

BEGIN

 DN_VALIDATE_SAVE_RIGHTS(M_USERNAME,'WD_Pw_Expiry');

   --CREATED BY ASHINI
   --CREATED DATE 27-05-2005

UPDATE    DN_REF_PASSWORD_EXPIRE_DUR
SET       EXPIRE_DURATION = M_DURATION,
          REMINDER        = M_REMINDER,
          USER_NAME       = M_USERNAME,
          ENT_DATE        = SYSDATE;

IF SQL%NOTFOUND THEN
 INSERT INTO DN_REF_PASSWORD_EXPIRE_DUR
 (EXPIRE_DURATION,REMINDER,USER_NAME)
 VALUES
 (M_DURATION,M_REMINDER,M_USERNAME);
END IF;

COMMIT;
END MBFSL_EXPIRE_DURATION;

