set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_EXCHANGE_RATES" 
(
M_VALUE_DATE                VARCHAR2,
M_CURR_CODE                 DN_REF_EXCHANGE_RATES.CURR_CODE%TYPE,
M_CURRENCY_VALUE            DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE
)
AS

BEGIN

   --CREATED BY NIRMALA FERNANDO
   --CREATED DATE 14-12-2001


UPDATE    DN_REF_EXCHANGE_RATES
SET       VALUE_DATE=TO_DATE(M_VALUE_DATE,'DD-MM-YYYY'),
          CURRENCY_VALUE=M_CURRENCY_VALUE
WHERE     CURR_CODE=M_CURR_CODE;


IF SQL%NOTFOUND THEN
 INSERT INTO DN_REF_EXCHANGE_RATES
 (VALUE_DATE,CURRENCY_VALUE,CURR_CODE)
 VALUES
 (TO_DATE(M_VALUE_DATE,'DD-MM-YYYY'),M_CURRENCY_VALUE,M_CURR_CODE);
END IF;

COMMIT;
END MBFSL_EXCHANGE_RATES;

/
