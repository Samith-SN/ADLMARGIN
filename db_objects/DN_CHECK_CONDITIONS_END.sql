set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CHECK_CONDITIONS_END" 
(
  M_PROCESS_DATE                DATE
)
AS
M_COUNT1   NUMBER;
M_COUNT2   NUMBER;

err_num   varchar2(200);
err_msg   varchar2(200);

BEGIN

FOR I IN
(SELECT DEAL_NO DEAL_NO,SUM(FACE_VAL) FACE_VAL
 FROM DN_INV_INT_CUST_DEAL_SERNO
 WHERE TO_DATE(M_PROCESS_DATE,'DD-MM-YYYY')-10<=TO_DATE(TO_CHAR(PROCESS_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') AND
       TO_DATE(TO_CHAR(PROCESS_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=TO_DATE(M_PROCESS_DATE,'DD-MM-YYYY') AND
       COUP_PAY>0 AND
       MATURITY_PAY>0
 GROUP BY DEAL_NO)

LOOP

SELECT COUNT(SUM(FACE_VAL))
INTO   M_COUNT1
FROM   DN_INV_CUST_DEAL_SERIAL_NO
WHERE  SERIAL_NO_STATUS<>'WID' AND
       DEAL_NO=I.DEAL_NO AND
       I.FACE_VAL=(SELECT SUM(FACE_VAL)
                   FROM   DN_INV_CUST_DEAL_SERIAL_NO
                   WHERE  DEAL_NO=I.DEAL_NO
                   GROUP BY DEAL_NO)
GROUP BY DEAL_NO;

IF M_COUNT1<>1 THEN
 RAISE_APPLICATION_ERROR(-20201,'MISMATCH WITH DN_INV_CUST_DEAL_SERIAL_NO IN DN_CHECK_CONDITIONS_END!!'||I.DEAL_NO||I.FACE_VAL);
END IF;

END LOOP;

---------------------
---------------------
---------------------
FOR H IN
(SELECT DEAL_NO DEAL_NO,(SUM(COUP_PAY)+SUM(MATURITY_PAY)) FACE_VAL
 FROM DN_INV_INT_CUST_DEAL_SERNO
 WHERE TO_DATE(M_PROCESS_DATE,'DD-MM-YYYY')-10<=TO_DATE(TO_CHAR(PROCESS_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') AND
       TO_DATE(TO_CHAR(PROCESS_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=TO_DATE(M_PROCESS_DATE,'DD-MM-YYYY') AND
       COUP_PAY>0 AND
       MATURITY_PAY>0
 GROUP BY DEAL_NO)

LOOP


SELECT COUNT(SUM(TRNAMOUNT))
INTO   M_COUNT2
FROM   DN_ACC_LICENCEE_GEN_ACCOUNT
WHERE  DOCREFNO=H.DEAL_NO AND ACC_TYPE_CODE='302' AND
       TO_DATE(M_PROCESS_DATE,'DD-MM-YYYY')-10<=TO_DATE(TO_CHAR(TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY') AND
       TO_DATE(TO_CHAR(TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=TO_DATE(M_PROCESS_DATE,'DD-MM-YYYY')  AND
       H.FACE_VAL=(SELECT SUM(TRNAMOUNT)
                   FROM   DN_ACC_LICENCEE_GEN_ACCOUNT
                   WHERE  ACC_TYPE_CODE='302' AND
                          TO_DATE(M_PROCESS_DATE,'DD-MM-YYYY')-10<=TO_DATE(TO_CHAR(TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY') AND
                          TO_DATE(TO_CHAR(TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=TO_DATE(M_PROCESS_DATE,'DD-MM-YYYY') AND
                          DOCREFNO=H.DEAL_NO
                   GROUP BY DOCREFNO)
GROUP BY DOCREFNO;

IF M_COUNT2<>1 THEN
 RAISE_APPLICATION_ERROR(-20201,'MISMATCH WITH DN_ACC_LICENCEE_GEN_ACCOUNT IN DN_CHECK_CONDITIONS_END!!'||H.DEAL_NO||H.FACE_VAL);
END IF;

END LOOP;
