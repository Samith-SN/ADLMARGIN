set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."WEBDN_AMORTISING_DATES" 
   (
    M_SECURITY_CODE     WEBDN_REF_SECURITY.SECURITY_CODE%TYPE,
    M_DATE              VARCHAR2,
    M_AMOUNT            NUMBER,
    M_COUNT             NUMBER

   )

   IS

    -- PROCEDUE     : AMOUTISING DATES
    -- SYSTEM       : DEALNET SYSTEM
  

   M_COUNT1            NUMBER;

BEGIN
 IF M_COUNT = 1 THEN
  DELETE WEBDN_REF_SECURITY_AMORTISE_DATES
  WHERE  SECURITY_CODE    = M_SECURITY_CODE /*AND
         RATE_CHANGE_DATE = TO_DATE(M_DATE,'DD-MM-YYYY')*/;
 END IF;
    SELECT COUNT(*)
    INTO   M_COUNT1
    FROM   WEBDN_REF_SECURITY_AMORTISE_DATES
    WHERE  SECURITY_CODE    = M_SECURITY_CODE AND
           AMORTISING_DATE = TO_DATE(M_DATE,'DD-MM-YYYY');

    IF M_COUNT1=0 THEN
      INSERT INTO WEBDN_REF_SECURITY_AMORTISE_DATES
      (SECURITY_CODE,AMORTISING_DATE,AMOUNT)
      VALUES
      (M_SECURITY_CODE,TO_DATE(M_DATE,'DD-MM-YYYY'),M_AMOUNT);
     ELSE
      UPDATE WEBDN_REF_SECURITY_AMORTISE_DATES
      SET    AMOUNT  = M_AMOUNT
      WHERE  SECURITY_CODE    = M_SECURITY_CODE AND
             AMORTISING_DATE = TO_DATE(M_DATE,'DD-MM-YYYY');
     END IF;
      COMMIT;
  /*
EXCEPTION
  WHEN OTHERS THEN

RAISE_APPLICATION_ERROR(-20001,'SECURITY_CODE='||M_SECURITY_CODE||' - RATE_CHANGE_DATE='||M_DATE);
*/

END WEBDN_AMORTISING_DATES; 

/
