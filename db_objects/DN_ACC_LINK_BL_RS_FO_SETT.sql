set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_LINK_BL_RS_FO_SETT" 
   (
    M_DEAL_NO          DN_TRN_BL_FUND.DEAL_NO%TYPE,
    M_LEG1_VALUE       DN_TRN_BL_FUND.LEG1_VALUE%TYPE
   )

   IS

    -- Procedue     : Link (BL) REPO SETTLEMET to the accounting at the confiremation
    -- System       : Dealnet system
    -- Created by   : D.P. Pubudu Thushara
    -- Created on   : 19/08/1999

    M_BORR_PORTFOLIO_CODE     DN_TRN_BL_FUND.BORR_PORTFOLIO_CODE%TYPE;
    M_LEND_PORTFOLIO_CODE     DN_TRN_BL_FUND.LEND_PORTFOLIO_CODE%TYPE;
    M_EFF_VALDATE             DN_TRN_BL_FUND.EFF_VALDATE%TYPE;
    M_BORR_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_BORR_OWNED_BY_MBFSL     DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;
    M_LEND_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_LEND_OWNED_BY_MBFSL     DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;

BEGIN

     SELECT
        A.BORR_PORTFOLIO_CODE,
        A.LEND_PORTFOLIO_CODE,
        B.PF_TYPE,
        B.OWNED_BY_MBFSL,
        C.PF_TYPE,
        C.OWNED_BY_MBFSL,
        A.EFF_VALDATE
        INTO  M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE,
              M_BORR_PF_TYPE,M_BORR_OWNED_BY_MBFSL,M_LEND_PF_TYPE,M_LEND_OWNED_BY_MBFSL,
              M_EFF_VALDATE
     FROM
        DN_TRN_BL_FUND A,
        DN_REF_PORTFOLIO B,
        DN_REF_PORTFOLIO C
     WHERE
        A.DEAL_NO=M_DEAL_NO
        AND
        A.BORR_PORTFOLIO_CODE=B.PORTFOLIO_CODE
        AND
        A.LEND_PORTFOLIO_CODE=C.PORTFOLIO_CODE;

  IF M_BORR_OWNED_BY_MBFSL='Y' AND   M_LEND_PF_TYPE='C' THEN

      DN_ACC_A_5_4_X(M_DEAL_NO);

  ELSIF M_BORR_PF_TYPE='C' AND M_LEND_OWNED_BY_MBFSL='Y' THEN

      DN_ACC_A_6_4_X(M_DEAL_NO);

  ELSIF M_BORR_PF_TYPE='P' AND M_BORR_OWNED_BY_MBFSL='N' AND M_LEND_PF_TYPE='C' THEN

      DN_ACC_B_5_5_X(M_DEAL_NO);

  ELSIF M_BORR_PF_TYPE='C' AND M_LEND_PF_TYPE='P' AND M_LEND_OWNED_BY_MBFSL='N' THEN

      DN_ACC_B_6_5_X(M_DEAL_NO);

  ELSIF M_BORR_PF_TYPE='P' AND M_BORR_OWNED_BY_MBFSL='N' AND  M_LEND_OWNED_BY_MBFSL='Y' THEN

      DN_ACC_B_5_5_X(M_DEAL_NO);
      DN_ACC_A_6_4_X(M_DEAL_NO);

  ELSIF M_BORR_OWNED_BY_MBFSL='Y' AND  M_LEND_PF_TYPE='P' AND M_LEND_OWNED_BY_MBFSL='N' THEN

      DN_ACC_A_5_4_X(M_DEAL_NO);
      DN_ACC_B_6_5_X(M_DEAL_NO);

  ELSIF M_BORR_OWNED_BY_MBFSL='Y' AND   M_LEND_OWNED_BY_MBFSL='Y' THEN

      DN_ACC_A_5_4_X(M_DEAL_NO);
      DN_ACC_A_6_4_X(M_DEAL_NO);

  ELSIF M_BORR_PF_TYPE='P' AND M_BORR_OWNED_BY_MBFSL='N' AND  M_LEND_PF_TYPE='P' AND M_LEND_OWNED_BY_MBFSL='N' THEN

      DN_ACC_B_5_5_X(M_DEAL_NO);
      DN_ACC_B_6_5_X(M_DEAL_NO);

  END IF;


END DN_ACC_LINK_BL_RS_FO_SETT;

/
