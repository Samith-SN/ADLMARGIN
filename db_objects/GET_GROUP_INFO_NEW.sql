  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."GET_GROUP_INFO_NEW" 
(
M_GROUP_DEALNO       DN_TRN_OUTP_SALE.GROUP_DEALNO%TYPE,
M_NO                 VARCHAR2
)RETURN VARCHAR2
AS
RET_NUM  NUMBER;
M1 NUMBER;M2 NUMBER;
M3 NUMBER;M4 NUMBER;
M5 NUMBER;M6 NUMBER;
M7 NUMBER;

BEGIN
IF(SUBSTR(M_GROUP_DEALNO,1,2)='GO')THEN
SELECT  NVL(SUM(H.FACE_VALUE),0), NVL(SUM(J.LEG2_VALUE),0), NVL(SUM(H.COST),0),
        NVL(SUM(J.LEG1_VALUE),0), NVL(SUM(H.ACC_INT),0),
        NVL(SUM(J.ACC_INT),0), NVL(SUM(H.SETTLE_VALUE),0)
INTO    M1,M2,M3,M4,M5,M6,M7
FROM    DN_TRN_OUTP_SALE H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);

RETURN  M1||','||M2||','||M3||','||M4||','||M5||','||M6||','||M7 ;


ELSIF(SUBSTR(M_GROUP_DEALNO,1,2)='GF')THEN

IF M_NO='M1' THEN
SELECT  NVL(SUM(H.LEG1_VALUE),0)
INTO    RET_NUM
FROM    DN_TRN_REPO_FRESH H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);
ELSIF M_NO='M2' THEN
SELECT  NVL(SUM(H.LEG2_VALUE),0)
INTO    RET_NUM
FROM    DN_TRN_REPO_FRESH H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);
ELSIF M_NO='M3' THEN
SELECT  NVL(SUM(H.INT_AMOUNT),0)
INTO    RET_NUM
FROM    DN_TRN_REPO_FRESH H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);
ELSIF M_NO='M4' THEN
SELECT  NVL(SUM(J.LEG1_VALUE),0)
INTO    RET_NUM
FROM    DN_TRN_REPO_FRESH H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);
ELSIF M_NO='M5' THEN
SELECT  NVL(SUM(J.LEG2_VALUE),0)
INTO    RET_NUM
FROM    DN_TRN_REPO_FRESH H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);
END IF;

ELSIF(SUBSTR(M_GROUP_DEALNO,1,2)='GR')THEN

IF M_NO='M1' THEN
SELECT  NVL(SUM(H.LEG1_VALUE),0)
INTO    RET_NUM
FROM    DN_TRN_REPO_ROLLOVER H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);
ELSIF M_NO='M2' THEN
SELECT  NVL(SUM(H.LEG2_VALUE),0)
INTO    RET_NUM
FROM    DN_TRN_REPO_ROLLOVER H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);
ELSIF M_NO='M3' THEN
SELECT  NVL(SUM(H.INT_AMOUNT),0)
INTO    RET_NUM
FROM    DN_TRN_REPO_ROLLOVER H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);
ELSIF M_NO='M4' THEN
SELECT  NVL(SUM(J.LEG1_VALUE),0)
INTO    RET_NUM
FROM    DN_TRN_REPO_ROLLOVER H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);
ELSIF M_NO='M5' THEN
SELECT  NVL(SUM(J.LEG2_VALUE),0)
INTO    RET_NUM
FROM    DN_TRN_REPO_ROLLOVER H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);



END IF;


END IF;
RETURN  RET_NUM;

END GET_GROUP_INFO_NEW;

