set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_E_1" 
(
M_DOCREFNO   IN OUT     DN_TRN_BO_CUSTODIAL_DEAL.DEAL_NO%TYPE
)
AS

/* PROCEDURE  - DN_ACC_E_1 RECEIPT OF SECURITIES FOR SAFE CUSTODIY
   SYSTEM     - DEALNET
   CREATED BY - LATHIKA
   CREATED ON - 28/DEC/1999*/


M_CUSTODIAL_CODE      DN_TRN_BO_CUSTODIAL_DEAL.CUSTODIAL_CODE%TYPE;
M_TRNAMOUNT           DN_TRN_BO_CUSTODIAL_DEAL.FACE_VALUE%TYPE;
M_EFF_VALDATE         DN_TRN_BO_CUSTODIAL_DEAL.EFF_VALDATE%TYPE;
M_INST_TYPE           DN_TRN_BO_CUSTODIAL_DEAL.INST_TYPE%TYPE;

BEGIN

SELECT CUSTODIAL_CODE,FACE_VALUE,EFF_VALDATE,INST_TYPE
INTO M_CUSTODIAL_CODE,M_TRNAMOUNT,M_EFF_VALDATE,M_INST_TYPE
FROM DN_TRN_BO_CUSTODIAL_DEAL
WHERE DEAL_NO=M_DOCREFNO;

-------------------(1)-------------------------
INSERT INTO DN_ACC_CUST_INST_ACCOUNT
   (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_CUSTODIAL_CODE,M_INST_TYPE,M_EFF_VALDATE,'001','DR',M_TRNAMOUNT,M_DOCREFNO,'RECEIPT OF SEC - SAFE CUSTODY','600');

INSERT INTO DN_ACC_CUST_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_CUSTODIAL_CODE,M_CUSTODIAL_CODE,M_EFF_VALDATE,'600','CR',M_TRNAMOUNT,M_DOCREFNO,'RECEIPT OF SEC - SAFE CUSTODY','001');


END DN_ACC_E_1;

