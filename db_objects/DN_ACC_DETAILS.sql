set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_DETAILS" 
(
  M_ENT_DATE       VARCHAR2
)
AS


CURSOR LICENCEE_DETAIL IS
  SELECT  A.PORTFOLIO_CODE PORTFOLIO_CODE,
          A.TRNDATE TRNDATE,
          NVL(A.ACC_TYPE_CODE,'0') ACC_TYPE_CODE,
          A.DRCR_STATUS DRCR_STATUS,
          NVL(A.TRNAMOUNT,0) TRNAMOUNT,
          A.DOCREFNO DOCREFNO,
          A.ENTDATE ENTDATE,
          A.PROC_DESC PROC_DESC,
          A.CORR_ACC_NO CORR_ACC_NO,
          NULL ACC_SYS_REFNO
  FROM    DN_ACC_LICENCEE_INST_ACCOUNT A
  WHERE   --TO_DATE(TO_CHAR(A.TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY')=M_ENT_DATE AND
          A.TRNDATE=TO_DATE(M_ENT_DATE,'DD-MM-YYYY') AND
          A.ACC_TYPE_CODE<>'800'
 UNION ALL
 SELECT   A.PORTFOLIO_CODE PORTFOLIO_CODE,
          A.TRNDATE TRNDATE,
          NVL(A.ACC_TYPE_CODE,'0') ACC_TYPE_CODE,
          A.DRCR_STATUS DRCR_STATUS,
          NVL(A.TRNAMOUNT,0) TRNAMOUNT,
          A.DOCREFNO DOCREFNO,
          A.ENTDATE ENTDATE,
          A.PROC_DESC PROC_DESC,
          A.CORR_ACC_NO CORR_ACC_NO,
          NULL ACC_SYS_REFNO
 FROM     DN_ACC_LICENCEE_GEN_ACCOUNT A
 WHERE    --TO_DATE(TO_CHAR(A.TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY')=M_ENT_DATE AND
          A.TRNDATE=TO_DATE(M_ENT_DATE,'DD-MM-YYYY') AND
          A.ACC_TYPE_CODE<>'800'
 UNION ALL
 SELECT   A.PORTFOLIO_CODE PORTFOLIO_CODE,
          A.TRNDATE TRNDATE,
          NVL(A.ACC_TYPE_CODE,'0') ACC_TYPE_CODE,
          A.DRCR_STATUS DRCR_STATUS,
          NVL(A.TRNAMOUNT,0) TRNAMOUNT,
          A.DOCREFNO DOCREFNO,
          A.ENTDATE ENTDATE,
          A.PROC_DESC PROC_DESC,
          A.CORR_ACC_NO CORR_ACC_NO,
          A.ACC_SYS_REFNO ACC_SYS_REFNO
 FROM     DN_ACC_LICENCEE_GEN_ACCOUNT A
 WHERE    --TO_DATE(TO_CHAR(A.TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY')=M_ENT_DATE AND
          A.TRNDATE=TO_DATE(M_ENT_DATE,'DD-MM-YYYY') AND
          A.ACC_TYPE_CODE='800'
 --ORDER BY 1,2
 ;

M_PORTFOLIO_CODE      DN_ACC_LICEN_INST_GEN_DETAIL.PORTFOLIO_CODE%TYPE;
M_TRNDATE             DN_ACC_LICEN_INST_GEN_DETAIL.TRNDATE%TYPE;
M_ACC_TYPE_CODE       DN_ACC_LICEN_INST_GEN_DETAIL.ACC_TYPE_CODE%TYPE;
M_DRCR_STATUS         DN_ACC_LICEN_INST_GEN_DETAIL.DRCR_STATUS%TYPE;
M_TRNAMOUNT           DN_ACC_LICEN_INST_GEN_DETAIL.TRNAMOUNT%TYPE;
M_DOCREFNO            DN_ACC_LICEN_INST_GEN_DETAIL.DOCREFNO%TYPE;
M_ENTDATE             DN_ACC_LICEN_INST_GEN_DETAIL.ENTDATE%TYPE;
M_PROC_DESC           DN_ACC_LICEN_INST_GEN_DETAIL.PROC_DESC%TYPE;
M_CORR_ACC_NO         DN_ACC_LICEN_INST_GEN_DETAIL.CORR_ACC_NO%TYPE;
M_ACC_SYS_REFNO       DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE;
M_ROW INTEGER;
BEGIN
FOR I IN LICENCEE_DETAIL
LOOP

   M_PORTFOLIO_CODE :=I.PORTFOLIO_CODE;
   M_TRNDATE:=I.TRNDATE;
   M_ACC_TYPE_CODE:=I.ACC_TYPE_CODE;
   M_DRCR_STATUS:=I.DRCR_STATUS;
   M_TRNAMOUNT:=I.TRNAMOUNT;
   M_DOCREFNO:=I.DOCREFNO;
   M_ENTDATE:=I.ENTDATE;
   M_PROC_DESC:=I.PROC_DESC;
   M_CORR_ACC_NO:=I.CORR_ACC_NO;
   M_ACC_SYS_REFNO:=I.ACC_SYS_REFNO;

-------------------(1)-------------------------
IF M_PORTFOLIO_CODE IS NOT NULL AND M_ACC_TYPE_CODE <> 0 THEN
   IF(M_ACC_TYPE_CODE<>'800')THEN

    UPDATE DN_ACC_LICEN_INST_GEN_DETAIL
       SET TRNAMOUNT      =M_TRNAMOUNT
     WHERE PORTFOLIO_CODE =M_PORTFOLIO_CODE AND
           TRNDATE        =M_TRNDATE  AND
           ACC_TYPE_CODE  =M_ACC_TYPE_CODE AND
           DRCR_STATUS    =M_DRCR_STATUS AND
           DOCREFNO       =M_DOCREFNO AND
           ENTDATE        =M_ENTDATE AND
           PROC_DESC      =M_PROC_DESC AND
           CORR_ACC_NO    =M_CORR_ACC_NO;

   IF SQL%NOTFOUND THEN
     INSERT INTO DN_ACC_LICEN_INST_GEN_DETAIL
           (PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,
            DOCREFNO,ENTDATE,PROC_DESC,CORR_ACC_NO)
     VALUES
           (M_PORTFOLIO_CODE,M_TRNDATE,M_ACC_TYPE_CODE,M_DRCR_STATUS,M_TRNAMOUNT,
            M_DOCREFNO,M_ENTDATE,M_PROC_DESC,M_CORR_ACC_NO);
   END IF;

 ELSE

      UPDATE DN_ACC_LICEN_INST_GEN_DETAIL
       SET TRNAMOUNT      =M_TRNAMOUNT
     WHERE PORTFOLIO_CODE =M_PORTFOLIO_CODE AND
           TRNDATE        =M_TRNDATE  AND
           ACC_TYPE_CODE  =M_ACC_TYPE_CODE AND
           DRCR_STATUS    =M_DRCR_STATUS AND
           DOCREFNO       =M_DOCREFNO AND
           ENTDATE        =M_ENTDATE AND
           PROC_DESC      =M_PROC_DESC AND
           CORR_ACC_NO    =M_CORR_ACC_NO AND
           ACC_SYS_REFNO  =M_ACC_SYS_REFNO;

   IF SQL%NOTFOUND THEN
     INSERT INTO DN_ACC_LICEN_INST_GEN_DETAIL
           (PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,
            DOCREFNO,ENTDATE,PROC_DESC,CORR_ACC_NO,ACC_SYS_REFNO)
     VALUES
           (M_PORTFOLIO_CODE,M_TRNDATE,M_ACC_TYPE_CODE,M_DRCR_STATUS,M_TRNAMOUNT,
            M_DOCREFNO,M_ENTDATE,M_PROC_DESC,M_CORR_ACC_NO,M_ACC_SYS_REFNO);
   END IF;
 END IF;
 END IF;
END LOOP;
END DN_ACC_DETAILS;

