  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_LOGIN_OK" 
(
 M_USER                 VARCHAR2,
 M_PASSWORD             VARCHAR2,
 M_USER_STATUS          IN OUT NUMBER,
 M_URL                  IN OUT DN_REF_SCREEN_URL.DN_SCREEN_URL%TYPE,
 M_SCRNAME              DN_REF_SCREEN_URL.DN_SCREEN_NAME%TYPE,
 M_CLIENT_IP            VARCHAR2
)
AS

M_ROLE_NAME          VARCHAR2(40);
M_USER1              VARCHAR2(10):='';
M_MIN                NUMBER:=0;
M_COUNT              NUMBER;
M_EXPIRE_DEU         NUMBER;
M_SYS_DATE           DATE;
M_LOGIN_DATE         DATE;
M_LOG_COUNT          NUMBER;
M_PW_COUNT           NUMBER;

BEGIN
M_USER_STATUS:=0;
  --MCP MODIFIED BY MADHAWA 2011-12-01
  -- CREATED BY   : ASHINI HEWAGE
  -- CREATED ON   : 27-05-2005

--RAISE_APPLICATION_ERROR(-20201,'M_USER'||M_USER||'M_PASSWORD'||M_PASSWORD||'M_USER_STATUS'||M_USER_STATUS||'M_URL'||M_URL||'M_SCRNAME'||M_SCRNAME||'M_CLIENT_IP'||M_CLIENT_IP);

SELECT COUNT(*)
INTO   M_EXPIRE_DEU
FROM   DN_REF_PASSWORD_UPDATE A ,DN_REF_PASSWORD_EXPIRE_DUR B
WHERE  DN_USER=M_USER AND
       (EXPIRE_DURATION-(TO_DATE(TO_CHAR(SYSDATE,'DD-MON-YYYY'),'DD-MON-YYYY')-A.ENT_DATE))<REMINDER;


IF M_EXPIRE_DEU>0 THEN
    SELECT EXPIRE_DURATION-(TO_DATE(TO_CHAR(SYSDATE,'DD-MON-YYYY'),'DD-MON-YYYY')-A.ENT_DATE)
    INTO   M_EXPIRE_DEU
    FROM   DN_REF_PASSWORD_UPDATE A ,DN_REF_PASSWORD_EXPIRE_DUR B
    WHERE  DN_USER=M_USER AND
           (EXPIRE_DURATION-(TO_DATE(TO_CHAR(SYSDATE,'DD-MON-YYYY'),'DD-MON-YYYY')-A.ENT_DATE))<REMINDER;

    IF M_EXPIRE_DEU <=0 THEN

      UPDATE DN_REF_USER
      SET    ACTIVE_STATUS = 'L'
      WHERE  DN_USER =  M_USER;
    -- MASTER_LOG('TIME_LOG', M_USER, SYSDATE, 'System Login', '-', 'Unsuccessful system log-on attempts - User Lock',  'NEW');
  
    END IF;
END IF;
--END TEST

IF M_SCRNAME='WD_MT_MAIN'THEN ---if FCAM_MAIN

   /*-----------------------------TASK24082021-03666-NIROSHIMA*/
    SELECT  COUNT (*)
    INTO  M_PW_COUNT
    FROM  DN_REF_USER B
    WHERE UPPER(B.DN_USER) = UPPER(M_USER)
    AND   PCODE =  M_PASSWORD
    AND   ACTIVE_STATUS = 'Y';
    
    IF M_PW_COUNT = 0 THEN
     M_USER_STATUS := 0; 
     
        DN_UNAUTHORIZED_LOGIN_LOG(M_USER,M_SCRNAME,M_CLIENT_IP);
        UPDATE DN_REF_USER_INVALID_LOG
        SET    INVALID_COUNT= INVALID_COUNT+1
        WHERE  DN_USER = M_USER;

        IF SQL%NOTFOUND THEN
         INSERT INTO DN_REF_USER_INVALID_LOG
         VALUES (M_USER,1);

        END IF;
      --  MASTER_LOG('TIME_LOG', M_USER, SYSDATE, 'System Login', '-', 'Unsuccessful system log-on attempts - Invalid Username & Password',  'NEW');

     RETURN;

    END IF;
    
/*--------------------------------------*/

  SELECT
  COUNT(*) INTO M_COUNT
  FROM DN_REF_USER_STATUS
  WHERE  DN_USER = M_USER ;

  IF M_COUNT =0 THEN
    INSERT INTO  DN_REF_USER_STATUS
    VALUES(M_USER,'N',SYSDATE,M_SCRNAME);

  END IF;

  SELECT
  DECODE(ACTIVE_STATUS,'Y',(SYSDATE-LOGIN_DATE)*24*60,'N',0) INTO M_MIN
  FROM DN_REF_USER_STATUS
  WHERE  DN_USER = M_USER ;

  IF ( M_MIN >=15 AND M_SCRNAME <> 'WD_MT_MAIN') THEN 
     /*****************MADHAWA 2011-11-02************************************************************************/
     /*
        USER WHO DID NOT LOGGED OUT (ACTIVE_STATUS='Y') AND THE SESSION TIME OUT 
        PERIOD HAS ALREADY EXPIRED((SYSDATE-LOGIN_DATE)*24*60 > 15 MIN)

        THE USER WHO SATISFY  THE ABOVE CRITERIAS,WHEN TRYING TO LOGGED IN
        (AT HERE SCREEN NAME WILL BE WD_MT_MAIN) 
        SINCE THEIR ACTIVE_STATUS='Y' THEY WILL BE CHECKED AGAINST SESSION EXPIRATION DATA BASE LAVEL CHECK ..
        SO THEY ALMOST FAILS THE CHECK SINCE TIME OUT PERIOD LAPSED ALREADY SINCE THEY LOG OUT NEGLECTED USERS PREVIOUSLY
        .WHEN THEY TRYING TO LOGING THIS EXPIRATION CHECK FAILS.THEIR LOGGING ATTEMPT IS CONSIDERED AS INVALID ATEMOT AND
        ACTIVE STATUS SET TO 'N',
        FOR ACTIVE STATUS='N' USER'S SESSION EXPIRATION CHECK AVOIDED IN ABOVE SQL,. SO ONLY 2ND LOGIN WILL ONLY BE SUCCESS.
        THIS CAUSE USERS TO FACE THE USER AUTHENTICATION TWICE.
        SO CONDITION IS ADDED M_SCRNAME <>'WD_MT_MAIN'
     */  
     /*****************MADHAWA 2011-11-02************************************************************************/
    --if time out

    DN_UNAUTHORIZED_LOGIN_LOG(M_USER,M_SCRNAME,M_CLIENT_IP);

    UPDATE DN_REF_USER_STATUS
    SET    ACTIVE_STATUS= 'N'
    WHERE  DN_USER = M_USER;

    UPDATE DN_REF_USER_INVALID_LOG
    SET    INVALID_COUNT= INVALID_COUNT+1
    WHERE  DN_USER = M_USER;

    IF SQL%NOTFOUND THEN
      INSERT INTO DN_REF_USER_INVALID_LOG
      VALUES (M_USER,1);

    END IF;

  ELSE -- else time out       ---ELSE OF "HNB_MAIN"

    SELECT
      DN_SCREEN_URL,1 INTO M_URL,M_USER_STATUS
    FROM
      DN_REF_SCREEN_URL
    WHERE
      DN_SCREEN_NAME=M_SCRNAME;
 -- RAISE_APPLICATION_ERROR(-20001,''||M_URL||'***'||M_USER_STATUS);
  /*  IF M_USER_STATUS = 0 THEN

       DN_UNAUTHORIZED_LOGIN_LOG(M_USER,M_SCRNAME,M_CLIENT_IP);
        UPDATE DN_REF_USER_INVALID_LOG
        SET    INVALID_COUNT= INVALID_COUNT+1
        WHERE  DN_USER = M_USER;

        IF SQL%NOTFOUND THEN
         INSERT INTO DN_REF_USER_INVALID_LOG
         VALUES (M_USER,1);

        END IF;
        MASTER_LOG('TIME_LOG', M_USER, SYSDATE, 'System Login', '-', 'Unsuccessful system log-on attempts - Invalid Username',  'NEW');

    ELSE*/
   IF M_USER_STATUS != 0 THEN
       INSERT INTO DN_TRN_TIME_LOG(USER_NAME,IN_OUT_DATE,IN_OUT_STATUS,CLIENT_IP)
       VALUES (M_USER,SYSDATE,'LOG_IN',M_CLIENT_IP);
         --ADDED BY SVA ON 30-09-2005 FOR SEQUENCE CHANGE
       UPDATE DN_REF_USER_STATUS
       SET    LOGIN_DATE   = SYSDATE
       WHERE  TO_DATE(TO_CHAR(LOGIN_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>TO_DATE(TO_CHAR(SYSDATE,'DD-MON-YYYY'),'DD-MON-YYYY');

       SELECT COUNT(*)
       INTO   M_LOG_COUNT
       FROM   DN_REF_USER_STATUS
       HAVING MAX(LOGIN_DATE)<=SYSDATE ;

       IF M_LOG_COUNT >0 THEN

       SELECT TO_DATE(TO_CHAR(SYSDATE,'DD-MON-YYYY'),'DD-MON-YYYY'),
              TO_DATE(TO_CHAR(MAX(LOGIN_DATE),'DD-MON-YYYY'),'DD-MON-YYYY')
       INTO   M_SYS_DATE,M_LOGIN_DATE
       FROM   DN_REF_USER_STATUS
       HAVING MAX(LOGIN_DATE)<=SYSDATE ;

      /* IF M_SYS_DATE>M_LOGIN_DATE THEN
--          RAISE_APPLICATION_ERROR(-20001,'ABOUT TO RUN SEQUENCE'); ---TEMP CHECK
          DN_CAL_ADJUST_SEQUENCES;

       END IF;*/
     /*  ELSIF M_LOG_COUNT = 0 THEN
          DN_CAL_ADJUST_SEQUENCES;*/
       END IF;

       UPDATE DN_REF_USER_STATUS
       SET    LOGIN_DATE   = SYSDATE
       WHERE  TO_DATE(TO_CHAR(LOGIN_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>TO_DATE(TO_CHAR(SYSDATE,'DD-MON-YYYY'),'DD-MON-YYYY');

       -- END OF SEQUENCE CHANGE

       UPDATE DN_REF_USER_STATUS
       SET    LOGIN_DATE   = SYSDATE,
              LOGIN_SCREEN = M_SCRNAME,
              ACTIVE_STATUS= 'Y'
       WHERE  DN_USER = M_USER;

       IF SQL%NOTFOUND THEN
          INSERT INTO  DN_REF_USER_STATUS
          VALUES(M_USER,'Y',SYSDATE,M_SCRNAME);

       END IF;



       SELECT COUNT(*) INTO M_EXPIRE_DEU
       FROM   DN_REF_USER_INVALID_LOG
       WHERE  DN_USER = M_USER;

       IF M_EXPIRE_DEU>0 THEN
           UPDATE DN_REF_USER_INVALID_LOG
           SET    INVALID_COUNT= 0
           WHERE  DN_USER = M_USER;

       END IF;

    END IF;
   END IF; -- end time out
ELSE -- else fcam_main
--  RAISE_APPLICATION_ERROR(-20201,'M_USER'||M_USER||'M_PASSWORD'||M_PASSWORD||'M_USER_STATUS'||M_USER_STATUS||'M_URL'||M_URL||'M_SCRNAME'||M_SCRNAME||'M_CLIENT_IP'||M_CLIENT_IP);



  SELECT
  DECODE(ACTIVE_STATUS,'Y',(SYSDATE-LOGIN_DATE)*24*60,'N',0) INTO M_MIN
  FROM DN_REF_USER_STATUS
  WHERE  DN_USER = M_USER ;

  IF M_MIN >=15 THEN -- if time out

    DN_UNAUTHORIZED_LOGIN_LOG(M_USER,M_SCRNAME,M_CLIENT_IP);

    UPDATE DN_REF_USER_STATUS
    SET    ACTIVE_STATUS= 'N'
    WHERE  DN_USER = M_USER;

    UPDATE DN_REF_USER_INVALID_LOG
    SET    INVALID_COUNT= INVALID_COUNT+1
    WHERE  DN_USER = M_USER;
  --  MASTER_LOG('TIME_LOG', M_USER, SYSDATE, 'System Login', '-', 'Unsuccessful system log-on attempts',  'NEW');

    IF SQL%NOTFOUND THEN
      INSERT INTO DN_REF_USER_INVALID_LOG
      VALUES (M_USER,1);

    END IF;

    M_USER_STATUS:=-1; -- ADDED BY MADHAWA TO INDICATE SESSION EXPIRATION IN DATA BASE LEVEL BEFORE 15 MINUTES

  ELSE  -- else time out

 --        RAISE_APPLICATION_ERROR(-20201,'mcp M_USER_STATUS'||M_USER_STATUS);
    SELECT
    COUNT (*)
    INTO M_USER_STATUS
    FROM DN_REF_USER_VIEW_ACCESS A,DN_REF_USER B
    WHERE A.DN_USER=M_USER AND A.DN_USER=B.DN_USER AND
          upper(SCREEN_NAME)=upper(M_SCRNAME) AND ACTIVE_STATUS='Y';

    IF M_USER_STATUS>0 THEN
    SELECT
      DN_SCREEN_URL INTO M_URL
    FROM
      DN_REF_SCREEN_URL
    WHERE
      UPPER(DN_SCREEN_NAME)=UPPER(M_SCRNAME);

    INSERT INTO DN_TRN_TIME_LOG(USER_NAME,IN_OUT_DATE,IN_OUT_STATUS,CLIENT_IP)
    VALUES (M_USER,SYSDATE,M_SCRNAME,M_CLIENT_IP);

      --ADDED BY SVA ON 30-09-2005 FOR SEQUENCE CHANGE
       UPDATE DN_REF_USER_STATUS
       SET    LOGIN_DATE = SYSDATE
       WHERE  TO_DATE(TO_CHAR(LOGIN_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(TO_CHAR(SYSDATE,'DD-MON-YYYY'),'DD-MON-YYYY');

       SELECT SUM(M_LOG_COUNT)
       INTO   M_LOG_COUNT
       FROM (
           SELECT COUNT(*) M_LOG_COUNT
           FROM   DN_REF_USER_STATUS
           HAVING MAX(LOGIN_DATE) <= SYSDATE
           
           UNION ALL
           
           SELECT 0 FROM DUAL   --DUE TO SENFIN 19C DB ISSUE  not working [ HAVING MAX(LOGIN_DATE)<=SYSDATE ]           
       );

       IF M_LOG_COUNT > 0 THEN

       SELECT TO_DATE(TO_CHAR(SYSDATE,'DD-MON-YYYY'),'DD-MON-YYYY'),
              TO_DATE(TO_CHAR(MAX(LOGIN_DATE),'DD-MON-YYYY'),'DD-MON-YYYY')
       INTO   M_SYS_DATE,M_LOGIN_DATE
       FROM   DN_REF_USER_STATUS
       HAVING MAX(LOGIN_DATE) <= SYSDATE ;

    /*   IF M_SYS_DATE>M_LOGIN_DATE THEN
--          RAISE_APPLICATION_ERROR(-20001,'ABOUT TO RUN SEQUENCE'); ---TEMP CHECK
          DN_CAL_ADJUST_SEQUENCES;

       END IF;*/
     /*  ELSIF M_LOG_COUNT = 0 THEN
          DN_CAL_ADJUST_SEQUENCES;*/
       END IF;

       -- END OF SEQUENCE CHANGE

    UPDATE DN_REF_USER_STATUS
    SET    LOGIN_DATE   = SYSDATE,
           LOGIN_SCREEN = M_SCRNAME,
           ACTIVE_STATUS= 'Y'
    WHERE  DN_USER = M_USER;

    IF SQL%NOTFOUND THEN
          INSERT INTO  DN_REF_USER_STATUS
          VALUES(M_USER,'Y',SYSDATE,M_SCRNAME);

    END IF;


       SELECT COUNT(*) INTO M_EXPIRE_DEU
       FROM   DN_REF_USER_INVALID_LOG
       WHERE  DN_USER = M_USER;

       IF M_EXPIRE_DEU>0 THEN
           UPDATE DN_REF_USER_INVALID_LOG
           SET    INVALID_COUNT= 0
           WHERE  DN_USER = M_USER;

       END IF;
   ELSE
      DN_UNAUTHORIZED_LOGIN_LOG(M_USER,M_SCRNAME,M_CLIENT_IP);

    UPDATE DN_REF_USER_STATUS
    SET    LOGIN_DATE   = SYSDATE,
           LOGIN_SCREEN = M_SCRNAME,
           ACTIVE_STATUS= 'N'
    WHERE  DN_USER = M_USER;



    IF SQL%NOTFOUND THEN
          INSERT INTO  DN_REF_USER_STATUS
          VALUES(M_USER,'N',SYSDATE,M_SCRNAME);

    END IF;
    UPDATE DN_REF_USER_INVALID_LOG
    SET    INVALID_COUNT= INVALID_COUNT+1
    WHERE  DN_USER = M_USER;

    IF SQL%NOTFOUND THEN
      INSERT INTO DN_REF_USER_INVALID_LOG
      VALUES (M_USER,1);

    END IF;
   END IF ;
  END IF ; -- end time out
END IF; -- end fcam_main
  --RAISE_APPLICATION_ERROR(-20201,'M_USER_STATUS'||M_USER_STATUS||'M_URL'||M_URL);
COMMIT;
END DN_LOGIN_OK;








