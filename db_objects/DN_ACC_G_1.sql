set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_G_1" 
(
M_DOCREFNO      DN_TRN_BO_SETTL_INT_TRANSFER.INT_TRANS_NO%TYPE,
M_EFF_DATE      VARCHAR2
)
AS

/* PROCEDURE  - G_1 Transfers between FCAM Bank Accounts
   CREATED BY - SUKATHISVARAN
   CREATED ON - 20/MARCH/2000*/

M_TRNAMOUNT          DN_ACC_LICENCEE_GEN_ACCOUNT.TRNAMOUNT%TYPE;
M_PORTF_CODE         DN_ACC_LICENCEE_GEN_ACCOUNT.PORTFOLIO_CODE%TYPE;
M_ACC_SYS_REFNO_I    DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE;
M_ACC_SYS_REFNO_O    DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE;
M_INF_BRANCH_CODE    DN_TRN_BO_SETTL_INT_TRANSFER.INF_BRANCH_CODE%TYPE;
M_OUTF_BRANCH_CODE   DN_TRN_BO_SETTL_INT_TRANSFER.OUTF_BRANCH_CODE%TYPE;
M_ACC_SYS_REFNO_INF  DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE;
M_ACC_SYS_REFNO_OUTF DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE;



BEGIN
   SELECT TRANS_AMOUNT,PORTFOLIO_CODE,INF_ACC_NO,OUTF_ACC_NO,INF_BRANCH_CODE,OUTF_BRANCH_CODE
   INTO M_TRNAMOUNT,M_PORTF_CODE,M_ACC_SYS_REFNO_I,M_ACC_SYS_REFNO_O,M_INF_BRANCH_CODE,M_OUTF_BRANCH_CODE
   FROM DN_TRN_BO_SETTL_INT_TRANSFER
   WHERE INT_TRANS_NO=M_DOCREFNO;

  SELECT
      ACC_SYS_REFNO
   INTO M_ACC_SYS_REFNO_INF
   FROM DN_REF_LICENCEE_SETTLEMENT
   WHERE BRANCH_CODE=M_INF_BRANCH_CODE
   AND ACC_NO = M_ACC_SYS_REFNO_I
   AND ACTIVE_STATUS ='Y';

   SELECT
      ACC_SYS_REFNO
   INTO M_ACC_SYS_REFNO_OUTF
   FROM DN_REF_LICENCEE_SETTLEMENT
   WHERE BRANCH_CODE=M_OUTF_BRANCH_CODE
   AND ACC_NO = M_ACC_SYS_REFNO_O
   AND ACTIVE_STATUS ='Y';

  INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
    ( PORTFOLIO_CODE,
      DN_PORTFOLIO_CODE,
      TRNDATE,
      ACC_TYPE_CODE,
      DRCR_STATUS,
      TRNAMOUNT,
      DOCREFNO,
      ACC_SYS_REFNO,
      PROC_DESC,
      CORR_ACC_NO   )
          VALUES(   M_PORTF_CODE,
                    M_PORTF_CODE,
                    TO_DATE(M_EFF_DATE,'DD/MM/YYYY'),
                    '800',
                    'DR',
                    M_TRNAMOUNT,
                    M_DOCREFNO,
                    M_ACC_SYS_REFNO_INF,
                    'TRANSFERS BETWEEN BANK A/C',
                    '800'   );
 INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
    ( PORTFOLIO_CODE,
      DN_PORTFOLIO_CODE,
      TRNDATE,
      ACC_TYPE_CODE,
      DRCR_STATUS,
      TRNAMOUNT,
      DOCREFNO,
      ACC_SYS_REFNO,
      PROC_DESC,
      CORR_ACC_NO   )
            VALUES( M_PORTF_CODE,
                    M_PORTF_CODE,
                    TO_DATE(M_EFF_DATE,'DD/MM/YYYY'),
                    '800',
                    'CR',
                    M_TRNAMOUNT,
                    M_DOCREFNO,
                    M_ACC_SYS_REFNO_OUTF,
                    'TRANSFERS BETWEEN BANK A/C',
                    '800'   );


END DN_ACC_G_1;

