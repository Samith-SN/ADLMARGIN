--------------------------------------------------------
--  DDL for Procedure DN_MARKET_VALUES_EQUI
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_MARKET_VALUES_EQUI" 
   (
    M_SECURITY_CODE             DN_TRN_MARKET_RATE_EQUI.SECURITY_CODE%TYPE,
    M_VALUE_DATE                VARCHAR2,
    M_MARKET_RATE               VARCHAR2
  )
AS


   M_MARKET_RATE2              DN_TRN_MARKET_RATE_EQUI.MARKET_RATE%TYPE;
   M_CNT  NUMBER DEFAULT 0;
BEGIN

   SELECT    COUNT(*) INTO M_CNT FROM
    DN_TRN_MARKET_RATE_EQUI WHERE SECURITY_CODE=M_SECURITY_CODE AND DN_DATE = TO_DATE(M_VALUE_DATE,'DD-MM-YYYY');

    IF M_CNT > 0 THEN
    DELETE FROM
    DN_TRN_MARKET_RATE_EQUI WHERE SECURITY_CODE=M_SECURITY_CODE AND DN_DATE = TO_DATE(M_VALUE_DATE,'DD-MM-YYYY');

   INSERT INTO DN_TRN_MARKET_RATE_EQUI
    (SECURITY_CODE,MARKET_RATE,DN_DATE)
   VALUES
    (M_SECURITY_CODE,M_MARKET_RATE,TO_DATE(M_VALUE_DATE,'DD/MM/YYYY'));

    ELSE
    INSERT INTO DN_TRN_MARKET_RATE_EQUI
    (SECURITY_CODE,MARKET_RATE,DN_DATE)
   VALUES
    (M_SECURITY_CODE,M_MARKET_RATE,TO_DATE(M_VALUE_DATE,'DD/MM/YYYY'));

    END IF;

   COMMIT;
    EXCEPTION WHEN OTHERS THEN
   RAISE_APPLICATION_ERROR(-20001,TO_CHAR(SQLCODE)||SQLERRM||'Error..'); 
   ROLLBACK;

END DN_MARKET_VALUES_EQUI;

