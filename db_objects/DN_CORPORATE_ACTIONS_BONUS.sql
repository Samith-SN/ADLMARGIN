  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CORPORATE_ACTIONS_BONUS" 
(
 M_LAST_DAILY         DATE,
 M_USERNAME           VARCHAR2
)

IS
 CURSOR C1 IS
 SELECT A.PORTFOLIO_CODE PORT,A.SECURITY_CODE SEC,A.INST_TYPE INST,
 SUM(A.FACE_VAL) NOOFSHARES,DN_GET_DEAL_INV_TYPE_NAME(A.DEAL_NO) INV_TYPE,
   --ADD by WARUNA 2012-05-30
 (SELECT ACTI_REF_NO
  FROM DN_CORPORATE_ACTIONS C
  WHERE
  C.ACTIVITY IN ('BONUS')
  AND C.XC_DATE = TRUNC(M_LAST_DAILY,'DD')+1
  AND C.INST_TYPE IN (SELECT INST_TYPE
                      FROM DN_REF_INSTRUMENT
                      WHERE INST_CAT ='EQUITY')
                      AND C.STATUS = 'ENT'
                      AND C.SECURITY_CODE=A.SECURITY_CODE
  ) ACTI_REF_NO,
  GET_PORT_BROKER(A.PORTFOLIO_CODE,A.DEAL_NO) BROKER
 --ADD by WARUNA 2012-05-30

 FROM DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_REF_SECURITY B
 WHERE A.SECURITY_CODE=B.SECURITY_CODE
 AND A.SERIAL_NO_STATUS='INV'
 AND A.SECURITY_CODE IN (SELECT SECURITY_CODE
                         FROM DN_CORPORATE_ACTIONS A
                         WHERE A.ACTIVITY IN ('BONUS')
                         AND A.XC_DATE = TRUNC(M_LAST_DAILY,'DD')+1
                         AND A.INST_TYPE IN (SELECT INST_TYPE
                                             FROM DN_REF_INSTRUMENT
                                             WHERE INST_CAT ='EQUITY')
                                             AND STATUS = 'ENT'  )
 GROUP BY A.PORTFOLIO_CODE,A.SECURITY_CODE,A.INST_TYPE,DN_GET_DEAL_INV_TYPE_NAME(A.DEAL_NO),GET_PORT_BROKER(A.PORTFOLIO_CODE,A.DEAL_NO);

 I             NUMBER;
 M_CNT         NUMBER DEFAULT 0;
 NO_OF_SHARES  NUMBER;
 NR            NUMBER;
 DR            NUMBER;
 SEC_CODE      DN_REF_SECURITY.SECURITY_CODE%TYPE;
 MISSUER_CODE  DN_REF_SECURITY.ISSUER_CODE%TYPE;
 MISSUER_CODE1 DN_REF_PRIMARY_ISSUER.ISSUER_CODE%TYPE;
 MISSUER_NAME  DN_REF_PRIMARY_ISSUER.ISSUER_NAME%TYPE;
 M_DEAL_NO     DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
 M_END_CODE    VARCHAR2(1);
 EDATE         DATE;
 MINST         DN_REF_INSTRUMENT.INST_TYPE%TYPE;



BEGIN

SELECT  TRUNC(M_LAST_DAILY,'DD')+1 INTO EDATE FROM DUAL;

dbms_output.put_line('begin ');

FOR I IN C1 LOOP
M_DEAL_NO :='';

SEC_CODE := I.SEC  ;
MINST := I.INST;

dbms_output.put_line('SEC_CODE ='||SEC_CODE||' - MINST = '||MINST);
/*
SELECT ISSUER_CODE INTO MISSUER_CODE FROM DN_REF_SECURITY WHERE SECURITY_CODE=SEC_CODE;


SELECT COUNT(PORTFOLIO_CODE) INTO  M_CNT  FROM DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE = MISSUER_CODE;

dbms_output.put_line(MISSUER_CODE||' - M_CNT ='||M_CNT);
IF M_CNT = 0 THEN
 SELECT ISSUER_CODE,ISSUER_NAME  INTO MISSUER_CODE1 ,MISSUER_NAME
 FROM DN_REF_PRIMARY_ISSUER  WHERE ISSUER_CODE=MISSUER_CODE;

 INSERT INTO  DN_REF_PORTFOLIO
 (PORTFOLIO_CODE,PF_TYPE,PF_NAME,POSTAL_CODE,BUSI_REG_NIC,CATEGORY_ENTITY, NATURE_OCCUPATION,SECT_CODE,MBFSL_SECT_CODE,
 NEST_REVIEW, TOT_EXP_LIMIT,PERC_TOT_EXP,APPLY_STATUS,LIMIT,USER_TYPE,
 MARGIN_CALL_STATUS,TEMP_MARGIN_CALL_STATUS,MANAGEMENT_FEE,PA_STATUS,ACTIVE_STATUS,CDS_ACC_NO)
 VALUES
 (MISSUER_CODE1,'C',MISSUER_NAME,'99999','1234','COMPANY','ABC','TRAD','MBSE',SYSDATE,'0',0,'D',0,'B','N','N',5,'N','N','N/A') ;

END IF;
*/

         SELECT   RATIO1,RATIO2 INTO NR,DR
         FROM DN_CORPORATE_ACTIONS
         WHERE ACTIVITY = 'BONUS'
         AND SECURITY_CODE=I.SEC
         AND INST_TYPE=I.INST
         AND XC_DATE =  TRUNC(M_LAST_DAILY,'DD')+1
         AND STATUS = 'ENT' ;

 dbms_output.put_line('nr-'||NR||' - DR-'||DR);

         SELECT ROUND((I.NOOFSHARES/DR)*NR)
         INTO  NO_OF_SHARES
         FROM DUAL;

/* MBFSL_OUTRIGHT_IN1 (M_DEAL_NO,I.PORT,MISSUER_CODE,I.INST,I.SEC,M_END_CODE,'SLR','UD',
 EDATE,'A365',0,0,0,NO_OF_SHARES,0,0,0,M_USERNAME,M_DEAL_NO,'N','SL',M_DEAL_NO,'EQUITY_COR',0,SYSDATE,SYSDATE,'',I.INV_TYPE);
COMMENTED BY INDITHA 2005-7-14 FOR VC05-008
*/
--ADD BY INDITHA 2005-7-12 VC05-008

             IF NO_OF_SHARES > 0 THEN

                     DN_CORP_ACTION_ORDEAL_GEN_B(M_DEAL_NO,I.PORT,I.BROKER/*MISSUER_CODE*/,I.INST,I.SEC,M_END_CODE,'SLR','UD',
                     TO_CHAR(EDATE,'DD-MM-YYYY'),'A365',0,0,0,NO_OF_SHARES,0,0,0,M_USERNAME,M_DEAL_NO,'N','SL',M_DEAL_NO,'EQUITY_COR',0,TO_CHAR(EDATE,'DD-MM-YYYY'),TO_CHAR(EDATE,'DD-MM-YYYY'));

                     INSERT INTO DN_CORPORATE_ACTIONS_DEAL(DEAL_NO, ACTIVITY,SECURITY_CODE,XC_DATE,ALLOTMENT_DATE,LETTER_DISPATCH,ACCEPTANCE_DATE,PROCESS,EXIST_HOLDING,ENTITLEMENT,REC_DATE,ACTI_REF_NO)
                     VALUES(M_DEAL_NO,'BONUS',I.SEC,TRUNC(M_LAST_DAILY+1,'DD'),NULL,NULL,NULL,'EX_DATE',I.NOOFSHARES,NO_OF_SHARES,NULL,I.ACTI_REF_NO);

                     INSERT INTO DN_CORPORATE_ACT_REF ( ACTI_REF_NO, FACILITY_NO, ELIGIBLE_SHARE, OBTAIN_SHARE,OBTAIN_AMMOUNT, OBTAIN_VALUE, ENT_DATE)
                     VALUES (I.ACTI_REF_NO,I.PORT,I.NOOFSHARES,NO_OF_SHARES,0,0,SYSDATE);

             END IF;

END LOOP;

         UPDATE DN_CORPORATE_ACTIONS
         SET STATUS = 'PROCESSED'
         WHERE ACTIVITY = 'BONUS'
         AND SECURITY_CODE=SEC_CODE
         AND INST_TYPE=MINST
         AND XC_DATE =  TRUNC(M_LAST_DAILY,'DD')+1
         AND STATUS = 'ENT';




END DN_CORPORATE_ACTIONS_BONUS; 

