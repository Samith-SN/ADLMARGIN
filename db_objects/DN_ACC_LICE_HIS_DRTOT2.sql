  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_ACC_LICE_HIS_DRTOT2" (
     M_ACC_TYPE_CODE        DN_ACC_LICEN_INST_GEN_HIS.ACC_TYPE_CODE%TYPE,
     M_FROM_DATE            VARCHAR2,
     M_TO_DATE              VARCHAR2,
     M_OPTION               VARCHAR2,
     M_MODE                 VARCHAR2
    )
   RETURN  REAL
    IS

    -- Function     : TO RETURN DRTOT FROM HISTORY TABLE
    -- System       : DEALNET
    -- Created by   : LATHIKA
    -- Created on   : 02/02/2000

 M_DRTOT                   NUMBER;
 M_DRTOT2                  NUMBER;
 M_COUNT                   NUMBER;

  BEGIN
M_DRTOT:=0;
M_DRTOT2:=0;
M_COUNT:=0;

IF M_OPTION='DATA4' THEN
  IF M_MODE='SUM' THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
   INTO   M_DRTOT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='DR';

   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
   INTO   M_DRTOT2
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='DR';

  ELSIF M_MODE='HIS' THEN
   SELECT COUNT(*)
   INTO   M_COUNT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS   IN('DR','CR');

   IF  M_COUNT=0 THEN

      SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
      INTO   M_DRTOT
      FROM   DN_ACC_LICEN_INST_GEN_HIS A
      WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
      AND    A.DRCR_STATUS    ='DR';
   ELSE
    M_DRTOT:=0;
   END IF;

  END IF;
ELSIF M_OPTION='DATA3' THEN
 IF M_MODE='SUM' THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
   INTO   M_DRTOT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='DR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') ;

 SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
   INTO   M_DRTOT2
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='DR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') ;

ELSIF M_MODE='HIS' THEN
   SELECT COUNT(*)
   INTO   M_COUNT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS   IN('DR','CR')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') ;

   IF  M_COUNT=0 THEN

      SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
      INTO   M_DRTOT
      FROM   DN_ACC_LICEN_INST_GEN_HIS A
      WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
      AND    A.DRCR_STATUS    ='DR'
      AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY')
      AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') ;

   ELSE
    M_DRTOT:=0;
   END IF;

  END IF;
ELSIF M_OPTION='DATA2' THEN
  IF M_MODE='SUM' THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
   INTO   M_DRTOT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='DR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY');

   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
   INTO   M_DRTOT2
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='DR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY');

 ELSIF M_MODE='HIS' THEN
  SELECT COUNT(*)
   INTO   M_COUNT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY')
   AND    A.DRCR_STATUS   IN('DR','CR');

   IF  M_COUNT=0 THEN

      SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
      INTO   M_DRTOT
      FROM   DN_ACC_LICEN_INST_GEN_HIS A
      WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
      AND    A.DRCR_STATUS    ='DR'
      AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY');

   ELSE
    M_DRTOT:=0;
   END IF;

  END IF;

ELSIF M_OPTION='DATA1' THEN
  IF M_MODE='SUM' THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
   INTO   M_DRTOT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='DR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY');

   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
   INTO   M_DRTOT2
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='DR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY');

 ELSIF M_MODE='HIS' THEN
  SELECT COUNT(*)
   INTO   M_COUNT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS   IN('DR','CR')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY');

   IF  M_COUNT=0 THEN

      SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT
      INTO   M_DRTOT
      FROM   DN_ACC_LICEN_INST_GEN_HIS A
      WHERE  A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
      AND    A.DRCR_STATUS    ='DR'
      AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY');

   ELSE
    M_DRTOT:=0;
   END IF;

  END IF;

END IF;

 M_DRTOT:= M_DRTOT+M_DRTOT2;

 RETURN ROUND(M_DRTOT,2);
END DN_ACC_LICE_HIS_DRTOT2;

