set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MF_REF_LOCATION" 

   (M_LOC_CODE      DN_REF_LOCATION.LOC_CODE%TYPE,
    M_LOC_DESC      DN_REF_LOCATION.LOC_DESC%TYPE,
    M_ADD_ID        DN_REF_LOCATION.ADD_IDENTIFICATION%TYPE,
    M_ADD_LOC       DN_REF_LOCATION.ADD_LOCATION%TYPE,
    M_ADD_STREET    DN_REF_LOCATION.ADD_STREET%TYPE,
    M_ADD_CITY      DN_REF_LOCATION.ADD_CITY%TYPE,
    M_ADD_COUNTRY   DN_REF_LOCATION.ADD_COUNTRY%TYPE,
    M_POSTAL_CODE   DN_REF_LOCATION.POSTAL_CODE%TYPE,
    CONTACT_NO      VARCHAR2,
    M_STATUS        CHAR
   )
  AS
    LOC_COUNT      NUMBER;
    T_COUNT        NUMBER;
    F_COUNT        NUMBER;
    E_COUNT        NUMBER;
    INCT           INTEGER;
    INCF           INTEGER;
    INCE           INTEGER;
BEGIN

    /* PROCEDURE  -  TO INSERT LOCATION DETAILS
       SYSTEM     -  DEALNET
       CREATED BY -  DAYAN.
       CREATED ON -  15/06/1999 */

        LOC_COUNT:=0;
        T_COUNT:=0;
        F_COUNT:=0;
        E_COUNT:=0;

 SELECT COUNT(*) INTO LOC_COUNT FROM DN_REF_LOCATION
        WHERE M_LOC_CODE=LOC_CODE;

    IF LOC_COUNT=0  THEN
          INSERT INTO DN_REF_LOCATION
            (LOC_CODE, LOC_DESC, ADD_IDENTIFICATION,ADD_LOCATION, ADD_STREET, ADD_CITY, ADD_COUNTRY,POSTAL_CODE)
          VALUES
            (M_LOC_CODE,M_LOC_DESC,M_ADD_ID,M_ADD_LOC,M_ADD_STREET,M_ADD_CITY,M_ADD_COUNTRY,M_POSTAL_CODE);
    END IF;

  SELECT COUNT(*) INTO T_COUNT FROM DN_REF_LOCATION_CONT_TELNO
         WHERE  LOC_CODE=M_LOC_CODE AND TEL_NO=CONTACT_NO ;

     IF T_COUNT=0  AND CONTACT_NO<>'NULL' AND M_STATUS='T' THEN
        SELECT MAX(SEQ_NO)+1 INTO INCT FROM DN_REF_LOCATION_CONT_TELNO;

           INSERT INTO DN_REF_LOCATION_CONT_TELNO
                (LOC_CODE,TEL_NO,SEQ_NO)
           VALUES
                (M_LOC_CODE,CONTACT_NO,INCT);
    END IF;

SELECT COUNT(*) INTO F_COUNT FROM DN_REF_LOCATION_CONT_FAXNO
        WHERE LOC_CODE=M_LOC_CODE AND FAX_NO=CONTACT_NO;

     IF F_COUNT=0 AND CONTACT_NO<>'NULL' AND M_STATUS='F' THEN

         SELECT MAX(SEQ_NO)+1 INTO INCF FROM DN_REF_LOCATION_CONT_FAXNO;

         INSERT INTO  DN_REF_LOCATION_CONT_FAXNO
           (LOC_CODE,FAX_NO,SEQ_NO)
          VALUES
           (M_LOC_CODE,CONTACT_NO,INCF);

    END IF;

SELECT COUNT(*) INTO E_COUNT FROM DN_REF_LOCATION_CONT_EMAIL
       WHERE LOC_CODE=M_LOC_CODE AND EMAIL=CONTACT_NO;

      IF E_COUNT=0 AND CONTACT_NO<>'NULL' AND M_STATUS='E' THEN

        SELECT MAX(SEQ_NO)+1 INTO INCE FROM DN_REF_LOCATION_CONT_EMAIL;


         INSERT INTO DN_REF_LOCATION_CONT_EMAIL
           (LOC_CODE,EMAIL,SEQ_NO)
        VALUES
           (M_LOC_CODE,CONTACT_NO,INCE);

       END IF;

 COMMIT;
END MF_REF_LOCATION;

