  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_LICENCE_MT_PERCENT" 
(
 M_SECURITY_CODE        DN_REF_SECURITY.SECURITY_CODE%TYPE
 )
 RETURN NUMBER
 AS
 M_LICENCE_MT_PERCENT      NUMBER;

 BEGIN

   SELECT  A.LICENCE_MT_PERCENT  INTO   M_LICENCE_MT_PERCENT
   FROM DN_REF_SECURITY A WHERE A.SECURITY_CODE=M_SECURITY_CODE;
