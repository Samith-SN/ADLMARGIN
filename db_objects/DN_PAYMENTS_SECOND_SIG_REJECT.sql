/*CURSOR M_CURSOR IS SELECT A.PAYMENT_NO, A.PORTFOLIO_CODE, A.SUS_REF_NO, A.SETTLE_MODE,
                A.ENTRY_TYPE, A.ID_PORTFOLIO_CODE, A.PAY_AMOUNT,
                A.LIC_BRANCH_CODE, A.LIC_ACC_NO, A.PAYEE_BRANCH_CODE,
