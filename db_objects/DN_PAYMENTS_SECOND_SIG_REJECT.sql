                AND A.PAYMENT_NO=TRIM(M_PAYMENT_NO);*/
                
                
                
                CURSOR M_CURSOR(MM_PAYMENT_NO DN_TRN_BO_SETTL_PAYMENT_TEMP.PAYMENT_NO%TYPE) IS -- INF=DIVIDUAL PAYMENT
                    SELECT A.PAYMENT_NO, A.PORTFOLIO_CODE, A.SUS_REF_NO, A.SETTLE_MODE,
                    A.ENTRY_TYPE, A.ID_PORTFOLIO_CODE, A.PAY_AMOUNT,
                    A.LIC_BRANCH_CODE, A.LIC_ACC_NO, A.PAYEE_BRANCH_CODE,
                    A.PAYEE_ACC_NO, A.PROCESS_STATUS, A.DN_USER, A.ENTDATE,
                    A.RECON_STATUS, A.RECON_DATE, A.RECON_BY, A.EFF_VALDATE,
                    A.REALISED_DATE, A.PAYEE_NAME, A.PAY_AMOUNT_CURR,
                    A.PAY_ADVICE_STATUS, A.OTH_COMMENT, A.TRNDATE, B.PORTFOLIO_CODE CLIENT_CODE,
                   -- A.DN_MOD_USER, A.MODDATE, A.APP_STATUS
                    A.GROUP_NET_NO
                    FROM DN_TRN_BO_SETTL_PAYMENT A, DN_TRN_BO_SETTL_PAYMENT_BULK B 
                    WHERE PAY_STATUS='SIG1' 
                    AND A.PAYMENT_NO=TRIM(MM_PAYMENT_NO)
                    AND A.PAYMENT_NO= B.PAYMENT_NO
                    AND GROUP_NET_NO IS NULL
               
                    ;
                    
CURSOR M_CURSOR_2(M_GROUP_NET_NO DN_TRN_BO_SETTL_PAYMENT_TEMP.GROUP_NET_NO%TYPE)  
IS (  
  SELECT PAYMENT_NO ,'PAYMENT' SETTLE_TYPE FROM
  DN_TRN_BO_SETTL_PAYMENT 
  WHERE GROUP_NET_NO = M_GROUP_NET_NO
  AND PAY_STATUS='SIG1'

 UNION ALL

 SELECT A.REC_NO ,'RECEIPT' SETTLE_TYPE
 FROM   DN_TRN_BO_SETTL_RECEIPT_TMP A
 WHERE GROUP_NET_NO = M_GROUP_NET_NO
 AND APP_STATUS='APPR1'
 
  ) ;   
 
CURSOR M_CURSOR_3(M_REC_NO  DN_TRN_BO_NET_RECEIPT_TMP.REC_NO%TYPE) IS       SELECT A.REC_NO, A.SUS_REF_NO, A.SETTLE_MODE, A.PAYER_BRANCH_CODE,
                            A.PAYER_ACC_NO, A.PAYER_REF, A.PORTFOLIO_CODE,
                            A.SUSPENSE_ENTRY_TYPE, A.ID_PORTFOLIO_CODE, A.REC_AMOUNT,
                            A.OTH_COMMENTS, A.BRANCH_CODE, A.ACC_NO, A.STATUS, A.DN_USER,
                            A.ENTDATE, A.RECON_STATUS, A.RECON_DATE, A.RECON_BY,
                            A.EFF_VALDATE, A.REALISED_DATE, A.REC_AMOUNT_CURR,
                            A.EXCHANGE_GAIN_LOSS, A.SELL_PORTFOLIO_CODE, A.TRNDATE
                            FROM DN_TRN_BO_SETTL_RECEIPT_BULK  A--DN_TRN_BO_NET_RECEIPT_TMP A CAHNGE BY WARUNA 2012-08-14
                            WHERE REC_STATUS = 'APPR1' --APP_STATUS
                            AND A.REC_NO     = M_REC_NO
                            AND A.GROUP_NET_NO IS NOT NULL
                            
                            ;  
                
CURSOR M_CURSOR_4(MM_PAYMENT_NO DN_TRN_BO_SETTL_PAYMENT_TEMP.PAYMENT_NO%TYPE) IS  -- GROUP OR NET SETTELEMET
                  
                    
                    SELECT A.PAYMENT_NO, A.PORTFOLIO_CODE, A.SUS_REF_NO, A.SETTLE_MODE,
                    A.ENTRY_TYPE, A.ID_PORTFOLIO_CODE, A.PAY_AMOUNT,
                    A.LIC_BRANCH_CODE, A.LIC_ACC_NO, A.PAYEE_BRANCH_CODE,
                    A.PAYEE_ACC_NO, A.PROCESS_STATUS, A.DN_USER, A.ENTDATE,
                    A.RECON_STATUS, A.RECON_DATE, A.RECON_BY, A.EFF_VALDATE,
                    A.REALISED_DATE, A.PAYEE_NAME, A.PAY_AMOUNT_CURR,
                    A.PAY_ADVICE_STATUS, A.OTH_COMMENT, A.TRNDATE, B.PORTFOLIO_CODE CLIENT_CODE,
                  --  A.DN_MOD_USER, A.MODDATE, A.APP_STATUS,
                    A.GROUP_NET_NO
                    FROM DN_TRN_BO_SETTL_PAYMENT A, DN_TRN_BO_SETTL_PAYMENT_BULK B 
                    WHERE PAY_STATUS='SIG1' 
                    AND A.PAYMENT_NO=TRIM(MM_PAYMENT_NO)
                    AND A.PAYMENT_NO= B.PAYMENT_NO
                    AND GROUP_NET_NO IS NOT NULL
                    ;
M_GROUP_NET_COUNT   NUMBER;
M_GROUP_NET_MODE    DN_MAS_SETLE_GROUP_NET.GROUP_NET_MODE%TYPE; 
BEGIN

--RAISE_APPLICATION_ERROR(-20201,'PAYMENT INVALID='||M_PAYMENT_NO||'**');

   M_SETTLEMENT := 'NOT_CURR_ACC';
  M_PORT_CODE  := 'GEN';
  M_DEAL_TYPE  := 'CACC';
 
 
 SELECT LAST_DAILY INTO M_LAST_DAILY FROM DN_SYS_PARAMETER;
 
 
IF M_ACTIVE_STATUS='ENT' THEN
  
  
  SELECT COUNT(A.GROUP_NET_MODE)
  INTO M_GROUP_NET_COUNT
  FROM DN_MAS_SETLE_GROUP_NET A 
  WHERE A.GROUP_NET_NO = M_PAYMENT_NO; 
  
  IF M_GROUP_NET_COUNT > 0 THEN 
  
    SELECT A.GROUP_NET_MODE,TRNDATE 
    INTO M_GROUP_NET_MODE,M_GROUP_TRNDATE
    FROM DN_MAS_SETLE_GROUP_NET A 
    WHERE A.GROUP_NET_NO = M_PAYMENT_NO; 
  
  IF(M_LAST_DAILY<M_GROUP_TRNDATE) THEN
  
    UPDATE DN_MAS_SETLE_GROUP_NET
    SET APP_STATUS     = 'REJ'
    WHERE GROUP_NET_NO = M_PAYMENT_NO;
  ELSE 
      RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT REJECT, TRN_DATE LOWER THAN EOD ='||M_PAYMENT_NO);
  END IF; 
  
  END IF;
    
  IF M_GROUP_NET_COUNT = 0 THEN  -- NOT A GROSS OR NET SETTLEMENT
           
       FOR X IN M_CURSOR(M_PAYMENT_NO) LOOP 
           
        EXIT WHEN M_CURSOR%NOTFOUND;
       
        IF(DN_GET_TOTAL_PAYMENT(X.CLIENT_CODE,X.ID_PORTFOLIO_CODE,TO_CHAR(X.EFF_VALDATE,'DD/MM/YYYY'))>=  DN_GET_TOTAL_PAID(X.CLIENT_CODE,X.ID_PORTFOLIO_CODE,TO_CHAR(X.EFF_VALDATE,'DD/MM/YYYY')) +DN_GET_TOTAL_PENDING_PAYMENTS(X.CLIENT_CODE,X.ID_PORTFOLIO_CODE,TO_CHAR(X.EFF_VALDATE,'DD/MM/YYYY'))) THEN
        
        IF(M_LAST_DAILY<X.TRNDATE) THEN
     
          UPDATE DN_TRN_BO_SETTL_PAYMENT_TEMP A
          SET  A.APP_STATUS = 'REJ',
          A.DN_MOD_USER     = M_USER,
          A.MODDATE         = SYSDATE
          WHERE A.PAYMENT_NO =X.PAYMENT_NO;
          
          UPDATE DN_TRN_BO_SETTL_PAYMENT A
           SET    A.PAY_STATUS = 'REJ'
           WHERE A.PAYMENT_NO =X.PAYMENT_NO;
          
          UPDATE DN_TRN_BO_NET_PAYMENT_TEMP A
          SET  A.APP_STATUS  = 'REJ',
          A.DN_MOD_USER      = M_USER,
          A.MODDATE          = SYSDATE
          WHERE A.PAYMENT_NO = X.PAYMENT_NO;
           
                        SELECT  ACC_SYS_REFNO  INTO M_ACC_SYS_REFNO
                        FROM  DN_REF_LICENCEE_SETTLEMENT
                        WHERE  BRANCH_CODE=X.LIC_BRANCH_CODE
                        AND    ACC_NO=X.LIC_ACC_NO;
                        
                        IF(M_SETTLEMENT='CURR_ACC') THEN
                        DN_ACC_LINK_CURR_ACCOUNT('CACC',M_PORT_CODE,X.ID_PORTFOLIO_CODE,TO_DATE(TO_CHAR(M_LAST_DAILY+1,'DD-MM-YYYY'),'DD-MM-YYYY'),X.PAY_AMOUNT*-1,X.PAYMENT_NO,M_ACC_SYS_REFNO,X.ID_PORTFOLIO_CODE);--M_DEALNO --ADD BY WARUNA 2011-01-20
                        
                        ELSE
                        DN_ACC_LINK_BO_SETTL_PAY('CACC',M_PORT_CODE,X.ID_PORTFOLIO_CODE,TO_DATE(TO_CHAR(M_LAST_DAILY+1,'DD-MM-YYYY'),'DD-MM-YYYY'),X.PAY_AMOUNT*-1,X.PAYMENT_NO,M_ACC_SYS_REFNO,X.ID_PORTFOLIO_CODE);--M_DEALNO --ADD BY WARUNA 2011-1-20
                        DN_ACC_LINK_BO_SETTL_PINV('CACC',M_PORT_CODE,X.ID_PORTFOLIO_CODE,TO_DATE(TO_CHAR(M_LAST_DAILY+1,'DD-MM-YYYY'),'DD-MM-YYYY'),X.PAY_AMOUNT*-1,X.PAYMENT_NO,M_ACC_SYS_REFNO,X.ID_PORTFOLIO_CODE);--M_DEALNO --ADD BY WARUNA 2011-10-20
                        END IF;
           
        
           INSERT INTO DN_DOC_STATUS_LOG( DOC_REF_NO,DOC_TYPE,DOC_STATUS,DN_USER,ENT_DATE,DESCRIPTION)
           VALUES(M_PAYMENT_NO,'PAYMNET  CANCEL','REJ',M_USER,SYSDATE,'PAYMNET  CANCEL-'||M_ACTIVE_STATUS);
          
           ELSE 
            RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT REJECT  , TRN_DATE LOWER THAN EOD ='||M_PAYMENT_NO);
           END IF;
          
           ELSE
            RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT REJECT  PAYMNET   ='||M_PAYMENT_NO);
            
           END IF;
           
         END LOOP;    


ELSIF(M_GROUP_NET_COUNT > 0 ) THEN     ----[END] NOT A GROSS OR NET SETTLEMENT 
   
 FOR Y IN M_CURSOR_2(M_PAYMENT_NO) LOOP 
           
    EXIT WHEN M_CURSOR_2%NOTFOUND;
    
        
        -- RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT CONFIRM  ='||Y.PAYMENT_NO);
         
      IF Y.SETTLE_TYPE='PAYMENT' THEN -- PAYMENTS
      --  RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT CONFIRM  ='||Y.PAYMENT_NO);          
        FOR X IN M_CURSOR_4(Y.PAYMENT_NO) LOOP   --GOING TO SETTEL NET PAYMENT OR GROSS PAYMENT
     
      
            
        EXIT WHEN M_CURSOR_4%NOTFOUND;
       
        IF(DN_GET_TOTAL_PAYMENT(X.CLIENT_CODE,X.ID_PORTFOLIO_CODE,TO_CHAR(X.EFF_VALDATE,'DD/MM/YYYY'))>=  DN_GET_TOTAL_PAID(X.CLIENT_CODE,X.ID_PORTFOLIO_CODE,TO_CHAR(X.EFF_VALDATE,'DD/MM/YYYY')) +DN_GET_TOTAL_PENDING_PAYMENTS(X.CLIENT_CODE,X.ID_PORTFOLIO_CODE,TO_CHAR(X.EFF_VALDATE,'DD/MM/YYYY'))) THEN
       
         IF(M_LAST_DAILY<X.TRNDATE) THEN
       
          UPDATE DN_TRN_BO_SETTL_PAYMENT_TEMP A
          SET  A.APP_STATUS = 'REJ',
          A.DN_MOD_USER     = M_USER,
          A.MODDATE         = SYSDATE
          WHERE A.PAYMENT_NO =X.PAYMENT_NO;
          
          UPDATE DN_TRN_BO_SETTL_PAYMENT A
          SET    A.PAY_STATUS = 'REJ'
          WHERE A.PAYMENT_NO =X.PAYMENT_NO;
                   
          UPDATE DN_TRN_BO_NET_PAYMENT_TEMP A
          SET  A.APP_STATUS  = 'REJ',
          A.DN_MOD_USER      = M_USER,
          A.MODDATE          = SYSDATE
          WHERE A.PAYMENT_NO = X.PAYMENT_NO;
           
                        SELECT  ACC_SYS_REFNO  INTO M_ACC_SYS_REFNO
                        FROM  DN_REF_LICENCEE_SETTLEMENT
                        WHERE  BRANCH_CODE=X.LIC_BRANCH_CODE
                        AND    ACC_NO=X.LIC_ACC_NO;
                        
                        IF(M_SETTLEMENT='CURR_ACC') THEN
                        DN_ACC_LINK_CURR_ACCOUNT('CACC',M_PORT_CODE,X.ID_PORTFOLIO_CODE,TO_DATE(TO_CHAR(M_LAST_DAILY+1,'DD-MM-YYYY'),'DD-MM-YYYY'),X.PAY_AMOUNT*-1,X.PAYMENT_NO,M_ACC_SYS_REFNO,X.ID_PORTFOLIO_CODE);--M_DEALNO --ADD BY WARUNA 2011-01-20
                        
                        ELSE
                        DN_ACC_LINK_BO_SETTL_PAY('CACC',M_PORT_CODE,X.ID_PORTFOLIO_CODE,TO_DATE(TO_CHAR(M_LAST_DAILY+1,'DD-MM-YYYY'),'DD-MM-YYYY'),X.PAY_AMOUNT*-1,X.PAYMENT_NO,M_ACC_SYS_REFNO,X.ID_PORTFOLIO_CODE);--M_DEALNO --ADD BY WARUNA 2011-1-20
                        DN_ACC_LINK_BO_SETTL_PINV('CACC',M_PORT_CODE,X.ID_PORTFOLIO_CODE,TO_DATE(TO_CHAR(M_LAST_DAILY+1,'DD-MM-YYYY'),'DD-MM-YYYY'),X.PAY_AMOUNT*-1,X.PAYMENT_NO,M_ACC_SYS_REFNO,X.ID_PORTFOLIO_CODE);--M_DEALNO --ADD BY WARUNA 2011-10-20
                        END IF;
        
        
           INSERT INTO DN_DOC_STATUS_LOG( DOC_REF_NO,DOC_TYPE,DOC_STATUS,DN_USER,ENT_DATE,DESCRIPTION)
           VALUES(X.PAYMENT_NO,'PAYMNET  CANCEL','REJ',M_USER,SYSDATE,'PAYMNET  CANCEL-'||M_ACTIVE_STATUS);
          
           ELSE
            RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT REJECT  PAYMNET ,  TRN_DATE LOWER THAN EOD ='||M_PAYMENT_NO);
            
           END IF;
            
           ELSE
            RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT CANCEL PAYMNET   ='||X.PAYMENT_NO);
            
           END IF;
           
         END LOOP;
  
   ELSIF Y.SETTLE_TYPE='RECEIPT' THEN  --[END] PAYMENT        
   
   FOR xy IN M_CURSOR_3(Y.PAYMENT_NO) LOOP 
   EXIT WHEN M_CURSOR_3%NOTFOUND;
         
IF( DN_GET_TOTAL_RECEIPT(xy.SELL_PORTFOLIO_CODE,xy.ID_PORTFOLIO_CODE,to_char(xy.eff_valdate,'dd/mm/yyyy'))>=DN_GET_TOTAL_RECEIVED(xy.SELL_PORTFOLIO_CODE,xy.ID_PORTFOLIO_CODE,to_char(xy.eff_valdate,'dd/mm/yyyy'))+DN_GET_TOTAL_PENDING_RECEIPTS(xy.SELL_PORTFOLIO_CODE,xy.ID_PORTFOLIO_CODE,to_char(xy.eff_valdate,'dd/mm/yyyy'))) then
          
         /* TRN_SETTLE_RECEIPTS_ALL_GROUP (xy.REC_NO,xy.PORTFOLIO_CODE,'CACC',--xy.SUSPENSE_ENTRY_TYPE,
            XY.SUS_REF_NO,
            XY.ID_PORTFOLIO_CODE,XY.SETTLE_MODE,XY.REC_AMOUNT,XY.PAYER_BRANCH_CODE,XY.PAYER_ACC_NO,
            XY.PAYER_REF,XY.OTH_COMMENTS,XY.BRANCH_CODE,XY.ACC_NO,XY.STATUS,XY.DN_USER,TO_CHAR(XY.EFF_VALDATE,'DD/MM/YYYY'),
            XY.REC_NO,XY.SELL_PORTFOLIO_CODE,XY.SUS_REF_NO,XY.GROUP_NET_NO
                    );*/
          IF(M_LAST_DAILY<XY.TRNDATE) THEN
          
              UPDATE DN_TRN_BO_SETTL_RECEIPT_TMP A
              SET  A.APP_STATUS = 'REJ',
              A.DN_MOD_USER  = M_USER,
              A.MODDATE      = SYSDATE
              WHERE A.REC_NO =  xy.REC_NO;
                                        
              UPDATE DN_TRN_BO_NET_RECEIPT_TMP A
              SET  A.APP_STATUS = 'REJ',
              A.DN_MOD_USER  = M_USER,
              A.MODDATE      = SYSDATE
              WHERE A.REC_NO =  xy.REC_NO;
              
              UPDATE DN_TRN_BO_SETTL_RECEIPT_BULK A
              SET  A.REC_STATUS = 'REJ'
             -- A.DN_MOD_USER  = M_USER
             -- A.MODDATE      = SYSDATE
              WHERE A.REC_NO =  xy.REC_NO;
                        
                        SELECT ACC_SYS_REFNO  INTO M_ACC_SYS_REFNO
                        FROM   DN_REF_LICENCEE_SETTLEMENT
                        WHERE  BRANCH_CODE = XY.BRANCH_CODE
                        AND    ACC_NO      = XY.ACC_NO;
                        
                        IF(M_SETTLEMENT='CURR_ACC') THEN
                        DN_ACC_LINK_CURR_ACCOUNT_REC(M_DEAL_TYPE,'GEN',XY.ID_PORTFOLIO_CODE,TO_DATE(TO_CHAR(M_LAST_DAILY+1,'DD-MM-YYYY'),'DD-MM-YYYY'),XY.REC_AMOUNT*-1,XY.REC_NO,M_ACC_SYS_REFNO);--ADD BY WARUNA 2011-01-21      
                        ELSE
                        DN_ACC_LINK_BO_SETTL_REC(M_DEAL_TYPE,'GEN',XY.ID_PORTFOLIO_CODE,TO_DATE(TO_CHAR(M_LAST_DAILY+1,'DD-MM-YYYY'),'DD-MM-YYYY'),XY.REC_AMOUNT*-1,XY.REC_NO,M_ACC_SYS_REFNO,XY.SUS_REF_NO);--ADDED M_DEALNO FOR CURRENCY --ADD BY WARUNA 2010-11-21
                        END IF;                  
                        
        
           INSERT INTO DN_DOC_STATUS_LOG( DOC_REF_NO,DOC_TYPE,DOC_STATUS,DN_USER,ENT_DATE,DESCRIPTION)
           VALUES(XY.REC_NO ,'PAYMNET CANCEL','REJ',M_USER,SYSDATE,'PAYMNET  CANCEL-'||M_ACTIVE_STATUS);
        
           ELSE
           
            RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT REJECT  PAYMNET , TRN_DATE LOWER THAN EOD='||M_PAYMENT_NO);
            
           END IF;
           
        ELSE
         RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT PAYMNET  CANCEL  ='||XY.REC_NO);
         END IF;  
         END LOOP;
         
    END IF;--[END] RECEIPT    
    
      END LOOP; 
  
END IF;  

            
END IF;
  

--COMMIT;



END ; 

