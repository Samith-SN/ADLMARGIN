  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_PAYMENTS_SECOND_SIG_REJECT" 
   (
   M_PAYMENT_NO         dn_trn_bo_settl_payment.PAYMENT_NO%TYPE,
   M_ACTIVE_STATUS      DN_REF_PORTFOLIO.ACTIVE_STATUS%TYPE,
   M_USER               DN_DOC_STATUS_LOG.DN_USER%TYPE
   )
AS
M_NUMBER         VARCHAR(100);
M_SETTLEMENT     VARCHAR(100);
M_PORT_CODE      VARCHAR(3);
M_LAST_DAILY     DN_SYS_PARAMETER.LAST_DAILY%TYPE;
M_ACC_SYS_REFNO  DN_REF_LICENCEE_SETTLEMENT.ACC_SYS_REFNO%TYPE;
M_DEAL_TYPE      VARCHAR(100);
M_GROUP_TRNDATE  DATE;   

