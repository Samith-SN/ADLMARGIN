set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_REBATE_PAY_FIRST_SIG_REJECT" 
   (
   M_PAYMENT_NO         DN_TRN_REBATE_PAYMENT.PAYMENT_NO%TYPE,
   M_ACTIVE_STATUS      DN_REF_PORTFOLIO.ACTIVE_STATUS%TYPE,
   M_USER               DN_DOC_STATUS_LOG.DN_USER%TYPE
   )
AS
M_NUMBER VARCHAR(100);
M_AMT  DN_TRN_REBATE_PAYMENT.PAY_AMOUNT%TYPE;

/*
CREATED BY - K. M.WARUNA SRI JAYANATH
CREATED ON - 2012-02-27
SYSTEM     - ADLMARGIN

*/
        


BEGIN

--RAISE_APPLICATION_ERROR(-20201,'PAYMENT INVALID='||M_PAYMENT_NO||'**');
  
  
 IF M_ACTIVE_STATUS='CANCEL' THEN
  
  SELECT A.PAY_AMOUNT INTO M_AMT 
  FROM DN_TRN_REBATE_PAYMENT A 
  WHERE PAYMENT_NO = M_PAYMENT_NO;
 
  UPDATE DN_TRN_REBATE_PAYMENT
  SET    PAY_STATUS  = 'REJ'
  WHERE  PAYMENT_NO  = M_PAYMENT_NO
  AND    PAY_STATUS  = 'SIG1';
  
  IF SQL%FOUND THEN
  
   UPDATE DN_ACC_SUS_PAYMENT
   SET PAY_FROM_INT_BAL_AMT = PAY_FROM_INT_BAL_AMT-M_AMT,
          BAL_TO_BE_PAID    = BAL_TO_BE_PAID+M_AMT,
          LAST_MOD_DATE     = SYSDATE
   WHERE
   SUS_REF_NO=M_PAYMENT_NO AND SUSPENSE_ENTRY_TYPE='D';
   
   DN_ACC_G_4(M_PAYMENT_NO); --revece

 END IF;
            
END IF;




END ; 

/
