  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."GET_CLIENT_BROKER" 
(
   M_SELL_PORTFOLIO_CODE       DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE,
   M_BUY_PORTFOLIO_CODE        DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE
)
   RETURN  VARCHAR
IS

   ISCL_BRO  VARCHAR2(10);
   

BEGIN

 /*SELECT count(A.BUY_PORTFOLIO_CODE) INTO ISCL_BRO
 FROM DN_TRN_OUTP_SALE A WHERE
 ((A.SELL_PORTFOLIO_CODE=M_SELL_PORTFOLIO_CODE and BUY_PORTFOLIO_CODE =M_BUY_PORTFOLIO_CODE)
  OR
 (A.SELL_PORTFOLIO_CODE=M_BUY_PORTFOLIO_CODE and BUY_PORTFOLIO_CODE =M_SELL_PORTFOLIO_CODE))
 AND APP_STATUS ='CONF'
 ; */

SELECT PORTFOLIO_CODE INTO ISCL_BRO
FROM (
SELECT PORTFOLIO_CODE
FROM   DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_TRN_OUTP_SALE B
WHERE  A.DEAL_NO            = B.DEAL_NO AND
       A.PORTFOLIO_CODE     = B.SELL_PORTFOLIO_CODE AND
       A.PORTFOLIO_CODE     = M_SELL_PORTFOLIO_CODE AND
       B.BUY_PORTFOLIO_CODE = M_BUY_PORTFOLIO_CODE  AND
       A.SERIAL_NO_STATUS   = 'INV'
UNION ALL
SELECT PORTFOLIO_CODE
FROM   DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_TRN_OUTP_SALE B
WHERE  A.DEAL_NO             = B.DEAL_NO AND
       A.PORTFOLIO_CODE      = B.BUY_PORTFOLIO_CODE AND
       A.PORTFOLIO_CODE      = M_SELL_PORTFOLIO_CODE AND
       B.SELL_PORTFOLIO_CODE = M_BUY_PORTFOLIO_CODE AND
       A.SERIAL_NO_STATUS    = 'INV'
)WHERE ROWNUM=1;


RETURN ISCL_BRO;
END ;

