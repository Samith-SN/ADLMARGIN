set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_INVENTORY_EXCHANGE_R_V1" 
(
M_INV_EXCHG_NO         DN_TRN_BO_INV_EXCHANGE.INV_EXCHG_NO%TYPE,
M_PORTFOLIO_CODE       DN_TRN_BO_INV_EXCHANGE.PORTFOLIO_CODE%TYPE,
M_DEAL_NO              DN_TRN_BO_INV_EXCHANGE.DEAL_NO%TYPE,
M_INST_TYPE            DN_TRN_BO_INV_EXCHANGE.INST_TYPE%TYPE,
M_SECURITY_CODE        DN_TRN_BO_INV_EXCHANGE.SECURITY_CODE%TYPE,
M_SERIAL_NO            DN_TRN_BO_INV_EXCHANGE.SERIAL_NO%TYPE,
M_INV_CODE             DN_TRN_BO_INV_EXCHANGE.INV_CODE%TYPE,
M_FACE_VALUE           DN_TRN_BO_INV_EXCHANGE.FACE_VALUE%TYPE,
M_DN_USER              DN_TRN_BO_INV_EXCHANGE.DN_USER%TYPE,
M_STATUS               VARCHAR2
)

AS
MM_SERIAL_NO       DN_TRN_BO_INV_EXCHANGE.SERIAL_NO%TYPE;

   /*  PROCEDURE  - DN_INVENTORY_EXCHANGE_R  SAVING EXCHANGE
       SYSTEM     - DEALNET
       CREATED BY - SUKATHISVARAN
       CREATED ON - 21/SEPTEMBER/1999 */

BEGIN
    IF(M_SERIAL_NO IS NULL)THEN
               SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS.NEXTVAL),4,'0')
               INTO   MM_SERIAL_NO
               FROM   DUAL;

               MM_SERIAL_NO:='S'||MM_SERIAL_NO;

          UPDATE DN_TRN_BO_INV_EXCHANGE
          SET    FACE_VALUE=FACE_VALUE+M_FACE_VALUE
          WHERE  INV_EXCHG_NO=M_INV_EXCHG_NO AND
                 TRANS_TYPE='R' AND
                 SECURITY_CODE=M_SECURITY_CODE;

       IF SQL%NOTFOUND THEN
         INSERT INTO DN_TRN_BO_INV_EXCHANGE
            (INV_EXCHG_NO,EXCHANGE_DATE,PORTFOLIO_CODE,DEAL_NO,INST_TYPE,
             SECURITY_CODE,SERIAL_NO,INV_CODE,TRANS_TYPE,FACE_VALUE,
             HCUT_PER,FVAL_WITH_HCUT,DN_USER,ALLO_DEAL_NO)

         VALUES(M_INV_EXCHG_NO,SYSDATE,M_PORTFOLIO_CODE,M_DEAL_NO,M_INST_TYPE ,
               M_SECURITY_CODE,MM_SERIAL_NO,M_INV_CODE,'R',M_FACE_VALUE,'10',
              '1100',M_DN_USER,M_DEAL_NO  );
       END IF;

     ELSE
       INSERT INTO DN_TRN_BO_INV_EXCHANGE
            (INV_EXCHG_NO,EXCHANGE_DATE,PORTFOLIO_CODE,DEAL_NO,INST_TYPE,
             SECURITY_CODE,SERIAL_NO,INV_CODE,TRANS_TYPE,FACE_VALUE,
             HCUT_PER,FVAL_WITH_HCUT,DN_USER,ALLO_DEAL_NO)

         VALUES(M_INV_EXCHG_NO,SYSDATE,M_PORTFOLIO_CODE,M_DEAL_NO,M_INST_TYPE ,
               M_SECURITY_CODE,M_SERIAL_NO,M_INV_CODE,'R',M_FACE_VALUE,'10',
              '1100',M_DN_USER,M_DEAL_NO  );




     END IF;



IF (M_STATUS='Y') THEN

    ------------CALLING MAIN PROCEDURE
   DN_INV_EXCH_BACKEND_MAIN_V1(M_INV_EXCHG_NO,M_DEAL_NO,M_PORTFOLIO_CODE,'0');--$$##SC
END IF;


COMMIT;

END DN_INVENTORY_EXCHANGE_R_V1 ;

