                     EFF_VALDATE > = M_PREV_F AND
                     EFF_VALDATE < = M_PREV_L AND
                     APP_STATUS = 'CONF')
LOOP

M_INTEREST := M_INTEREST + I.X1 ;

END LOOP;

--RAISE_APPLICATION_ERROR(-20201,'M_INTEREST'||M_INTEREST);

RETURN M_INTEREST;


END;

