 BEGIN

--RAISE_APPLICATION_ERROR(-20201,'M_FROM_DATE'||M_FROM_DATE);

SELECT  TO_DATE(M_FROM_DATE,'DD-MM-YYYY') INTO M_DATE
FROM DUAL;

SELECT ADD_MONTHS(M_DATE,-1) INTO  T_DATE1
FROM DUAL;

SELECT  TO_CHAR(T_DATE1,'MM-YYYY') INTO T_DATE2
FROM DUAL;

SELECT  '01-'||T_DATE2  INTO T_DATE3
FROM DUAL;

SELECT  TO_DATE(T_DATE3,'DD-MM-YYYY')  INTO M_PREV_F
FROM DUAL;

SELECT LAST_DAY(T_DATE1) INTO M_PREV_L
FROM DUAL;



FOR I IN ( SELECT    INT_AMOUNT X1
              FROM   DN_TRN_REPO_FRESH
              WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                     EFF_VALDATE > = M_PREV_F AND
                     EFF_VALDATE < = M_PREV_L AND
                     APP_STATUS = 'CONF'
              UNION ALL
              SELECT INT_AMOUNT X1
              FROM   DN_TRN_REPO_ROLLOVER
              WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                     EFF_VALDATE > = M_PREV_F AND
                     EFF_VALDATE < = M_PREV_L AND
                     APP_STATUS = 'CONF'
              UNION ALL
              SELECT -1*INT_AMOUNT X1
              FROM   DN_TRN_REPO_FRESH
              WHERE  LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                     EFF_VALDATE > = M_PREV_F AND
                     EFF_VALDATE < = M_PREV_L AND
                     APP_STATUS = 'CONF'
