--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."CORPORATE_ACTION_DELETION" 

   (M_ACTIVITY_TYPE  DN_CORPORATE_ACTIONS.ACTIVITY%TYPE,
    M_SEC_CODE       DN_CORPORATE_ACTIONS.SECURITY_CODE%TYPE,
    M_INST_TYPE      DN_CORPORATE_ACTIONS.INST_TYPE%TYPE,
    M_XCDATE         VARCHAR2,
    M_USER_NAME      DN_CORPORATE_ACTIONS.USER_NAME%TYPE

   )

AS



BEGIN

UPDATE   DN_CORPORATE_ACTIONS
SET STATUS ='CANCEL' ,  USER_NAME= M_USER_NAME
WHERE  ACTIVITY=M_ACTIVITY_TYPE
AND SECURITY_CODE=M_SEC_CODE AND INST_TYPE=M_INST_TYPE AND
--TO_DATE(TO_CHAR(XC_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') >TO_DATE(M_XCDATE,'DD-MM-YYYY')  ; --change by Prabash on 17-11-2011 
TO_DATE(TO_CHAR(XC_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') =TO_DATE(M_XCDATE,'DD-MM-YYYY')  ;


COMMIT;

END CORPORATE_ACTION_DELETION;

/
