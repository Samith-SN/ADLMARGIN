--------------------------------------------------------
--  DDL for Procedure DN_LIMIT_TRA_OVRL_TRA_ISSUE
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_LIMIT_TRA_OVRL_TRA_ISSUE" 
  (
   M_DEAL_NO      DN_TRN_OUTP_SALE.DEAL_NO%TYPE
  )

   IS

 /*
	PURPOSE OF THE PROCEDURE : TRANSACTION PROCEDURE FOR THE OVRALL MATURITY BAND
	CREATED BY :DAYAN
  DATE: 2000/01/04
	*/


 M_CURRENT_UTILIZATION      LMT_UTL_OVRL_MAT.CURRENT_UTILIZATION%TYPE;
 M_CURRENT_UTILIZATION1     LMT_UTL_OVRL_MAT.CURRENT_UTILIZATION%TYPE;
 M_DEAL_INFLOW              LMT_UTL_OVRL_MAT.DEAL_INFLOW%TYPE;
 M_DEAL_OUTFLOW             LMT_UTL_OVRL_MAT.DEAL_OUTFLOW%TYPE;
 M_USER						LMT_UTL_OVRL_MAT.DN_USER%TYPE;
 M_COUNT					INTEGER;
 M_FACE_VAL					NUMBER;
 M_ISSUER_CODE	            VARCHAR2(15);
 M_LIMIT_CODE			    VARCHAR2(30);
 M_AUCTION_TYPE             VARCHAR2(1);
 M_ISSUER_LIA_TYPE          VARCHAR2(25);
 M_INST_TYPE 			    VARCHAR2(25);
 M_WARN_VAL	                NUMBER;
 M_BUY_STATUS				CHAR;
 M_SELL_STATUS				CHAR;
 M_COUNT1					NUMBER;
 M_COUNT2					NUMBER;
 M_COUNT3					NUMBER;
 M_COUNT4					NUMBER;
 M_COUNT5                   NUMBER;
 M_ROW_ID					NUMBER;


BEGIN

/* CHECK NUMBER OF RECORDS IN LMT_UTL_OVRL_MAT*/
	SELECT COUNT(*) INTO M_COUNT FROM LMT_UTL_ISSUER_INST_AMT;
	IF(M_COUNT=0) THEN
	   M_CURRENT_UTILIZATION:=0;
	ELSE
	 SELECT CURRENT_UTILIZATION INTO M_CURRENT_UTILIZATION
	 FROM LMT_UTL_ISSUER_INST_AMT
	 WHERE ROW_ID=(SELECT MAX(ROW_ID) FROM LMT_UTL_ISSUER_INST_AMT);
	END IF;
    M_ROW_ID:=M_ROW_ID +1;

/*##########################THIS IS TO CHECK AVAILABLE RECORD###########################################*/
  SELECT COUNT(*) INTO M_COUNT1
  FROM DN_TRN_OUTP_SALE A,
  DN_REF_SECURITY B
  WHERE A.DEAL_NO=M_DEAL_NO AND
  A.SECURITY_CODE=B.SECURITY_CODE;

/*^^^^^^^^^^^^^^^^^^^^^^^^^^THIS IS TO SELECT RELEVENT MATURITY DAYS AND FACE VALUES^^^^^^^^^^^^^^^^^^^^*/
  IF(M_COUNT1>0) THEN
  SELECT A.FACE_VALUE,B.ISSUER_CODE,A.DN_USER INTO M_FACE_VAL,M_ISSUER_CODE,M_USER
	FROM DN_TRN_OUTP_SALE A,
	     DN_REF_SECURITY B
	WHERE A.DEAL_NO=M_DEAL_NO AND
	     	A.SECURITY_CODE=B.SECURITY_CODE;
  END IF;

/*^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^TO CHECK PORTFOLIO TYPE OF BUY_PORTFOLIO_CODE^^^^^^^^^^^^^^^^^^*/
  SELECT COUNT(*) INTO M_COUNT2
  FROM DN_REF_PORTFOLIO A,
	     DN_TRN_OUTP_SALE B
  WHERE B.DEAL_NO=M_DEAL_NO AND
		    B.BUY_PORTFOLIO_CODE=A.PORTFOLIO_CODE;

 IF(M_COUNT2>0)THEN
 SELECT A.PF_TYPE INTO M_BUY_STATUS
 FROM DN_REF_PORTFOLIO A,
	     DN_TRN_OUTP_SALE B
 WHERE B.DEAL_NO=M_DEAL_NO AND
       B.BUY_PORTFOLIO_CODE=A.PORTFOLIO_CODE;
 END IF;

 IF(M_BUY_STATUS='P')THEN
   M_DEAL_INFLOW:=M_FACE_VAL;
 END IF;

/*^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^TO CHECK PORTFOLIO TYPE OF SELL_PORTFOLIO_CODE^^^^^^^^^^^^^^^^^^*/
SELECT COUNT(*) INTO M_COUNT3
FROM DN_REF_PORTFOLIO A,
     DN_TRN_OUTP_SALE B
WHERE B.DEAL_NO=M_DEAL_NO AND
	  B.SELL_PORTFOLIO_CODE=A.PORTFOLIO_CODE;

IF(M_COUNT3>0) THEN
SELECT A.PF_TYPE INTO M_SELL_STATUS
FROM DN_REF_PORTFOLIO A,
     DN_TRN_OUTP_SALE B
WHERE B.DEAL_NO=M_DEAL_NO AND
	  B.SELL_PORTFOLIO_CODE=A.PORTFOLIO_CODE;
END IF;

IF(M_SELL_STATUS='P')THEN
  M_DEAL_OUTFLOW:=M_FACE_VAL;
END IF;

M_CURRENT_UTILIZATION1:=M_CURRENT_UTILIZATION+M_DEAL_INFLOW-M_DEAL_OUTFLOW;

/* IS TO START COMPARISON PROCESS*/

/*THIS TO SELECT RELEVENT LIMIT CODE FROM THE TABLE*/

  SELECT COUNT(*) INTO M_COUNT4 FROM LMT_STR_ISSUER_INST_AMT
  WHERE SUBSTR(LIMIT_CODE,4,4)=M_ISSUER_CODE
  AND M_CURRENT_UTILIZATION1 BETWEEN  START_AMOUNT AND END_AMOUNT AND CONDITION='B';

  IF(M_COUNT4>0) THEN
  SELECT LIMIT_CODE,AUCTION_TYPE,ISSUER_CODE,ISSUER_LIABILITY_TYPE,INST_TYPE INTO
  M_LIMIT_CODE,M_AUCTION_TYPE,M_ISSUER_CODE,M_ISSUER_LIA_TYPE,M_INST_TYPE FROM LMT_STR_ISSUER_INST_AMT
  WHERE SUBSTR(LIMIT_CODE,4,4)=M_ISSUER_CODE
  AND M_CURRENT_UTILIZATION1 BETWEEN  START_AMOUNT AND END_AMOUNT AND CONDITION='B';
  ELSE
  SELECT COUNT(*) INTO M_COUNT5 FROM LMT_STR_ISSUER_INST_AMT
  WHERE SUBSTR(LIMIT_CODE,4,4)=M_ISSUER_CODE
  AND CONDITION='G';
  IF(M_COUNT5>0) THEN
	SELECT LIMIT_CODE,AUCTION_TYPE,ISSUER_CODE,ISSUER_LIABILITY_TYPE,INST_TYPE INTO
  M_LIMIT_CODE,M_AUCTION_TYPE,M_ISSUER_CODE,M_ISSUER_LIA_TYPE,M_INST_TYPE FROM LMT_STR_ISSUER_INST_AMT
  WHERE SUBSTR(LIMIT_CODE,4,4)=M_ISSUER_CODE
  AND CONDITION='G';
  END IF;

END IF;

/*###############################INSERT FRESH DETAILS INSERT INTO LMT_UTL_OVRL_MAT####################*/
INSERT INTO LMT_UTL_ISSUER_INST_AMT
 (LIMIT_TYPE,AUCTION_TYPE,ISSUER_CODE,ISSUER_LIABILITY_TYPE,INST_TYPE,BF_UTILIZATION,DEAL_INFLOW,DEAL_OUTFLOW,CURRENT_UTILIZATION,DN_USER,ROW_ID)
VALUES
('04',M_AUCTION_TYPE,M_ISSUER_CODE,M_ISSUER_LIA_TYPE,M_INST_TYPE,M_CURRENT_UTILIZATION,M_DEAL_INFLOW,M_DEAL_OUTFLOW,M_CURRENT_UTILIZATION1,M_USER,M_ROW_ID);

/*###################################THIS TO CHECK WHETHER SELECTED LMIT_CODE IS ACTIVATED#############*/
IF(M_COUNT4>0 OR M_COUNT5>0 ) THEN
 SELECT COUNT(*) INTO M_COUNT  FROM LMT_ACT_DETAILS
 WHERE LIMIT_CODE=M_LIMIT_CODE AND ACTIVE_STATUS='Y';

/*!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!THIS TO CHECK POSSIBLE VIOLATIONS!!!!!!!!!!!!!!!!!!!!!!!!!!!!*/

 IF(M_COUNT>0) THEN
 SELECT END_AMOUNT*LIMIT_WARNING_LEVEL INTO M_WARN_VAL
 FROM LMT_STR_ISSUER_INST_AMT
 WHERE LIMIT_CODE=M_LIMIT_CODE AND CONDITION='B';

/*^^^^^^^^^^^^^^^^^^^^^^^^^^^UPDATING LMT_EXC_UNCONF TABLE^^^^^^^^^^^^^^^^^^^^^^^^^^^*/
 IF(M_CURRENT_UTILIZATION1>M_WARN_VAL)THEN
 INSERT INTO LMT_EXC_UNCONF
 (LIMIT_CODE,VIOLATED_DATE,VIOLATED_BY,ACTIVATED_TYPE)
 VALUES
 (M_LIMIT_CODE,SYSDATE,M_USER,'Y');
 END IF;
ELSE
  INSERT INTO LMT_EXC_CURRENT
  (LIMIT_CODE,VIOLATED_DATE,VIOLATED_BY,ACTIVATED_TYPE)
  VALUES
 (M_LIMIT_CODE,SYSDATE,M_USER,'Y');

  END IF;
 END IF;

/*##############################################END OF THE COMMPARISON PROCESS#########################*/
COMMIT ;
END DN_LIMIT_TRA_OVRL_TRA_ISSUE;

