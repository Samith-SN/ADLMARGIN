set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_LIMIT_COMPARE_MODI_OVRL" 
   --(
		--M_DEAL_NO     DN_TRN_OUTP_SALE.DEAL_NO%TYPE
   --)

   IS

    -- Procedue     : Compare actuals with allowed to identify the violations and possible violation
    -- System       : Dealnet system
    -- Created by   : V.Sukathis
    -- Created on   : 27/12/1999

		M_CURRENT_UTILIZATION		LMT_UTL_OVRL_TRA.CURRENT_UTILIZATION%TYPE;
   		M_COUNT						NUMBER;
		M_LIMIT_CODE				LMT_STR_OVRL_AMT.LIMIT_CODE%TYPE;
		M_ACTIVE_STATUS				VARCHAR2(1);
		M_ACTIVE_COUNT				NUMBER;
		M_DN_USER					DN_TRN_OUTP_SALE.DN_USER%TYPE;
		M_POSSIBLE_STATUS			VARCHAR2(1);
		M_END_AMOUNT				LMT_STR_OVRL_AMT.END_AMOUNT%TYPE;
		M_LIMIT_WARNING_LEVEL		NUMBER;
        M_COUNT_UTILIZATION			NUMBER;
        M_LIMIT_CODE_MIN            LMT_STR_OVRL_AMT.LIMIT_CODE%TYPE;
        M_COUNT_LIMIT_CODE_MIN      NUMBER;

	BEGIN

    SELECT COUNT(*) INTO M_COUNT_UTILIZATION
        FROM LMT_UTL_OVRL_TRA;
    IF (M_COUNT_UTILIZATION>0) THEN
      	SELECT CURRENT_UTILIZATION INTO M_CURRENT_UTILIZATION
      		FROM LMT_UTL_OVRL_TRA;
    ELSE
        M_CURRENT_UTILIZATION:=NULL;
    END IF;

IF M_CURRENT_UTILIZATION IS NOT NULL THEN
    SELECT COUNT(*) INTO M_COUNT FROM LMT_STR_OVRL_AMT
		WHERE M_CURRENT_UTILIZATION > START_AMOUNT AND M_CURRENT_UTILIZATION <=END_AMOUNT AND CONDITION='B' ;


	IF (M_COUNT>0) THEN
		SELECT LIMIT_CODE INTO M_LIMIT_CODE FROM LMT_STR_OVRL_AMT
			WHERE M_CURRENT_UTILIZATION > START_AMOUNT AND M_CURRENT_UTILIZATION <=END_AMOUNT AND CONDITION='B' ;
			M_POSSIBLE_STATUS:='T' ;
	ELSE
		SELECT LIMIT_CODE INTO M_LIMIT_CODE FROM LMT_STR_OVRL_AMT
			WHERE  CONDITION='G' ;
			M_POSSIBLE_STATUS:='F' ;
	END IF;
--RAISE_APPLICATION_ERROR(-20201,'*********'||M_LIMIT_CODE);
    SELECT COUNT(*) INTO M_ACTIVE_COUNT FROM LMT_ACT_DETAILS
			WHERE LIMIT_CODE=M_LIMIT_CODE AND ACTIVE_STATUS='Y' ;

					IF ( M_ACTIVE_COUNT > 0 ) THEN
						M_ACTIVE_STATUS:='Y';
					ELSE
						M_ACTIVE_STATUS:='N';
					END IF;

/*SELECT DN_USER INTO M_DN_USER FROM
DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO ;*/
SELECT DN_USER INTO M_DN_USER FROM
LMT_UTL_OVRL_TRA; --WHERE DEAL_NO=M_DEAL_NO
DBMS_OUTPUT.PUT_LINE('EVALD  '||M_DN_USER);
--RAISE_APPLICATION_ERROR(-20201,'*********'||M_DN_USER);
	IF ( M_ACTIVE_STATUS ='N' ) THEN		/*	SUCH LIMIT IS NOT ACTIVATED	*/
	/* THERE IS A VIOLATION.INSERT VIOLATION AND REMOVED IT FROM POSSIBLE VIOLATION	*/

        DELETE FROM LMT_EXC_CURRENT WHERE LIMIT_CODE LIKE '01%';

        --SELECTING  LIMIT_CODE
        SELECT COUNT(*) INTO M_COUNT_LIMIT_CODE_MIN
            FROM LMT_ACT_DETAILS
            WHERE  ACTIVE_STATUS='Y'
            AND LIMIT_TYPE='01';
            IF (M_COUNT_LIMIT_CODE_MIN>0) THEN
                SELECT MAX(LIMIT_CODE) INTO M_LIMIT_CODE_MIN
                    FROM LMT_ACT_DETAILS
                    WHERE  ACTIVE_STATUS='Y'
                    AND LIMIT_TYPE='01';
            ELSE
                --IF NO LIMIT CODE WAS ACTIVATED
                M_LIMIT_CODE_MIN:='01-0001';
            END IF;

            INSERT INTO LMT_EXC_CURRENT
				( LIMIT_CODE, VIOLATED_DATE, VIOLATED_BY, ACTIVATED_TYPE )
				VALUES (M_LIMIT_CODE_MIN , SYSDATE , M_DN_USER ,'Y') ;

			UPDATE  LMT_EXC_UNCONF
                SET ACTIVATED_TYPE = 'N'
					WHERE LIMIT_CODE LIKE '01%' ;


	ELSIF ( M_ACTIVE_STATUS ='Y' ) THEN		/*	SUCH LIMIT IS ACTIVATED	*/
     DELETE FROM LMT_EXC_CURRENT WHERE LIMIT_CODE LIKE '01%';
			IF (M_POSSIBLE_STATUS ='T') THEN
				/*	POSSIBLE VIOLATION OCCURS ONLY ACTIVATED LIMITS		*/
				SELECT END_AMOUNT,LIMIT_WARNING_LEVEL INTO M_END_AMOUNT,M_LIMIT_WARNING_LEVEL
					FROM LMT_STR_OVRL_AMT
					WHERE LIMIT_CODE = M_LIMIT_CODE;
					M_END_AMOUNT := M_END_AMOUNT * M_LIMIT_WARNING_LEVEL/100 ;

						IF ( M_CURRENT_UTILIZATION > M_END_AMOUNT )THEN
                                UPDATE LMT_EXC_UNCONF
                                    SET LIMIT_CODE=M_LIMIT_CODE ,
                                        VIOLATED_DATE=SYSDATE ,
                                        VIOLATED_BY=M_DN_USER ,
                                        ACTIVATED_TYPE='Y'
                                        WHERE  LIMIT_CODE=M_LIMIT_CODE ;
                                        IF SQL%NOTFOUND THEN
										      INSERT INTO LMT_EXC_UNCONF
												( LIMIT_CODE, VIOLATED_DATE, VIOLATED_BY, ACTIVATED_TYPE )
												VALUES (M_LIMIT_CODE , SYSDATE , M_DN_USER ,'Y') ;
                                         END IF;
						END IF ;
			END IF ;
	END IF ;
END IF;--FOR NULL CONDITION
	--COMMIT;

END DN_LIMIT_COMPARE_MODI_OVRL;

