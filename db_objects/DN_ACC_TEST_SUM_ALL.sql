--  DDL for Procedure DN_ACC_TEST_SUM_ALL
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_TEST_SUM_ALL" 
(
M_ENT_DATE        DN_ACC_LICENCEE_INST_ACCOUNT.ENTDATE%TYPE
)
AS

/* PROCEDURE  - DN_ACC_TEST_SUM_ALL TO INSERT ALL RECORDS TO SUMMARY TABLE
   CREATED BY - LATHIKA
   CREATED ON - 27/01/2000  */

CURSOR LICENCEE_SUM IS
 SELECT A.PORTFOLIO_CODE,NVL(A.ACC_TYPE_CODE,'0'),
       NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
       NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT,A.TRNDATE
 FROM
       DN_ACC_LICENCEE_INST_ACCOUNT A
 WHERE
       LTRIM(RTRIM(to_char(A.ENTDATE,'DD-MON-YYYY') ))<LTRIM(RTRIM(to_char(M_ENT_DATE,'DD-MON-YYYY') ))
 GROUP BY
       A.PORTFOLIO_CODE,A.ACC_TYPE_CODE,A.TRNDATE
 UNION ALL
 SELECT A.PORTFOLIO_CODE,NVL(A.ACC_TYPE_CODE,'0'),
       NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
       NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT,A.TRNDATE
 FROM
       DN_ACC_LICENCEE_GEN_ACCOUNT A
 WHERE
       LTRIM(RTRIM(to_char(A.ENTDATE,'DD-MON-YYYY') ))<LTRIM(RTRIM(to_char(M_ENT_DATE,'DD-MON-YYYY') ))
 GROUP BY
       A.PORTFOLIO_CODE,A.ACC_TYPE_CODE,A.TRNDATE
 ORDER BY 1,2;

M_PORTFOLIO_CODE       DN_ACC_LICEN_INST_GEN_SUM.PORTFOLIO_CODE%TYPE;
M_TRNDATE              DN_ACC_LICEN_INST_GEN_SUM.TRNDATE%TYPE;
M_ACC_TYPE_CODE        DN_ACC_LICEN_INST_GEN_SUM.ACC_TYPE_CODE%TYPE;
M_DRCR_STATUS          DN_ACC_LICEN_INST_GEN_SUM.DRCR_STATUS%TYPE;
M_TRNAMOUNT            DN_ACC_LICEN_INST_GEN_SUM.TRNAMOUNT%TYPE;
M_DRTOT                DN_ACC_LICEN_INST_GEN_SUM.TRNAMOUNT%TYPE;
M_CRTOT                DN_ACC_LICEN_INST_GEN_SUM.TRNAMOUNT%TYPE;
M_COUNT                DN_ACC_LICEN_INST_GEN_SUM.TRNAMOUNT%TYPE;

BEGIN

--RAISE_APPLICATION_ERROR(-20201,'DATE'||''||M_ENT_DATE);
OPEN LICENCEE_SUM;
LOOP

FETCH LICENCEE_SUM INTO
   M_PORTFOLIO_CODE,M_ACC_TYPE_CODE,M_DRTOT,M_CRTOT,M_TRNDATE;

EXIT WHEN LICENCEE_SUM%NOTFOUND;
-------------------(1)-------------------------
IF M_PORTFOLIO_CODE IS NOT NULL AND M_ACC_TYPE_CODE <> 0 THEN
 M_TRNAMOUNT:=0;

  IF  M_DRTOT<> 0 THEN
    M_DRCR_STATUS:= 'DR';
  ELSE
    M_DRCR_STATUS:= 'CR';
  END IF;

  SELECT  COUNT(*)
  INTO    M_COUNT
  FROM    DN_ACC_LICEN_INST_GEN_SUM
  WHERE   PORTFOLIO_CODE =M_PORTFOLIO_CODE  AND
          TRNDATE        =M_TRNDATE AND
          ACC_TYPE_CODE  =M_ACC_TYPE_CODE AND
          DRCR_STATUS    =M_DRCR_STATUS;

 IF  M_COUNT > 0    THEN
    SELECT  NVL(TRNAMOUNT,0)
    INTO    M_TRNAMOUNT
    FROM    DN_ACC_LICEN_INST_GEN_SUM
    WHERE   PORTFOLIO_CODE =M_PORTFOLIO_CODE  AND
            TRNDATE        =M_TRNDATE AND
            ACC_TYPE_CODE  =M_ACC_TYPE_CODE AND
            DRCR_STATUS    =M_DRCR_STATUS;
  ELSE
      M_TRNAMOUNT:=0;
  END IF;

  IF M_DRCR_STATUS= 'DR' THEN
     M_TRNAMOUNT := M_DRTOT + M_TRNAMOUNT;
  ELSE
     M_TRNAMOUNT := M_CRTOT + M_TRNAMOUNT;
  END IF;

 -- RAISE_APPLICATION_ERROR(-20201,M_PORTFOLIO_CODE||''||M_ACC_TYPE_CODE||''||M_DRTOT||''||M_CRTOT||''||M_TRNDATE||''||M_DRCR_STATUS||''||M_TRNAMOUNT);

  IF M_TRNAMOUNT > 0 THEN
    UPDATE DN_ACC_LICEN_INST_GEN_SUM
       SET TRNAMOUNT      =M_TRNAMOUNT
     WHERE PORTFOLIO_CODE =M_PORTFOLIO_CODE  AND
           TRNDATE        =M_TRNDATE AND
           ACC_TYPE_CODE  =M_ACC_TYPE_CODE AND
           DRCR_STATUS    =M_DRCR_STATUS;
   IF SQL%NOTFOUND THEN
     INSERT INTO DN_ACC_LICEN_INST_GEN_SUM
           (PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT)
     VALUES
           (M_PORTFOLIO_CODE,M_TRNDATE,M_ACC_TYPE_CODE,M_DRCR_STATUS,M_TRNAMOUNT);
   END IF;
  END IF;

 END IF;

END LOOP;

--DN_ACC_TEST_DETAILS(M_ENT_DATE);

COMMIT;
END DN_ACC_TEST_SUM_ALL;

