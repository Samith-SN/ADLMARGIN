--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_GLOBAL_CONCENT_PERCENT" 
(
 M_SECURITY_CODE        DN_REF_SECURITY.SECURITY_CODE%TYPE
 )
 RETURN NUMBER
 AS
 M_CONCENTRATION_PERCENT      NUMBER;
 /*
 || CREATED BY : WARUNA SRI JAYANATH
 || CREATEND OM : LBMARGIN 2012-03-02
 ||
 */
 BEGIN

   SELECT  A.CONCENTRATION_PERCENT  INTO   M_CONCENTRATION_PERCENT
   FROM DN_REF_SECURITY A 
   WHERE A.SECURITY_CODE=M_SECURITY_CODE;
   
   RETURN  M_CONCENTRATION_PERCENT;
--A.SECURITY_CODE, A.EXT_SECURITY_CODE,
 END ; 

