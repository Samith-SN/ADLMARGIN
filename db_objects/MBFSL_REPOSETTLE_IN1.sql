set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_REPOSETTLE_IN1" (
    M_DEAL_NO  IN OUT    DN_TRN_REPO_SETTLEMENT.DEAL_NO%TYPE,
    M_PRIOR_DEAL_NO      DN_TRN_REPO_SETTLEMENT.PRIOR_DEAL_NO%TYPE,
    M_BCODE              DN_TRN_REPO_SETTLEMENT_SETTLE.BORR_PORTFOLIO_CODE%TYPE,
    M_LCODE              DN_TRN_REPO_SETTLEMENT_SETTLE.LEND_PORTFOLIO_CODE%TYPE,
    M_CURR               DN_TRN_REPO_SETTLEMENT.CURR_CODE%TYPE,
    M_SET_DATE           CHAR,
    M_TENOR              DN_TRN_REPO_SETTLEMENT.PAYMENT_TO_LEND%TYPE,
    M_SEL_MODES          DN_TRN_REPO_SETTLEMENT.NO_OF_SETTL_MODES%TYPE,
    M_SETTLE             DN_TRN_REPO_SETTLEMENT_SETTLE.SETTLE_MODE%TYPE,
    M_SETAMT             DN_TRN_REPO_SETTLEMENT_SETTLE.SETTLE_AMOUNT%TYPE,
    M_BACC               DN_TRN_REPO_SETTLEMENT_SETTLE.BORR_ACC_NO%TYPE,
    M_SACC               DN_TRN_REPO_SETTLEMENT_SETTLE.LEND_ACC_NO%TYPE,
    M_COMM1              DN_TRN_REPO_SETTLEMENT_SETTLE.BORR_SETTLE_COMMENT%TYPE,
    M_COMM2              DN_TRN_REPO_SETTLEMENT_SETTLE.LEND_SETTLE_COMMENT%TYPE,
    M_USERNAME           DN_TRN_REPO_SETTLEMENT.DN_USER%TYPE,
    M_SELECT_TYPE        CHAR,
    M_DEAL_NUMBER        DN_TRN_REPO_SETTLEMENT.DEAL_NO%TYPE,
    M_GDEAL_NUMBER       DN_TRN_REPO_ROLLOVER.DEAL_NO%TYPE--GROUP DEALS
)

AS

   M_USER          DN_TRN_REPO_SETTLEMENT.DN_USER%TYPE;
   M_S_DATE        DN_TRN_REPO_SETTLEMENT.SETTLE_DATE%TYPE;
   M_BCOUNT        NUMBER;
   M_LCOUNT        NUMBER;
   M_BORR_BRANCH_CODE      DN_REF_PORTF_SETTLEMENT.BRANCH_CODE%TYPE;
   M_LEND_BRANCH_CODE      DN_REF_PORTF_SETTLEMENT.BRANCH_CODE%TYPE;
   MM_CURRENCY_VALUE       DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE;--CURRENCY

BEGIN
SELECT  CURRENCY_VALUE
INTO    MM_CURRENCY_VALUE
FROM    DN_REF_EXCHANGE_RATES
WHERE   CURR_CODE=M_CURR;

    --RAISE_APPLICATION_ERROR(-20201,M_ADJTYPE);

    -- PROCEDURE  -  TO INSERT REPOS SETTLEMENT DETAILS
    -- SYSTEM     -  MBFSL SYSTEM
    -- CREATED BY -  V.THILAKESAN.
    -- CREATED ON -  02/07/1999

    IF SUBSTR(M_USERNAME,1,1)=' ' OR M_USERNAME IS NULL THEN
       M_USER:='Un Identify';
    ELSE
       M_USER:=M_USERNAME;
    END IF;
    --Format settlement date type
    SELECT
      TO_DATE(M_SET_DATE,'DD/MM/YYYY')
    INTO
      M_S_DATE
    FROM DUAL;
    --Creating new sequence
    IF M_DEAL_NUMBER IS NULL THEN
       SELECT TO_CHAR(SYSDATE,'YY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_REPO_SETTLEMENT.NEXTVAL),3,'0') INTO M_DEAL_NO FROM DUAL;
       M_DEAL_NO:=  'RSMT'||M_DEAL_NO;
    ELSE
       M_DEAL_NO:=M_DEAL_NUMBER;
    END IF;

    IF M_SEL_MODES>0 THEN
       UPDATE DN_TRN_REPO_SETTLEMENT
       SET NO_OF_SETTL_MODES=M_SEL_MODES
       WHERE DEAL_NO=M_DEAL_NO;
    END IF;

    IF M_DEAL_NO IS NOT NULL AND M_SELECT_TYPE='MAIN1' THEN
IF M_CURR<>'SLR' THEN --CURRENCY
------------------------------------------------CURRENCY

 INSERT INTO DN_TRN_DEAL_CURRENCY
  (DEAL_NO,PAYTO_LENDER,CURR_CODE,LEG1_VALUE)
 VALUES
  (M_DEAL_NO,M_TENOR,M_CURR,M_TENOR);

/*UPDATE DN_TRN_DEAL_CURRENCY
SET    LEG1_VALUE=M_LEG1,
       LEG2_VALUE=M_LEG2,
       CURR_CODE=M_CURRENCY
WHERE  DEAL_NO=M_DEAL_NO;
*/
------------------------------------------------CURRENCY
UPDATE DN_TRN_REPO_SETTLEMENT
       SET PRIOR_DEAL_NO      =M_PRIOR_DEAL_NO,
           CURR_CODE          =M_CURR,
           SETTLE_DATE        =M_S_DATE,
           PAYMENT_TO_LEND    =M_TENOR*MM_CURRENCY_VALUE,--CURRENCY
           DN_USER            =M_USER
       WHERE
           DEAL_NO=M_DEAL_NO
           AND
           APP_STATUS='ENT';

       IF SQL%NOTFOUND THEN
        IF (SUBSTR(M_GDEAL_NUMBER,1,2)='GR')THEN --GROUP DEAL
              INSERT INTO DN_TRN_REPO_SETTLEMENT
          (DEAL_NO,PRIOR_DEAL_NO,CURR_CODE,SETTLE_DATE,PAYMENT_TO_LEND,DN_USER)--,GROUP_DEALNO
           VALUES(M_DEAL_NO,M_PRIOR_DEAL_NO,M_CURR, M_S_DATE, M_TENOR*MM_CURRENCY_VALUE,--CURRENCY
             M_USER  );--,M_GDEAL_NUMBER




         ELSE
            INSERT INTO DN_TRN_REPO_SETTLEMENT
          (DEAL_NO,PRIOR_DEAL_NO,CURR_CODE,SETTLE_DATE,PAYMENT_TO_LEND,DN_USER)
           VALUES(M_DEAL_NO,M_PRIOR_DEAL_NO,M_CURR, M_S_DATE, M_TENOR*MM_CURRENCY_VALUE,--CURRENCY
             M_USER   );

         END IF;





--ADDED FOR TIME LOG MANAGEMENT BY S.YASODHA

              INSERT INTO DN_TIME_LOG
          (SUS_REF_NO,
           DN_USER,
           ENT_DATE,
           DESCRIPTION)
           VALUES
            (
              M_DEAL_NO,
              M_USER,
              SYSDATE,
              'ENTERED');
--*******************************
       END IF;




ELSE --CURRENCY
       UPDATE DN_TRN_REPO_SETTLEMENT
       SET PRIOR_DEAL_NO      =M_PRIOR_DEAL_NO,
           CURR_CODE          =M_CURR,
           SETTLE_DATE        =M_S_DATE,
           PAYMENT_TO_LEND    =M_TENOR,
           DN_USER            =M_USER
       WHERE
           DEAL_NO=M_DEAL_NO
           AND
           APP_STATUS='ENT';

       IF SQL%NOTFOUND THEN
         IF (SUBSTR(M_GDEAL_NUMBER,1,2)='GR')THEN --GROUP DEAL
           INSERT INTO DN_TRN_REPO_SETTLEMENT
          (DEAL_NO,PRIOR_DEAL_NO,CURR_CODE,SETTLE_DATE,PAYMENT_TO_LEND,DN_USER)--,GROUP_DEALNO
           VALUES(M_DEAL_NO,M_PRIOR_DEAL_NO,M_CURR,M_S_DATE,M_TENOR,M_USER);--,M_GDEAL_NUMBER



         ELSE
           INSERT INTO DN_TRN_REPO_SETTLEMENT
          (DEAL_NO,PRIOR_DEAL_NO,CURR_CODE,SETTLE_DATE,PAYMENT_TO_LEND,DN_USER)
           VALUES(M_DEAL_NO,M_PRIOR_DEAL_NO,M_CURR,M_S_DATE,M_TENOR,M_USER );
         END IF;

--ADDED FOR TIME LOG MANAGEMENT BY S.YASODHA

              INSERT INTO DN_TIME_LOG
          (SUS_REF_NO,
           DN_USER,
           ENT_DATE,
           DESCRIPTION)
           VALUES
            (
              M_DEAL_NO,
              M_USER,
              SYSDATE,
              'ENTERED');
--*******************************
       END IF;
END IF;--CURRENCY
   END IF;
   --Select BORR_PORTFOLIO_CODE details from DN_REF_PORTF_SETTLEMENT
   M_BCOUNT:=0;
   SELECT COUNT(*) INTO M_BCOUNT
   FROM  DN_REF_PORTF_SETTLEMENT A
   WHERE A.PORTFOLIO_CODE=M_BCODE AND A.ACC_NO=M_BACC;
   IF M_BCOUNT>0 THEN
      SELECT A.BRANCH_CODE INTO M_BORR_BRANCH_CODE
      FROM  DN_REF_PORTF_SETTLEMENT A
      WHERE A.PORTFOLIO_CODE=M_BCODE AND A.ACC_NO=M_BACC;
   END IF;

   --Select SEL_PORTFOLIO_CODE details from DN_REF_PORTF_SETTLEMENT
   M_LCOUNT:=0;
   SELECT COUNT(*) INTO M_LCOUNT
   FROM  DN_REF_PORTF_SETTLEMENT A
   WHERE A.PORTFOLIO_CODE=M_LCODE AND A.ACC_NO=M_SACC;
   IF M_LCOUNT>0 THEN
      SELECT A.BRANCH_CODE INTO M_LEND_BRANCH_CODE
      FROM  DN_REF_PORTF_SETTLEMENT A
      WHERE A.PORTFOLIO_CODE=M_LCODE AND A.ACC_NO=M_SACC;
   END IF;



   IF M_DEAL_NO IS NOT NULL AND M_SETTLE<>'NULL' AND M_SELECT_TYPE='MAIN2' THEN
      IF M_SETTLE IS NOT NULL THEN
         IF M_CURR<>'SLR' THEN --CURRENCY
        UPDATE DN_TRN_REPO_SETTLEMENT_SETTLE
         SET SETTLE_AMOUNT       =M_SETAMT*MM_CURRENCY_VALUE,--CURRENCY
             BORR_PORTFOLIO_CODE =M_BCODE,
             BORR_BRANCH_CODE    =M_BORR_BRANCH_CODE,
             BORR_ACC_NO         =M_BACC,
             BORR_SETTLE_COMMENT =M_COMM1,
             LEND_PORTFOLIO_CODE =M_LCODE,
             LEND_BRANCH_CODE    =M_LEND_BRANCH_CODE,
             LEND_ACC_NO         =M_SACC,
             LEND_SETTLE_COMMENT =M_COMM2,
             CURRENCY_SETTLE_AMOUNT=M_SETAMT--CURRENCY
         WHERE
             DEAL_NO    =M_DEAL_NO
             AND
             SETTLE_MODE=M_SETTLE;

             IF SQL%NOTFOUND THEN
                INSERT INTO DN_TRN_REPO_SETTLEMENT_SETTLE
                (DEAL_NO,
                 SETTLE_MODE,
                 SETTLE_AMOUNT,
                 BORR_PORTFOLIO_CODE,
                 BORR_BRANCH_CODE,
                 BORR_ACC_NO,
                 BORR_SETTLE_COMMENT,
                 LEND_PORTFOLIO_CODE,
                 LEND_BRANCH_CODE,
                 LEND_ACC_NO,
                 LEND_SETTLE_COMMENT,
                 CURRENCY_SETTLE_AMOUNT--CURRENCY
                )
                VALUES(M_DEAL_NO,
                       M_SETTLE,
                       M_SETAMT*MM_CURRENCY_VALUE,--CURRENCY
                       M_BCODE,
                       M_BORR_BRANCH_CODE,
                       M_BACC,
                       M_COMM1,
                       M_LCODE,
                       M_LEND_BRANCH_CODE,
                       M_SACC,
                       M_COMM2,
                       M_SETAMT--CURRENCY
                );
             END IF;

          ELSE --CURRENCY
         UPDATE DN_TRN_REPO_SETTLEMENT_SETTLE
         SET SETTLE_AMOUNT       =M_SETAMT,
             BORR_PORTFOLIO_CODE =M_BCODE,
             BORR_BRANCH_CODE    =M_BORR_BRANCH_CODE,
             BORR_ACC_NO         =M_BACC,
             BORR_SETTLE_COMMENT =M_COMM1,
             LEND_PORTFOLIO_CODE =M_LCODE,
             LEND_BRANCH_CODE    =M_LEND_BRANCH_CODE,
             LEND_ACC_NO         =M_SACC,
             LEND_SETTLE_COMMENT =M_COMM2
         WHERE
             DEAL_NO    =M_DEAL_NO
             AND
             SETTLE_MODE=M_SETTLE;

             IF SQL%NOTFOUND THEN
                INSERT INTO DN_TRN_REPO_SETTLEMENT_SETTLE
                (DEAL_NO,
                 SETTLE_MODE,
                 SETTLE_AMOUNT,
                 BORR_PORTFOLIO_CODE,
                 BORR_BRANCH_CODE,
                 BORR_ACC_NO,
                 BORR_SETTLE_COMMENT,
                 LEND_PORTFOLIO_CODE,
                 LEND_BRANCH_CODE,
                 LEND_ACC_NO,
                 LEND_SETTLE_COMMENT
                )
                VALUES(M_DEAL_NO,
                       M_SETTLE,
                       M_SETAMT,
                       M_BCODE,
                       M_BORR_BRANCH_CODE,
                       M_BACC,
                       M_COMM1,
                       M_LCODE,
                       M_LEND_BRANCH_CODE,
                       M_SACC,
                       M_COMM2
                );
             END IF;

      END IF;--CURRENCY
      END IF;

ELSIF M_GDEAL_NUMBER IS NOT NULL AND M_SETTLE<>'NULL' AND M_SELECT_TYPE='MAIN1' THEN
      IF M_SETTLE IS NOT NULL THEN
         IF M_CURR<>'SLR' THEN --CURRENCY
           INSERT INTO DN_TRN_REPO_SETTLEMENT_SETTLE
             (DEAL_NO,SETTLE_MODE,SETTLE_AMOUNT,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE,
             CURRENCY_SETTLE_AMOUNT)
           VALUES(M_DEAL_NO, M_SETTLE,M_SETAMT*MM_CURRENCY_VALUE,--CURRENCY
                  M_BCODE,M_LCODE, M_SETAMT--CURRENCY
                  );

         ELSE--CURRENCY
           INSERT INTO DN_TRN_REPO_SETTLEMENT_SETTLE
             (DEAL_NO,SETTLE_MODE,SETTLE_AMOUNT,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE)
           VALUES(M_DEAL_NO, M_SETTLE,M_SETAMT,M_BCODE,M_LCODE);

        END IF; --CURRENCY
      END IF;--M_SETTLE


END IF;

    --If the data type is incorrect then delete the records from the relavent tables

 /*EXCEPTION
  WHEN OTHERS THEN

    DELETE DN_TRN_REPO_SETTLEMENT
    WHERE
    DEAL_NO=M_DEAL_NO;

    DELETE DN_TRN_REPO_SETTLEMENT_SETTLE
    WHERE
    DEAL_NO=M_DEAL_NO;

    COMMIT;

    RAISE_APPLICATION_ERROR(-20201,'Data error');*/

END MBFSL_REPOSETTLE_IN1; 

