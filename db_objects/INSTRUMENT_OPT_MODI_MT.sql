set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."INSTRUMENT_OPT_MODI_MT" 

   (M_INS_CODE              DN_REF_INSTRUMENT.INST_TYPE%TYPE,
    M_INS_DESC              DN_REF_INSTRUMENT.INST_DESC%TYPE,
    M_REPO                  DN_REF_INSTRUMENT.REPO_TRN_STATUS%TYPE,
    M_REPO_TRANS            DN_REF_INSTRUMENT.RPTRN_HCUT_PER%TYPE,
    M_MT_PERCENT            DN_REF_INSTRUMENT.MT_PERCENT%TYPE,
    M_BASE_INTEREST_RATE    DN_REF_INSTRUMENT.BASE_INTEREST_RATE%TYPE,
    M_USRE                  VARCHAR

   )

AS

BEGIN

DN_VALIDATE_SAVE_RIGHTS(M_USRE,'WD_Instrument_Types_MT');  --added by ashini on 31/10/2005 for sr0509-047


    /* PROCEDURE  - TO MODIFY INSTRUMENT OPTIONS
       SYSTEM     -  DEALNET
       CREATED BY -
       CREATED ON -  */

UPDATE DN_REF_INSTRUMENT
SET    INST_DESC=M_INS_DESC,
       REPO_TRN_STATUS=M_REPO,
       RPTRN_HCUT_PER=NVL(M_REPO_TRANS,'0')/100,
       MT_PERCENT=M_MT_PERCENT/100,
       BASE_INTEREST_RATE=M_BASE_INTEREST_RATE
WHERE  UPPER(INST_TYPE)=UPPER(M_INS_CODE);

COMMIT;

END INSTRUMENT_OPT_MODI_MT;

