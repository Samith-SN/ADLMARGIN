--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_TXN_TYPE" 
(
  M_BUY_PORTFOLIO_CODE		DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE,
  M_SELL_PORTFOLIO_CODE		DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE
)
RETURN VARCHAR2

AS
M_TXN_TYPE VARCHAR2(1);
M_BUY_PF_TYPE VARCHAR2(1);
M_SELL_PF_TYPE VARCHAR2(1);

BEGIN
     SELECT DISTINCT(PF_TYPE)
     INTO   M_BUY_PF_TYPE
     FROM   DN_REF_PORTFOLIO
     WHERE  PORTFOLIO_CODE = M_BUY_PORTFOLIO_CODE;

     SELECT DISTINCT(PF_TYPE)
     INTO   M_SELL_PF_TYPE
     FROM   DN_REF_PORTFOLIO
     WHERE  PORTFOLIO_CODE = M_SELL_PORTFOLIO_CODE;



     IF M_BUY_PF_TYPE='P' AND M_SELL_PF_TYPE='P' THEN
     M_TXN_TYPE:='P';
     ELSIF M_BUY_PF_TYPE='P' AND M_SELL_PF_TYPE='C' THEN
      M_TXN_TYPE:='P';
     ELSIF M_BUY_PF_TYPE='C' AND M_SELL_PF_TYPE='P' THEN
      M_TXN_TYPE:='S';
     END IF;
RETURN M_TXN_TYPE;

END RETURN_TXN_TYPE;

/
