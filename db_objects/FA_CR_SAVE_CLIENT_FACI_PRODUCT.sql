--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."FA_CR_SAVE_CLIENT_FACI_PRODUCT" 
(
M_FACILITY_NO                   dn_client_fact_prod.FACILITY_NO%TYPE,
M_CLIENT_CODE                   dn_client_fact_prod.CLIENT_CODE%TYPE,
M_PRODUCT_FEATURE_CODE          dn_client_fact_prod.PRODUCT_FEATURE_CODE%TYPE,
M_COMMENTS                      dn_client_fact_prod.COMMENTS%TYPE,
M_SCREEN                        VARCHAR2,
M_USER                          dn_client_fact_prod.ENT_USER%TYPE,
M_NUM                           INT,
M_ACTIVATION_POINT_CODE         dn_client_fact_prod.ACTIVATION_POINT_CODE%TYPE,
M_ACTION                        dn_client_fact_prod.ACTION%TYPE,
M_MAIL_CODE                     dn_client_fact_prod.MAIL_CODE%TYPE,
M_FREQUENCY                     dn_client_fact_prod.FREQUENCY%TYPE,
M_MODE_OF_SEND_MAIL             dn_client_fact_prod.MODE_OF_SEND_MAIL%TYPE,
M_MODE_OF_SEND_FAX              dn_client_fact_prod.MODE_OF_SEND_FAX%TYPE,
M_MODE_OF_SEND_LET              dn_client_fact_prod.MODE_OF_SEND_LET%TYPE
)

AS
-- CODE BY INDITHA FOR OFSCL FACTORING 22-09-2006

BEGIN

IF UPPER(M_SCREEN)='NEW' THEN

INSERT INTO dn_client_fact_prod
(FACILITY_NO,CLIENT_CODE,PRODUCT_FEATURE_CODE,COMMENTS,ENT_USER,ENT_DATE,
ACTIVATION_POINT_CODE,ACTION,MAIL_CODE,FREQUENCY,MODE_OF_SEND_MAIL,MODE_OF_SEND_FAX,MODE_OF_SEND_LET)
VALUES
(M_FACILITY_NO,M_CLIENT_CODE,M_PRODUCT_FEATURE_CODE,M_COMMENTS,M_USER,SYSDATE,
M_ACTIVATION_POINT_CODE,M_ACTION,M_MAIL_CODE,M_FREQUENCY,M_MODE_OF_SEND_MAIL,M_MODE_OF_SEND_FAX,M_MODE_OF_SEND_LET);

ELSE

IF M_NUM=0 THEN

INSERT INTO dn_client_fact_prod_BK
(FACILITY_NO,CLIENT_CODE,PRODUCT_FEATURE_CODE,COMMENTS,ENT_USER,ENT_DATE,MOD_USER,MOD_DATE,
ACTIVATION_POINT_CODE,ACTION,MAIL_CODE,FREQUENCY,MODE_OF_SEND_MAIL,MODE_OF_SEND_FAX,MODE_OF_SEND_LET)
SELECT
FACILITY_NO,CLIENT_CODE,PRODUCT_FEATURE_CODE,COMMENTS,ENT_USER,ENT_DATE,MOD_USER,MOD_DATE,
ACTIVATION_POINT_CODE,ACTION,MAIL_CODE,FREQUENCY,MODE_OF_SEND_MAIL,MODE_OF_SEND_FAX,MODE_OF_SEND_LET
FROM dn_client_fact_prod
WHERE FACILITY_NO=M_FACILITY_NO;

DELETE FROM dn_client_fact_prod
WHERE FACILITY_NO=M_FACILITY_NO;

END IF;

INSERT INTO dn_client_fact_prod
(FACILITY_NO,CLIENT_CODE,PRODUCT_FEATURE_CODE,COMMENTS,ENT_USER,ENT_DATE,
ACTIVATION_POINT_CODE,ACTION,MAIL_CODE,FREQUENCY,MODE_OF_SEND_MAIL,MODE_OF_SEND_FAX,MODE_OF_SEND_LET)
VALUES
(M_FACILITY_NO,M_CLIENT_CODE,M_PRODUCT_FEATURE_CODE,M_COMMENTS,M_USER,SYSDATE,
M_ACTIVATION_POINT_CODE,M_ACTION,M_MAIL_CODE,M_FREQUENCY,M_MODE_OF_SEND_MAIL,M_MODE_OF_SEND_FAX,M_MODE_OF_SEND_LET);
END IF;

END;

