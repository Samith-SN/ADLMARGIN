set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_CHANGE_USER_PASSWORD_V1" 
  ( M_USERID            VARCHAR2,
    M_PASSWORD          VARCHAR2
  )


   -- PROCEDURE    : CHANGE USER PASSWORD
   -- SYSTEM       : DEALNET SYSTEM
   -- CREATED BY   : DAYAN NISHANTHA
   -- CREATED ON   : 05/09/1999

  AS

  MAIN_CUR          INTEGER;
  IGNORE            INTEGER;
  M_ACTIVE_STATUS   DN_REF_USER.ACTIVE_STATUS%TYPE;
  M_SAVE_STATUS     DN_REF_USER_VIEW_ACCESS.SAVE_STATUS%TYPE;
  M_COUNT           NUMBER;

BEGIN
---ADDED ON 13-09-2005 FOR PASSWORD--------------------------
--RAISE_APPLICATION_ERROR(-20201,M_PASSWORD);
 SELECT ACTIVE_STATUS INTO M_ACTIVE_STATUS
 FROM   DN_REF_USER
 WHERE  DN_USER = M_USERID;

 SELECT COUNT(*) INTO M_COUNT
 FROM   DN_REF_USER_VIEW_ACCESS
 WHERE  SCREEN_NAME = 'WD_UNLOCK_USER' AND
        DN_USER     = M_USERID;

 IF  M_COUNT > 0 THEN
 SELECT SAVE_STATUS INTO M_SAVE_STATUS
 FROM   DN_REF_USER_VIEW_ACCESS
 WHERE  SCREEN_NAME = 'WD_UNLOCK_USER' AND
        DN_USER     = M_USERID;
 ELSE
 M_SAVE_STATUS:='N';
 END IF;


 IF  M_ACTIVE_STATUS = 'Y'  THEN
---------END OF ADDED ON 13-09-2005 FOR PASSWORD-------------------------------

  MAIN_CUR:=SYS.DBMS_SQL.OPEN_CURSOR;

  SYS.DBMS_SQL.PARSE(MAIN_CUR,
     'ALTER USER '||M_USERID||' IDENTIFIED BY "'||M_PASSWORD||'"',DBMS_SQL.V7);

 IGNORE:=SYS.DBMS_SQL.EXECUTE(MAIN_CUR);

  --ADDED BY ASHINI HEWAGE TO  CHECHK PWASSWORD EXPIRE OR NOT  ON 27-05-2005
  UPDATE DN_REF_PASSWORD_UPDATE
  SET    ENT_DATE = SYSDATE
  WHERE  DN_USER  = M_USERID ;

   IF SQL%NOTFOUND THEN

   INSERT INTO  DN_REF_PASSWORD_UPDATE ( DN_USER , ENT_DATE)
   VALUES(M_USERID,SYSDATE);

   END IF;

 UPDATE DN_REF_USER
 SET    ACTIVE_STATUS = 'Y'
 WHERE  DN_USER =  M_USERID;

 ------------------------END-----------------------------------------------


 --UPDATE MLLADMIN.MLL_USER
 --SET ML_PASSWORD=M_PASSWORD
 --WHERE ML_USER=M_USERID;
---ADDED ON 13-09-2005 FOR PASSWORD-------------------------------------------------------
 ELSIF M_SAVE_STATUS='Y' AND M_ACTIVE_STATUS = 'L'  THEN

  MAIN_CUR:=SYS.DBMS_SQL.OPEN_CURSOR;

  SYS.DBMS_SQL.PARSE(MAIN_CUR,
     'ALTER USER '||M_USERID||' IDENTIFIED BY '||M_PASSWORD,DBMS_SQL.V7);

 IGNORE:=SYS.DBMS_SQL.EXECUTE(MAIN_CUR);

 --ADDED BY ASHINI HEWAGE TO  CHECHK PWASSWORD EXPIRE OR NOT  ON 27-05-2005
  UPDATE DN_REF_PASSWORD_UPDATE
  SET    ENT_DATE = SYSDATE
  WHERE  DN_USER  = M_USERID ;

   IF SQL%NOTFOUND THEN

   INSERT INTO  DN_REF_PASSWORD_UPDATE ( DN_USER , ENT_DATE)
   VALUES(M_USERID,SYSDATE);

   END IF;

 UPDATE DN_REF_USER
 SET    ACTIVE_STATUS = 'Y'
 WHERE  DN_USER =  M_USERID;

 ELSE -- ACTIVE STATUS <> 'Y'

   RAISE_APPLICATION_ERROR(-20001,'User status is locked or inactive. Please contact the administrator.');

 END IF; --END OF ACTIVE STATUS <> 'Y'
------END OF ADDED ON 13-09-2005 FOR PASSWORD-----------------------------------------------------------------

 COMMIT;

END MBFSL_CHANGE_USER_PASSWORD_V1;

