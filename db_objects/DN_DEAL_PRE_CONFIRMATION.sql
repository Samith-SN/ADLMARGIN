set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_DEAL_PRE_CONFIRMATION" 

   (M_BUYER_NAME      DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE,
    M_SELLER_NAME     DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE,
   -- M_SEC_CODE        DN_TRN_OUTP_SALE.SECURITY_CODE%TYPE,
    M_VALDATE         VARCHAR2,
    M_USER            DN_TRN_REPO_FRESH.DN_USER%TYPE
   )

AS
M_DEALNO           DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
M_COUNT            NUMBER;
J                  INTEGER;

CURSOR C1 IS
    SELECT DEAL_NO ,SECURITY_CODE
    FROM DN_TRN_OUTP_SALE
    WHERE APP_STATUS='APPRO2'
    AND BUY_PORTFOLIO_CODE = M_BUYER_NAME
    AND SELL_PORTFOLIO_CODE = M_SELLER_NAME

     --AND SECURITY_CODE = M_SEC_CODE --commented by manjula on 02-02-2005 for SRF 0501-009
    AND TO_CHAR(EFF_VALDATE,'DD-MM-YYYY') = M_VALDATE;


BEGIN

--PROCEDURE  -  DEAL PRE_CONFIRMATION
--SYSTEM     -  DEALNET
--CREATED BY -  KEITH
--CREATED ON -  07/10/2004 FOR SN-REF SN-REF 0409-071 --1 PRE CONFIRMATION

--dbms_output.put_line('##### ');
--RAISE_APPLICATION_ERROR(-20201,'******'||M_BUYER_NAME||'-----'||M_SELLER_NAME||'========'||M_SEC_CODE||'========'||M_VALDATE||'========'||M_USER);
--RAISE_APPLICATION_ERROR(-20201,'M_SEC_CODE'||M_SEC_CODE);
FOR I IN C1 LOOP
RAISE_APPLICATION_ERROR(-20201,I.DEAL_NO);
dbms_output.put_line('M_DEALNO '||I.DEAL_NO);

MBFSL_DEAL_CONFIRMATION(I.DEAL_NO,M_USER);

INSERT INTO DN_TIME_LOG
           (SUS_REF_NO,
           DN_USER,
           ENT_DATE,
           DESCRIPTION)
           VALUES
            (
              I.DEAL_NO,
              M_USER,
              SYSDATE,
              'CONFIRMATION');

    UPDATE DN_TRN_OUTP_SALE
    SET APP_STATUS='CONF'
    WHERE DEAL_NO=I.DEAL_NO AND
    SECURITY_CODE=I.SECURITY_CODE AND
    APP_STATUS='APPRO2';
 END LOOP;

COMMIT;

END DN_DEAL_PRE_CONFIRMATION;

