  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_INV_OUTPS_DEL_ALLO_INTEREST" 
(
 M_PROCESS_DATE    DN_SYS_PARAMETER.LAST_DAILY%TYPE
)

   -- Procedure    : Outright - Interest calculation for delaiyed allocation
   -- System       : Dealnet system
   -- Created by   : ITU - D.P. Pubudu Thushara
   -- Created on   : 07/09/1999

  AS

    CURSOR  SERIAL_NO IS

    SELECT
       C.PORTFOLIO_CODE,
       C.EFF_VALDATE, C.INST_TYPE,
       C.SECURITY_CODE,C.SERIAL_NO,
       C.DEAL_NO,C.SALE_EFF_VALDATE,
       C.FACE_VAL
    FROM
       DN_INV_OUTPS_DEAL_SERIAL_NO C
    WHERE
       C.SALE_EFF_VALDATE<ADD_MONTHS(M_PROCESS_DATE,-1) --deleayed month by waruna 2012-01-31
       AND
       (C.SERIAL_NO_STATUS='SAD' OR C.SERIAL_NO_STATUS='SND') --ADDED BY SM ON 16-02-00
       AND
        (C.COST_TRANS_STATUS IS NULL OR C.COST_TRANS_STATUS<>'Y'); --ADDED BY NIRMALA ON 30-04-2001


 M_TOT_COUP_INT       DN_INV_INT_OUTPS_DEAL_SERNO.COUP_INT%TYPE;
 M_TOT_PRICE_INT      DN_INV_INT_OUTPS_DEAL_SERNO.PRICE_INT%TYPE;
 M_PORTFOLIO_CODE     DN_INV_OUTPS_DEAL_SERIAL_NO.PORTFOLIO_CODE%TYPE;
 M_EFF_VALDATE        DN_INV_OUTPS_DEAL_SERIAL_NO.EFF_VALDATE%TYPE;
 M_SALE_EFF_VALDATE   DN_INV_OUTPS_DEAL_SERIAL_NO.SALE_EFF_VALDATE%TYPE;
 M_INST_TYPE          DN_INV_OUTPS_DEAL_SERIAL_NO.INST_TYPE%TYPE;
 M_SECURITY_CODE      DN_INV_OUTPS_DEAL_SERIAL_NO.SECURITY_CODE%TYPE;
 M_DEAL_NO            DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_NO%TYPE;
 M_SERIAL_NO          DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
 M_CARR_VAL           DN_INV_INT_OUTPS_DEAL_SERNO.COUP_INT%TYPE;
 M_COUP_INT_ACCR      DN_INV_INT_OUTPS_DEAL_SERNO.COUP_INT%TYPE;
 M_TOT_SEC_PRICE_INT  DN_INV_INT_OUTPS_DEAL_SERNO.COUP_INT%TYPE;
 M_TOT_SEC_COUP_INT   DN_INV_INT_OUTPS_DEAL_SERNO.PRICE_INT%TYPE;
 M_SER_FACE_VAL       DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;  --ADDED BY SM
 M_SEC_FACE_VAL       DN_INV_INT_OUTPS_DEAL_SEC.FACE_VAL%TYPE;  --ADDED BY SM
 M_DUP_SALE_CARR_VAL  DN_INV_INT_OUTPS_DEAL_SERNO.SALE_CARR_VAL%TYPE;  --ADDED BY SM
 M_DUP_SALE_ACCR_INT  DN_INV_INT_OUTPS_DEAL_SERNO.SALE_ACCR_INT%TYPE;  --ADDED BY SM
 M_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;--ADDED BY SM 14/07/2003
 M_OWNED_BY           DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;--ADDED BY SM 14/07/2003
BEGIN

   OPEN SERIAL_NO;

   LOOP

      FETCH  SERIAL_NO INTO

      M_PORTFOLIO_CODE,M_EFF_VALDATE,M_INST_TYPE,
      M_SECURITY_CODE,M_SERIAL_NO,M_DEAL_NO,M_SALE_EFF_VALDATE,
      M_SER_FACE_VAL; --INSERTED BY SM ON 04-02-2000
      --ORDER WAS WRONG, CORRECTED SM 03/12/99

      EXIT WHEN SERIAL_NO%NOTFOUND;

        -- At serial number level

        SELECT
           SUM(PRICE_INT-DEL_PRICE_INT),
           SUM(COUP_INT-DEL_COUP_INT)
           INTO
              M_TOT_PRICE_INT,M_TOT_COUP_INT
        FROM
           DN_INV_INT_OUTPS_DEAL_SERNO
        WHERE
           PROCESS_DATE>=M_SALE_EFF_VALDATE  --TO_DATE--TO_CHAR ???
           AND
           PROCESS_DATE<ADD_MONTHS(M_PROCESS_DATE,-1)--delayed month by waruna 2012-01-31  --TO_DATE--TO_CHAR ???
           AND
           PORTFOLIO_CODE=M_PORTFOLIO_CODE
           AND
           EFF_VALDATE=M_EFF_VALDATE  --TO_DATE--TO_CHAR ???
           AND
           INST_TYPE=M_INST_TYPE
           AND
           SECURITY_CODE=M_SECURITY_CODE
           AND
           SERIAL_NO=M_SERIAL_NO
           AND
           DEAL_NO=M_DEAL_NO;

----------THE FOLLOWING SECTION WAS ADDED BY SM TO OVERCOME PROBLEM OF DELAYED ALLOCATION
----------WHEN INTERST ACCRUAL TAKES PLACE AT DEAL SEC LEVEL-----------------------------

        SELECT
           NVL(SUM((PRICE_INT)/FACE_VAL*M_SER_FACE_VAL),0),
           NVL(SUM((COUP_INT)/FACE_VAL*M_SER_FACE_VAL),0)
           --MAX(FACE_VAL)
           INTO
              M_TOT_SEC_PRICE_INT,M_TOT_SEC_COUP_INT--,M_SEC_FACE_VAL
        FROM
           DN_INV_INT_OUTPS_DEAL_SEC
        WHERE
           PROCESS_DATE>=M_SALE_EFF_VALDATE  --TO_DATE--TO_CHAR ???
           AND
           PROCESS_DATE<ADD_MONTHS(M_PROCESS_DATE,-1) --delayed month by waruna 2012-01-31  --TO_DATE--TO_CHAR ???
           AND
           PORTFOLIO_CODE=M_PORTFOLIO_CODE
           AND
           EFF_VALDATE=M_EFF_VALDATE  --TO_DATE--TO_CHAR ???
           AND
           INST_TYPE=M_INST_TYPE
           AND
           SECURITY_CODE=M_SECURITY_CODE
           AND
           DEAL_NO=M_DEAL_NO;

         /*
         SET
           M_TOT_SEC_PRICE_INT=(NVL(M_TOT_SEC_PRICE_INT/M_SEC_FACE_VAL*M_SER_FACE_VAL),0);
           M_TOT_SEC_COUP_INT=(NVL(M_TOT_SEC_COUP_INT/M_SEC_FACE_VAL*M_SER_FACE_VAL),0)
         FROM DUAL
         */

-----------------------THE ABOVE SECTION WAS ADDED BY SM ON 01-02-2000-------------------


        IF M_TOT_PRICE_INT IS NULL THEN
           M_TOT_PRICE_INT:=0;
        END IF;

        IF M_TOT_COUP_INT IS NULL THEN
           M_TOT_COUP_INT:=0;
        END IF;

---THE ABOVE CONDITIONS ARE NOW REDUNDANT------------------------------------------------
---SM 04-02-2000
--SM-23-11-2000 CONSIDER CHANGING CONDITION BELOW TO '<>0'
        IF (M_TOT_PRICE_INT<>0 OR
            M_TOT_COUP_INT<>0 OR
            M_TOT_SEC_PRICE_INT<>0 OR
            M_TOT_SEC_COUP_INT<>0)
        THEN

           UPDATE DN_INV_INT_OUTPS_DEAL_SERNO
              SET DEL_PRICE_INT=M_TOT_PRICE_INT+M_TOT_SEC_PRICE_INT,
                  DEL_COUP_INT =M_TOT_COUP_INT+M_TOT_SEC_COUP_INT
           WHERE
              PROCESS_DATE=ADD_MONTHS(M_PROCESS_DATE,-1) --delayed month by waruna 2012-01-31
              AND
              PORTFOLIO_CODE=M_PORTFOLIO_CODE
              AND
              EFF_VALDATE=M_EFF_VALDATE  --TO_DATE--TO_CHAR ???
              AND
              INST_TYPE=M_INST_TYPE
              AND
              SECURITY_CODE=M_SECURITY_CODE
              AND
              SERIAL_NO=M_SERIAL_NO
              AND
              DEAL_NO=M_DEAL_NO;

         IF SQL%NOTFOUND THEN

           INSERT INTO DN_INV_INT_OUTPS_DEAL_SERNO
              (PROCESS_DATE, PORTFOLIO_CODE,
               EFF_VALDATE, INST_TYPE,
               SECURITY_CODE,
               DEAL_NO,SERIAL_NO,
               DEAL_YIELD,YIELD_WITH_BROKERAGE,
               SCRIP_FACE_VAL,FACE_VAL,
               DEL_PRICE_INT,DEL_COUP_INT,
               SERIAL_NO_STATUS
              )
              SELECT
                 M_PROCESS_DATE,PORTFOLIO_CODE,
                 EFF_VALDATE, INST_TYPE,
                 SECURITY_CODE,
                 DEAL_NO,SERIAL_NO,
                 DEAL_YIELD,YIELD_WITH_BROKERAGE,
                 SCRIP_FACE_VAL,FACE_VAL,
                 M_TOT_PRICE_INT+M_TOT_SEC_PRICE_INT,
                 M_TOT_COUP_INT+M_TOT_SEC_COUP_INT,
                 SERIAL_NO_STATUS
              FROM
                 DN_INV_OUTPS_DEAL_SERIAL_NO
              WHERE
                 PORTFOLIO_CODE=M_PORTFOLIO_CODE
                 AND
                 EFF_VALDATE=M_EFF_VALDATE  --TO_DATE--TO_CHAR ???
                 AND
                 INST_TYPE=M_INST_TYPE
                 AND
                 SECURITY_CODE=M_SECURITY_CODE
                 AND
                 SERIAL_NO=M_SERIAL_NO
                 AND
                 DEAL_NO=M_DEAL_NO;

         END IF;

--UPDATING INVEMTORY INFORMATION
          UPDATE DN_INV_OUTPS_DEAL_SERIAL_NO A
             SET PRICE_INT_ACCR=PRICE_INT_ACCR-M_TOT_PRICE_INT-M_TOT_SEC_PRICE_INT,
                 CARR_VAL      =CARR_VAL-M_TOT_PRICE_INT-M_TOT_SEC_PRICE_INT,
                 COUP_INT_ACCR =COUP_INT_ACCR-M_TOT_COUP_INT-M_TOT_SEC_COUP_INT,
                 TOT_COUP_INT  =TOT_COUP_INT-M_TOT_COUP_INT-M_TOT_SEC_COUP_INT
          WHERE
             PORTFOLIO_CODE=M_PORTFOLIO_CODE
             AND
             EFF_VALDATE=M_EFF_VALDATE  --TO_DATE--TO_CHAR ???
             AND
             INST_TYPE=M_INST_TYPE
             AND
             SECURITY_CODE=M_SECURITY_CODE
             AND
             SERIAL_NO=M_SERIAL_NO
             AND
             DEAL_NO=M_DEAL_NO;

     END IF;
--INSERTED BY TDS / SM ON 27/01/2000 TO OVERCOME PROBLEM OF DELAYED ALLOCATION SALE VALUES
--BEING MISSED OUT FROM DAY END ROUTINE

            SELECT CARR_VAL,TOT_COUP_INT
            INTO M_CARR_VAL,M_COUP_INT_ACCR
            FROM DN_INV_OUTPS_DEAL_SERIAL_NO A
            WHERE
               PORTFOLIO_CODE=M_PORTFOLIO_CODE
               AND
               EFF_VALDATE=M_EFF_VALDATE  --TO_DATE--TO_CHAR ???
               AND
               INST_TYPE=M_INST_TYPE
               AND
               SECURITY_CODE=M_SECURITY_CODE
               AND
               SERIAL_NO=M_SERIAL_NO
               AND
               DEAL_NO=M_DEAL_NO;

------------------ADJUSTING FOR SALE CARRYING VALUES ALREADY ACCOUNTED FOR-----------------

              SELECT
                 NVL(SUM(SALE_CARR_VAL),0),
                 NVL(SUM(SALE_ACCR_INT),0)
                 INTO
                 M_DUP_SALE_CARR_VAL,M_DUP_SALE_ACCR_INT
              FROM
                 DN_INV_INT_OUTPS_DEAL_SERNO
              WHERE
                 --PROCESS_DATE>=M_SALE_EFF_VALDATE  --TO_DATE--TO_CHAR ???
                 --AND
                 PROCESS_DATE<=ADD_MONTHS(M_PROCESS_DATE,-1) --deleayed month waruna 2012-01-31  --TO_DATE--TO_CHAR ???
                 AND
                 PROCESS_DATE>M_EFF_VALDATE-2  --NIRMALA
                 AND
                 PORTFOLIO_CODE=M_PORTFOLIO_CODE
                 AND
                 EFF_VALDATE=M_EFF_VALDATE  --TO_DATE--TO_CHAR ???
                 AND
                 INST_TYPE=M_INST_TYPE
                 AND
                 SECURITY_CODE=M_SECURITY_CODE
                 AND
                 SERIAL_NO=M_SERIAL_NO
                 AND
                 DEAL_NO=M_DEAL_NO;


      ---------------------------------------------------------------------------------------

      IF (M_CARR_VAL-M_DUP_SALE_CARR_VAL<>0 OR
          M_COUP_INT_ACCR-M_DUP_SALE_ACCR_INT<>0)
      THEN
--CHANGES BEING CONTEMPLATED TO ACCOUNT FOR DELAYED ALLOCATION TO BE INSERTED TO ACCOUNT TABLES
--ON SALE EFFECTIVE VALUE DATE

--CONDITION ADDED ON 14/07/2003
SELECT  PF_TYPE INTO M_PF_TYPE
FROM  DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE=M_PORTFOLIO_CODE;

SELECT  OWNED_BY_MBFSL INTO M_OWNED_BY
FROM  DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE=M_PORTFOLIO_CODE;


IF  M_PF_TYPE='P' AND M_OWNED_BY='Y' THEN

      INSERT INTO DN_ACC_LICENCEE_INST_ACCOUNT
         (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
      VALUES
         (M_PORTFOLIO_CODE,M_INST_TYPE, M_SALE_EFF_VALDATE,'103','DR', M_CARR_VAL-M_DUP_SALE_CARR_VAL, M_DEAL_NO,'TRFR OF CARR VAL-SALE','001');

      INSERT INTO DN_ACC_LICENCEE_INST_ACCOUNT
         (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
      VALUES
         (M_PORTFOLIO_CODE,M_INST_TYPE, M_SALE_EFF_VALDATE,'001','CR', M_CARR_VAL-M_DUP_SALE_CARR_VAL, M_DEAL_NO,'TRFR OF CARR VAL-SALE','103');

      INSERT INTO DN_ACC_LICENCEE_INST_ACCOUNT
         (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
      VALUES
         (M_PORTFOLIO_CODE,M_INST_TYPE, M_SALE_EFF_VALDATE,'103','DR', M_COUP_INT_ACCR-M_DUP_SALE_ACCR_INT, M_DEAL_NO,'TRFR OF COUP. INT - SALE','101');

      INSERT INTO DN_ACC_LICENCEE_INST_ACCOUNT
         (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
      VALUES
         (M_PORTFOLIO_CODE,M_INST_TYPE, M_SALE_EFF_VALDATE,'101','CR', M_COUP_INT_ACCR-M_DUP_SALE_ACCR_INT, M_DEAL_NO,'TRFR OF COUP. INT - SALE','103');

--     END IF;
ELSIF M_PF_TYPE='P' AND M_OWNED_BY='N' THEN

      INSERT INTO DN_ACC_PORTF_INST_ACCOUNT
         (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
      VALUES
         (M_PORTFOLIO_CODE,M_INST_TYPE, M_SALE_EFF_VALDATE,'103','DR', M_CARR_VAL-M_DUP_SALE_CARR_VAL, M_DEAL_NO,'TRFR OF CARR VAL-SALE','001');

      INSERT INTO DN_ACC_PORTF_INST_ACCOUNT
         (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
      VALUES
         (M_PORTFOLIO_CODE,M_INST_TYPE, M_SALE_EFF_VALDATE,'001','CR', M_CARR_VAL-M_DUP_SALE_CARR_VAL, M_DEAL_NO,'TRFR OF CARR VAL-SALE','103');

      INSERT INTO DN_ACC_PORTF_INST_ACCOUNT
         (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
      VALUES
         (M_PORTFOLIO_CODE,M_INST_TYPE, M_SALE_EFF_VALDATE,'103','DR', M_COUP_INT_ACCR-M_DUP_SALE_ACCR_INT, M_DEAL_NO,'TRFR OF COUP. INT - SALE','101');

      INSERT INTO DN_ACC_PORTF_INST_ACCOUNT
         (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
      VALUES
         (M_PORTFOLIO_CODE,M_INST_TYPE, M_SALE_EFF_VALDATE,'101','CR', M_COUP_INT_ACCR-M_DUP_SALE_ACCR_INT, M_DEAL_NO,'TRFR OF COUP. INT - SALE','103');

END IF;
--TEMPORARILY COMMENTED-----------------------------------------
               UPDATE DN_INV_INT_OUTPS_DEAL_SERNO
                  SET SALE_CARR_VAL=M_CARR_VAL-M_DUP_SALE_CARR_VAL,
                      SALE_ACCR_INT=M_COUP_INT_ACCR-M_DUP_SALE_ACCR_INT
               WHERE
                  PROCESS_DATE=M_SALE_EFF_VALDATE
                  AND
                  PORTFOLIO_CODE=M_PORTFOLIO_CODE
                  AND
                  EFF_VALDATE=M_EFF_VALDATE  --TO_DATE--TO_CHAR ???
                  AND
                  INST_TYPE=M_INST_TYPE
                  AND
                  SECURITY_CODE=M_SECURITY_CODE
                  AND
                  SERIAL_NO=M_SERIAL_NO
                  AND
                  DEAL_NO=M_DEAL_NO;

--               END IF;

               IF SQL%NOTFOUND THEN

                 INSERT INTO DN_INV_INT_OUTPS_DEAL_SERNO
                    (PROCESS_DATE, PORTFOLIO_CODE,
                     EFF_VALDATE, INST_TYPE,
                     SECURITY_CODE,
                     DEAL_NO,SERIAL_NO,
                     DEAL_YIELD,YIELD_WITH_BROKERAGE,
                     SCRIP_FACE_VAL,FACE_VAL,
                     SALE_CARR_VAL,SALE_ACCR_INT,
                     SERIAL_NO_STATUS
                    )
                    SELECT
                       M_SALE_EFF_VALDATE,PORTFOLIO_CODE,
                       EFF_VALDATE, INST_TYPE,
                       SECURITY_CODE,
                       DEAL_NO,SERIAL_NO,
                       DEAL_YIELD,YIELD_WITH_BROKERAGE,
                       SCRIP_FACE_VAL,FACE_VAL,
                       M_CARR_VAL-M_DUP_SALE_CARR_VAL,
                       M_COUP_INT_ACCR-M_DUP_SALE_ACCR_INT,
                       SERIAL_NO_STATUS
                    FROM
                       DN_INV_OUTPS_DEAL_SERIAL_NO
                    WHERE
                       PORTFOLIO_CODE=M_PORTFOLIO_CODE
                       AND
                       EFF_VALDATE=M_EFF_VALDATE  --TO_DATE--TO_CHAR ???
                       AND
                       INST_TYPE=M_INST_TYPE
                       AND
                       SECURITY_CODE=M_SECURITY_CODE
                       AND
                       SERIAL_NO=M_SERIAL_NO
                       AND
                       DEAL_NO=M_DEAL_NO;

               END IF;
    -----------------ADDED BY NIRMALA ON 27-04-2001-----------------------
