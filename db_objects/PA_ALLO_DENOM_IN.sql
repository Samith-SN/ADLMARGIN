set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."PA_ALLO_DENOM_IN" (
        M_REF_NO                     PA_BID_ENTRY_DENOMI.REF_NO%TYPE,
        M_INST_TYPE                  PA_BID_ENTRY_DENOMI.INST_TYPE%TYPE,
        M_ISSUER_CODE                PA_BID_ENTRY_DENOMI.ISSUER_CODE%TYPE,
        M_DENOMINATION               PA_BID_ENTRY_DENOMI.DENOMINATION%TYPE,
        M_DENOMI_NUMBER              PA_BID_ENTRY_DENOMI.DENOMI_NUMBER%TYPE,
        M_FACE_VALUE                 PA_BID_ENTRY_DENOMI.FACE_VALUE%TYPE)
 AS
 M_DENOMI_MOD           PA_BID_ENTRY.DENOMI_MOD%TYPE;

 BEGIN

/*RAISE_APPLICATION_ERROR(-20201,M_AUCTION_DATE ||' '||M_INST_TYPE||' '||M_SECURITY_CODE||' '||M_ISSUER_CODE||' '||M_PORTFOLIO_CODE||' '||M_ENTERED_BY||' '||M_SELECT_TYPE);*/


    /* PROCEDURE  - TO SAVE PRIMARY AUCTION ORDER ENTRY-DENOMINATIONS
       SYSTEM     - DEALNET
       CREATED BY - LATHIKA
       CREATED ON - 29-10-99 */
--RAISE_APPLICATION_ERROR(-20201,M_REF_NO ||' '||M_INST_TYPE||' '||M_ISSUER_CODE||''||M_DENOMINATION||''||M_FACE_VALUE);
 SELECT DENOMI_MOD
 INTO   M_DENOMI_MOD
 FROM   PA_BID_ENTRY
 WHERE  REF_NO = M_REF_NO;

 ---AFTER TRADE ALLOCATION SAVING-----------
 IF M_DENOMI_MOD IS NOT NULL THEN
    M_DENOMI_MOD := NULL;

    UPDATE PA_BID_ENTRY
       SET DENOMI_MOD =M_DENOMI_MOD
    WHERE  REF_NO = M_REF_NO;
 END IF;

 IF M_REF_NO IS NOT NULL  THEN

    UPDATE PA_BID_ENTRY_DENOMI
         SET DENOMI_NUMBER  =M_DENOMI_NUMBER,
             FACE_VALUE     =M_FACE_VALUE
       WHERE
         REF_NO         =M_REF_NO AND
         INST_TYPE      =M_INST_TYPE AND
         ISSUER_CODE    =M_ISSUER_CODE AND
         DENOMINATION   =M_DENOMINATION;


   IF SQL%NOTFOUND THEN
      INSERT INTO PA_BID_ENTRY_DENOMI
        (REF_NO,
         INST_TYPE,
         ISSUER_CODE,
         DENOMINATION,
         DENOMI_NUMBER,
         FACE_VALUE)
           VALUES(
             M_REF_NO,
             M_INST_TYPE,
             M_ISSUER_CODE,
             M_DENOMINATION,
             M_DENOMI_NUMBER,
             M_FACE_VALUE
              );
   END IF;
END IF;

COMMIT;

END PA_ALLO_DENOM_IN;

