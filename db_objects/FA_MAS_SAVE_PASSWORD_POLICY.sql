  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."FA_MAS_SAVE_PASSWORD_POLICY" 
( 
M_MINIMUM_LENGTH               FA_MAS_PASSWORD_POLICY.MINIMUM_LENGTH%TYPE,
M_MAXIMUM_LENGTH               FA_MAS_PASSWORD_POLICY.MAXIMUM_LENGTH%TYPE,
M_LOWERCASE_CHAR               FA_MAS_PASSWORD_POLICY.LOWERCASE_CHAR%TYPE,
M_UPPERCASE_CHAR               FA_MAS_PASSWORD_POLICY.UPPERCASE_CHAR%TYPE,
M_NUMERIC_CHAR                 FA_MAS_PASSWORD_POLICY.NUMERIC_CHAR%TYPE,
M_NUMERIC_EMBEDDED             FA_MAS_PASSWORD_POLICY.NUMERIC_EMBEDDED%TYPE,
M_SPECIAL_CHAR                 FA_MAS_PASSWORD_POLICY.SPECIAL_CHAR%TYPE,
M_SPECIAL_CHAR_EMBEDDED        FA_MAS_PASSWORD_POLICY.SPECIAL_CHAR_EMBEDDED%TYPE,
M_PASSWORD_CHANGE_ATTEMPT      FA_MAS_PASSWORD_POLICY.PASSWORD_CHANGE_ATTEMPT%TYPE,
M_ALLOW_USER_NAME              FA_MAS_PASSWORD_POLICY.ALLOW_USER_NAME%TYPE,
M_REPEAT_PASSWORD              FA_MAS_PASSWORD_POLICY.REPEAT_PASSWORD%TYPE,
M_PASSWORD_CHANGE_MINIMUM_GAP  FA_MAS_PASSWORD_POLICY.PASSWORD_CHANGE_MINIMUM_GAP%TYPE,
M_PASSWORD_EXPIRATION_DAYS     FA_MAS_PASSWORD_POLICY.PASSWORD_EXPIRATION_DAYS%TYPE,
M_WARNING_MESSAGE_DAYS         FA_MAS_PASSWORD_POLICY.WARNING_MESSAGE_DAYS%TYPE,
M_USER                         VARCHAR2
)
 
 AS
/*
PROCEDURE:FA_MAS_SAVE_PASSWORD_POLICY
NAME: THAMALI JAYATUNGA
DATE/TIME: 2010.07.02
*/
M_COUNT   NUMBER;
M_COUNT2  NUMBER;

 
BEGIN
 
DN_VALIDATE_SAVE_RIGHTS(M_USER,'WD_password_policy_Users');

SELECT COUNT(*) INTO M_COUNT FROM FA_MAS_PASSWORD_POLICY;
SELECT COUNT(*) INTO M_COUNT2 FROM DN_REF_PASSWORD_EXPIRE_DUR;
 
IF M_COUNT = 0 THEN 

INSERT INTO FA_MAS_PASSWORD_POLICY
(MINIMUM_LENGTH,MAXIMUM_LENGTH,LOWERCASE_CHAR,UPPERCASE_CHAR,
NUMERIC_CHAR,NUMERIC_EMBEDDED,SPECIAL_CHAR,SPECIAL_CHAR_EMBEDDED,
PASSWORD_CHANGE_ATTEMPT,ALLOW_USER_NAME,REPEAT_PASSWORD,
PASSWORD_CHANGE_MINIMUM_GAP,PASSWORD_EXPIRATION_DAYS,
WARNING_MESSAGE_DAYS,ENT_USER,ENT_DATE)
VALUES(M_MINIMUM_LENGTH,M_MAXIMUM_LENGTH,M_LOWERCASE_CHAR,M_UPPERCASE_CHAR,
M_NUMERIC_CHAR,M_NUMERIC_EMBEDDED,M_SPECIAL_CHAR,M_SPECIAL_CHAR_EMBEDDED,
M_PASSWORD_CHANGE_ATTEMPT,M_ALLOW_USER_NAME,M_REPEAT_PASSWORD,
M_PASSWORD_CHANGE_MINIMUM_GAP,M_PASSWORD_EXPIRATION_DAYS,
M_WARNING_MESSAGE_DAYS,M_USER,SYSDATE);

    IF M_COUNT2 = 0 THEN 
        INSERT INTO DN_REF_PASSWORD_EXPIRE_DUR
        (EXPIRE_DURATION,REMINDER,USER_NAME,ENT_DATE)
        VALUES
        (M_PASSWORD_EXPIRATION_DAYS,M_WARNING_MESSAGE_DAYS,M_USER,SYSDATE);
     ELSE
     
         UPDATE DN_REF_PASSWORD_EXPIRE_DUR
         SET
            EXPIRE_DURATION = M_PASSWORD_EXPIRATION_DAYS,
            REMINDER        = M_WARNING_MESSAGE_DAYS, --SINGLE RECORD AVIALABLE FOR ENTITRE SYSTEM
            USER_NAME       = M_USER,
            ENT_DATE        = SYSDATE;
             
            
           
        
     END IF;
         
 
ELSE 

INSERT INTO FA_MAS_PASSWORD_POLICY_BK
(MINIMUM_LENGTH,MAXIMUM_LENGTH,LOWERCASE_CHAR,UPPERCASE_CHAR,
NUMERIC_CHAR,NUMERIC_EMBEDDED,SPECIAL_CHAR,SPECIAL_CHAR_EMBEDDED,
PASSWORD_CHANGE_ATTEMPT,ALLOW_USER_NAME,REPEAT_PASSWORD,
PASSWORD_CHANGE_MINIMUM_GAP,PASSWORD_EXPIRATION_DAYS,
WARNING_MESSAGE_DAYS,ENT_USER,ENT_DATE,MOD_USER,MOD_DATE)

SELECT MINIMUM_LENGTH,MAXIMUM_LENGTH,LOWERCASE_CHAR,UPPERCASE_CHAR,
NUMERIC_CHAR,NUMERIC_EMBEDDED,SPECIAL_CHAR,SPECIAL_CHAR_EMBEDDED,
PASSWORD_CHANGE_ATTEMPT,ALLOW_USER_NAME,REPEAT_PASSWORD,
PASSWORD_CHANGE_MINIMUM_GAP,PASSWORD_EXPIRATION_DAYS,
WARNING_MESSAGE_DAYS,ENT_USER,ENT_DATE,MOD_USER,MOD_DATE
FROM FA_MAS_PASSWORD_POLICY;
 
UPDATE FA_MAS_PASSWORD_POLICY
SET MINIMUM_LENGTH              = M_MINIMUM_LENGTH,
    MAXIMUM_LENGTH              = M_MAXIMUM_LENGTH,
    LOWERCASE_CHAR              = M_LOWERCASE_CHAR,
    UPPERCASE_CHAR              = M_UPPERCASE_CHAR,
    NUMERIC_CHAR                = M_NUMERIC_CHAR,
    NUMERIC_EMBEDDED            = M_NUMERIC_EMBEDDED,
    SPECIAL_CHAR                = M_SPECIAL_CHAR,
    SPECIAL_CHAR_EMBEDDED       = M_SPECIAL_CHAR_EMBEDDED,
    PASSWORD_CHANGE_ATTEMPT     = M_PASSWORD_CHANGE_ATTEMPT,
    ALLOW_USER_NAME             = M_ALLOW_USER_NAME,
    REPEAT_PASSWORD             = M_REPEAT_PASSWORD,
    PASSWORD_CHANGE_MINIMUM_GAP = M_PASSWORD_CHANGE_MINIMUM_GAP,
    PASSWORD_EXPIRATION_DAYS    = M_PASSWORD_EXPIRATION_DAYS,
    WARNING_MESSAGE_DAYS        = M_WARNING_MESSAGE_DAYS,
    MOD_USER                    = UPPER(M_USER),
    MOD_DATE                    = SYSDATE;
    
    --- PASSWORD_EXPIRATION_DAYS
    
    IF M_COUNT2 = 0 THEN 
        INSERT INTO DN_REF_PASSWORD_EXPIRE_DUR
        (EXPIRE_DURATION,REMINDER,USER_NAME,ENT_DATE)
        VALUES
        (M_PASSWORD_EXPIRATION_DAYS,M_WARNING_MESSAGE_DAYS,M_USER,SYSDATE);
     ELSE
     
         UPDATE DN_REF_PASSWORD_EXPIRE_DUR
         SET
            EXPIRE_DURATION = M_PASSWORD_EXPIRATION_DAYS,
            REMINDER        = M_WARNING_MESSAGE_DAYS, --SINGLE RECORD AVIALABLE FOR ENTITRE SYSTEM
            USER_NAME       = M_USER,
            ENT_DATE        = SYSDATE;
             
            
           
        
     END IF;

    
    
    
 
END IF;
 
END;

