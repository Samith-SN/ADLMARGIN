--------------------------------------------------------
--  DDL for Function DN_GET_BALANCE_BF_RPT
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_BALANCE_BF_RPT" 
(
 M_DATE                  VARCHAR2,
 M_PORTFOLIO_CODE        DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE
 )
 RETURN NUMBER
 AS
 M_PF_TYPE          DN_REF_PORTFOLIO.PF_TYPE%TYPE;
 M_MAT_DATE_REPO    DATE;
 M_MAT_DATE_SETE    DATE;
 M_MAT_DATE_SETE1   DATE;
 M_AMOUNT           NUMBER;
 M_INT_AMOUNT       NUMBER;
 M_COUNT            NUMBER;

 BEGIN
dbms_output.put_line('Value of M_DATE='||M_DATE);
SELECT MAX(MATURITY_DATE)
INTO   M_MAT_DATE_REPO
FROM
(SELECT MAX(MATURITY_DATE) MATURITY_DATE
FROM   DN_TRN_REPO_FRESH
WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <   TO_DATE(M_DATE,'DD-MM-YYYY') AND
       APP_STATUS    = 'CONF'
UNION ALL
SELECT MAX(MATURITY_DATE) MATURITY_DATE
FROM   DN_TRN_REPO_ROLLOVER
WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <   TO_DATE(M_DATE,'DD-MM-YYYY') AND
       APP_STATUS    = 'CONF');


SELECT MAX(SETTLE_DATE)
INTO   M_MAT_DATE_SETE1
FROM   DN_TRN_REPO_SETTLEMENT
WHERE  PRIOR_DEAL_NO IN (SELECT DEAL_NO
                        FROM   DN_TRN_REPO_FRESH
                        WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                               TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <   TO_DATE(M_DATE,'DD-MM-YYYY') AND
                               APP_STATUS    = 'CONF'
                        UNION ALL
                        SELECT DEAL_NO
                        FROM   DN_TRN_REPO_ROLLOVER
                        WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                               TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <   TO_DATE(M_DATE,'DD-MM-YYYY') AND
                               APP_STATUS    = 'CONF')  AND
       APP_STATUS    = 'CONF'       ;
         dbms_output.put_line('Value of M_MAT_DATE_SETE1='||M_MAT_DATE_SETE1);
dbms_output.put_line('Value of M_MAT_DATE_REPO='||M_MAT_DATE_REPO);
IF(M_MAT_DATE_SETE1>=M_MAT_DATE_REPO) THEN

   IF TO_CHAR(M_MAT_DATE_SETE1,'DD') = '01' THEN
      M_MAT_DATE_SETE := ADD_MONTHS(M_MAT_DATE_SETE1,-1);
   ELSE
      M_MAT_DATE_SETE := LAST_DAY(ADD_MONTHS(M_MAT_DATE_SETE1,-1))+1;
   END IF;

         --dbms_output.put_line('Value of M_AMOUNT='||M_AMOUNT);
SELECT SUM(TOT)/*,SUM(ABSTOT)*/
INTO   M_AMOUNT
FROM (
SELECT A.DN_PORTFOLIO_CODE,C.PF_NAME,
SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT,0)) -SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT,0)) TOT ,
ABS(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT,0)) -SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT,0))) ABSTOT
FROM DN_ACC_LICENCEE_GEN_ACCOUNT A,
DN_REF_PORTFOLIO C
WHERE TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(TO_CHAR(M_MAT_DATE_SETE1,'DD-MON-YYYY'),'DD-MON-YYYY') AND
TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<TO_DATE(M_DATE,'DD-MM-YYYY')  AND
A.DN_PORTFOLIO_CODE=C.PORTFOLIO_CODE AND
DOCREFNO NOT IN (SELECT DEAL_NO FROM DN_TRN_OUTP_SALE X --,DN_REF_INSTRUMENT Y
                WHERE X.DEAL_NO=A.DOCREFNO AND DN_GET_INSTRUMENT_CAT(INST_TYPE)='EQUITY') AND
A.ACC_TYPE_CODE IN('301') AND SUBSTR(DOCREFNO,0,2) IN ('CD','CW','OR','RI','RF','RR') AND
A.DN_PORTFOLIO_CODE = M_PORTFOLIO_CODE
GROUP BY A.DN_PORTFOLIO_CODE,C.PF_NAME

UNION ALL
SELECT X.PORTFOLIO_CODE DN_PORTFOLIO_CODE,V.PF_NAME PF_NAME,SUM(-1*TRNAMOUNT) TOT,ABS(SUM(TRNAMOUNT)) ABSTOT
FROM DN_TRN_DIVIDEND_INCOME X,
     DN_REF_PORTFOLIO V
WHERE
X.PORTFOLIO_CODE = V.PORTFOLIO_CODE AND
V.PF_TYPE = 'P' AND V.OWNED_BY_MBFSL='N' AND
TO_DATE(TO_CHAR(RECEIVED_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>=TO_DATE(TO_CHAR(M_MAT_DATE_SETE1,'DD-MON-YYYY'),'DD-MON-YYYY') AND
TO_DATE(TO_CHAR(RECEIVED_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')<TO_DATE(M_DATE,'DD-MM-YYYY')  AND
X.PORTFOLIO_CODE = M_PORTFOLIO_CODE
GROUP BY X.PORTFOLIO_CODE,V.PF_NAME

UNION ALL

SELECT BUY_PORTFOLIO_CODE DN_PORTFOLIO_CODE,W.PF_NAME PF_NAME,SUM(SETTLE_VALUE)-0 TOT,ABS(SUM(SETTLE_VALUE)-0) ABSTOT
FROM DN_TRN_OUTP_SALE X, ---- .DN_REF_INSTRUMENT Y,
     DN_TRN_OUTP_SALE_SETTLE_EQUITY Z,
    DN_REF_PORTFOLIO W,
     DN_REF_PORTFOLIO V
WHERE
Z.DEAL_NO= X.DEAL_NO AND
X.BUY_PORTFOLIO_CODE= W.PORTFOLIO_CODE AND
X.SELL_PORTFOLIO_CODE = V.PORTFOLIO_CODE AND
APP_STATUS = 'CONF' AND
DN_GET_INSTRUMENT_CAT(INST_TYPE)='EQUITY' AND
W.PF_TYPE = 'P' AND W.OWNED_BY_MBFSL='N' AND
TO_DATE(TO_CHAR(BUY_SETLE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>=TO_DATE(TO_CHAR(M_MAT_DATE_SETE1,'DD-MON-YYYY'),'DD-MON-YYYY') AND
TO_DATE(TO_CHAR(BUY_SETLE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')<TO_DATE(M_DATE,'DD-MM-YYYY')  AND
W.PORTFOLIO_CODE = M_PORTFOLIO_CODE
GROUP BY BUY_PORTFOLIO_CODE,W.PF_NAME

UNION ALL

SELECT SELL_PORTFOLIO_CODE DN_PORTFOLIO_CODE,W.PF_NAME PF_NAME,SUM(0-SETTLE_VALUE) TOT,SUM(0-SETTLE_VALUE) ABSTOT
FROM DN_TRN_OUTP_SALE X,
     DN_TRN_OUTP_SALE_SETTLE_EQUITY Z,
     DN_REF_PORTFOLIO W,
     DN_REF_PORTFOLIO V
WHERE
Z.DEAL_NO= X.DEAL_NO AND
X.SELL_PORTFOLIO_CODE= W.PORTFOLIO_CODE AND
X.BUY_PORTFOLIO_CODE = V.PORTFOLIO_CODE AND
APP_STATUS = 'CONF' AND
DN_GET_INSTRUMENT_CAT(INST_TYPE)='EQUITY' AND
W.PF_TYPE = 'P' AND W.OWNED_BY_MBFSL='N' AND
TO_DATE(TO_CHAR(SELL_SETLE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>=TO_DATE(TO_CHAR(M_MAT_DATE_SETE1,'DD-MON-YYYY'),'DD-MON-YYYY') AND
TO_DATE(TO_CHAR(SELL_SETLE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')<TO_DATE(M_DATE,'DD-MM-YYYY')  AND
W.PORTFOLIO_CODE = M_PORTFOLIO_CODE
GROUP BY SELL_PORTFOLIO_CODE,W.PF_NAME
);
dbms_output.put_line('QQQQQQValue of M_AMOUNT='||M_AMOUNT);
dbms_output.put_line('Value of M_MAT_DATE_SETE='||M_MAT_DATE_SETE);
IF TO_CHAR(M_MAT_DATE_SETE,'MON')  <> TO_CHAR(TO_DATE(M_DATE,'DD-MM-YYYY'),'MON') AND TO_CHAR(TO_DATE(M_DATE,'DD-MM-YYYY'),'DD') = '01' THEN

 SELECT SUM(INT_AMOUNT)
 INTO   M_INT_AMOUNT
 FROM (
 SELECT INT_AMOUNT
 FROM   DN_TRN_REPO_FRESH A,DN_REF_PORTFOLIO B
 WHERE  BORR_PORTFOLIO_CODE= B.PORTFOLIO_CODE AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') >=  TO_DATE(TO_CHAR(M_MAT_DATE_SETE,'DD-MON-YYYY'),'DD-MON-YYYY') AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <   TO_DATE(M_DATE,'DD-MM-YYYY')  AND
        BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
        APP_STATUS   = 'CONF'
 UNION ALL
 SELECT INT_AMOUNT
 FROM   DN_TRN_REPO_ROLLOVER A,DN_REF_PORTFOLIO B
 WHERE  BORR_PORTFOLIO_CODE= B.PORTFOLIO_CODE AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') >=   TO_DATE(TO_CHAR(M_MAT_DATE_SETE,'DD-MON-YYYY'),'DD-MON-YYYY') AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <    TO_DATE(M_DATE,'DD-MM-YYYY')  AND
        BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       --ON_CALL_DEAL = 'Y' AND
        APP_STATUS   = 'CONF' );
        dbms_output.put_line('WWWWWValue of M_INT_AMOUNT='||M_INT_AMOUNT);
        --dbms_output.put_line('Value of M_AMOUNT='||M_AMOUNT);
 M_AMOUNT := NVL(M_AMOUNT,0) + NVL(M_INT_AMOUNT,0);
END IF;

ELSE
dbms_output.put_line('Value of M_MAT_DATE_SETE=TEST');
  IF TO_CHAR(TO_DATE(M_DATE,'DD-MM-YYYY'),'DD')='01' THEN
       M_MAT_DATE_SETE := ADD_MONTHS(TO_DATE(M_DATE,'DD-MM-YYYY'),-1);
       dbms_output.put_line('Value of M_MAT_DATE_SETE='||M_MAT_DATE_SETE);
       dbms_output.put_line('Value of M_DATE='||M_DATE);
       SELECT SUM(INT_AMOUNT)
       INTO   M_AMOUNT
       FROM (
       SELECT INT_AMOUNT
       FROM   DN_TRN_REPO_FRESH A,DN_REF_PORTFOLIO B
       WHERE  BORR_PORTFOLIO_CODE= B.PORTFOLIO_CODE AND
              TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') >=  TO_DATE(TO_CHAR(M_MAT_DATE_SETE,'DD-MON-YYYY'),'DD-MON-YYYY') AND
              TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <   TO_DATE(M_DATE,'DD-MM-YYYY')  AND
              BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
              APP_STATUS   = 'CONF'
       UNION ALL
       SELECT INT_AMOUNT
       FROM   DN_TRN_REPO_ROLLOVER A,DN_REF_PORTFOLIO B
       WHERE  BORR_PORTFOLIO_CODE= B.PORTFOLIO_CODE AND
              TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') >=   TO_DATE(TO_CHAR(M_MAT_DATE_SETE,'DD-MON-YYYY'),'DD-MON-YYYY') AND
              TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <    TO_DATE(M_DATE,'DD-MM-YYYY')  AND
              BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
             --ON_CALL_DEAL = 'Y' AND
              APP_STATUS   = 'CONF' );
              dbms_output.put_line('EEEEEValue of M_AMOUNT='||M_AMOUNT);
 ELSE
      M_AMOUNT :=0;
 END IF;
END IF;
   RETURN  M_AMOUNT;

 END DN_GET_BALANCE_BF_RPT;

