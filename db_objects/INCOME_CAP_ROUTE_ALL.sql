set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."INCOME_CAP_ROUTE_ALL" 
(
M_START_DATE     VARCHAR2,
M_END_DATE       VARCHAR2,
M_USER           DN_REF_USER.DN_USER%TYPE
)
AS

BEGIN

INSERT INTO DN_INCOME_CAP_PARAMETERS_HIS
(LAST_PROCESSED,USER_NAME,START_DATE,PORTFOLIO_CODE,ACC_TYPE_CODE,NET_VALUE,DRAMOUNT,CRAMOUNT)
    SELECT
    LAST_PROCESSED,USER_NAME,START_DATE,PORTFOLIO_CODE,ACC_TYPE_CODE,NET_VALUE,DRAMOUNT,CRAMOUNT
    FROM DN_INCOME_CAP_PARAMETERS;
DELETE  DN_INCOME_CAP_PARAMETERS   ;

 FOR I IN

 (SELECT A.PORTFOLIO_CODE PORTFOLIO_CODE,
       A.ACC_TYPE_CODE CODE,
       NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
       NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT ,
       NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0)- NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0) ABS
FROM   DN_ACC_PORTF_INST_ACCOUNT A,
       DN_ACC_ACCOUNT_TYPE B
WHERE  A.ACC_TYPE_CODE=B.ACC_TYPE_CODE AND
       A.TRNAMOUNT<>0   AND
       A.PORTFOLIO_CODE IN (SELECT PORTFOLIO_CODE FROM DN_REF_PORTFOLIO WHERE PF_TYPE='P' AND OWNED_BY_MBFSL='N' ) AND
       TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_START_DATE,'DD/MM/YYYY') AND
       TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_END_DATE,'DD/MM/YYYY') AND
       B.ACC_NOTE IN ('IN','EX')
GROUP BY A.PORTFOLIO_CODE,A.ACC_TYPE_CODE

UNION

SELECT A.PORTFOLIO_CODE PORTFOLIO_CODE,
       A.ACC_TYPE_CODE CODE,
       NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
       NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT ,
       NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0)- NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0)
FROM   DN_ACC_PORTF_GEN_ACCOUNT A, DN_ACC_ACCOUNT_TYPE B
WHERE  A.ACC_TYPE_CODE=B.ACC_TYPE_CODE  AND
       A.TRNAMOUNT<>0   AND
       A.PORTFOLIO_CODE IN (SELECT PORTFOLIO_CODE FROM DN_REF_PORTFOLIO WHERE PF_TYPE='P' AND OWNED_BY_MBFSL='N' ) AND
       TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_START_DATE,'DD/MM/YYYY') AND
       TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_END_DATE,'DD/MM/YYYY')  AND
       B.ACC_NOTE IN ('IN','EX')

GROUP BY A.PORTFOLIO_CODE,A.ACC_TYPE_CODE
ORDER BY 1,2
)

 LOOP


   INSERT INTO DN_INCOME_CAP_PARAMETERS
    (LAST_PROCESSED,USER_NAME,START_DATE,PORTFOLIO_CODE,ACC_TYPE_CODE,NET_VALUE,DRAMOUNT,CRAMOUNT)
   VALUES
    (TO_DATE(M_END_DATE,'DD/MM/YYYY'),M_USER,TO_DATE(M_START_DATE,'DD/MM/YYYY'),
     I.PORTFOLIO_CODE,I.CODE,I.ABS,I.DRTOT,I.CRTOT);


END LOOP;

 INSERT INTO DN_ACC_PORTF_GEN_ACCOUNT
 (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE, DRCR_STATUS,
  TRNAMOUNT,DOCREFNO,ENTDATE,PROC_DESC,CORR_ACC_NO)
 SELECT PORTFOLIO_CODE,PORTFOLIO_CODE,TO_DATE(M_END_DATE,'DD/MM/YYYY'),ACC_TYPE_CODE,
  DECODE(SIGN(NET_VALUE),1,'CR','DR'),ABS(NET_VALUE),'INC.CAP',
  TO_DATE(TO_CHAR(SYSDATE,'DD-MM-YYYY'),'DD-MM-YYYY'),'INCOME CAPITALIZATION','600'
 FROM DN_INCOME_CAP_PARAMETERS;


INSERT INTO DN_ACC_PORTF_GEN_ACCOUNT
 (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE, DRCR_STATUS,
  TRNAMOUNT,DOCREFNO,ENTDATE,PROC_DESC,CORR_ACC_NO)
SELECT PORTFOLIO_CODE,PORTFOLIO_CODE,TO_DATE(M_END_DATE,'DD/MM/YYYY'),'600',
  DECODE(SIGN(NET_VALUE),1,'DR','CR'),ABS(NET_VALUE),'INC.CAP',
  TO_DATE(TO_CHAR(SYSDATE,'DD-MM-YYYY'),'DD-MM-YYYY'),'INCOME CAPITALIZATION',ACC_TYPE_CODE
 FROM DN_INCOME_CAP_PARAMETERS;

UPDATE DN_SYS_INCOME_CAP
 SET LAST_PROCESSED=TO_DATE(M_END_DATE,'DD/MM/YYYY');



END INCOME_CAP_ROUTE_ALL;

