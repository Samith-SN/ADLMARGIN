  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_CDS_NO" 
(
 BUY_PORTFOLIO_CODE         DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE,
 SELL_PORTFOLIO_CODE        DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE
)
RETURN VARCHAR
AS
M_CDS_ACC_NO                DN_REF_PORTFOLIO.CDS_ACC_NO%TYPE;
M_BUY_PF                    DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE;
M_SELL_PF                   DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE;

BEGIN

SELECT PF_TYPE  INTO M_BUY_PF
FROM DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE =BUY_PORTFOLIO_CODE;

SELECT PF_TYPE  INTO M_SELL_PF
FROM DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE =SELL_PORTFOLIO_CODE;

dbms_output.put_line('M_SELL_PF '||M_SELL_PF||'M_BUY_PF'||M_BUY_PF);

IF ((M_BUY_PF='P' AND M_SELL_PF='C' ) OR (M_BUY_PF='P' AND M_SELL_PF='P'))THEN
SELECT CDS_ACC_NO INTO M_CDS_ACC_NO
FROM DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE=BUY_PORTFOLIO_CODE;
ELSIF (M_BUY_PF='C' AND M_SELL_PF='P' ) THEN
SELECT CDS_ACC_NO INTO M_CDS_ACC_NO
FROM DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE=SELL_PORTFOLIO_CODE;
END IF;

--dbms_output.put_line('M_CDS_ACC_NO '||M_CDS_ACC_NO);

RETURN M_CDS_ACC_NO;
END;

/
