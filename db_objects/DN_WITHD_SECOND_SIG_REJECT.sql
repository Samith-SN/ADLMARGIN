set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_WITHD_SECOND_SIG_REJECT" 
   (
   M_DOCREFNO           DN_TRN_BO_CAP_DEPOSIT.DOCREFNO%TYPE,
   M_ACTIVE_STATUS      DN_REF_PORTFOLIO.ACTIVE_STATUS%TYPE,
   M_USER               DN_DOC_STATUS_LOG.DN_USER%TYPE
   )
AS
M_NUMBER VARCHAR(100);
M_COUNT  NUMBER;

/*
CREATED BY - K. M.WARUNA SRI JAYANATH
CREATED ON - 2012-02-27
SYSTEM     - ADLMARGIN

*/
        


BEGIN

--RAISE_APPLICATION_ERROR(-20201,'PAYMENT INVALID='||M_PAYMENT_NO||'**'||M_ACTIVE_STATUS);

SELECT  COUNT(*)INTO M_COUNT
FROM DN_TRN_BO_CAP_DEPOSIT_TEMP 
WHERE   DOCREFNO  = M_DOCREFNO 
AND EFF_VAL_DATE <(SELECT A.LAST_DAILY
                   FROM DN_SYS_DAILY_MARGIN_TRADING A);
                   
 IF M_COUNT>0 THEN
 RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT REJECT ,   EFF_VAL_DATE LOWER THAN EOD ');
 END IF;                  

  
  
 IF M_ACTIVE_STATUS='ENT' THEN
  
 
  UPDATE DN_TRN_BO_CAP_DEPOSIT_TEMP
  SET    CURRENT_STATUS  = 'REJ'
  WHERE  DOCREFNO  = M_DOCREFNO
  AND    CURRENT_STATUS  = 'SIG1';
 
  UPDATE DN_TRN_BO_CAP_DEPOSIT
  SET    APP_STATUS  = 'REJ',
         SIGNATURE_1 = M_USER
  WHERE  DOCREFNO    = M_DOCREFNO
  AND    APP_STATUS  = 'SIG1';
  
  
  IF SQL%FOUND THEN
        
  DN_ACC_G_5(M_DOCREFNO); --revece

  END IF;

            
END IF;




END ; 

/
