--------------------------------------------------------
--  DDL for Procedure MBFSL_REPOROLOVER_SERIAL_NO
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_REPOROLOVER_SERIAL_NO" (
    M_DEAL_NUMBER        DN_TRN_REPO_FRESH.DEAL_NO%TYPE
)

AS

M_CNT NUMBER DEFAULT 0;
M_CNT1 NUMBER DEFAULT 0;
M_CNT0 NUMBER DEFAULT 0;

M_PREV_DEAL  DN_TRN_REPO_ROLLOVER.PRIOR_DEAL_NO%TYPE;


BEGIN


SELECT COUNT(*) INTO M_CNT1 FROM
DN_TRN_REPO_ROLLOVER_SEC
WHERE DEAL_NO=M_DEAL_NUMBER;

IF M_CNT1 = 0 THEN


SELECT PRIOR_DEAL_NO INTO  M_PREV_DEAL FROM DN_TRN_REPO_ROLLOVER
WHERE DEAL_NO=M_DEAL_NUMBER;
-- RAISE_APPLICATION_ERROR(-20201,M_PREV_DEAL);


IF SUBSTR(M_PREV_DEAL,0,2) = 'RF' THEN




SELECT COUNT(*) INTO M_CNT FROM
DN_TRN_REPO_FRESH_SEC
WHERE     DEAL_NO=M_PREV_DEAL;

IF M_CNT > 0 THEN


DELETE FROM DN_TRN_REPO_ROLLOVER_INST WHERE DEAL_NO=M_DEAL_NUMBER;
INSERT INTO DN_TRN_REPO_ROLLOVER_INST(DEAL_NO,
    INST_TYPE,
    INV_CODE,
    RPTRN_HCUT_PER)
(SELECT M_DEAL_NUMBER,
    INST_TYPE,
    INV_CODE,
    RPTRN_HCUT_PER FROM DN_TRN_REPO_FRESH_INST WHERE DEAL_NO=M_PREV_DEAL);


INSERT INTO DN_TRN_REPO_ROLLOVER_SEC (DEAL_NO,INST_TYPE,INV_CODE,
    SECURITY_CODE,
    ENDOSER_CODE,
    FACE_VALUE,
    FVAL_WITH_HAIR_CUT,
    INV_STATUS,
    FACE_VALUE_CURR)
(SELECT   M_DEAL_NUMBER,INST_TYPE,INV_CODE,SECURITY_CODE,ENDOSER_CODE,
    FACE_VALUE,
    FVAL_WITH_HAIR_CUT,
    'N',
    FACE_VALUE_CURR FROM DN_TRN_REPO_FRESH_SEC
WHERE     DEAL_NO=M_PREV_DEAL);


INSERT INTO DN_TRN_REPO_ROLLOVER_SERIAL_NO( DEAL_NO,INST_TYPE,INV_CODE,SECURITY_CODE,SERIAL_NO,
    FACE_VALUE,INV_STATUS,DATA_FROM,LOCATION,PREV_DEAL_NO,FACE_VALUE_CURR)
(SELECT M_DEAL_NUMBER,INST_TYPE,INV_CODE,SECURITY_CODE,SERIAL_NO,
    FACE_VALUE,'N',DATA_FROM,LOCATION,PREV_DEAL_NO,FACE_VALUE_CURR
    FROM DN_TRN_REPO_FRESH_SERIAL_NO WHERE     DEAL_NO=M_PREV_DEAL);

END IF;

ELSE


SELECT COUNT(*) INTO M_CNT FROM
DN_TRN_REPO_ROLLOVER_SEC
WHERE     DEAL_NO=M_PREV_DEAL;

IF M_CNT > 0 THEN

DELETE FROM DN_TRN_REPO_ROLLOVER_INST WHERE DEAL_NO=M_DEAL_NUMBER;
INSERT INTO DN_TRN_REPO_ROLLOVER_INST(DEAL_NO,
    INST_TYPE,
    INV_CODE,
    RPTRN_HCUT_PER)
(SELECT M_DEAL_NUMBER,
    INST_TYPE,
    INV_CODE,
    RPTRN_HCUT_PER FROM DN_TRN_REPO_ROLLOVER_INST WHERE DEAL_NO=M_PREV_DEAL);




INSERT INTO DN_TRN_REPO_ROLLOVER_SEC (DEAL_NO,INST_TYPE,INV_CODE,
    SECURITY_CODE,
    ENDOSER_CODE,
    FACE_VALUE,
    FVAL_WITH_HAIR_CUT,
    INV_STATUS,
    FACE_VALUE_CURR)
(SELECT   M_DEAL_NUMBER,INST_TYPE,INV_CODE,SECURITY_CODE,ENDOSER_CODE,
    FACE_VALUE,
    FVAL_WITH_HAIR_CUT,
    'N',
    FACE_VALUE_CURR FROM DN_TRN_REPO_ROLLOVER_SEC
WHERE     DEAL_NO=M_PREV_DEAL);


INSERT INTO DN_TRN_REPO_ROLLOVER_SERIAL_NO( DEAL_NO,INST_TYPE,INV_CODE,SECURITY_CODE,SERIAL_NO,
    FACE_VALUE,INV_STATUS,DATA_FROM,LOCATION,PREV_DEAL_NO,FACE_VALUE_CURR)
(SELECT M_DEAL_NUMBER,INST_TYPE,INV_CODE,SECURITY_CODE,SERIAL_NO,
    FACE_VALUE,'N',DATA_FROM,LOCATION,PREV_DEAL_NO,FACE_VALUE_CURR
    FROM DN_TRN_REPO_ROLLOVER_SERIAL_NO WHERE     DEAL_NO=M_PREV_DEAL);

END IF;


END IF;

END IF;


END MBFSL_REPOROLOVER_SERIAL_NO;

