set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_REF_MODI_ISSUER_INS" 

   (M_ISSUER_CODE                 DN_REF_ISSUER_INST_TYPE.ISSUER_CODE%TYPE,
    M_INST_TYPE                   DN_REF_ISSUER_INST_TYPE.INST_TYPE%TYPE,

    M_LIABILITY_ISSUE             DN_REF_ISSUER_INST_TYPE.LIABILITY_ISSUE%TYPE,
    M_LIABILITY_ISSUE_PREM        DN_REF_ISSUER_INST_TYPE.LIABILITY_ISSUE_PREM%TYPE,

    M_LIABILITY_GUARANTEE         DN_REF_ISSUER_INST_TYPE.LIABILITY_GUARANTEE%TYPE,
    M_LIABILITY_GUARANTEE_PREM    DN_REF_ISSUER_INST_TYPE.LIABILITY_GUARANTEE_PREM%TYPE,

    M_LIABILITY_ENDOSE            DN_REF_ISSUER_INST_TYPE.LIABILITY_ENDOSE%TYPE,
    M_LIABILITY_ENDOSE_PREM       DN_REF_ISSUER_INST_TYPE.LIABILITY_ENDOSE_PREM%TYPE


   )
AS
M_COUNT INTEGER;
BEGIN

    /* PROCEDURE  -  TO INSERT ISSUER INSTRUMENT DETAILS
       SYSTEM     -  DEALNET
       CREATED BY -  CHARMINDA.
       CREATED ON -  15/06/1999 */

--RAISE_APPLICATION_ERROR(-20201,M_LIABILITY_ISSUE||' '||M_LIABILITY_ISSUE_PREM||' '||M_LIABILITY_GUARANTEE||' '||M_LIABILITY_GUARANTEE_PREM||' '||M_LIABILITY_ENDOSE||' '||M_LIABILITY_ENDOSE_PREM);

   SELECT COUNT(*) INTO M_COUNT
   FROM DN_REF_ISSUER_INST_TYPE
   WHERE ISSUER_CODE=M_ISSUER_CODE AND INST_TYPE=M_INST_TYPE;

   --RAISE_APPLICATION_ERROR(-20201,M_ROLE);

   IF M_COUNT>0 THEN

        DELETE DN_REF_ISSUER_INST_TYPE
        WHERE ISSUER_CODE=M_ISSUER_CODE AND INST_TYPE=M_INST_TYPE;
    END IF;

       UPDATE DN_REF_ISSUER_INST_TYPE SET
               LIABILITY_ISSUE=M_LIABILITY_ISSUE,
               LIABILITY_ISSUE_PREM=M_LIABILITY_ISSUE_PREM,
               LIABILITY_GUARANTEE=M_LIABILITY_GUARANTEE,
               LIABILITY_GUARANTEE_PREM=M_LIABILITY_GUARANTEE_PREM,
               LIABILITY_ENDOSE=M_LIABILITY_ENDOSE,
               LIABILITY_ENDOSE_PREM=M_LIABILITY_ENDOSE_PREM
       WHERE ISSUER_CODE=M_ISSUER_CODE AND INST_TYPE=M_INST_TYPE;

       IF SQL%NOTFOUND THEN

       INSERT INTO DN_REF_ISSUER_INST_TYPE
              (ISSUER_CODE,
               INST_TYPE,
               LIABILITY_ISSUE,
               LIABILITY_ISSUE_PREM,
               LIABILITY_GUARANTEE,
               LIABILITY_GUARANTEE_PREM,
               LIABILITY_ENDOSE,
               LIABILITY_ENDOSE_PREM

              )
        VALUES
              (M_ISSUER_CODE,
               M_INST_TYPE,
               M_LIABILITY_ISSUE,
               M_LIABILITY_ISSUE_PREM,
               M_LIABILITY_GUARANTEE,
               M_LIABILITY_GUARANTEE_PREM,
               M_LIABILITY_ENDOSE,
               M_LIABILITY_ENDOSE_PREM);
      END IF;

COMMIT;

END DN_REF_MODI_ISSUER_INS;

