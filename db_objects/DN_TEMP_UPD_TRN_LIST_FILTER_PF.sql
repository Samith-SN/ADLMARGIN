  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_TEMP_UPD_TRN_LIST_FILTER_PF" 
(
 M_USER_NAME         DN_TEMP_TRN_LIST_PF.USER_NAME%TYPE,
 M_TRN_TYPE          varchar  -- add by waruna 2010-19-16
/*, M_COUNT             NUMBER*/
)
AS
M_DEAL_NO              DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
M_SECURITY_CODE        DN_REF_SECURITY.SECURITY_CODE%TYPE;
M_ISSUER_CODE          DN_REF_SECURITY.ISSUER_CODE%TYPE;
M_GUARANTEE_CODE       DN_REF_SECURITY.GUARANTEE_CODE%TYPE;
M_INST_TYPE            DN_REF_SECURITY.INST_TYPE%TYPE;
M_CURR_CODE            DN_REF_SECURITY.CURR_CODE%TYPE;
M_DEAL_NUMBER          DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
M_PAR_VALUE            DN_REF_SECURITY.PAR_VALUE%TYPE;
M_S_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_B_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_B_PORT_CODE          DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
M_S_PORT_CODE          DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
M_SEC_COUNT            NUMBER;
M_BRO_COUNT            NUMBER;
M_COUNT                NUMBER;
MM_COUNT               NUMBER; 
M_PF_COUNT             NUMBER;
M_PF_ACOUNT            NUMBER;
M_ERROR_COUNT          NUMBER;
M_ERROR_STR            varchar2(1000);   
M_TEMP_MARGIN_CALL     DN_REF_PORTFOLIO.TEMP_MARGIN_CALL_STATUS%TYPE;
M_PORTFOLIO_CODE       DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
m_FACE_VAL number;
BEGIN

-- created by udara on21-09-2011

 -- CAREATED BY SVA ON 11-05-2005 TO UPDATE THE TEMP TABLE FROM EXCEL SHEET
 --DELETE DN_TEMP_TRN_UPLOAD_ERROR_LOG;
 --DELETE FROM   DN_TEMP_TRN_LIST_PF WHERE TRN_DATE is NULL;  -- add by waruna 2010-09-13
-- RAISE_APPLICATION_ERROR(-20201,'*****'||M_USER_NAME||'***');
 FOR X IN (SELECT TO_CHAR(TRN_DATE,'DD-MM-YYYY') TRN_DATE,
                  TRN_TIME,
                  DEAL_TYPE,
                  CONTRACT_NO,
                  REPLACE(EXT_SECURITY_CODE,' ','') EXT_SECURITY_CODE,
                  QTY,
                  PRICE,
                  INTERNAL_USER,
                  REF_NO,
                 LPAD(nvl(a.CLIENT_CDS,''),11,'0') CLIENT_CDS_no,-- CLIENT_CDS,--DECODE(DEAL_TYPE,'B',DN_GET_PORTFOLIO_CODE(CLIENT_CDS),BROKER) BUY,
                 a.CLIENT_CDS CLIENT_CDS_temp,
                  BROKER,--DECODE(DEAL_TYPE,'S',DN_GET_PORTFOLIO_CODE(CLIENT_CDS),BROKER) SEL,
                  SEC_FEE+CSE_FEE+CDS_FEE+CESS_FEE+BROKERAGE+GOVT_LEVY BROKERAGE,
                  ORDER_ID,
                  TO_CHAR(DN_FIN_BUYER_SETTLE_DATE(TO_CHAR(TRN_DATE,'DD-MM-YYYY'),'3'),'DD-MM-YYYY') BUY_SET,
                  TO_CHAR(DN_FIN_BUYER_SETTLE_DATE(TO_CHAR(TRN_DATE,'DD-MM-YYYY'),'3'),'DD-MM-YYYY') SEL_SET
           FROM   DN_TEMP_TRN_LIST_PF a
           WHERE  USER_NAME = M_USER_NAME
           --AND DEAL_TYPE=M_TRN_TYPE  --add by waruna 2010-09-15
           AND EXT_SECURITY_CODE IS NOT NULL ) LOOP
m_FACE_VAL:=0;
M_ERROR_COUNT:=0;
M_ERROR_STR:='';

--RAISE_APPLICATION_ERROR(-20201,'*****'||x.CLIENT_CDS||'***');
     SELECT COUNT(*)
     INTO   M_SEC_COUNT
     FROM   DN_REF_SECURITY
     WHERE  EXT_SECURITY_CODE = TRIM(X.EXT_SECURITY_CODE);
     
IF M_SEC_COUNT=0 THEN
M_ERROR_COUNT:=M_ERROR_COUNT+1;
M_ERROR_STR:=M_ERROR_STR||X.EXT_SECURITY_CODE||' Security code not Available ';
--RAISE_APPLICATION_ERROR(-20201,x.CLIENT_CDS_no);
--RAISE_APPLICATION_ERROR(-20201,'<B>***Following Security code Not Available Please Enter </B>:='||X.EXT_SECURITY_CODE);
ELSE
     SELECT SECURITY_CODE
     INTO   M_SECURITY_CODE
     FROM   DN_REF_SECURITY
     WHERE  EXT_SECURITY_CODE = TRIM(X.EXT_SECURITY_CODE);
     
END IF;

  SELECT COUNT(PORTFOLIO_CODE) 
  INTO   M_PF_COUNT
  FROM   DN_REF_PORTFOLIO A 
  WHERE  A.CDS_ACC_NO=x.CLIENT_CDS_no;--LPAD(X.CLIENT_CDS,11,'0');

IF M_PF_COUNT=0 then

     IF M_ERROR_COUNT >0 THEN
        M_ERROR_STR:=M_ERROR_STR||',';
     END IF;

M_ERROR_COUNT:=M_ERROR_COUNT+1;
M_ERROR_STR:=M_ERROR_STR||X.CLIENT_CDS_no||' CDS No. not Available  ';

elsif M_PF_COUNT>1 then
M_ERROR_COUNT:=M_ERROR_COUNT+1;
M_ERROR_STR:=M_ERROR_STR||X.CLIENT_CDS_no||' CDS No. Map to '||M_PF_COUNT||' Client Code';
ELSE 

  SELECT a.PORTFOLIO_CODE
  INTO   M_PORTFOLIO_CODE
  FROM   DN_REF_PORTFOLIO A 
  WHERE  nvl(A.CDS_ACC_NO,'')=x.CLIENT_CDS_no;--LPAD(nvl(X.CLIENT_CDS,''),11,'0'); 

END IF;



--add by waruna 2011-07-25---
  SELECT COUNT(PORTFOLIO_CODE) 
  INTO   M_PF_ACOUNT
  FROM   DN_REF_PORTFOLIO A 
  WHERE  A.CDS_ACC_NO=x.CLIENT_CDS_no and  a.active_status='Y';
  
IF M_PF_ACOUNT=0 then

      IF M_ERROR_COUNT >0 THEN
        M_ERROR_STR:=M_ERROR_STR||',';
     END IF;
M_ERROR_COUNT:=M_ERROR_COUNT+1;
M_ERROR_STR:=M_ERROR_STR||x.CLIENT_CDS_no||' Client not Active ';

END IF;
--end add by waruna 2011-07-25----

     SELECT COUNT(*)
     INTO   M_BRO_COUNT
     FROM   DN_REF_BROKER_MAP
     WHERE  BROKER_CODE = X.BROKER;
     
IF M_BRO_COUNT=0 then
--RAISE_APPLICATION_ERROR(-20201,'<B>***BROKER_MAP Not Available Please Enter </B>:='||X.BROKER);
     IF M_ERROR_COUNT >0 THEN
        M_ERROR_STR:=M_ERROR_STR||',';
     END IF;
M_ERROR_COUNT:=M_ERROR_COUNT+1;
M_ERROR_STR:=M_ERROR_STR||X.BROKER||' Broker Maping not Available ';
END IF;

     
   

  SELECT SUM(FACE_VAL) INTO M_FACE_VAL
  FROM DN_INV_OUTPS_DEAL_SERIAL_NO A 
  WHERE PORTFOLIO_CODE=M_PORTFOLIO_CODE 
  AND SECURITY_CODE=M_SECURITY_CODE 
  AND SERIAL_NO_STATUS='INV';

 
IF X.QTY>M_FACE_VAL and X.DEAL_TYPE='S'  THEN
--RAISE_APPLICATION_ERROR(-20201,'<B>***BROKER_MAP Not Available Please Enter </B>:='||X.BROKER);
     IF M_ERROR_COUNT >0 THEN
        M_ERROR_STR:=M_ERROR_STR||',';
     END IF;
M_ERROR_COUNT:=M_ERROR_COUNT+1;
M_ERROR_STR:=M_ERROR_STR||' Inventory not Available ';
END IF;
-------------------------------------------------------------

--RAISE_APPLICATION_ERROR(-20201,'*****'||M_PF_COUNT||'***'||M_ERROR_COUNT||M_ERROR_STR);
if M_ERROR_COUNT>0 then
  INSERT INTO  DN_TEMP_TRN_LIST_FAIL_PF( TRN_DATE, TRN_TIME, DEAL_TYPE, CONTRACT_NO,
          EXT_SECURITY_CODE, QTY, PRICE, INTERNAL_USER, REF_NO,
          CLIENT_CDS, BROKER, SEC_FEE, CSE_FEE, CDS_FEE,
          CESS_FEE, BROKERAGE, ORDER_ID, USER_NAME, STATUS,
          GOVT_LEVY,REJ_STATUS)(
  SELECT  TRN_DATE, TRN_TIME, DEAL_TYPE, CONTRACT_NO,
          EXT_SECURITY_CODE, QTY, PRICE, INTERNAL_USER, REF_NO,
          CLIENT_CDS, BROKER, SEC_FEE, CSE_FEE, CDS_FEE,
          CESS_FEE, BROKERAGE, ORDER_ID, USER_NAME, STATUS,
          GOVT_LEVY,M_ERROR_STR
   FROM DN_TEMP_TRN_LIST_PF
   WHERE REF_NO=X.REF_NO 
   AND CLIENT_CDS=X.CLIENT_CDS_temp 
   AND DEAL_TYPE=X.DEAL_TYPE
   AND USER_NAME=M_USER_NAME);


Delete FROM DN_TEMP_TRN_LIST_PF 
WHERE REF_NO=X.REF_NO 
AND CLIENT_CDS=X.CLIENT_CDS_temp
AND DEAL_TYPE=X.DEAL_TYPE 
AND USER_NAME=M_USER_NAME;
  end if;

 SELECT COUNT(*)
     INTO   MM_COUNT
     FROM   DN_TRN_OUTP_SALE
     WHERE  CONTRACT_NO = TO_CHAR(X.REF_NO) AND APP_STATUS<>'CANCEL' AND
      BUY_PORTFOLIO_CODE=M_B_PORT_CODE AND SELL_PORTFOLIO_CODE=M_S_PORT_CODE AND --add by waruna Sri JAyanath
     --TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(X.TRN_DATE,'DD-MM-YYYY'); comment and mod by waruna 2011-02-03
     EFF_VALDATE=TO_DATE(X.TRN_DATE,'DD-MM-YYYY');
   Delete FROM   DN_TEMP_TRN_LIST_PF
   WHERE  USER_NAME = M_USER_NAME  --AND DEAL_TYPE=M_TRN_TYPE 
   AND REF_NO=X.REF_NO 
   AND BROKER=X.BROKER
   AND (MM_COUNT)>0;


--RAISE_APPLICATION_ERROR(-20001,'M_USER_NAME'||M_USER_NAME||'Count'||MM_COUNT);

-----------------------------------------------------------

 END LOOP;
 ---dont use delete bellow
 --Delete FROM   DN_TEMP_TRN_LIST_PF WHERE  USER_NAME = M_USER_NAME  AND DEAL_TYPE=M_TRN_TYPE ;--add by waruna 2010-09-15
