--  DDL for Function FN_CHK_STAT
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."FN_CHK_STAT" 
(
M_DEAL             DN_TRN_REPO_FRESH.GROUP_DEALNO%TYPE,
M_STAT             VARCHAR2 ,
M_TABLE            VARCHAR2
)
RETURN  VARCHAR2
IS
M_RET_STAT     VARCHAR2(1):='N';
M_STAT_COUNT   NUMBER;
M_STAT_ST       VARCHAR2(6);

BEGIN
IF (M_TABLE='O')THEN

SELECT COUNT(*)
INTO   M_STAT_COUNT
FROM
   (SELECT   APP_STATUS
    FROM     DN_TRN_OUTP_SALE
    WHERE    GROUP_DEALNO=M_DEAL  AND APP_STATUS=M_STAT
    GROUP BY APP_STATUS);

IF M_STAT_COUNT=1 THEN

    SELECT   APP_STATUS
    INTO     M_STAT_ST
    FROM     DN_TRN_OUTP_SALE
    WHERE    GROUP_DEALNO=M_DEAL AND APP_STATUS=M_STAT
    GROUP BY APP_STATUS;

  IF(M_STAT_ST=M_STAT)THEN
    M_RET_STAT:='Y';
  ELSE
    M_RET_STAT:='N';
  END IF;
END IF;
ELSIF (M_TABLE='F')THEN

SELECT COUNT(*)
INTO   M_STAT_COUNT
FROM
   (SELECT   APP_STATUS
    FROM     DN_TRN_REPO_FRESH
    WHERE    GROUP_DEALNO=M_DEAL     AND APP_STATUS=M_STAT
    GROUP BY APP_STATUS);

IF M_STAT_COUNT=1 THEN

    SELECT   APP_STATUS
    INTO     M_STAT_ST
    FROM     DN_TRN_REPO_FRESH
    WHERE    GROUP_DEALNO=M_DEAL AND APP_STATUS=M_STAT
    GROUP BY APP_STATUS;

  IF(M_STAT_ST=M_STAT)THEN
    M_RET_STAT:='Y';
  ELSE
    M_RET_STAT:='N';
  END IF;
END IF;

ELSIF (M_TABLE='R')THEN

SELECT COUNT(*)
INTO   M_STAT_COUNT
FROM
   (SELECT   APP_STATUS
    FROM     DN_TRN_REPO_ROLLOVER
    WHERE    GROUP_DEALNO=M_DEAL   AND APP_STATUS=M_STAT
    GROUP BY APP_STATUS);

IF M_STAT_COUNT=1 THEN

    SELECT   APP_STATUS
    INTO     M_STAT_ST
    FROM     DN_TRN_REPO_ROLLOVER
    WHERE    GROUP_DEALNO=M_DEAL AND APP_STATUS=M_STAT
    GROUP BY APP_STATUS;

  IF(M_STAT_ST=M_STAT)THEN
    M_RET_STAT:='Y';
  ELSE
    M_RET_STAT:='N';
  END IF;
END IF;

ELSIF (M_TABLE='S')THEN
SELECT COUNT(*)
INTO   M_STAT_COUNT
FROM
   (SELECT   APP_STATUS
    FROM     DN_TRN_REPO_SETTLEMENT
    WHERE    GROUP_DEALNO=M_DEAL  AND APP_STATUS=M_STAT
    GROUP BY APP_STATUS);

IF M_STAT_COUNT=1 THEN

    SELECT   APP_STATUS
    INTO     M_STAT_ST
    FROM     DN_TRN_REPO_SETTLEMENT
    WHERE    GROUP_DEALNO=M_DEAL AND APP_STATUS=M_STAT
    GROUP BY APP_STATUS;

  IF(M_STAT_ST=M_STAT)THEN
    M_RET_STAT:='Y';
  ELSE
    M_RET_STAT:='N';
  END IF;
END IF;



END IF;

RETURN M_RET_STAT;
END FN_CHK_STAT;

