set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_LINK_OUTPS_FO_SETT" 
   (
    M_DEAL_NO      DN_TRN_OUTP_SALE.DEAL_NO%TYPE,
    M_FACE_VALUE   DN_TRN_OUTP_SALE.FACE_VALUE%TYPE
   )

   IS

    -- Procedue     : Link outright Settlements to the accounting at the confiremation
    -- System       : Dealnet system
    -- Created by   : D.P. Pubudu Thushara
    -- Created on   : 15/08/1999

    M_BUY_PORTFOLIO_CODE      DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE;
    M_SELL_PORTFOLIO_CODE     DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE;
    M_EFF_VALDATE             DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE;
    M_BUY_PF_TYPE             DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_BUY_OWNED_BY_MBFSL      DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;
    M_SELL_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_SELL_OWNED_BY_MBFSL     DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;

BEGIN

   SELECT
      A.BUY_PORTFOLIO_CODE,
      A.SELL_PORTFOLIO_CODE,
      B.PF_TYPE,
      B.OWNED_BY_MBFSL,
      C.PF_TYPE,
      C.OWNED_BY_MBFSL,
      A.EFF_VALDATE
      INTO  M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,
            M_BUY_PF_TYPE,M_BUY_OWNED_BY_MBFSL,M_SELL_PF_TYPE,M_SELL_OWNED_BY_MBFSL,
            M_EFF_VALDATE
   FROM
      DN_TRN_OUTP_SALE A,
      DN_REF_PORTFOLIO B,
      DN_REF_PORTFOLIO C
   WHERE
      A.DEAL_NO=M_DEAL_NO
      AND
      A.BUY_PORTFOLIO_CODE=B.PORTFOLIO_CODE
      AND
      A.SELL_PORTFOLIO_CODE=C.PORTFOLIO_CODE;

  IF M_BUY_OWNED_BY_MBFSL='Y' AND   M_SELL_PF_TYPE='C' THEN

     DN_ACC_A_2_1_X(M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,M_EFF_VALDATE,M_FACE_VALUE,M_DEAL_NO);

  ELSIF M_BUY_PF_TYPE='C' AND M_SELL_OWNED_BY_MBFSL='Y' THEN

     DN_ACC_A_2_8_X(M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,M_EFF_VALDATE,M_FACE_VALUE,M_DEAL_NO);

  ELSIF M_BUY_PF_TYPE='P' AND M_BUY_OWNED_BY_MBFSL='N' AND M_SELL_PF_TYPE='C' THEN

     DN_ACC_B_2_1_X(M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,M_EFF_VALDATE,M_FACE_VALUE,M_DEAL_NO);

  ELSIF M_BUY_PF_TYPE='C' AND M_SELL_PF_TYPE='P' AND M_SELL_OWNED_BY_MBFSL='N' THEN

     DN_ACC_B_2_11_X(M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,M_EFF_VALDATE,M_FACE_VALUE,M_DEAL_NO);

  ELSIF M_BUY_PF_TYPE='P' AND M_BUY_OWNED_BY_MBFSL='N' AND  M_SELL_OWNED_BY_MBFSL='Y' THEN

     DN_ACC_A_2_8_X(M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,M_EFF_VALDATE,M_FACE_VALUE,M_DEAL_NO);

  ELSIF M_BUY_OWNED_BY_MBFSL='Y' AND   M_SELL_PF_TYPE='P' AND M_SELL_OWNED_BY_MBFSL='N' THEN

     DN_ACC_B_2_1_X(M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,M_EFF_VALDATE,M_FACE_VALUE,M_DEAL_NO);

  ELSIF M_BUY_OWNED_BY_MBFSL='Y' AND   M_SELL_OWNED_BY_MBFSL='Y' THEN

     DN_ACC_A_2_1_X(M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,M_EFF_VALDATE,M_FACE_VALUE,M_DEAL_NO);
     DN_ACC_A_2_8_X(M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,M_EFF_VALDATE,M_FACE_VALUE,M_DEAL_NO);

  ELSIF M_BUY_PF_TYPE='P' AND M_BUY_OWNED_BY_MBFSL='N' AND  M_SELL_PF_TYPE='P' AND M_SELL_OWNED_BY_MBFSL='N' THEN

     DN_ACC_B_2_1_X(M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,M_EFF_VALDATE,M_FACE_VALUE,M_DEAL_NO);
     DN_ACC_B_2_11_X(M_BUY_PORTFOLIO_CODE,M_SELL_PORTFOLIO_CODE,M_EFF_VALDATE,M_FACE_VALUE,M_DEAL_NO);

  END IF;


END DN_ACC_LINK_OUTPS_FO_SETT;

