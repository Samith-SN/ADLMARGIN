  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_MARGIN_FACTOR_NOW" 
(
  M_PORTFOLIO_CODE IN DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE,
  M_DATE              VARCHAR2
 )
  RETURN NUMBER IS

  M_MARGIN_FACTOR            NUMBER;
  M_COUNT                    NUMBER;

BEGIN
-- create by waruna to get current margin 
--RAISE_APPLICATION_ERROR(-20201,'M_PORTFOLIO_CODE=' || M_PORTFOLIO_CODE || '  M_DATE=' || M_DATE || '  M_AMOUNT=' || M_AMOUNT);

 SELECT COUNT(*)
 INTO   M_COUNT
 FROM   DN_REP_MARGIN_CALL
 WHERE  TRN_DATE       = TO_DATE(M_DATE,'DD-MM-YYYY')-1 AND
        PORTFOLIO_CODE = M_PORTFOLIO_CODE;

 IF M_COUNT>0 THEN
 SELECT SUM(FACE_VAL*MARKET_RATE)
 INTO   M_MARGIN_FACTOR
 FROM   DN_REP_MARGIN_CALL
 WHERE  TRN_DATE       = TO_DATE(M_DATE,'DD-MM-YYYY')-1 AND
        PORTFOLIO_CODE = M_PORTFOLIO_CODE;


 IF M_MARGIN_FACTOR =0 THEN
 M_MARGIN_FACTOR:=0;
 ELSE
 /*
 SELECT DISTINCT ((REPO_LEG2NET_CASHFLOWSINT_AMOUNT)/M_MARGIN_FACTOR)*100
 INTO   M_MARGIN_FACTOR
 FROM   DN_REP_MARGIN_CALL
 WHERE  TRN_DATE       = TO_DATE(M_DATE,'DD-MM-YYYY')-1 AND
        PORTFOLIO_CODE = M_PORTFOLIO_CODE AND ROWNUM=1;
*/


                        SELECT  decode(	SUM(NVL(A.FACE_VAL,0)* NVL(A.MARKET_RATE,0)),0,0,  A.REPO_LEG2/ SUM(NVL(A.FACE_VAL,0)* NVL(A.MARKET_RATE,0))    )
			         	INTO   M_MARGIN_FACTOR
                	--	A.REPO_LEG2,  --5
					--	A.DIFFERENCE,  --6
					--	A.NET_CASHFLOWS, --7
					--	SUM(NVL(A.FACE_VAL,0)* NVL(A.MARKET_RATE,0)) --8
						 
						FROM DN_TEMP_MARGIN_CALL A,  DN_REF_PORTFOLIO B 
						WHERE 
						A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
						AND A.PORTFOLIO_CODE = B.PORTFOLIO_CODE 
						GROUP BY A.REPO_LEG2,A.DIFFERENCE,A.NET_CASHFLOWS;
						 
						 


 END IF;
 ELSE
    M_MARGIN_FACTOR:=0;
 END IF;

 RETURN M_MARGIN_FACTOR;

/*EXCEPTION
   WHEN OTHERS THEN
       RAISE_APPLICATION_ERROR(-20001,*/
END; -- Function WD_GET_PORTFOLIO_NAME

