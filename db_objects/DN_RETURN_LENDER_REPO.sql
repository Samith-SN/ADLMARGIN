--------------------------------------------------------
--  DDL for Function DN_RETURN_LENDER_REPO
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_RETURN_LENDER_REPO" 
(
  M_DEAL_NO   DN_INV_REPO_DEAL_SERIAL_NO.DEAL_NO%TYPE,
   M_SERIAL_NO   DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_NO%TYPE
 )RETURN VARCHAR2


AS
  M_LENDER VARCHAR2(20);
  MDEALNO DN_INV_REPO_DEAL_SERIAL_NO.DEAL_NO%TYPE;
  MENDDATE DN_INV_REPO_DEAL_SERIAL_NO.DEAL_NO%TYPE;
  MCNT NUMBER ;

BEGIN

 SELECT COUNT(*) INTO MCNT FROM DN_INV_REPO_DEAL_SERIAL_NO A, DN_INV_REPO_DEAL_SERNO_ALLO B
 WHERE A.DEAL_NO=M_DEAL_NO  AND A.SERIAL_NO=B.SERIAL_NO AND
 A.SERIAL_NO=M_SERIAL_NO AND A.DEAL_NO=B.PREV_DEAL_NO AND A.PORTFOLIO_CODE=B.PORTFOLIO_CODE
 AND A.SECURITY_CODE =B.SECURITY_CODE AND A.SERIAL_NO =B.SERIAL_NO AND A.INST_TYPE=B.INST_TYPE
 AND B.END_DATE > SYSDATE  ;

 IF MCNT > 0 THEN

 SELECT B.DEAL_NO,MAX(B.END_DATE) INTO MDEALNO ,MENDDATE FROM DN_INV_REPO_DEAL_SERIAL_NO A, DN_INV_REPO_DEAL_SERNO_ALLO B
 WHERE A.DEAL_NO=M_DEAL_NO  AND A.SERIAL_NO=B.SERIAL_NO AND
 A.SERIAL_NO=M_SERIAL_NO AND A.DEAL_NO=B.PREV_DEAL_NO AND A.PORTFOLIO_CODE=B.PORTFOLIO_CODE
 AND A.SECURITY_CODE =B.SECURITY_CODE AND A.SERIAL_NO =B.SERIAL_NO AND A.INST_TYPE=B.INST_TYPE
 AND B.END_DATE > SYSDATE  GROUP BY B.DEAL_NO ;

  -- SELECTING THE LENDER CODE FOR REPO FRESH DEALS
 IF  SUBSTR(MDEALNO,1,2)='RF' THEN
 SELECT LEND_PORTFOLIO_CODE
 INTO M_LENDER
 FROM DN_TRN_REPO_FRESH
 WHERE DEAL_NO=MDEALNO;

  -- SELECTING THE LENDER CODE FOR RR
 ELSIF SUBSTR(MDEALNO,1,2)='RR' THEN
 SELECT LEND_PORTFOLIO_CODE
 INTO M_LENDER
 FROM DN_TRN_REPO_ROLLOVER
 WHERE DEAL_NO=MDEALNO;

 END IF ;


 ELSE

 M_LENDER := '';

 END IF;

 RETURN M_LENDER;

END DN_RETURN_LENDER_REPO;


-- End of DDL script for DN_RETURN_LENDER_REPO

