set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_OUTRIGHT_IN_NEW2" 
(
    M_DEAL_NO  		        DN_TRN_OUTP_SALE.DEAL_NO%TYPE,--DEAL NO
    M_SETTLE                DN_TRN_OUTP_SALE_SETTLE.SETTLE_MODE%TYPE,--SETTLE MODE
    M_BACC                  DN_TRN_OUTP_SALE_SETTLE.BUY_ACC_NO%TYPE,--BUY ACC NO
    M_SACC                  DN_TRN_OUTP_SALE_SETTLE.SELL_ACC_NO%TYPE,--SELLER ACC NO
    M_BUY_COMMENT           DN_TRN_OUTP_SALE_SETTLE.BUY_SETTLE_COMMENT%TYPE,
    M_SEL_COMMENT           DN_TRN_OUTP_SALE_SETTLE.SELL_SETTLE_COMMENT%TYPE,
    M_BUY_PORTFOLIO_CODE    DN_REF_PORTF_SETTLEMENT.PORTFOLIO_CODE%TYPE,
    M_SELL_PORTFOLIO_CODE   DN_REF_PORTF_SETTLEMENT.PORTFOLIO_CODE%TYPE
)

AS

M_SETAMO  DN_TRN_OUTP_SALE_SETTLE.SETTLE_AMOUNT%TYPE;--SETTLE AMOUNT

BEGIN

 -- PROCEDURE  -  TO INSERT VALUES INTO OUTP_SETTLE TABLE FROM OUTRUGHT NEW SCREEN
 -- CREATED ON -  2004-11-4 10:48AM
 -- SYSTEM     -  FCLMGT
 -- INDITHA


SELECT SETTLE_VALUE INTO M_SETAMO FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;--GET SETTLE AMOUNT

IF M_DEAL_NO IS NOT NULL THEN

  INSERT INTO DN_TRN_OUTP_SALE_SETTLE
  (
    DEAL_NO,
    SETTLE_MODE,
    SETTLE_AMOUNT,
    BUY_PORTFOLIO_CODE,
    BUY_ACC_NO,
    BUY_SETTLE_COMMENT,
    SELL_PORTFOLIO_CODE,
    SELL_ACC_NO,
    SELL_SETTLE_COMMENT
  )
  VALUES
  (
    M_DEAL_NO,
    M_SETTLE,
    M_SETAMO,
    M_BUY_PORTFOLIO_CODE,
    M_BACC,
    M_BUY_COMMENT,
    M_SELL_PORTFOLIO_CODE,
    M_SACC,
    M_SEL_COMMENT
   );

END IF;

--------EXCEPTION
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE_APPLICATION_ERROR(-20201,SQLCODE||SQLERRM);

END MBFSL_OUTRIGHT_IN_NEW2;

