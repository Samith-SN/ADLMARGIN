  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_F_4" 
(
M_INVOICE_NO        DN_TRN_BROKERAGE.INVOICE_NO%TYPE,
M_DOCREFNO          DN_TRN_BROKERAGE.DEAL_NO%TYPE,
M_PORTF_CODE        DN_TRN_BROKERAGE.BROK_CODE%TYPE,
M_DN_PORTF_CODE     DN_TRN_BROKERAGE.CP_CODE%TYPE,
M_TRNAMOUNT         DN_TRN_BROKERAGE.BROK_FEE_AMOUNT%TYPE,
M_TRNAMOUNT2        DN_TRN_BROKERAGE.BROK_GST%TYPE
)
AS

/* PROCEDURE  - F_4 BROKERAGE EXPENSE OF FCAM WHEN SELLING A SECURITY
   SYSTEM     - DEALNET
   CREATED BY - SUKATHISVARAN
   CREATED ON - 09/AUGUEST/1999

   MODIFIED BY- LATHIKA
   MODIFIED ON- 29/DEC/1999 */


M_TRNDATE         DN_TRN_BL_FUND.eff_valdate%TYPE;
M_TRNDATE2        DN_TRN_BL_FUND.eff_valdate%TYPE;

M_INST_TYPE       DN_TRN_OUTP_SALE.inst_type%TYPE;
M_INST_TYPE2      DN_TRN_OUTP_SALE.inst_type%TYPE;
M_OWNER           DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;
M_SELL_PORTFOLIO_CODE  DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE;


BEGIN
 --RAISE_APPLICATION_ERROR(-20201,M_DOCREFNO||' '||M_PORTF_CODE||'  '||M_DN_PORTF_CODE);

 M_SELL_PORTFOLIO_CODE :=M_PORTF_CODE;
IF SUBSTR(M_DOCREFNO,1,2)='OR' THEN
    SELECT EFF_VALDATE,inst_type
    INTO M_TRNDATE,M_INST_TYPE
    FROM DN_TRN_OUTP_SALE
    WHERE DEAL_NO=M_DOCREFNO;

ELSIF SUBSTR(M_DOCREFNO,1,2)='SO' THEN
    SELECT P1_EFF_VALDATE,P2_EFF_VALDATE,p1_inst_type,p2_inst_type
    INTO M_TRNDATE,M_TRNDATE2,M_INST_TYPE,M_INST_TYPE2
    FROM DN_TRN_SWAP_OUTRIGHT
    WHERE DEAL_NO=M_DOCREFNO;

END IF;


IF (SUBSTR(M_DOCREFNO,1,2)='OR')  THEN
--------RECORDING BROKERAGE RECEIVABLE-----------------------
INSERT INTO DN_ACC_LICENCEE_INST_ACCOUNT
   (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_SELL_PORTFOLIO_CODE,M_INST_TYPE,M_TRNDATE,'103','DR',M_TRNAMOUNT,M_INVOICE_NO,'BROK PAYABLE -SALE OF SEC','302');

INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_SELL_PORTFOLIO_CODE,M_DN_PORTF_CODE,M_TRNDATE,'302','CR',M_TRNAMOUNT,M_INVOICE_NO,'BROK PAYABLE -PURCHASE OF SEC','103');

INSERT INTO DN_ACC_COUNTP_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_SELL_PORTFOLIO_CODE,M_DN_PORTF_CODE,M_TRNDATE,'302','CR',M_TRNAMOUNT,M_INVOICE_NO,'BROK PAYABLE -PURCHASE OF SEC','103');

-------RECORDING GST RECEIVABLE-------------------------------------
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_SELL_PORTFOLIO_CODE,M_DN_PORTF_CODE,M_TRNDATE,'501','DR',M_TRNAMOUNT2,M_INVOICE_NO,'VAT PAYABLE -PURCHASE OF SEC','302');

INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_SELL_PORTFOLIO_CODE,M_DN_PORTF_CODE,M_TRNDATE,'302','CR',M_TRNAMOUNT2,M_INVOICE_NO,'VAT PAYABLE -PURCHASE OF SEC','501');

INSERT INTO DN_ACC_COUNTP_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_SELL_PORTFOLIO_CODE,M_DN_PORTF_CODE,M_TRNDATE,'302','CR',M_TRNAMOUNT2,M_INVOICE_NO,'VAT PAYABLE -PURCHASE OF SEC','501');

END IF;

END DN_ACC_F_4;

