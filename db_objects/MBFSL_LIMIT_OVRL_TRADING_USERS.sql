--DELETING EXISTING RECORDS
 IF(M_IDENTITY='CLEAN') THEN
  DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '01-%';
 END IF;

--INSERTING AUTHORITY USERS TO LMT_STR_AUTHORITY TABLE

     INSERT INTO LMT_STR_AUTHORITY
         (LIMIT_CODE,
          DN_USER,
