  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_LIMIT_OVRL_TRADING_USERS" 

   ( M_LIMIT_CODE        LMT_STR_AUTHORITY.LIMIT_CODE%TYPE,
     M_USER              LMT_STR_AUTHORITY.DN_USER%TYPE,
     M_LIMIT_LEVEL       LMT_STR_AUTHORITY.LIMIT_LEVEL%TYPE,
     M_IDENTITY          CHAR
   )
AS




BEGIN
--RAISE_APPLICATION_ERROR(-20201,M_LIMIT_CODE ||' '||M_USER||' '||M_LIMIT_LEVEL||' '||M_IDENTITY);

    /* PROCEDURE  -  OVERALL TRADING
       SYSTEM     -  DEALNT
