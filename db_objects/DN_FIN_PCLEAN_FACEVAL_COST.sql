  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_FIN_PCLEAN_FACEVAL_COST" 
   (
    M_SECURITY_CODE               DN_TRN_OUTP_SALE.SECURITY_CODE%TYPE,
    M_COST                        DN_TRN_OUTP_SALE.PRICE_CLEAN%TYPE,
    M_EFF_VALDATE_TYPE            VARCHAR2,
    M_FACE_VALUE                  DN_TRN_OUTP_SALE.FACE_VALUE%TYPE
   )RETURN  VARCHAR2
   IS


    -- Proceudre    : PASS COST,FACE VALUE AND GET THE PRICE CLEAN VALUE
    -- System       : DEALNET System
    -- Created by   : NIRMALA
    -- Created on   : 30/06/2003
   M_PRICE_CLEAN                VARCHAR2(20);
   M_ISSUE_DATE                 DN_REF_SECURITY.ISSUE_DATE%TYPE;
   M_COUPON_INT                 DN_REF_SECURITY.COUPON_INT%TYPE;
   M_ADJ_EST1_YIELD             NUMBER;
   M_NO_DAYS_INT_ACCRUAL        NUMBER;
   M_INT_ADJ                    NUMBER;
   M_BOND_FACE_VALUE            NUMBER;
   M_NO_DAYS_P_ANN              NUMBER;
   M_NEXT_COUPON_DATE           DN_REF_SECURITY.MATURITY_DATE%TYPE;
   M_LAST_COUPON_DATE           DN_REF_SECURITY.MATURITY_DATE%TYPE;
   M_EFF_VALDATE                DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE;

BEGIN

   SELECT TO_DATE(M_EFF_VALDATE_TYPE,'DD/MM/YYYY')
   INTO   M_EFF_VALDATE
   FROM   DUAL;

   M_BOND_FACE_VALUE:=100.00;  -- Allways bond face value is this

   SELECT ISSUE_DATE,COUPON_INT
   INTO   M_ISSUE_DATE,M_COUPON_INT
   FROM   DN_REF_SECURITY
   WHERE  SECURITY_CODE=M_SECURITY_CODE;

   SELECT   COUNT(SECURITY_CODE)
   INTO     M_NO_DAYS_P_ANN
   FROM     DN_REF_SECURITY_INT_PAY_DATES
   WHERE    SECURITY_CODE=M_SECURITY_CODE  AND
            INT_PAY_DATE>=M_ISSUE_DATE   AND
            INT_PAY_DATE<=ADD_MONTHS(M_ISSUE_DATE,12);

 -- Next coupon date

  SELECT   MIN(INT_PAY_DATE)
  INTO     M_NEXT_COUPON_DATE
  FROM     DN_REF_SECURITY_INT_PAY_DATES
  WHERE    SECURITY_CODE=M_SECURITY_CODE    AND
           INT_PAY_DATE>=M_EFF_VALDATE;

-- Last coupon date

  SELECT   MAX(INT_PAY_DATE)
  INTO     M_LAST_COUPON_DATE
  FROM     DN_REF_SECURITY_INT_PAY_DATES
  WHERE    SECURITY_CODE=M_SECURITY_CODE    AND
           INT_PAY_DATE<M_EFF_VALDATE;

  IF M_LAST_COUPON_DATE IS NULL THEN
     ---Which is higher
    M_LAST_COUPON_DATE:=M_ISSUE_DATE;
  END IF;

  -- Interest accural
  IF M_EFF_VALDATE>M_ISSUE_DATE THEN
       M_NO_DAYS_INT_ACCRUAL:=M_EFF_VALDATE-M_LAST_COUPON_DATE;
       M_INT_ADJ:=ROUND((((M_BOND_FACE_VALUE*M_COUPON_INT)/M_NO_DAYS_P_ANN)/(M_NEXT_COUPON_DATE-M_LAST_COUPON_DATE)*M_NO_DAYS_INT_ACCRUAL),4);
  ELSE
       M_INT_ADJ:=0;
  END IF;


M_PRICE_CLEAN :=  --TO_CHAR(
                     ROUND(
                      ((M_COST*M_BOND_FACE_VALUE)/M_FACE_VALUE)
                       ,4);
                       --,'FM999G999G999G999G990D0000');
RETURN M_PRICE_CLEAN;

END DN_FIN_PCLEAN_FACEVAL_COST;

