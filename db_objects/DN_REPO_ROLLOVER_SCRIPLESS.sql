set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_REPO_ROLLOVER_SCRIPLESS" 
(
 M_DEAL_NO         DN_TRN_REPO_ROLLOVER.DEAL_NO%TYPE,
 M_USER            DN_TRN_REPO_ROLLOVER.DN_USER%TYPE
)
AS

    M_COUNT_LEND            INTEGER;
    M_COUNT_BORR            INTEGER;
    M_BORR_PORTFOLIO_CODE   DN_TRN_REPO_ROLLOVER.BORR_PORTFOLIO_CODE%TYPE;
    M_LEND_PORTFOLIO_CODE   DN_TRN_REPO_ROLLOVER.LEND_PORTFOLIO_CODE%TYPE;

BEGIN

             --CREATED BY  : NIRMALA FERNANDO.
             --CREATED ON  : 11-10-2001
             --SYSTEM      : DEALNET(MBFSL)
             --PROCEDURE   : SCRIPLESS SYSTEM REPO ROLLOVER PROCEDURE



  SELECT  BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE
  INTO    M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE
  FROM    DN_TRN_REPO_ROLLOVER
  WHERE   DEAL_NO=M_DEAL_NO ;


  SELECT  COUNT(*)
  INTO    M_COUNT_LEND
  FROM    DN_REF_PORTFOLIO
  WHERE   PORTFOLIO_CODE=M_LEND_PORTFOLIO_CODE AND
          PF_TYPE='P' ;


  SELECT  COUNT(*)
  INTO    M_COUNT_BORR
  FROM    DN_REF_PORTFOLIO
  WHERE   PORTFOLIO_CODE=M_BORR_PORTFOLIO_CODE AND
          PF_TYPE='P' ;


  IF(M_COUNT_LEND>0)THEN


     DN_REPOROLL_LEND_SCRIPLESS(M_DEAL_NO);
  END IF;

  IF(M_COUNT_BORR>0)THEN
     DN_REPOROLL_BORR_SCRIPLESS(M_DEAL_NO,M_USER);
  END IF;












END DN_REPO_ROLLOVER_SCRIPLESS;

/
