set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_SECURITY_MAPPING" 
   (
    M_SECURITY_CODE     DN_REF_SECURITY_SHARE_NAME.SECURITY_CODE%TYPE,
    M_SECURITY_NAME     DN_REF_SECURITY_SHARE_NAME.SECURITY_NAME%TYPE,
    M_USER_NAME         DN_REF_SECURITY_SHARE_NAME.USER_NAME%TYPE,
    M_SCREAN_NAME       VARCHAR2
   )
   IS
    -- Procedue     : Trigger
    -- Created by   : SVA
    -- Created on   : 22-02-2005

   --M_INT_DATE       DN_REF_SECURITY_INT_PAY_DATES.INT_PAY_DATE%TYPE;
   --M_MATURITY_DATE  DN_REF_SECURITY.MATURITY_DATE%TYPE;
   M_COUNT1            NUMBER;

BEGIN

 SELECT COUNT(*) --SECURITY_CODE,SECURITY_NAME,USER_NAME,ENT_DATE
 INTO   M_COUNT1
 FROM   DN_REF_SECURITY_SHARE_NAME
 WHERE  SECURITY_CODE = UPPER(M_SECURITY_CODE);

 IF M_COUNT1>0 THEN
  IF M_SECURITY_NAME IS NOT NULL THEN

    UPDATE DN_REF_SECURITY_SHARE_NAME
    SET    SECURITY_NAME      = M_SECURITY_NAME,
           USER_NAME          = M_USER_NAME,
           ENT_DATE           = SYSDATE
    WHERE  SECURITY_CODE      = UPPER(M_SECURITY_CODE);
  ELSE

    DELETE DN_REF_SECURITY_SHARE_NAME
    WHERE  SECURITY_CODE      = UPPER(M_SECURITY_CODE);

  END IF;
 ELSE
  IF M_SECURITY_NAME IS NOT NULL THEN
   INSERT INTO DN_REF_SECURITY_SHARE_NAME(SECURITY_CODE,SECURITY_NAME,USER_NAME,ENT_DATE)
   VALUES(M_SECURITY_CODE,UPPER(M_SECURITY_NAME),M_USER_NAME,SYSDATE);
  END IF;
 END IF;

 COMMIT;

EXCEPTION
  WHEN OTHERS THEN

RAISE_APPLICATION_ERROR(-20001,'M_SECURITY_CODE-'||M_SECURITY_CODE||'- M_SECURITY_NAME-'||M_SECURITY_NAME);

END DN_SECURITY_MAPPING;

/
