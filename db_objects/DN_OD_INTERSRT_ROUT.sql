set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_OD_INTERSRT_ROUT" 
(
 M_PROCESS_DATE    DN_SYS_PARAMETER.LAST_DAILY%TYPE
)

   -- Procedure    : OD Calculate interest 
   -- System       : Dealnet system
   -- Created by   : K.M.Waruna Sri Jayanath
   -- Created on   : 04/01/2012
   -- Modified By  : K.M.Waruna Sri Jayanath
   -- Modified on  : 04/01/2012

  AS
  

M_DOCREFNO         DN_TRN_PORTF_OD_INTEREST.DOCREFNO%TYPE;
M_OD_INT_AMOUNT      NUMBER(18,4);     

CURSOR M_CURSOR IS     

                SELECT PORTFOLIO_CODE,SEC_LIMIT,PORT_LIMIT,REPO_LEG2,DIFFERENCE,OD_AMOUNT,OVER_PAID_INT_RATE FROM(
                
                SELECT A.PORTFOLIO_CODE, SUM(NVL(A.SEC_LIMIT,0)) SEC_LIMIT ,A.PORT_LIMIT, A.REPO_LEG2 , 
                (A.REPO_LEG2- LEAST(A.PORT_LIMIT,SUM(NVL(A.SEC_LIMIT,0)))) "DIFFERENCE",
                CASE WHEN A.REPO_LEG2- LEAST(A.PORT_LIMIT,SUM(NVL(A.SEC_LIMIT,0))) > 0 THEN 
                A.REPO_LEG2- LEAST(A.PORT_LIMIT,SUM(NVL(A.SEC_LIMIT,0)) )
                ELSE 0
                END AS "OD_AMOUNT",
                NVL(B.OVER_PAID_INT_RATE,0) OVER_PAID_INT_RATE
                FROM DN_TEMP_MARGIN_CALL A,DN_REF_PORTFOLIO B
                WHERE A.PORTFOLIO_CODE   = B.PORTFOLIO_CODE
                GROUP BY A.PORTFOLIO_CODE, A.PORT_LIMIT, A.REPO_LEG2 ,B.OVER_PAID_INT_RATE
                ) WHERE OD_AMOUNT >0
                ;



BEGIN

  FOR X IN M_CURSOR() LOOP 
      
        EXIT WHEN M_CURSOR%NOTFOUND;
        
         M_OD_INT_AMOUNT :=0;
               
         SELECT 'OIMT'||TO_CHAR(SYSDATE,'YY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'
            ||LPAD(TO_CHAR(DN_SEQ_PORTF_CHARGE.NEXTVAL),3,'0')
         INTO M_DOCREFNO
         FROM DUAL;
        
          M_OD_INT_AMOUNT:= X.OD_AMOUNT*X.OVER_PAID_INT_RATE/TO_NUMBER(ADD_MONTHS(M_PROCESS_DATE,12)-M_PROCESS_DATE);
        
        
         INSERT INTO DN_TRN_PORTF_OD_INTEREST (
         DOCREFNO, PORTFOLIO_CODE, TRANSACTION_TYPE, PROC_DESC,
         LICENCEE_BRANCH_CODE, LICENCEE_ACCOUNT_NO, 
         OD_RATE,  OD_AMOUNT, OD_INTEREST,
          DN_USER, TRNDATE, RECON_BY,
         RECON_DATE, RECON_STATUS, REALISED_DATE, ENTDATE)
         VALUES(M_DOCREFNO, X.PORTFOLIO_CODE, 
          'I', 'OD INTEREST',
          NULL,--LICENCEE_BRANCH_CODE,
          NULL,--A.LICENCEE_ACCOUNT_NO, 
          X.OVER_PAID_INT_RATE,
          X.OD_AMOUNT,  
          M_OD_INT_AMOUNT,
          'SYS',
          M_PROCESS_DATE,
          NULL,--RECON_BY,
          NULL,--RECON_DATE,
          'N',--RECON_STATUS,
          NULL,--REALISED_DATE,
          SYSDATE);
       
        UPDATE  DN_TEMP_MARGIN_CALL
        SET    OD_INT_RATE     = X.OVER_PAID_INT_RATE,
               OD_INT_AMOUNT   = M_OD_INT_AMOUNT
        WHERE  PORTFOLIO_CODE  = X.PORTFOLIO_CODE ;
        
        UPDATE  DN_REP_MARGIN_CALL
        SET    OD_INT_RATE     = X.OVER_PAID_INT_RATE,
               OD_INT_AMOUNT   = M_OD_INT_AMOUNT
        WHERE  PORTFOLIO_CODE  = X.PORTFOLIO_CODE
        AND    TRN_DATE        = M_PROCESS_DATE ;    
        
   
       
   INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES( 'ADLMT',X.PORTFOLIO_CODE, M_PROCESS_DATE,'021','CR',M_OD_INT_AMOUNT, M_DOCREFNO,'OD INTEREST CALCULATION','124');
   
   INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES( 'ADLMT',X.PORTFOLIO_CODE, M_PROCESS_DATE,'124','DR',M_OD_INT_AMOUNT, M_DOCREFNO,'OD INTEREST CALCULATION','021');


   INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES( 'ADLMT',X.PORTFOLIO_CODE, TO_DATE('01-'||TO_CHAR(ADD_MONTHS(M_PROCESS_DATE,1),'MON-YYYY'),'DD-MM-YYYY'),'301','DR',M_OD_INT_AMOUNT, M_DOCREFNO,'OD INTEREST CALCULATION','021');
   
   INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES( 'ADLMT',X.PORTFOLIO_CODE, TO_DATE('01-'||TO_CHAR(ADD_MONTHS(M_PROCESS_DATE,1),'MON-YYYY'),'DD-MM-YYYY'),'021','CR',M_OD_INT_AMOUNT, M_DOCREFNO,'OD INTEREST CALCULATION','301');
   
   
      
   END LOOP; 
  
   
  
  


END;

