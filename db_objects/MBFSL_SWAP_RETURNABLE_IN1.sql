--  DDL for Procedure MBFSL_SWAP_RETURNABLE_IN1
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_SWAP_RETURNABLE_IN1" (
    M_DEAL_NO  IN OUT       DN_TRN_SWAP_RETURNABLE.DEAL_NO%TYPE,
    M_P1_PORTFOLIO_CODE     DN_TRN_SWAP_RETURNABLE.P1_PORTFOLIO_CODE%TYPE,
    M_P2_PORTFOLIO_CODE     DN_TRN_SWAP_RETURNABLE.P2_PORTFOLIO_CODE%TYPE,
    M_P1_INSTRUMENT         DN_TRN_SWAP_RETURNABLE.P1_INST_TYPE%TYPE,
    M_P2_INSTRUMENT         DN_TRN_SWAP_RETURNABLE.P2_INST_TYPE%TYPE,
    M_P1_SECURITY           DN_TRN_SWAP_RETURNABLE.P1_SECURITY_CODE%TYPE,
    M_P2_SECURITY           DN_TRN_SWAP_RETURNABLE.P2_SECURITY_CODE%TYPE,
    M_P1_ENDORSER           DN_TRN_SWAP_RETURNABLE.P1_ENDOSER_CODE%TYPE,
    M_P2_ENDORSER           DN_TRN_SWAP_RETURNABLE.P2_ENDOSER_CODE%TYPE,
    M_P1_PHYSICAL           DN_TRN_SWAP_RETURNABLE.P1_PHYSICAL_DELIVERY%TYPE,
    M_P2_PHYSICAL           DN_TRN_SWAP_RETURNABLE.P2_PHYSICAL_DELIVERY%TYPE,
    M_P1_CURRENCY           DN_TRN_SWAP_RETURNABLE.P1_CURR_CODE%TYPE,
    M_P2_CURRENCY           DN_TRN_SWAP_RETURNABLE.P2_CURR_CODE%TYPE,
    M_VALUE_DATE_TYPE1      DN_TRN_SWAP_RETURNABLE.P1_EFF_VALDATE_TYPE%TYPE,
    M_VALUE_DATE_TYPE2      DN_TRN_SWAP_RETURNABLE.P2_EFF_VALDATE_TYPE%TYPE,
    M_VALUE_DATE1           CHAR,
    M_VALUE_DATE2           CHAR,
    M_MAT_DATE1             CHAR,
    M_MAT_DATE2             CHAR,
    M_P1_TENOR              DN_TRN_SWAP_RETURNABLE.P1_TENOR%TYPE,
    M_P2_TENOR              DN_TRN_SWAP_RETURNABLE.P2_TENOR%TYPE,
    M_P1_FACE_VALUE         DN_TRN_SWAP_RETURNABLE.P1_FACE_VALUE%TYPE,
    M_P2_FACE_VALUE         DN_TRN_SWAP_RETURNABLE.P2_FACE_VALUE%TYPE,
    M_P1_RATE_PER_ANN       DN_TRN_SWAP_RETURNABLE.P1_FEE_RATE_PER_ANN%TYPE,
    M_P2_RATE_PER_ANN       DN_TRN_SWAP_RETURNABLE.P2_FEE_RATE_PER_ANN%TYPE,
    M_P1_FEE_AMOUNT_DUE     DN_TRN_SWAP_RETURNABLE.P1_FEE_AMOUNT_DUE%TYPE,
    M_P2_FEE_AMOUNT_DUE     DN_TRN_SWAP_RETURNABLE.P2_FEE_AMOUNT_DUE%TYPE,
    M_P1_NET_AMOUNT_DUE     DN_TRN_SWAP_RETURNABLE.P1_NET_AMOUNT_DUE%TYPE,
    M_P2_NET_AMOUNT_DUE     DN_TRN_SWAP_RETURNABLE.P2_NET_AMOUNT_DUE%TYPE,
    M_FDUE_DATE1            CHAR,
    M_FDUE_DATE2            CHAR,
    M_USERNAME              DN_TRN_SWAP_RETURNABLE.DN_USER%TYPE,
    M_DEAL_NUMBER           DN_TRN_SWAP_RETURNABLE.DEAL_NO%TYPE
)

AS

   M_USER               DN_TRN_SWAP_RETURNABLE.DN_USER%TYPE;
   M_P1_VAL_DATE        DN_TRN_SWAP_RETURNABLE.P1_EFF_VALDATE%TYPE;
   M_P2_VAL_DATE        DN_TRN_SWAP_RETURNABLE.P2_EFF_VALDATE%TYPE;
   M_P1_MATU_DATE       DN_TRN_SWAP_RETURNABLE.P1_MATURITY_DATE%TYPE;
   M_P2_MATU_DATE       DN_TRN_SWAP_RETURNABLE.P2_MATURITY_DATE%TYPE;
   M_P1_DUE_DATE        DN_TRN_SWAP_RETURNABLE.P1_FEE_DUE_DATE%TYPE;
   M_P2_DUE_DATE        DN_TRN_SWAP_RETURNABLE.P2_FEE_DUE_DATE%TYPE;

BEGIN

    --RAISE_APPLICATION_ERROR(-20201,M_DEAL_NO);

    -- PROCEDURE  -  TO INSERT SWAPS RETURNABLE DETAILS
    -- SYSTEM     -  MBFSL SYSTEM
    -- CREATED BY -  V.THILAKESAN.
    -- CREATED ON -  16/07/1999

    IF SUBSTR(M_USERNAME,1,1)=' ' OR M_USERNAME IS NULL THEN
       M_USER:='Un Identify';
    ELSE
       M_USER:=M_USERNAME;
    END IF;
    --To select the value date1
    IF M_VALUE_DATE_TYPE1<>'UD' THEN
       SELECT DN_FIN_EFF_VALDATE(M_VALUE_DATE_TYPE1) INTO M_P1_VAL_DATE FROM DUAL;
    ELSE
       SELECT TO_DATE(M_VALUE_DATE1,'DD/MM/YYYY') INTO M_P1_VAL_DATE FROM DUAL;
    END IF;
    --To select the value date2
    IF M_VALUE_DATE_TYPE2<>'UD' THEN
       SELECT DN_FIN_EFF_VALDATE(M_VALUE_DATE_TYPE2) INTO M_P2_VAL_DATE FROM DUAL;
    ELSE
       SELECT TO_DATE(M_VALUE_DATE2,'DD/MM/YYYY') INTO M_P2_VAL_DATE FROM DUAL;
    END IF;
    --To format the maturity date
    SELECT TO_DATE(M_MAT_DATE1,'DD/MM/YYYY') INTO M_P1_MATU_DATE FROM DUAL;
    SELECT TO_DATE(M_MAT_DATE2,'DD/MM/YYYY') INTO M_P2_MATU_DATE FROM DUAL;
    --To format the fee due date
    SELECT TO_DATE(M_FDUE_DATE1,'DD/MM/YYYY') INTO M_P1_DUE_DATE FROM DUAL;
    SELECT TO_DATE(M_FDUE_DATE2,'DD/MM/YYYY') INTO M_P2_DUE_DATE FROM DUAL;

    -- To Create the new sequence
    IF M_DEAL_NUMBER IS NULL THEN
       SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_BL_SEC.NEXTVAL),3,'0') INTO M_DEAL_NO FROM DUAL;
       M_DEAL_NO:=  'SR'||M_DEAL_NO;
    ELSE
       M_DEAL_NO:=M_DEAL_NUMBER;
    END IF;

    IF M_DEAL_NO IS NOT NULL THEN

       UPDATE DN_TRN_SWAP_RETURNABLE
       SET P1_PORTFOLIO_CODE     =M_P1_PORTFOLIO_CODE,
           P2_PORTFOLIO_CODE     =M_P2_PORTFOLIO_CODE,
           P1_INST_TYPE          =M_P1_INSTRUMENT,
           P2_INST_TYPE          =M_P2_INSTRUMENT,
           P1_SECURITY_CODE      =M_P1_SECURITY,
           P2_SECURITY_CODE      =M_P2_SECURITY,
           P1_ENDOSER_CODE       =M_P1_ENDORSER,
           P2_ENDOSER_CODE       =M_P2_ENDORSER,
           P1_PHYSICAL_DELIVERY  =M_P1_PHYSICAL,
           P2_PHYSICAL_DELIVERY  =M_P2_PHYSICAL,
           P1_CURR_CODE          =M_P1_CURRENCY,
           P2_CURR_CODE          =M_P2_CURRENCY,
           P1_EFF_VALDATE_TYPE   =M_VALUE_DATE_TYPE1,
           P2_EFF_VALDATE_TYPE   =M_VALUE_DATE_TYPE2,
           P1_EFF_VALDATE        =M_P1_VAL_DATE,
           P2_EFF_VALDATE        =M_P2_VAL_DATE,
           P1_MATURITY_DATE      =M_P1_MATU_DATE,
           P2_MATURITY_DATE      =M_P2_MATU_DATE,
           P1_TENOR              =M_P1_TENOR,
           P2_TENOR              =M_P2_TENOR,
           P1_FACE_VALUE         =M_P1_FACE_VALUE,
           P2_FACE_VALUE         =M_P2_FACE_VALUE,
           P1_FEE_RATE_PER_ANN   =M_P1_RATE_PER_ANN,
           P2_FEE_RATE_PER_ANN   =M_P2_RATE_PER_ANN,
           P1_FEE_AMOUNT_DUE     =M_P1_FEE_AMOUNT_DUE,
           P2_FEE_AMOUNT_DUE     =M_P2_FEE_AMOUNT_DUE,
           P1_NET_AMOUNT_DUE     =M_P1_NET_AMOUNT_DUE,
           P2_NET_AMOUNT_DUE     =M_P2_NET_AMOUNT_DUE,
           P1_FEE_DUE_DATE       =M_P1_DUE_DATE,
           P2_FEE_DUE_DATE       =M_P2_DUE_DATE,
           DN_USER               =M_USER
       WHERE
           DEAL_NO=M_DEAL_NO
           AND
           APP_STATUS='ENT';

       --RAISE_APPLICATION_ERROR(-20201,M_DEAL_NO||'-'||M_BORR_PORTFOLIO_CODE||'-'||M_LEND_PORTFOLIO_CODE||'-'||M_SECURITY||'-'||M_PHYSICAL||'-'||M_EXCHANGEABILITY||'-'||M_CURRENCY||'-'||M_BASIS||'-'||M_VALUE_DATE_TYPE||'-'||M_VAL_DATE||'-'||M_YIELD_NET||'-'||M_YIELD_NSL||'-'||M_LEG1||'-'||M_LEG2||'-'||M_MATU_DATE||'-'||M_TENOR||'-'||M_INTEREST||'-'||M_USER);

       IF SQL%NOTFOUND THEN
          INSERT INTO DN_TRN_SWAP_RETURNABLE
          (DEAL_NO,
           P1_PORTFOLIO_CODE,
           P2_PORTFOLIO_CODE,
           P1_INST_TYPE,
           P2_INST_TYPE,
           P1_SECURITY_CODE,
           P2_SECURITY_CODE,
           P1_ENDOSER_CODE,
           P2_ENDOSER_CODE,
           P1_PHYSICAL_DELIVERY,
           P2_PHYSICAL_DELIVERY,
           P1_CURR_CODE,
           P2_CURR_CODE,
           P1_EFF_VALDATE_TYPE,
           P2_EFF_VALDATE_TYPE,
           P1_EFF_VALDATE,
           P2_EFF_VALDATE,
           P1_MATURITY_DATE,
           P2_MATURITY_DATE,
           P1_TENOR,
           P2_TENOR,
           P1_FACE_VALUE,
           P2_FACE_VALUE,
           P1_FEE_RATE_PER_ANN,
           P2_FEE_RATE_PER_ANN,
           P1_FEE_AMOUNT_DUE,
           P2_FEE_AMOUNT_DUE,
           P1_NET_AMOUNT_DUE,
           P2_NET_AMOUNT_DUE,
           P1_FEE_DUE_DATE,
           P2_FEE_DUE_DATE,
           DN_USER)
           VALUES(
             M_DEAL_NO,
             M_P1_PORTFOLIO_CODE,
             M_P2_PORTFOLIO_CODE,
             M_P1_INSTRUMENT,
             M_P2_INSTRUMENT,
             M_P1_SECURITY,
             M_P2_SECURITY,
             M_P1_ENDORSER,
             M_P2_ENDORSER,
             M_P1_PHYSICAL,
             M_P2_PHYSICAL,
             M_P1_CURRENCY,
             M_P2_CURRENCY,
             M_VALUE_DATE_TYPE1,
             M_VALUE_DATE_TYPE2,
             M_P1_VAL_DATE,
             M_P2_VAL_DATE,
             M_P1_MATU_DATE,
             M_P2_MATU_DATE,
             M_P1_TENOR,
             M_P2_TENOR,
             M_P1_FACE_VALUE,
             M_P2_FACE_VALUE,
             M_P1_RATE_PER_ANN,
             M_P2_RATE_PER_ANN,
             M_P1_FEE_AMOUNT_DUE,
             M_P2_FEE_AMOUNT_DUE,
             M_P1_NET_AMOUNT_DUE,
             M_P2_NET_AMOUNT_DUE,
             M_P1_DUE_DATE,
             M_P2_DUE_DATE,
             M_USER
             );
       END IF;
   END IF;
   COMMIT;
    --If the data type is incorrect then delete the records from the relavent tables

 EXCEPTION
  WHEN OTHERS THEN

    DELETE DN_TRN_BROKERAGE
    WHERE
    DEAL_NO=M_DEAL_NO;

    DELETE DN_TRN_SWAP_RETURNABLE_SETTLE
    WHERE
    DEAL_NO=M_DEAL_NO;

    DELETE DN_TRN_SWAP_RETURNABLE
    WHERE
    DEAL_NO=M_DEAL_NO;

    COMMIT;

    RAISE_APPLICATION_ERROR(-20201,'Data error');

END MBFSL_SWAP_RETURNABLE_IN1;

