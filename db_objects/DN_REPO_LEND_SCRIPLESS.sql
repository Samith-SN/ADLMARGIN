set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_REPO_LEND_SCRIPLESS" 
(
  M_DEALNO           DN_TRN_REPO_FRESH.DEAL_NO%TYPE
 )
AS

 CURSOR MY_CUR_LEND IS
        SELECT   A.DEAL_NO,A.INST_TYPE,A.INV_CODE,A.SECURITY_CODE,NVL(A.ENDOSER_CODE,'NA'),A.FACE_VALUE,
                 A.FVAL_WITH_HAIR_CUT,A.INV_STATUS,B.LEND_PORTFOLIO_CODE,B.EFF_VALDATE,B.MATURITY_DATE
        FROM     DN_TRN_REPO_FRESH_SEC A,DN_TRN_REPO_FRESH B,DN_REF_PORTFOLIO C
        WHERE    RTRIM(LTRIM(A.DEAL_NO))=RTRIM(LTRIM(M_DEALNO)) AND
                 A.DEAL_NO=B.DEAL_NO AND
                 C.PF_TYPE='P' AND
                 C.PORTFOLIO_CODE=B.LEND_PORTFOLIO_CODE AND
                 B.SCRIPT_STATUS='SL';




   MM_DEAL_NO                        DN_TRN_REPO_FRESH.DEAL_NO%TYPE;
   MM_INST_TYPE                      DN_TRN_REPO_FRESH_SEC.INST_TYPE%TYPE;
   MM_INV_CODE                       DN_TRN_REPO_FRESH_SEC.INV_CODE%TYPE;
   MM_SECURITY_CODE                  DN_TRN_REPO_FRESH_SEC.SECURITY_CODE%TYPE;
   MM_ENDOSER_CODE                   DN_TRN_REPO_FRESH_SEC.ENDOSER_CODE%TYPE;
   MM_FACE_VALUE                     DN_TRN_REPO_FRESH_SEC.FACE_VALUE%TYPE;
   MM_FVAL_WITH_HAIR_CUT             DN_TRN_REPO_FRESH_SEC.FVAL_WITH_HAIR_CUT%TYPE;
   MM_INV_STATUS                     DN_TRN_REPO_FRESH_SEC.INV_STATUS%TYPE:='N';
   MM_LEND_PORTFOLIO_CODE            DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE;
   MM_EFF_VALDATE                    DN_TRN_REPO_FRESH.EFF_VALDATE%TYPE;
   MM_MATURITY_DATE                  DN_TRN_REPO_FRESH.MATURITY_DATE%TYPE;
   MM_SERIAL_NO                      DN_TRN_REPO_FRESH_SERIAL_NO.SERIAL_NO%TYPE;
err_num   varchar2(200);
err_msg   varchar2(200);
BEGIN

    -- CREATED ON :06-09-2001
    -- CREATED BY :NIRMALA
    -- SYSTEM     :DEALNET(MBFSL)

---------------------------------LENDER (PORTFOLIO) INFORMATION----------------------------------
----------------------------------------------------------------------------------------------
OPEN MY_CUR_LEND;
LOOP
FETCH MY_CUR_LEND INTO
                 MM_DEAL_NO,MM_INST_TYPE,MM_INV_CODE,MM_SECURITY_CODE,MM_ENDOSER_CODE,
                 MM_FACE_VALUE,MM_FVAL_WITH_HAIR_CUT,MM_INV_STATUS,MM_LEND_PORTFOLIO_CODE,
                 MM_EFF_VALDATE,MM_MATURITY_DATE;


EXIT WHEN MY_CUR_LEND%NOTFOUND;

   SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS.NEXTVAL),4,'0')--$$##SC
   INTO   MM_SERIAL_NO
   FROM   DUAL;

   MM_SERIAL_NO:='S'||MM_SERIAL_NO;


   INSERT INTO DN_TRN_REPO_FRESH_SERIAL_NO
    (DEAL_NO,INST_TYPE,INV_CODE,SECURITY_CODE,SERIAL_NO,FACE_VALUE,INV_STATUS,DATA_FROM,LOCATION)--PREV_DEAL_NO
   VALUES
    (MM_DEAL_NO,MM_INST_TYPE,MM_INV_CODE,MM_SECURITY_CODE,MM_SERIAL_NO,MM_FACE_VALUE,'Y1','FO',MM_LEND_PORTFOLIO_CODE);

 /* INSERT INTO DN_INV_REPO_DEAL_SEC
     (PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,SECURITY_CODE,TRN_TYPE,DEAL_NO,FACE_VAL,FWD_RECEIPT,
      LOCATION,ALLO_REPO,ALLO_BL,FWD_ALLO_REPO,FWD_ALLO_BL,RET_DUE_DATE)
   VALUES
     (MM_LEND_PORTFOLIO_CODE,MM_EFF_VALDATE,MM_INST_TYPE,MM_SECURITY_CODE,'LN',MM_DEAL_NO,MM_FACE_VALUE,0,
      MM_LEND_PORTFOLIO_CODE,0,0,0,0,DN_FIN_RET_DUE_DATE(MM_MATURITY_DATE,MM_SECURITY_CODE));
*/

   INSERT INTO DN_INV_REPO_DEAL_SERIAL_NO
     ( PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,SECURITY_CODE,DEAL_NO,SERIAL_NO,SCRIP_FACE_VAL,FACE_VAL,FWD_RECEIPT,LOCATION,
       ALLO_REPO,ALLO_BL,FWD_ALLO_REPO,FWD_ALLO_BL,RET_DUE_DATE,SCRIPT_STATUS)
   VALUES
     (MM_LEND_PORTFOLIO_CODE,MM_EFF_VALDATE,MM_INST_TYPE,MM_SECURITY_CODE,MM_DEAL_NO,MM_SERIAL_NO,MM_FACE_VALUE,MM_FACE_VALUE,0,MM_LEND_PORTFOLIO_CODE,
      0,0,0,0,DN_FIN_RET_DUE_DATE(MM_MATURITY_DATE,MM_SECURITY_CODE),'SL');

END LOOP;
CLOSE MY_CUR_LEND;
EXCEPTION
  WHEN OTHERS THEN
   err_num :=  substr(SQLCODE,1,15);
   err_msg := substr(SQLERRM,1,200) ;
  INSERT INTO DN_REF_SEQUENCE_LOG VALUES (MM_SERIAL_NO,err_num||''||err_msg,'ERROR',SYSDATE);
  COMMIT;
 RAISE_APPLICATION_ERROR(-20201,SQLCODE||SQLERRM);
------------------------------------------END-----------------------------------------------------------
--***SCRIPLESS
END DN_REPO_LEND_SCRIPLESS;

