               AND
               SERIAL_NO=M_SERIAL_NO;


--UPDATING THE LOCATION OF THE SERIAL NUMBERS RELATING TO THE NEW DEAL
              UPDATE DN_INV_REPO_DEAL_SERIAL_NO
              SET    LOCATION=M_CURR_LOCATION
              WHERE  PORTFOLIO_CODE=M_LEND_PORTFOLIO_CODE
               AND
