       M_USER:=M_USERNAME;
    END IF;
    --Format the value date type
    SELECT
      TO_DATE(M_VALUE_DATE,'DD/MM/YYYY')
    INTO
      M_VAL_DATE
    FROM DUAL;
    --Format the maturity date type
    SELECT
      TO_DATE(M_MAT_DATE,'DD/MM/YYYY')
    INTO
      M_MATU_DATE
    FROM DUAL;
