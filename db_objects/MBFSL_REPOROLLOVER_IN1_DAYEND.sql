       UPDATE DN_TRN_REPO_ROLLOVER
       SET PRIOR_DEAL_NO      =M_PRIOR_DEAL_NO,
           BORR_PORTFOLIO_CODE=M_BORROWER_CODE,
           LEND_PORTFOLIO_CODE=M_LENDER_CODE,
           SEC_ALW_LENDER     =M_SECURITY,
           PHYSICAL_DELIVERY  =M_PHYSICAL,
           EXCHANGE_SEC       =M_EXCHANGEABILITY,
           CURR_CODE          =M_CURRENCY,
           INT_RATE_BASE_CODE =M_BASIS,
           EFF_VALDATE_TYPE   =M_VALUE_DATE_TYPE,
           EFF_VALDATE        =M_VAL_DATE,
           YEILD              =M_YIELD,
           ON_CALL_DEAL       =M_ON_CALL,
           LEG1_VALUE         =M_LEG1,
           LEG2_VALUE         =M_LEG2,
           MATURITY_DATE      =M_MATU_DATE,
           TENOR              =M_TENOR,
           INT_AMOUNT         =M_INTEREST,
           PAYMENT_TO_BORR    =M_PAY_TO_BORR,
           PAYMENT_TO_LEND    =M_PAY_TO_LEND,
           DN_USER            =M_USER
       WHERE
           DEAL_NO=M_DEAL_NO
           AND
           APP_STATUS='ENT'
           AND
           SCRIPT_STATUS=M_SCRIPT_STATUS;

      --RAISE_APPLICATION_ERROR(-20201,M_DEAL_NO||'-'||M_PRIOR_DEAL_NO||'-'||M_BORROWER_CODE||'-'||M_LENDER_CODE||'-'||M_SECURITY||'-'||M_PHYSICAL||'-'||M_EXCHANGEABILITY||'-'||M_CURRENCY||'-'||M_BASIS||'-'||M_VALUE_DATE_TYPE||'-'||M_VAL_DATE||'-'||M_YIELD||'-'||M_ON_CALL||'-'||M_LEG1||'-'||M_LEG2||'-'||M_MATU_DATE||'-'||M_TENOR||'-'||M_INTEREST||'-'||M_PAY_TO_BORR||'-'||M_PAY_TO_LEND||'-'||M_USER);

       IF SQL%NOTFOUND THEN
        IF (SUBSTR(M_DEAL_NUMBER,1,2)='GR')THEN --GROUP DEAL
          INSERT INTO DN_TRN_REPO_ROLLOVER
          (DEAL_NO,PRIOR_DEAL_NO,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE, SEC_ALW_LENDER,
           PHYSICAL_DELIVERY, EXCHANGE_SEC,CURR_CODE,INT_RATE_BASE_CODE,EFF_VALDATE_TYPE,
           EFF_VALDATE,YEILD,ON_CALL_DEAL,LEG1_VALUE,LEG2_VALUE,MATURITY_DATE,TENOR,
           INT_AMOUNT,PAYMENT_TO_BORR,PAYMENT_TO_LEND,DN_USER, SCRIPT_STATUS, GROUP_DEALNO, APP_STATUS)
           VALUES(
             M_DEAL_NO,M_PRIOR_DEAL_NO,M_BORROWER_CODE,M_LENDER_CODE,M_SECURITY,M_PHYSICAL,
             M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,M_VALUE_DATE_TYPE,M_VAL_DATE,M_YIELD,
             M_ON_CALL,M_LEG1,M_LEG2,M_MATU_DATE, M_TENOR,M_INTEREST,M_PAY_TO_BORR,M_PAY_TO_LEND,
             M_USER,M_SCRIPT_STATUS , M_GDEAL_NUMBER,'CANCEL');


           UPDATE DN_TRN_REPO_ROLLOVER
           SET    GROUP_PORT_TYPE=(SELECT DECODE(A.BORR_PORTFOLIO_CODE,'GROUP','B','L')
                                  FROM   DN_TRN_REPO_ROLLOVER A
                                  WHERE   DEAL_NO=M_DEAL_NO)
           WHERE  GROUP_DEALNO=M_DEAL_NO;





         ELSE
           INSERT INTO DN_TRN_REPO_ROLLOVER
          (DEAL_NO,PRIOR_DEAL_NO,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE, SEC_ALW_LENDER,
           PHYSICAL_DELIVERY, EXCHANGE_SEC,CURR_CODE,INT_RATE_BASE_CODE,EFF_VALDATE_TYPE,
           EFF_VALDATE,YEILD,ON_CALL_DEAL,LEG1_VALUE,LEG2_VALUE,MATURITY_DATE,TENOR,
           INT_AMOUNT,PAYMENT_TO_BORR,PAYMENT_TO_LEND,DN_USER, SCRIPT_STATUS,GROUP_DEALNO)
           VALUES(
             M_DEAL_NO,M_PRIOR_DEAL_NO,M_BORROWER_CODE,M_LENDER_CODE,M_SECURITY,M_PHYSICAL,
             M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,M_VALUE_DATE_TYPE,M_VAL_DATE,M_YIELD,
             M_ON_CALL,M_LEG1,M_LEG2,M_MATU_DATE, M_TENOR,M_INTEREST,M_PAY_TO_BORR,M_PAY_TO_LEND,
             M_USER,M_SCRIPT_STATUS,M_GDEAL_NUMBER );

         END IF;






                    --ADDED FOR TIME LOG MANAGEMENT BY S.YASODHA
        INSERT INTO DN_TIME_LOG
          (SUS_REF_NO, DN_USER,ENT_DATE,DESCRIPTION)
           VALUES
            ( M_DEAL_NO, M_USER, SYSDATE, 'ENTERED');
              --*********************************
       END IF;
     END IF;--CURRENCY
   /*   IF M_TENOR>0 THEN
         DN_LIMIT_TRN_OVRL_MATU(M_DEAL_NO,'I');--ADD BY DAYAN TO RUN TRANSACTION PROCEDURE
         DN_LIMIT_TRN_OVRL(M_DEAL_NO,'I');-- Modified by Sukathis
