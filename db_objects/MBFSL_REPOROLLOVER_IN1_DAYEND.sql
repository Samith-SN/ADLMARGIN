             M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,M_VALUE_DATE_TYPE, M_VAL_DATE,M_YIELD,
             M_ON_CALL,M_LEG1*MM_CURRENCY_VALUE,--CURRENCY
             M_LEG2*MM_CURRENCY_VALUE,--CURRENCY
             M_MATU_DATE,M_TENOR,M_INTEREST*MM_CURRENCY_VALUE,--CURRENCY
             M_PAY_TO_BORR*MM_CURRENCY_VALUE,--CURRENCY
             M_PAY_TO_LEND*MM_CURRENCY_VALUE,--CURRENCY
