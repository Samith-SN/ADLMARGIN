           PAYMENT_TO_BORR    =M_PAY_TO_BORR*MM_CURRENCY_VALUE,--CURRENCY
           PAYMENT_TO_LEND    =M_PAY_TO_LEND*MM_CURRENCY_VALUE,--CURRENCY
