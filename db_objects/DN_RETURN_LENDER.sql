  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_RETURN_LENDER" 
(
  M_DEAL_NO   DN_INV_OUTPS_DEAL_SERNO_ALLO.DEAL_NO%TYPE,
  M_STATUS    VARCHAR2
)RETURN VARCHAR2

-- --------------------------------------------------------------------------------------------------------------------

-- THIS FUNCTION WILL RETURN THE LENDER CODE ACCORDING TO THE PASSING DEAL NO
-- CREATED ON 13.07.04
-- CREATED BY NILU
-- ---------------------------------------------------------------------------------------------------------------------

AS
  M_LENDER VARCHAR2(6);

  M_DEAL DN_INV_OUTPS_DEAL_SERNO_ALLO.DEAL_NO%TYPE;

BEGIN

IF M_STATUS='O' THEN

SELECT DISTINCT  SUBSTR(DEAL_NO,1,2)
INTO M_DEAL
FROM DN_INV_OUTPS_DEAL_SERNO_ALLO
WHERE DEAL_NO=M_DEAL_NO;

  -- SELECTING THE LENDER CODE FOR REPO FRESH DEALS
IF M_DEAL='RF' THEN
 SELECT LEND_PORTFOLIO_CODE
 INTO M_LENDER
 FROM DN_TRN_REPO_FRESH
 WHERE DEAL_NO=M_DEAL_NO;

  -- SELECTING THE LENDER CODE FOR RR
 ELSIF M_DEAL='RR' THEN
 SELECT LEND_PORTFOLIO_CODE
 INTO M_LENDER
 FROM DN_TRN_REPO_ROLLOVER
 WHERE DEAL_NO=M_DEAL_NO;

 END IF ;

 ELSIF M_STATUS='R' THEN
 SELECT DISTINCT  SUBSTR(DEAL_NO,1,2)
INTO M_DEAL
FROM DN_INV_REPO_DEAL_SERNO_ALLO
WHERE DEAL_NO=M_DEAL_NO;

  -- SELECTING THE LENDER CODE FOR REPO FRESH DEALS
IF M_DEAL='RF' THEN
 SELECT LEND_PORTFOLIO_CODE
 INTO M_LENDER
 FROM DN_TRN_REPO_FRESH
 WHERE DEAL_NO=M_DEAL_NO;

  -- SELECTING THE LENDER CODE FOR RR
 ELSIF M_DEAL='RR' THEN
 SELECT LEND_PORTFOLIO_CODE
 INTO M_LENDER
 FROM DN_TRN_REPO_ROLLOVER
 WHERE DEAL_NO=M_DEAL_NO;

 END IF ;
 END IF;

 RETURN M_LENDER;

END DN_RETURN_LENDER;

/
