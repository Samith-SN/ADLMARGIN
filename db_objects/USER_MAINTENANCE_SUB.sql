set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."USER_MAINTENANCE_SUB" 

( M_VIEW VARCHAR2,

M_EXEC VARCHAR2,

M_SCREEN_NAMES VARCHAR2,

M_USER_NAME VARCHAR2,

M_SAVETYPE VARCHAR2,

M_ROWID NUMBER,

M_USER VARCHAR2

)

AS

M_COUNT1 INTEGER;

BEGIN

DN_VALIDATE_SAVE_RIGHTS(M_USER,'WD_Users'); --added by ashini on 31/10/2005 for sr0509-047

 

IF ((M_VIEW='on' )OR(M_EXEC='on') ) THEN


DELETE DN_REF_USER_VIEW_ACCESS_BK

WHERE DN_USER=M_USER_NAME

AND SCREEN_NAME=M_SCREEN_NAMES ;----modified susitha 05-06-2011


INSERT INTO DN_REF_USER_VIEW_ACCESS_BK

(DN_USER,SCREEN_NAME,SAVE_STATUS)

SELECT DN_USER,SCREEN_NAME,SAVE_STATUS

FROM DN_REF_USER_VIEW_ACCESS 

WHERE DN_USER=M_USER_NAME

AND SCREEN_NAME=M_SCREEN_NAMES ;----modified susitha 05-06-2011



IF (M_VIEW='on') THEN

IF M_SAVETYPE='MOD' THEN

DELETE DN_REF_USER_VIEW_ACCESS

WHERE DN_USER=M_USER_NAME AND SCREEN_NAME=M_SCREEN_NAMES ;

END IF;


-- ADDED BY UMESHA \ CHANDANA ON THE 16.10.2006 VC06/020

DELETE DN_REF_USER_VIEW_ACCESS

WHERE DN_USER=M_USER_NAME AND SCREEN_NAME=M_SCREEN_NAMES;

-- END BY UMESHA \ CHANDANA ON THE 16.10.2006 VC06/020

INSERT INTO DN_REF_USER_VIEW_ACCESS

(DN_USER,SCREEN_NAME,SAVE_STATUS)

VALUES

(UPPER(M_USER_NAME),M_SCREEN_NAMES,'N');

END IF;

IF (M_EXEC='on') THEN

UPDATE DN_REF_USER_VIEW_ACCESS

SET SAVE_STATUS='Y'

WHERE DN_USER=UPPER(M_USER_NAME) AND

SCREEN_NAME=M_SCREEN_NAMES;

END IF;

 

ELSE

DELETE DN_REF_USER_VIEW_ACCESS

WHERE DN_USER=M_USER_NAME AND SCREEN_NAME=M_SCREEN_NAMES;

END IF;

COMMIT;

 

END USER_MAINTENANCE_SUB;

