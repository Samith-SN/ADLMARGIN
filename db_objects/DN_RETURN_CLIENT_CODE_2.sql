--------------------------------------------------------
--  DDL for Function DN_RETURN_CLIENT_CODE_2
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_RETURN_CLIENT_CODE_2" 
(
  M_DEAL_NO     DN_TRN_BL_SECURITY.DEAL_NO%TYPE
)
RETURN VARCHAR2
AS
M_CLIENT_CODE           DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
M_PORTFOLIO_CODE1       DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
M_PORTFOLIO_CODE2       DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
M_PF_TYPE1              DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_PF_TYPE2              DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_PRIOR_DEAL_NO         DN_TRN_REPO_SETTLEMENT.PRIOR_DEAL_NO%TYPE;
BEGIN

IF(SUBSTR(M_DEAL_NO,1,2)='BS')THEN

SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE
INTO   M_PORTFOLIO_CODE1,M_PORTFOLIO_CODE2
FROM   DN_TRN_BL_SECURITY
WHERE  DEAL_NO=M_DEAL_NO;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE1,M_PORTFOLIO_CODE1
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE1;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE2,M_PORTFOLIO_CODE2
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE2;

ELSIF (SUBSTR(M_DEAL_NO,1,2)='RF')THEN

SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE
INTO   M_PORTFOLIO_CODE1,M_PORTFOLIO_CODE2
FROM   DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_DEAL_NO;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE1,M_PORTFOLIO_CODE1
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE1;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE2,M_PORTFOLIO_CODE2
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE2;

ELSIF (SUBSTR(M_DEAL_NO,1,2)='RR')THEN

SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE
INTO   M_PORTFOLIO_CODE1,M_PORTFOLIO_CODE2
FROM   DN_TRN_REPO_ROLLOVER
WHERE  DEAL_NO=M_DEAL_NO;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE1,M_PORTFOLIO_CODE1
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE1;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE2,M_PORTFOLIO_CODE2
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE2;


ELSIF (SUBSTR(M_DEAL_NO,1,2)='PI')THEN

SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE
INTO   M_PORTFOLIO_CODE1,M_PORTFOLIO_CODE2
FROM   DN_TRN_REPO_PERIOD_INT
WHERE  DEAL_NO=M_DEAL_NO;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE1,M_PORTFOLIO_CODE1
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE1;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE2,M_PORTFOLIO_CODE2
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE2;
--add by waruna 2010-10-18
ELSIF (SUBSTR(M_DEAL_NO,1,2)='SP')THEN

SELECT PORTFOLIO_CODE,DN_PORTFOLIO_CODE
INTO   M_PORTFOLIO_CODE1,M_PORTFOLIO_CODE2
FROM   DN_TRN_BO_SETTL_PAYMENT_BULK
WHERE  PAYMENT_NO=M_DEAL_NO;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE1,M_PORTFOLIO_CODE1
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE1;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE2,M_PORTFOLIO_CODE2
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE2;

-----------------------end


ELSIF (SUBSTR(M_DEAL_NO,1,2)='BF')THEN

SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE
INTO   M_PORTFOLIO_CODE1,M_PORTFOLIO_CODE2
FROM   DN_TRN_BL_FUND
WHERE  DEAL_NO=M_DEAL_NO;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE1,M_PORTFOLIO_CODE1
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE1;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE2,M_PORTFOLIO_CODE2
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE2;

ELSIF (SUBSTR(M_DEAL_NO,1,2)='OR')THEN

SELECT BUY_PORTFOLIO_CODE,SELL_PORTFOLIO_CODE
INTO   M_PORTFOLIO_CODE1,M_PORTFOLIO_CODE2
FROM   DN_TRN_OUTP_SALE
WHERE  DEAL_NO=M_DEAL_NO;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE1,M_PORTFOLIO_CODE1
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE1;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE2,M_PORTFOLIO_CODE2
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE2;

ELSIF (SUBSTR(M_DEAL_NO,1,2)='RS')THEN
SELECT  PRIOR_DEAL_NO
INTO    M_PRIOR_DEAL_NO
FROM    DN_TRN_REPO_SETTLEMENT
WHERE   DEAL_NO=M_DEAL_NO;

IF (SUBSTR(M_PRIOR_DEAL_NO,1,2)='RF')THEN

SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE
INTO   M_PORTFOLIO_CODE1,M_PORTFOLIO_CODE2
FROM   DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_PRIOR_DEAL_NO;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE1,M_PORTFOLIO_CODE1
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE1;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE2,M_PORTFOLIO_CODE2
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE2;
ELSE
SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE
INTO   M_PORTFOLIO_CODE1,M_PORTFOLIO_CODE2
FROM   DN_TRN_REPO_ROLLOVER
WHERE  DEAL_NO=M_PRIOR_DEAL_NO;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE1,M_PORTFOLIO_CODE1
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE1;

SELECT PF_TYPE,PORTFOLIO_CODE
INTO   M_PF_TYPE2,M_PORTFOLIO_CODE2
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE2;

END IF;
END IF;

SELECT DECODE(M_PF_TYPE1,'P',M_PORTFOLIO_CODE1,M_PORTFOLIO_CODE2)
INTO M_CLIENT_CODE
FROM DUAL;

RETURN M_CLIENT_CODE;
END dn_return_client_code_2;

