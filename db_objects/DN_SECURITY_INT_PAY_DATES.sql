--------------------------------------------------------
--  DDL for Procedure DN_SECURITY_INT_PAY_DATES
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_SECURITY_INT_PAY_DATES" 
   (
    M_SECURITY_CODE     DN_REF_SECURITY.SECURITY_CODE%TYPE,
    M_FREQUENCY         DN_REF_SECURITY.FREQUENCY%TYPE

   )

   IS

    -- Procedue     : Interest payment dates
    -- System       : Dealnet system
    -- Created by   : D.P. Pubudu Thushara
    -- Created on   : 30/06/1999

   M_INT_DATE       DN_REF_SECURITY_INT_PAY_DATES.INT_PAY_DATE%TYPE;
   M_MATURITY_DATE  DN_REF_SECURITY.MATURITY_DATE%TYPE;
   M_ISSUE_DATE     DN_REF_SECURITY.ISSUE_DATE%TYPE;

BEGIN

  DELETE DN_REF_SECURITY_INT_PAY_DATES
  WHERE SECURITY_CODE=M_SECURITY_CODE;

  SELECT
     ISSUE_DATE,MATURITY_DATE
     INTO
     M_ISSUE_DATE,M_MATURITY_DATE
  FROM
     DN_REF_SECURITY
  WHERE
     SECURITY_CODE=M_SECURITY_CODE;

  M_INT_DATE:=M_MATURITY_DATE;

--  RAISE_APPLICATION_ERROR(-20201,'M_INT_DATE'||M_INT_DATE||'M_ISSUE_DATE'||M_ISSUE_DATE);

  WHILE M_INT_DATE>M_ISSUE_DATE LOOP

      INSERT INTO DN_REF_SECURITY_INT_PAY_DATES
      (SECURITY_CODE,INT_PAY_DATE)
      VALUES
      (M_SECURITY_CODE,M_INT_DATE);

      SELECT
         ADD_MONTHS(M_INT_DATE,(-12/M_FREQUENCY))
         INTO  M_INT_DATE
      FROM DUAL;

      COMMIT;

 END LOOP;

END DN_SECURITY_INT_PAY_DATES;

