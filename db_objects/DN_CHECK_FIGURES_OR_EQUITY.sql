 FROM   DN_TRN_OUTP_SALE_SEC
 WHERE  DEAL_NO=M_DEAL_NO
 GROUP BY DEAL_NO;

   IF MSL_FACE_VALUE <> M_SECTAB_TOT THEN
        RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN TOTAL VALUE OF THE DN_TRN_OUTP_SALE_SEC TABLE AND FACE VALUE IN DN_TRN_OUTP_SALE TABLE!! ');
   END IF;

END IF;
END IF;
--ADDED BY SARANGA ON 28-06-2004
SELECT (PRICE_CLEAN * FACE_VALUE )- BROKER_COST INTO  M_COST
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;
SELECT COST  INTO  MM_COST
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;

IF M_COST <> MM_COST THEN
  RAISE_APPLICATION_ERROR(-20201,M_DEAL_NO||'MISMATCH IN THE TOTAL COST  !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

ELSE  ---COUNT

SELECT (PRICE_CLEAN * FACE_VALUE )+ BROKER_COST INTO  M_COST
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;
SELECT COST  INTO  MM_COST
FROM DN_TRN_OUTP_SALE WHERE DEAL_NO=M_DEAL_NO;

IF M_COST <> MM_COST THEN
  RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN THE TOTAL COST  !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;
--END

END IF;--COUNT
