  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_PORT_BALANCE" 
(
 M_DATE                  VARCHAR2,
 M_PORTFOLIO_CODE        DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE
 )
 RETURN NUMBER
 AS
 M_PF_TYPE          DN_REF_PORTFOLIO.PF_TYPE%TYPE;
 M_MAT_DATE_REPO    DATE;
 M_MAT_DATE_SETE    DATE;
 M_MAT_DATE_SETE1   DATE;
 M_AMOUNT           NUMBER;
 M_INT_AMOUNT       NUMBER;
 M_COUNT            NUMBER;

 BEGIN

SELECT COUNT(*)
INTO   M_COUNT
FROM (
SELECT (MATURITY_DATE) MATURITY_DATE
FROM   DN_TRN_REPO_FRESH
WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       MATURITY_DATE >= TO_DATE(M_DATE,'DD-MM-YYYY') AND
       EFF_VALDATE   <= TO_DATE(M_DATE,'DD-MM-YYYY')  
UNION ALL
SELECT (MATURITY_DATE) MATURITY_DATE
FROM   DN_TRN_REPO_ROLLOVER
WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       MATURITY_DATE >= TO_DATE(M_DATE,'DD-MM-YYYY') AND
       EFF_VALDATE   <= TO_DATE(M_DATE,'DD-MM-YYYY')  
----------------------------------       
UNION ALL
SELECT (MATURITY_DATE) MATURITY_DATE
FROM   DN_TRN_REPO_FRESH
WHERE  LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       MATURITY_DATE >= TO_DATE(M_DATE,'DD-MM-YYYY') AND
       EFF_VALDATE   <= TO_DATE(M_DATE,'DD-MM-YYYY')  
UNION ALL
SELECT (MATURITY_DATE) MATURITY_DATE
FROM   DN_TRN_REPO_ROLLOVER
WHERE  LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       MATURITY_DATE >= TO_DATE(M_DATE,'DD-MM-YYYY') AND
       EFF_VALDATE   <= TO_DATE(M_DATE,'DD-MM-YYYY')  

----------------------------------
);

IF M_COUNT >0 THEN

--SELECT LEG1_VALUE comment by waruna 2010-12-17
SELECT Sum(LEG1_VALUE) --add by waruna 2010-12-17

INTO   M_AMOUNT
FROM (
SELECT LEG1_VALUE LEG1_VALUE
FROM   DN_TRN_REPO_FRESH
WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       MATURITY_DATE >= TO_DATE(M_DATE,'DD-MM-YYYY') AND
       EFF_VALDATE   <= TO_DATE(M_DATE,'DD-MM-YYYY')  
UNION ALL
SELECT LEG1_VALUE LEG1_VALUE
FROM   DN_TRN_REPO_ROLLOVER
WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       MATURITY_DATE >= TO_DATE(M_DATE,'DD-MM-YYYY') AND
       EFF_VALDATE   <= TO_DATE(M_DATE,'DD-MM-YYYY')  
----------------------------------       
UNION ALL
SELECT LEG1_VALUE LEG1_VALUE
FROM   DN_TRN_REPO_FRESH
WHERE  LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       MATURITY_DATE >= TO_DATE(M_DATE,'DD-MM-YYYY') AND
       EFF_VALDATE   <= TO_DATE(M_DATE,'DD-MM-YYYY')  
UNION ALL
SELECT LEG1_VALUE LEG1_VALUE
FROM   DN_TRN_REPO_ROLLOVER
WHERE  LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       MATURITY_DATE >= TO_DATE(M_DATE,'DD-MM-YYYY') AND
       EFF_VALDATE   <= TO_DATE(M_DATE,'DD-MM-YYYY')  

----------------------------------
);
 

ELSE
    M_AMOUNT :=0;
END IF;

RETURN  M_AMOUNT;

END DN_GET_PORT_BALANCE;

