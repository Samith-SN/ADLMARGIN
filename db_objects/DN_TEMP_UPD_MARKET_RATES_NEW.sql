  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_TEMP_UPD_MARKET_RATES_NEW" 
(
 M_EXTERNAL_CODE1      DN_TEMP_MARKET_RATES.EXTERNAL_CODE%TYPE,
 M_PRICE              VARCHAR2,--DN_TEMP_MARKET_RATES.PRICE%TYPE
 M_NO_OF_SHARES       NUMBER,
 M_MAIN_TYPE          VARCHAR2,--- manjula on 9-04-2007 for tapsec.lk
 M_COUNT              NUMBER
)
AS
M_PRICE1              VARCHAR2(50);--DN_TEMP_MARKET_RATES.PRICE%TYPE
M_PRICE2              DN_TEMP_MARKET_RATES.PRICE%TYPE;
M_EXTERNAL_CODE       DN_TEMP_MARKET_RATES.EXTERNAL_CODE%TYPE;
M_EXTERNAL_CODE2      DN_TEMP_MARKET_RATES.EXTERNAL_CODE%TYPE;
M_MAIN_TYPE2          VARCHAR2(50);--- manjula on 9-04-2007 for tapsec.lk
M_REP_STR             VARCHAR2(50);--- manjula on 9-04-2007 for tapsec.lk

BEGIN

--------- added by Manjula on 09-04-2007 for tapsec.lk price upload.
M_REP_STR:=SUBSTR(M_MAIN_TYPE,1,1);

IF ((M_REP_STR='N') OR (M_REP_STR='X') OR (M_REP_STR='R') OR (M_REP_STR='W') OR (M_REP_STR='B') OR (M_REP_STR='P') OR (M_REP_STR='U'))  THEN

SELECT REPLACE(M_MAIN_TYPE,M_REP_STR,'-'||M_REP_STR||'-')
INTO M_MAIN_TYPE2
FROM DUAL;

END IF;

--M_EXTERNAL_CODE:=M_EXTERNAL_CODE1||M_MAIN_TYPE2;
--M_EXTERNAL_CODE2:=SUBSTR(M_EXTERNAL_CODE1,2)||M_MAIN_TYPE2;//comment by waruna
M_EXTERNAL_CODE2:=M_EXTERNAL_CODE1||M_MAIN_TYPE2;


SELECT REPLACE(M_EXTERNAL_CODE2,' ','')
INTO M_EXTERNAL_CODE
FROM DUAL;

/*raise_application_error(-20201,'M_EXTERNAL_CODE1---'||M_EXTERNAL_CODE1||
'M_MAIN_TYPE---'||M_MAIN_TYPE||'M_COUNT---'||M_COUNT||'M_EXTERNAL_CODE---'||
M_EXTERNAL_CODE||'M_MAIN_TYPE2==='||M_MAIN_TYPE2);*/
--- end modifications  done by manjula on 09-04-2007 for tapsec.lk price upload.

--RAISE_APPLICATION_ERROR(-20201,'M_MAIN_TYPE2==='||M_MAIN_TYPE2||'M_EXTERNAL_CODE1==='||M_EXTERNAL_CODE1||'M_EXTERNAL_CODE=='||M_EXTERNAL_CODE);
--SELECT REPLACEREPLACE(str,search_str[,replace_str])


 -- CAREATED BY SA ON 06-10-2004 TO UPDATE THE TEMP TABLE FROM EXCEL SHEET
 IF M_COUNT =0 THEN
    DELETE DN_TEMP_MARKET_RATES;
    --WHERE  EXTERNAL_CODE = M_EXTERNAL_CODE;
 END IF;
 SELECT REPLACE(M_PRICE,'XD','') INTO  M_PRICE1 FROM DUAL;
 SELECT TO_NUMBER(REPLACE(M_PRICE1,'XR','')) INTO  M_PRICE2 FROM DUAL;

 IF (M_EXTERNAL_CODE IS NOT NULL AND M_PRICE IS NOT NULL AND M_NO_OF_SHARES>=100) THEN

   INSERT INTO DN_TEMP_MARKET_RATES(EXTERNAL_CODE,PRICE,ROW_COUNT)
   VALUES(TRIM(M_EXTERNAL_CODE),TRIM(M_PRICE2),M_COUNT);

 END IF;

COMMIT;
END ;

