set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_INVENTORY_CHANGELOC" 
(
M_INV_MOD_LOC_NO IN OUT     DN_TRN_BO_INV_MODIFY_LOCATION.INV_MOD_LOC_NO%TYPE,
M_PORTFOLIO_CODE            DN_TRN_BO_INV_MODIFY_LOCATION.PORTFOLIO_CODE%TYPE,
M_inst_type                 DN_TRN_BO_INV_MODIFY_LOCATION.inst_type%TYPE,
M_SECURITY_CODE             DN_TRN_BO_INV_MODIFY_LOCATION.SECURITY_CODE%TYPE,
M_SERIAL_NO                 DN_TRN_BO_INV_MODIFY_LOCATION.SERIAL_NO%TYPE,
M_inv_code                  DN_TRN_BO_INV_MODIFY_LOCATION.inv_code%TYPE,
M_OLD_LOCATION              DN_TRN_BO_INV_MODIFY_LOCATION.OLD_LOCATION%TYPE,
M_NEW_LOCATION              DN_TRN_BO_INV_MODIFY_LOCATION.NEW_LOCATION%TYPE,
M_DN_USER                   DN_TRN_BO_INV_MODIFY_LOCATION.DN_USER%TYPE,
M_INV_MOD_LOC_NO2           DN_TRN_BO_INV_MODIFY_LOCATION.INV_MOD_LOC_NO%TYPE,
M_DEAL_CODE                 DN_TIME_LOG_SETTLE.REL_DEAL_NO%TYPE

)
AS

   /*  PROCEDURE  - DN_INVENTORY_CHANGELOC SAVING INVENTORY LOCATION CHANGES
       SYSTEM     - DEALNET
       CREATED BY - SUKATHISVARAN
       CREATED ON - 02/SEPTEMBER/1999  */



BEGIN

--RAISE_APPLICATION_ERROR(-20201,M_PORTFOLIO_CODE||'|'||M_inst_type||'|'||M_SECURITY_CODE||'|'||M_SERIAL_NO||'|'||M_inv_code||'|'||M_OLD_LOCATION||'|'||M_NEW_LOCATION||'|'||M_DN_USER);
IF M_INV_MOD_LOC_NO2 IS NULL THEN
 SELECT  'IL'||TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'
        ||LPAD(TO_CHAR(DN_SEQ_INV_MOD_LOC.NEXTVAL),3,'0')
        INTO    M_INV_MOD_LOC_NO
        FROM    DUAL;
ELSE
    M_INV_MOD_LOC_NO:=M_INV_MOD_LOC_NO2;

END IF;


INSERT INTO  DN_TRN_BO_INV_MODIFY_LOCATION
             (  INV_MOD_LOC_NO,PORTFOLIO_CODE,inst_type,SECURITY_CODE,SERIAL_NO,
                inv_code,OLD_LOCATION,NEW_LOCATION,DN_USER)

      VALUES (M_INV_MOD_LOC_NO,M_PORTFOLIO_CODE,M_inst_type,M_SECURITY_CODE,M_SERIAL_NO ,
              M_inv_code,M_OLD_LOCATION,M_NEW_LOCATION,M_DN_USER);
--DN_BO_INV_MOD_LOCATION(M_INV_MOD_LOC_NO);

   IF M_inv_code='OR' THEN

      UPDATE DN_INV_OUTPS_DEAL_SERIAL_NO
      SET LOCATION=M_NEW_LOCATION
      WHERE
         PORTFOLIO_CODE=M_PORTFOLIO_CODE
         AND
         INST_TYPE=M_inst_type
         AND
         SECURITY_CODE=M_SECURITY_CODE
         AND
         SERIAL_NO=M_SERIAL_NO;

   ELSIF  M_inv_code='RP' THEN

      UPDATE DN_INV_REPO_DEAL_SERIAL_NO
      SET LOCATION=M_NEW_LOCATION
      WHERE
         PORTFOLIO_CODE=M_PORTFOLIO_CODE
         AND
         INST_TYPE=M_inst_type
         AND
         SECURITY_CODE=M_SECURITY_CODE
         AND
         SERIAL_NO=M_SERIAL_NO;

   ELSIF M_inv_code='BL' THEN

      UPDATE DN_INV_BL_DEAL_SERIAL_NO
      SET LOCATION=M_NEW_LOCATION
      WHERE
         PORTFOLIO_CODE=M_PORTFOLIO_CODE
         AND
         INST_TYPE=M_inst_type
         AND
         SECURITY_CODE=M_SECURITY_CODE
         AND
         SERIAL_NO=M_SERIAL_NO;

   END IF;

 -- ADDED FOR TIME LOG MANAGEMENT BY YASODHA ON 10-08-2000
 INSERT INTO DN_TIME_LOG_SETTLE
          (DOC_REF_NO,
           REL_DEAL_NO,
           DN_USER,
           ENT_DATE,
           DESCRIPTION)
           VALUES
            (
              M_INV_MOD_LOC_NO,
              M_DEAL_CODE,
              M_DN_USER,
              SYSDATE,
              'INVENTORY LOC CHANGE '
           );

COMMIT;

 END DN_INVENTORY_CHANGELOC;

