  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_SEC_LIMIT_RESTRICTION" 
   (
  M_SECURITY_CODE             DN_TRN_SECURITY_LIMIT.SECURITY_CODE%TYPE ,
  M_PORT_CODE                 DN_TRN_SECURITY_LIMIT.PORTFOLIO_CODE%TYPE ,
  M_RATE                      DN_TRN_SECURITY_LIMIT.SEC_PER%TYPE ,
  M_ENT_USER                  DN_TRN_SECURITY_LIMIT.ENT_USER%TYPE,
  M_OPTION1                   VARCHAR2,
  M_DATE                      VARCHAR2    
   )

   IS

    -- Procedue     : SECURITIES RESTRICTION
    -- System       : Dealnet system
    -- Created by   : K.m.w.s waruna sri jayanath
    -- Created on   : 2010-10-27
    -- Added to ADLMARGIN by Prabash on 22-09-2011

   M_COUNT    NUMBER;
   M_OPTION  VARCHAR2(3);
BEGIN
  M_OPTION := M_OPTION1;
  /*
  SELECT COUNT(*) INTO M_COUNT
  FROM   DN_TRN_SECURITY_LIMIT
  WHERE  SECURITY_CODE  = M_SECURITY_CODE AND
         PORTFOLIO_CODE = M_PORT_CODE  ;

 IF M_COUNT>0 AND M_OPTION ='NEW' THEN
    M_OPTION :='MOD';
 END IF ;
 
 IF M_COUNT=0 AND M_OPTION ='MOD' THEN
    M_OPTION :='NEW';
 END IF ;
*/


IF M_OPTION ='NEW' THEN
 
 INSERT INTO DN_TRN_SECURITY_LIMIT(SECURITY_CODE, PORTFOLIO_CODE, SEC_PER, ENT_DATE,
       ENT_USER,VALUE_DATE)
 VALUES(M_SECURITY_CODE,M_PORT_CODE,M_RATE,SYSDATE,
       M_ENT_USER,to_date(M_DATE,'DD/MM/YYYY'));      

ELSIF M_OPTION = 'MOD' THEN
--RAISE_APPLICATION_ERROR(-20201,'<BR><B>Please Select Option</B><BR>');
  INSERT INTO DN_TRN_SECURITY_LIMIT_BK(SECURITY_CODE, PORTFOLIO_CODE, SEC_PER, ENT_DATE,
       ENT_USER, MOD_DATE, MOD_USER,VALUE_DATE)
  SELECT SECURITY_CODE, PORTFOLIO_CODE, SEC_PER, ENT_DATE,
       ENT_USER, MOD_DATE, MOD_USER,VALUE_DATE
  FROM   DN_TRN_SECURITY_LIMIT
  WHERE  SECURITY_CODE  = M_SECURITY_CODE --AND
         --PORTFOLIO_CODE = M_PORT_CODE 
          ;   

  UPDATE DN_TRN_SECURITY_LIMIT
  SET    SEC_PER        = M_RATE,
         MOD_DATE       = SYSDATE ,
         MOD_USER       = M_ENT_USER,
         VALUE_DATE     = to_date(M_DATE,'DD/MM/YYYY')
  WHERE  SECURITY_CODE  = M_SECURITY_CODE --AND
        -- PORTFOLIO_CODE = M_PORT_CODE 
          ; 
         
ELSIF M_OPTION = 'DEL' THEN
  INSERT INTO DN_TRN_SECURITY_LIMIT_BK(SECURITY_CODE, PORTFOLIO_CODE, SEC_PER, ENT_DATE,
       ENT_USER, MOD_DATE, MOD_USER,VALUE_DATE)
  SELECT SECURITY_CODE, PORTFOLIO_CODE, SEC_PER, ENT_DATE,
       ENT_USER, MOD_DATE, MOD_USER,VALUE_DATE
  FROM   DN_TRN_SECURITY_LIMIT
  WHERE  SECURITY_CODE  = M_SECURITY_CODE --AND
         --PORTFOLIO_CODE = M_PORT_CODE  
         ;   

  DELETE DN_TRN_SECURITY_LIMIT
  WHERE  SECURITY_CODE  = M_SECURITY_CODE --AND
        -- PORTFOLIO_CODE = M_PORT_CODE  
         ; 
else
RAISE_APPLICATION_ERROR(-20201,'<BR><B>Please Select Option</B><BR>');
END IF;



END ;

