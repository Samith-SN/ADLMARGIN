--------------------------------------------------------
--  DDL for Procedure DN_AUTO_ROLLOVER_RATECHANGE
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_AUTO_ROLLOVER_RATECHANGE" 
  (   M_E_VAL_DATE         VARCHAR2,
      M_FIX_RATE           VARCHAR2,
      M_BASE_RATE          VARCHAR2,
      M_USER               VARCHAR2,
      M_PORTFOLIO_CODE     DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE --add by waruna 2012-05-24
   )
   IS

CURSOR C1 IS
SELECT A.LEND_PORTFOLIO_CODE LENDER,A.DEAL_NO  DEALNO
FROM   DN_TRN_REPO_FRESH  A
WHERE  A.ON_CALL_DEAL = 'Y' AND A.APP_STATUS ='CONF' AND
       --(A.LEND_PORTFOLIO_CODE =M_PORTFOLIO_CODE OR  BORR_PORTFOLIO_CODE= M_PORTFOLIO_CODE) AND --add by waruna 2012-05-24
       A.BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND --add by waruna 2012-07-27
       TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') = TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
       A.DEAL_NO NOT IN (SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_ROLLOVER WHERE PRIOR_DEAL_NO= A.DEAL_NO) AND
       A.DEAL_NO NOT IN (SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_SETTLEMENT WHERE PRIOR_DEAL_NO= A.DEAL_NO) ;
       

CURSOR C2 IS
SELECT A.LEND_PORTFOLIO_CODE LENDER,A.DEAL_NO DEALNO
FROM   DN_TRN_REPO_ROLLOVER  A
WHERE  A.ON_CALL_DEAL = 'Y' AND A.APP_STATUS ='CONF' AND
       --(A.LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE OR  BORR_PORTFOLIO_CODE= M_PORTFOLIO_CODE) AND --add by waruna 2012-05-24
       BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND --add by waruna 2012-07-27
       TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') = TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
       A.DEAL_NO NOT IN (SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_ROLLOVER WHERE PRIOR_DEAL_NO= A.DEAL_NO) AND
       A.DEAL_NO NOT IN (SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_SETTLEMENT WHERE PRIOR_DEAL_NO= A.DEAL_NO) ;


 MDEAL_NO      VARCHAR2(14);
 MLENDER       VARCHAR2(10);
 M_TENOR       NUMBER  DEFAULT 0;
 MAT_DATE      VARCHAR2(15);
 LEG2_VAL      NUMBER (18,2);
 INT_AMT       NUMBER (18,2);
 MPRIOR_NO     VARCHAR2(14);
 MLEG1         NUMBER (18,2);
 M_BRANCH      VARCHAR2(30);
 MINST_TYPE    DN_TRN_REPO_FRESH_INST.INST_TYPE%TYPE;
 --MSEC_CODE     DN_REF_REPO_RATE.SEC_CODE%TYPE;
 --MSERIAL_NO    DN_REF_REPO_RATE.SERIAL_NO%TYPE;
 MHAIRCUT      DN_TRN_REPO_FRESH_INST.RPTRN_HCUT_PER%TYPE;
 --MFACE_VALUE   DN_REF_REPO_RATE.FACE_VALUE%TYPE;
 M_RATE_BASE   DN_TRN_REPO_FRESH.INT_RATE_BASE_CODE%TYPE;
 M_BORROWER    DN_TRN_REPO_FRESH.BORR_PORTFOLIO_CODE%TYPE;
 I             NUMBER;
 J             NUMBER;
 M_SECURITY           DN_TRN_REPO_ROLLOVER.SEC_ALW_LENDER%TYPE;
 M_PHYSICAL           DN_TRN_REPO_ROLLOVER.PHYSICAL_DELIVERY%TYPE;
 M_EXCHANGEABILITY    DN_TRN_REPO_ROLLOVER.EXCHANGE_SEC%TYPE;
 M_CURRENCY           DN_TRN_REPO_ROLLOVER.CURR_CODE%TYPE;
 M_BASIS              DN_REF_INTR_BASE.INTR_BASE_DESC%TYPE;
 M_VALUE_DATE_TYPE    DN_TRN_REPO_ROLLOVER.EFF_VALDATE_TYPE%TYPE;
 M_SCRIPT_STATUS      DN_TRN_REPO_ROLLOVER.SCRIPT_STATUS%TYPE;
 MM NUMBER ;
 MM_REPO_RATE         DN_REF_REPO_RATE.RATE%TYPE;
 MM_RATE              DN_REF_PORTFOLIO.RATE%TYPE;
 MM_RATE_TYPE         DN_REF_PORTFOLIO.RATE_TYPE%TYPE;
 M_RATE               NUMBER;
BEGIN

UPDATE DN_REF_REPO_RATE
SET    RATE = M_BASE_RATE;

FOR I IN C1 LOOP
 SELECT A.DEAL_NO,A.LEG1_VALUE,A.INT_RATE_BASE_CODE,A.BORR_PORTFOLIO_CODE,--LEG2_VALUE-->LEG1_VALUE by waruna 2012-07-24
        A.SEC_ALW_LENDER,A.PHYSICAL_DELIVERY,A.EXCHANGE_SEC,A.CURR_CODE,
        DN_RETURN_RATE_BASE_CODE(A.INT_RATE_BASE_CODE),A.EFF_VALDATE_TYPE,A.SCRIPT_STATUS
 INTO   MPRIOR_NO,MLEG1,M_RATE_BASE,M_BORROWER,M_SECURITY,M_PHYSICAL,
        M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,M_VALUE_DATE_TYPE,M_SCRIPT_STATUS
 FROM   DN_TRN_REPO_FRESH A
 WHERE  A.DEAL_NO=I.DEALNO;
--dbms_output.put_line('Value of M_BORROWER='||M_BORROWER);
-- TEMPORARILIY COMMENTED ON 07/08/2003
/*MINST_TYPE:='TBOND'; --ADDED TEMP
MHAIRCUT:=12; --ADDED TEMP*/

SELECT RATE,RATE_TYPE
INTO   MM_RATE,MM_RATE_TYPE
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_BORROWER;

IF MM_RATE_TYPE IS NOT NULL THEN

-- M_RATE := MM_RATE*100+TO_NUMBER(M_BASE_RATE);
M_RATE := MM_RATE+TO_NUMBER(M_BASE_RATE);
ELSE

 M_RATE := TO_NUMBER(M_FIX_RATE);
 UPDATE DN_REF_PORTFOLIO
 SET    RATE =M_FIX_RATE
 WHERE  PORTFOLIO_CODE=M_BORROWER;

END IF;

SELECT INST_TYPE,RPTRN_HCUT_PER
INTO   MINST_TYPE,MHAIRCUT
FROM   DN_TRN_REPO_FRESH_INST
WHERE  DEAL_NO=I.DEALNO;

SELECT TO_CHAR(DN_FIN_EFF_VALDATE_MAT('TOM',M_E_VAL_DATE),'DD-MON-YYYY')
INTO   MAT_DATE
FROM   DUAL;

 M_TENOR :=TO_DATE(MAT_DATE,'DD-MM-YYYY') - TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY');
--RAISE_APPLICATION_ERROR(-20201,'M_TENOR**********'||M_TENOR );
 SELECT DN_FIN_LEG2_F_LEG1(MLEG1,M_RATE,M_TENOR,M_RATE_BASE,TO_DATE(MAT_DATE,'DD/MM/YYYY'))
 INTO LEG2_VAL
 FROM DUAL;

 SELECT LEG2_VAL-MLEG1
 INTO   INT_AMT
 FROM   DUAL;
--RAISE_APPLICATION_ERROR(-20201,'INT_AMT**********'||INT_AMT ); 
 MBFSL_REPOROLLOVER_IN1(MDEAL_NO,MPRIOR_NO,M_BORROWER,I.LENDER,MINST_TYPE,MHAIRCUT,
                        M_SECURITY,M_PHYSICAL,M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,
                        M_VALUE_DATE_TYPE,M_E_VAL_DATE,M_RATE,'Y',MLEG1,LEG2_VAL,
                        MAT_DATE,M_TENOR,INT_AMT,0,0,M_USER,'MAIN1',MDEAL_NO,'N',
                        M_SCRIPT_STATUS,NULL);--,'RATE_CHANGE',M_BRANCH

-- DN_AUTO_REPOROLLOVER_JOB_ROLL(MDEAL_NO,MINST_TYPE,MHAIRCUT,M_BORROWER,MLEG1,M_RATE/100);
 DN_AUTO_REPOROLLOVER_JOB_ROLL(MDEAL_NO,MINST_TYPE,MHAIRCUT,M_BORROWER,0,M_RATE);--change by waruna 2012-05-24
 
  MBFSL_DEAL_CONFIRMATION_MT(MDEAL_NO,M_USER); --add by waruna 2012-05-24

 MDEAL_NO := NULL;

UPDATE DN_TRN_REPO_FRESH
SET    ON_CALL_DEAL='S'
WHERE  DEAL_NO=I.DEALNO;

END LOOP;

FOR J IN C2 LOOP
-- RAISE_APPLICATION_ERROR(-20201,'MLEG1**********');
SELECT A.DEAL_NO,A.LEG1_VALUE,A.INT_RATE_BASE_CODE,A.BORR_PORTFOLIO_CODE, --LEG2_VALUE-->LEG1_VALUE by waruna 2012-07-24
       A.SEC_ALW_LENDER,A.PHYSICAL_DELIVERY,A.EXCHANGE_SEC,A.CURR_CODE,
       DN_RETURN_RATE_BASE_CODE(A.INT_RATE_BASE_CODE),A.EFF_VALDATE_TYPE,A.SCRIPT_STATUS
INTO   MPRIOR_NO,MLEG1,M_RATE_BASE,M_BORROWER,M_SECURITY,M_PHYSICAL,
       M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,M_VALUE_DATE_TYPE,M_SCRIPT_STATUS
FROM   DN_TRN_REPO_ROLLOVER A
WHERE  A.DEAL_NO=J.DEALNO;
dbms_output.put_line('Value of M_BORROWER='||M_BORROWER);
SELECT RATE,RATE_TYPE
INTO   MM_RATE,MM_RATE_TYPE
FROM   DN_REF_PORTFOLIO
WHERE  PORTFOLIO_CODE=M_BORROWER;

 --RAISE_APPLICATION_ERROR(-20201,'MM_RATE_TYPE**********'||MM_RATE_TYPE);

IF MM_RATE_TYPE IS NOT NULL THEN

-- M_RATE := MM_RATE*100+TO_NUMBER(M_BASE_RATE);
 M_RATE := MM_RATE+TO_NUMBER(M_BASE_RATE);
ELSE

 M_RATE := TO_NUMBER(M_FIX_RATE);
 UPDATE DN_REF_PORTFOLIO
 SET    RATE =M_FIX_RATE
 WHERE  PORTFOLIO_CODE=M_BORROWER;
 
  dbms_output.put_line('MM_RATE_TYPE2**********'||MM_RATE_TYPE);

END IF;

-- TEMPORARILIY COMMENTED ON 07/08/2003
/*MINST_TYPE:='TBOND'; --ADDED TEMP
MHAIRCUT:=12; --ADDED TEMP*/

SELECT INST_TYPE,RPTRN_HCUT_PER
INTO   MINST_TYPE,MHAIRCUT
FROM   DN_TRN_REPO_ROLLOVER_INST
WHERE  DEAL_NO=J.DEALNO;

SELECT TO_CHAR(DN_FIN_EFF_VALDATE_MAT('TOM',M_E_VAL_DATE),'DD-MON-YYYY')
INTO   MAT_DATE
FROM   DUAL;

M_TENOR :=   TO_DATE(MAT_DATE,'DD-MM-YYYY')- TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY');

SELECT DN_FIN_LEG2_F_LEG1(MLEG1,M_RATE,M_TENOR,M_RATE_BASE,TO_DATE(MAT_DATE,'DD-MM-YYYY'))
INTO   LEG2_VAL
FROM   DUAL;

SELECT LEG2_VAL-MLEG1
INTO   INT_AMT
FROM   DUAL;
--RAISE_APPLICATION_ERROR(-20201,'INT_AMT**********'||INT_AMT);
MBFSL_REPOROLLOVER_IN1(MDEAL_NO,MPRIOR_NO,M_BORROWER,J.LENDER,MINST_TYPE,MHAIRCUT,
                       M_SECURITY,M_PHYSICAL,M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,
                       M_VALUE_DATE_TYPE,M_E_VAL_DATE,M_RATE,'Y',MLEG1,LEG2_VAL,
                       MAT_DATE,M_TENOR,INT_AMT,0,0,M_USER,'MAIN1',MDEAL_NO,'N',
                       M_SCRIPT_STATUS,NULL);--,'RATE_CHANGE',M_BRANCH

--DN_AUTO_REPOROLLOVER_JOB_ROLL(MDEAL_NO,MINST_TYPE,MHAIRCUT,M_BORROWER,MLEG1,M_RATE/100);
DN_AUTO_REPOROLLOVER_JOB_ROLL(MDEAL_NO,MINST_TYPE,MHAIRCUT,M_BORROWER,0,M_RATE);--change by waruna 2012-05-24
MBFSL_DEAL_CONFIRMATION_MT(MDEAL_NO,M_USER); --add by waruna 2012-05-24
MDEAL_NO := NULL;

UPDATE DN_TRN_REPO_ROLLOVER
SET    ON_CALL_DEAL='S'
WHERE  DEAL_NO=J.DEALNO;

END LOOP;

-- AFTER MONTH END INCREASE ON CALL BY 1---
UPDATE DN_SYS_PARAMETER_ONCALL
SET    LAST_DAILY = LAST_DAILY+1;
--
UPDATE DN_REF_RATE_CHANGE
SET    ROLLOVER_STATUS ='RUN'
WHERE  TO_DATE(CHANGE_DATE,'DD-MM-YY')= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') ;
COMMIT;


EXCEPTION WHEN OTHERS THEN
ROLLBACK;

END DN_AUTO_ROLLOVER_RATECHANGE; 

