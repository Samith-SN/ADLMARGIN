set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_REPOFRESH_IN1_UP" (
    M_DEAL_NO  IN OUT    DN_TRN_REPO_FRESH.DEAL_NO%TYPE,
    M_BORROWER_CODE      DN_TRN_REPO_FRESH.BORR_PORTFOLIO_CODE%TYPE,
    M_LENDER_CODE        DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE,
    M_INSTRUMENT         DN_TRN_REPO_FRESH_INST.INST_TYPE%TYPE,
    M_HAIR_CUT           DN_TRN_REPO_FRESH_INST.RPTRN_HCUT_PER%TYPE,
    M_SECURITY           DN_TRN_REPO_FRESH.SEC_ALW_LENDER%TYPE,
    M_PHYSICAL           DN_TRN_REPO_FRESH.PHYSICAL_DELIVERY%TYPE,
    M_EXCHANGEABILITY    DN_TRN_REPO_FRESH.EXCHANGE_SEC%TYPE,
    M_CURRENCY           DN_TRN_REPO_FRESH.CURR_CODE%TYPE,
    M_B_CODE             CHAR,
    M_VALUE_DATE_TYPE    DN_TRN_REPO_FRESH.EFF_VALDATE_TYPE%TYPE,
    M_VALUE_DATE         CHAR,
    M_YIELD              DN_TRN_REPO_FRESH.YIELD%TYPE,
    M_ON_CALL            DN_TRN_REPO_FRESH.ON_CALL_DEAL%TYPE,
    M_LEG1               DN_TRN_REPO_FRESH.LEG1_VALUE%TYPE,
    M_LEG2               DN_TRN_REPO_FRESH.LEG2_VALUE%TYPE,
    M_MAT_DATE           CHAR,
    M_TENOR              DN_TRN_REPO_FRESH.TENOR%TYPE,
    M_INTEREST           DN_TRN_REPO_FRESH.INT_AMOUNT%TYPE,
    M_USERNAME           DN_TRN_REPO_FRESH.DN_USER%TYPE,
    M_SELECT_TYPE        CHAR,
    M_DEAL_NUMBER        DN_TRN_REPO_FRESH.DEAL_NO%TYPE,
    M_CUSTODIAL_STATUS          DN_TRN_REPO_FRESH.CUSTODIAL_STATUS%TYPE,
    M_SCRIPT_STATUS       DN_TRN_REPO_FRESH.SCRIPT_STATUS%TYPE,
    M_GDEAL_NUMBER       DN_TRN_OUTP_SALE.DEAL_NO%TYPE--GROUP DEALS
)

AS

   --M_USER             DN_TRN_REPO_FRESH.DN_USER%TYPE;
   M_VAL_DATE         DN_TRN_REPO_FRESH.EFF_VALDATE%TYPE;
   --M_MATU_DATE        DN_TRN_REPO_FRESH.MATURITY_DATE%TYPE;
   M_BASIS            DN_TRN_REPO_FRESH.INT_RATE_BASE_CODE%TYPE;
   MM_CURRENCY_VALUE  DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE;--CURRENCY
   err_num   varchar2(200);
   err_msg   varchar2(200);
    M_COUNT_2 number;
    M_COUNT_3 number;
BEGIN

DN_VALIDATE_SAVE_RIGHTS(M_USERNAME,'WD_Repos_Fresh'); --added by ashini on 31/10/2005 for sr0509-047
 -----------------------Select the value date-----------------------------
    IF M_VALUE_DATE_TYPE<>'UD' THEN
       SELECT DN_FIN_EFF_VALDATE(M_VALUE_DATE_TYPE) INTO M_VAL_DATE FROM DUAL;
    ELSE
       SELECT TO_DATE(M_VALUE_DATE,'DD/MM/YYYY') INTO M_VAL_DATE FROM DUAL;
    END IF;

    -------------------------Select the base code----------------------------------
    SELECT   INT_RATE_BASE_CODE
    INTO     M_BASIS
    FROM     DN_REF_INTR_BASE
    WHERE    INTR_BASE_DESC=M_B_CODE;
    
     SELECT count(a.portfolio_code) into M_COUNT_2
     FROM dn_ref_portfolio a where a.portfolio_code=M_BORROWER_CODE;
 
     IF M_COUNT_2=0 and M_BORROWER_CODE is not null THEN
     RAISE_APPLICATION_ERROR(-20201,'****NO BORR_PORTFOLIO_CODE **'||M_BORROWER_CODE); 
     end if;
  
     SELECT count(a.portfolio_code) into M_COUNT_3
     FROM dn_ref_portfolio a where a.portfolio_code=M_LENDER_CODE; 
   
     IF M_COUNT_3=0 and M_LENDER_CODE is not null THEN
     RAISE_APPLICATION_ERROR(-20201,'****NO LEND_PORTFOLIO_CODE **'||M_LENDER_CODE); 
     end if;

         INSERT INTO DN_TEMP_REPO_FRESH
          (DEAL_NO,BORR_PORTFOLIO_CODE, LEND_PORTFOLIO_CODE,SEC_ALW_LENDER, PHYSICAL_DELIVERY,
           EXCHANGE_SEC, CURR_CODE, INT_RATE_BASE_CODE, EFF_VALDATE_TYPE, EFF_VALDATE,
           YIELD,ON_CALL_DEAL, LEG1_VALUE, LEG2_VALUE, MATURITY_DATE, TENOR,INT_AMOUNT,
           DN_USER,SCRIPT_STATUS, CUSTODIAL_STATUS , GROUP_DEALNO, APP_STATUS)

          VALUES( M_DEAL_NO,M_BORROWER_CODE, M_LENDER_CODE, M_SECURITY,M_PHYSICAL,
          M_EXCHANGEABILITY, M_CURRENCY,M_BASIS,M_VALUE_DATE_TYPE, M_VAL_DATE, 
          M_YIELD, M_ON_CALL, M_LEG1,--CURRENCY
              M_LEG2,--CURRENCY
             to_date(M_MAT_DATE,'DD/MM/YYYY'), M_TENOR,M_INTEREST,--CURRENCY --M_INTEREST,
             M_USERNAME, M_SCRIPT_STATUS, M_CUSTODIAL_STATUS, M_GDEAL_NUMBER,'CONF');--defalt ENT

         



   COMMIT;

  

END MBFSL_REPOFRESH_IN1_UP;

