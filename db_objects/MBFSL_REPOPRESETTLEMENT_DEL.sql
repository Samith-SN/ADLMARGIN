set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_REPOPRESETTLEMENT_DEL" (
    M_DEAL_NO            DN_TRN_REPO_SETTLEMENT.DEAL_NO%TYPE,
    M_PRIOR_DEAL_NO      DN_TRN_REPO_SETTLEMENT.PRIOR_DEAL_NO%TYPE,
    M_USERNAME           DN_TRN_REPO_SETTLEMENT.DN_USER%TYPE
    --M_DEAL_NUMBER        DN_TRN_REPO_SETTLEMENT.DEAL_NO%TYPE
)

AS

   M_MATURITY_DATE      DN_TRN_REPO_PRE_SETTLEMENT.MATURITY_DATE%TYPE;
   M_TENOR              DN_TRN_REPO_PRE_SETTLEMENT.TENOR%TYPE;
   M_YEILD              DN_TRN_REPO_PRE_SETTLEMENT.YEILD%TYPE;
   M_LEG2_VALUE         DN_TRN_REPO_PRE_SETTLEMENT.LEG2_VALUE%TYPE;
   M_INT_AMOUNT         DN_TRN_REPO_PRE_SETTLEMENT.INT_AMOUNT%TYPE;
   M_NEW_LEG2_VALUE     DN_TRN_REPO_PRE_SETTLEMENT.NEW_LEG2_VALUE%TYPE;
   err_num              varchar2(200);
   err_msg              varchar2(200);


BEGIN

   --DN_VALIDATE_SAVE_RIGHTS(M_USERNAME,'WD_Repos_Pre_Mature_Settlement');

   UPDATE DN_TRN_REPO_SETTLEMENT
   SET    APP_STATUS    = 'CANCEL',
          PRIOR_DEAL_NO = DEAL_NO
   WHERE  DEAL_NO = M_DEAL_NO;

   SELECT MATURITY_DATE,TENOR,YEILD,LEG2_VALUE,INT_AMOUNT,NEW_LEG2_VALUE
   INTO   M_MATURITY_DATE,M_TENOR,M_YEILD,M_LEG2_VALUE,M_INT_AMOUNT,M_NEW_LEG2_VALUE
   FROM   DN_TRN_REPO_PRE_SETTLEMENT
   WHERE  DEAL_NO = M_DEAL_NO AND PRIOR_DEAL_NO = M_PRIOR_DEAL_NO;

 IF SUBSTR(M_PRIOR_DEAL_NO,0,2) = 'RF' THEN

      UPDATE DN_TRN_REPO_FRESH
      SET    LEG2_VALUE    = M_LEG2_VALUE,
             MATURITY_DATE = M_MATURITY_DATE,
             TENOR         = M_TENOR,
             YIELD         = M_YEILD,
             INT_AMOUNT    = M_INT_AMOUNT
      WHERE  DEAL_NO    = M_PRIOR_DEAL_NO AND
             LEG2_VALUE = M_NEW_LEG2_VALUE;

    ELSIF SUBSTR(M_PRIOR_DEAL_NO,0,2) = 'RR' THEN


     UPDATE  DN_TRN_REPO_ROLLOVER
     SET     LEG2_VALUE    = M_LEG2_VALUE,
             MATURITY_DATE = M_MATURITY_DATE,
             TENOR         = M_TENOR,
             YEILD         = M_YEILD,
             INT_AMOUNT    = M_INT_AMOUNT
      WHERE  DEAL_NO    = M_PRIOR_DEAL_NO AND
             LEG2_VALUE = M_NEW_LEG2_VALUE;


    END IF;

    UPDATE DN_ACC_LICENCEE_GEN_ACCOUNT
    SET    TRNAMOUNT = M_LEG2_VALUE,
           TRNDATE   = M_MATURITY_DATE
    WHERE  DOCREFNO  = M_PRIOR_DEAL_NO AND
           TRNAMOUNT = M_NEW_LEG2_VALUE /*AND
           TO_DATE(TRNDATE,'DD-MM-YYYY')   = TO_DATE(M_SET_DATE,'DD-MM-YYYY')*/;


   INSERT INTO DN_TIME_LOG(SUS_REF_NO,DN_USER,ENT_DATE,DESCRIPTION)
   VALUES(M_DEAL_NO,M_USERNAME,SYSDATE,'DEL_PRE_MAT');

   UPDATE DN_TRN_REPO_PRE_SETTLEMENT
   SET    PRIOR_DEAL_NO = M_DEAL_NO
   WHERE  DEAL_NO = M_DEAL_NO;

   COMMIT;

/*EXCEPTION
  WHEN OTHERS THEN

    DELETE DN_TRN_REPO_SETTLEMENT
    WHERE
    DEAL_NO=M_DEAL_NO;

    DELETE DN_TRN_REPO_SETTLEMENT_SETTLE
    WHERE
    DEAL_NO=M_DEAL_NO;

    COMMIT;

    RAISE_APPLICATION_ERROR(-20201,'Data error');*/

END MBFSL_REPOPRESETTLEMENT_DEL;

