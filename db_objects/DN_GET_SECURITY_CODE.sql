  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_SECURITY_CODE" 
   (
    M_EXT_SECURITY_CODE   IN  DN_REF_SECURITY.EXT_SECURITY_CODE%TYPE

   ) RETURN  VARCHAR2


    IS

    -- FUNCTION     : EFFECTIVE VALUE DATE
    -- SYSTEM       : DEAL NET
    -- CREATED BY   : D.P. PUBUDU THUSHARA
    -- CREATED ON   : 30/06/1999

M_SECURITY_CODE     DN_REF_SECURITY.SECURITY_CODE%TYPE;

BEGIN
   
 SELECT SECURITY_CODE
 INTO   M_SECURITY_CODE
 FROM   DN_REF_SECURITY
 WHERE  EXT_SECURITY_CODE = M_EXT_SECURITY_CODE;

 RETURN M_SECURITY_CODE;

EXCEPTION WHEN OTHERS THEN
 RETURN NULL;

END ;

/
