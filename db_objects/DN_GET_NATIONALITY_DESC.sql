--------------------------------------------------------
--  DDL for Function DN_GET_NATIONALITY_DESC
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_NATIONALITY_DESC" (
    M_NATIONALITY_CODE                   IN DN_REF_NATIONALITIES.NATIONALITY_CODE % TYPE                /* 01 */
)

RETURN VARCHAR2

AS
    
    M_NATIONALITY_DESCRIPTION               DN_REF_NATIONALITIES.DESCRIPTION % TYPE;
    
BEGIN
    
    SELECT A.DESCRIPTION
    INTO   M_NATIONALITY_DESCRIPTION
    FROM   DN_REF_NATIONALITIES A
    WHERE  A.NATIONALITY_CODE = M_NATIONALITY_CODE;
    
    
    RETURN NVL(M_NATIONALITY_DESCRIPTION, '-');
    
END DN_GET_NATIONALITY_DESC;

/
