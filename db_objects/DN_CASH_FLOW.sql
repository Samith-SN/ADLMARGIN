     INSERT INTO DN_TRN_BO_CASH_FLOW
        (PORTFOLIO_CODE,OPENING_BALANCE,CLOSING_BALANCE,ENT_DATE,CASHFLOW_STARTDATE,CASHFLOW_ENDDATE)
   VALUES
        (M_PORT,MM_OPEN,MM_CLOSE,SYSDATE,MM_CASH_DATE_FROM,MM_CASH_DATE);


 IF SQL%NOTFOUND THEN
