  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CASH_FLOW" 

   (M_PORT                         DN_TRN_BO_CASH_FLOW.PORTFOLIO_CODE%TYPE,
     M_OPEN                         VARCHAR2,
    M_CLOSE                       VARCHAR2,
    M_CASH_DATE                    VARCHAR2,
M_CASH_DATE_FROM                    VARCHAR2
    )

AS
  MM_OPEN                         DN_TRN_BO_CASH_FLOW.OPENING_BALANCE%TYPE;
   MM_CLOSE                        DN_TRN_BO_CASH_FLOW.CLOSING_BALANCE%TYPE;
 MM_CASH_DATE                         DN_TRN_BO_CASH_FLOW.CASHFLOW_ENDDATE%TYPE;
MM_CASH_DATE_FROM                      DN_TRN_BO_CASH_FLOW.CASHFLOW_STARTDATE%TYPE;
BEGIN
    MM_OPEN := TO_NUMBER(M_OPEN);
     MM_CLOSE := TO_NUMBER(M_CLOSE);
    MM_CASH_DATE := TO_DATE(M_CASH_DATE,'DD-MM-YYYY');
 MM_CASH_DATE_FROM := TO_DATE(M_CASH_DATE_FROM,'DD-MM-YYYY');
