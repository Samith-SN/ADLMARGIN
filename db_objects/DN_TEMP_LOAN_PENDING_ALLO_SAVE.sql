  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_TEMP_LOAN_PENDING_ALLO_SAVE" 
(

 M_VALDATE                VARCHAR2,
 M_USER                   VARCHAR2
)

 AS

 MM_VALDATE                 DATE;
 BEGIN

-- CREATED bY : WARUNA SRI JAYANATH 2012-03-28
-- CREATED ON ADLMARGIN

MM_VALDATE := TO_DATE(M_VALDATE,'DD-MM-YYYY');
--bk Preavios day deal

INSERT INTO DN_LOAN_PENDING_ALLO
       (TRN_TYPE,DOCREFNO,PORTFOLIO_CODE, CILENT_NAME,
       BROKER, SECURITY_CODE, PRICE, TOT, ABSTOT,
       TRANSFERRED_AMOUNT, ALLO_AMOUNT,VALUE_DATE,TRAN_DATE)
       (
       SELECT 
       TRN_TYPE,DOCREFNO,PORTFOLIO_CODE, CILENT_NAME,
       BROKER, SECURITY_CODE, PRICE, TOT, ABSTOT,
       TRANSFERRED_AMOUNT, ALLO_AMOUNT,MM_VALDATE,TRAN_DATE
       FROM DN_TEMP_LOAN_PENDING_ALLO
       );
       
DELETE FROM DN_TEMP_LOAN_PENDING_ALLO; --clear table

-- day excuse money deals add to Pending_allo table for use nexet day

INSERT INTO DN_TEMP_LOAN_PENDING_ALLO
       (TRN_TYPE,DOCREFNO,PORTFOLIO_CODE, CILENT_NAME,
       BROKER, SECURITY_CODE, PRICE, TOT, ABSTOT,
       TRANSFERRED_AMOUNT, ALLO_AMOUNT,TRAN_DATE)
(SELECT A.TRN_TYPE, A.DOCREFNO, A.PORTFOLIO_CODE, A.CILENT_NAME,
       A.BROKER, A.SECURITY_CODE, A.PRICE, A.TOT, A.ABSTOT,
       A.TRANSFERRED_AMOUNT, A.ALLO_AMOUNT,TRAN_DATE
FROM DN_TEMP_LOAN_GENERATION A
WHERE NVL(TOT,0)-NVL(TRANSFERRED_AMOUNT,0)+NVL(ALLO_AMOUNT,0)<>0
AND TRN_TYPE NOT IN ('BUY','CW'));


 INSERT INTO DN_TRN_LOAN_SETTL_RECEIPT
    ( REC_NO,PORTFOLIO_CODE,SUS_REF_NO, SETTLE_MODE, SUSPENSE_ENTRY_TYPE,ID_PORTFOLIO_CODE,REC_AMOUNT,
      PAYER_BRANCH_CODE,PAYER_ACC_NO, PAYER_REF, OTH_COMMENTS, BRANCH_CODE, ACC_NO, STATUS, DN_USER, ENTDATE,EFF_VALDATE,TRN_DATE,DUE_DATE)
     (
     SELECT 
     'LRMT'||TO_CHAR(SYSDATE,'YY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_LOAN_SETTLE_REC.NEXTVAL),3,'0')
     ,LEND_PORTFOLIO_CODE,ALLO_DOCREFNO_TO,'CURR_ACC','L',BORR_PORTFOLIO_CODE,ALLO_AMOUNT,
      '','','','AUTO RECEIPT','M_BRANCH_CODE','M_ACC_NO','TBD',
      M_USER,SYSDATE,MM_VALDATE,MM_VALDATE,MM_VALDATE
      FROM DN_LOAN_DEAL_ALLOCATION A,
      (SELECT DEAL_NO,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE FROM DN_TRN_REPO_FRESH
       UNION ALL
       SELECT DEAL_NO,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE FROM DN_TRN_REPO_ROLLOVER
      ) B
      WHERE ALLO_AMOUNT > 0 
      AND A.ALLO_DOCREFNO_TO =B.DEAL_NO
      );




END ;

