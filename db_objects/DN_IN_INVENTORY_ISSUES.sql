    M_INST_TYPE          DN_TRN_BO_INV_ISSUE.INST_TYPE%TYPE,
    M_SECURITY_CODE      DN_TRN_BO_INV_ISSUE.SECURITY_CODE%TYPE,
    M_SERIAL_NO          DN_TRN_BO_INV_ISSUE.SERIAL_NO%TYPE,
    M_FACE_VALUE         DN_TRN_BO_INV_ISSUE.FACE_VALUE%TYPE,
    M_DN_USER            DN_TRN_BO_INV_ISSUE.DN_USER%TYPE,
    M_ISS_NUMBER         DN_TRN_BO_INV_ISSUE.INV_ISSUE_NO%TYPE,
    M_INV_CODE           DN_TRN_BO_INV_ISSUE.INV_CODE%TYPE,
    M_SCREEN             VARCHAR2
   )
AS
   Y NUMBER;
MN_COUNT1             NUMBER;--CURRENCY
