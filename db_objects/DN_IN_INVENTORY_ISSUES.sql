              (INV_ISSUE_NO,
               PORTFOLIO_CODE,
               DEAL_NO,
               INST_TYPE,
               SECURITY_CODE,
               SERIAL_NO,
               FACE_VALUE,
               DN_USER,
               ENTDATE,
               INV_CODE,
               FACE_VALUE_CURR--CURRENCY
              )
        VALUES
              (M_ISS_NO,
               M_PORTFOLIO_CODE,
               M_DEAL_NO,
               M_INST_TYPE,
               M_SECURITY_CODE,
               M_SERIAL_NO,
               M_FACE_VALUE*M_CURRENCY_VALUE,---CURRENCY
               M_DN_USER,
               SYSDATE,
               M_INV_CODE,
               M_FACE_VALUE--CURRENCY
               );

UPDATE DN_INV_SUS_ISSUE_SERIAL_NO SET
       ISSUE_FROM_INT_BAL_CURR=ISSUE_FROM_INT_BAL_CURR+M_FACE_VALUE,--CURRENCY
       BAL_TO_BE_ISSUED_CURR=BAL_TO_BE_ISSUED_CURR-M_FACE_VALUE,--CURRENCY
       ISSUE_FROM_INT_BAL=ISSUE_FROM_INT_BAL+(M_FACE_VALUE*M_CURRENCY_VALUE),--CURRENCY
       BAL_TO_BE_ISSUED=BAL_TO_BE_ISSUED-(M_FACE_VALUE*M_CURRENCY_VALUE)--CURRENCY
WHERE DEAL_NO=M_DEAL_NO AND SERIAL_NO=M_SERIAL_NO AND INV_CODE=M_INV_CODE AND SENDER_CODE=M_PORTFOLIO_CODE AND RECEIVER_CODE=M_SENDER_CODE;

UPDATE DN_INV_SUS_ISSUE_SEC SET
       ISSUE_FROM_INT_BAL_CURR=ISSUE_FROM_INT_BAL_CURR+M_FACE_VALUE,--CURRENCY
       BAL_TO_BE_ISSUED_CURR=BAL_TO_BE_ISSUED_CURR-M_FACE_VALUE,--CURRENCY

       ISSUE_FROM_INT_BAL=ISSUE_FROM_INT_BAL+(M_FACE_VALUE*M_CURRENCY_VALUE),--CURRENCY
       BAL_TO_BE_ISSUED=BAL_TO_BE_ISSUED-(M_FACE_VALUE*M_CURRENCY_VALUE)--CURRENCY
WHERE DEAL_NO=M_DEAL_NO AND SECURITY_CODE=M_SECURITY_CODE AND INV_CODE=M_INV_CODE AND SENDER_CODE=M_PORTFOLIO_CODE AND RECEIVER_CODE=M_SENDER_CODE;

UPDATE DN_INV_SUS_ISSUE_INST SET
       ISSUE_FROM_INT_BAL_CURR=ISSUE_FROM_INT_BAL_CURR+M_FACE_VALUE,--CURRENCY
       BAL_TO_BE_ISSUED_CURR=BAL_TO_BE_ISSUED_CURR-M_FACE_VALUE,--CURRENCY

       ISSUE_FROM_INT_BAL=ISSUE_FROM_INT_BAL+(M_FACE_VALUE*M_CURRENCY_VALUE),--CURRENCY
       BAL_TO_BE_ISSUED=BAL_TO_BE_ISSUED-(M_FACE_VALUE*M_CURRENCY_VALUE)--CURRENCY
WHERE DEAL_NO=M_DEAL_NO AND INST_TYPE=M_INST_TYPE AND INV_CODE=M_INV_CODE AND SENDER_CODE=M_PORTFOLIO_CODE AND RECEIVER_CODE=M_SENDER_CODE;






ELSE--CURRENCY
