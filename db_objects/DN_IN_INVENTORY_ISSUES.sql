  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_IN_INVENTORY_ISSUES" 

   (M_ISS_NO  IN OUT     DN_TRN_BO_INV_ISSUE.INV_ISSUE_NO%TYPE,
    M_PORTFOLIO_CODE     DN_TRN_BO_INV_ISSUE.PORTFOLIO_CODE%TYPE,
