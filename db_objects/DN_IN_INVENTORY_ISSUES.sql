       SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_INV_ISSUES.NEXTVAL),3,'0') INTO M_ISS_NO FROM DUAL;
       M_ISS_NO:='II'||M_ISS_NO;
      ELSE
       M_ISS_NO:=M_ISS_NUMBER;
      END IF;

--------------CURRENCY----------------------------------------
     SELECT COUNT(*)
     INTO   MN_COUNT1
     FROM   DN_TRN_DEAL_CURRENCY
     WHERE  DEAL_NO=M_DEAL_NO;

IF(MN_COUNT1>0)THEN--CURRENCY
       SELECT CURR_CODE
       INTO   M_CURR_CODE
       FROM   DN_TRN_DEAL_CURRENCY
       WHERE  DEAL_NO=M_DEAL_NO;

       SELECT   CURRENCY_VALUE
       INTO     M_CURRENCY_VALUE
       FROM     DN_REF_EXCHANGE_RATES
       WHERE    CURR_CODE=M_CURR_CODE;


