  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."FA_GET_PRODUCT_PACK_NAME" 
(
M_FA_PRODUCT_CODE     FA_CO_MAS_PRODUCT.FA_PRODUCT_CODE%TYPE
