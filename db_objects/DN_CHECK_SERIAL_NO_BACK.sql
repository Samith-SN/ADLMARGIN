--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_CHECK_SERIAL_NO_BACK" 
   (
    M_SECURITY_CODE           IN      DN_TRN_OUTP_SALE_SEC.SECURITY_CODE%TYPE,
    M_SERIALNO                IN      DN_TRN_OUTP_SALE_SEC.SERIAL_NO%TYPE,
    M_INST_TYPE               IN      DN_TRN_OUTP_SALE.INST_TYPE%TYPE,
    M_DEAL_NO                 IN      DN_TRN_OUTP_SALE.DEAL_NO%TYPE

     )

     RETURN VARCHAR2

     IS

CURSOR C1 IS
   SELECT  DEAL_NO
   FROM  DN_TRN_OUTP_SALE
   WHERE SECURITY_CODE=M_SECURITY_CODE AND INST_TYPE=M_INST_TYPE    AND DEAL_NO NOT IN (M_DEAL_NO) AND
   APP_STATUS NOT IN ( 'CONF' ,'CANCEL');


M_RETVAL         VARCHAR2(100)  DEFAULT 'SHOW';
M_RETVAL_NEW     VARCHAR2(100)   ;
M_APP_STATUS     VARCHAR2(10);
M_COUNT          NUMBER;
M_COUNT1         NUMBER;
M_DEAL_NO1       VARCHAR2(100);

BEGIN





   FOR I IN C1 LOOP
   SELECT NVL(COUNT(*),0) INTO M_COUNT
   FROM DN_TRN_OUTP_SALE_SEC
   WHERE DEAL_NO =I.DEAL_NO AND SERIAL_NO =M_SERIALNO;

   IF M_COUNT > 0 THEN
     M_RETVAL     :=  'NOSHOW';
     M_RETVAL_NEW :=  'NOSHOW';
   ELSE
     M_RETVAL :=  'SHOW';
   END IF;


--dbms_output.put_line(' M_RETVAL_NEW'||M_RETVAL_NEW);


 END LOOP;
   IF  M_RETVAL_NEW ='NOSHOW' THEN
    M_RETVAL     :=  'NOSHOW';
   ELSE
    M_RETVAL     :=  'SHOW';
   END IF;

--   RAISE_APPLICATION_ERROR(-20201,'M_RETVAL'||M_RETVAL);
  RETURN M_RETVAL;
  END       DN_CHECK_SERIAL_NO_BACK;

/
