set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CLIENT_STATEMENT" 
(
 M_FROMDATE         	   VARCHAR2,
 M_TODATE                  VARCHAR2,
 M_PORT                    DN_ACC_LICENCEE_GEN_ACCOUNT.PORTFOLIO_CODE%TYPE,
 M_DNPORT                  DN_ACC_LICENCEE_GEN_ACCOUNT.DN_PORTFOLIO_CODE%TYPE

)

AS

        --CREATED BY  : GAYAN
        --CREATED ON  : 29-03-2001
        --SYSTEM      : NWAM DEALNET.
        --PURPOSE     : TO DISPLAY THE CLIENT STATEMENT

          M_TRDATE         DATE;
          M_TRREFNO        CHAR(14);
          M_DR             NUMBER;
          M_CR             NUMBER;
          M_NARRATION      CHAR(100);
          M_ACC_TYPE_CODE  CHAR(10);
          M_CORR_ACC_NO    CHAR(10);


CURSOR MY_CUR IS

                SELECT TO_CHAR(TRNDATE,'DD/MON/YY'),DOCREFNO,
                DECODE(NVL(DECODE(DRCR_STATUS,'DR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
                DECODE(NVL(DECODE(DRCR_STATUS,'CR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
 		        DECODE(DN_RETURN_NARRATION(ACC_TYPE_CODE),'Repo Interest Income','REPO INTEREST INCOME','Repo Interest Expense','REPO INTEREST EXPENSE','OTHER',PROC_DESC),
                ACC_TYPE_CODE,CORR_ACC_NO
                FROM DN_ACC_LICENCEE_GEN_ACCOUNT
				WHERE PORTFOLIO_CODE=M_PORT AND
                DN_PORTFOLIO_CODE=M_DNPORT AND
				ACC_TYPE_CODE='302' AND CORR_ACC_NO NOT IN ('404','409') AND
                TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROMDATE,'DD/MM/YYYY') AND
				TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TODATE,'DD/MM/YYYY')
                GROUP BY
							  DECODE(DN_RETURN_NARRATION(ACC_TYPE_CODE),'Repo Interest Income','REPO INTEREST INCOME','Repo Interest Expense','REPO INTEREST EXPENSE','OTHER',PROC_DESC),
							  TO_CHAR(TRNDATE,'DD/MON/YY'),
							  DOCREFNO,DECODE(NVL(DECODE(DRCR_STATUS,'DR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
 							  DECODE(NVL(DECODE(DRCR_STATUS,'CR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
                              ACC_TYPE_CODE,CORR_ACC_NO

                UNION

                SELECT TO_CHAR(TRNDATE,'DD/MON/YY'),DOCREFNO,
                DECODE(NVL(DECODE(DRCR_STATUS,'DR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
                DECODE(NVL(DECODE(DRCR_STATUS,'CR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
 		        DECODE(DN_RETURN_NARRATION(ACC_TYPE_CODE),'Repo Interest Income','REPO INTEREST INCOME','Repo Interest Expense','REPO INTEREST EXPENSE','OTHER',PROC_DESC),
                ACC_TYPE_CODE,CORR_ACC_NO
                FROM DN_ACC_LICENCEE_GEN_ACCOUNT
				WHERE PORTFOLIO_CODE=M_PORT AND
                DN_PORTFOLIO_CODE=M_DNPORT AND
				ACC_TYPE_CODE='300' AND CORR_ACC_NO  IN ('406') AND
                TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROMDATE,'DD/MM/YYYY') AND
				TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TODATE,'DD/MM/YYYY')
                GROUP BY
							  DECODE(DN_RETURN_NARRATION(ACC_TYPE_CODE),'Repo Interest Income','REPO INTEREST INCOME','Repo Interest Expense','REPO INTEREST EXPENSE','OTHER',PROC_DESC),
							  TO_CHAR(TRNDATE,'DD/MON/YY'),
							  DOCREFNO,DECODE(NVL(DECODE(DRCR_STATUS,'DR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
 							  DECODE(NVL(DECODE(DRCR_STATUS,'CR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
                              ACC_TYPE_CODE,CORR_ACC_NO
                 UNION

                SELECT TO_CHAR(TRNDATE,'DD/MON/YY'),DOCREFNO,
                DECODE(NVL(DECODE(DRCR_STATUS,'DR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
                DECODE(NVL(DECODE(DRCR_STATUS,'CR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
 		        DECODE(DN_RETURN_NARRATION(ACC_TYPE_CODE),'Repo Interest Income','REPO INTEREST INCOME','Repo Interest Expense','REPO INTEREST EXPENSE','OTHER',PROC_DESC),
                ACC_TYPE_CODE,CORR_ACC_NO
                FROM DN_ACC_LICENCEE_GEN_ACCOUNT
				WHERE PORTFOLIO_CODE=M_PORT AND
                DN_PORTFOLIO_CODE=M_DNPORT AND
				ACC_TYPE_CODE='300' AND CORR_ACC_NO  IN ('411') AND
                TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROMDATE,'DD/MM/YYYY') AND
				TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TODATE,'DD/MM/YYYY')
                GROUP BY
							  DECODE(DN_RETURN_NARRATION(ACC_TYPE_CODE),'Repo Interest Income','REPO INTEREST INCOME','Repo Interest Expense','REPO INTEREST EXPENSE','OTHER',PROC_DESC),
							  TO_CHAR(TRNDATE,'DD/MON/YY'),
							  DOCREFNO,DECODE(NVL(DECODE(DRCR_STATUS,'DR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
 							  DECODE(NVL(DECODE(DRCR_STATUS,'CR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
                              ACC_TYPE_CODE,CORR_ACC_NO
                UNION

                SELECT TO_CHAR(TRNDATE,'DD/MON/YY'),DOCREFNO,
                DECODE(NVL(DECODE(DRCR_STATUS,'DR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
                DECODE(NVL(DECODE(DRCR_STATUS,'CR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
 		        DECODE(DN_RETURN_NARRATION(ACC_TYPE_CODE),'Repo Interest Income','REPO INTEREST INCOME','Repo Interest Expense','REPO INTEREST EXPENSE','OTHER',PROC_DESC),
                ACC_TYPE_CODE,CORR_ACC_NO
                FROM DN_ACC_LICENCEE_GEN_ACCOUNT
				WHERE PORTFOLIO_CODE=M_PORT AND
                DN_PORTFOLIO_CODE=M_DNPORT AND
				ACC_TYPE_CODE IN ('404','409') AND CORR_ACC_NO  IN ('800') AND
                TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROMDATE,'DD/MM/YYYY') AND
				TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TODATE,'DD/MM/YYYY')
                GROUP BY
							  DECODE(DN_RETURN_NARRATION(ACC_TYPE_CODE),'Repo Interest Income','REPO INTEREST INCOME','Repo Interest Expense','REPO INTEREST EXPENSE','OTHER',PROC_DESC),
							  TO_CHAR(TRNDATE,'DD/MON/YY'),
							  DOCREFNO,DECODE(NVL(DECODE(DRCR_STATUS,'DR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
 							  DECODE(NVL(DECODE(DRCR_STATUS,'CR',TRNAMOUNT),0),0,0,TRNAMOUNT,TRNAMOUNT),
                              ACC_TYPE_CODE,CORR_ACC_NO
                 ORDER BY 2;
   BEGIN

       DELETE DN_TEMP_CLIENT_STATEMENT;

   OPEN MY_CUR;
   LOOP


          M_DR            :=0;
          M_CR            :=0;


     FETCH MY_CUR INTO M_TRDATE,M_TRREFNO,M_DR,M_CR,M_NARRATION,M_ACC_TYPE_CODE,M_CORR_ACC_NO;
   EXIT WHEN MY_CUR%NOTFOUND;




         INSERT INTO DN_TEMP_CLIENT_STATEMENT
                  (TRDATE,TRREFNO,DR,CR,NARRATION,ACC_TYPE_CODE,CORR_ACC_NO)
                VALUES
                  (M_TRDATE,M_TRREFNO,M_DR,M_CR,M_NARRATION,M_ACC_TYPE_CODE,M_CORR_ACC_NO);



    END LOOP;
    COMMIT;
    CLOSE MY_CUR;




    END DN_CLIENT_STATEMENT;

