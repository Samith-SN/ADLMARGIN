--  DDL for Procedure DN_RPT_INST_STATEMENT_IR
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_RPT_INST_STATEMENT_IR" 
(
M_FROM_DATE                 VARCHAR2,
M_TO_DATE                   VARCHAR2,
M_PORTFOLIO_CODE            DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE,
M_USER                      DN_TEMP_INST_STATEMENT_IR.USER_NAME%TYPE

)
 AS

 M_DATE           DATE;
 M_NO_OF_MONTH    NUMBER;
 M_COUNT          NUMBER;

 BEGIN
  DELETE FROM DN_TEMP_INST_STATEMENT_IR WHERE USER_NAME=M_USER;
--  COMMIT;
  --------------------------------------------------------------------
 INSERT INTO DN_TEMP_INST_STATEMENT_IR(YEAR,MONTH,INTEREST,WHT,TOTAL,USER_NAME)
  SELECT
    TO_CHAR(TO_DATE(TO_CHAR(TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY'),'YYYY'),
    TO_CHAR(TO_DATE(TO_CHAR(TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY'),'MON'),
    SUM(DECODE(DRCR_STATUS,'DR',TRNAMOUNT,'CR',-1*TRNAMOUNT)),
    0,
    SUM(DECODE(DRCR_STATUS,'DR',TRNAMOUNT,'CR',-1*TRNAMOUNT)),
    M_USER
 FROM  DN_ACC_PORTF_GEN_ACCOUNT A , DN_REF_PORTFOLIO B
 WHERE A.PORTFOLIO_CODE = B.PORTFOLIO_CODE AND
       A.PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       B.PF_TYPE  = 'P' AND B.OWNED_BY_MBFSL = 'N' AND
       A.ACC_TYPE_CODE  = '112' AND
       A.TRNDATE   >=TO_DATE(M_FROM_DATE,'DD-MM-YYYY') AND
       A.TRNDATE   <=LAST_DAY(TO_DATE(M_TO_DATE,'DD-MM-YYYY'))
 GROUP BY A.PORTFOLIO_CODE,TO_DATE(TO_CHAR(TRNDATE,'MON-YYYY'),'MON-YYYY'),
    TO_CHAR(TO_DATE(TO_CHAR(TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY'),'YYYY'),
    TO_CHAR(TO_DATE(TO_CHAR(TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY'),'MON');

SELECT COUNT(*)
  INTO   M_COUNT
  FROM   DN_TEMP_INST_STATEMENT_IR;

SELECT MONTHS_BETWEEN(TO_DATE(M_TO_DATE,'DD-MM-YYYY'),TO_DATE(M_FROM_DATE,'DD-MM-YYYY')) INTO M_NO_OF_MONTH FROM DUAL;

FOR  X IN 0..M_NO_OF_MONTH LOOP

  SELECT COUNT(*)
  INTO   M_COUNT
  FROM   DN_TEMP_INST_STATEMENT_IR
  WHERE  USER_NAME = M_USER AND
         MONTH = TO_CHAR(ADD_MONTHS(TO_DATE(M_FROM_DATE,'DD-MM-YYYY'),X),'MON') AND
         YEAR  = TO_CHAR(ADD_MONTHS(TO_DATE(M_FROM_DATE,'DD-MM-YYYY'),X),'YYYY') ;

  IF M_COUNT=0 THEN
    INSERT INTO DN_TEMP_INST_STATEMENT_IR(MONTH,YEAR,INTEREST,WHT,TOTAL,USER_NAME)
    VALUES (TO_CHAR(ADD_MONTHS(TO_DATE(M_FROM_DATE,'DD-MM-YYYY'),X),'MON'),
            TO_CHAR(ADD_MONTHS(TO_DATE(M_FROM_DATE,'DD-MM-YYYY'),X),'YYYY'),
            0,0,0,M_USER);
  END IF;

END LOOP;

--add by waruna/pb 2012-01-13
FOR  X IN 0..M_NO_OF_MONTH LOOP
-------------------
 UPDATE DN_TEMP_INST_STATEMENT_IR 
 SET ODI_INT = nvl(DN_GET_OD_ACCRUED_INTEREST(M_PORTFOLIO_CODE,TRUNC(ADD_MONTHS(TO_DATE(M_FROM_DATE,'DD-MM-YYYY'),x),'MON') ,LAST_DAY(ADD_MONTHS(TO_DATE(M_FROM_DATE,'DD-MM-YYYY'),x))),0)

 WHERE  USER_NAME = M_USER AND
         MONTH = TO_CHAR(ADD_MONTHS(TO_DATE(M_FROM_DATE,'DD-MM-YYYY'),X),'MON') AND
         YEAR  = TO_CHAR(ADD_MONTHS(TO_DATE(M_FROM_DATE,'DD-MM-YYYY'),X),'YYYY') ;                  
-------------------

END LOOP;
--add by waruna/Pb 2012-01-13


COMMIT;
END;

