--------------------------------------------------------
--  DDL for Procedure DN_MARKET_VALUES_DEBT
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_MARKET_VALUES_DEBT" 
   (
    M_SECURITY_CODE             DN_TRN_MARKET_RATE_DEBT.SECURITY_CODE%TYPE,
    M_VALUE_DATE                VARCHAR2,
    M_MARKET_RATE               VARCHAR2
  )
AS


   M_MARKET_RATE2              DN_TRN_MARKET_RATE_DEBT.MARKET_RATE%TYPE;
   M_CNT  NUMBER DEFAULT 0;
BEGIN

   M_MARKET_RATE2:=TO_NUMBER((M_MARKET_RATE/100));

    SELECT    COUNT(*) INTO M_CNT FROM
    DN_TRN_MARKET_RATE_DEBT WHERE SECURITY_CODE=M_SECURITY_CODE AND DN_DATE = TO_DATE(M_VALUE_DATE,'DD-MM-YYYY');

    IF M_CNT > 0 THEN
    DELETE FROM
    DN_TRN_MARKET_RATE_DEBT WHERE SECURITY_CODE=M_SECURITY_CODE AND DN_DATE = TO_DATE(M_VALUE_DATE,'DD-MM-YYYY');

   INSERT INTO DN_TRN_MARKET_RATE_DEBT
   (SECURITY_CODE,MARKET_RATE,DN_DATE)
   VALUES
   (M_SECURITY_CODE,M_MARKET_RATE2,TO_DATE(M_VALUE_DATE,'DD/MM/YYYY'));

   ELSE

   INSERT INTO DN_TRN_MARKET_RATE_DEBT
   (SECURITY_CODE,MARKET_RATE,DN_DATE)
   VALUES
   (M_SECURITY_CODE,M_MARKET_RATE2,TO_DATE(M_VALUE_DATE,'DD/MM/YYYY'));

   END IF;

   COMMIT;

   EXCEPTION WHEN OTHERS THEN
   ROLLBACK;

END DN_MARKET_VALUES_DEBT;

