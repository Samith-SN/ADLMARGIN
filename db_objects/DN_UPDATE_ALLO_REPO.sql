--------------------------------------------------------
--  DDL for Procedure DN_UPDATE_ALLO_REPO
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_UPDATE_ALLO_REPO" 
(
 M_DEAL_NO          DN_TRN_REPO_SETTLEMENT.DEAL_NO%TYPE
 )
 AS

   CURSOR MY_CUR IS
      SELECT A.SERIAL_NO,A.DEAL_NO
      FROM   DN_INV_REPO_DEAL_SERIAL_NO A,
             DN_INV_REPO_DEAL_SERNO_ALLO B
      WHERE  B.DEAL_NO=(SELECT PRIOR_DEAL_NO
                        FROM   DN_TRN_REPO_SETTLEMENT
                         WHERE  DEAL_NO=M_DEAL_NO) AND
             B.PREV_DEAL_NO=A.DEAL_NO AND
             B.SERIAL_NO=A.SERIAL_NO  ;

 CURSOR MY_CUR_OR IS
      SELECT A.SERIAL_NO,A.DEAL_NO
      FROM   DN_INV_OUTPS_DEAL_SERIAL_NO A,
             DN_INV_OUTPS_DEAL_SERNO_ALLO B
      WHERE  B.DEAL_NO=(SELECT PRIOR_DEAL_NO
                        FROM   DN_TRN_REPO_SETTLEMENT
                         WHERE  DEAL_NO=M_DEAL_NO) AND
             B.PREV_DEAL_NO=A.DEAL_NO AND
             B.SERIAL_NO=A.SERIAL_NO  ;


MM_SERIAL_NO           DN_INV_REPO_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
MM_DEAL_NO             DN_TRN_REPO_SETTLEMENT.DEAL_NO%TYPE;
MMM_SERIAL_NO           DN_INV_REPO_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
MMM_DEAL_NO             DN_TRN_REPO_SETTLEMENT.DEAL_NO%TYPE;

 BEGIN

      --CREATED ON  :05-09-2001
      --CREATED BY  :NIRMALA FERNANDO
      --SYSTEM      :MBFSL DEALNET
 OPEN MY_CUR;
 LOOP
 FETCH MY_CUR INTO MM_SERIAL_NO,MM_DEAL_NO;
 EXIT WHEN MY_CUR%NOTFOUND;

    UPDATE DN_INV_REPO_DEAL_SERIAL_NO
    SET    ALLO_REPO=0
    WHERE  DEAL_NO=MM_DEAL_NO AND
           SERIAL_NO=MM_SERIAL_NO;


 END LOOP;
 CLOSE MY_CUR;

OPEN MY_CUR_OR;
 LOOP
 FETCH MY_CUR_OR INTO MMM_SERIAL_NO,MMM_DEAL_NO;
 EXIT WHEN MY_CUR_OR%NOTFOUND;

    UPDATE DN_INV_OUTPS_DEAL_SERIAL_NO
    SET    ALLO_REPO=0
    WHERE  DEAL_NO=MMM_DEAL_NO AND
           SERIAL_NO=MMM_SERIAL_NO;


 END LOOP;
 CLOSE MY_CUR_OR;



 --COMMIT;
 END DN_UPDATE_ALLO_REPO;

