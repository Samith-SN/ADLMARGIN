set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_TEMP_UPD_TRN_LIST_MOVE" 
(
 M_USER_NAME         DN_TEMP_TRN_LIST.USER_NAME%TYPE,
 M_TRN_TYPE          VARCHAR  -- add by waruna 2010-19-16
/*, M_COUNT             NUMBER*/
)
AS
M_DEAL_NO              DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
M_SECURITY_CODE        DN_REF_SECURITY.SECURITY_CODE%TYPE;
M_ISSUER_CODE          DN_REF_SECURITY.ISSUER_CODE%TYPE;
M_GUARANTEE_CODE       DN_REF_SECURITY.GUARANTEE_CODE%TYPE;
M_INST_TYPE            DN_REF_SECURITY.INST_TYPE%TYPE;
M_CURR_CODE            DN_REF_SECURITY.CURR_CODE%TYPE;
M_DEAL_NUMBER          DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
M_PAR_VALUE            DN_REF_SECURITY.PAR_VALUE%TYPE;
M_S_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_B_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_B_PORT_CODE          DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
M_S_PORT_CODE          DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
M_SEC_COUNT            NUMBER;
M_BRO_COUNT            NUMBER;
M_COUNT                NUMBER;
MM_COUNT               NUMBER; 
M_PF_COUNT             NUMBER;
M_ERROR_COUNT          NUMBER;
M_ERROR_STR            VARCHAR2(200);   
M_TEMP_MARGIN_CALL    DN_REF_PORTFOLIO.TEMP_MARGIN_CALL_STATUS%TYPE;
M_FACE_VAL            NUMBER;
M_PORTFOLIO_CODE      DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
--M_SECURITY_CODE   DN_REF_SECURITY.SECURITY_CODE %TYPE;

BEGIN
 --CAREATED BY WARUNA SRI JAYANATH 
 --DELETE DN_TEMP_TRN_UPLOAD_ERROR_LOG;

 
 DELETE FROM DN_TEMP_TRN_LIST WHERE TRN_DATE IS NULL;  -- add by waruna 2010-09-13
 FOR X IN (SELECT TO_CHAR(TRN_DATE,'DD-MM-YYYY') TRN_DATE,
                  TRN_TIME,
                  DEAL_TYPE,
                  CONTRACT_NO,
                  REPLACE(EXT_SECURITY_CODE,' ','') EXT_SECURITY_CODE,
                  QTY,
                  PRICE,
                  INTERNAL_USER,
                  REF_NO,
                  CLIENT_CDS,--DECODE(DEAL_TYPE,'B',DN_GET_PORTFOLIO_CODE(CLIENT_CDS),BROKER) BUY,
                  BROKER,--DECODE(DEAL_TYPE,'S',DN_GET_PORTFOLIO_CODE(CLIENT_CDS),BROKER) SEL,
                  SEC_FEE+CSE_FEE+CDS_FEE+CESS_FEE+BROKERAGE+GOVT_LEVY BROKERAGE,
                  ORDER_ID,
                  TO_CHAR(DN_FIN_BUYER_SETTLE_DATE(TO_CHAR(TRN_DATE,'DD-MM-YYYY'),'3'),'DD-MM-YYYY') BUY_SET,
                  TO_CHAR(DN_FIN_BUYER_SETTLE_DATE(TO_CHAR(TRN_DATE,'DD-MM-YYYY'),'3'),'DD-MM-YYYY') SEL_SET
           FROM   DN_TEMP_TRN_LIST_FAIL--DN_TEMP_TRN_LIST
           WHERE  USER_NAME = M_USER_NAME
          -- AND DEAL_TYPE=M_TRN_TYPE  --add by waruna 2010-09-15
           AND EXT_SECURITY_CODE IS NOT NULL ) LOOP
M_FACE_VAL    := 0;
M_ERROR_COUNT := 0;
M_ERROR_STR   := '';
 
 
   
 ------------------------BACKUP FALI DATA-------------------------------
  INSERT INTO  DN_TEMP_TRN_LIST_FAIL_BK( TRN_DATE, TRN_TIME, DEAL_TYPE, CONTRACT_NO,
          EXT_SECURITY_CODE, QTY, PRICE, INTERNAL_USER, REF_NO,
          CLIENT_CDS, BROKER, SEC_FEE, CSE_FEE, CDS_FEE,
          CESS_FEE, BROKERAGE, ORDER_ID, USER_NAME, STATUS,
          GOVT_LEVY,REJ_STATUS,Bk_user)(
  SELECT  TRN_DATE, TRN_TIME, DEAL_TYPE, CONTRACT_NO,
          EXT_SECURITY_CODE, QTY, PRICE, INTERNAL_USER, REF_NO,
          CLIENT_CDS, BROKER, SEC_FEE, CSE_FEE, CDS_FEE,
          CESS_FEE, BROKERAGE, ORDER_ID, USER_NAME, STATUS,
          GOVT_LEVY,M_ERROR_STR,M_USER_NAME
   FROM DN_TEMP_TRN_LIST_FAIL
    WHERE REF_NO  = X.REF_NO 
   AND CLIENT_CDS = X.CLIENT_CDS
   AND DEAL_TYPE  = X.DEAL_TYPE 
   and USER_NAME  = M_USER_NAME);
   
   
   INSERT INTO  DN_TEMP_TRN_LIST( TRN_DATE, TRN_TIME, DEAL_TYPE, CONTRACT_NO,
          EXT_SECURITY_CODE, QTY, PRICE, INTERNAL_USER, REF_NO,
          CLIENT_CDS, BROKER, SEC_FEE, CSE_FEE, CDS_FEE,
          CESS_FEE, BROKERAGE, ORDER_ID, USER_NAME, STATUS,
          GOVT_LEVY)(
   SELECT  TRN_DATE, TRN_TIME, DEAL_TYPE, CONTRACT_NO,
          EXT_SECURITY_CODE, QTY, PRICE, INTERNAL_USER, REF_NO,
          CLIENT_CDS, BROKER, SEC_FEE, CSE_FEE, CDS_FEE,
          CESS_FEE, BROKERAGE, ORDER_ID, USER_NAME, STATUS,
          GOVT_LEVY
   FROM  DN_TEMP_TRN_LIST_FAIL
   WHERE REF_NO   = X.REF_NO 
   AND CLIENT_CDS = X.CLIENT_CDS 
   AND DEAL_TYPE  = X.DEAL_TYPE 
   AND USER_NAME  = M_USER_NAME);
  --RAISE_APPLICATION_ERROR(-20001,'X.REF_NO'||X.REF_NO||'X.CLIENT_CDS '||X.CLIENT_CDS||X.DEAL_TYPE||M_USER_NAME ); 
   
   DELETE FROM DN_TEMP_TRN_LIST_FAIL 
   WHERE REF_NO   = X.REF_NO 
   AND CLIENT_CDS = X.CLIENT_CDS 
   AND DEAL_TYPE  = X.DEAL_TYPE
   and USER_NAME  = M_USER_NAME ;
   
  




-------------------------------------------------------------
 SELECT COUNT(*)
     INTO   MM_COUNT
     FROM   DN_TRN_OUTP_SALE
     WHERE  CONTRACT_NO         = TO_CHAR(X.REF_NO) 
     AND    APP_STATUS          <> 'CANCEL'
     AND    BUY_PORTFOLIO_CODE  = M_B_PORT_CODE 
     AND    SELL_PORTFOLIO_CODE = M_S_PORT_CODE AND --add by waruna Sri JAyanath
     --TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(X.TRN_DATE,'DD-MM-YYYY'); comment and mod by waruna 2011-02-03
     EFF_VALDATE         = TO_DATE(X.TRN_DATE,'DD-MM-YYYY');
     
   DELETE FROM   DN_TEMP_TRN_LIST
   WHERE  USER_NAME = M_USER_NAME  
   AND DEAL_TYPE    = X.DEAL_TYPE 
   AND REF_NO       = X.REF_NO 
   AND BROKER       = X.BROKER
   AND (MM_COUNT)   >0;


--RAISE_APPLICATION_ERROR(-20001,'M_USER_NAME'||M_USER_NAME||'Count'||MM_COUNT);

-----------------------------------------------------------

 END LOOP;
 --DONT USE DELETE BELLOW
 --DELETE FROM   DN_TEMP_TRN_LIST WHERE  USER_NAME = M_USER_NAME  AND DEAL_TYPE=M_TRN_TYPE ;--add by waruna 2010-09-15
COMMIT;
END ;

