--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_ADVISOR_NAME" 
(
  M_PORTFOLIO_CODE		DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE
)
RETURN VARCHAR2

AS
M_PF_NAME VARCHAR2(100):='-';

BEGIN

SELECT DISTINCT NVL(A.ADV_NAME,'-')
INTO   M_PF_NAME
FROM   DN_REF_ADVISOR A,DN_REF_PORT_ADV B
WHERE  UPPER(B.PORT_CODE)=UPPER(M_PORTFOLIO_CODE) AND B.ADV_CODE = A.ADV_CODE ;


RETURN M_PF_NAME;

END RETURN_ADVISOR_NAME;

/
