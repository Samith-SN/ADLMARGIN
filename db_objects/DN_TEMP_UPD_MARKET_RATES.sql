set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_TEMP_UPD_MARKET_RATES" 
(
 M_EXTERNAL_CODE      DN_TEMP_MARKET_RATES.EXTERNAL_CODE%TYPE,
 M_PRICE              VARCHAR2,--DN_TEMP_MARKET_RATES.PRICE%TYPE
 M_NO_OF_SHARES       NUMBER,
 M_COUNT              NUMBER,
 M_USER              varchar

)
AS
M_PRICE1              VARCHAR2(50);--DN_TEMP_MARKET_RATES.PRICE%TYPE
M_PRICE2              DN_TEMP_MARKET_RATES.PRICE%TYPE;

BEGIN

DN_VALIDATE_SAVE_RIGHTS(M_USER,'WD_SEC_RATE_ENTRY');  --added by ashini on 31/10/2005 for sr0509-047

 -- CAREATED BY SA ON 06-10-2004 TO UPDATE THE TEMP TABLE FROM EXCEL SHEET
 IF M_COUNT =0 THEN
    DELETE DN_TEMP_MARKET_RATES;
    --WHERE  EXTERNAL_CODE = M_EXTERNAL_CODE;
 END IF;
 SELECT REPLACE(M_PRICE,'XD','') INTO  M_PRICE1 FROM DUAL;
 SELECT TO_NUMBER(REPLACE(M_PRICE1,'XR','')) INTO  M_PRICE2 FROM DUAL;

 IF (M_EXTERNAL_CODE IS NOT NULL AND M_PRICE IS NOT NULL AND M_NO_OF_SHARES>=100) THEN

   INSERT INTO DN_TEMP_MARKET_RATES(EXTERNAL_CODE,PRICE,ROW_COUNT)
   VALUES(TRIM(M_EXTERNAL_CODE),TRIM(M_PRICE2),M_COUNT);

 END IF;

COMMIT;
END ;

