--  DDL for Procedure DN_UPDATE_MARKET_RATES
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_UPDATE_MARKET_RATES" 
(
M_USERNAME           DN_TRN_REPO_FRESH.DN_USER%TYPE,
M_DATE               VARCHAR2--DN_TRN_MARKET_RATE_EQUI.DN_DATE%TYPE

)
AS

M_DN_DATE            DN_TRN_MARKET_RATE_EQUI.DN_DATE%TYPE;
M_DN_COUNT           NUMBER;
M_LAST_DAILY         DATE;
BEGIN

 --CREATED BY SA ON 07-10-2004 TO UPDATE MARKET RATES FOR SYSTEM DATE

 DELETE DN_TRN_MARKET_RATE_EQUI
 WHERE  DN_DATE=TO_DATE(M_DATE,'DD-MM-YYYY');

 --added by sva on 21-12-2004
   --------- SELECT MAX(DN_DATE)+1 INTO M_DN_DATE
   ----------- FROM   DN_TRN_MARKET_RATE_EQUI;
    --HAVING TO_CHAR(MAX(DN_DATE)+1,'DD-MON-YYYY')<= TO_CHAR(SYSDATE,'DD-MON-YYYY') ;


 /*IF M_DN_DATE IS NULL THEN
   RAISE_APPLICATION_ERROR(-20001,'Error');
 END IF ;
 -- end
 IF TO_DATE(TO_CHAR(M_DN_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(TO_CHAR(SYSDATE,'DD-MON-YYYY'),'DD-MON-YYYY') THEN
*/
 INSERT INTO DN_TRN_MARKET_RATE_EQUI(SECURITY_CODE , MARKET_RATE , DN_DATE)
 (SELECT SECURITY_CODE,PRICE/100,TO_DATE(M_DATE,'DD-MM-YYYY')--M_DN_DATE--TO_DATE(TO_CHAR(SYSDATE,'DD-MON-YYYY'),'DD-MON-YYYY')
  FROM   DN_TEMP_MARKET_RATES A,DN_REF_SECURITY B
  WHERE  EXT_SECURITY_CODE = EXTERNAL_CODE 
  AND   ROW_COUNT IN (SELECT MAX(ROW_COUNT) 
                      FROM DN_TEMP_MARKET_RATES C 
                      WHERE  A.EXTERNAL_CODE = C.EXTERNAL_CODE ) );
                      
   --ADD BY WARUNA 2012-02-01--------
        
   SELECT GREATEST(A.LAST_DAILY,B.LAST_DAILY) INTO M_LAST_DAILY  
   FROM DN_SYS_PARAMETER A,DN_SYS_DAILY_MARGIN_TRADING B;
    
   IF TO_DATE(M_DATE,'DD-MM-YYYY')>=M_LAST_DAILY THEN
       DN_MARGIN_CALL_STATUS(TO_CHAR(M_LAST_DAILY,'DD-MM-YYYY'));
   END IF;                
   --END BY WARUNA 2012-02-01--------
   

COMMIT;

EXCEPTION
     WHEN OTHERS THEN
      ROLLBACK;
      RAISE_APPLICATION_ERROR(-20001,TO_CHAR(SQLCODE)||SQLERRM||'Error..');

END ;

/
