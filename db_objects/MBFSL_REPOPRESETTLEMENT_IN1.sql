             M_DEAL_NO,
             M_PRIOR_DEAL_NO,
             M_CURR,
             M_S_DATE,
             M_NEW_LEG2_VALUE*MM_CURRENCY_VALUE,--CURRENCY
             M_USER
             );
--ADDED FOR TIME LOG MANAGEMENT BY S.YASODHA

              INSERT INTO DN_TIME_LOG
          (SUS_REF_NO,
           DN_USER,
           ENT_DATE,
           DESCRIPTION)
