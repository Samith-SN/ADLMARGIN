  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CORPORATE_ACTIONS_AMAL" 
(
   M_LAST_DAILY         DATE,
   M_USERNAME           VARCHAR2 --add by waruna 2012-10-11
)

IS

 CURSOR C1 IS
 
 SELECT PORT,SEC,INST,SUM(NOOFSHARES) NOOFSHARES,BROKER,ACTI_REF_NO FROM (
  
 SELECT A.PORTFOLIO_CODE PORT,A.SECURITY_CODE SEC,A.INST_TYPE INST,
 A.FACE_VAL NOOFSHARES ,A.DEAL_NO DEALNO,A.SERIAL_NO SNO,A.EFF_VALDATE EFFDATE,
 DEAL_YIELD AA,YIELD_WITH_BROKERAGE BB,SCRIP_FACE_VAL CC,FACE_VAL DD,INITIAL_COST EE,
 BROKERAGE FF,PRICE_INT_ACCR GG,CARR_VAL HH,
 COUP_INT_PURCH II,COUP_INT_ACCR JJ,TOT_COUP_INT KK,
 FWD_SALE LL,FWD_PURCHASE MM,LOCATION NN,
 ALLO_REPO OO,ALLO_BL PP,FWD_ALLO_REPO QQ,
 FWD_ALLO_BL RR,SALE_DEAL_NO SS,RET_DUE_DATE TT,COST_TRANS_STATUS UU,
 SCRIP_STATUS VV,FACE_VAL_CURR WW,ORG_SERNO XX,
 
   --ADD by WARUNA 2012-05-30
 (SELECT ACTI_REF_NO FROM DN_CORPORATE_ACTIONS C
  WHERE
  C.ACTIVITY IN ('AMALGAMATION') 
  AND C.XC_DATE = TRUNC(M_LAST_DAILY,'DD')
  AND C.INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT
                      WHERE INST_CAT ='EQUITY') 
  AND C.STATUS = 'ENT' 
  AND C.SECURITY_CODE=A.SECURITY_CODE
  ) ACTI_REF_NO,
  GET_PORT_BROKER(A.PORTFOLIO_CODE,A.DEAL_NO) BROKER
 --ADD by WARUNA 2012-05-30
 
 FROM DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_REF_SECURITY B
 WHERE A.SECURITY_CODE=B.SECURITY_CODE
 AND A.SERIAL_NO_STATUS='INV'
 AND A.SECURITY_CODE IN (SELECT SECURITY_CODE FROM DN_CORPORATE_ACTIONS A
 WHERE
 A.ACTIVITY IN ('AMALGAMATION')  AND A.XC_DATE =  TRUNC(M_LAST_DAILY,'DD')
 AND A.INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT
 WHERE INST_CAT ='EQUITY')  AND STATUS = 'ENT' )--;
 )GROUP BY PORT,SEC,INST,BROKER,ACTI_REF_NO;

 CURSOR C2 IS SELECT DISTINCT SECURITY_CODE SECU FROM DN_CORPORATE_ACTIONS A
 WHERE
 A.ACTIVITY IN ('AMALGAMATION')  AND A.XC_DATE =  TRUNC(M_LAST_DAILY,'DD')
 AND A.INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT
 WHERE INST_CAT ='EQUITY') AND STATUS = 'ENT';

 I             NUMBER;
 J             NUMBER;
 M_PAR         NUMBER;
 NEW_PAR       NUMBER;
 M_CNT         NUMBER DEFAULT 0;
 NO_OF_SHARES  NUMBER;
 NR            NUMBER;
 DR            NUMBER;
 SEC_CODE      DN_REF_SECURITY.SECURITY_CODE%TYPE;
 MISSUER_CODE  DN_REF_SECURITY.ISSUER_CODE%TYPE;
 MISSUER_CODE1 DN_REF_PRIMARY_ISSUER.ISSUER_CODE%TYPE;
 MISSUER_NAME  DN_REF_PRIMARY_ISSUER.ISSUER_NAME%TYPE;
 M_DEAL_NO     DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
 M_END_CODE    VARCHAR2(1);
 EDATE         DATE;
 AA VARCHAR2(100);
 BB VARCHAR2(100);
 CC VARCHAR2(100);
 DD NUMBER;
 MPRICE  NUMBER;
 SHARE_PRICE  NUMBER;
  MINST DN_REF_INSTRUMENT.INST_TYPE%TYPE;



BEGIN

--SELECT  TRUNC(M_LAST_DAILY,'DD') INTO EDATE FROM DUAL;
SELECT  TRUNC(M_LAST_DAILY+1,'DD') INTO EDATE FROM DUAL; --CHANGE BY WARUNA 2012-10-11



FOR I IN C1 LOOP
M_DEAL_NO :='';

SEC_CODE := I.SEC  ;
MINST := I.INST  ;

 SELECT   RATIO1,RATIO2,PRICE INTO NR,DR,MPRICE
 FROM DN_CORPORATE_ACTIONS
 WHERE ACTIVITY = 'AMALGAMATION' AND SECURITY_CODE=I.SEC AND INST_TYPE=I.INST
 AND XC_DATE =  TRUNC(M_LAST_DAILY,'DD');

 SELECT FLOOR((I.NOOFSHARES/NR)*DR) INTO  NO_OF_SHARES FROM DUAL;

/*
 UPDATE DN_INV_OUTPS_DEAL_SERIAL_NO SET
 SERIAL_NO_STATUS ='AMAL' , SALE_EFF_VALDATE =I.EFFDATE
 WHERE
 PORTFOLIO_CODE = I.PORT AND SECURITY_CODE = I.SEC
 AND INST_TYPE=I.INST AND DEAL_NO=I.DEALNO AND SERIAL_NO=I.SNO
 AND EFF_VALDATE = I.EFFDATE ;


 INSERT INTO DN_INV_OUTPS_DEAL_SERIAL_NO ( PORTFOLIO_CODE,EFF_VALDATE,
    INST_TYPE,    SECURITY_CODE,    DEAL_NO,
