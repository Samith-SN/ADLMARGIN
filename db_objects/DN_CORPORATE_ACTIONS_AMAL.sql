    SCRIP_FACE_VAL,    FACE_VAL,    INITIAL_COST,
    BROKERAGE,    PRICE_INT_ACCR,    CARR_VAL,
    COUP_INT_PURCH,    COUP_INT_ACCR,    TOT_COUP_INT,
    FWD_SALE,    FWD_PURCHASE,    LOCATION,
    ALLO_REPO,    ALLO_BL,    FWD_ALLO_REPO,
    FWD_ALLO_BL,    SALE_DEAL_NO,    SERIAL_NO_STATUS,
    RET_DUE_DATE,    COST_TRANS_STATUS,
    SCRIP_STATUS,    FACE_VAL_CURR,    ORG_SERNO) --SALE_EFF_VALDATE IS NULL
VALUES
    (I.PORT,I.EFFDATE,I.INST,I.SEC,
    I.DEALNO,I.SNO||'A',I.AA,I.BB,NO_OF_SHARES,NO_OF_SHARES,I.EE,
    I.FF,I.GG,I.HH,I.II,I.JJ,I.KK,I.LL,I.MM,I.NN,I.OO,I.PP,I.QQ,
    I.RR,I.SS,'INV',I.TT,I.UU,I.VV,I.WW,I.XX) ;

*/


                        /*ADDED BY WARUNA 2012-10-11*/
                        DN_CORPORATE_ACTION_ORDEAL_GEN (M_DEAL_NO,I.BROKER,I.PORT,--GET_PORT_BROKER(I.PORT,I.DEAL_NO)MISSUER_CODE,
                        I.INST,I.SEC,M_END_CODE,'SLR','UD',
                        TO_CHAR(EDATE,'DD-MM-YYYY'),'A365',0,0,MPRICE,NO_OF_SHARES,MPRICE,0,0,M_USERNAME,M_DEAL_NO,'N','SL',M_DEAL_NO,'EQUITY_COR',0,
                        TO_CHAR(EDATE,'DD-MM-YYYY'),TO_CHAR(EDATE,'DD-MM-YYYY'));
                         
                        INSERT INTO DN_CORPORATE_ACTIONS_DEAL(DEAL_NO, ACTIVITY,SECURITY_CODE,XC_DATE,ALLOTMENT_DATE,LETTER_DISPATCH,ACCEPTANCE_DATE,PROCESS,EXIST_HOLDING,ENTITLEMENT,REC_DATE,ACTI_REF_NO)
                        VALUES(M_DEAL_NO,'AMALGAMATION',I.SEC,TRUNC(M_LAST_DAILY,'DD'),NULL,NULL,NULL,'EX_DATE',I.NOOFSHARES,NO_OF_SHARES,NULL,I.ACTI_REF_NO);
                                        
                        INSERT INTO DN_CORPORATE_ACT_REF ( ACTI_REF_NO, FACILITY_NO, ELIGIBLE_SHARE, OBTAIN_SHARE,OBTAIN_AMMOUNT, OBTAIN_VALUE, ENT_DATE)
                        VALUES (I.ACTI_REF_NO,I.PORT,I.NOOFSHARES,NO_OF_SHARES,0,0,SYSDATE);

END LOOP;

FOR J IN C2 LOOP
    SELECT PAR_VALUE INTO M_PAR
    FROM DN_REF_SECURITY WHERE  SECURITY_CODE=J.SECU ;
    INSERT INTO DN_REF_SECURITY_PAR_BACKUP
    VALUES(J.SECU,M_PAR);

   SELECT (NR/DR)*M_PAR INTO NEW_PAR FROM DUAL;

   UPDATE DN_REF_SECURITY SET PAR_VALUE=NEW_PAR
   WHERE  SECURITY_CODE=J.SECU ;


 END LOOP;


 UPDATE DN_CORPORATE_ACTIONS
 SET STATUS = 'PROCESSED'
 WHERE ACTIVITY = 'AMALGAMATION' AND SECURITY_CODE=SEC_CODE AND INST_TYPE=MINST
 AND XC_DATE =  TRUNC(M_LAST_DAILY,'DD') ;


END DN_CORPORATE_ACTIONS_AMAL; 

