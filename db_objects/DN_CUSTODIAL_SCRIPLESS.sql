--  DDL for Procedure DN_CUSTODIAL_SCRIPLESS
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CUSTODIAL_SCRIPLESS" 
(
 M_DEAL_NO     IN OUT     DN_TRN_BO_CUSTODIAL_DEAL.DEAL_NO%TYPE,
 M_DEAL_NO_PR             DN_TRN_OUTP_SALE.DEAL_NO%TYPE,
 M_CUST_STAT              VARCHAR2,
 M_FINISHED_STAT          VARCHAR2,
 M_FEE_AMOUNT             DN_TRN_BO_CUSTODIAL_DEAL.FEE_AMOUNT%TYPE
)
AS

    CURSOR MY_CUR IS
       SELECT  A.BUY_PORTFOLIO_CODE,A.INST_TYPE,A.SECURITY_CODE,A.CURR_CODE,
               A.EFF_VALDATE_TYPE,A.EFF_VALDATE,A.FACE_VALUE,A.NO_OF_SETTL_MODES,A.DN_USER,
               B.SERIAL_NO,B.FACE_VAL
       FROM    DN_TRN_OUTP_SALE A,
               DN_INV_OUTPS_DEAL_SERIAL_NO B
       WHERE   B.SALE_DEAL_NO=A.DEAL_NO AND
               A.DEAL_NO=M_DEAL_NO_PR;



       --CREATED ON  : 25-09-2001
       --CREATED BY  : NIRMALA FERNANDO
       --SYSTEM      : DEALNET-SCRIPLESS(FCAM)
       --TO DO THE CUSTODIAL TRANSACTIONS IN SCRIPLESS SYSTEM


M_BUY_PORTFOLIO_CODE              DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE;
M_INST_TYPE                       DN_TRN_OUTP_SALE.INST_TYPE%TYPE;
M_SECURITY_CODE                   DN_TRN_OUTP_SALE.SECURITY_CODE%TYPE;
M_CURR_CODE                       DN_TRN_OUTP_SALE.CURR_CODE%TYPE;
M_EFF_VALDATE_TYPE                DN_TRN_OUTP_SALE.EFF_VALDATE_TYPE%TYPE;
M_EFF_VALDATE                     DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE;
M_FACE_VALUE                      DN_TRN_OUTP_SALE.FACE_VALUE%TYPE;
M_NO_OF_SETTL_MODES               DN_TRN_OUTP_SALE.NO_OF_SETTL_MODES%TYPE;
M_DN_USER                         DN_TRN_OUTP_SALE.DN_USER%TYPE;
M_SERIAL_NO                       DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
M_SERIAL_FACE_VAL                 DN_INV_OUTPS_DEAL_SERIAL_NO.FACE_VAL%TYPE;


BEGIN

  IF (M_DEAL_NO IS NULL) THEN
    SELECT 'CS'||TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_CUSTODIAL_DEAL.NEXTVAL),3,'0')
    INTO   M_DEAL_NO
    FROM   DUAL;
  END IF;

       UPDATE DN_TRN_OUTP_SALE
       SET    TRANS_CUST=NVL(M_CUST_STAT,'')
       WHERE  DEAL_NO=M_DEAL_NO_PR;

 IF(M_CUST_STAT='Y')THEN
 OPEN MY_CUR;
 LOOP
 FETCH MY_CUR INTO
       M_BUY_PORTFOLIO_CODE,M_INST_TYPE,M_SECURITY_CODE,M_CURR_CODE,
       M_EFF_VALDATE_TYPE,M_EFF_VALDATE,M_FACE_VALUE,M_NO_OF_SETTL_MODES,M_DN_USER,
       M_SERIAL_NO,M_SERIAL_FACE_VAL;

 EXIT WHEN MY_CUR%NOTFOUND;

       UPDATE DN_TRN_BO_CUSTODIAL_DEAL
       SET    DEAL_TYPE='D',
              CUSTODIAL_CODE=M_BUY_PORTFOLIO_CODE,
              CURR_CODE=M_CURR_CODE,
              EFF_VALDATE=M_EFF_VALDATE,
              EFF_VALDATE_TYPE=M_EFF_VALDATE_TYPE,
              FACE_VALUE=M_FACE_VALUE,
              INST_TYPE=M_INST_TYPE,
              SECURITY_CODE=M_SECURITY_CODE,
              NO_OF_SETTL_MODES=M_NO_OF_SETTL_MODES,
              FEE_AMOUNT=M_FEE_AMOUNT,
              DN_USER=M_DN_USER,
              ENT_DATE=SYSDATE
       WHERE  DEAL_NO= M_DEAL_NO;


       IF SQL%NOTFOUND THEN
       INSERT INTO DN_TRN_BO_CUSTODIAL_DEAL
         (DEAL_NO,DEAL_TYPE,CUSTODIAL_CODE,CURR_CODE,EFF_VALDATE,EFF_VALDATE_TYPE,
          FACE_VALUE,INST_TYPE,SECURITY_CODE,NO_OF_SETTL_MODES,FEE_AMOUNT,DN_USER,
          ENT_DATE)
       VALUES
          (M_DEAL_NO,'D',M_BUY_PORTFOLIO_CODE,M_CURR_CODE,M_EFF_VALDATE,M_EFF_VALDATE_TYPE,
           M_FACE_VALUE,M_INST_TYPE,M_SECURITY_CODE,M_NO_OF_SETTL_MODES,NVL(M_FEE_AMOUNT,0),
           M_DN_USER,SYSDATE);
       END IF;


       UPDATE  DN_TRN_BO_CUSTODIAL_DEAL_SEC
       SET     FACE_VALUE=M_SERIAL_FACE_VAL
       WHERE   DEAL_NO=M_DEAL_NO AND
               SECURITY_CODE=M_SECURITY_CODE AND
               SERIAL_NO=M_SERIAL_NO ;

       IF SQL%NOTFOUND THEN
       INSERT INTO DN_TRN_BO_CUSTODIAL_DEAL_SEC
       (DEAL_NO,SECURITY_CODE,SERIAL_NO,FACE_VALUE)
       VALUES
       (M_DEAL_NO,M_SECURITY_CODE,M_SERIAL_NO,M_SERIAL_FACE_VAL);
       END IF;

       UPDATE DN_TRN_BO_CUSTODIAL_DEAL_SETT
       SET    SETTLE_MODE='CB_CHEQUE',
              SETTLE_AMOUNT=NVL(M_FEE_AMOUNT,0),
              OWN_PORTFOLIO_CODE=NULL,
              OWN_BRANCH_CODE=0,
              OWN_ACC_NO=NULL,
              CUSTODIAL_CODE=M_BUY_PORTFOLIO_CODE,
              CUSTODIAL_BRANCH_CODE=0,
              CUSTODIAL_ACC_NO=NULL,
              SETTLE_COMMENT=NULL
       WHERE  DEAL_NO=M_DEAL_NO;

       IF SQL%NOTFOUND THEN
       INSERT INTO DN_TRN_BO_CUSTODIAL_DEAL_SETT
       (DEAL_NO,SETTLE_MODE,SETTLE_AMOUNT,OWN_PORTFOLIO_CODE,OWN_BRANCH_CODE,OWN_ACC_NO,
        CUSTODIAL_CODE,CUSTODIAL_BRANCH_CODE,CUSTODIAL_ACC_NO,SETTLE_COMMENT)
       VALUES
       (M_DEAL_NO,'CB_CHEQUE',NVL(M_FEE_AMOUNT,0),NULL,0,NULL,M_BUY_PORTFOLIO_CODE,0,NULL,NULL);
       END IF;



 END LOOP;
 CLOSE MY_CUR;
 END IF;


IF(M_FINISHED_STAT='Y')THEN
 COMMIT;
END IF;

END DN_CUSTODIAL_SCRIPLESS;

