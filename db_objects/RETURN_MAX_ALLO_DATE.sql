--------------------------------------------------------
--  DDL for Function RETURN_MAX_ALLO_DATE
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_MAX_ALLO_DATE" 
(
M_SERIAL_NO                   DN_INV_OUTPS_DEAL_SERNO_ALLO.SERIAL_NO%TYPE,
M_SECURITY_CODE               DN_INV_OUTPS_DEAL_SERNO_ALLO.SECURITY_CODE%TYPE,
M_PORT_CODE                   DN_INV_OUTPS_DEAL_SERNO_ALLO.PORTFOLIO_CODE%TYPE
)
RETURN VARCHAR2
IS

MM_COUNT                       NUMBER;
MMM_END_DATE                   VARCHAR2(15);

BEGIN

SELECT COUNT(*)
INTO   MM_COUNT
FROM   DN_INV_OUTPS_DEAL_SERNO_ALLO
WHERE  PORTFOLIO_CODE= M_PORT_CODE AND
       M_SERIAL_NO=SERIAL_NO AND
       M_SECURITY_CODE=SECURITY_CODE;

IF MM_COUNT<>0 THEN
SELECT NVL(TO_CHAR(MAX(END_DATE),'DD-MM-YYYY'),'-')
INTO   MMM_END_DATE
FROM   DN_INV_OUTPS_DEAL_SERNO_ALLO
WHERE  PORTFOLIO_CODE= M_PORT_CODE AND
       SERIAL_NO=M_SERIAL_NO AND
       SECURITY_CODE=M_SECURITY_CODE;
ELSE
    MMM_END_DATE:='-';
END IF;

RETURN MMM_END_DATE ;

END;

/
