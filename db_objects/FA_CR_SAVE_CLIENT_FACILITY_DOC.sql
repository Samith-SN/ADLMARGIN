set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."FA_CR_SAVE_CLIENT_FACILITY_DOC" 
(
M_FACILITY_NO                   DN_client_margin_doc.FACILITY_NO%TYPE,
M_CLIENT_CODE                   DN_client_margin_doc.CLIENT_CODE%TYPE,
M_DOCUMENT_CODE                 DN_client_margin_doc.DOCUMENT_CODE%TYPE,
M_DOCUMENT_NAME                 DN_client_margin_doc.DOCUMENT_NAME%TYPE,
M_APPLICANT_TYPE                DN_client_margin_doc.APPLICANT_TYPE%TYPE,
M_FROM_SCREEN                   DN_client_margin_doc.FROM_SCREEN%TYPE,
M_TO_SCREEN                     DN_client_margin_doc.TO_SCREEN%TYPE,
M_DOC_RECEIVED                  DN_client_margin_doc.DOC_RECEIVED%TYPE,
M_SCREEN                        VARCHAR2,
M_USER                          DN_client_margin_doc.ENT_USER%TYPE,
M_NUM                           INT,
M_DOC_RECEIVED_DATE             VARCHAR2
)

AS
-- CODE BY THAMALI JAYATUNGA ON 2010.05.31

BEGIN

IF UPPER(M_SCREEN)='NEW' THEN

INSERT INTO DN_client_margin_doc
(FACILITY_NO,CLIENT_CODE,DOCUMENT_CODE,DOCUMENT_NAME,APPLICANT_TYPE,
FROM_SCREEN,TO_SCREEN,DOC_RECEIVED,ENT_USER,ENT_DATE,DOC_RECEIVED_DATE)
VALUES
(M_FACILITY_NO,M_CLIENT_CODE,M_DOCUMENT_CODE,M_DOCUMENT_NAME,M_APPLICANT_TYPE,
M_FROM_SCREEN,M_TO_SCREEN,M_DOC_RECEIVED,M_USER,SYSDATE,TO_DATE(M_DOC_RECEIVED_DATE,'DD-MM-YYYY'));

ELSE

IF M_NUM=0 THEN

INSERT INTO DN_client_margin_doc_BK
(FACILITY_NO,CLIENT_CODE,DOCUMENT_CODE,DOCUMENT_NAME,APPLICANT_TYPE,
FROM_SCREEN,TO_SCREEN,DOC_RECEIVED,ENT_USER,ENT_DATE,MOD_USER,MOD_DATE,DOC_RECEIVED_DATE)
SELECT
FACILITY_NO,CLIENT_CODE,DOCUMENT_CODE,DOCUMENT_NAME,APPLICANT_TYPE,
FROM_SCREEN,TO_SCREEN,DOC_RECEIVED,ENT_USER,ENT_DATE,MOD_USER,MOD_DATE,DOC_RECEIVED_DATE
FROM DN_client_margin_doc
WHERE FACILITY_NO=M_FACILITY_NO;

DELETE FROM DN_client_margin_doc
WHERE FACILITY_NO=M_FACILITY_NO;

END IF;

INSERT INTO DN_client_margin_doc
(FACILITY_NO,CLIENT_CODE,DOCUMENT_CODE,DOCUMENT_NAME,APPLICANT_TYPE,
FROM_SCREEN,TO_SCREEN,DOC_RECEIVED,ENT_USER,ENT_DATE,DOC_RECEIVED_DATE)
VALUES
(M_FACILITY_NO,M_CLIENT_CODE,M_DOCUMENT_CODE,M_DOCUMENT_NAME,M_APPLICANT_TYPE,
M_FROM_SCREEN,M_TO_SCREEN,M_DOC_RECEIVED,M_USER,SYSDATE,TO_DATE(M_DOC_RECEIVED_DATE,'DD-MM-YYYY'));
END IF;

END;

