--------------------------------------------------------
--  DDL for Procedure DN_PORTFOLIOS_DEL
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_PORTFOLIOS_DEL" 

   (M_PORTFOLIO_CODE   IN OUT   DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE,
    M_SELECT_TYPE               CHAR,
    M_ACTIVITY_CODE             DN_REF_PORTF_ALLOW_ACTIVITY.ACTIVITY_CODE%TYPE
   -- M_USRE                VARCHAR


   )

AS
BEGIN

--DN_VALIDATE_SAVE_RIGHTS(M_USRE,'WD_Portfolios_MT');  --added by ashini on 31/10/2005 for sr0509-047


    /* PROCEDURE  - TO DELETE PORFOLIO CODE
                  - TO DELETE COUNTER PARTY CODE
                  - TO DELETE CUSTODIAL CODE

       SYSTEM     -  DEALNET
       CREATED BY -
       CREATED ON -  */
IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='DIR' THEN

DELETE FROM DN_REF_PORTF_DIRECTOR
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE;
END IF;

IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='AUTHO' THEN

DELETE FROM DN_REF_PORTF_AUTHO_SIGN
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE;
END IF;

IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='CONT' THEN

DELETE FROM DN_REF_PORTF_CONT_PERSON
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE;
END IF;

IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='TEL' THEN

DELETE FROM DN_REF_PORTF_CONT_TELNO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE;
END IF;

IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='FAX' THEN

DELETE FROM DN_REF_PORTF_CONT_FAXNO
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE;
END IF;

IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='MAIL' THEN

DELETE FROM DN_REF_PORTF_CONT_EMAIL
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE;
END IF;


IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='BANK' THEN

DELETE FROM DN_REF_PORTF_SETTLEMENT
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE;
END IF;

IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='INS' THEN

DELETE FROM DN_REF_PORTF_ALLOW_INSTRUMENT
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE;

END IF;
--RAISE_APPLICATION_ERROR(-20201,M_PORTFOLIO_CODE||' '||M_SELECT_TYPE||' '||M_ACTIVITY_CODE);

IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='ACT' THEN
--RAISE_APPLICATION_ERROR(-20201,M_PORTFOLIO_CODE||' '||M_SELECT_TYPE||' '||M_ACTIVITY_CODE);

    IF(M_ACTIVITY_CODE='OUT') THEN

    DELETE FROM DN_REF_PORTF_ALLOW_ACTIVITY
      WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE
          AND ACTIVITY_CODE LIKE('O%');

    END IF;

    IF(M_ACTIVITY_CODE='BLF') THEN

    DELETE FROM DN_REF_PORTF_ALLOW_ACTIVITY
      WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE
        AND ACTIVITY_CODE IN ('BF','LF');
    END IF;

    IF(M_ACTIVITY_CODE='BLS') THEN

    DELETE FROM DN_REF_PORTF_ALLOW_ACTIVITY
      WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE
        AND ACTIVITY_CODE IN ('BS','LS');
    END IF;

    IF(M_ACTIVITY_CODE='REP') THEN

    DELETE FROM DN_REF_PORTF_ALLOW_ACTIVITY
      WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE
        AND ACTIVITY_CODE LIKE('R%');
    END IF;

END IF;

IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='CORP' THEN

DELETE FROM DN_REF_PORTF_ALLOW_CORPORATE
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE;

END IF;

IF M_PORTFOLIO_CODE IS NOT NULL AND M_SELECT_TYPE='COUN' THEN

DELETE FROM DN_REF_PORTF_ALLOW_CP
WHERE  PORTFOLIO_CODE=M_PORTFOLIO_CODE;

END IF;

COMMIT;

END DN_PORTFOLIOS_DEL;

