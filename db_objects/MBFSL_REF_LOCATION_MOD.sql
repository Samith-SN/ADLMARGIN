--  DDL for Procedure MBFSL_REF_LOCATION_MOD
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_REF_LOCATION_MOD" 

   (M_LOC_CODE      DN_REF_LOCATION.LOC_CODE%TYPE,
    M_LOC_DESC      DN_REF_LOCATION.LOC_DESC%TYPE,
    M_ADD_ID        DN_REF_LOCATION.ADD_IDENTIFICATION%TYPE,
    M_ADD_LOC       DN_REF_LOCATION.ADD_LOCATION%TYPE,
    M_ADD_STREET    DN_REF_LOCATION.ADD_STREET%TYPE,
    M_ADD_CITY      DN_REF_LOCATION.ADD_CITY%TYPE,
    M_ADD_COUNTRY   DN_REF_LOCATION.ADD_COUNTRY%TYPE,
    M_POSTAL_CODE   DN_REF_LOCATION.POSTAL_CODE%TYPE,
    CONTACT_NO      DN_REF_LOCATION_CONT_EMAIL.EMAIL%TYPE,
    M_STATUS        CHAR,
    DEL_STATUS      NUMBER,
    M_USRE          VARCHAR
    )
  AS
    LOC_COUNT       NUMBER;
    T_COUNT         NUMBER;
    F_COUNT         NUMBER;
    E_COUNT         NUMBER;
    INCT            INTEGER;
    INCF            INTEGER;
    INCE            INTEGER;
BEGIN

--RAISE_APPLICATION_ERROR(-20201,'M_USRE'||M_USRE);

DN_VALIDATE_SAVE_RIGHTS(M_USRE,'WD_Location');  --added by ashini on 31/10/2005 for sr0509-047

    /* PROCEDURE  -  TO UPDATE LOCATION DETAILS
       SYSTEM     -  DEALNET
       CREATED BY -  DAYAN.
       CREATED ON -  22/06/1999 */

        LOC_COUNT:=0;
        T_COUNT:=0;
        F_COUNT:=0;
        E_COUNT:=0;
--RAISE_APPLICATION_ERROR(-20201,M_LOC_CODE||' '||M_LOC_DESC||' '||M_ADD_ID||' '||M_ADD_LOC||' '||M_ADD_STREET||' '||M_ADD_CITY||' '||M_ADD_COUNTRY||' '||M_POSTAL_CODE||' '||CONTACT_NO||' '||M_STATUS||' '||DEL_STATUS);

UPDATE DN_REF_LOCATION
   SET
       LOC_CODE=M_LOC_CODE,
       LOC_DESC=M_LOC_DESC,
       ADD_IDENTIFICATION=M_ADD_ID,
       ADD_LOCATION=M_ADD_LOC,
       ADD_STREET=M_ADD_STREET,
       ADD_CITY=M_ADD_CITY,
       ADD_COUNTRY=M_ADD_COUNTRY,
       POSTAL_CODE=M_POSTAL_CODE
   WHERE LOC_CODE=M_LOC_CODE;

IF (M_STATUS='T' AND  CONTACT_NO<>' ')THEN
   IF DEL_STATUS='1' THEN
      DELETE  FROM DN_REF_LOCATION_CONT_TELNO
      WHERE LOC_CODE=M_LOC_CODE;
   END IF;

   SELECT  MAX(SEQ_NO)+1 INTO INCT FROM DN_REF_LOCATION_CONT_TELNO
   WHERE  LOC_CODE=M_LOC_CODE;

      IF INCT IS NULL THEN
         INCT:=1;
      END IF;

      INSERT INTO DN_REF_LOCATION_CONT_TELNO
        (LOC_CODE,TEL_NO,SEQ_NO)
      VALUES
       (M_LOC_CODE,CONTACT_NO,INCT);

END IF;

IF (M_STATUS='F' AND CONTACT_NO<>' ') THEN
   IF DEL_STATUS='1' THEN
      DELETE FROM DN_REF_LOCATION_CONT_FAXNO
      WHERE LOC_CODE=M_LOC_CODE;
   END IF;

   SELECT  MAX(SEQ_NO)+1 INTO INCF FROM DN_REF_LOCATION_CONT_FAXNO
   WHERE  LOC_CODE=M_LOC_CODE;

      IF INCF IS NULL THEN
         INCF:=1;
      END IF;

  INSERT INTO DN_REF_LOCATION_CONT_FAXNO
      (LOC_CODE,FAX_NO,SEQ_NO)
  VALUES
      (M_LOC_CODE,CONTACT_NO,INCF);
END IF;

IF (M_STATUS='E' AND CONTACT_NO<>' ') THEN
   IF DEL_STATUS='1' THEN
     DELETE  FROM DN_REF_LOCATION_CONT_EMAIL
     WHERE LOC_CODE=M_LOC_CODE;
    END IF;

   SELECT  MAX(SEQ_NO)+1 INTO INCE FROM DN_REF_LOCATION_CONT_EMAIL
   WHERE  LOC_CODE=M_LOC_CODE;

      IF INCE IS NULL THEN
         INCE:=1;
      END IF;

   INSERT INTO DN_REF_LOCATION_CONT_EMAIL
      (LOC_CODE,EMAIL,SEQ_NO)
    VALUES
      (M_LOC_CODE,CONTACT_NO,INCE);
  END IF;
COMMIT;
 --RAISE_APPLICATION_ERROR(-20201,M_LOC_CODE||' '||M_LOC_DESC||' '||M_ADD_ID||' '||M_ADD_LOC||' '||M_ADD_STREET||' '||M_ADD_CITY||' '||M_ADD_COUNTRY||' '||M_POSTAL_CODE||' '||CONTACT_NO||' '||M_STATUS);

END MBFSL_REF_LOCATION_MOD;

