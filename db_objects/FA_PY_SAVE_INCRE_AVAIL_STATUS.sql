--  DDL for Procedure FA_PY_SAVE_INCRE_AVAIL_STATUS
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."FA_PY_SAVE_INCRE_AVAIL_STATUS" 
(
     M_SAVE_ORDER_NO                      IN FA_PY_INCREASE_AVAIL_STATUS.SAVE_ORDER_NO%TYPE,  
     M_PAY_NO                             IN FA_PY_INCREASE_AVAIL_STATUS.PAY_NO%TYPE,
     M_FACILITY_NO                        IN FA_PY_INCREASE_AVAIL_STATUS.FACILITY_NO%TYPE,
     M_USER                               IN FA_PY_INCREASE_AVAIL_STATUS.ENT_USER%TYPE,
     M_SAVE_EVENT                         IN FA_PY_INCR_AVAIL_STA_SUMMERY.SAVE_EVENT%TYPE
)

/* 
 * Author                   :   Waruna Sri Jayanath
 * Date                     :   2012-03-15
 * 
 * System                   :   LBMARGIN
 * Menu Hierarchy           :   MARGINtrading -> Payment
 * Screen Name              :   
 * Screen URL               :   
 * Save Servlet             :   
 * Display Name             :   Broker Payment
 * 
 * Purpose                  :   SAVE PROCEDURE TO SAVE AN INCREASE IN AVAILABILITY STATUS WHEN ENT PAYMENT 
 */

AS
    
    MM_COUNT                                NUMBER(1);
    M_COMPANY_VAL                           NUMBER(25,4);
    M_LOAN_BAL                              NUMBER(25,4);
    M_DAY_MOV                               NUMBER(25,4);
    M_CURRENT_AVAILABILITY_REC              FA_PY_INCR_AVAIL_STA_SUMMERY.CURRENT_AVAILABILITY_REC%TYPE; 
    M_CURRENT_AVAILABILITY_APP              FA_PY_INCR_AVAIL_STA_SUMMERY.CURRENT_AVAILABILITY_APP%TYPE;
    M_VALUATION_ENHANCE_AMOUNT_REC          FA_PY_INCR_AVAIL_STA_SUMMERY.VALUATION_ENHANCE_AMOUNT_REC%TYPE;
    M_VALUATION_ENHANCE_AMOUNT_APP          FA_PY_INCR_AVAIL_STA_SUMMERY.VALUATION_ENHANCE_AMOUNT_APP%TYPE;
    M_CONCEN_ADJ_AMOUNT_REC                 FA_PY_INCR_AVAIL_STA_SUMMERY.CONCEN_ADJ_AMOUNT_REC%TYPE;
    M_CONCEN_ADJ_AMOUNT_APP                 FA_PY_INCR_AVAIL_STA_SUMMERY.CONCEN_ADJ_AMOUNT_APP%TYPE;
    M_DUE_REC_AMOUNT_REC                    FA_PY_INCR_AVAIL_STA_SUMMERY.DUE_REC_AMOUNT_REC%TYPE;
    M_DUE_REC_AMOUNT_APP                    FA_PY_INCR_AVAIL_STA_SUMMERY.DUE_REC_AMOUNT_APP%TYPE;
   
BEGIN
    
   
  INSERT INTO FA_PY_INCREASE_AVAIL_STATUS (TYPE, FACILITY_NO, SECURITY_CODE, PAY_NO,
       BALANCE_AMOUNT, RECOMMENDED_AMOUNT, APPROVED_AMOUNT,
       THIS_PAYMENT_INCREASE_STATUS, THIS_PERIOD_INCREASE_STATUS,
       THIS_PERIOD_INCREASE_DATE, PERMANENT_INCREASE_STATUS,
       COMMENTS, STATUS, ENT_USER, ENT_DATE, MOD_USER,
       MOD_DATE, CREDIT_LIMIT_REC, CREDIT_LIMIT_APP,
       PERCENTAGE_REC, PERCENTAGE_APP, EFF_VALDATE,
       ENHANCED_AMOUNT, PERCENTAGE_APP_LAST, APPROVED_AMOUNT_LAST,SAVE_ORDER_NO) (  

  SELECT TYPE, FACILITY_NO, SECURITY_CODE, M_PAY_NO,
       BALANCE_AMOUNT, RECOMMENDED_AMOUNT, APPROVED_AMOUNT,
       THIS_PAYMENT_INCREASE_STATUS, THIS_PERIOD_INCREASE_STATUS,
       THIS_PERIOD_INCREASE_DATE, PERMANENT_INCREASE_STATUS,
       COMMENTS, STATUS, ENT_USER, ENT_DATE, MOD_USER,
       MOD_DATE, CREDIT_LIMIT_REC, CREDIT_LIMIT_APP,
       PERCENTAGE_REC, PERCENTAGE_APP, EFF_VALDATE,
       ENHANCED_AMOUNT, PERCENTAGE_APP_LAST, APPROVED_AMOUNT_LAST,M_SAVE_ORDER_NO
  FROM FA_PY_INCREASE_AVAILABILITY A
  WHERE FACILITY_NO = M_FACILITY_NO);
  
  
BEGIN
    
      
SELECT  NVL(VAL,0),NVL(REPO_LEG2,0),NVL(DN_GET_DAYEND_LOAN_MOVE(PORTFOLIO_CODE,TO_CHAR(LAST_DAILY+1,'DD/MM/YYYY')),0) LOAN_MOV
       ,NVL(DN_GET_CLIENT_ENHANCE_RECEIPT(PORTFOLIO_CODE,'APPROVED'),0) REC_APP
       ,NVL(DN_GET_CLIENT_ENHANCE_RECEIPT(PORTFOLIO_CODE,'RECOMMENDED'),0) REC_REC
       ,NVL((COMPANY_VALUE_ENHANCE_APP-COMPANY_VA_ENHANCE_LAST) ,0) COM_APP
       ,NVL((COMPANY_VALUE_ENHANCE_REC-COMPANY_VA_ENHANCE_LAST) ,0) COM_REC
       ,NVL((ADJ_VALUE_ENHANCE_APP-ADJ_VA_ENHANCE_LAST ),0) ADJ_APP
       ,NVL((ADJ_VALUE_ENHANCE_REC-ADJ_VA_ENHANCE_LAST ),0) ADJ_REC
      
INTO M_COMPANY_VAL,M_LOAN_BAL,M_DAY_MOV,
        M_DUE_REC_AMOUNT_APP,M_DUE_REC_AMOUNT_REC,
        M_VALUATION_ENHANCE_AMOUNT_APP,M_VALUATION_ENHANCE_AMOUNT_REC,
        M_CONCEN_ADJ_AMOUNT_APP,M_CONCEN_ADJ_AMOUNT_REC
FROM(
SELECT PORTFOLIO_CODE,
       REPO_LEG2,
       LEAST(PORT_LIMIT,COMPANY_VALUE)VAL ,
       COMPANY_VALUE_ENHANCE_APP,
       COMPANY_VALUE_ENHANCE_REC,
       ADJ_VALUE_ENHANCE_APP,
       ADJ_VALUE_ENHANCE_REC,
       COMPANY_VA_ENHANCE_LAST,
       COMPANY_VALUE,
       ADJ_VA_ENHANCE_LAST,
       B.LAST_DAILY FROM (
SELECT PORTFOLIO_CODE ,
       A.REPO_LEG2 ,
       A.PORT_LIMIT,
            
SUM(NVL(A.FACE_VAL,0)* NVL(A.MARKET_RATE,0)*NVL(DN_GET_CLIENT_LICENCE_MT_PERC(A.SECURITY_CODE,PORTFOLIO_CODE,'APPROVED'),0)/100)  COMPANY_VALUE_ENHANCE_APP,
SUM(NVL(A.FACE_VAL,0)* NVL(A.MARKET_RATE,0)*NVL(DN_GET_CLIENT_LICENCE_MT_PERC(A.SECURITY_CODE,PORTFOLIO_CODE,'RECOMMENDED'),0)/100)  COMPANY_VALUE_ENHANCE_REC,
SUM(NVL(A.FACE_VAL,0)* NVL(A.MARKET_RATE,0)*NVL(DN_GET_CLIENT_LICENCE_MT_PERC(A.SECURITY_CODE,PORTFOLIO_CODE,'APPROVED'),0)*NVL(DN_GET_CLIENT_CONCENT_PERCENT(A.SECURITY_CODE,PORTFOLIO_CODE,'APPROVED'),0)/10000)  ADJ_VALUE_ENHANCE_APP,
SUM(NVL(A.FACE_VAL,0)* NVL(A.MARKET_RATE,0)*NVL(DN_GET_CLIENT_LICENCE_MT_PERC(A.SECURITY_CODE,PORTFOLIO_CODE,'APPROVED'),0)*NVL(DN_GET_CLIENT_CONCENT_PERCENT(A.SECURITY_CODE,PORTFOLIO_CODE,'RECOMMENDED'),0)/10000)  ADJ_VALUE_ENHANCE_REC,
SUM(NVL(A.FACE_VAL,0)* NVL(A.MARKET_RATE,0)*NVL(DN_GET_LICENCE_MT_PERCENT(SECURITY_CODE),0)/100)  COMPANY_VALUE,
SUM(NVL(A.FACE_VAL,0)* NVL(A.MARKET_RATE,0)*NVL(DN_GET_CLIENT_LICENCE_MT_PER_L(SECURITY_CODE,PORTFOLIO_CODE),0)/100)  COMPANY_VA_ENHANCE_LAST,
SUM(NVL(A.FACE_VAL,0)* NVL(A.MARKET_RATE,0)*NVL(DN_GET_CLIENT_LICENCE_MT_PERC(SECURITY_CODE,PORTFOLIO_CODE,'APPROVED'),0)*NVL(DN_GET_CLIENT_CONCENT_PER_L(SECURITY_CODE,PORTFOLIO_CODE),0)/10000)  ADJ_VA_ENHANCE_LAST

FROM DN_TEMP_MARGIN_CALL A 
WHERE PORTFOLIO_CODE  = M_FACILITY_NO
GROUP BY A.PORTFOLIO_CODE ,A.REPO_LEG2 ,A.PORT_LIMIT) A ,
DN_SYS_PARAMETER B
);
  
EXCEPTION
    WHEN OTHERS THEN 
    
   
    M_COMPANY_VAL               :=0;
    M_LOAN_BAL                  :=0;
    M_DAY_MOV                   :=0;
    M_CURRENT_AVAILABILITY_REC  :=0;
    M_CURRENT_AVAILABILITY_APP  :=0;
    M_VALUATION_ENHANCE_AMOUNT_REC  :=0;
    M_VALUATION_ENHANCE_AMOUNT_APP  :=0;
    M_CONCEN_ADJ_AMOUNT_REC         :=0;
    M_CONCEN_ADJ_AMOUNT_APP         :=0;
    M_DUE_REC_AMOUNT_REC            :=0;
    M_DUE_REC_AMOUNT_APP            :=0;
  END;    
  
  
  M_CURRENT_AVAILABILITY_REC := M_COMPANY_VAL - M_LOAN_BAL - M_DAY_MOV;
  M_CURRENT_AVAILABILITY_APP := M_CURRENT_AVAILABILITY_REC;
  
  INSERT INTO FA_PY_INCR_AVAIL_STA_SUMMERY (FACILITY_NO, PAY_NO, CURRENT_AVAILABILITY_REC,
       CURRENT_AVAILABILITY_APP, VALUATION_ENHANCE_AMOUNT_REC,
       VALUATION_ENHANCE_AMOUNT_APP, CONCEN_ADJ_AMOUNT_REC,
       CONCEN_ADJ_AMOUNT_APP, DUE_REC_AMOUNT_REC,
       DUE_REC_AMOUNT_APP,SAVE_ORDER_NO,SAVE_EVENT)
  VALUES(
       M_FACILITY_NO, M_PAY_NO, M_CURRENT_AVAILABILITY_REC,
       M_CURRENT_AVAILABILITY_APP, M_VALUATION_ENHANCE_AMOUNT_REC,
       M_VALUATION_ENHANCE_AMOUNT_APP, M_CONCEN_ADJ_AMOUNT_REC,
       M_CONCEN_ADJ_AMOUNT_APP, M_DUE_REC_AMOUNT_REC,
       M_DUE_REC_AMOUNT_APP,M_SAVE_ORDER_NO,M_SAVE_EVENT
       );
  
  
  
    
END ; 

