             --A.BROKER, A.SECURITY_CODE, A.PRICE, A.TOT-NVL(TRANSFERRED_AMOUNT,0)-NVL(A.ALLO_AMOUNT,0),ABS(A.TOT-NVL(TRANSFERRED_AMOUNT,0)-NVL(A.ALLO_AMOUNT,0)) ,
