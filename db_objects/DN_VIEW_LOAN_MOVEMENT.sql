SELECT TRN_TYPE,DOCREFNO,DN_PORTFOLIO_CODE,PF_NAME,BROKER,SECURITY_CODE,PRICE_CLEAN,SUM(TOT),SUM(ABSTOT),M_VALTODATE,DECODE(TRN_TYPE,'CW',1,'SELL',2,'CD',3,'BUY',100,100)
FROM (

           SELECT 'BUY' TRN_TYPE,X.DEAL_NO DOCREFNO,BUY_PORTFOLIO_CODE DN_PORTFOLIO_CODE,W.PF_NAME PF_NAME, SELL_PORTFOLIO_CODE BROKER,X.SECURITY_CODE,X.PRICE_CLEAN,
                        SUM(SETTLE_VALUE)-0 TOT,ABS(SUM(SETTLE_VALUE)-0) ABSTOT

           FROM       DN_TRN_OUTP_SALE X,
                      DN_TRN_OUTP_SALE_SETTLE_EQUITY Z,
                      DN_REF_PORTFOLIO W,
                      DN_REF_PORTFOLIO V
            WHERE
                Z.DEAL_NO             = X.DEAL_NO
            AND X.BUY_PORTFOLIO_CODE  = W.PORTFOLIO_CODE
            AND X.SELL_PORTFOLIO_CODE = V.PORTFOLIO_CODE
            AND APP_STATUS            = 'CONF'
            AND DN_GET_INSTRUMENT_CAT(INST_TYPE)='EQUITY'
            AND W.PF_TYPE             = 'P'
            AND W.OWNED_BY_MBFSL      ='N'
            AND TO_DATE(TO_CHAR(BUY_SETLE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>=M_VALFROMDATE
            AND TO_DATE(TO_CHAR(BUY_SETLE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=M_VALTODATE
                GROUP BY X.DEAL_NO,BUY_PORTFOLIO_CODE,W.PF_NAME,
                SELL_PORTFOLIO_CODE ,X.SECURITY_CODE,X.PRICE_CLEAN


) GROUP BY TRN_TYPE,DOCREFNO,DN_PORTFOLIO_CODE,PF_NAME,BROKER,SECURITY_CODE,PRICE_CLEAN
      );

