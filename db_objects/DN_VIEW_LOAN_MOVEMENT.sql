                 SUM(0-SETTLE_VALUE) TOT,ABS(SUM(0-SETTLE_VALUE)) ABSTOT

                 FROM DN_TRN_OUTP_SALE X,
                      DN_TRN_OUTP_SALE_SETTLE_EQUITY Z,
                      DN_REF_PORTFOLIO W,
                      DN_REF_PORTFOLIO V
                 WHERE
                            Z.DEAL_NO             = X.DEAL_NO
                        AND X.SELL_PORTFOLIO_CODE = W.PORTFOLIO_CODE
                        AND X.BUY_PORTFOLIO_CODE  = V.PORTFOLIO_CODE
                        AND APP_STATUS            = 'CONF'
                        AND DN_GET_INSTRUMENT_CAT(INST_TYPE)='EQUITY'
                        AND W.PF_TYPE             = 'P'
                        AND W.OWNED_BY_MBFSL='N'
                        AND TO_DATE(TO_CHAR(SELL_SETLE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>=M_VALFROMDATE
                        AND TO_DATE(TO_CHAR(SELL_SETLE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=M_VALTODATE
                            GROUP BY X.DEAL_NO ,SELL_PORTFOLIO_CODE,W.PF_NAME ,
                                     BUY_PORTFOLIO_CODE,X.SECURITY_CODE,X.PRICE_CLEAN


