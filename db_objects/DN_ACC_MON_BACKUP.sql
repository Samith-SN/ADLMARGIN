  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_MON_BACKUP" 
(
M_TRNDATE2        VARCHAR2
)
AS
--M_TRNDATE        DN_ACC_LICEN_INST_GEN_SUM.TRNDATE%TYPE
--TO_DATE(M_TRNDATE,'DD-MON-YYYY') > TO_DATE(TO_CHAR(B.TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY');
/* PROCEDURE  - DN_ACC_TEST_MON_BACKUP MONTH END ROUTINE
   CREATED BY - LATHIKA
   CREATED ON - 24/01/2000*/

M_TRNDATE              DN_ACC_LICEN_INST_GEN_SUM.TRNDATE%TYPE;
M_ENTDATE              DN_ACC_LICEN_INST_GEN_HIS.ENTDATE%TYPE;

BEGIN
M_TRNDATE := TO_CHAR(TO_DATE(TO_DATE(M_TRNDATE2,'DD-MM-YYYY'),'DD-MON-YYYY'),'DD-MON-YYYY');
--M_TRNDATE :=LTRIM(RTRIM ( TO_CHAR( TO_DATE(M_TRNDATE2,'DD-MM-YYYY'),'DD-MON-YYYY')  ));
-------------------(1)-------------------------
IF M_TRNDATE IS NOT NULL  THEN
SELECT SYSDATE
INTO   M_ENTDATE
FROM   DUAL;

INSERT INTO DN_ACC_LICEN_INST_GEN_HIS
    (PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT)
   SELECT
      A.PORTFOLIO_CODE,A.TRNDATE,A.ACC_TYPE_CODE,A.DRCR_STATUS,A.TRNAMOUNT
   FROM
      DN_ACC_LICEN_INST_GEN_SUM A
   WHERE
    TO_DATE(M_TRNDATE2,'DD-MM-YYYY') > TO_DATE(TO_CHAR(A.TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY');


 DELETE FROM DN_ACC_LICEN_INST_GEN_SUM B
 WHERE
  TO_DATE(M_TRNDATE2,'DD-MM-YYYY') > TO_DATE(TO_CHAR(B.TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY');

 END IF;

COMMIT;
END DN_ACC_MON_BACKUP;

/
