  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_ALLO_STATUS" 
(
M_SERIAL_NO                   DN_INV_OUTPS_DEAL_SERNO_ALLO.SERIAL_NO%TYPE,
M_SECURITY_CODE               DN_INV_OUTPS_DEAL_SERNO_ALLO.SECURITY_CODE%TYPE,
M_PDEAL_NO                    DN_INV_OUTPS_DEAL_SERNO_ALLO.DEAL_NO%TYPE,
M_NDEAL_NO                    DN_INV_OUTPS_DEAL_SERNO_ALLO.DEAL_NO%TYPE,
M_EFF_VALDATE                 VARCHAR2,
M_INV_STATUS                  VARCHAR2
)
RETURN VARCHAR2
IS
MM_SERIAL_NO                   DN_INV_OUTPS_DEAL_SERNO_ALLO.SERIAL_NO%TYPE;
MM_SECURITY_CODE               DN_INV_OUTPS_DEAL_SERNO_ALLO.SECURITY_CODE%TYPE;
MM_COUNT                       INTEGER;
MMM_END_DATE                   VARCHAR2(15);
MM_RETURN                      VARCHAR2(1);
MN_COUNT NUMBER;
BEGIN

MMM_END_DATE :='N';


IF M_INV_STATUS='OR' THEN


SELECT COUNT(*)
INTO   MN_COUNT
FROM   DN_INV_OUTPS_DEAL_SERNO_ALLO
WHERE  M_SERIAL_NO=SERIAL_NO AND
       M_SECURITY_CODE=SECURITY_CODE AND
       DEAL_NO NOT IN (M_PDEAL_NO,M_NDEAL_NO);

IF MN_COUNT=0 THEN
MM_RETURN:='Y';
ELSE
SELECT NVL(TO_CHAR(MAX(END_DATE),'DD-MM-YYYY'),'N')
INTO   MMM_END_DATE
FROM   DN_INV_OUTPS_DEAL_SERNO_ALLO
WHERE  TO_DATE(M_EFF_VALDATE,'DD-MM-YYYY')  >  (SELECT MAX(TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY'))
                     FROM   DN_INV_OUTPS_DEAL_SERNO_ALLO
                     WHERE  M_SERIAL_NO=SERIAL_NO AND
                            M_SECURITY_CODE=SECURITY_CODE AND
                            DEAL_NO NOT IN (M_PDEAL_NO,M_NDEAL_NO)
                     GROUP BY  SERIAL_NO,SECURITY_CODE ) AND

       DEAL_NO NOT IN (M_PDEAL_NO,M_NDEAL_NO) AND
       M_SERIAL_NO=SERIAL_NO AND
       M_SECURITY_CODE=SECURITY_CODE;


IF(MMM_END_DATE='N')THEN
MM_RETURN:='N';
ELSE
MM_RETURN:='Y';
END IF;

END IF;

ELSIF  M_INV_STATUS='RP' THEN

SELECT COUNT(*)
INTO   MN_COUNT
FROM   DN_INV_REPO_DEAL_SERNO_ALLO
WHERE  M_SERIAL_NO=SERIAL_NO AND
       M_SECURITY_CODE=SECURITY_CODE AND
       DEAL_NO NOT IN (M_PDEAL_NO,M_NDEAL_NO);

IF MN_COUNT=0 THEN
MM_RETURN:='Y';
ELSE
SELECT NVL(TO_CHAR(MAX(END_DATE),'DD-MM-YYYY'),'N')
INTO   MMM_END_DATE
FROM   DN_INV_REPO_DEAL_SERNO_ALLO
WHERE  TO_DATE(M_EFF_VALDATE,'DD-MM-YYYY')  > (SELECT MAX(TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY'))
                     FROM   DN_INV_REPO_DEAL_SERNO_ALLO
                     WHERE  M_SERIAL_NO=SERIAL_NO AND
                            M_SECURITY_CODE=SECURITY_CODE AND
                            DEAL_NO NOT IN (M_PDEAL_NO,M_NDEAL_NO)
                     GROUP BY  SERIAL_NO,SECURITY_CODE ) AND

       DEAL_NO NOT IN (M_PDEAL_NO,M_NDEAL_NO) AND
       M_SERIAL_NO=SERIAL_NO AND
       M_SECURITY_CODE=SECURITY_CODE;


IF(MMM_END_DATE='N')THEN
MM_RETURN:='N';
ELSE
MM_RETURN:='Y';
END IF;

END IF;
END IF;

RETURN MM_RETURN ;

END RETURN_ALLO_STATUS;

