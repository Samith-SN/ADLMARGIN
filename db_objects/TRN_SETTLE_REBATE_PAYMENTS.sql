    MM_PORT_CODE         DN_TRN_REBATE_PAYMENT.PORTFOLIO_CODE%TYPE,
    M_DEAL_TYPE          DN_TRN_REBATE_PAYMENT.ENTRY_TYPE%TYPE,
    M_DEALNO             DN_TRN_REBATE_PAYMENT.SUS_REF_NO%TYPE,        --4
    M_ID_PORTCODE        DN_TRN_REBATE_PAYMENT.ID_PORTFOLIO_CODE%TYPE, --5
    M_SETTLEMENT         DN_TRN_REBATE_PAYMENT.SETTLE_MODE%TYPE,       --6
    MM_AMT               DN_TRN_REBATE_PAYMENT.PAY_AMOUNT%TYPE,        --7  CURRENCY
    M_LIC_BANK_CODE      DN_TRN_REBATE_PAYMENT.LIC_BRANCH_CODE%TYPE,   --8
    M_LIC_ACCNO          DN_TRN_REBATE_PAYMENT.LIC_ACC_NO%TYPE,        --9
    --M_PAYEE_BANK_CODE    DN_TRN_REBATE_PAYMENT.PAYEE_BRANCH_CODE%TYPE,
    --M_PAYEE_ACC_NO       DN_TRN_REBATE_PAYMENT.PAYEE_ACC_NO%TYPE,
    M_USER               DN_TRN_REBATE_PAYMENT.DN_USER%TYPE,           --10
