    M_DUMMY_NO           DN_TRN_REBATE_PAYMENT.PAYMENT_NO%TYPE,        --12
    M_OTH_COMMENT        DN_TRN_REBATE_PAYMENT.OTH_COMMENT%TYPE,       --13 add by inditha 2005-8-10 sr0508-007
    M_PAYMENT_STATUS     DN_TRN_REBATE_PAYMENT.OTH_COMMENT%TYPE ,      --14 ADDED BY ASHINI ON 19/05/2006 FOR SR0605-019

    M_SUS_REF_NO         DN_TRN_BO_SETTL_PAYMENT.SUS_REF_NO%TYPE,      --15
    M_SAVE_ORDER_NO      DN_TRN_BO_SETTL_PAYMENT.SAVE_ORDER_NO%TYPE,   --16
    M_TRNDATE            VARCHAR2
   )
AS
M_ACC_SYS_REFNO   DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE;
M_CACC_SEQNO      DN_ACC_SUS_PAYMENT.SUS_REF_NO%TYPE;

NN_BAL_TO_BE_PAID_CURR    DN_ACC_SUS_PAYMENT.BAL_TO_BE_PAID_CURR%TYPE;--CURRENCY
NN_BAL_TO_BE_PAID         DN_ACC_SUS_PAYMENT.BAL_TO_BE_PAID%TYPE;--CURRENCY
NN_COUNT_ALL              NUMBER;--CURRENCY
M_COUNT_ALL               NUMBER;--CURRENCY
M_AMT                     DN_TRN_BO_SETTL_PAYMENT.PAY_AMOUNT%TYPE;--CURRENCY
M_PORT_CODE               DN_TRN_BO_SETTL_PAYMENT.PORTFOLIO_CODE%TYPE;
