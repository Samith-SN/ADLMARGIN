--DN_VALIDATE_SAVE_RIGHTS(M_USER,'WD_Payments_Bulk'); --added by ashini on 31/10/2005 for sr0509-047
M_PORT_CODE:='GEN';
M_PAY_NO:=M_PAY_NO;
SELECT LAST_DAILY INTO M_LAST_DAILY FROM DN_SYS_PARAMETER;


--INSERTING AND UPDATING DN_ACC_SUS_RECEIPT TABLE-----------------------
M_AMT:=MM_AMT;--CURRENCY
--RAISE_APPLICATION_ERROR(-20001,'555'||M_DEAL_TYPE);
IF(M_DEAL_TYPE='D') THEN
M_CACC_SEQNO:=M_SUS_REF_NO;



IF M_DUMMY_NO IS NULL THEN

    SELECT TO_CHAR(SYSDATE,'YY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_SET_PAY.NEXTVAL),3,'0') INTO M_PAY_NO FROM DUAL;
       M_PAY_NO:='LPMT'||M_PAY_NO;
   ELSE
       M_PAY_NO:=M_DUMMY_NO;
   END IF;



--INSERT INTO TRANSACTION TABLE
   INSERT INTO DN_TRN_REBATE_PAYMENT
  (PAYMENT_NO, PORTFOLIO_CODE,SUS_REF_NO, SETTLE_MODE, ENTRY_TYPE, ID_PORTFOLIO_CODE, PAY_AMOUNT, LIC_BRANCH_CODE, LIC_ACC_NO, PAYEE_BRANCH_CODE, PAYEE_ACC_NO, DN_USER,PROCESS_STATUS, ENTDATE,EFF_VALDATE,OTH_COMMENT,TRNDATE,PAY_STATUS,SAVE_ORDER_NO)
   VALUES
  (M_PAY_NO,M_PORT_CODE,M_CACC_SEQNO,M_SETTLEMENT,'D',M_ID_PORTCODE,M_AMT, M_LIC_BANK_CODE,M_LIC_ACCNO ,'','',M_USER,'N',SYSDATE,TO_DATE(M_EFF_VALDATE,'DD-MM-YYYY'),M_OTH_COMMENT,TO_DATE(M_TRNDATE,'DD-MM-YYYY'),'ENT',M_SAVE_ORDER_NO); --OTH_COMMENT add by inditha 2005-8-10 sr0508-007 --appr1 status add by waruna 2011-09-26

   UPDATE DN_ACC_SUS_PAYMENT
    SET PAY_FROM_INT_BAL_AMT=PAY_FROM_INT_BAL_AMT+M_AMT,
          BAL_TO_BE_PAID    =BAL_TO_BE_PAID-M_AMT,
          LAST_MOD_DATE     =SYSDATE
   WHERE
        SUS_REF_NO=M_CACC_SEQNO AND SUSPENSE_ENTRY_TYPE='D';

END IF;

 
  ------------------------------------------------------
    -- ADDED FOR TIME LOG MANAGEMENT BY YASODHA ON 10-09-2000
   INSERT INTO DN_TIME_LOG_SETTLE
