 EDATE,'A365',0,0,MPRICE,NO_OF_SHARES,MPRICE,0,0,M_USERNAME,M_DEAL_NO,'N','SL',M_DEAL_NO,'EQUITY_COR',0,SYSDATE,SYSDATE,'',I.INV_TYPE);
