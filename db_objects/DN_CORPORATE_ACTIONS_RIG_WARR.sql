  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CORPORATE_ACTIONS_RIG_WARR" 
(
   M_LAST_DAILY         VARCHAR2 ,
 M_USERNAME   VARCHAR2)


IS

 CURSOR C1 IS
SELECT A.PORTFOLIO_CODE PORT,B.SECURITY_CODE SEC,B.INST_TYPE INST,
 SUM(A.FACE_VAL) NOOFSHARES,DN_GET_DEAL_INV_TYPE_NAME(A.DEAL_NO) INV_TYPE,A.SECURITY_CODE SEC1,A.INST_TYPE INST1
 FROM DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_REF_SECURITY B,DN_CORPORATE_ACTIONS C
 WHERE C.SECURITY_CODE=B.SECURITY_CODE
 AND A.SERIAL_NO_STATUS='INV'
 AND A.SECURITY_CODE =C.REL_SECURITY_CODE AND --FROM DN_CORPORATE_ACTIONS A
-- WHERE
 C.ACTIVITY IN ('RIGHTS','WARRANT') AND C.REC_DATE = TO_DATE(M_LAST_DAILY,'DD-MM-YYYY')
 AND C.INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT
 WHERE INST_CAT ='EQUITY') AND STATUS = 'HPROCESS'-- )
 GROUP BY A.PORTFOLIO_CODE,B.SECURITY_CODE,B.INST_TYPE,A.SECURITY_CODE,A.INST_TYPE,DN_GET_DEAL_INV_TYPE_NAME(A.DEAL_NO);
 
 

