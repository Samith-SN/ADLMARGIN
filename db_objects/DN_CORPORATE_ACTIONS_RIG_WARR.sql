 */

 --RAISE_APPLICATION_ERROR(-20201,'NO_OF_SHARES'||NO_OF_SHARES);

 /*MBFSL_OUTRIGHT_IN2(M_DEAL_NO,I.SEC,'',NO_OF_SHARES,1,'CASH',0,'','','COM1','COM2','BR1','BR2',0,0,
 'COST','COST','PR','PR',0,0,0,0,0,0,'SUB1','EQUITY','',0,'NWAMALL',0,'SL');
COMMENTED BY INDITHA 2005-7-14 FOR VC05-008
 */
 --ADD BY INDITHA 2005-7-14 FOR VC05-008
 DN_CORPORATE_ACTION_ORDEAL_GEN (M_DEAL_NO,I.PORT,MISSUER_CODE,I.INST,I.SEC,M_END_CODE,'SLR','UD',
 TO_CHAR(EDATE,'DD-MM-YYYY'),'A365',0,0,MPRICE,NO_OF_SHARES,MPRICE,0,0,M_USERNAME,M_DEAL_NO,'N','SL',M_DEAL_NO,'EQUITY_COR',0,TO_CHAR(SYSDATE,'DD-MM-YYYY'),TO_CHAR(SYSDATE,'DD-MM-YYYY'));

 UPDATE DN_INV_OUTPS_DEAL_SERIAL_NO A
 SET    SERIAL_NO_STATUS = 'SND',
        SALE_EFF_VALDATE = EDATE,
        SALE_DEAL_NO     = M_DEAL_NO,
        COST_TRANS_STATUS= 'Y'
 WHERE  PORTFOLIO_CODE   = I.PORT AND
        SECURITY_CODE    = I.SEC1 AND
        SERIAL_NO_STATUS = 'INV'; 


 END LOOP;


 UPDATE DN_CORPORATE_ACTIONS
 SET STATUS = 'PROCESS'
 WHERE ACTIVITY IN ('RIGHTS','WARRANT') AND SECURITY_CODE=SEC_CODE AND INST_TYPE=MINST
 AND REC_DATE = TO_DATE(M_LAST_DAILY,'DD-MM-YYYY') AND STATUS = 'PROCESSED';



END ;

