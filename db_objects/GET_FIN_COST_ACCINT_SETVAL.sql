   M_RETURN_2                   varchar(100);*/
BEGIN

  SELECT TO_DATE(M_EFF_VALDATE_TYPE,'DD/MM/YYYY')
   INTO M_EFF_VALDATE
   FROM DUAL;

  M_BOND_FACE_VALUE:=100.00;  -- Allways bond face value is this

  SELECT
     ISSUE_DATE,COUPON_INT
     INTO
     M_ISSUE_DATE,M_COUPON_INT
  FROM
     DN_REF_SECURITY
  WHERE
     SECURITY_CODE=M_SECURITY_CODE;

  SELECT
     COUNT(SECURITY_CODE) INTO M_NO_DAYS_P_ANN
  FROM
     DN_REF_SECURITY_INT_PAY_DATES
  WHERE
     SECURITY_CODE=M_SECURITY_CODE
     AND
     INT_PAY_DATE>=M_ISSUE_DATE
     AND
     INT_PAY_DATE<=ADD_MONTHS(M_ISSUE_DATE,12);

 -- Next coupon date

  SELECT
     MIN(INT_PAY_DATE) INTO  M_NEXT_COUPON_DATE
  FROM
     DN_REF_SECURITY_INT_PAY_DATES
  WHERE
     SECURITY_CODE=M_SECURITY_CODE
     AND
     INT_PAY_DATE>M_EFF_VALDATE;--REMOVED "=" SING ON 1/9/2003 SVA

 --CHANGED FROM INT_PAY_DATE>M_EFF_VALDATE TO INT_PAY_DATE>=M_EFF_VALDATE
 -- CHANGED ON 8/10/1999 TO HANDLE ERROR IN PRICE WHERE EFF VAL DATE = MATURITY DATE
 -- CHANGED BY TDS AND SM


-- Last coupon date

  SELECT
     MAX(INT_PAY_DATE) INTO  M_LAST_COUPON_DATE
  FROM
     DN_REF_SECURITY_INT_PAY_DATES
  WHERE
     SECURITY_CODE=M_SECURITY_CODE
     AND
     INT_PAY_DATE<=M_EFF_VALDATE; --ADDED "=" SING ON 1/9/2003 BY SM

  IF M_LAST_COUPON_DATE IS NULL THEN

     ---Which is higher

     M_LAST_COUPON_DATE:=M_ISSUE_DATE;

  END IF;

  -- Interest accural

    IF M_EFF_VALDATE>M_ISSUE_DATE THEN

       M_NO_DAYS_INT_ACCRUAL:=M_EFF_VALDATE-M_LAST_COUPON_DATE;

       M_INT_ADJ:=ROUND((((M_BOND_FACE_VALUE*M_COUPON_INT)/M_NO_DAYS_P_ANN)/(M_NEXT_COUPON_DATE-M_LAST_COUPON_DATE)*M_NO_DAYS_INT_ACCRUAL),4);

    ELSE

      M_INT_ADJ:=0;

    END IF;

   -- COST, accured interest and total transaction value

  --OPEN CUR_VALUES FOR

