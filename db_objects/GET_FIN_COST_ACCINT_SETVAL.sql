   (
    M_SECURITY_CODE             DN_TRN_OUTP_SALE.SECURITY_CODE%TYPE,
    M_CLEAN_PRICE              DN_TRN_OUTP_SALE.PRICE_CLEAN%TYPE,
    M_EFF_VALDATE_TYPE          VARCHAR2,
