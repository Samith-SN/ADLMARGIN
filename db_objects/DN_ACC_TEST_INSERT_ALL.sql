set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_TEST_INSERT_ALL" 
(
M_ENT_DATE        DN_ACC_LICENCEE_INST_ACCOUNT.ENTDATE%TYPE
)
AS

/* PROCEDURE  - DN_ACC_TEST_INSERT_ALL TO INSERT ALL RECORDS AT ONCE
   CREATED BY - LATHIKA
   CREATED ON - 26/01/2000*/



BEGIN

--RAISE_APPLICATION_ERROR(-20201,'DATE'||''||M_ENT_DATE);
-------------------(1)-------------------------
IF M_ENT_DATE IS NOT NULL  THEN

INSERT INTO DN_ACC_LICEN_INST_GEN_DETAIL
   (PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,ENTDATE,PROC_DESC,CORR_ACC_NO)
SELECT A.PORTFOLIO_CODE,A.TRNDATE,NVL(A.ACC_TYPE_CODE,'0'),A.DRCR_STATUS,A.TRNAMOUNT,
       A.DOCREFNO,A.ENTDATE,A.PROC_DESC,A.CORR_ACC_NO
  FROM
       DN_ACC_LICENCEE_INST_ACCOUNT A
 WHERE
       LTRIM(RTRIM(to_char(A.ENTDATE,'DD-MON-YYYY') ))<LTRIM(RTRIM(to_char(M_ENT_DATE,'DD-MON-YYYY') ));

INSERT INTO DN_ACC_LICEN_INST_GEN_DETAIL
   (PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,ENTDATE,PROC_DESC,CORR_ACC_NO)
SELECT A.PORTFOLIO_CODE,A.TRNDATE,NVL(A.ACC_TYPE_CODE,'0'),A.DRCR_STATUS,A.TRNAMOUNT,
       A.DOCREFNO,A.ENTDATE,A.PROC_DESC,A.CORR_ACC_NO
  FROM
       DN_ACC_LICENCEE_GEN_ACCOUNT A
 WHERE
       LTRIM(RTRIM(to_char(A.ENTDATE,'DD-MON-YYYY') ))<LTRIM(RTRIM(to_char(M_ENT_DATE,'DD-MON-YYYY') ));
-----------------
END IF;

COMMIT;
END DN_ACC_TEST_INSERT_ALL;

