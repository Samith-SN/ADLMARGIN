--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."INCOME_CAP_ROUTINE" 
(
M_END_DATE        VARCHAR2,
M_PORT            DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE ,
M_USER            DN_REF_USER.DN_USER%TYPE
)

AS
M_LAST_PROCESSED DATE;
M_START_DATE VARCHAR2(10);
BEGIN
--------------------START DATE-----------------------------
SELECT  LAST_PROCESSED+1
INTO    M_LAST_PROCESSED
FROM    DN_SYS_INCOME_CAP;

SELECT TO_CHAR(M_LAST_PROCESSED,'DD-MM-YYYY') INTO M_START_DATE FROM DUAL;
-----------------------------------------------------------
IF(M_PORT IS NOT NULL ) THEN


IF (M_PORT = 'ALL') THEN
 INCOME_CAP_ROUTE_ALL(M_START_DATE,M_END_DATE,M_USER);
ELSE
 INCOME_CAP_ROUTE_PORT(M_START_DATE,M_END_DATE,M_USER,M_PORT);
END IF;
END IF;



COMMIT;
EXCEPTION WHEN OTHERS THEN
DELETE FROM  DN_INCOME_CAP_PARAMETERS;
RAISE_APPLICATION_ERROR(-20201,'ERROR IN INCOME CAPITALIZATION ROUTINE');

END INCOME_CAP_ROUTINE;

/
