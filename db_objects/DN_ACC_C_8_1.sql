)
AS

  /* PROCEDURE  - DN_ACC_C_8_1  BORROWING OF SECURITIES BY PORTFOLIO FROM FCAM
   SYSTEM     - DEALNET
   CREATED BY - SUKATHISVARAN
   CREATED ON - 05/AUGUEST/1999*/


M_PORTF_CODE      DN_TRN_BL_SECURITY.BORR_PORTFOLIO_CODE%TYPE;
M_INST_TYPE       DN_TRN_BL_SECURITY.INST_TYPE%TYPE;
M_TRNDATE         DN_TRN_BL_SECURITY.EFF_VALDATE%TYPE;
M_TRNAMOUNT       DN_TRN_BL_SECURITY.FACE_VALUE%TYPE;
M_DN_PORTF_CODE   DN_TRN_BL_SECURITY.LEND_PORTFOLIO_CODE%TYPE;

BEGIN

SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE,INST_TYPE,EFF_VALDATE,FACE_VALUE
INTO M_PORTF_CODE,M_DN_PORTF_CODE,M_INST_TYPE,M_TRNDATE,M_TRNAMOUNT
FROM DN_TRN_BL_SECURITY
WHERE DEAL_NO=M_DOCREFNO;


INSERT INTO DN_ACC_PORTF_INST_ACCOUNT
   (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_INST_TYPE,M_TRNDATE,'040','DR',M_TRNAMOUNT,M_DOCREFNO,'BORROW OF SECURITIES BY PORTF','041');
INSERT INTO DN_ACC_PORTF_INST_ACCOUNT
   (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_INST_TYPE,M_TRNDATE,'041','CR',M_TRNAMOUNT,M_DOCREFNO,'BORROW OF SECURITIES BY PORTF','040');

INSERT INTO DN_ACC_LICENCEE_INST_ACCOUNT
   (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_DN_PORTF_CODE,M_INST_TYPE,M_TRNDATE,'043','DR',M_TRNAMOUNT,M_DOCREFNO,'BORROW OF SECURITIES BY PORTF','042');
INSERT INTO DN_ACC_LICENCEE_INST_ACCOUNT
   (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_DN_PORTF_CODE,M_INST_TYPE,M_TRNDATE,'042','CR',M_TRNAMOUNT,M_DOCREFNO,'BORROW OF SECURITIES BY PORTF','043');


END DN_ACC_C_8_1;

