        SUM(A.CARR_VAL)X11,
        B.INST_TYPE X12,
        MT_PERCENT X13,
        A.PORTFOLIO_CODE X14
        FROM
        DN_INV_OUTPS_DEAL_SEC A,
        DN_REF_SECURITY B
        WHERE
        --A.PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
        --A.INST_TYPE=M_INST_TYPE AND
        A.SECURITY_CODE=B.SECURITY_CODE AND
        TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_DATE,'DD/MM/YYYY') AND
        TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
        TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
        (A.FACE_VAL > 0 OR A.FACE_VAL < 0) AND
        (A.TRN_TYPE = 'B' OR A.TRN_TYPE = 'S') AND
        A.FACE_VAL_CURR IS NULL /*AND
        A.SCRIP_STATUS=M_SCRIP_STATUS*/
        GROUP BY A.PORTFOLIO_CODE,A.SECURITY_CODE,B.INST_TYPE,B.MATURITY_DATE,DN_GET_COUPON_RATE(B.SECURITY_CODE),MT_PERCENT/*,
