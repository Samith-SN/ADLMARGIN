*/
 
 
 
BEGIN
--raise_application_error(-20001,M_MAIL_CODE||'**'||M_MAIL_DESC||'**'||M_MAIL_CAT||'**'||M_SCREEN_NAME||'**'||M_USER);--prab
 
--DN_VALIDATE_SAVE_RIGHTS('AF_AD_BANK',M_USER);
 
IF UPPER(M_SCREEN_NAME)='NEW' THEN --NEW
--ADD NEW RECORDS TO TABLE
INSERT INTO FA_CR_LETTER_MAIL_CODES
(MAIL_CODE,MAIL_DESC,MAIL_CAT,ACTIVE_STATUS,ENT_USER,ENT_DATE)
VALUES(UPPER(M_MAIL_CODE),M_MAIL_DESC,M_MAIL_CAT,'Y',UPPER(M_USER),SYSDATE);
 
ELSIF UPPER(M_SCREEN_NAME)='EDIT' THEN --UPDATE
--BACKUP EXSISTING RECORDS TO BACKUP TABLE
INSERT INTO FA_CR_LETTER_MAIL_CODES_BK
(MAIL_CODE,MAIL_DESC,MAIL_CAT,ACTIVE_STATUS,ENT_USER,ENT_DATE)
SELECT MAIL_CODE,MAIL_DESC,MAIL_CAT,ACTIVE_STATUS,ENT_USER,ENT_DATE
FROM FA_CR_LETTER_MAIL_CODES
WHERE UPPER(MAIL_CODE)=UPPER(M_MAIL_CODE);
 
UPDATE FA_CR_LETTER_MAIL_CODES
SET MAIL_DESC=M_MAIL_DESC,
    MAIL_CAT = M_MAIL_CAT,
    ACTIVE_STATUS='Y',
    MOD_USER=UPPER(M_USER),
    MOD_DATE=SYSDATE
WHERE UPPER(MAIL_CODE)=UPPER(M_MAIL_CODE);
 
ELSIF UPPER(M_SCREEN_NAME)='DACT' THEN --DEACTIVATE
--BACKUP EXSISTING RECORDS TO BACKUP TABLE
INSERT INTO FA_CR_LETTER_MAIL_CODES_BK
(MAIL_CODE,MAIL_DESC,MAIL_CAT,ACTIVE_STATUS,ENT_USER,ENT_DATE)
SELECT MAIL_CODE,MAIL_DESC,MAIL_CAT,ACTIVE_STATUS,ENT_USER,ENT_DATE
FROM FA_CR_LETTER_MAIL_CODES
WHERE UPPER(MAIL_CODE)=UPPER(M_MAIL_CODE);
 
 
--UPDATE RECORDS TO TABLE
UPDATE FA_CR_LETTER_MAIL_CODES
 SET ACTIVE_STATUS='N',
  MOD_USER=UPPER(M_USER),
  MOD_DATE=SYSDATE
WHERE UPPER(MAIL_CODE)=UPPER(M_MAIL_CODE);
 
ELSIF UPPER(M_SCREEN_NAME)='RACT' THEN --REACTIVATE
--BACKUP EXSISTING RECORDS TO BACKUP TABLE
INSERT INTO FA_CR_LETTER_MAIL_CODES_BK
(MAIL_CODE,MAIL_DESC,MAIL_CAT,ACTIVE_STATUS,ENT_USER,ENT_DATE)
SELECT MAIL_CODE,MAIL_DESC,MAIL_CAT,ACTIVE_STATUS,ENT_USER,ENT_DATE
FROM FA_CR_LETTER_MAIL_CODES
WHERE UPPER(MAIL_CODE)=UPPER(M_MAIL_CODE);
 
 

UPDATE FA_CR_LETTER_MAIL_CODES
 SET ACTIVE_STATUS='Y',
  MOD_USER=UPPER(M_USER),
  MOD_DATE=SYSDATE
WHERE UPPER(MAIL_CODE)=UPPER(M_MAIL_CODE);
 
END IF;
 

 
END;

