  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."FA_CR_SAVE_MAIL_CODE" 
( 
M_MAIL_CODE       FA_CR_LETTER_MAIL_CODES.MAIL_CODE%TYPE,
M_MAIL_DESC       FA_CR_LETTER_MAIL_CODES.MAIL_DESC%TYPE,
M_MAIL_CAT       FA_CR_LETTER_MAIL_CODES.MAIL_CAT%TYPE,
M_SCREEN_NAME     VARCHAR2,
M_USER            VARCHAR2
)
 
 AS
/*
