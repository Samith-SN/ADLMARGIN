--------------------------------------------------------
--  DDL for Procedure DN_REPO_FRESH_SCRIPLESS
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_REPO_FRESH_SCRIPLESS" 
(
  M_DEALNO           DN_TRN_REPO_FRESH.DEAL_NO%TYPE,
  M_USER            DN_TRN_REPO_FRESH.DN_USER%TYPE


)

AS
    M_COUNT_LEND            INTEGER;
    M_COUNT_BORR            INTEGER;
    M_BORR_PORTFOLIO_CODE   DN_TRN_REPO_FRESH.BORR_PORTFOLIO_CODE%TYPE;
    M_LEND_PORTFOLIO_CODE   DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE;


BEGIN

  SELECT  BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE
  INTO    M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE
  FROM    DN_TRN_REPO_FRESH
  WHERE   DEAL_NO=M_DEALNO ;


  SELECT  COUNT(*)
  INTO    M_COUNT_LEND
  FROM    DN_REF_PORTFOLIO
  WHERE   PORTFOLIO_CODE=M_LEND_PORTFOLIO_CODE AND
          PF_TYPE='P' ;


  SELECT  COUNT(*)
  INTO    M_COUNT_BORR
  FROM    DN_REF_PORTFOLIO
  WHERE   PORTFOLIO_CODE=M_BORR_PORTFOLIO_CODE AND
          PF_TYPE='P' ;


  IF(M_COUNT_LEND>0)THEN
     DN_REPO_LEND_SCRIPLESS(M_DEALNO);
  END IF;

  IF(M_COUNT_BORR>0)THEN
    DN_REPO_BORR_SCRIPLESS(M_DEALNO,M_USER);
  END IF;




--COMMIT;
END DN_REPO_FRESH_SCRIPLESS;

/
