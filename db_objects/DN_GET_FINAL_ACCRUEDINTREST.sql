--  DDL for Function DN_GET_FINAL_ACCRUEDINTREST
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_FINAL_ACCRUEDINTREST" 
  ( M_DEALNO   IN VARCHAR2,
    M_TODATE   IN VARCHAR2,
    M_FRMDATE  IN VARCHAR2,
    BORROWER   IN VARCHAR2,
    LENDER     IN VARCHAR2,
    M_TABLE    IN VARCHAR2)
  RETURN  NUMBER IS
    --
    -- Purpose: This function will return the current Accrude Interest Amount
    --
    -- Created By :
    -- Person      Date           Comments
    -- Siva        28-07-2000
    -- ---------   ----------     -------------------------------------------
   ----------------------------------------------------------------------------------------------
FINALINT      NUMBER DEFAULT 0;
INITIALINT    NUMBER DEFAULT 0;
SETTLEINT     NUMBER DEFAULT 0;
PRESETINT     NUMBER DEFAULT 0;
PREMATINT     NUMBER DEFAULT 0;
PREMATINT2    NUMBER DEFAULT 0;
PREMATLEG1    NUMBER DEFAULT 0;
PREMATEFFDATE DATE;
PREMATCHK     NUMBER(1) DEFAULT 0;
ORIGDEALNO    VARCHAR2(20);
ORIGEFFDATE   DATE;
ORIGYIELD     NUMBER;
ORIGBASIS     VARCHAR2(10);
M_CNT         NUMBER DEFAULT 0;

BEGIN
----

SELECT COUNT(*) INTO PREMATCHK FROM(SELECT ORIGINALDEAL_NO FROM DN_TRN_PREMATURE_SETTLE
WHERE (ORIGINALDEAL_NO=M_DEALNO));

 IF PREMATCHK =0 THEN

     IF M_TABLE = 'FRESH' THEN
        INITIALINT:=0;
        SELECT DN_GET_ACCRUED_INTEREST(A.LEG1_VALUE,(A.YIELD*100),A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY')) INTO INITIALINT
        FROM DN_TRN_REPO_FRESH A
        WHERE A.DEAL_NO=M_DEALNO;

       /* SETTLEINT:=0;
        SELECT SUM(SETTINT)INTO SETTLEINT FROM (
        SELECT WD_GET_ACCRUED_INTEREST(A.LEG1_VALUE,A.YIELD,A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY')) SETTINT
        FROM  CSADMIN.WEBDN_TRN_REPO_FRESH A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY')
        );*/

    END IF;

     IF M_TABLE = 'ROLLOVER' THEN
        INITIALINT:=0;
        SELECT DN_GET_ACCRUED_INTEREST(A.LEG1_VALUE,(A.YEILD*100),A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY')) INTO INITIALINT
        FROM DN_TRN_REPO_ROLLOVER A
        WHERE A.DEAL_NO =M_DEALNO ;
        /*
        SETTLEINT:=0;
        SELECT SUM(SETTINT) INTO SETTLEINT FROM(
        SELECT WD_GET_ACCRUED_INTEREST(A.LEG1_VALUE,A.YEILD,A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY')) SETTINT
        FROM CSADMIN.WEBDN_TRN_REPO_ROLLOVER A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY')
        );*/

    END IF;
    IF M_TABLE = 'BL_FUND' THEN

        INITIALINT:=0;

        SELECT DN_GET_ACCRUED_INTEREST(A.LEG1_VALUE,(A.YEILD_PER_NET),A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY'))  INTO INITIALINT
        FROM DN_TRN_BL_FUND A
        WHERE A.DEAL_NO = M_DEALNO ;
/*--THIS SECTION IS TO BE REMARKED -- CONSIDER ALL PLACES
        SETTLEINT:=0;
        SELECT SUM(SETTINT) INTO SETTLEINT FROM(
        SELECT WD_GET_ACCRUED_INTEREST(A.LEG1_VALUE,(A.YEILD_PER_NET/1),A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY')) SETTINT
        FROM CSADMIN.WEBDN_TRN_BL_FUND A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY')
        );
---*/
        ----
    END IF;
   ELSE
     IF M_TABLE = 'FRESH' THEN
        INITIALINT:=0;

        SELECT DN_GET_ACCRUED_INTEREST(A.LEG1_VALUE,(A.YIELD*100),A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY')) INTO INITIALINT
        FROM DN_TRN_REPO_FRESH A
        WHERE A.DEAL_NO=M_DEALNO;

        ---Pre Mature Calculation
        PREMATINT:=0;
        PRESETINT:=0;
        PREMATINT2:=0;
        FOR PREMATREC IN (SELECT * FROM DN_TRN_PREMATURE_SETTLE
        WHERE (ORIGINALDEAL_NO=M_DEALNO)) LOOP

        SELECT COUNT(*) INTO M_CNT FROM(
        SELECT A.LEG1_VALUE,A.EFF_VALDATE
        FROM DN_TRN_REPO_FRESH A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA')
        AND A.APP_STATUS <> 'CANCEL'
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY'));

        IF M_CNT > 0 THEN
        SELECT A.LEG1_VALUE,A.EFF_VALDATE INTO PREMATLEG1,PREMATEFFDATE
        FROM DN_TRN_REPO_FRESH A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA')
        AND A.APP_STATUS <> 'CANCEL'
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY');

        SELECT A.EFF_VALDATE,YIELD,INT_RATE_BASE_CODE INTO ORIGEFFDATE,ORIGYIELD,ORIGBASIS
        FROM DN_TRN_REPO_FRESH A
        WHERE A.LEND_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE = BORROWER
        AND A.DEAL_NO=PREMATREC.ORIGINALDEAL_NO
        AND A.LEND_PORTFOLIO_CODE  IN('LANDM','CEYLEC','FMA')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY');

       PREMATINT:=PREMATINT+(PREMATLEG1-DN_FIN_LEG1_F_LEG2(PREMATLEG1,ORIGYIELD,(PREMATEFFDATE-ORIGEFFDATE),ORIGBASIS,ORIGEFFDATE));

        --CALCULATION OF OFF SETTING INTEREST ON PRE MAT DEAL BEYOND LEG 1 DATE----

        SELECT DN_GET_ACCRUED_INTEREST(A.LEG1_VALUE,(A.YIELD*100),A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY'))
        INTO PRESETINT
        FROM DN_TRN_REPO_FRESH A
        WHERE A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
              AND A.APP_STATUS <> 'CANCEL';

        PREMATINT2:=PREMATINT2+PRESETINT;

       END IF;
       END LOOP;
       ----End of PreMat Calculation----


    END IF;

     IF M_TABLE = 'ROLLOVER' THEN
        INITIALINT:=0;
        SELECT DN_GET_ACCRUED_INTEREST(A.LEG1_VALUE,(A.YEILD*100),A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY')) INTO INITIALINT
        FROM DN_TRN_REPO_ROLLOVER A
        WHERE A.DEAL_NO =M_DEALNO ;

        ---Pre Mature Calculation
        PREMATINT:=0;
        PRESETINT:=0;
        PREMATINT2:=0;

        FOR PREMATREC IN (SELECT * FROM DN_TRN_PREMATURE_SETTLE
        WHERE (ORIGINALDEAL_NO=M_DEALNO)) LOOP

        SELECT COUNT(*) INTO M_CNT FROM (
        SELECT A.LEG1_VALUE,A.EFF_VALDATE
        FROM DN_TRN_REPO_FRESH A --CHANGED FROM 'ROLLOVER' BECAUSE ALL REPO PRE MAT SETTLEMENTS WILL BE DONE THROUGH THE REPO FRESH TABLE
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA')
        AND A.APP_STATUS <> 'CANCEL'
        AND TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY'));
        IF M_CNT>0 THEN
        SELECT A.LEG1_VALUE,A.EFF_VALDATE INTO PREMATLEG1,PREMATEFFDATE
        FROM DN_TRN_REPO_FRESH A --CHANGED FROM 'ROLLOVER' BECAUSE ALL REPO PRE MAT SETTLEMENTS WILL BE DONE THROUGH THE REPO FRESH TABLE
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA')
        AND A.APP_STATUS <> 'CANCEL'
        AND TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY');

        SELECT A.EFF_VALDATE,YEILD,INT_RATE_BASE_CODE INTO ORIGEFFDATE,ORIGYIELD,ORIGBASIS
        FROM DN_TRN_REPO_ROLLOVER A
        WHERE A.LEND_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE = BORROWER
        AND A.DEAL_NO=PREMATREC.ORIGINALDEAL_NO
        AND A.LEND_PORTFOLIO_CODE  IN('LANDM','CEYLEC','FMA')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY');

        PREMATINT:=PREMATINT+(PREMATLEG1-DN_FIN_LEG1_F_LEG2(PREMATLEG1,ORIGYIELD,(PREMATEFFDATE-ORIGEFFDATE),ORIGBASIS,ORIGEFFDATE));


        --CALCULATION OF OFF SETTING INTEREST ON PRE MAT DEAL BEYOND LEG 1 DATE----
        --YIELD SHOULD BE MULTIPLY BY 100 FOR THE ACCRUED_INTEREST FUNCTION
        SELECT DN_GET_ACCRUED_INTEREST(A.LEG1_VALUE,(A.YIELD*100),A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY'))
        INTO PRESETINT
        FROM DN_TRN_REPO_FRESH A --CHANGED FROM 'ROLLOVER' BECAUSE ALL REPO PRE MAT SETTLEMENTS WILL BE DONE THROUGH THE REPO FRESH TABLE
        WHERE A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.APP_STATUS <> 'CANCEL';

        PREMATINT2:=PREMATINT2+PRESETINT;

        END IF;
       END LOOP;
      ----End of PreMat Calculation----

    END IF;
    IF M_TABLE = 'BL_FUND' THEN
        INITIALINT:=0;

        SELECT DN_GET_ACCRUED_INTEREST(A.LEG1_VALUE,(A.YEILD_PER_NET),A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY'))  INTO INITIALINT
        FROM DN_TRN_BL_FUND A
        WHERE A.DEAL_NO = M_DEALNO ;

        ---Pre Mature Calculation
        PREMATINT:=0;
        PRESETINT:=0;
        PREMATINT2:=0;
        FOR PREMATREC IN (SELECT * FROM DN_TRN_PREMATURE_SETTLE
        WHERE (ORIGINALDEAL_NO=M_DEALNO)) LOOP

        SELECT COUNT(*) INTO M_CNT FROM (
        SELECT A.LEG1_VALUE,A.EFF_VALDATE
        FROM DN_TRN_BL_FUND A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA')
        AND A.APP_STATUS <> 'CANCEL'
        AND TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY'));

        IF M_CNT>0 THEN
        SELECT A.LEG1_VALUE,A.EFF_VALDATE
        INTO PREMATLEG1,PREMATEFFDATE
        FROM DN_TRN_BL_FUND A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA')
        AND A.APP_STATUS <> 'CANCEL'
        AND TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY');

        SELECT A.EFF_VALDATE,(YEILD_PER_NET/1),INT_RATE_BASE_CODE
        INTO ORIGEFFDATE,ORIGYIELD,ORIGBASIS
        FROM DN_TRN_BL_FUND A
        WHERE A.LEND_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE = BORROWER
        AND A.DEAL_NO=PREMATREC.ORIGINALDEAL_NO
        AND A.LEND_PORTFOLIO_CODE  IN('LANDM','CEYLEC','FMA')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY');

        PREMATINT:=PREMATINT+(PREMATLEG1-DN_FIN_LEG1_F_LEG2(PREMATLEG1,(ORIGYIELD/100),(PREMATEFFDATE-ORIGEFFDATE),ORIGBASIS,ORIGEFFDATE));

        --CALCULATION OF OFF SETTING INTEREST ON PRE MAT DEAL BEYOND LEG 1 DATE----

        SELECT DN_GET_ACCRUED_INTEREST(A.LEG1_VALUE,(A.YEILD_PER_NET),A.INT_RATE_BASE_CODE,DECODE(SIGN((TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_TODATE,'DD-MM-YYYY'))),-1,TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),M_TODATE),TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY'))
        INTO PRESETINT
        FROM DN_TRN_BL_FUND A
        WHERE A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
              AND A.APP_STATUS <> 'CANCEL';

        PREMATINT2:=PREMATINT2+PRESETINT;

        END IF;
       END LOOP;
       ----End of PreMat Calculation----
       ----
    END IF;


   END IF;
     IF INITIALINT IS NULL THEN
        INITIALINT:=0;
     END IF;
     IF SETTLEINT IS NULL THEN
         SETTLEINT:=0;
     END IF;
     IF PREMATINT IS NULL THEN
         PREMATINT:=0;
     END IF;
     IF PREMATINT2 IS NULL THEN
         PREMATINT2:=0;
     END IF;
--RAISE_APPLICATION_ERROR(-20000,INITIALINT||'-'||SETTLEINT||'-'||PREMATINT);
    FINALINT:=0;
    FINALINT:=INITIALINT-SETTLEINT-PREMATINT-PREMATINT2;
    IF ABS(FINALINT) < 2 THEN
         FINALINT:=0.00;
     END IF;
    RETURN FINALINT ;
END; -- Function WD_GET_FINAL_ACCRUEDINTREST

