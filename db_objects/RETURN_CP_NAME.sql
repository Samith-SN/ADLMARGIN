--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_CP_NAME" 
(
  M_DEAL		DN_TRN_REPO_FRESH.DEAL_NO%TYPE
)
RETURN VARCHAR2

AS
M_PF_NAME VARCHAR2(50);

BEGIN

IF SUBSTR(M_DEAL,0,2) = 'OR'  THEN
      SELECT DISTINCT(PF_NAME)
      INTO M_PF_NAME
      FROM DN_REF_PORTFOLIO
      WHERE PORTFOLIO_CODE = (SELECT SELL_PORTFOLIO_CODE FROM DN_TRN_OUTP_SALE WHERE DEAL_NO = M_DEAL );
END IF;

RETURN M_PF_NAME;

END RETURN_CP_NAME;

/
