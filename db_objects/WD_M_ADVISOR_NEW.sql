M_FULL_DATE_DOB_D := TO_DATE(M_FULL_DATE_DOB,'DD-MM-YYYY');

--RAISE_APPLICATION_ERROR(-20201,M_TXT_CODE||' '||M_TXT_TITLE||' '||M_TXT_DESIG||' '||M_TXT_ADD1||' '|| M_TXT_ADD2||' '||M_TXT_ADD3||' '||M_TXT_ADD4||' '||M_FULL_DATE_DOB||' '||M_TXT_NIC||' '||M_TXT_REMARKS||' '||M_TXT_CON1||' '||M_FULL_DATE_DOB_D);

          
       SELECT LPAD(TO_CHAR(DN_SEQ_ADVISOR_CODE.NEXTVAL),8,'0') INTO M_TXT_CODE FROM DUAL;
       M_TXT_CODE:=  'ADV-'||M_TXT_CODE;

INSERT INTO DN_REF_ADVISOR
            (ADV_CODE,ADV_NAME,ADV_DESIG,ADV_ADD1,ADV_ADD2,ADV_ADD3,ADV_ADD4,ADV_DOB,ADV_NIC,REMARKS,CON_NO,BROKER_CODE)
