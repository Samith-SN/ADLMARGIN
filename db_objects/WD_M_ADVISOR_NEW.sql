  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."WD_M_ADVISOR_NEW" 

   (
    M_TXT_CODE         IN OUT  DN_REF_ADVISOR.ADV_CODE%TYPE,
    M_TXT_TITLE			 DN_REF_ADVISOR.ADV_NAME%TYPE,
	M_TXT_DESIG			 DN_REF_ADVISOR.ADV_DESIG%TYPE,
	M_TXT_ADD1			 DN_REF_ADVISOR.ADV_ADD1%TYPE,
	M_TXT_ADD2			 DN_REF_ADVISOR.ADV_ADD2%TYPE,
	M_TXT_ADD3           DN_REF_ADVISOR.ADV_ADD3%TYPE,
    M_TXT_ADD4			 DN_REF_ADVISOR.ADV_ADD4%TYPE,
	M_FULL_DATE_DOB		 VARCHAR2,
