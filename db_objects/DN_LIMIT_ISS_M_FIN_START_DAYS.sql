  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_LIMIT_ISS_M_FIN_START_DAYS" 
(
 M_MAT_START_DAYS        LMT_STR_ISSUER_INST_MATU.START_DAYS%TYPE,
 M_ISSUER_CODE           LMT_STR_ISSUER_INST_MATU.ISSUER_CODE%TYPE,
 M_LIAB_TYPE               LMT_STR_ISSUER_INST_MATU.ISSUER_LIABILITY_TYPE%TYPE,
 M_INST_TYPE             LMT_STR_ISSUER_INST_MATU.INST_TYPE%TYPE
 )
 RETURN  INTEGER

IS

    -- FUNCTION     : THIS RETURNS START DAY;
    -- SYSTEM       : DEALNET SYSTEM
    -- CREATED BY   : SUKATHIS
    -- CREATED ON   : 24/01/2000

M_RETURN_DAYS       INTEGER;

BEGIN
SELECT DISTINCT MAX(START_DAYS) INTO M_RETURN_DAYS
    FROM LMT_STR_ISSUER_INST_MATU
    WHERE START_DAYS <= M_MAT_START_DAYS
            AND ISSUER_CODE=M_ISSUER_CODE AND
                 INST_TYPE=M_INST_TYPE AND
                  ISSUER_LIABILITY_TYPE=M_LIAB_TYPE  ;

RETURN M_RETURN_DAYS;

END DN_LIMIT_ISS_M_FIN_START_DAYS;

/
