--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_PF_NAME2" 
(
  M_BORR_PORTFOLIO_CODE		DN_TRN_REPO_FRESH.BORR_PORTFOLIO_CODE%TYPE
)
RETURN VARCHAR2

AS
M_PF_NAME VARCHAR2(100);

BEGIN
     SELECT DISTINCT(PF_NAME)
      INTO M_PF_NAME
      FROM DN_REF_PORTFOLIO
      WHERE PORTFOLIO_CODE = M_BORR_PORTFOLIO_CODE;

RETURN M_PF_NAME;

END RETURN_PF_NAME2;

