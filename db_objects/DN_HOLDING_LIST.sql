set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_HOLDING_LIST" 
(
  M_INVTYPE  IN VARCHAR2,
  M_FROMDATE IN VARCHAR2,
  M_TODATE   IN VARCHAR2,
  HOLDLST    IN OUT HOLDING_LIST_PKG.HOLDINGLIST
)
IS
BEGIN
OPEN HOLDLST FOR

SELECT DEALNO,BORROWER,LENDER,EFFVALDATE,MATURITYDATE,YEILD,OUTSTANDING,BORRSETTLECOMMENT
,ACCRUEDINTREST
FROM
(SELECT A.DEAL_NO DEALNO,DN_GET_PORTFOLIO_NAME(A.BORR_PORTFOLIO_CODE) BORROWER,
A.LEND_PORTFOLIO_CODE LENDER,TO_CHAR(EFF_VALDATE,'DD-MON-YYYY') EFFVALDATE, TO_CHAR(MATURITY_DATE,'DD-MON-YYYY') MATURITYDATE, YEILD_PER_NET YEILD,
DN_OUTSTANDING_AMOUNTS(A.DEAL_NO,M_TODATE,M_FROMDATE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,'BL_FUND')OUTSTANDING,
DN_GET_FINAL_ACCRUEDINTREST(A.DEAL_NO,M_TODATE,M_FROMDATE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,'BL_FUND')ACCRUEDINTREST,
NVL(BORR_SETTLE_COMMENT,' ')BORRSETTLECOMMENT, LEG1_VALUE, INT_RATE_BASE_CODE
FROM DN_TRN_BL_FUND A , DN_TRN_BL_FUND_SETTLE B
WHERE (A.APP_STATUS <> 'CANCEL') AND (A.DEAL_NO=B.DEAL_NO) AND
TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY') AND
TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FROMDATE,'DD-MM-YYYY') AND
A.LEND_PORTFOLIO_CODE =M_INVTYPE
UNION
SELECT A.DEAL_NO  DEALNO,DN_GET_PORTFOLIO_NAME(A.BORR_PORTFOLIO_CODE)BORROWER,
A.LEND_PORTFOLIO_CODE LENDER,TO_CHAR(EFF_VALDATE,'DD-MON-YYYY')EFFVALDATE, TO_CHAR(MATURITY_DATE,'DD-MON-YYYY')MATURITYDATE, (YEILD*100)YEILD,
DN_OUTSTANDING_AMOUNTS(A.DEAL_NO,M_TODATE,M_FROMDATE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,'ROLLOVER')OUTSTANDING,
DN_GET_FINAL_ACCRUEDINTREST(A.DEAL_NO,M_TODATE,M_FROMDATE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,'ROLLOVER')ACCRUEDINTREST,
NVL(BORR_SETTLE_COMMENT,' ')BORRSETTLECOMMENT, LEG1_VALUE, INT_RATE_BASE_CODE
FROM DN_TRN_REPO_ROLLOVER A , DN_TRN_REPO_ROLLOVER_SETTLE B
WHERE (A.APP_STATUS <> 'CANCEL') AND (A.DEAL_NO=B.DEAL_NO) AND (A.DEAL_NO NOT IN(SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_SETTLEMENT)) AND
TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY') AND
TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FROMDATE,'DD-MM-YYYY') AND
A.LEND_PORTFOLIO_CODE =M_INVTYPE
UNION
SELECT A.DEAL_NO  DEALNO,DN_GET_PORTFOLIO_NAME(A.BORR_PORTFOLIO_CODE)BORROWER,
A.LEND_PORTFOLIO_CODE LENDER,TO_CHAR(EFF_VALDATE,'DD-MON-YYYY')EFFVALDATE, TO_CHAR(MATURITY_DATE,'DD-MON-YYYY')MATURITYDATE, (YEILD*100)YEILD,
DN_OUTSTANDING_AMOUNTS(A.DEAL_NO,M_TODATE,M_FROMDATE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,'ROLLOVER')OUTSTANDING,
DN_GET_FINAL_ACCRUEDINTREST(A.DEAL_NO,M_TODATE,M_FROMDATE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,'ROLLOVER')ACCRUEDINTREST,
NVL(BORR_SETTLE_COMMENT,' ')BORRSETTLECOMMENT, LEG1_VALUE , INT_RATE_BASE_CODE
FROM DN_TRN_REPO_ROLLOVER A , DN_TRN_REPO_ROLLOVER_SETTLE B
WHERE (A.APP_STATUS <> 'CANCEL') AND (A.DEAL_NO=B.DEAL_NO) AND (A.ON_CALL_DEAL='Y') AND
(A.DEAL_NO NOT IN(SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_SETTLEMENT)) AND
TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY') AND
A.LEND_PORTFOLIO_CODE =M_INVTYPE
UNION
SELECT A.DEAL_NO  DEALNO,DN_GET_PORTFOLIO_NAME(A.BORR_PORTFOLIO_CODE)BORROWER,
A.LEND_PORTFOLIO_CODE LENDER,TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY')EFFVALDATE, TO_CHAR(MATURITY_DATE,'DD-MON-YYYY')MATURITYDATE, (YIELD*100)YEILD,
DN_OUTSTANDING_AMOUNTS(A.DEAL_NO,M_TODATE,M_FROMDATE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,'FRESH')OUTSTANDING,
DN_GET_FINAL_ACCRUEDINTREST(A.DEAL_NO,M_TODATE,M_FROMDATE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,'FRESH')ACCRUEDINTREST,
NVL(BORR_SETTLE_COMMENT,' ')BORRSETTLECOMMENT, LEG1_VALUE, INT_RATE_BASE_CODE
FROM DN_TRN_REPO_FRESH A , DN_TRN_REPO_FRESH_SETTLE B
WHERE (A.APP_STATUS <> 'CANCEL') AND (A.DEAL_NO=B.DEAL_NO) AND (A.DEAL_NO NOT IN(SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_SETTLEMENT)) AND
TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY') AND
TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FROMDATE,'DD-MM-YYYY') AND
A.LEND_PORTFOLIO_CODE =M_INVTYPE
UNION
SELECT A.DEAL_NO  DEALNO,DN_GET_PORTFOLIO_NAME(A.BORR_PORTFOLIO_CODE)BORROWER,
A.LEND_PORTFOLIO_CODE LENDER,TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY')EFFVALDATE, TO_CHAR(MATURITY_DATE,'DD-MON-YYYY')MATURITYDATE, (YIELD*100) YEILD,
DN_OUTSTANDING_AMOUNTS(A.DEAL_NO,M_TODATE,M_FROMDATE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,'FRESH')OUTSTANDING,
DN_GET_FINAL_ACCRUEDINTREST(A.DEAL_NO,M_TODATE,M_FROMDATE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,'FRESH')ACCRUEDINTREST,
NVL(BORR_SETTLE_COMMENT,' ')BORRSETTLECOMMENT, LEG1_VALUE, INT_RATE_BASE_CODE
FROM DN_TRN_REPO_FRESH A , DN_TRN_REPO_FRESH_SETTLE B
WHERE (A.APP_STATUS <> 'CANCEL') AND (A.DEAL_NO=B.DEAL_NO) AND (A.ON_CALL_DEAL='Y') AND
(A.DEAL_NO NOT IN(SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_SETTLEMENT)) AND
TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY') AND
A.LEND_PORTFOLIO_CODE =M_INVTYPE)
WHERE (OUTSTANDING>0)
ORDER BY BORRSETTLECOMMENT;

END; -- Procedure WD_HOLDING_LIST

