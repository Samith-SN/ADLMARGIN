--------------------------------------------------------
--  DDL for Procedure MATURITY_DATE_CURSOR
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MATURITY_DATE_CURSOR" 
 IS
CURSOR MYCURSOR IS
SELECT CEIL(MATURITY_DATE-SYSDATE)
FROM DN_REF_SECURITY
WHERE SECURITY_CODE  IN
 (SELECT SECURITY_CODE  FROM DN_TRN_OUTP_SALE WHERE
 EFF_VALDATE<=SYSDATE) AND MATURITY_DATE < SYSDATE;
 M_MATURITY_DATE  NUMBER;

BEGIN
   OPEN MYCURSOR;
   LOOP
    FETCH MYCURSOR INTO   M_MATURITY_DATE;
    EXIT WHEN MYCURSOR%NOTFOUND;

   END LOOP;
   CLOSE MYCURSOR;

END MATURITY_DATE_CURSOR;

/
