--------------------------------------------------------
--  DDL for Procedure DN_INTEREST_CAPITALIZATION
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_INTEREST_CAPITALIZATION" 
(
M_FROM_DATE                      VARCHAR2,
M_TO_DATE                        VARCHAR2
)
 AS

 M_REPO_LEG2      DN_TRN_REPO_ROLLOVER.LEG2_VALUE%TYPE;
 M_LIMIT          DN_REF_PORTFOLIO.LIMIT%TYPE;
 M_MAX_LIMIT      DN_REF_PORTFOLIO.LIMIT%TYPE;
 M_NO_OF_DAYS     NUMBER;
 M_DURATION       NUMBER;
 M_DATE           DATE;

 BEGIN

  DELETE FROM DN_TEMP_INTEREST_CAPITAL;

  --------------------------------------------------------------------

/*1) GET THE NO OF DAYS*/
SELECT TO_DATE(M_TO_DATE,'DD-MM-YYYY')-TO_DATE(M_FROM_DATE,'DD-MM-YYYY')+1 INTO M_NO_OF_DAYS FROM DUAL;
/*1) END*/

  dbms_output.put_line('START1');
/*2)INSERTING OPENING BAL TO TEMP TABLE */

  INSERT INTO DN_TEMP_INTEREST_CAPITAL
  (PORTFOLIO_CODE,DESCRIPTION,DR,CR,DIFFERENT,DURATION,TRNDATE)
(SELECT PORTFOLIO_CODE,'OPENING BALANCE',SUM(DRTOT),SUM(CRTOT),SUM(TOT),M_NO_OF_DAYS,TO_DATE(M_FROM_DATE,'DD/MM/YYYY')
   FROM(SELECT 1 S,A.PORTFOLIO_CODE,--A.ACC_TYPE_CODE, B.ACC_TYPE_DESC,
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
        NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT,
        SUM(NVL(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT),0))-SUM(NVL(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT),0)) TOT
        FROM DN_ACC_PORTF_INST_ACCOUNT A, DN_ACC_ACCOUNT_TYPE B
        WHERE A.ACC_TYPE_CODE=B.ACC_TYPE_CODE  AND A.TRNAMOUNT<>0 AND
        TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<TO_DATE(M_FROM_DATE,'DD/MM/YYYY') AND
        B.ACC_BS_PL='PL' AND B.ACC_NOTE='IN'
        GROUP BY A.PORTFOLIO_CODE--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC
        UNION ALL
        SELECT 1 S,A.PORTFOLIO_CODE,--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC,
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
        NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT,
        SUM(NVL(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT),0))-SUM(NVL(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT),0)) TOT
        FROM DN_ACC_PORTF_GEN_ACCOUNT A, DN_ACC_ACCOUNT_TYPE B
        WHERE A.ACC_TYPE_CODE=B.ACC_TYPE_CODE  AND A.TRNAMOUNT<>0 AND
        TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<TO_DATE(M_FROM_DATE,'DD/MM/YYYY') AND
        B.ACC_BS_PL='PL' AND B.ACC_NOTE='IN'
        GROUP BY A.PORTFOLIO_CODE--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC
        UNION ALL
        SELECT 2 S,A.PORTFOLIO_CODE,--A.ACC_TYPE_CODE, B.ACC_TYPE_DESC,
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0)*-1 DRTOT,
        NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0)*-1 CRTOT,
        (NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0)-
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0))*-1 TOT
        FROM DN_ACC_PORTF_INST_ACCOUNT A, DN_ACC_ACCOUNT_TYPE B
        WHERE  A.ACC_TYPE_CODE=B.ACC_TYPE_CODE  AND A.TRNAMOUNT<>0 AND
        TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<TO_DATE(M_FROM_DATE,'DD/MM/YYYY') AND
        B.ACC_BS_PL='PL' AND B.ACC_NOTE='EX'
        GROUP BY A.PORTFOLIO_CODE--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC
        UNION ALL
        SELECT 2 S,A.PORTFOLIO_CODE,--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC,
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0)*-1 DRTOT,
        NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0)*-1 CRTOT,
        (NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0)-
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0))*-1 TOT
        FROM DN_ACC_PORTF_GEN_ACCOUNT A, DN_ACC_ACCOUNT_TYPE B
        WHERE A.ACC_TYPE_CODE=B.ACC_TYPE_CODE  AND A.TRNAMOUNT<>0 AND
        TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<TO_DATE(M_FROM_DATE,'DD/MM/YYYY') AND
        B.ACC_BS_PL='PL' AND B.ACC_NOTE='EX'
        GROUP BY A.PORTFOLIO_CODE--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC
        UNION ALL
        SELECT 3 S,A.DN_PORTFOLIO_CODE,
        SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT,0)),
        SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT,0)),
        SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT,0)) -SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT,0))
        FROM DN_ACC_LICENCEE_GEN_ACCOUNT A
        WHERE TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<TO_DATE(M_FROM_DATE,'DD/MM/YYYY') AND
        A.ACC_TYPE_CODE IN('301') AND SUBSTR(DOCREFNO,0,2) IN ('CD','CW','DI','RI')
        GROUP BY A.DN_PORTFOLIO_CODE
        )
    GROUP BY PORTFOLIO_CODE
    HAVING SUM(TOT)>0 );
  COMMIT;

/*2) END */

/*3)CHECK THE BAL FOR EACH DAY*/

  FOR Y IN 0..M_NO_OF_DAYS-1 LOOP
    M_DATE     := TO_DATE(M_FROM_DATE,'DD-MM-YYYY')+Y;
    M_DURATION := M_NO_OF_DAYS-Y;

  INSERT INTO DN_TEMP_INTEREST_CAPITAL
  (PORTFOLIO_CODE,DESCRIPTION,DR,CR,DIFFERENT,DURATION,TRNDATE)
  (SELECT PORTFOLIO_CODE,TO_CHAR(M_DATE,'DD-MM-YYYY'),SUM(DRTOT),SUM(CRTOT),SUM(TOT),M_DURATION,M_DATE
   FROM(SELECT 1 S,A.PORTFOLIO_CODE,--A.ACC_TYPE_CODE, B.ACC_TYPE_DESC,
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
        NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT,
        SUM(NVL(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT),0))-SUM(NVL(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT),0)) TOT
        FROM DN_ACC_PORTF_INST_ACCOUNT A, DN_ACC_ACCOUNT_TYPE B
        WHERE A.ACC_TYPE_CODE=B.ACC_TYPE_CODE  AND A.TRNAMOUNT<>0 AND
        TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')=TO_DATE(TO_CHAR(M_DATE,'DD/MM/YYYY'),'DD/MM/YYYY') AND
        B.ACC_BS_PL='PL' AND B.ACC_NOTE='IN'
        GROUP BY A.PORTFOLIO_CODE--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC
        UNION ALL
        SELECT 1 S,A.PORTFOLIO_CODE,--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC,
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
        NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT,
        SUM(NVL(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT),0))-SUM(NVL(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT),0)) TOT
        FROM DN_ACC_PORTF_GEN_ACCOUNT A, DN_ACC_ACCOUNT_TYPE B
        WHERE A.ACC_TYPE_CODE=B.ACC_TYPE_CODE  AND A.TRNAMOUNT<>0 AND
        TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')=TO_DATE(TO_CHAR(M_DATE,'DD/MM/YYYY'),'DD/MM/YYYY') AND
        B.ACC_BS_PL='PL' AND B.ACC_NOTE='IN'
        GROUP BY A.PORTFOLIO_CODE--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC
        UNION ALL
        SELECT 2 S,A.PORTFOLIO_CODE,--A.ACC_TYPE_CODE, B.ACC_TYPE_DESC,
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0)*-1 DRTOT,
        NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0)*-1 CRTOT,
        (NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0)-
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0))*-1 TOT
        FROM DN_ACC_PORTF_INST_ACCOUNT A, DN_ACC_ACCOUNT_TYPE B
        WHERE  A.ACC_TYPE_CODE=B.ACC_TYPE_CODE  AND A.TRNAMOUNT<>0 AND
        TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')=TO_DATE(TO_CHAR(M_DATE,'DD/MM/YYYY'),'DD/MM/YYYY') AND
        B.ACC_BS_PL='PL' AND B.ACC_NOTE='EX'
        GROUP BY A.PORTFOLIO_CODE--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC
        UNION ALL
        SELECT 2 S,A.PORTFOLIO_CODE,--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC,
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0)*-1 DRTOT,
        NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0)*-1 CRTOT,
        (NVL(SUM(DECODE(DRCR_STATUS,'CR',A.TRNAMOUNT)),0)-
        NVL(SUM(DECODE(DRCR_STATUS,'DR',A.TRNAMOUNT)),0))*-1 TOT
        FROM DN_ACC_PORTF_GEN_ACCOUNT A, DN_ACC_ACCOUNT_TYPE B
        WHERE A.ACC_TYPE_CODE=B.ACC_TYPE_CODE  AND A.TRNAMOUNT<>0 AND
        TO_DATE(TO_CHAR(TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')=TO_DATE(TO_CHAR(M_DATE,'DD/MM/YYYY'),'DD/MM/YYYY') AND
        B.ACC_BS_PL='PL' AND B.ACC_NOTE='EX'
        GROUP BY A.PORTFOLIO_CODE--A.ACC_TYPE_CODE,B.ACC_TYPE_DESC
        UNION ALL
        SELECT 3 S,A.DN_PORTFOLIO_CODE,
        SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT,0)),
        SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT,0)),
        SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT,0)) -SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT,0))
        FROM DN_ACC_LICENCEE_GEN_ACCOUNT A
        WHERE TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')=TO_DATE(TO_CHAR(M_DATE,'DD/MM/YYYY'),'DD/MM/YYYY') AND
        A.ACC_TYPE_CODE IN('301') AND SUBSTR(DOCREFNO,0,2) IN ('CD','CW','DI','RI')
        GROUP BY A.DN_PORTFOLIO_CODE

        )
    GROUP BY PORTFOLIO_CODE );
    COMMIT;
  END LOOP;
 /*3)END*/

 /*4)UPDATING MANAGEMENT_FEE*/
 FOR X IN (SELECT PORTFOLIO_CODE,MANAGEMENT_FEE,PROFIT_SHARING,BASE_RATE
           FROM   DN_REF_PORTFOLIO
           WHERE /*PF_TYPE='P' AND*/ ACTIVE_STATUS='Y') LOOP

    UPDATE DN_TEMP_INTEREST_CAPITAL
    SET    MAN_FEE        = NVL(X.MANAGEMENT_FEE,0)
    WHERE  PORTFOLIO_CODE = X.PORTFOLIO_CODE;
 END LOOP;
 /*4)END*/

 /*5)CALCULATE FEE AMOUNT*/

    UPDATE DN_TEMP_INTEREST_CAPITAL
    SET    FEE_AMOUNT     = DIFFERENT*(NVL(MAN_FEE/100,0)/365)*DURATION;

 /*5)END*/

 END;

