    /* PROCEDURE  - TO SAVE CUSTODIAL FEES INVOICING SCREEN
       SYSTEM     - DEALNET
       CREATED BY - LATHIKA
       CREATED ON - 13-DEC-1999 */

--M_INVOICE_NO:=NULL;

 SELECT
       SYSDATE
   INTO
       M_SDATE
   FROM
       DUAL;

  IF M_INVOICE_NO2 IS NULL THEN
        SELECT
         'CI'||TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_CUST_FEES_INV.NEXTVAL),3,'0')
       INTO
         M_INVOICE_NO
       FROM
         DUAL;
  ELSE
    M_INVOICE_NO:=M_INVOICE_NO2;

  END IF;

IF M_CUS_FEE_REF_NO IS NOT NULL  AND M_SELECT_TYPE='MAIN1' THEN

    UPDATE DN_TRN_BO_CUSTODIAL_FEES
       SET REMARK           =M_REMARK,
           INVOICE_STATUS   ='Y',
           INVOICE_NO       =M_INVOICE_NO,
           INVOICE_DATE     =M_SDATE
      WHERE
           CUS_FEE_REF_NO  =M_CUS_FEE_REF_NO ;

 END IF;

 COMMIT;


END CS_FEES_INVOICING_IN;

