set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_INV_OUTPS_HIS_UPDATION" 
(
 M_PROCESS_DATE    DN_SYS_PARAMETER.LAST_DAILY%TYPE
)

   -- Procedure    : History updation of outright inventory
   -- System       : Dealnet system
   -- Created by   : ITU - D.P. Pubudu Thushara
   -- Created on   : 09/08/1999

  AS

BEGIN

   INSERT INTO DN_HIS_OUTPS_DEAL_SERIAL_NO
     (PORTFOLIO_CODE, EFF_VALDATE,
      INST_TYPE, SECURITY_CODE,
      DEAL_NO, SERIAL_NO,
      DEAL_YIELD, YIELD_WITH_BROKERAGE,
      SCRIP_FACE_VAL, FACE_VAL,
      INITIAL_COST, BROKERAGE,
      PRICE_INT_ACCR, CARR_VAL,
      COUP_INT_PURCH, COUP_INT_ACCR,
      TOT_COUP_INT, FWD_SALE,
      FWD_PURCHASE, LOCATION,
      ALLO_REPO, ALLO_BL,
      FWD_ALLO_REPO, FWD_ALLO_BL,
      SALE_DEAL_NO, SERIAL_NO_STATUS,
      SALE_EFF_VALDATE, RET_DUE_DATE,FACE_VAL_CURR,SCRIP_STATUS--CURRENCY
     )
   SELECT
      PORTFOLIO_CODE, EFF_VALDATE,
      INST_TYPE, SECURITY_CODE,
      DEAL_NO, SERIAL_NO,
      DEAL_YIELD, YIELD_WITH_BROKERAGE,
      SCRIP_FACE_VAL, FACE_VAL,
      INITIAL_COST, BROKERAGE,
      PRICE_INT_ACCR, CARR_VAL,
      COUP_INT_PURCH, COUP_INT_ACCR,
      TOT_COUP_INT, FWD_SALE,
      FWD_PURCHASE, LOCATION,
      ALLO_REPO, ALLO_BL,
      FWD_ALLO_REPO, FWD_ALLO_BL,
      SALE_DEAL_NO, SERIAL_NO_STATUS,
      SALE_EFF_VALDATE, RET_DUE_DATE,FACE_VAL_CURR,SCRIP_STATUS
   FROM
      DN_INV_OUTPS_DEAL_SERIAL_NO
   WHERE
      ((SERIAL_NO_STATUS='SAD' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1)  AND COST_TRANS_STATUS ='Y') OR (SERIAL_NO_STATUS='SND' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1)  AND COST_TRANS_STATUS ='Y') OR (SERIAL_NO_STATUS='SSW' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1)  ) OR SERIAL_NO_STATUS='SWP' OR SERIAL_NO_STATUS='MAT'  OR SERIAL_NO_STATUS='PTA')--SND add SSW add by waruna 27-01-2012--PART ALLOCATIONS ---AND COST_TRANS_STATUS ='Y' ADDED BY AH ON 17-11-05 add --deleayed month 31-01-2012 Waruna
--THE ABOVE CONDITION WAS CHANGED BY SM ON 11-01-2000
--PLEASE NOTE THE CHANGES IN 3 OTHER PLACES BELOW
      AND
      ALLO_REPO=0
      AND
      ALLO_BL=0
      AND
      FWD_ALLO_REPO=0
      AND
      FWD_ALLO_BL=0;


   INSERT INTO DN_HIS_OUTPS_DEAL_SERNO_ALLO
     (PORTFOLIO_CODE, EFF_VALDATE,
      INST_TYPE, SECURITY_CODE,
      DEAL_NO, SERIAL_NO,
      ALLO_TYPE, START_DATE,
      END_DATE, ALLO_FACE_VALUE
     )

   SELECT
      A.PORTFOLIO_CODE, A.EFF_VALDATE,
      A.INST_TYPE, A.SECURITY_CODE,
      A.DEAL_NO, A.SERIAL_NO,
      A.ALLO_TYPE, A.START_DATE,
      A.END_DATE, A.ALLO_FACE_VALUE
   FROM
      DN_INV_OUTPS_DEAL_SERIAL_NO B,
      DN_INV_OUTPS_DEAL_SERNO_ALLO A
   WHERE
      ((SERIAL_NO_STATUS='SAD' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1)  AND COST_TRANS_STATUS ='Y')  OR (SERIAL_NO_STATUS='SND' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1)  AND COST_TRANS_STATUS ='Y') OR (SERIAL_NO_STATUS='SSW' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1)  ) OR SERIAL_NO_STATUS='SWP' OR SERIAL_NO_STATUS='MAT') --SND add SSW add by waruna 27-01-2012 add --deleayed month 31-01-2012 Waruna
--      (B.SERIAL_NO_STATUS='SAD' OR B.SERIAL_NO_STATUS='SWP' OR B.SERIAL_NO_STATUS='MAT')
      AND
      B.ALLO_REPO=0
      AND
      B.ALLO_BL=0
      AND
      B.FWD_ALLO_REPO=0
      AND
      B.FWD_ALLO_BL=0
      AND
      B.PORTFOLIO_CODE=A.PORTFOLIO_CODE
      AND
      B.EFF_VALDATE=A.EFF_VALDATE
      AND
      B.INST_TYPE=A.INST_TYPE
      AND
      B.SECURITY_CODE=A.SECURITY_CODE
      AND
      B.DEAL_NO=A.DEAL_NO
      AND
      B.SERIAL_NO=A.SERIAL_NO;


   DELETE DN_INV_OUTPS_DEAL_SERNO_ALLO A
   WHERE
      A.PORTFOLIO_CODE||A.INST_TYPE||A.SECURITY_CODE||A.PREV_DEAL_NO||A.SERIAL_NO
      IN
      (SELECT
          B.PORTFOLIO_CODE||B.INST_TYPE||B.SECURITY_CODE||B.DEAL_NO||B.SERIAL_NO
       FROM
          DN_INV_OUTPS_DEAL_SERIAL_NO B
       WHERE
      ((SERIAL_NO_STATUS='SAD' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1)  AND COST_TRANS_STATUS ='Y')  OR (SERIAL_NO_STATUS='SND' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1)  AND COST_TRANS_STATUS ='Y') OR (SERIAL_NO_STATUS='SSW' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1)  )OR SERIAL_NO_STATUS='SWP' OR SERIAL_NO_STATUS='MAT') --SND add SSW add by waruna 27-01-2012 add --deleayed month 31-01-2012 Waruna
--        (B.SERIAL_NO_STATUS='SAD' OR B.SERIAL_NO_STATUS='SWP' OR B.SERIAL_NO_STATUS='MAT')
          AND
          B.ALLO_REPO=0
          AND
          B.ALLO_BL=0
          AND
          B.FWD_ALLO_REPO=0
          AND
          B.FWD_ALLO_BL=0);


     DELETE
        DN_INV_OUTPS_DEAL_SERIAL_NO B
     WHERE
      ((SERIAL_NO_STATUS='SAD' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1) AND COST_TRANS_STATUS ='Y')  OR (SERIAL_NO_STATUS='SND' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1) AND COST_TRANS_STATUS ='Y') OR (SERIAL_NO_STATUS='SSW' AND SALE_EFF_VALDATE<=ADD_MONTHS(M_PROCESS_DATE,-1) )OR SERIAL_NO_STATUS='SWP' OR SERIAL_NO_STATUS='MAT') --SND add SSW add by waruna 27-01-2012 --add --deleayed month 31-01-2012 Waruna
--      (B.SERIAL_NO_STATUS='SAD' OR B.SERIAL_NO_STATUS='SWP' OR B.SERIAL_NO_STATUS='MAT')
        AND
        B.ALLO_REPO=0
        AND
        B.ALLO_BL=0
        AND
        B.FWD_ALLO_REPO=0
        AND
        B.FWD_ALLO_BL=0;


END DN_INV_OUTPS_HIS_UPDATION;

