set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_HOLDING_LIST_REPOALLO" 
(
  M_TODATE           IN VARCHAR2,
  M_PORT             IN VARCHAR2,
  M_SCRIPT_STATUS    IN DN_TRN_OUTP_SALE.SCRIPT_STATUS%TYPE

)
IS


CURSOR  HOLDLST IS

 SELECT A.PORTFOLIO_CODE PORTFOLIO_CODE,
        A.INST_TYPE INST_TYPE,
        A.SECURITY_CODE SECURITY_CODE,
        DN_EXT_SECURITY(A.SECURITY_CODE)EXTSEC,
        SUM(A.FACE_VAL)FACE_VAL,
        A.SERIAL_NO SERIAL_NO,
        A.DEAL_NO DEAL_NO
 FROM   DN_INV_REPO_DEAL_SERIAL_NO A
 WHERE  TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.RET_DUE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') > TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND A.PORTFOLIO_CODE=M_PORT
        AND A.SWAP_STATUS<>'Y'
        AND A.SCRIPT_STATUS=M_SCRIPT_STATUS
 GROUP BY A.SECURITY_CODE,A.INST_TYPE,A.PORTFOLIO_CODE,DN_EXT_SECURITY(A.SECURITY_CODE),A.SERIAL_NO,A.DEAL_NO;




M_LEND_PORTFOLIO_CODE  DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE;
M_BORR_PORTFOLIO_CODE  DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE;

MM_DEALNO              DN_TEMP_HOLDING_LIST.DEALNO%TYPE;
MM_COUNT               NUMBER;

BEGIN
--------------------------------------------------------------------
DELETE DN_TEMP_REPO_ALLOCATION
COMMIT;
  FOR I IN  HOLDLST
  LOOP


    SELECT COUNT(*)
    INTO   MM_COUNT
    FROM   DN_INV_REPO_DEAL_SERNO_ALLO
    WHERE  PREV_DEAL_NO=I.DEAL_NO AND
           INST_TYPE=I.INST_TYPE AND
           SECURITY_CODE=I.SECURITY_CODE AND
           SERIAL_NO=I.SERIAL_NO AND
           --TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>=TO_DATE(M_TODATE,'DD-MM-YYYY') ;
           TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>TO_DATE(M_TODATE,'DD-MM-YYYY') ;--COMMENTED AND ADD BY INDITHA 2005-7-11 VC05/003


    IF MM_COUNT>0 THEN
    SELECT DEAL_NO
    INTO   MM_DEALNO
    FROM   DN_INV_REPO_DEAL_SERNO_ALLO
    WHERE  PREV_DEAL_NO=I.DEAL_NO AND
           INST_TYPE=I.INST_TYPE AND
           SECURITY_CODE=I.SECURITY_CODE AND
           SERIAL_NO=I.SERIAL_NO AND
           --TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>=TO_DATE(M_TODATE,'DD-MM-YYYY') AND
           TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>TO_DATE(M_TODATE,'DD-MM-YYYY') AND--COMMENTED AND ADD BY INDITHA 2005-7-11 VC05/003
           ROWNUM=1;

     SELECT  LEND_PORTFOLIO_CODE
     INTO    M_LEND_PORTFOLIO_CODE
     FROM
      (SELECT  LEND_PORTFOLIO_CODE
       FROM    DN_TRN_REPO_FRESH
       WHERE   DEAL_NO =MM_DEALNO
        UNION
       SELECT  LEND_PORTFOLIO_CODE
       FROM    DN_TRN_REPO_ROLLOVER
       WHERE   DEAL_NO =MM_DEALNO
       );

ELSIF MM_COUNT=0 THEN
M_LEND_PORTFOLIO_CODE:='-';
MM_DEALNO:='-';

END IF;

    SELECT  BORR_PORTFOLIO_CODE
     INTO    M_BORR_PORTFOLIO_CODE
     FROM
      (SELECT  BORR_PORTFOLIO_CODE
       FROM    DN_TRN_REPO_FRESH
       WHERE   DEAL_NO =I.DEAL_NO
        UNION
       SELECT  BORR_PORTFOLIO_CODE
       FROM    DN_TRN_REPO_ROLLOVER
       WHERE   DEAL_NO =I.DEAL_NO
       );
   INSERT INTO DN_TEMP_REPO_ALLOCATION
   (EXT_SECCODE,PORTFOLIO_CODE,DEAL_NO,SECURITY_CODE,FACE_VAL,SERIAL_NO,INST_TYPE,ALLO_PARTY,OWN_PARTY,ALLO_DEAL_NO  )
   VALUES
   (I.EXTSEC,I.PORTFOLIO_CODE,I.DEAL_NO,I.SECURITY_CODE,I.FACE_VAL,I.SERIAL_NO,I.INST_TYPE,M_LEND_PORTFOLIO_CODE,M_BORR_PORTFOLIO_CODE,MM_DEALNO  );



   --END IF;

  COMMIT;
  END LOOP;
END;

