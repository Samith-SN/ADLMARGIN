  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_COUPON_RATE" 
(
M_SECURITY_CODE        DN_REF_SECURITY.SECURITY_CODE%TYPE
)
RETURN   DN_REF_SECURITY.COUPON_INT%TYPE
IS
M_COUPON_RATE   DN_REF_SECURITY.COUPON_INT%TYPE;

