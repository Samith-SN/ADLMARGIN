set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_MAP_SAVE" 
   (M_ACC_CODE                         DN_ACC_ACCOUNT_TYPE_MAP.ACC_TYPE_CODE%TYPE,
    M_MP_ACC_CODE                      DN_ACC_ACCOUNT_TYPE_MAP.MAP_ACC_TYPE_CODE%TYPE,
    M_MP_ACC_DIS                       DN_ACC_ACCOUNT_TYPE_MAP.MAP_ACC_TYPE_DESC%TYPE,
    M_USER                             DN_ACC_ACCOUNT_TYPE_MAP.DN_USER%TYPE,
    M_SCR_TYPE                         VARCHAR2,
    M_ACC_DR_CR_STATUS                 DN_ACC_ACCOUNT_TYPE_MAP.ACC_DR_CR_STATUS%TYPE  
    )

AS

BEGIN
   /* PROCEDURE  -  DN_ACC_MAP_SAVE
   SYSTEM     -  PABC
   CREATED BY -  waruna
   CREATED ON -  10/08/2010*/
   
IF M_SCR_TYPE='NEW' THEN

        INSERT INTO DN_ACC_ACCOUNT_TYPE_MAP (ACC_TYPE_CODE,MAP_ACC_TYPE_CODE, MAP_ACC_TYPE_DESC,DN_USER,ACC_DR_CR_STATUS)
        VALUES(M_ACC_CODE,M_MP_ACC_CODE,M_MP_ACC_DIS,M_USER,M_ACC_DR_CR_STATUS);
        
ELSIF M_SCR_TYPE='MOD' THEN
  
        INSERT INTO DN_ACC_ACCOUNT_TYPE_MAP_BK (ACC_TYPE_CODE,MAP_ACC_TYPE_CODE, MAP_ACC_TYPE_DESC,DN_USER,ENT_DATE,ACC_DR_CR_STATUS)
        (SELECT ACC_TYPE_CODE,MAP_ACC_TYPE_CODE, MAP_ACC_TYPE_DESC,DN_USER,ENT_DATE,ACC_DR_CR_STATUS 
        FROM DN_ACC_ACCOUNT_TYPE_MAP WHERE ACC_TYPE_CODE=M_ACC_CODE AND ACC_DR_CR_STATUS=M_ACC_DR_CR_STATUS);
        
        DELETE FROM DN_ACC_ACCOUNT_TYPE_MAP WHERE ACC_TYPE_CODE=M_ACC_CODE AND ACC_DR_CR_STATUS=M_ACC_DR_CR_STATUS;
        
        INSERT INTO DN_ACC_ACCOUNT_TYPE_MAP (ACC_TYPE_CODE,MAP_ACC_TYPE_CODE, MAP_ACC_TYPE_DESC,DN_USER,ACC_DR_CR_STATUS)
        VALUES(M_ACC_CODE,M_MP_ACC_CODE,M_MP_ACC_DIS,M_USER,M_ACC_DR_CR_STATUS);
        
ELSIF M_SCR_TYPE='DEL' THEN

        INSERT INTO DN_ACC_ACCOUNT_TYPE_MAP_BK (ACC_TYPE_CODE,MAP_ACC_TYPE_CODE, MAP_ACC_TYPE_DESC,DN_USER,ENT_DATE,ACC_DR_CR_STATUS)
        (SELECT ACC_TYPE_CODE,MAP_ACC_TYPE_CODE, MAP_ACC_TYPE_DESC,DN_USER,ENT_DATE,ACC_DR_CR_STATUS 
         FROM DN_ACC_ACCOUNT_TYPE_MAP WHERE ACC_TYPE_CODE=M_ACC_CODE AND ACC_DR_CR_STATUS=M_ACC_DR_CR_STATUS);

        DELETE FROM DN_ACC_ACCOUNT_TYPE_MAP WHERE ACC_TYPE_CODE=M_ACC_CODE AND ACC_DR_CR_STATUS=M_ACC_DR_CR_STATUS;
END IF;

END DN_ACC_MAP_SAVE;

