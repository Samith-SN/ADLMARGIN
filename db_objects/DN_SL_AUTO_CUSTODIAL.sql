INTO M_FACE_VALUE,M_SECURITY_CODE
FROM   DN_TRN_OUTP_SALE_SEC
WHERE  DEAL_NO = M_DEAL_NO --AND INV_ISSUE_NO = M_INV_ISSUE_NO
GROUP BY DEAL_NO,SECURITY_CODE;




SELECT distinct BUY_SETTLE_COMMENT||'-'||SELL_SETTLE_COMMENT
INTO   M_COMMENTS
FROM   DN_TRN_OUTP_SALE_SETTLE
WHERE  DEAL_NO = M_DEAL_NO ;


 INSERT INTO DN_TRN_BO_CUSTODIAL_DEAL
    (DEAL_NO,DEAL_TYPE,CUSTODIAL_CODE,CURR_CODE,EFF_VALDATE,EFF_VALDATE_TYPE,FACE_VALUE,INST_TYPE,
    SECURITY_CODE,NO_OF_SETTL_MODES,FEE_AMOUNT,DN_USER,ENT_DATE,INCUSTODY_STATUS,OR_DEAL_NO,COMMENTS)

VALUES(M_CUS_NO,'D',M_BUY_PORTFOLIO_CODE,'SLR',M_EFF_VAL_DATE,'S',M_FACE_VALUE,
            M_INST_TYPE,M_SECURITY_CODE,'1','0',M_USER,SYSDATE,'Y',M_DEAL_NO,M_COMMENTS);
    /*SELECT M_CUS_NO,'D',M_BUY_PORTFOLIO_CODE,'SLR',M_EFF_VAL_DATE,'S',M_FACE_VALUE,
            M_INST_TYPE,M_SECURITY_CODE,'1','0',M_USER,SYSDATE,'Y',M_DEAL_NO,M_COMMENTS
    FROM DN_TRN_OUTP_SALE_SEC
    WHERE DEAL_NO = M_DEAL_NO ;*/


 INSERT INTO DN_TRN_BO_CUSTODIAL_DEAL_SEC
    (DEAL_NO,SECURITY_CODE,SERIAL_NO,FACE_VALUE)
  SELECT M_CUS_NO,SECURITY_CODE,SERIAL_NO,FACE_VALUE
         FROM DN_TRN_OUTP_SALE_SEC
         WHERE DEAL_NO= M_DEAL_NO /*AND INV_ISSUE_NO = M_INV_ISSUE_NO*/;

 DN_INV_CUST_UP_DEAL_SERNO(M_CUS_NO);

END IF;
