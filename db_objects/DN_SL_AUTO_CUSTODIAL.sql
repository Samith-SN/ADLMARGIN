SELECT /*SELL_PORTFOLIO_CODE,*/BUY_PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE
INTO   /*M_SELL_PORTFOLIO_CODE,*/M_BUY_PORTFOLIO_CODE,M_EFF_VAL_DATE,M_INST_TYPE
FROM   DN_TRN_OUTP_SALE
WHERE  DEAL_NO = M_DEAL_NO ;

SELECT PF_TYPE,USER_TYPE
INTO M_PF_TYPE,M_USER_TYPE
FROM DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE = M_BUY_PORTFOLIO_CODE ;

IF SUBSTR(M_DEAL_NO,1,2) = 'OR' AND M_PF_TYPE='C'  THEN--AND M_USER_TYPE<>'W'

  SELECT  'CS'||TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_CUSTODIAL_DEAL.NEXTVAL),3,'0')
  INTO    M_CUS_NO
  FROM    DUAL;

/*SELECT SUM(FACE_VALUE),SECURITY_CODE
