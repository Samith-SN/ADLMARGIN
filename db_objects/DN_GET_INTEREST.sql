  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_INTEREST" 
(
 M_DATE                  VARCHAR2,
 M_PORTFOLIO_CODE        DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE
 )
 RETURN NUMBER
 AS
 M_PF_TYPE          DN_REF_PORTFOLIO.PF_TYPE%TYPE;
 M_MAT_DATE_REPO    DATE;
 M_MAT_DATE_SETE    DATE;
 M_MAT_DATE_SETE1   DATE;
 M_AMOUNT           NUMBER;
 M_INT_AMOUNT       NUMBER;
 M_COUNT            NUMBER;
 M_LEG1_VALUE       NUMBER;

 BEGIN

SELECT MAX(MATURITY_DATE)
INTO   M_MAT_DATE_REPO
FROM
(SELECT MAX(MATURITY_DATE) MATURITY_DATE
FROM   DN_TRN_REPO_FRESH
WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       EFF_VALDATE   < TO_DATE(M_DATE,'DD-MM-YYYY')
UNION ALL
SELECT MAX(MATURITY_DATE) MATURITY_DATE
FROM   DN_TRN_REPO_ROLLOVER
WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       EFF_VALDATE   < TO_DATE(M_DATE,'DD-MM-YYYY')
