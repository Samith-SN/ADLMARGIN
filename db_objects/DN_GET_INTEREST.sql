UNION ALL
SELECT MAX(MATURITY_DATE) MATURITY_DATE
FROM   DN_TRN_REPO_FRESH
WHERE  LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       EFF_VALDATE   < TO_DATE(M_DATE,'DD-MM-YYYY')
UNION ALL
SELECT MAX(MATURITY_DATE) MATURITY_DATE
FROM   DN_TRN_REPO_ROLLOVER
WHERE  LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       APP_STATUS    = 'CONF' AND
       EFF_VALDATE   < TO_DATE(M_DATE,'DD-MM-YYYY')
--------------@@@@@@@@@@@
       );


SELECT MAX(SETTLE_DATE)
INTO   M_MAT_DATE_SETE1
FROM   DN_TRN_REPO_SETTLEMENT
WHERE  PRIOR_DEAL_NO IN (SELECT DEAL_NO
                        FROM   DN_TRN_REPO_FRESH
                        WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                               APP_STATUS    = 'CONF' AND
                               EFF_VALDATE   < TO_DATE(M_DATE,'DD-MM-YYYY')
                        UNION ALL
                        SELECT DEAL_NO
                        FROM   DN_TRN_REPO_ROLLOVER
                        WHERE  BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                               APP_STATUS    = 'CONF' AND
                               EFF_VALDATE   < TO_DATE(M_DATE,'DD-MM-YYYY')
                        ----------@@@@@@@@@@@@@@@@@@@@@@@
                        UNION ALL
                        SELECT DEAL_NO
                        FROM   DN_TRN_REPO_FRESH
                        WHERE  LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                               APP_STATUS    = 'CONF' AND
                               EFF_VALDATE   < TO_DATE(M_DATE,'DD-MM-YYYY')
                        UNION ALL
                        SELECT DEAL_NO
                        FROM   DN_TRN_REPO_ROLLOVER
                        WHERE  LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                               APP_STATUS    = 'CONF' AND
                               EFF_VALDATE   < TO_DATE(M_DATE,'DD-MM-YYYY')
                        ----------@@@@@@@@@@@@@@@@@@@@@@@
                               )  AND
       APP_STATUS    = 'CONF'       ;

       dbms_output.put_line('22Value of M_MAT_DATE_SETE1='||M_MAT_DATE_SETE1);
       dbms_output.put_line('22Value of M_MAT_DATE_REPO='||M_MAT_DATE_REPO);
IF(M_MAT_DATE_SETE1>=M_MAT_DATE_REPO) THEN
    --dbms_output.put_line('Value of M_MAT_DATE_SETE1='||M_MAT_DATE_SETE1);
 IF TO_CHAR(TO_DATE(M_DATE,'DD-MM-YYYY'),'MM') = TO_CHAR(M_MAT_DATE_SETE1,'MM') THEN --ADDED BY SVA ON 03-01-2006
   IF TO_CHAR(M_MAT_DATE_SETE1,'DD') = '01' THEN
      M_MAT_DATE_SETE := ADD_MONTHS(M_MAT_DATE_SETE1,-1);
   ELSE
      M_MAT_DATE_SETE := LAST_DAY(ADD_MONTHS(M_MAT_DATE_SETE1,-1))+1;
   END IF;

 SELECT SUM(INT_AMOUNT)
 INTO   M_INT_AMOUNT
 FROM (
 SELECT INT_AMOUNT
 FROM   DN_TRN_REPO_FRESH A,DN_REF_PORTFOLIO B
 WHERE  BORR_PORTFOLIO_CODE= B.PORTFOLIO_CODE AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') >=  TO_DATE(TO_CHAR(M_MAT_DATE_SETE,'DD-MON-YYYY'),'DD-MON-YYYY') AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <   TO_DATE(M_DATE,'DD-MM-YYYY')  AND
        BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
        APP_STATUS   = 'CONF'
 UNION ALL
 SELECT INT_AMOUNT
 FROM   DN_TRN_REPO_ROLLOVER A,DN_REF_PORTFOLIO B
 WHERE  BORR_PORTFOLIO_CODE= B.PORTFOLIO_CODE AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') >=   TO_DATE(TO_CHAR(M_MAT_DATE_SETE,'DD-MON-YYYY'),'DD-MON-YYYY') AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <    TO_DATE(M_DATE,'DD-MM-YYYY')  AND
        BORR_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       --ON_CALL_DEAL = 'Y' AND
        APP_STATUS   = 'CONF'
-------------------@@@@@@@@@@@@@@@@@@@@@@@@
UNION ALL
SELECT INT_AMOUNT
 FROM   DN_TRN_REPO_FRESH A,DN_REF_PORTFOLIO B
 WHERE  LEND_PORTFOLIO_CODE= B.PORTFOLIO_CODE AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') >=  TO_DATE(TO_CHAR(M_MAT_DATE_SETE,'DD-MON-YYYY'),'DD-MON-YYYY') AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <   TO_DATE(M_DATE,'DD-MM-YYYY')  AND
        LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
        APP_STATUS   = 'CONF'
 UNION ALL
 SELECT INT_AMOUNT
 FROM   DN_TRN_REPO_ROLLOVER A,DN_REF_PORTFOLIO B
 WHERE  LEND_PORTFOLIO_CODE= B.PORTFOLIO_CODE AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') >=   TO_DATE(TO_CHAR(M_MAT_DATE_SETE,'DD-MON-YYYY'),'DD-MON-YYYY') AND
        TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') <    TO_DATE(M_DATE,'DD-MM-YYYY')  AND
        LEND_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
       --ON_CALL_DEAL = 'Y' AND
        APP_STATUS   = 'CONF'

-------------------@@@@@@@@@@@@@@@@@@@@@@@@
        );
