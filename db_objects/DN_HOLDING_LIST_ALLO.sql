  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_HOLDING_LIST_ALLO" 
(
  M_TODATE   IN VARCHAR2,
  M_FROMDATE  IN VARCHAR2
)
IS


CURSOR  HOLDLST IS

 SELECT  DEALNO,SECURITY,SER,INST_TYPE
 FROM    DN_TEMP_HOLDING_LIST;


M_LEND_PORTFOLIO_CODE  DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE;
MM_DEALNO              DN_TEMP_HOLDING_LIST.DEALNO%TYPE;
MM_COUNT               NUMBER;

BEGIN


  FOR I IN  HOLDLST
  LOOP

    SELECT COUNT(*)
    INTO   MM_COUNT
    FROM   DN_INV_OUTPS_DEAL_SERNO_ALLO
    WHERE  PREV_DEAL_NO=I.DEALNO AND
           INST_TYPE=I.INST_TYPE AND
           SECURITY_CODE=I.SECURITY AND
           SERIAL_NO=I.SER AND
         --  TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>=TO_DATE(M_TODATE,'DD-MM-YYYY') ; -- Added by Nilu on 08-11-04 for VCF 04-256
          TO_DATE(TO_CHAR(START_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=TO_DATE(M_FROMDATE,'DD-MM-YYYY') AND
           TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>TO_DATE(M_TODATE,'DD-MM-YYYY');



    IF MM_COUNT>0 THEN
    SELECT DEAL_NO
    INTO   MM_DEALNO
    FROM   DN_INV_OUTPS_DEAL_SERNO_ALLO
    WHERE  PREV_DEAL_NO=I.DEALNO AND
           INST_TYPE=I.INST_TYPE AND
           SECURITY_CODE=I.SECURITY AND
           SERIAL_NO=I.SER AND
          -- TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>=TO_DATE(M_TODATE,'DD-MM-YYYY') AND -- Added by Nilu on 08-11-04 for VCF 04-256
           TO_DATE(TO_CHAR(START_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=TO_DATE(M_FROMDATE,'DD-MM-YYYY') AND
           TO_DATE(TO_CHAR(END_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>TO_DATE(M_TODATE,'DD-MM-YYYY') AND
           ROWNUM=1;


     SELECT  LEND_PORTFOLIO_CODE
     INTO    M_LEND_PORTFOLIO_CODE
     FROM
      (SELECT  LEND_PORTFOLIO_CODE
       FROM    DN_TRN_REPO_FRESH
       WHERE   DEAL_NO =MM_DEALNO
        UNION
       SELECT  LEND_PORTFOLIO_CODE
       FROM    DN_TRN_REPO_ROLLOVER
       WHERE   DEAL_NO =MM_DEALNO
       );

ELSIF MM_COUNT=0 THEN
M_LEND_PORTFOLIO_CODE:='-';
MM_DEALNO:='-';

END IF;






   UPDATE DN_TEMP_HOLDING_LIST
   SET    OTHER_PARTY=M_LEND_PORTFOLIO_CODE,
          ALLO_DEAL_NO=MM_DEALNO
   WHERE  DEALNO=I.DEALNO AND
          INST_TYPE=I.INST_TYPE AND
          SECURITY=I.SECURITY AND
          SER=I.SER ;





  COMMIT;

  END LOOP;
END;

