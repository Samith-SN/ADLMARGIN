  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_ENTERED_USER" 
(
 M_DEAL_NO        DN_TRN_REPO_FRESH.DEAL_NO%TYPE
)
RETURN   DN_TIME_LOG.DN_USER%TYPE
AS

  --CREATED BY  : NIRMALA FERNANDO
  --CREATED ON  : 10-05-2002
  --PURPOSE     : TO RETURN THE DEAL ENTERED USER TO THE REPORTS

M_DN_USER       DN_TIME_LOG.DN_USER%TYPE:='-';

BEGIN

  SELECT NVL(DN_USER,'-')
  INTO   M_DN_USER
  FROM   DN_TIME_LOG
  WHERE  SUS_REF_NO=M_DEAL_NO   AND
         DESCRIPTION='ENTERED';

  RETURN   M_DN_USER;

END RETURN_ENTERED_USER;

/
