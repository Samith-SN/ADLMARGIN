set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_LINK_BO_SETTL_INV" 
   (
   M_SUSPENSE_ENTRY_TYPE     DN_TRN_BO_SETTL_RECEIPT.SUSPENSE_ENTRY_TYPE%TYPE,
   M_PORTFOLIO_CODE          DN_ACC_LICENCEE_GEN_ACCOUNT.PORTFOLIO_CODE%TYPE,
   M_ID_PORTFOLIO_CODE       DN_ACC_LICENCEE_GEN_ACCOUNT.DN_PORTFOLIO_CODE%TYPE,
   M_TRNDATE                 DN_ACC_LICENCEE_GEN_ACCOUNT.TRNDATE%TYPE,
   M_TRNAMOUNT               DN_ACC_LICENCEE_GEN_ACCOUNT.TRNAMOUNT%TYPE,
   M_DOCREFNO                DN_ACC_LICENCEE_GEN_ACCOUNT.DOCREFNO%TYPE,
   M_ACC_SYS_REFNO           DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE
   )

   IS

    -- Procedue     : Link Settlement receipts to the accounting
    -- System       : Dealnet system
    -- Created by   : LATHIKA
    -- Created on   : 13/01/2000
    M_PORT_CODE_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_PORT_CODE_OWNED_BY_MBFSL     DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;
    M_ID_PORT_CODE_PF_TYPE         DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_ID_PORT_CODE_OWNED_BY_MBFSL  DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;

BEGIN

--   RAISE_APPLICATION_ERROR(-20201,'M_SUSPENSE_ENTRY_TYPE   '||M_SUSPENSE_ENTRY_TYPE);

   SELECT
      B.PF_TYPE,
      B.OWNED_BY_MBFSL,
      C.PF_TYPE,
      C.OWNED_BY_MBFSL
      INTO M_PORT_CODE_PF_TYPE,M_PORT_CODE_OWNED_BY_MBFSL,
           M_ID_PORT_CODE_PF_TYPE,M_ID_PORT_CODE_OWNED_BY_MBFSL
   FROM
      DN_REF_PORTFOLIO B,
      DN_REF_PORTFOLIO C
   WHERE
      B.PORTFOLIO_CODE=M_PORTFOLIO_CODE
      AND
      C.PORTFOLIO_CODE=M_ID_PORTFOLIO_CODE;


IF M_SUSPENSE_ENTRY_TYPE='C' THEN

      IF M_ID_PORT_CODE_OWNED_BY_MBFSL='N' THEN --AND   M_ID_PORT_CODE_PF_TYPE<>'P' THEN

        DN_ACC_E_3(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      END IF;


ELSIF M_SUSPENSE_ENTRY_TYPE='M' THEN

      IF M_ID_PORT_CODE_OWNED_BY_MBFSL='N' THEN --AND   M_ID_PORT_CODE_PF_TYPE<>'P' THEN

         DN_ACC_E_6(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
      END IF;

 END IF;

END DN_ACC_LINK_BO_SETTL_INV;

