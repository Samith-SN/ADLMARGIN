--------------------------------------------------------
--  DDL for Procedure DN_TRANAMOUNT_ZERO_DEL
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_TRANAMOUNT_ZERO_DEL" 
(
   M_PROCESS_DATE                     DN_SYS_PARAMETER.LAST_DAILY%TYPE

 )
AS


---  CREATED TO DELETE TRANAMOUNT=0 RECORDS FROM  DN_ACC_LICENCEE_GEN_ACCOUNT
---- AND DN_ACC_LICENCEE_INST_ACCOUNT
---- TO INCREASE EFFICENCY OF TRIAL BALANCE

BEGIN
--RAISE_APPLICATION_ERROR(-20201,M_PROCESS_DATE);
DELETE  DN_ACC_LICENCEE_GEN_ACCOUNT
WHERE TO_DATE(TO_CHAR(TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(TO_CHAR(M_PROCESS_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')
AND TRNAMOUNT = 0;

DELETE  DN_ACC_LICENCEE_INST_ACCOUNT
WHERE TO_DATE(TO_CHAR(TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(TO_CHAR(M_PROCESS_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')
AND TRNAMOUNT = 0;

--COMMIT;
END DN_TRANAMOUNT_ZERO_DEL;

/
