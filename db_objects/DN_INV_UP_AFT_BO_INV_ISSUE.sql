--  DDL for Procedure DN_INV_UP_AFT_BO_INV_ISSUE
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_INV_UP_AFT_BO_INV_ISSUE" 
   (
    M_DEAL_NO                 DN_TRN_BO_INV_ISSUE.DEAL_NO%TYPE,
    M_INST_TYPE               DN_TRN_BO_INV_ISSUE.INST_TYPE%TYPE,
    M_SECURITY_CODE           DN_TRN_BO_INV_ISSUE.SECURITY_CODE%TYPE,
    M_SERIAL_NO               DN_TRN_BO_INV_ISSUE.SERIAL_NO%TYPE,
    M_FACE_VALUE              DN_TRN_BO_INV_ISSUE.FACE_VALUE%TYPE,
    M_INV_CODE                DN_TRN_BO_INV_ISSUE.INV_CODE%TYPE,
    M_ISSUER                  DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE,
    M_CURR_CODE               DN_REF_EXCHANGE_RATES.CURR_CODE%TYPE--,--CURRENCY
   )

   IS

    -- Procedue     : Update inventory after bo inv. issues
    -- System       : Dealnet system
    -- Created by   : D.P. Pubudu Thushara
    -- Created on   : 14/07/1999
    -- Modified on  : 01/09/1999

  M_COUNT                   NUMBER;
  M_LEND_PORTFOLIO_CODE     DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE;
  M_BORR_PORTFOLIO_CODE     DN_TRN_REPO_FRESH.BORR_PORTFOLIO_CODE%TYPE;
  M_LOCATION                DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE;
  MN_COUNT1                 NUMBER;--CURRENCY
--  M_CURR_CODE               DN_REF_EXCHANGE_RATES.CURR_CODE%TYPE;--CURRENCY
  M_CURRENCY_VALUE          DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE;--CURRENCY
BEGIN

IF SUBSTR(M_DEAL_NO,1,2)='BF' THEN

   SELECT
      DECODE(LEND_PORTFOLIO_CODE,M_ISSUER,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE)
      INTO M_LOCATION
   FROM
      DN_TRN_BL_FUND
   WHERE
      DEAL_NO=M_DEAL_NO;

     -- Allways from the FO

     UPDATE DN_TRN_BL_FUND_SERIAL_NO
        SET LOCATION=M_LOCATION
     WHERE
        DEAL_NO=M_DEAL_NO
        AND
        INST_TYPE=M_INST_TYPE
        AND
        SECURITY_CODE=M_SECURITY_CODE
        AND
        SERIAL_NO=M_SERIAL_NO;

  DN_INV_BL_RF_DEAL_SERNO_BOI(M_DEAL_NO,M_INST_TYPE,M_SECURITY_CODE,M_SERIAL_NO,M_FACE_VALUE,M_INV_CODE,M_LOCATION);


ELSIF SUBSTR(M_DEAL_NO,1,2)='BS' THEN

   SELECT
      DECODE(LEND_PORTFOLIO_CODE,M_ISSUER,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE)
      INTO M_LOCATION
   FROM
      DN_TRN_BL_SECURITY
   WHERE
      DEAL_NO=M_DEAL_NO;

     -- Allways from the FO

     UPDATE DN_TRN_BL_SECURITY_SERIAL_NO
        SET LOCATION=M_LOCATION
     WHERE
        DEAL_NO=M_DEAL_NO
        AND
        INST_TYPE=M_INST_TYPE
        AND
        SECURITY_CODE=M_SECURITY_CODE
        AND
        SERIAL_NO=M_SERIAL_NO;

     DN_INV_BL_SEC_DEAL_SERNO_BOI(M_DEAL_NO,M_INST_TYPE,M_SECURITY_CODE,M_SERIAL_NO,M_FACE_VALUE,M_INV_CODE,M_LOCATION);

ELSIF SUBSTR(M_DEAL_NO,1,2)='OR' THEN
--------------CURRENCY----------------------------------------
     SELECT COUNT(*)
     INTO   MN_COUNT1
     FROM   DN_TRN_DEAL_CURRENCY
     WHERE  DEAL_NO=M_DEAL_NO;

IF(MN_COUNT1>0)THEN--CURRENCY
       SELECT   CURRENCY_VALUE
       INTO     M_CURRENCY_VALUE
       FROM     DN_REF_EXCHANGE_RATES
       WHERE    CURR_CODE=M_CURR_CODE;

    SELECT
      COUNT(*) INTO M_COUNT
   FROM
      DN_TRN_OUTP_SALE_SEC
   WHERE
      DEAL_NO=M_DEAL_NO
      AND
      SECURITY_CODE=M_SECURITY_CODE
      AND
      SERIAL_NO=M_SERIAL_NO;

  IF M_COUNT=0 THEN

       INSERT INTO DN_TRN_OUTP_SALE_SEC
         (DEAL_NO,
          SECURITY_CODE,
          SERIAL_NO,
          FACE_VALUE,
          DATA_FROM,
          FACE_VALUE_CURR--CURRENCY
         )
        VALUES
         (M_DEAL_NO,
          M_SECURITY_CODE,
          M_SERIAL_NO,
          M_FACE_VALUE*M_CURRENCY_VALUE,--CURRENCY
          'BOI',
          M_FACE_VALUE--CURRENCY
         );

     END IF;


ELSE--CURRENCY

   SELECT
      COUNT(*) INTO M_COUNT
   FROM
      DN_TRN_OUTP_SALE_SEC
   WHERE
      DEAL_NO=M_DEAL_NO
      AND
      SECURITY_CODE=M_SECURITY_CODE
      AND
      SERIAL_NO=M_SERIAL_NO;

  IF M_COUNT=0 THEN

       INSERT INTO DN_TRN_OUTP_SALE_SEC
         (DEAL_NO,
          SECURITY_CODE,
          SERIAL_NO,
          FACE_VALUE,
          DATA_FROM
         )
        VALUES
         (M_DEAL_NO,
          M_SECURITY_CODE,
          M_SERIAL_NO,
          M_FACE_VALUE,
          'BOI'
         );

     END IF;
     END IF;--CURRENCY
     DN_INV_OUTPS_UP_DEAL_SERNO_BOI(M_DEAL_NO,M_INST_TYPE,M_SECURITY_CODE,M_SERIAL_NO,M_FACE_VALUE,M_CURR_CODE);--CURRENCY

ELSIF SUBSTR(M_DEAL_NO,1,2)='RF' THEN
   SELECT
      DECODE(LEND_PORTFOLIO_CODE,M_ISSUER,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE)
      INTO M_LOCATION
   FROM
      DN_TRN_REPO_FRESH
   WHERE
      DEAL_NO=M_DEAL_NO;

     -- Allways from the FO

     UPDATE DN_TRN_REPO_FRESH_SERIAL_NO
        SET LOCATION=M_LOCATION
     WHERE
        DEAL_NO=M_DEAL_NO
        AND
        INST_TYPE=M_INST_TYPE
        AND
        SECURITY_CODE=M_SECURITY_CODE
        AND
        SERIAL_NO=M_SERIAL_NO;

        DN_INV_REPO_RF_DEAL_SERNO_BOI(M_DEAL_NO,M_INST_TYPE,M_SECURITY_CODE,M_SERIAL_NO,M_FACE_VALUE,M_INV_CODE,M_LOCATION);


ELSIF SUBSTR(M_DEAL_NO,1,2)='RP' THEN

   M_COUNT:=0;

ELSIF SUBSTR(M_DEAL_NO,1,2)='RR' THEN

   SELECT
      DECODE(LEND_PORTFOLIO_CODE,M_ISSUER,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE)
      INTO M_LOCATION
   FROM
      DN_TRN_REPO_ROLLOVER
   WHERE
      DEAL_NO=M_DEAL_NO;

     -- Allways from the FO

     UPDATE DN_TRN_REPO_ROLLOVER_SERIAL_NO
        SET LOCATION=M_LOCATION
     WHERE
        DEAL_NO=M_DEAL_NO
        AND
        INST_TYPE=M_INST_TYPE
        AND
        INV_CODE=M_INV_CODE
        AND
        SECURITY_CODE=M_SECURITY_CODE
        AND
        SERIAL_NO=M_SERIAL_NO;

       DN_INV_REPO_RR_DEAL_SERNO_BOI(M_DEAL_NO,M_INST_TYPE,M_SECURITY_CODE,M_SERIAL_NO,M_FACE_VALUE,M_INV_CODE,M_LOCATION);

ELSIF SUBSTR(M_DEAL_NO,1,2)='RS' THEN

      DN_INV_REPO_RS_DEAL_SERNO_BOI(M_DEAL_NO,M_INST_TYPE,M_SECURITY_CODE,M_SERIAL_NO,M_FACE_VALUE,M_INV_CODE,M_ISSUER);

ELSIF SUBSTR(M_DEAL_NO,1,2)='SO' THEN

   M_COUNT:=0;

ELSIF SUBSTR(M_DEAL_NO,1,2)='SR' THEN

   M_COUNT:=0;

END IF;

END DN_INV_UP_AFT_BO_INV_ISSUE;

