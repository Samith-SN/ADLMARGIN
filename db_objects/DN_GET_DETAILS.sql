  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_DETAILS" 
(
M_PAYMENT_NO            DN_TRN_BO_SETTL_PAYMENT.PAYMENT_NO%TYPE,
M_SUS_REF_NO              DN_TRN_BO_SETTL_PAYMENT.SUS_REF_NO%TYPE,
M_PORTFOLIO_CODE         DN_TRN_BO_SETTL_PAYMENT.PORTFOLIO_CODE%TYPE,
M_EFF_VALDATE         VARCHAR2,
M_VAL                VARCHAR2,
M_MARFAC_TYPE        VARCHAR2   -- ADDED BY YOHAN ON 27-04-2006 FOR SR 0604-068
)RETURN VARCHAR
AS

M_RETURN VARCHAR2(400);
M_COUNT1 NUMBER;
M_DN_PORTFOLIO_CODE  DN_TRN_BO_SETTL_PAYMENT_BULK.PORTFOLIO_CODE%TYPE;

BEGIN

--RAISE_APPLICATION_ERROR(-20201,'M_EFF_VALDATE=' || M_EFF_VALDATE );


SELECT COUNT(PAYMENT_NO)
INTO   M_COUNT1
FROM DN_TRN_BO_SETTL_PAYMENT_BULK
WHERE PAYMENT_NO=M_PAYMENT_NO;


IF M_COUNT1 =0 THEN
 SELECT  OTH_COMMENT
 INTO M_RETURN
 FROM DN_TRN_BO_SETTL_PAYMENT
 WHERE PAYMENT_NO=M_PAYMENT_NO;

ELSE

SELECT PORTFOLIO_CODE
INTO   M_DN_PORTFOLIO_CODE
FROM DN_TRN_BO_SETTL_PAYMENT_BULK
WHERE PAYMENT_NO=M_PAYMENT_NO;

--SELECT 'Client -: '||nvl(RETURN_PF_NAME(PORTFOLIO_CODE),'-')||' / Margin Factor ' || M_MARFAC_TYPE || ' -: '||nvl(TO_CHAR(DN_GET_MARGIN_FACTOR_T(PORTFOLIO_CODE,TO_DATE(M_EFF_VALDATE,'DD-MM-YYYY'),'0',DECODE(M_MARFAC_TYPE,'(T-3)',3,'(T-1)',1,0)),'FM999G999G999G999G999G999G999G999D00'),'0')  /*MODIFIED DN_GET_MARGIN_FACTOR TO DN_GET_MARGIN_FACTOR_T  BY YOHAN ON 27-04-2006 FOR SR 0604-068*/ --COMMENTED BY UMESHA ON THE 04.05.2006
SELECT 'Client -: '||nvl(RETURN_PF_NAME(PORTFOLIO_CODE),'-')||' / Margin Factor (T-1) -: '||NVL(TO_CHAR(DN_GET_MARGIN_FACTOR(M_DN_PORTFOLIO_CODE,TO_CHAR(TO_DATE(M_EFF_VALDATE,'DD/MM/YY'),'DD/MM/YYYY'),'0'),'FM999G999G999G999G999G999G999G999D00'),'0') || ' Margin Factor (T-3) -: '||NVL(TO_CHAR(DN_GET_MARGIN_FACTORT3(M_DN_PORTFOLIO_CODE,TO_CHAR(TO_DATE(M_EFF_VALDATE,'DD/MM/YY'),'DD/MM/YYYY'),'0'),'FM999G999G999G999G999G999G999G999D00'),'0')
INTO M_RETURN
FROM DN_TRN_BO_SETTL_PAYMENT_BULK
WHERE PAYMENT_NO= M_PAYMENT_NO  ;

END IF;


RETURN M_RETURN;

END;

