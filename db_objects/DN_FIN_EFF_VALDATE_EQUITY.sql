--------------------------------------------------------
--  DDL for Function DN_FIN_EFF_VALDATE_EQUITY
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_FIN_EFF_VALDATE_EQUITY" 
   (
    M_DEAL_NO       DN_TRN_OUTP_SALE.DEAL_NO%TYPE,
    M_PORT_CODE     DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE

   ) RETURN  DATE


    IS


M_EFF_VALDATE     DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE;
CNT1   NUMBER DEFAULT 0;
CNT2   NUMBER DEFAULT 0;
CNT11   NUMBER DEFAULT 0;
CNT12   NUMBER DEFAULT 0;
DEALTYPE      DN_REF_INSTRUMENT.INST_CAT%TYPE;

BEGIN



  SELECT B.INST_CAT INTO  DEALTYPE FROM
  DN_TRN_OUTP_SALE A,
  DN_REF_INSTRUMENT B
  WHERE  A.DEAL_NO=M_DEAL_NO  AND A.INST_TYPE=B.INST_TYPE ;
  dbms_output.put_line('DEALTYPE '||DEALTYPE);
IF DEALTYPE = 'EQUITY' THEN


SELECT COUNT(BUY_PORTFOLIO_CODE) INTO CNT1 FROM   DN_TRN_OUTP_SALE
WHERE DEAL_NO=M_DEAL_NO AND  BUY_PORTFOLIO_CODE= M_PORT_CODE ;

SELECT COUNT(SELL_PORTFOLIO_CODE) INTO CNT2 FROM   DN_TRN_OUTP_SALE
WHERE DEAL_NO=M_DEAL_NO AND SELL_PORTFOLIO_CODE= M_PORT_CODE ;


IF CNT1 = 1 THEN


 SELECT COUNT(*) INTO CNT11 FROM DN_TRN_OUTP_SALE_SETTLE_EQUITY WHERE DEAL_NO=M_DEAL_NO;

 IF CNT11 > 0 THEN

  SELECT BUY_SETLE_DATE INTO M_EFF_VALDATE FROM DN_TRN_OUTP_SALE_SETTLE_EQUITY WHERE DEAL_NO=M_DEAL_NO;

  ELSE

  SELECT SYSDATE INTO M_EFF_VALDATE FROM DUAL;


  END IF;



ELSIF CNT2 = 1 THEN

 SELECT COUNT(*) INTO CNT12 FROM DN_TRN_OUTP_SALE_SETTLE_EQUITY WHERE DEAL_NO=M_DEAL_NO;

 IF CNT12 > 0 THEN
  SELECT SELL_SETLE_DATE INTO M_EFF_VALDATE FROM DN_TRN_OUTP_SALE_SETTLE_EQUITY WHERE DEAL_NO=M_DEAL_NO;

 ELSE

  SELECT SYSDATE INTO M_EFF_VALDATE FROM DUAL;

 END IF;

END IF;


ELSE

 SELECT          B.EFF_VALDATE INTO M_EFF_VALDATE
                    FROM DN_ACC_SUS_RECEIPT A,
                    DN_TRN_OUTP_SALE B
                    WHERE A.SUS_REF_NO = M_DEAL_NO AND A.SUSPENSE_ENTRY_TYPE='D' AND
                    A.BAL_TO_BE_RECEIVED>'0' AND
                    A.SUS_REF_NO=B.DEAL_NO ;




END IF;




RETURN M_EFF_VALDATE;

END DN_FIN_EFF_VALDATE_EQUITY;

