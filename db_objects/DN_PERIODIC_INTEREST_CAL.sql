set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_PERIODIC_INTEREST_CAL" 
   (
    M_DEAL_NO             DN_TRN_REPO_FRESH.DEAL_NO%TYPE,
    M_LEG1_VALUE          DN_TRN_REPO_FRESH.LEG1_VALUE%TYPE,
    M_YIELD               DN_TRN_REPO_FRESH.YIELD%TYPE,
    M_EFF_VALDATE         DN_TRN_REPO_FRESH.EFF_VALDATE%TYPE,
    M_INT_RATE_BASE_CODE  DN_TRN_REPO_FRESH.INT_RATE_BASE_CODE%TYPE,
    M_MATURITY_DATE       DN_TRN_REPO_FRESH.MATURITY_DATE%TYPE,
    M_MONTHS              NUMBER
   )

   IS

    -- Procedue     : Periodic Interest payment
    -- System       : Dealnet system
    -- Created by   : V.Thilakesan.
    -- Created on   : 04/02/2000

   M_INT_DATE      DN_REF_SECURITY.MATURITY_DATE%TYPE;
   M_INT_DATE1     DN_REF_SECURITY.MATURITY_DATE%TYPE;
   M_INT_CAL_DAYS  NUMBER;
   M_INT_BASE_DAYS NUMBER;
   M_COUNT         NUMBER;
   M_COUNT1         NUMBER;
   M_LEG2_VALUE    NUMBER;

BEGIN

  DELETE TEST_DN_PERIODIC_INTERST
  WHERE DEAL_NO=M_DEAL_NO;

  COMMIT;

  SELECT
      TO_NUMBER(DENOMINATOR) INTO M_INT_BASE_DAYS
  FROM
      DN_REF_INTR_BASE
  WHERE
      INT_RATE_BASE_CODE=M_INT_RATE_BASE_CODE;

  M_INT_DATE:=M_EFF_VALDATE;
  M_COUNT:=0;

  WHILE M_INT_DATE<M_MATURITY_DATE LOOP
        M_INT_DATE1:=M_INT_DATE;
        M_COUNT:=ROUND(((ADD_MONTHS(M_INT_DATE1,M_MONTHS)-M_INT_DATE)/30),2);
        IF M_COUNT>=M_MONTHS AND ADD_MONTHS(M_INT_DATE1,M_MONTHS)<M_MATURITY_DATE THEN
           SELECT
              ADD_MONTHS(M_INT_DATE1,M_MONTHS)-M_INT_DATE
              INTO M_INT_CAL_DAYS
           FROM DUAL;
           --leg 2 value
           SELECT
               ROUND((((M_LEG1_VALUE*M_YIELD)/M_INT_BASE_DAYS)*M_INT_CAL_DAYS),2)
               INTO M_LEG2_VALUE
           FROM DUAL;

           INSERT INTO TEST_DN_PERIODIC_INTERST
           (DEAL_NO,PERIOD1,PERIOD2,INTERST,DAYS)
            VALUES(M_DEAL_NO,M_INT_DATE,ADD_MONTHS(M_INT_DATE1,M_MONTHS),M_LEG2_VALUE,M_INT_CAL_DAYS);

            M_COUNT1:=ROUND(((ADD_MONTHS(M_INT_DATE1,M_MONTHS)-M_INT_DATE)/30),2);
            IF M_COUNT1>=M_MONTHS AND ADD_MONTHS(M_INT_DATE1,M_MONTHS)<M_MATURITY_DATE THEN
               SELECT ADD_MONTHS(M_INT_DATE1,M_MONTHS) INTO M_INT_DATE FROM DUAL;
            ELSE
               SELECT M_INT_DATE1 INTO M_INT_DATE FROM DUAL;
            END IF;
      ELSE
           SELECT
              M_MATURITY_DATE-M_INT_DATE
              INTO M_INT_CAL_DAYS
           FROM DUAL;
           --leg 2 value
           SELECT
               ROUND((((M_LEG1_VALUE*M_YIELD)/M_INT_BASE_DAYS)*M_INT_CAL_DAYS),2)
               INTO M_LEG2_VALUE
           FROM DUAL;

           INSERT INTO TEST_DN_PERIODIC_INTERST
           (DEAL_NO,PERIOD1,PERIOD2,INTERST,DAYS)
           VALUES(M_DEAL_NO,M_INT_DATE,M_MATURITY_DATE,M_LEG2_VALUE,M_INT_CAL_DAYS);

           SELECT ADD_MONTHS(M_MATURITY_DATE,M_MONTHS) INTO M_INT_DATE FROM DUAL;

        END IF;
        COMMIT;
 END LOOP;

END DN_PERIODIC_INTEREST_CAL;

