set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_RATE_CHANGE_ROUTINES" 
   (M_DAILY       CHAR,
    M_USERNAME   VARCHAR2
   )
AS

----------------------------------------------------------------------
    --   PROCEDURE  - TO SAVE DAILY ROUTINE DETAILS
    --   SYSTEM     - Dealnet
    --   CREATED BY - Charminda Bandara.
    --   CREATED ON - 03.12.1999
----------------------------------------------------------------------
M_LAST_DAILY       DN_SYS_PARAMETER.LAST_DAILY%TYPE;
M_LAST_DAY       DN_SYS_PARAMETER.LAST_DAILY%TYPE;
M_LAST_MONTH       DN_SYS_PARAMETER.LAST_DAILY%TYPE;

BEGIN
--SELECT TO_DATE(M_DAILY,'DD-MM-YYYY') INTO M_LAST_DAILY FROM DUAL;

FOR X IN (SELECT INST_TYPE,BASE_INTEREST_RATE*100 BASE_INTEREST_RATE
           FROM DN_REF_INSTRUMENT_RATES
           WHERE TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(M_DAILY,'DD-MM-YYYY')+1
             AND ACTIVE_STATUS='Y') LOOP

       UPDATE DN_REF_INSTRUMENT
       SET    BASE_INTEREST_RATE = X.BASE_INTEREST_RATE
       WHERE  INST_TYPE = X.INST_TYPE;

       UPDATE DN_SYS_PARAMETER_RATECHANGE
       SET    LAST_DAILY=TO_DATE(M_DAILY,'DD-MM-YYYY')+1;
END LOOP;

UPDATE DN_REF_INSTRUMENT_RATES
SET    ACTIVE_STATUS='P'
WHERE  TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(M_DAILY,'DD-MM-YYYY')+1
 AND   ACTIVE_STATUS='Y';

FOR X IN (SELECT PORTFOLIO_CODE,BASE_INTEREST_RATE
           FROM DN_REF_PORTFOLIO_RATES
         --  WHERE TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')= TO_DATE(M_DAILY,'DD-MM-YYYY')+1-- change by waruna 2012-05-24
           WHERE TRUNC(EFF_VALDATE,'DD')=TO_DATE(M_DAILY,'DD-MM-YYYY')
          
             AND ACTIVE_STATUS='Y') LOOP
dbms_output.put_line('Value of X.PORTFOLIO_CODE='||X.PORTFOLIO_CODE);
       UPDATE DN_REF_PORTFOLIO
       SET    RATE = X.BASE_INTEREST_RATE
       WHERE  PORTFOLIO_CODE = X.PORTFOLIO_CODE;

--RAISE_APPLICATION_ERROR(-20201,'X.PORTFOLIO_CODE**********'||X.PORTFOLIO_CODE ); 
   DN_AUTO_ROLLOVER_RATECHANGE (M_DAILY,X.BASE_INTEREST_RATE , 0,  M_USERNAME,X.PORTFOLIO_CODE );--add by waruna 2012-05-24


       UPDATE DN_SYS_PARAMETER_RATECHANGE
       SET    LAST_DAILY=TO_DATE(M_DAILY,'DD-MM-YYYY');--REMOVE +1 BY WARUNA 2012-06-01
       
       
       
END LOOP;

UPDATE DN_REF_PORTFOLIO_RATES
SET    ACTIVE_STATUS='P'
WHERE  TRUNC(EFF_VALDATE,'DD') = TO_DATE(M_DAILY,'DD-MM-YYYY') --REMOVE +1 BY WARUNA 2012-06-01
 AND   ACTIVE_STATUS='Y';




END ; 

/
