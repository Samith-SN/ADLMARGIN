--  DDL for Function GET_SETTL_PRIO_DEAL_MAT_DATE
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."GET_SETTL_PRIO_DEAL_MAT_DATE" 
(
M_DEAL_NO     DN_TRN_REPO_SETTLEMENT.PRIOR_DEAL_NO%TYPE


)


RETURN DATE
IS

M_MATURITY_DATE    DATE;


BEGIN


SELECT MATURITY_DATE INTO M_MATURITY_DATE  FROM 
(SELECT * FROM (
SELECT DEAL_NO,MATURITY_DATE FROM DN_TRN_REPO_FRESH
UNION ALL
SELECT DEAL_NO,MATURITY_DATE FROM DN_TRN_REPO_ROLLOVER )) AA,

(SELECT PRIOR_DEAL_NO  
FROM DN_TRN_REPO_SETTLEMENT A
WHERE DEAL_NO=M_DEAL_NO) 
 BB  WHERE AA.DEAL_NO =BB.PRIOR_DEAL_NO 
 AND ROWNUM =1;
 
RETURN M_MATURITY_DATE ;

END; 

