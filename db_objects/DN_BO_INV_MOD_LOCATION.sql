set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_BO_INV_MOD_LOCATION" 
   (
    M_INV_MOD_LOC_NO      DN_TRN_BO_INV_MODIFY_LOCATION.INV_MOD_LOC_NO%TYPE
   )

   IS

    -- Procedue     : Update new location in the inventory
    -- System       : Dealnet system
    -- Created by   : D.P. Pubudu Thushara
    -- Created on   : 09/09/1999

   M_PORTFOLIO_CODE    DN_TRN_BO_INV_MODIFY_LOCATION.PORTFOLIO_CODE%TYPE;
   M_INST_TYPE         DN_TRN_BO_INV_MODIFY_LOCATION.INST_TYPE%TYPE;
   M_SECURITY_CODE     DN_TRN_BO_INV_MODIFY_LOCATION.SECURITY_CODE%TYPE;
   M_SERIAL_NO         DN_TRN_BO_INV_MODIFY_LOCATION.SERIAL_NO%TYPE;
   M_INV_CODE          DN_TRN_BO_INV_MODIFY_LOCATION.INV_CODE%TYPE;
   M_NEW_LOCATION      DN_TRN_BO_INV_MODIFY_LOCATION.NEW_LOCATION%TYPE;

BEGIN

   SELECT
      PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,
      SERIAL_NO,NEW_LOCATION,INV_CODE
      INTO
         M_PORTFOLIO_CODE,M_INST_TYPE,M_SECURITY_CODE,
         M_SERIAL_NO,M_NEW_LOCATION,M_INV_CODE
   FROM
      DN_TRN_BO_INV_MODIFY_LOCATION
   WHERE
      INV_MOD_LOC_NO=M_INV_MOD_LOC_NO  ;

   IF M_INV_CODE='OR' THEN

      UPDATE DN_INV_OUTPS_DEAL_SERIAL_NO
      SET LOCATION=M_NEW_LOCATION
      WHERE
         PORTFOLIO_CODE=M_PORTFOLIO_CODE
         AND
         INST_TYPE=M_INST_TYPE
         AND
         SECURITY_CODE=M_SECURITY_CODE
         AND
         SERIAL_NO=M_SERIAL_NO;

   ELSIF  M_INV_CODE='RP' THEN

      UPDATE DN_INV_REPO_DEAL_SERIAL_NO
      SET LOCATION=M_NEW_LOCATION
      WHERE
         PORTFOLIO_CODE=M_PORTFOLIO_CODE
         AND
         INST_TYPE=M_INST_TYPE
         AND
         SECURITY_CODE=M_SECURITY_CODE
         AND
         SERIAL_NO=M_SERIAL_NO;

   ELSIF M_INV_CODE='BL' THEN

      UPDATE DN_INV_BL_DEAL_SERIAL_NO
      SET LOCATION=M_NEW_LOCATION
      WHERE
         PORTFOLIO_CODE=M_PORTFOLIO_CODE
         AND
         INST_TYPE=M_INST_TYPE
         AND
         SECURITY_CODE=M_SECURITY_CODE
         AND
         SERIAL_NO=M_SERIAL_NO;

   END IF;


END DN_BO_INV_MOD_LOCATION;

