  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_F_2_1" 
(
M_INVOICE_NO        DN_TRN_BROKERAGE.INVOICE_NO%TYPE,
M_DOCREFNO          DN_TRN_BROKERAGE.DEAL_NO%TYPE,
M_PORTF_CODE        DN_TRN_BROKERAGE.BROK_CODE%TYPE,
M_DN_PORTF_CODE     DN_TRN_BROKERAGE.CP_CODE%TYPE,
M_TRNAMOUNT         DN_TRN_BROKERAGE.BROK_FEE_AMOUNT%TYPE,
