   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_DN_PORTF_CODE,M_PORTF_CODE,M_TRNDATE2,'301','CR',M_TRNAMOUNT2,M_DOCREFNO,'RECEIPT OF GST-BROK FROM PORT','800');

END IF;

END DN_ACC_F_2_1;

