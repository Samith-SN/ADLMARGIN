M_TRNDATE         DN_TRN_BL_FUND.eff_valdate%TYPE;
M_TRNDATE2        DN_TRN_BL_FUND.eff_valdate%TYPE;

BEGIN

IF SUBSTR(M_DOCREFNO,1,2)='BF' THEN
    SELECT EFF_VALDATE
    INTO M_TRNDATE
    FROM DN_TRN_BL_FUND
    WHERE DEAL_NO=M_DOCREFNO;

ELSIF SUBSTR(M_DOCREFNO,1,2)='BS' THEN
    SELECT EFF_VALDATE
    INTO M_TRNDATE
    FROM DN_TRN_BL_SECURITY
    WHERE DEAL_NO=M_DOCREFNO;

ELSIF SUBSTR(M_DOCREFNO,1,2)='OR' THEN
    SELECT EFF_VALDATE
    INTO M_TRNDATE
    FROM DN_TRN_OUTP_SALE
    WHERE DEAL_NO=M_DOCREFNO;

ELSIF SUBSTR(M_DOCREFNO,1,2)='RF' THEN
    SELECT EFF_VALDATE
    INTO M_TRNDATE
    FROM DN_TRN_REPO_FRESH
    WHERE DEAL_NO=M_DOCREFNO;

ELSIF SUBSTR(M_DOCREFNO,1,2)='RP' THEN
    SELECT EFF_VALDATE
    INTO M_TRNDATE
    FROM DN_TRN_REPO_PERIOD_INT
    WHERE DEAL_NO=M_DOCREFNO;

ELSIF SUBSTR(M_DOCREFNO,1,2)='RR' THEN
    SELECT EFF_VALDATE
    INTO M_TRNDATE
    FROM DN_TRN_REPO_ROLLOVER
    WHERE DEAL_NO=M_DOCREFNO;


ELSIF SUBSTR(M_DOCREFNO,1,2)='RS' THEN
    SELECT SETTLE_DATE
    INTO M_TRNDATE
    FROM DN_TRN_REPO_SETTLEMENT
    WHERE DEAL_NO=M_DOCREFNO;

ELSIF SUBSTR(M_DOCREFNO,1,2)='SO' THEN
    SELECT P1_EFF_VALDATE,P2_EFF_VALDATE
    INTO M_TRNDATE,M_TRNDATE2
    FROM DN_TRN_SWAP_OUTRIGHT
    WHERE DEAL_NO=M_DOCREFNO;

ELSIF SUBSTR(M_DOCREFNO,1,2)='SR' THEN
    SELECT P1_EFF_VALDATE,P2_EFF_VALDATE
    INTO M_TRNDATE,M_TRNDATE2
    FROM DN_TRN_SWAP_RETURNABLE
    WHERE DEAL_NO=M_DOCREFNO;
END IF;


IF (SUBSTR(M_DOCREFNO,1,2)='BF' OR SUBSTR(M_DOCREFNO,1,2)='BS' OR SUBSTR(M_DOCREFNO,1,2)='OR'
    OR SUBSTR(M_DOCREFNO,1,2)='RF' OR SUBSTR(M_DOCREFNO,1,2)='RP' OR
    SUBSTR(M_DOCREFNO,1,2)='RR') THEN
---------------------(1)-------------------------
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'800','DR',M_TRNAMOUNT,M_DOCREFNO,'RECEIPT OF BROK FROM PORT','301');
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'301','CR',M_TRNAMOUNT,M_DOCREFNO,'RECEIPT OF BROK FROM PORT','800');

---------------------(2)-------------------------
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'800','DR',M_TRNAMOUNT2,M_DOCREFNO,'RECEIPT OF GST-BROK FROM PORT','301');
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'301','CR',M_TRNAMOUNT2,M_DOCREFNO,'RECEIPT OF GST-BROK FROM PORT','800');


ELSIF (SUBSTR(M_DOCREFNO,1,2)='SO' OR SUBSTR(M_DOCREFNO,1,2)='SR') THEN
---------------------(1)-------------------------
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'800','DR',M_TRNAMOUNT,M_DOCREFNO,'RECEIPT OF BROK FROM PORT','301');
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'301','CR',M_TRNAMOUNT,M_DOCREFNO,'RECEIPT OF BROK FROM PORT','800');

INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_DN_PORTF_CODE,M_PORTF_CODE,M_TRNDATE2,'800','DR',M_TRNAMOUNT,M_DOCREFNO,'RECEIPT OF BROK FROM PORT','301');
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_DN_PORTF_CODE,M_PORTF_CODE,M_TRNDATE2,'301','CR',M_TRNAMOUNT,M_DOCREFNO,'RECEIPT OF BROK FROM PORT','800');

--------------------(2)--------------------------
