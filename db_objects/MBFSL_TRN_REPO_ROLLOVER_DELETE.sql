  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_TRN_REPO_ROLLOVER_DELETE" 
   (M_DEALNO           DN_TRN_REPO_ROLLOVER.DEAL_NO%TYPE,
    M_USER             DN_TRN_REPO_ROLLOVER.DN_USER%TYPE

   )
AS

MM_PRIOR_DEAL_NO DN_TRN_REPO_ROLLOVER.DEAL_NO%TYPE;

BEGIN

    /* PROCEDURE  -  REPO ROLLOVER DEAL_DELETE
       SYSTEM     -  DEALNET
       CREATED BY -  DAYAN
       CREATED ON -  26/07/1999 */
		-- MODIFIED BY -  V.SUKATHIS.
    -- MODIFIED ON -  27/1/2000

--RAISE_APPLICATION_ERROR(-20201,M_DEALNO);

  --ADDED FOR TIME LOG MANAGEMENT BY S.YASODHA
     INSERT INTO DN_TIME_LOG
           (SUS_REF_NO,
           DN_USER,
           ENT_DATE,
           DESCRIPTION)
           VALUES
            (
              M_DEALNO,
              M_USER,
              SYSDATE,
              'DELETION'
           );
 --*****************************************

--	DN_LIMIT_TRN_OVRL_EXPO(M_DEALNO,'U'); -- Modified by Sukathis
         /*   DN_LIMIT_TRN_OVRL_MATU(M_DEALNO,'U');--ADD BY DAYAN TO RUN TRANSACTION PROCEDURE
            DN_LIMIT_TRN_OVRL(M_DEALNO,'U');-- Modified by Sukathis
            DN_LIMIT_TRN_OVRL_EXPO(M_DEALNO,'U');-- Modified by Sukathis
            DN_LIMIT_TRN_ISSUER_INST_AMT(M_DEALNO,'U');--added by nirmala
            DN_LIMIT_TRN_ISSUER_INST_MAT(M_DEALNO,'U');--added by nirmala
            DN_LIMIT_TRN_ISS_HOL_PERIOD(M_DEALNO,'U');--added by nirmala*/
            --DN_LIMIT_TRN_DEALER_INST_AMT(M_DEALNO,'U');--added by nirmala


 IF (SUBSTR(M_DEALNO,1,2)='GR')THEN

   UPDATE DN_TRN_REPO_ROLLOVER
   SET    --APP_STATUS='CANCEL',
          PRIOR_DEAL_NO=M_DEALNO
   WHERE  DEAL_NO=M_DEALNO;

   UPDATE DN_TRN_REPO_ROLLOVER
   SET    APP_STATUS='CANCEL',
          PRIOR_DEAL_NO=DEAL_NO
   WHERE  GROUP_DEALNO=M_DEALNO;

   UPDATE DN_TRN_REPO_SETTLEMENT
   SET    --APP_STATUS='CANCEL',
          PRIOR_DEAL_NO=M_DEALNO
   WHERE  DEAL_NO=M_DEALNO;

   UPDATE DN_TRN_REPO_SETTLEMENT
   SET    APP_STATUS='CANCEL',
          PRIOR_DEAL_NO=DEAL_NO
   WHERE  GROUP_DEALNO=M_DEALNO;


 ELSE

SELECT PRIOR_DEAL_NO INTO MM_PRIOR_DEAL_NO FROM DN_TRN_REPO_ROLLOVER WHERE M_DEALNO=DEAL_NO;

     UPDATE DN_TRN_REPO_ROLLOVER
   SET
         APP_STATUS='CANCEL',
         PRIOR_DEAL_NO=M_DEALNO
   WHERE M_DEALNO=DEAL_NO;

 UPDATE DN_TRN_REPO_ROLLOVER
   SET
         ON_CALL_DEAL='Y'
   WHERE  MM_PRIOR_DEAL_NO=DEAL_NO AND  ON_CALL_DEAL='S';
   
 --THIS SECTION WAS ADDED BY SM ON 21-10-2010  
 UPDATE DN_TRN_REPO_FRESH
   SET
         ON_CALL_DEAL='Y'
   WHERE  MM_PRIOR_DEAL_NO=DEAL_NO AND  ON_CALL_DEAL='S';




 END IF;

COMMIT;

END MBFSL_TRN_REPO_ROLLOVER_DELETE;

