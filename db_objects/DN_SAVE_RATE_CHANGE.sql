set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_SAVE_RATE_CHANGE" (
 MDATE           VARCHAR2,
 MRATE           DN_REF_RATE_CHANGE.RATE%TYPE,
 MBASERATE       DN_REF_RATE_CHANGE.BASE_RATE%TYPE,
 MUSER           DN_REF_RATE_CHANGE.DN_USER%TYPE
)

AS

M_CNT  NUMBER DEFAULT 0;

BEGIN

   SELECT COUNT(*) INTO M_CNT
   FROM   DN_REF_RATE_CHANGE
   WHERE  TO_DATE(TO_CHAR(CHANGE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(MDATE,'DD-MM-YYYY');
   --RAISE_APPLICATION_ERROR(-20201,'M_CNT**********'||M_CNT||'MRATE'||MRATE||'MUSER'||MUSER);

   IF M_CNT >0 THEN
    SELECT COUNT(*) INTO M_CNT
    FROM   DN_REF_RATE_CHANGE
    WHERE  TO_DATE(TO_CHAR(CHANGE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(MDATE,'DD-MM-YYYY') AND
           ROLLOVER_STATUS='NOT_RUN';
    IF M_CNT >0 THEN
      UPDATE DN_REF_RATE_CHANGE
      SET    BASE_RATE=MBASERATE,RATE=MRATE,ROLLOVER_STATUS='NOT_RUN'
      WHERE  TO_DATE(TO_CHAR(CHANGE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(MDATE,'DD-MM-YYYY');
    END IF;
   ELSE
    INSERT INTO DN_REF_RATE_CHANGE(CHANGE_DATE,RATE,BASE_RATE,DN_USER)
    VALUES ( TO_DATE(MDATE,'DD-MM-YYYY'),MRATE,MBASERATE,MUSER);

   END IF;



COMMIT;




END;

