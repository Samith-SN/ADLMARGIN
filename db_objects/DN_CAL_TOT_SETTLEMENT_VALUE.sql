--  DDL for Function DN_CAL_TOT_SETTLEMENT_VALUE
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_CAL_TOT_SETTLEMENT_VALUE" 


     ( 
     
      M_SELLER  DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE,
	  M_BUYER   DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE,
      M_FROM_DATE VARCHAR2,
      M_TO_DATE   VARCHAR2
      
     )



  --CREATED BY ASHINI HEWAGE ON 17-05-2006- FOR SR0605-019 
  --TP GET THE TOTTAL SETTLEMENT VALUE 
  
  
  RETURN  REAL



   IS
	  TOTAL  DN_TRN_OUTP_SALE.SETTLE_VALUE%TYPE;



BEGIN


SELECT SUM(X.SETTLE_VALUE) INTO TOTAL
FROM DN_TRN_OUTP_SALE X, 
     DN_TRN_OUTP_SALE_SETTLE_EQUITY Z, 
      DN_REF_PORTFOLIO W,  
     DN_REF_PORTFOLIO V  
WHERE Z.DEAL_NO= X.DEAL_NO AND 
      X.APP_STATUS<>'CANCEL' AND X.BUY_PORTFOLIO_CODE= W.PORTFOLIO_CODE AND 
      X.SELL_PORTFOLIO_CODE = V.PORTFOLIO_CODE AND 
      X.SELL_PORTFOLIO_CODE = M_SELLER AND 
	  X.BUY_PORTFOLIO_CODE= M_BUYER AND 
   
   	DN_GET_INSTRUMENT_CAT(INST_TYPE)='EQUITY' AND  
     (W.PF_TYPE = 'P' OR W.OWNED_BY_MBFSL='Y') AND V.PF_TYPE='C' AND 
     TO_DATE(TO_CHAR(BUY_SETLE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')>=TO_DATE(M_FROM_DATE,'DD-MM-YYYY') AND  
     TO_DATE(TO_CHAR(BUY_SETLE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=TO_DATE(M_TO_DATE,'DD-MM-YYYY') ;

RETURN TOTAL;

END DN_CAL_TOT_SETTLEMENT_VALUE;

/
