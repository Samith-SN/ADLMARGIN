  FROM	  (SELECT  A.SECURITY_CODE U,TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY') V,
	  	           SUM(A.FACE_VALUE) X,SUM(A.COST) Y,SUM(A.FACE_VALUE*A.YIELD*100) Z,TO_DATE(B.MATURITY_DATE,'DD-MON-YYYY') Z1
		   FROM    DN_TRN_OUTP_SALE A,
	               DN_REF_SECURITY B,
                   DN_REF_PORTFOLIO C
           WHERE   TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
                   A.DEAL_NO NOT IN   (SELECT DEAL_NO
                                       FROM DN_TRN_DEAL_CURRENCY ) AND
