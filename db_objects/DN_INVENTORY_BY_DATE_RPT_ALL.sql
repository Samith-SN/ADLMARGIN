                   C.FACE_VAL_CURR IS NULL /*AND commented by inditha 2004/6/7
                   C.SCRIP_STATUS=M_SCRIP_STATUS*/
       GROUP BY    C.SECURITY_CODE,B.MATURITY_DATE,DN_GET_COUPON_RATE(B.SECURITY_CODE)  )T2
    WHERE T1.sec=T2.sec;


