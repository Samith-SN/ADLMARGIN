set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."SAVE_PAYMENT_ADVICE" 
(
 M_PAYMENT_NO          DN_TRN_BO_SETTL_PAYMENT.PAYMENT_NO%TYPE,
 M_PORTFOLIO_CODE      DN_TRN_BO_SETTL_PAYMENT.PORTFOLIO_CODE%TYPE,
 M_SUS_REF_NO          DN_TRN_BO_SETTL_PAYMENT.SUS_REF_NO%TYPE,
 M_SETTLE_MODE         DN_TRN_BO_SETTL_PAYMENT.SETTLE_MODE%TYPE
)

AS

    -- CREATED BY NIRMALA
    -- ON 29-05-2002
    -- TO SAVE PAYMENT ADVICE STATUS

BEGIN

   UPDATE DN_TRN_BO_SETTL_PAYMENT
   SET    PAY_ADVICE_STATUS='Y'
   WHERE  PAYMENT_NO=M_PAYMENT_NO AND
          PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
          SUS_REF_NO=M_SUS_REF_NO AND
          SETTLE_MODE=M_SETTLE_MODE;

COMMIT;
END SAVE_PAYMENT_ADVICE;

