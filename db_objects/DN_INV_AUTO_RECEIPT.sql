      PAYER_REF, OTH_COMMENTS, BRANCH_CODE, ACC_NO, STATUS, DN_USER, ENTDATE,EFF_VALDATE)

     SELECT M_REC_NO,'ADLMT',SUBSTR(SUS_REF_NO,1,10),'BANK_TRANF','C','GOVT',
            M_AMT,'CUST-COUP','CUST-COUP','CUST-COUP','CUST-COUP',M_BRANCH_CODE,
            M_ACC_NO,'CRD',M_USER,SYSDATE,TO_DATE(M_LAST_DAILY1,'DD-MM-YYYY')
     FROM   DN_ACC_SUS_RECEIPT
     WHERE  BAL_TO_BE_RECEIVED=0 AND
            TO_DATE(TO_CHAR(ENT_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(M_LAST_DAILY1,'DD-MM-YYYY') AND
            SUBSTR(SUS_REF_NO,1,2)='CC'
  GROUP BY  SUBSTR(SUS_REF_NO,1,10);


     DN_ACC_LINK_BO_SETTL_INV('C','ADLMT','GOVT',TO_DATE(M_LAST_DAILY1,'DD-MM-YYYY'),M_AMT,M_REC_NO,M_ACC_SYS_REFNO);
 END IF;
