        TO_DATE(TO_CHAR(ENT_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(M_LAST_DAILY1,'DD-MM-YYYY') AND
        SUBSTR(SUS_REF_NO,1,2)='CC';


