SELECT COUNT(*)
 INTO   M_ALL_COUNT
 FROM   DN_ACC_SUS_RECEIPT
 WHERE  BAL_TO_BE_RECEIVED=0 AND
        TO_DATE(TO_CHAR(ENT_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(M_LAST_DAILY1,'DD-MM-YYYY') AND
        SUBSTR(SUS_REF_NO,1,2)='MP';

  IF(M_ALL_COUNT>0) THEN

 SELECT BRANCH_CODE,ACC_NO,ACC_SYS_REFNO
 INTO   M_BRANCH_CODE,M_ACC_NO,M_ACC_SYS_REFNO
 FROM   DN_REF_LICENCEE_SETTLEMENT
 WHERE  ACTIVE_STATUS='Y' AND SETTLEMENT_STATUS='W' AND ROWNUM=1 ;


  SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_SET_REC.NEXTVAL),3,'0')
