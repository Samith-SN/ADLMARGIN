        SUBSTR(SUS_REF_NO,1,2)='CM';

  INSERT INTO DN_TRN_BO_SETTL_RECEIPT
    ( REC_NO,PORTFOLIO_CODE,SUS_REF_NO,SETTLE_MODE,SUSPENSE_ENTRY_TYPE,
