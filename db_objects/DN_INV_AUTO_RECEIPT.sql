      PAYER_REF, OTH_COMMENTS, BRANCH_CODE, ACC_NO, STATUS, DN_USER, ENTDATE,EFF_VALDATE)

     SELECT M_REC_NO,'ADLMT',SUBSTR(SUS_REF_NO,1,10),'BANK_TRANF','M','GOVT',
            M_AMT,'CUST-MATU','CUST-MATU','CUST-MATU','CUST-MATU',M_BRANCH_CODE,
