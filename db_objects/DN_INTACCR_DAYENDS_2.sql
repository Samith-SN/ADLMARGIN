set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_INTACCR_DAYENDS_2" 
(
M_DEAL_NO           DN_TRN_REPO_FRESH.DEAL_NO%TYPE
)
AS

M_EFF_VALDATE       DATE;--EFF DATE OF THE DEAL
M_MATURITY_DATE     DATE;--MAT DATE OF THE DEAL
M_MATURITY_DATE1    DATE;--MAT DATE OF THE DEAL
M_LAST_MON_DATE     DATE;--LAST DATE OF THE MONTH
M_COUNT             NUMBER;--GET MONTH DIFF.
J                   NUMBER;
MN_COUNT1           NUMBER;--ADDED BY NIRMALA


/********************************************************
     DESCRIPTION:   GET  INSERT MONTH ENDS BETWEEN EFF. DATE AND MAT. DATE
     SYSTEM:        MBFSL
     CREATE BY:     INDITHA
     COPIED BY  - KEITH FOR SAMPATH on 2004-11-30 for vc ref 04-266 backdated deals
     DATE:          2004-11-15
**********************************************************/

BEGIN

M_COUNT := 0;
J       := 0;


SELECT  LAST_DAY(TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')),
        LAST_DAY(TO_DATE(TO_CHAR(MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY'))
        INTO M_EFF_VALDATE,M_MATURITY_DATE
FROM    (SELECT EFF_VALDATE,MATURITY_DATE
          FROM   DN_TRN_REPO_FRESH
          WHERE  DEAL_NO=M_DEAL_NO
          UNION
          SELECT EFF_VALDATE,MATURITY_DATE
          FROM   DN_TRN_REPO_ROLLOVER
          WHERE  DEAL_NO=M_DEAL_NO
          );


SELECT  TO_DATE(TO_CHAR(MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY')-1
        INTO M_MATURITY_DATE1
FROM    (SELECT MATURITY_DATE
          FROM   DN_TRN_REPO_FRESH
          WHERE  DEAL_NO=M_DEAL_NO
          UNION
          SELECT MATURITY_DATE
          FROM   DN_TRN_REPO_ROLLOVER
          WHERE  DEAL_NO=M_DEAL_NO
          );


SELECT ROUND(MONTHS_BETWEEN(M_MATURITY_DATE,M_EFF_VALDATE)) INTO M_COUNT FROM DUAL;

M_COUNT:=M_COUNT-1;

DELETE FROM DN_TEMP_MONTHENDS;

FOR  J IN   0..M_COUNT  LOOP

    SELECT LAST_DAY(ADD_MONTHS(M_EFF_VALDATE,J)) INTO M_LAST_MON_DATE FROM DUAL;

    INSERT INTO DN_TEMP_MONTHENDS(MONTH_END_DAYS)
    VALUES(M_LAST_MON_DATE);--INSERT MONTH-ENDS

END LOOP;

--ADDED BY NIRMALA------
SELECT    COUNT(MONTH_END_DAYS)
INTO      MN_COUNT1
FROM      DN_TEMP_MONTHENDS
WHERE     TO_DATE(TO_CHAR(MONTH_END_DAYS,'DD-MM-YYYY'),'DD-MM-YYYY')=M_MATURITY_DATE1;
-------------------------
IF MN_COUNT1 = 0 THEN--ADDED BY NIRMALA
    INSERT INTO DN_TEMP_MONTHENDS(MONTH_END_DAYS)
    VALUES(M_MATURITY_DATE1);--INSERT LAST DAILY DATE
END IF;--ADDED BY NIRMALA

END DN_INTACCR_DAYENDS_2;

/
