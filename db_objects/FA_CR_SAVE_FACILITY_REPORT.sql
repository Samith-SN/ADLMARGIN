set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."FA_CR_SAVE_FACILITY_REPORT" 
(
M_CLIENT_CODE                       DN_facility_report.CLIENT_CODE%TYPE, 
M_FACILITY_NO                       DN_facility_report.FACILITY_NO%TYPE,
M_REPORT_CODE                       DN_facility_report.REPORT_CODE%TYPE,
M_REPORT_NAME                       DN_facility_report.REPORT_NAME%TYPE,
M_USER                              DN_facility_report.ENT_USER%TYPE,
M_SCREEN                            VARCHAR2,
M_NUM                               INT,
M_FREQUENCY                         DN_facility_report.FREQUENCY%TYPE,
M_PRINT                             DN_facility_report.PRINT%TYPE,
M_EMAIL                             DN_facility_report.EMAIL%TYPE,
M_FAX                               DN_facility_report.FAX%TYPE,
M_SUPPORTING_DOCS                   DN_facility_report.SUPPORTING_DOCS%TYPE,
M_MANDATORY                         DN_facility_report.MANDATORY%TYPE
)

AS
-- CREATED BY THAMALI JAYATUNGA ON 2010.03.16

BEGIN

IF UPPER(M_SCREEN)='NEW' THEN

INSERT INTO DN_facility_report
(CLIENT_CODE, FACILITY_NO, REPORT_CODE, REPORT_NAME, ENT_USER,ENT_DATE,
FREQUENCY,PRINT,EMAIL,FAX,SUPPORTING_DOCS,MANDATORY)
VALUES
(M_CLIENT_CODE,M_FACILITY_NO,M_REPORT_CODE,M_REPORT_NAME,M_USER,SYSDATE,
M_FREQUENCY,M_PRINT,M_EMAIL,M_FAX,M_SUPPORTING_DOCS,M_MANDATORY);

ELSE

IF M_NUM=0 THEN

INSERT INTO DN_facility_report_BK
(CLIENT_CODE, FACILITY_NO, REPORT_CODE, REPORT_NAME, ENT_USER,ENT_DATE,MOD_USER,MOD_DATE,
FREQUENCY,PRINT,EMAIL,FAX,SUPPORTING_DOCS,MANDATORY)
SELECT
CLIENT_CODE, FACILITY_NO, REPORT_CODE, REPORT_NAME, ENT_USER,ENT_DATE,MOD_USER,MOD_DATE,
FREQUENCY,PRINT,EMAIL,FAX,SUPPORTING_DOCS,MANDATORY
FROM DN_facility_report
WHERE CLIENT_CODE   = M_CLIENT_CODE
AND   FACILITY_NO = M_FACILITY_NO;

DELETE FROM DN_facility_report
WHERE CLIENT_CODE   = M_CLIENT_CODE
AND   FACILITY_NO = M_FACILITY_NO;

END IF;

INSERT INTO DN_FACILITY_REPORT
(CLIENT_CODE, FACILITY_NO, REPORT_CODE, REPORT_NAME, ENT_USER,ENT_DATE,
FREQUENCY,PRINT,EMAIL,FAX,SUPPORTING_DOCS,MANDATORY)
VALUES
(M_CLIENT_CODE,M_FACILITY_NO,M_REPORT_CODE,M_REPORT_NAME,M_USER,SYSDATE,
M_FREQUENCY,M_PRINT,M_EMAIL,M_FAX,M_SUPPORTING_DOCS,M_MANDATORY);

END IF;

END;

