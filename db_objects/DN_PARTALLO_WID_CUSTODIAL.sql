FROM    DN_TRN_BO_CUSTODIAL_DEAL_SEC
WHERE   DEAL_NO=M_DEAL_NO AND
        SECURITY_CODE=M_SECURITY_CODE AND
        SERIAL_NO=M_HID_PA_ORGSERIALNO AND
        FACE_VALUE=M_HID_FULL_AMT ;


  SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS.NEXTVAL),4,'0')--$$##SC
  INTO   MM_SWAP_SERNO2
  FROM   DUAL;

  M_SWAP_SERNO2:='S'||MM_SWAP_SERNO2;


INSERT INTO  DN_TRN_BO_CUSTODIAL_DEAL_SEC
 (DEAL_NO,SECURITY_CODE,SERIAL_NO,FACE_VALUE)
SELECT  DEAL_NO,SECURITY_CODE,M_SWAP_SERNO2,M_HID_PA_AMT
FROM    DN_TRN_BO_CUSTODIAL_DEAL_SEC
WHERE   DEAL_NO=M_DEAL_NO AND
