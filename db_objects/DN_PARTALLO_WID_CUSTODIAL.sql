       )
      VALUES
      (M_CUSTODIAL_CODE,M_EFF_VALDATE,M_INST_TYPE,M_SECURITY_CODE,M_DEAL_NO,M_SWAP_SERNO2,
       M_HID_PA_AMT,M_HID_PA_AMT,'DEP');

