 WHERE   SERIAL_NO=M_HID_PA_ORGSERIALNO AND
         CUSTODIAL_CODE=M_CUSTODIAL_CODE AND
         INST_TYPE=M_INST_TYPE AND
         SECURITY_CODE=M_SECURITY_CODE AND
         SCRIP_FACE_VAL=M_HID_FULL_AMT;




 -------UPDATING THE ORIGINAL SERIAL NO RECORED------------------------------------
 UPDATE DN_INV_CUST_DEAL_SERIAL_NO
 SET    DIP_WID_DEAL_NO=MM_DEAL_NO,
        SERIAL_NO_STATUS='TRF', --CHANGE ON 12-07-2004 VC04/181
        DIP_WID_EFF_VALDATE=M_EFF_VALDATE
 WHERE  SERIAL_NO=M_HID_PA_ORGSERIALNO AND
        CUSTODIAL_CODE=M_CUSTODIAL_CODE AND
        INST_TYPE=M_INST_TYPE AND
        SECURITY_CODE=M_SECURITY_CODE AND
        SCRIP_FACE_VAL=M_HID_FULL_AMT AND
        DEAL_NO=M_DEAL_NO;





----------------UPDATING THE  TABLE  DN_TRN_BO_CUSTODIAL_DEAL_SEC-----------------------------------
  SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS.NEXTVAL),4,'0')--$$##SC
  INTO   MM_SWAP_SERNO1
  FROM   DUAL;

  M_SWAP_SERNO1:='S'||MM_SWAP_SERNO1;

