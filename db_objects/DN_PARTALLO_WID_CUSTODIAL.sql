 --------------RECORD OF THE ORIGINAL SERIAL NO---------------------------------------
 SELECT  EFF_VALDATE,DEAL_NO,SERIAL_NO,
         SCRIP_FACE_VAL,FACE_VAL
 INTO    M_EFF_VALDATE,M_DEAL_NO,M_SERIAL_NO,
         M_SCRIP_FACE_VAL,M_FACE_VAL
