  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_NOT_HIT_VALID_RECEIPTS" 
(
 PORT           DN_TRN_BO_SETTL_RECEIPT_TMP.SELL_PORTFOLIO_CODE%TYPE,
 EFFDATE        VARCHAR2
)
 RETURN NUMBER
 AS
 M_TOTAL_PENDING       DN_TRN_BO_SETTL_RECEIPT_TMP.REC_AMOUNT%TYPE;


 BEGIN
 
   SELECT SUM(REC_AMOUNT) INTO M_TOTAL_PENDING
   FROM DN_TRN_BO_SETTL_RECEIPT_TMP A
   WHERE SELL_PORTFOLIO_CODE=PORT 
   AND TRNDATE<=TO_DATE(EFFDATE,'DD/MM/YYYY')
   --AND ID_PORTFOLIO_CODE=CP_CODE
   AND APP_STATUS IN('APPR1','APPR2','CONF','SIG1','SIG2','PRINT');
   
   RETURN  NVL(M_TOTAL_PENDING,0);

END ;

