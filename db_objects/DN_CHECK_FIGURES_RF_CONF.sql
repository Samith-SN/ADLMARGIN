  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CHECK_FIGURES_RF_CONF" 
(
M_DEAL_NO    DN_TRN_REPO_FRESH.DEAL_NO%TYPE,
M_SECTION    CHAR
)
AS
M_COUNT1                        NUMBER;
M_NO_OF_SETTL_MODES             DN_TRN_REPO_FRESH.NO_OF_SETTL_MODES%TYPE;
M_LEG1_VALUE1                   DN_TRN_REPO_FRESH.LEG1_VALUE%TYPE;
M_LEG1_VALUE2                   DN_TRN_REPO_FRESH.LEG1_VALUE%TYPE;
M_COUNT_INTRUMENT               NUMBER;
M_TENOR1                        DN_TRN_REPO_FRESH.TENOR%TYPE;
M_TENOR2                        DN_TRN_REPO_FRESH.TENOR%TYPE;
M_INTEREST1                     DN_TRN_REPO_FRESH.INT_AMOUNT%TYPE;
M_INTEREST2                     DN_TRN_REPO_FRESH.INT_AMOUNT%TYPE;
M_COUNT_NEW1                     NUMBER;
M_COUNT_NEW2                     NUMBER;
M_COUNT_NEW3                     NUMBER;
M_COUNT_NEW4                     NUMBER;
M_COUNT_NEW5                     NUMBER;
M_INT_AMOUNT                     NUMBER(20,4);
err_num   varchar2(200);
err_msg   varchar2(200);

BEGIN

SELECT  COUNT(*)------------------------1
INTO    M_COUNT_NEW1
FROM    DN_TRN_REPO_FRESH
WHERE   DEAL_NO=M_DEAL_NO AND
        LEG1_VALUE > 0 AND  LEG2_VALUE >0 AND  INT_AMOUNT >= 0 ;

IF(M_COUNT_NEW1<=0)THEN
RAISE_APPLICATION_ERROR(-20201,'DEAL_NO - '||M_DEAL_NO||'-'||'FACE_VALUE ,COST ,SETTLE_VALUE SHOULD BE GREATER THAN ZERO !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;

SELECT  COUNT(*)  ------------------------2
INTO    M_COUNT_NEW2
FROM    DN_TRN_REPO_FRESH
WHERE   DEAL_NO=M_DEAL_NO AND TENOR=TO_NUMBER(MATURITY_DATE-EFF_VALDATE) ;

IF(M_COUNT_NEW2<=0)THEN
RAISE_APPLICATION_ERROR(-20201,'DEAL_NO - '||M_DEAL_NO||'-'||'INCORRECT VALUE FOR TENOR !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;


SELECT COUNT(*)--------------------3
INTO   M_COUNT_NEW3
FROM   DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_DEAL_NO AND
      ABS( ROUND(((LEG1_VALUE*YIELD)/DN_FIN_INT_RATE_BASE_DATES(INT_RATE_BASE_CODE,EFF_VALDATE))*TENOR,2)- INT_AMOUNT)>2 ;

IF(M_COUNT_NEW3>0)THEN
RAISE_APPLICATION_ERROR(-20201,'DEAL_NO - '||M_DEAL_NO||'-'||'INCORRECT INTEREST AMOUNT !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;


 SELECT COUNT(*)--------------------------4
 INTO   M_COUNT_INTRUMENT
 FROM   DN_TRN_REPO_FRESH_INST
 WHERE  DEAL_NO=M_DEAL_NO;

IF(M_COUNT_INTRUMENT<=0)THEN
RAISE_APPLICATION_ERROR(-20201,'DEAL_NO - '||M_DEAL_NO||'-'||'NO RECORD FOUND IN INSTRUMENT TABLE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;




SELECT COUNT(*)------------------------5
INTO   M_COUNT1
FROM   DN_TRN_REPO_FRESH_SETTLE
WHERE  DEAL_NO=M_DEAL_NO;

IF M_COUNT1<=0 THEN
RAISE_APPLICATION_ERROR(-20201,'DEAL_NO - '||M_DEAL_NO||'-'||'NO RECORD FOUND IN SETTLE TABLE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;


SELECT COUNT(*) -----------------------6
INTO   M_COUNT_NEW4
FROM   DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_DEAL_NO;
IF (M_COUNT_NEW4>0)THEN
SELECT NO_OF_SETTL_MODES
INTO   M_NO_OF_SETTL_MODES
FROM   DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_DEAL_NO;
IF M_NO_OF_SETTL_MODES <= 0 THEN
RAISE_APPLICATION_ERROR(-20201,'DEAL_NO - '||M_DEAL_NO||'-'||'NO_OF_SETTL_MODES SHOULD BE GREATER THAN ZERO!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;

ELSE
RAISE_APPLICATION_ERROR(-20201,'DEAL_NO - '||M_DEAL_NO||'-'||'NO_RECORD EXISTS IN DN_TRN_REPO_FRESH TABLE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;


SELECT COUNT(*)--------------------------------7
INTO  M_COUNT_NEW5
FROM  DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_DEAL_NO AND
       LEG1_VALUE=(SELECT SUM(SETTLE_AMOUNT)
                    FROM   DN_TRN_REPO_FRESH_SETTLE
                    WHERE    DEAL_NO=M_DEAL_NO
                    GROUP BY DEAL_NO );


SELECT   LEG1_VALUE
INTO     M_LEG1_VALUE1
FROM     DN_TRN_REPO_FRESH
WHERE    DEAL_NO=M_DEAL_NO;

SELECT   SUM(SETTLE_AMOUNT)
INTO     M_LEG1_VALUE2
FROM     DN_TRN_REPO_FRESH_SETTLE
WHERE    DEAL_NO=M_DEAL_NO
GROUP BY DEAL_NO ;

IF (M_LEG1_VALUE1 <> M_LEG1_VALUE2 ) THEN
RAISE_APPLICATION_ERROR(-20201,'DEAL_NO - '||M_DEAL_NO||'-'||'MISMATCH IN SETTLE_VALUE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;

-- ADDED ON 13-05-2004 TO CHECK LEG2 VALUE
--NILU
