  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_SETTL_DATE" 
(
M_SEC_CODE     DN_REF_SECURITY.SECURITY_CODE%TYPE,
M_DEAL_NO      DN_TRN_OUTP_SALE.DEAL_NO%TYPE

)
---created by Manjula for SRF 0412-012
---for FCLMGT

RETURN DATE
IS
M_INST_CAT     DN_REF_INSTRUMENT.INST_CAT%TYPE;
M_SETT_DATE    DATE;
M_B_SETT_DATE    DATE;
M_S_SETT_DATE    DATE;
M_B_PF_TYPE      DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_S_PF_TYPE      DN_REF_PORTFOLIO.PF_TYPE%TYPE;

BEGIN


SELECT INST_CAT INTO M_INST_CAT
FROM DN_REF_INSTRUMENT
WHERE INST_TYPE IN
    ( SELECT INST_TYPE
      FROM DN_REF_SECURITY
      WHERE SECURITY_CODE=M_SEC_CODE );


IF M_INST_CAT='EQUITY' THEN
SELECT BUY_SETLE_DATE,SELL_SETLE_DATE INTO M_B_SETT_DATE,M_S_SETT_DATE
FROM DN_TRN_OUTP_SALE_SETTLE_EQUITY
WHERE DEAL_NO=M_DEAL_NO;


 SELECT
    B.PF_TYPE,
    C.PF_TYPE
 INTO M_B_PF_TYPE,M_S_PF_TYPE
 FROM DN_TRN_OUTP_SALE A,
      DN_REF_PORTFOLIO B,
      DN_REF_PORTFOLIO C
 WHERE BUY_PORTFOLIO_CODE=B.PORTFOLIO_CODE AND
       SELL_PORTFOLIO_CODE=C.PORTFOLIO_CODE AND
       DEAL_NO =M_DEAL_NO;

IF M_B_PF_TYPE = 'P' THEN
  M_SETT_DATE :=M_B_SETT_DATE;
ELSE
  M_SETT_DATE :=M_S_SETT_DATE;
END IF;

ELSE
SELECT MATURITY_DATE INTO M_SETT_DATE
FROM DN_REF_SECURITY
WHERE SECURITY_CODE=M_SEC_CODE;
END IF;
dbms_output.put_line('Value of M_SETT_DATE='||M_SETT_DATE);
RETURN M_SETT_DATE ;

END;

/
