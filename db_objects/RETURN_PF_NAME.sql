  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_PF_NAME" 
(
  M_LEND_PORTFOLIO_CODE     DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE
)
RETURN VARCHAR2

AS
M_PF_NAME DN_REF_PORTFOLIO.PF_NAME%TYPE;

BEGIN
     SELECT DISTINCT(PF_NAME)
      INTO M_PF_NAME
      FROM DN_REF_PORTFOLIO
      WHERE PORTFOLIO_CODE = M_LEND_PORTFOLIO_CODE;

RETURN M_PF_NAME;

END RETURN_PF_NAME; 

