M_RET_VAL1 := TO_CHAR(ROUND(((M_FACE_VALUE/M_BOND_FACE_VALUE)*M_CLEAN_PRICE),2),'FM999G999G999G999G990D00');
M_RET_VAL2 :=TO_CHAR(ROUND(((M_FACE_VALUE/M_BOND_FACE_VALUE)*M_INT_ADJ),2),'FM999G999G999G999G990D00');
