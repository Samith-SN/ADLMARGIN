  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_FIN_COST_ACCINT_SETVAL_TEST" 
   (
    M_SECURITY_CODE       IN      DN_TRN_OUTP_SALE.SECURITY_CODE%TYPE,
    M_CLEAN_PRICE         IN      DN_TRN_OUTP_SALE.PRICE_CLEAN%TYPE,
    M_EFF_VALDATE_TYPE    IN      VARCHAR2,
    --Char value of the date
    M_FACE_VALUE          IN      DN_TRN_OUTP_SALE.FACE_VALUE%TYPE,
    M_RET_VAL1            IN OUT  VARCHAR2,
