       TO_CHAR(ROUND(((M_FACE_VALUE/M_BOND_FACE_VALUE)*M_INT_ADJ),2),'FM999G999G999G999G990D00'),
       TO_CHAR(ROUND((((M_FACE_VALUE/M_BOND_FACE_VALUE)*M_CLEAN_PRICE)+
       ((M_FACE_VALUE/M_BOND_FACE_VALUE)*M_INT_ADJ)),2),'FM999G999G999G999G990D00')
