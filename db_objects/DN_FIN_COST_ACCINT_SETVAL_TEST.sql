       ROUND((((M_FACE_VALUE/M_BOND_FACE_VALUE)*M_CLEAN_PRICE)+
       ((M_FACE_VALUE/M_BOND_FACE_VALUE)*M_INT_ADJ)),2)
    FROM DUAL;

