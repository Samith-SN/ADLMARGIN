--------------------------------------------------------
--  DDL for Function RETURN_GROUPDEAL_STATUS
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_GROUPDEAL_STATUS" 
(
M_GROUP_DEALNO          DN_TRN_OUTP_SALE.GROUP_DEALNO%TYPE
)
RETURN VARCHAR2
AS
M_STAT_COUNT  INTEGER;
BEGIN

IF(SUBSTR(M_GROUP_DEALNO,1,2)='GO')THEN
SELECT COUNT(*)
INTO   M_STAT_COUNT
FROM
   (SELECT   APP_STATUS
    FROM     DN_TRN_OUTP_SALE
    WHERE    GROUP_DEALNO=M_GROUP_DEALNO
    GROUP BY APP_STATUS);
ELSIF (SUBSTR(M_GROUP_DEALNO,1,2)='GF')THEN
SELECT COUNT(*)
INTO   M_STAT_COUNT
FROM
   (SELECT   APP_STATUS
    FROM     DN_TRN_REPO_FRESH
    WHERE    GROUP_DEALNO=M_GROUP_DEALNO
    GROUP BY APP_STATUS);
ELSIF (SUBSTR(M_GROUP_DEALNO,1,2)='GR')THEN
SELECT COUNT(*)
INTO   M_STAT_COUNT
FROM
   (SELECT   APP_STATUS
    FROM     DN_TRN_REPO_ROLLOVER
    WHERE    GROUP_DEALNO=M_GROUP_DEALNO
    UNION
    SELECT   APP_STATUS
    FROM     DN_TRN_REPO_SETTLEMENT
    WHERE    GROUP_DEALNO=M_GROUP_DEALNO
    GROUP BY APP_STATUS);

END IF;
RETURN   M_STAT_COUNT;

END RETURN_GROUPDEAL_STATUS;

/
