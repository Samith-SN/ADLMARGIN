  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_FIN_EFF_VALDATE_EQUITY_HELP" 
   (
    M_DEAL_NO       DN_TRN_OUTP_SALE.DEAL_NO%TYPE
   ) RETURN  DATE


    IS


M_EFF_VALDATE     DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE;

BEGIN



IF SUBSTR(M_DEAL_NO,0,2)   = 'RF' THEN
    SELECT EFF_VALDATE INTO M_EFF_VALDATE FROM DN_TRN_REPO_FRESH WHERE DEAL_NO=M_DEAL_NO;

ELSIF SUBSTR(M_DEAL_NO,0,2)   = 'RR' THEN

  SELECT EFF_VALDATE INTO M_EFF_VALDATE FROM DN_TRN_REPO_ROLLOVER WHERE DEAL_NO=M_DEAL_NO;

 ELSIF SUBSTR(M_DEAL_NO,0,2)   = 'RS' THEN

  SELECT SETTLE_DATE INTO M_EFF_VALDATE FROM DN_TRN_REPO_SETTLEMENT WHERE DEAL_NO=M_DEAL_NO;


END IF;




RETURN M_EFF_VALDATE;

END DN_FIN_EFF_VALDATE_EQUITY_HELP;

