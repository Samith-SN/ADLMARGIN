set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_UPLOAD_BULK_OR_TRN_LIST" 
(
 M_USER_NAME         DN_TEMP_TRN_LIST.USER_NAME%TYPE,
 M_TRN_TYPE          VARCHAR , 
 M_EX_COUNT          OUT NUMBER
)
AS
M_DEAL_NO              DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
M_SECURITY_CODE        DN_REF_SECURITY.SECURITY_CODE%TYPE;
M_ISSUER_CODE          DN_REF_SECURITY.ISSUER_CODE%TYPE;
M_GUARANTEE_CODE       DN_REF_SECURITY.GUARANTEE_CODE%TYPE;
M_INST_TYPE            DN_REF_SECURITY.INST_TYPE%TYPE;
M_CURR_CODE            DN_REF_SECURITY.CURR_CODE%TYPE;
M_DEAL_NUMBER          DN_TRN_OUTP_SALE.DEAL_NO%TYPE;
M_PAR_VALUE            DN_REF_SECURITY.PAR_VALUE%TYPE;
M_S_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_B_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_B_PORT_CODE          DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
M_S_PORT_CODE          DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE;
M_SEC_COUNT            NUMBER;
M_BRO_COUNT            NUMBER;
M_COUNT                NUMBER;
M_PF_ACOUNT               NUMBER;--add by waruna 2011-07-26
MM_COUNT               NUMBER; 
M_PF_COUNT             NUMBER;  
M_TEMP_MARGIN_CALL     DN_REF_PORTFOLIO.TEMP_MARGIN_CALL_STATUS%TYPE;
M_LAST_DAILY_CON       NUMBER;

BEGIN
 -- CAREATED BY SVA ON 11-05-2005 TO UPDATE THE TEMP TABLE FROM EXCEL SHEET
 M_EX_COUNT :=0;
 DELETE DN_TEMP_TRN_UPLOAD_ERROR_LOG;
 DELETE FROM   DN_TEMP_TRN_LIST 
 WHERE TRN_DATE IS NULL;  -- add by waruna 2010-09-13
 


 FOR X IN (SELECT TO_CHAR(TRN_DATE,'DD-MM-YYYY') TRN_DATE,
                  TRN_TIME,
                  DEAL_TYPE,
                  CONTRACT_NO,
                  REPLACE(EXT_SECURITY_CODE,' ','') EXT_SECURITY_CODE,
                  QTY,
                  PRICE,
                  INTERNAL_USER,
                  REF_NO,
                  CLIENT_CDS,--DECODE(DEAL_TYPE,'B',DN_GET_PORTFOLIO_CODE(CLIENT_CDS),BROKER) BUY,
                  BROKER,--DECODE(DEAL_TYPE,'S',DN_GET_PORTFOLIO_CODE(CLIENT_CDS),BROKER) SEL,
                  SEC_FEE+CSE_FEE+CDS_FEE+CESS_FEE+BROKERAGE+GOVT_LEVY BROKERAGE,
                  ORDER_ID,
                  TO_CHAR(DN_FIN_BUYER_SETTLE_DATE(TO_CHAR(TRN_DATE,'DD-MM-YYYY'),'3'),'DD-MM-YYYY') BUY_SET,
                  TO_CHAR(DN_FIN_BUYER_SETTLE_DATE(TO_CHAR(TRN_DATE,'DD-MM-YYYY'),'3'),'DD-MM-YYYY') SEL_SET
           FROM   DN_TEMP_TRN_LIST
           WHERE  USER_NAME = M_USER_NAME
           AND DEAL_TYPE=M_TRN_TYPE  --add by waruna 2010-09-15
           AND EXT_SECURITY_CODE IS NOT NULL ) LOOP

M_DEAL_NO:=null; --add by waruna 2011-09-08


 SELECT count(A.LAST_DAILY ) into M_LAST_DAILY_CON
 FROM  DN_SYS_PARAMETER A where 
 LAST_DAILY>= to_date(x.TRN_DATE,'dd/mm/yyyy');
  
-- if(M_LAST_DAILY_CON>0) then -- udara 08-11-2011
if(M_LAST_DAILY_CON>3) then -- added by udara 08-11-2011
RAISE_APPLICATION_ERROR(-20001,'Transaction Date Must Be  Greater Than Last EOD Date;Automaticaly Deleted Invalid Transation');
delete DN_TEMP_TRN_LIST WHERE TRN_DATE =to_date(x.TRN_DATE,'dd/mm/yyyy');
delete DN_TEMP_TRN_LIST_FAIL WHERE TRN_DATE =to_date(x.TRN_DATE,'dd/mm/yyyy');

end if;				       
		



     SELECT COUNT(*)
     INTO   M_SEC_COUNT
     FROM   DN_REF_SECURITY
     WHERE  EXT_SECURITY_CODE = TRIM(X.EXT_SECURITY_CODE);
     
IF M_SEC_COUNT=0 then
RAISE_APPLICATION_ERROR(-20201,'<B>***Following Security code Not Available Please Enter </B>:='||X.EXT_SECURITY_CODE);
end if;

  SELECT COUNT(*) 
  INTO  M_PF_COUNT
  FROM  DN_REF_PORTFOLIO A 
  WHERE A.CDS_ACC_NO=LPAD(X.CLIENT_CDS,11,'0');

IF M_PF_COUNT=0 then
RAISE_APPLICATION_ERROR(-20201,'<B>***Following CDS No. Not Available Please Enter </B>:='||X.CLIENT_CDS);
end if;
--- add by waruna 2011-07-26-----
SELECT COUNT(*) 
  INTO  M_PF_ACOUNT
  FROM  DN_REF_PORTFOLIO A 
  WHERE A.CDS_ACC_NO=LPAD(X.CLIENT_CDS,11,'0') and a.active_status='Y';

IF M_PF_ACOUNT=0 then
RAISE_APPLICATION_ERROR(-20201,'<B>***Following CDS No. Not Active </B>:='||X.CLIENT_CDS);
end if;
--- end add by waruna 2011-07-26-----
     SELECT COUNT(*)
     INTO   M_BRO_COUNT
     FROM   DN_REF_BROKER_MAP
     WHERE  BROKER_CODE = X.BROKER;
     
IF M_BRO_COUNT=0 then
RAISE_APPLICATION_ERROR(-20201,'<B>***BROKER_MAP Not Available Please Enter </B>:='||X.BROKER);
end if;

     IF M_SEC_COUNT>0 AND  M_BRO_COUNT>0 THEN

     SELECT  SECURITY_CODE,ISSUER_CODE,GUARANTEE_CODE,INST_TYPE,CURR_CODE,PAR_VALUE
     INTO    M_SECURITY_CODE,M_ISSUER_CODE,M_GUARANTEE_CODE,M_INST_TYPE,M_CURR_CODE,M_PAR_VALUE
     FROM    DN_REF_SECURITY
     WHERE   EXT_SECURITY_CODE = TRIM(X.EXT_SECURITY_CODE);

     SELECT DECODE(X.DEAL_TYPE,'B',DN_GET_PORTFOLIO_CODE(LPAD(X.CLIENT_CDS,11,'0')),PORTFOLIO_CODE),
            DECODE(X.DEAL_TYPE,'S',DN_GET_PORTFOLIO_CODE(LPAD(X.CLIENT_CDS,11,'0')),PORTFOLIO_CODE)
     INTO   M_B_PORT_CODE,M_S_PORT_CODE
     FROM   DN_REF_BROKER_MAP
     WHERE  BROKER_CODE = X.BROKER;
    
--RAISE_APPLICATION_ERROR(-20201,'***'||M_B_PORT_CODE);
     -- ADDED BY SVA ON 11-10-2005
     --RAISE_APPLICATION_ERROR(-20201,'***4'||M_B_PORT_CODE||X.BROKER||'**'||X.CLIENT_CDS); 
     IF  upper(M_TRN_TYPE)='B' then--if else add by waruna 2010/10/12
      
     SELECT TEMP_MARGIN_CALL_STATUS
     INTO   M_TEMP_MARGIN_CALL
     FROM   DN_REF_PORTFOLIO
     WHERE  PORTFOLIO_CODE=M_B_PORT_CODE;
   -- RAISE_APPLICATION_ERROR(-20001,'X.REF_NO - '||X.REF_NO||'-X.TRN_DATE-'||X.TRN_DATE||'M_TEMP_MARGIN_CALL'||M_TEMP_MARGIN_CALL);
    ELSE 
    M_TEMP_MARGIN_CALL:='N';
    End if;     
     


     IF M_TEMP_MARGIN_CALL='N'  THEN
     -- END OF 11-10-2005
dbms_output.put_line('M_B_PORT_CODE--> '||M_B_PORT_CODE);
dbms_output.put_line('M_S_PORT_CODE---> '||M_S_PORT_CODE);
     M_B_PF_TYPE:=DN_GET_PF_TYPE(M_B_PORT_CODE);
     M_S_PF_TYPE:=DN_GET_PF_TYPE(M_S_PORT_CODE);

--RAISE_APPLICATION_ERROR(-20001,'X.REF_NO - '||X.REF_NO||'-X.TRN_DATE-'||X.TRN_DATE);

     --IF(X.DEAL_TYPE='B') THEN---- MANJULA ON 6-9-2010
     SELECT COUNT(*)
     INTO   M_COUNT
     FROM   DN_TRN_OUTP_SALE
     WHERE  CONTRACT_NO = TO_CHAR(X.REF_NO) AND APP_STATUS<>'CANCEL' AND
      BUY_PORTFOLIO_CODE=M_B_PORT_CODE AND SELL_PORTFOLIO_CODE=M_S_PORT_CODE AND --add by waruna Sri JAyanath
     TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(X.TRN_DATE,'DD-MM-YYYY');

     IF M_COUNT = 0 THEN
     IF M_B_PF_TYPE = 'P' THEN
    dbms_output.put_line('buy');
      MBFSL_OUTRIGHT_IN1(M_DEAL_NO,M_B_PORT_CODE,M_S_PORT_CODE,M_INST_TYPE,M_SECURITY_CODE,M_GUARANTEE_CODE,
                         M_CURR_CODE,'UD',X.TRN_DATE,'Act/Act','0',
                         (X.QTY*X.PRICE)+X.BROKERAGE,X.PRICE,X.QTY,X.PRICE,M_PAR_VALUE,
                          X.BROKERAGE,M_USER_NAME,M_DEAL_NUMBER,'N',
                          'SL',NULL,'EQUTY',X.QTY*M_PAR_VALUE,X.BUY_SET,
                          X.SEL_SET,X.REF_NO,'BROKER','WD_Outrights');

      MBFSL_OUTRIGHT_IN2(M_DEAL_NO,M_SECURITY_CODE,NULL,X.QTY,'1','CURR_ACC',(X.QTY*X.PRICE)+X.BROKERAGE,
                         NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,
                         NULL,NULL,'SUB2','EQUTY',NULL,NULL,M_USER_NAME,NULL,'SL');
      M_EX_COUNT :=M_EX_COUNT+1;                   
     ELSIF  M_S_PF_TYPE = 'P' THEN
     dbms_output.put_line('sale');
      MBFSL_OUTRIGHT_IN1(M_DEAL_NO,M_B_PORT_CODE,M_S_PORT_CODE,M_INST_TYPE,M_SECURITY_CODE,M_GUARANTEE_CODE,
                         M_CURR_CODE,'UD',X.TRN_DATE,'Act/Act','0',
                         (X.QTY*X.PRICE)-X.BROKERAGE,X.PRICE,X.QTY,X.PRICE,M_PAR_VALUE,
                          X.BROKERAGE,M_USER_NAME,M_DEAL_NUMBER,'N',
                          'SL',NULL,'EQUTY',X.QTY*M_PAR_VALUE,X.BUY_SET,
                          X.SEL_SET,X.REF_NO,'BROKER','WD_Outrights');

      MBFSL_OUTRIGHT_IN2(M_DEAL_NO,M_SECURITY_CODE,NULL,X.QTY,'1','CURR_ACC',(X.QTY*X.PRICE)-X.BROKERAGE,
                         NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,
                         NULL,NULL,'SUB2','EQUTY',NULL,NULL,M_USER_NAME,NULL,'SL');
      M_EX_COUNT :=M_EX_COUNT+1;                   
     ELSE -- BUYER AND SELLER NOT PORTFOLIOS
     
        dbms_output.put_line('another');
      MBFSL_OUTRIGHT_IN1(M_DEAL_NO,M_B_PORT_CODE,M_S_PORT_CODE,M_INST_TYPE,M_SECURITY_CODE,M_GUARANTEE_CODE,
                         M_CURR_CODE,'UD',X.TRN_DATE,'Act/Act','0',
                         (X.QTY*X.PRICE)+X.BROKERAGE,X.PRICE,X.QTY,X.PRICE,M_PAR_VALUE,
                          X.BROKERAGE,M_USER_NAME,M_DEAL_NUMBER,'N',
                          'SL',NULL,'EQUTY',X.QTY*M_PAR_VALUE,X.BUY_SET,
                          X.SEL_SET,X.REF_NO,'BROKER','WD_Outrights');

      MBFSL_OUTRIGHT_IN2(M_DEAL_NO,M_SECURITY_CODE,NULL,X.QTY,'1','CURR_ACC',(X.QTY*X.PRICE)+X.BROKERAGE,
                         NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,NULL,
                         NULL,NULL,'SUB2','EQUTY',NULL,NULL,M_USER_NAME,NULL,'SL');
      M_EX_COUNT :=M_EX_COUNT+1;                   
     END IF;

     --DN_CHECK_FIGURES_OR_EQUITY(M_DEAL_NO,'');
     END IF; --CONTRACT NO COUNT = 0

     ELSE -- ADDED BY SVA ON 11-10-2005

       INSERT INTO DN_TEMP_TRN_UPLOAD_ERROR_LOG(ERROR_MSG,CONTRACT_NO,ENT_DATE)
       VALUES ('EXCEEDED THE LIMIT CLIENT CODE - '||M_B_PORT_CODE,X.REF_NO,SYSDATE) ;

     END IF; -- ADDED BY SVA ON 11-10-2005

     ELSIF M_BRO_COUNT = 0 AND M_SEC_COUNT = 0 THEN

       INSERT INTO DN_TEMP_TRN_UPLOAD_ERROR_LOG(ERROR_MSG,CONTRACT_NO,ENT_DATE)
       VALUES ('BROKER CODE AND THE SECURITY CODE NOT MAPPED -'||X.BROKER||' - '||X.EXT_SECURITY_CODE,X.REF_NO,SYSDATE) ;

     ELSIF M_BRO_COUNT = 0 THEN

       INSERT INTO DN_TEMP_TRN_UPLOAD_ERROR_LOG(ERROR_MSG,CONTRACT_NO,ENT_DATE)
       VALUES ('BROKER CODE NOT MAPPED -'||X.BROKER,X.REF_NO,SYSDATE) ;

     ELSE

       INSERT INTO DN_TEMP_TRN_UPLOAD_ERROR_LOG(ERROR_MSG,CONTRACT_NO,ENT_DATE)
       VALUES ('SECURITY CODE NOT MAPPED -'||X.EXT_SECURITY_CODE,X.REF_NO,SYSDATE) ;

     END IF;

--------------
 SELECT COUNT(*)
     INTO   MM_COUNT
     FROM   DN_TRN_OUTP_SALE
     WHERE  CONTRACT_NO     = TO_CHAR(X.REF_NO) 
     AND APP_STATUS         IN ('ENT','CONF') 
     AND  BUY_PORTFOLIO_CODE = M_B_PORT_CODE 
     AND SELL_PORTFOLIO_CODE = M_S_PORT_CODE 
     AND  EFF_VALDATE        = TO_DATE(X.TRN_DATE,'DD-MM-YYYY');
     
   DELETE FROM   DN_TEMP_TRN_LIST
   WHERE  USER_NAME = M_USER_NAME  
   AND DEAL_TYPE    = M_TRN_TYPE 
   AND REF_NO       = X.REF_NO 
   AND BROKER       = X.BROKER
   AND (MM_COUNT)>0;


--RAISE_APPLICATION_ERROR(-20001,'M_USER_NAME'||M_USER_NAME||'Count'||MM_COUNT);

-----

 END LOOP;
 ---dont use delete bellow
 --Delete FROM   DN_TEMP_TRN_LIST WHERE  USER_NAME = M_USER_NAME  AND DEAL_TYPE=M_TRN_TYPE ;--add by waruna 2010-09-15
COMMIT;
END ;

