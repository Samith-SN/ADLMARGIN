set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_SWAP_OUTRIGHT_IN1" (
    M_DEAL_NO  IN OUT    DN_TRN_SWAP_OUTRIGHT.DEAL_NO%TYPE,
  	M_BCODE              DN_TRN_SWAP_OUTRIGHT.P1_PORTFOLIO_CODE%TYPE,
    M_LCODE              DN_TRN_SWAP_OUTRIGHT.P2_PORTFOLIO_CODE%TYPE,
  	M_INSTYPE1           DN_TRN_SWAP_OUTRIGHT.P1_INST_TYPE%TYPE,
  	M_INSTYPE2           DN_TRN_SWAP_OUTRIGHT.P2_INST_TYPE%TYPE,
	M_SECIDEN1           DN_TRN_SWAP_OUTRIGHT.P1_SECURITY_CODE%TYPE,
	M_SECIDEN2           DN_TRN_SWAP_OUTRIGHT.P2_SECURITY_CODE%TYPE,
	M_ENCODE1            DN_TRN_SWAP_OUTRIGHT.P1_ENDOSER_CODE%TYPE,
	M_ENCODE2            DN_TRN_SWAP_OUTRIGHT.P2_ENDOSER_CODE%TYPE,
	M_CURR1              DN_TRN_SWAP_OUTRIGHT.P1_CURR_CODE%TYPE,
	M_CURR2              DN_TRN_SWAP_OUTRIGHT.P2_CURR_CODE%TYPE,
	M_SEL_DATETYPE1      DN_TRN_SWAP_OUTRIGHT.P1_EFF_VALDATE_TYPE%TYPE,
	M_SEL_DATETYPE2      DN_TRN_SWAP_OUTRIGHT.P2_EFF_VALDATE_TYPE%TYPE,
	M_V_DATE1            CHAR,
	M_V_DATE2            CHAR,
	M_B_CODE1            CHAR,
	M_B_CODE2            CHAR,
	M_YIELD1             DN_TRN_SWAP_OUTRIGHT.P1_YIELD%TYPE,
	M_YIELD2             DN_TRN_SWAP_OUTRIGHT.P2_YIELD%TYPE,
	M_CLEAN1             DN_TRN_SWAP_OUTRIGHT.P1_PRICE_CLEAN%TYPE,
	M_CLEAN2             DN_TRN_SWAP_OUTRIGHT.P2_PRICE_CLEAN%TYPE,
	M_DIRTY1             DN_TRN_SWAP_OUTRIGHT.P1_PRICE_DIRTY%TYPE,
	M_DIRTY2             DN_TRN_SWAP_OUTRIGHT.P2_PRICE_DIRTY%TYPE,
	M_FACEVAL1           DN_TRN_SWAP_OUTRIGHT.P1_FACE_VALUE%TYPE,
	M_FACEVAL2           DN_TRN_SWAP_OUTRIGHT.P2_FACE_VALUE%TYPE,
	M_COST1              DN_TRN_SWAP_OUTRIGHT.P1_COST%TYPE,
	M_COST2              DN_TRN_SWAP_OUTRIGHT.P2_COST%TYPE,
	M_ACCINT1            DN_TRN_SWAP_OUTRIGHT.P1_ACC_INT%TYPE,
	M_ACCINT2            DN_TRN_SWAP_OUTRIGHT.P2_ACC_INT%TYPE,
	M_SETVAL1            DN_TRN_SWAP_OUTRIGHT.P1_SETTLE_VALUE%TYPE,
 	M_SETVAL2            DN_TRN_SWAP_OUTRIGHT.P2_SETTLE_VALUE%TYPE,
	M_NETAMT1            DN_TRN_SWAP_OUTRIGHT.P1_NET_AMOUNT_DUE%TYPE,
 	M_NETAMT2            DN_TRN_SWAP_OUTRIGHT.P2_NET_AMOUNT_DUE%TYPE,
    M_USERNAME           DN_TRN_SWAP_OUTRIGHT.DN_USER%TYPE,
    M_DEAL_NUMBER        DN_TRN_SWAP_OUTRIGHT.DEAL_NO%TYPE
)

AS

   M_USER             DN_TRN_SWAP_OUTRIGHT.DN_USER%TYPE;
   M_VAL_DATE1        DN_TRN_SWAP_OUTRIGHT.P1_EFF_VALDATE%TYPE;
   M_VAL_DATE2        DN_TRN_SWAP_OUTRIGHT.P2_EFF_VALDATE%TYPE;
   M_BASIS1           DN_TRN_SWAP_OUTRIGHT.P1_INT_RATE_BASE_CODE%TYPE;
   M_BASIS2           DN_TRN_SWAP_OUTRIGHT.P2_INT_RATE_BASE_CODE%TYPE;

BEGIN

    --RAISE_APPLICATION_ERROR(-20201,M_IS_DATE||' '||M_BASIS);

    -- PROCEDURE  -  TO INSERT SWAPS OUTRIGHT DETAILS
    -- SYSTEM     -  MBFSL SYSTEM
    -- CREATED BY -  V.THILAKESAN.
    -- CREATED ON -  16/07/1999

    IF SUBSTR(M_USERNAME,1,1)=' ' OR M_USERNAME IS NULL THEN
       M_USER:='Un Identify';
    ELSE
       M_USER:=M_USERNAME;
    END IF;
    --TO select the value date
    IF M_SEL_DATETYPE1<>'UD' THEN
       SELECT DN_FIN_EFF_VALDATE(M_SEL_DATETYPE1) INTO M_VAL_DATE1 FROM DUAL;
    ELSE
       SELECT TO_DATE(M_V_DATE1,'DD/MM/YYYY') INTO M_VAL_DATE1 FROM DUAL;
    END IF;
    IF M_SEL_DATETYPE2<>'UD' THEN
       SELECT DN_FIN_EFF_VALDATE(M_SEL_DATETYPE2) INTO M_VAL_DATE2 FROM DUAL;
    ELSE
       SELECT TO_DATE(M_V_DATE2,'DD/MM/YYYY') INTO M_VAL_DATE2 FROM DUAL;
    END IF;
    --To select the base code
    SELECT INT_RATE_BASE_CODE INTO M_BASIS1 FROM DN_REF_INTR_BASE WHERE INTR_BASE_DESC=M_B_CODE1;
    SELECT INT_RATE_BASE_CODE INTO M_BASIS2 FROM DN_REF_INTR_BASE WHERE INTR_BASE_DESC=M_B_CODE2;

    --To create the new sequence
    IF M_DEAL_NUMBER IS NULL THEN
       SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_SWAP_OUTR.NEXTVAL),3,'0') INTO M_DEAL_NO FROM DUAL;
       M_DEAL_NO:=  'SO'||M_DEAL_NO;
    ELSE
       M_DEAL_NO:=M_DEAL_NUMBER;
    END IF;


    IF M_DEAL_NO IS NOT NULL THEN

       UPDATE DN_TRN_SWAP_OUTRIGHT
       SET P1_PORTFOLIO_CODE     =M_BCODE,
           P2_PORTFOLIO_CODE     =M_LCODE,
  	       P1_INST_TYPE          =M_INSTYPE1,
  	       P2_INST_TYPE          =M_INSTYPE2,
	       P1_SECURITY_CODE      =M_SECIDEN1,
	       P2_SECURITY_CODE      =M_SECIDEN2,
	       P1_ENDOSER_CODE       =M_ENCODE1,
	       P2_ENDOSER_CODE       =M_ENCODE2,
	       P1_CURR_CODE          =M_CURR1,
	       P2_CURR_CODE          =M_CURR2,
	       P1_EFF_VALDATE_TYPE   =M_SEL_DATETYPE1,
	       P2_EFF_VALDATE_TYPE   =M_SEL_DATETYPE2,
	       P1_EFF_VALDATE        =M_VAL_DATE1,
	       P2_EFF_VALDATE        =M_VAL_DATE2,
	       P1_INT_RATE_BASE_CODE =M_BASIS1,
	       P2_INT_RATE_BASE_CODE =M_BASIS2,
	       P1_YIELD              =M_YIELD1,
	       P2_YIELD              =M_YIELD2,
	       P1_PRICE_CLEAN        =M_CLEAN1,
	       P2_PRICE_CLEAN        =M_CLEAN2,
	       P1_PRICE_DIRTY        =M_DIRTY1,
	       P2_PRICE_DIRTY        =M_DIRTY2,
	       P1_FACE_VALUE         =M_FACEVAL1,
	       P2_FACE_VALUE         =M_FACEVAL2,
	       P1_COST               =M_COST1,
	       P2_COST               =M_COST2,
	       P1_ACC_INT            =M_ACCINT1,
 	       P2_ACC_INT            =M_ACCINT2,
	       P1_SETTLE_VALUE       =M_SETVAL1,
	       P2_SETTLE_VALUE       =M_SETVAL2,
	       P1_NET_AMOUNT_DUE     =M_NETAMT1,
	       P2_NET_AMOUNT_DUE     =M_NETAMT2,
           DN_USER               =M_USER
       WHERE
           DEAL_NO=M_DEAL_NO
           AND
           APP_STATUS='ENT';

       IF SQL%NOTFOUND THEN
          INSERT INTO DN_TRN_SWAP_OUTRIGHT
          (DEAL_NO,
           P1_PORTFOLIO_CODE,
           P2_PORTFOLIO_CODE,
  	       P1_INST_TYPE,
  	       P2_INST_TYPE,
	       P1_SECURITY_CODE,
	       P2_SECURITY_CODE,
	       P1_ENDOSER_CODE,
	       P2_ENDOSER_CODE,
	       P1_CURR_CODE,
	       P2_CURR_CODE,
	       P1_EFF_VALDATE_TYPE,
	       P2_EFF_VALDATE_TYPE,
	       P1_EFF_VALDATE,
	       P2_EFF_VALDATE,
	       P1_INT_RATE_BASE_CODE,
	       P2_INT_RATE_BASE_CODE,
	       P1_YIELD,
	       P2_YIELD,
	       P1_PRICE_CLEAN,
	       P2_PRICE_CLEAN,
	       P1_PRICE_DIRTY,
	       P2_PRICE_DIRTY,
	       P1_FACE_VALUE,
	       P2_FACE_VALUE,
	       P1_COST,
	       P2_COST,
	       P1_ACC_INT,
 	       P2_ACC_INT,
	       P1_SETTLE_VALUE,
	       P2_SETTLE_VALUE,
	       P1_NET_AMOUNT_DUE,
	       P2_NET_AMOUNT_DUE,
           DN_USER
          )
          VALUES(
           M_DEAL_NO,
           M_BCODE,
           M_LCODE,
  	       M_INSTYPE1,
  	       M_INSTYPE2,
	       M_SECIDEN1,
	       M_SECIDEN2,
	       M_ENCODE1,
	       M_ENCODE2,
	       M_CURR1,
	       M_CURR2,
	       M_SEL_DATETYPE1,
	       M_SEL_DATETYPE2,
	       M_VAL_DATE1,
	       M_VAL_DATE2,
	       M_BASIS1,
	       M_BASIS2,
	       M_YIELD1,
	       M_YIELD2,
	       M_CLEAN1,
	       M_CLEAN2,
	       M_DIRTY1,
	       M_DIRTY2,
	       M_FACEVAL1,
	       M_FACEVAL2,
	       M_COST1,
	       M_COST2,
	       M_ACCINT1,
 	       M_ACCINT2,
	       M_SETVAL1,
	       M_SETVAL2,
	       M_NETAMT1,
	       M_NETAMT2,
           M_USER
           );
       END IF;
       COMMIT;
   END IF;

 EXCEPTION
  WHEN OTHERS THEN
   --If the data type is incorrect then delete the records from the relavent tables

   DELETE DN_TRN_BROKERAGE
   WHERE
   DEAL_NO=M_DEAL_NO;

   DELETE DN_TRN_SWAP_OUTRIGHT_SETTLE
   WHERE
   DEAL_NO=M_DEAL_NO;

   DELETE DN_TRN_SWAP_OUTRIGHT_SEC
   WHERE
   DEAL_NO=M_DEAL_NO;

   DELETE DN_TRN_SWAP_OUTRIGHT
   WHERE
   DEAL_NO=M_DEAL_NO;

   COMMIT;

   RAISE_APPLICATION_ERROR(-20201,'Data error');


END MBFSL_SWAP_OUTRIGHT_IN1;

