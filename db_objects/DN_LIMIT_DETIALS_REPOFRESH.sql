--------------------------------------------------------
--  DDL for Procedure DN_LIMIT_DETIALS_REPOFRESH
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_LIMIT_DETIALS_REPOFRESH" 
(
  M_TENOR                    DN_TRN_REPO_FRESH.TENOR%TYPE,
  M_DETAILS_CURSOR  IN  OUT  DN_PACKAGE_FRESH.LIMIT_DETAILS_CURSOR
)
AS

ROW_COUNT   NUMBER;

BEGIN

/*
created by   : dayan
date created : 10/02/2000
purpose      :  get limit details for repofresh
*/

/*###########################################################################################################*/
SELECT COUNT(*) INTO
ROW_COUNT
FROM LMT_UTL_OVRL_EXP A,
LMT_STR_OVRL_EXPO B,
LMT_ACT_DETAILS C
WHERE M_TENOR BETWEEN A.START_DAYS AND A.END_DAYS AND
A.START_DAYS=B.START_DAYS AND
A.END_DAYS=B.END_DAYS AND
B.LIMIT_CODE=C.LIMIT_CODE AND
C.LIMIT_TYPE='03' AND
C.ACTIVE_STATUS='Y';

IF(ROW_COUNT>0) THEN
OPEN M_DETAILS_CURSOR FOR
 SELECT
 B.LIMIT_CODE,
 A.START_DAYS,
 A.END_DAYS,
 TO_CHAR(B.START_AMOUNT,'FM999G999G999G999G990D00'),
 NVL(TO_CHAR(B.END_AMOUNT,'FM999G999G999G999G990D00'),'0.00'),
 A.CURRENT_UTILIZATION
 FROM LMT_UTL_OVRL_EXP A,
 LMT_STR_OVRL_EXPO B,
 LMT_ACT_DETAILS C
 WHERE M_TENOR BETWEEN A.START_DAYS AND A.END_DAYS AND
 A.START_DAYS=B.START_DAYS AND
 A.END_DAYS=B.END_DAYS AND
 B.LIMIT_CODE=C.LIMIT_CODE AND
 C.LIMIT_TYPE='03' AND
 C.ACTIVE_STATUS='Y';

ELSE
OPEN M_DETAILS_CURSOR FOR
SELECT
LIMIT_CODE,
START_DAYS,
END_DAYS,
START_AMOUNT,
END_AMOUNT,
'0.00'
FROM LMT_STR_OVRL_EXPO
WHERE LIMIT_CODE='03-0001';
END IF;

END DN_LIMIT_DETIALS_REPOFRESH;

/
