set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_INV_EXCH_BACKEND_MAIN_V1" 
(
M_INV_EXCHG_NO         DN_TRN_BO_INV_EXCHANGE.INV_EXCHG_NO%TYPE,
M_ALLO_DEAL_NO         DN_TRN_BO_INV_EXCHANGE.ALLO_DEAL_NO%TYPE,
M_PORTFOLIO_CODE       DN_TRN_BO_INV_EXCHANGE.PORTFOLIO_CODE%TYPE,
M_PARTALLO_STAT        VARCHAR2 --$$##SC
)

AS

--PROCEDURE  - DN_INVENTORY EXCHANGE MAIN CALLING PROCEDURE
--SYSTEM     - DEALNET
--CREATED BY - TDS / SM
--CREATED ON - 04/11/1999

M_BORR_PORTFOLIO_CODE           DN_TRN_REPO_FRESH.BORR_PORTFOLIO_CODE%TYPE;
M_LEND_PORTFOLIO_CODE           DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE;
--M_COUNP_LOCATION                DN_TRN_REPO_FRESH.BORR_PORTFOLIO_CODE%TYPE; --ADDED BY SM ON 25/05/2000 TO REMEDY ERRORS IN LOCATION SUBSEQUENT TO AN 'EXCHANGE'
M_DELIVERY                      DN_TRN_REPO_FRESH.PHYSICAL_DELIVERY%TYPE; --ADDED BY SM ON 25/05/2000 TO REMEDY ERRORS IN LOCATION SUBSEQUENT TO AN 'EXCHANGE'
M_SCRIPT_STATUS                 DN_TRN_REPO_FRESH.SCRIPT_STATUS%TYPE;--$$##SC
BEGIN

---------------CALLING BACK END PROCEDURES WHICH UPDATE INVENTORY  RELATED INFO
--RAISE_APPLICATION_ERROR(-20201,'*** '||M_INV_EXCHG_NO||'| '||M_ALLO_DEAL_NO||'| '||M_PORTFOLIO_CODE);


    IF SUBSTR(M_ALLO_DEAL_NO,1,2)='RF' THEN

        SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE,PHYSICAL_DELIVERY,SCRIPT_STATUS--$$##SC
        INTO   M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE,M_DELIVERY,M_SCRIPT_STATUS
        FROM   DN_TRN_REPO_FRESH
        WHERE  DEAL_NO=M_ALLO_DEAL_NO;


       IF M_PORTFOLIO_CODE=M_BORR_PORTFOLIO_CODE THEN
          --PROCEDURE TO BE CALLED WHEN TRAN TYPE IS 'RP' AND 'BORROWER'
          IF M_DELIVERY = 'Y' THEN
          DN_BO_INV_EXCH_RP_I(M_INV_EXCHG_NO,M_LEND_PORTFOLIO_CODE);  --SECOND VARIABLE ADDED BY SM ON 25/05/2000
          ELSE
          DN_BO_INV_EXCH_RP_I(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);
           /*IF (M_SCRIPT_STATUS='SC' OR M_PARTALLO_STAT='0') THEN--$$##SC
             DN_BO_INV_EXCH_RP_I(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);
           ELSE--$$##SC
             DN_BO_INV_EXCH_RP_I_SL(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);--$$##SC
           END IF;--$$##SC
           */



          END IF;

       ELSE
          --PROCEDURE TO BE CALLED WHEN TRAN TYPE IS 'RP' AND 'LENDER'
          IF M_DELIVERY = 'Y' THEN
          DN_BO_INV_EXCH_RP_R(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);
          ELSE
          DN_BO_INV_EXCH_RP_R(M_INV_EXCHG_NO,M_LEND_PORTFOLIO_CODE);
          END IF;

       END IF;


   ELSIF SUBSTR(M_ALLO_DEAL_NO,1,2)='RR' THEN

        SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE,PHYSICAL_DELIVERY
        INTO   M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE,M_DELIVERY
        FROM   DN_TRN_REPO_ROLLOVER
        WHERE  DEAL_NO=M_ALLO_DEAL_NO;

       IF M_PORTFOLIO_CODE=M_BORR_PORTFOLIO_CODE THEN
          --PROCEDURE TO BE CALLED WHEN TRAN TYPE IS 'RP' AND 'BORROWER'
          IF M_DELIVERY = 'Y' THEN
          DN_BO_INV_EXCH_RP_I(M_INV_EXCHG_NO,M_LEND_PORTFOLIO_CODE);
          ELSE
          DN_BO_INV_EXCH_RP_I(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);
          /*IF (M_SCRIPT_STATUS='SC' OR M_PARTALLO_STAT='0') THEN--$$##SC
              DN_BO_INV_EXCH_RP_I(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);
           ELSE--$$##SC
              DN_BO_INV_EXCH_RP_I_SL(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);--$$##SC
           END IF;--$$##SC
          */
          END IF;

       ELSE
          --PROCEDURE TO BE CALLED WHEN TRAN TYPE IS 'RP' AND 'LENDER'
          IF M_DELIVERY = 'Y' THEN
          DN_BO_INV_EXCH_RP_R(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);
          ELSE
          DN_BO_INV_EXCH_RP_R(M_INV_EXCHG_NO,M_LEND_PORTFOLIO_CODE);
          END IF;

       END IF;


    ELSIF SUBSTR(M_ALLO_DEAL_NO,1,2)='BF' THEN

        SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE,PHYSICAL_DELIVERY
        INTO   M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE,M_DELIVERY
        FROM   DN_TRN_BL_FUND
        WHERE  DEAL_NO=M_ALLO_DEAL_NO;

       IF M_PORTFOLIO_CODE=M_BORR_PORTFOLIO_CODE THEN
          --PROCEDURE TO BE CALLED WHEN TRAN TYPE IS 'BL' AND 'BORROWER'
          IF M_DELIVERY = 'Y' THEN
          DN_BO_INV_EXCH_BL_I(M_INV_EXCHG_NO,M_LEND_PORTFOLIO_CODE);
          ELSE
          DN_BO_INV_EXCH_BL_I(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);
          END IF;

       ELSE
          --PROCEDURE TO BE CALLED WHEN TRAN TYPE IS 'BL' AND 'LENDER'
          IF M_DELIVERY = 'Y' THEN
          DN_BO_INV_EXCH_BL_R(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);
          ELSE
          DN_BO_INV_EXCH_BL_R(M_INV_EXCHG_NO,M_LEND_PORTFOLIO_CODE);
          END IF;

       END IF;

     ELSIF SUBSTR(M_ALLO_DEAL_NO,1,2)='BS' THEN

        SELECT BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE,PHYSICAL_DELIVERY
        INTO   M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE,M_DELIVERY
        FROM   DN_TRN_BL_SECURITY
        WHERE  DEAL_NO=M_ALLO_DEAL_NO;

       IF M_PORTFOLIO_CODE=M_BORR_PORTFOLIO_CODE THEN
          --PROCEDURE TO BE CALLED WHEN TRAN TYPE IS 'BL' AND 'BORROWER'
          IF M_DELIVERY = 'Y' THEN
          DN_BO_INV_EXCH_BL_R(M_INV_EXCHG_NO,M_LEND_PORTFOLIO_CODE);
          ELSE
          DN_BO_INV_EXCH_BL_R(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);
          END IF;

       ELSE
          --PROCEDURE TO BE CALLED WHEN TRAN TYPE IS 'BL' AND 'LENDER'
          IF M_DELIVERY = 'Y' THEN
          DN_BO_INV_EXCH_BL_I(M_INV_EXCHG_NO,M_BORR_PORTFOLIO_CODE);
          ELSE
          DN_BO_INV_EXCH_BL_I(M_INV_EXCHG_NO,M_LEND_PORTFOLIO_CODE);
          END IF;

       END IF;

    END IF;



---------------


COMMIT;

END DN_INV_EXCH_BACKEND_MAIN_V1 ;

