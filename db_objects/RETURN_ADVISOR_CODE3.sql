  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RETURN_ADVISOR_CODE3" 
(
  M_PORTFOLIO_CODE		DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE
)
RETURN VARCHAR2

AS
M_PF_CODE VARCHAR2(20):='-';

BEGIN

SELECT DISTINCT NVL(A.ADV_CODE,'-')
INTO   M_PF_CODE
FROM   DN_REF_ADVISOR A,DN_REF_PORT_ADV B
WHERE  UPPER(B.PORT_CODE)=UPPER(M_PORTFOLIO_CODE) AND B.ADV_CODE = A.ADV_CODE ;


RETURN M_PF_CODE;

END return_advisor_code3;

/
