  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_FIN_PI_YIELD_PRICE_DIRTY" 
  (
    M_DIRTY_PRICE         DN_TRN_OUTP_SALE.PRICE_CLEAN%TYPE,
    M_EFF_VALDATE         DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE,
    M_INT_RATE_BASE_CODE  DN_TRN_OUTP_SALE.INT_RATE_BASE_CODE%TYPE,
    M_MATURITY_DATE       DN_TRN_REPO_PERIOD_INT.MATURITY_DATE%TYPE,
    M_COUPON_INT          DN_TRN_REPO_PERIOD_INT.TENOR%TYPE,
    M_FREQUENCY           NUMBER,
    M_SEQNO               VARCHAR2
   )

   RETURN  REAL

   IS

    -- Function     : This returns YEILD for the req.yield (periodic interst)
    -- System       : DealNet System
    -- Created by   : V.Thilakesan.
    -- Created on   : 13/3/2000

   M_RETVAL                     NUMBER;
   M_CLEAN_PRICE                NUMBER;

BEGIN

 SELECT
    M_DIRTY_PRICE-DN_FIN_PI_INT_ACCURAL(M_EFF_VALDATE,M_COUPON_INT,M_SEQNO)
    INTO M_CLEAN_PRICE
  FROM DUAL;

  --DBMS_OUTPUT.PUT_LINE('M_CLEAN_PRICE  '||TO_CHAR(M_CLEAN_PRICE));

   SELECT
      DN_FIN_PI_YIELD_PRICE_CLEAN(M_CLEAN_PRICE,M_EFF_VALDATE,M_INT_RATE_BASE_CODE,M_MATURITY_DATE,M_COUPON_INT,M_FREQUENCY,M_SEQNO)
      INTO M_RETVAL
    FROM DUAL;

   --RETURN M_RETVAL;
  RETURN ROUND(M_RETVAL,6);

END DN_FIN_PI_YIELD_PRICE_DIRTY;

