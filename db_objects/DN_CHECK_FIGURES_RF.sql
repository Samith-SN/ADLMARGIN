set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CHECK_FIGURES_RF" 
(
M_DEAL_NO    DN_TRN_REPO_FRESH.DEAL_NO%TYPE,
M_SECTION    CHAR
)
AS
--M_STAT1                         VARCHAR2(1);
M_COUNT1                        NUMBER;
M_NO_OF_SETTL_MODES             DN_TRN_REPO_FRESH.NO_OF_SETTL_MODES%TYPE;
M_LEG1_VALUE1                   DN_TRN_REPO_FRESH.LEG1_VALUE%TYPE;
M_LEG1_VALUE2                   DN_TRN_REPO_FRESH.LEG1_VALUE%TYPE;
M_COUNT_INTRUMENT               NUMBER;
M_TENOR1                        DN_TRN_REPO_FRESH.TENOR%TYPE;
M_TENOR2                        DN_TRN_REPO_FRESH.TENOR%TYPE;
M_INTEREST1                     DN_TRN_REPO_FRESH.INT_AMOUNT%TYPE;
M_INTEREST2                     DN_TRN_REPO_FRESH.INT_AMOUNT%TYPE;
M_COUNT_NEW1                     NUMBER;
M_COUNT_NEW2                     NUMBER;
M_COUNT_NEW3                     NUMBER;
M_COUNT_NEW4                     NUMBER;
M_COUNT_NEW5                     NUMBER;
M_INT_AMOUNT                     NUMBER(20,4);
err_num   varchar2(200);
err_msg   varchar2(200);

BEGIN
--M_STAT1 :='N';


--IF(M_SECTION = '1')THEN

SELECT  COUNT(*) --'Y'------------------------1
INTO    M_COUNT_NEW1 --M_STAT1
FROM    DN_TRN_REPO_FRESH
WHERE   DEAL_NO=M_DEAL_NO AND
        LEG1_VALUE > 0 AND  LEG2_VALUE >0 AND  INT_AMOUNT >= 0 ;

IF(M_COUNT_NEW1<=0)THEN --M_STAT1='N'
RAISE_APPLICATION_ERROR(-20201,'FACE_VALUE ,COST ,SETTLE_VALUE SHOULD BE GREATER THAN ZERO !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;

SELECT  COUNT(*)--TENOR, TO_NUMBER(MATURITY_DATE-EFF_VALDATE)   ------------------------2
INTO    M_COUNT_NEW2--M_TENOR1,M_TENOR2
FROM    DN_TRN_REPO_FRESH
WHERE   DEAL_NO=M_DEAL_NO AND TENOR=TO_NUMBER(MATURITY_DATE-EFF_VALDATE) ;

IF(M_COUNT_NEW2<=0)THEN --M_TENOR1<>M_TENOR2
RAISE_APPLICATION_ERROR(-20201,'INCORRECT VALUE FOR TENOR !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;


/*SELECT ROUND(((LEG1_VALUE*YIELD)/DN_FIN_INT_RATE_BASE_DATES(INT_RATE_BASE_CODE,EFF_VALDATE))*TENOR,2)
INTO   M_INT_AMOUNT
FROM   DUAL;
*/
SELECT COUNT(*)--DN_FIN_INT_AMT_F_LEG1_LEG2(LEG1_VALUE,LEG2_VALUE,TENOR,INT_RATE_BASE_CODE),INT_AMOUNT-------3
INTO   M_COUNT_NEW3--M_INTEREST1,M_INTEREST2
FROM   DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_DEAL_NO AND
      ABS( ROUND(((LEG1_VALUE*YIELD)/DN_FIN_INT_RATE_BASE_DATES(INT_RATE_BASE_CODE,EFF_VALDATE))*TENOR,2)- INT_AMOUNT)>2 ;

IF(M_COUNT_NEW3>0)THEN--M_INTEREST1<>M_INTEREST2
RAISE_APPLICATION_ERROR(-20201,'INCORRECT INTEREST AMOUNT !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;


 SELECT COUNT(*)--------------------------4
 INTO   M_COUNT_INTRUMENT
 FROM   DN_TRN_REPO_FRESH_INST
 WHERE  DEAL_NO=M_DEAL_NO;

IF(M_COUNT_INTRUMENT<=0)THEN
RAISE_APPLICATION_ERROR(-20201,'NO RECORD FOUND IN INSTRUMENT TABLE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;



--ELSIF (M_SECTION = '2') THEN

SELECT COUNT(*)------------------------1
INTO   M_COUNT1
FROM   DN_TRN_REPO_FRESH_SETTLE
WHERE  DEAL_NO=M_DEAL_NO;

IF M_COUNT1<=0 THEN
RAISE_APPLICATION_ERROR(-20201,'NO RECORD FOUND IN SETTLE TABLE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;


SELECT COUNT(*) -----------------------2
INTO   M_COUNT_NEW4
FROM   DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_DEAL_NO;
IF (M_COUNT_NEW4>0)THEN
SELECT NO_OF_SETTL_MODES
INTO   M_NO_OF_SETTL_MODES
FROM   DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_DEAL_NO;
IF M_NO_OF_SETTL_MODES <= 0 THEN
RAISE_APPLICATION_ERROR(-20201,'NO_OF_SETTL_MODES SHOULD BE GREATER THAN ZERO!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;

ELSE
RAISE_APPLICATION_ERROR(-20201,'NO_RECORD EXISTS IN DN_TRN_REPO_FRESH TABLE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;


SELECT COUNT(*)--------------------------------3
INTO  M_COUNT_NEW5
FROM  DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_DEAL_NO AND
       LEG1_VALUE=(SELECT SUM(SETTLE_AMOUNT)
                    FROM   DN_TRN_REPO_FRESH_SETTLE
                    WHERE    DEAL_NO=M_DEAL_NO
                    GROUP BY DEAL_NO );


SELECT   LEG1_VALUE--------------------------------3
INTO     M_LEG1_VALUE1
FROM     DN_TRN_REPO_FRESH
WHERE    DEAL_NO=M_DEAL_NO;

SELECT   SUM(SETTLE_AMOUNT)
INTO     M_LEG1_VALUE2
FROM     DN_TRN_REPO_FRESH_SETTLE
WHERE    DEAL_NO=M_DEAL_NO
GROUP BY DEAL_NO ;

IF (M_LEG1_VALUE1 <> M_LEG1_VALUE2 ) THEN--(M_LEG1_VALUE1 <> M_LEG1_VALUE2 )
RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN SETTLE_VALUE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;

-- ADDED ON 13-05-2004 TO CHECK LEG2 VALUE
--NILU
SELECT   ABS((LEG2_VALUE-LEG1_VALUE)-INT_AMOUNT)
INTO     M_LEG1_VALUE1
FROM     DN_TRN_REPO_FRESH
WHERE    DEAL_NO=M_DEAL_NO;

IF (M_LEG1_VALUE1 > 1 ) THEN--(M_LEG1_VALUE1 <> M_LEG1_VALUE2 )
RAISE_APPLICATION_ERROR(-20201,'INCORRECT LEG2 VALUE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;
-- END 13-05-2004

--END IF;

EXCEPTION
  WHEN OTHERS THEN


  --ROLLBACK;
--RAISE_APPLICATION_ERROR(-20201,'*****66666******');

DELETE DN_TRN_DEAL_CURRENCY
 WHERE
    DEAL_NO=M_DEAL_NO;
 DELETE DN_TRN_REPO_FRESH_SETTLE
    WHERE
    DEAL_NO=M_DEAL_NO;

 DELETE DN_TRN_REPO_FRESH_SERIAL_NO
    WHERE
    DEAL_NO=M_DEAL_NO;
 DELETE DN_TRN_REPO_FRESH_SEC
    WHERE
    DEAL_NO=M_DEAL_NO;

 DELETE DN_TRN_REPO_FRESH_INST
    WHERE
    DEAL_NO=M_DEAL_NO;

  /* DELETE DN_TRN_REPO_FRESH  --commented and add the below query on 21-01-2004 by nirmala
    WHERE
    DEAL_NO=M_DEAL_NO;*/
    UPDATE DN_TRN_REPO_FRESH
    SET APP_STATUS='CANCEL'
   WHERE DEAL_NO=M_DEAL_NO;

   err_num :=  substr(SQLCODE,1,15);
   err_msg := substr(SQLERRM,1,200) ;
  INSERT INTO DN_REF_SEQUENCE_LOG VALUES (M_DEAL_NO,err_num||''||err_msg,'ERROR IN REPOFRESH2',SYSDATE);
  COMMIT;
 RAISE_APPLICATION_ERROR(-20201,SQLCODE||SQLERRM);


END DN_CHECK_FIGURES_RF;

