  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_G_5" 
(
M_DOCREFNO        DN_TRN_REPO_FRESH.DEAL_NO%TYPE
)
AS

  /* PROCEDURE  - DN_ACC_B_2_7  Reverce
   SYSTEM     - DEALNET
   CREATED BY - Waruna Sri Jaynatah
   CREATED ON - 27/FEB/2012*/


M_PORTF_CODE        DN_TRN_BO_CAP_DEPOSIT.PORTFOLIO_CODE%TYPE;
M_TRNAMOUNT            DN_TRN_BO_CAP_DEPOSIT.TRNAMOUNT%TYPE;
M_TRNDATE               DN_TRN_BO_CAP_DEPOSIT.EFF_VAL_DATE%TYPE;
M_LICENCEE_BRANCH_CODE  DN_TRN_BO_CAP_DEPOSIT.LICENCEE_BRANCH_CODE%TYPE;
M_LICENCEE_ACCOUNT_NO   DN_TRN_BO_CAP_DEPOSIT.LICENEE_ACCOUNT_NO%TYPE;
M_ACC_SYS_REFNO         DN_REF_LICENCEE_SETTLEMENT.ACC_SYS_REFNO %TYPE;
BEGIN
-------IF THE DEAL AVAILABLE IN THE REBATE------------
IF SUBSTR(M_DOCREFNO,1,2)='CW' THEN

    SELECT PORTFOLIO_CODE,EFF_VAL_DATE,TRNAMOUNT,LICENCEE_BRANCH_CODE,LICENEE_ACCOUNT_NO
    INTO M_PORTF_CODE,M_TRNDATE,M_TRNAMOUNT,M_LICENCEE_BRANCH_CODE,M_LICENCEE_ACCOUNT_NO
    FROM DN_TRN_BO_CAP_DEPOSIT
    WHERE DOCREFNO=M_DOCREFNO;

 SELECT
 ACC_SYS_REFNO
 INTO M_ACC_SYS_REFNO
 FROM DN_REF_LICENCEE_SETTLEMENT
 WHERE BRANCH_CODE=M_LICENCEE_BRANCH_CODE
 AND ACC_NO = M_LICENCEE_ACCOUNT_NO
 AND ACTIVE_STATUS ='Y';

INSERT INTO DN_ACC_PORTF_GEN_ACCOUNT
  (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
  VALUES(M_PORTF_CODE,M_PORTF_CODE,M_TRNDATE,'600','CR',M_TRNAMOUNT,M_DOCREFNO,'PAYMENT TO PORTFOLIO','350');
INSERT INTO DN_ACC_PORTF_GEN_ACCOUNT
  (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
  VALUES(M_PORTF_CODE,M_PORTF_CODE,M_TRNDATE,'350','DR',M_TRNAMOUNT,M_DOCREFNO,'PAYMENT TO PORTFOLIO','600');

INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
  (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
  VALUES('GEN',M_PORTF_CODE,M_TRNDATE,'301','CR',M_TRNAMOUNT,M_DOCREFNO,'PAYMENT TO PORTFOLIO','800');
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
  (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,ACC_SYS_REFNO,PROC_DESC,CORR_ACC_NO)
  VALUES('GEN',M_PORTF_CODE,M_TRNDATE,'800','DR',M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO,'PAYMENT TO PORTFOLIO','301');

END IF;

END ; 

