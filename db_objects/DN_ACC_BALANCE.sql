--  DDL for Procedure DN_ACC_BALANCE
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_BALANCE" 
(
  M_ENT_DATE     VARCHAR2
)
AS


CURSOR LICENCEE_SUM IS
 SELECT A.PORTFOLIO_CODE PORTFOLIO_CODE,
        NVL(A.ACC_TYPE_CODE,'0') ACC_TYPE_CODE,
        NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
        NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT,
        A.DRCR_STATUS DRCR_STATUS,
        TO_CHAR(A.TRNDATE,'DD-MON-YYYY') TRNDATE,
        NULL ACC_SYS_REFNO,
        NULL ACC_NO,
        NULL BRANCH_NAME
 FROM   DN_ACC_LICENCEE_INST_ACCOUNT A
 WHERE  --TO_DATE(TO_CHAR(A.TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY')=M_ENT_DATE AND
        A.TRNDATE=TO_DATE(M_ENT_DATE,'DD-MM-YYYY') AND
        A.ACC_TYPE_CODE<>'800'
 GROUP BY  A.PORTFOLIO_CODE,A.ACC_TYPE_CODE,TO_CHAR(A.TRNDATE,'DD-MON-YYYY'),A.DRCR_STATUS
 UNION ALL
 SELECT A.PORTFOLIO_CODE PORTFOLIO_CODE,
        NVL(A.ACC_TYPE_CODE,'0') ACC_TYPE_CODE,
        NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
        NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT,
        A.DRCR_STATUS DRCR_STATUS,
        TO_CHAR(A.TRNDATE,'DD-MON-YYYY') TRNDATE,
        NULL ACC_SYS_REFNO,
        NULL ACC_NO,
        NULL BRANCH_NAME
 FROM   DN_ACC_LICENCEE_GEN_ACCOUNT A
 WHERE  --TO_DATE(TO_CHAR(A.TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY')=M_ENT_DATE AND
        A.TRNDATE=TO_DATE(M_ENT_DATE,'DD-MM-YYYY') AND
        A.ACC_TYPE_CODE<>'800'
 GROUP BY  A.PORTFOLIO_CODE,A.ACC_TYPE_CODE,TO_CHAR(A.TRNDATE,'DD-MON-YYYY'),A.DRCR_STATUS
 UNION ALL
 SELECT A.PORTFOLIO_CODE PORTFOLIO_CODE,NVL(A.ACC_TYPE_CODE,'0') ACC_TYPE_CODE,
        NVL(SUM(DECODE(A.DRCR_STATUS,'DR',A.TRNAMOUNT)),0) DRTOT,
        NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT,
        A.DRCR_STATUS DRCR_STATUS,
        TO_CHAR(A.TRNDATE,'DD-MON-YYYY') TRNDATE,
        A.ACC_SYS_REFNO ACC_SYS_REFNO,
        G.ACC_NO ACC_NO,
        D.BRANCH_NAME BRANCH_NAME
 FROM   DN_ACC_LICENCEE_GEN_ACCOUNT A,
        DN_REF_BANK D,
        DN_REF_LICENCEE_SETTLEMENT G
 WHERE  --TO_DATE(TO_CHAR(A.TRNDATE,'DD-MON-YYYY'),'DD-MON-YYYY')=M_ENT_DATE AND
        A.TRNDATE=TO_DATE(M_ENT_DATE,'DD-MM-YYYY') AND
        A.ACC_TYPE_CODE='800' AND
        A.ACC_SYS_REFNO=G.ACC_SYS_REFNO AND
        G.BRANCH_CODE=D.BRANCH_CODE

 GROUP BY  A.PORTFOLIO_CODE,A.ACC_TYPE_CODE,TO_CHAR(A.TRNDATE,'DD-MON-YYYY'), A.ACC_SYS_REFNO,G.ACC_NO,D.BRANCH_NAME,A.DRCR_STATUS
 --ORDER BY 1,2
 ;

M_PORTFOLIO_CODE       DN_ACC_LICEN_INST_GEN_SUM.PORTFOLIO_CODE%TYPE;
M_TRNDATE              DN_ACC_LICEN_INST_GEN_SUM.TRNDATE%TYPE;
M_ACC_TYPE_CODE        DN_ACC_LICEN_INST_GEN_SUM.ACC_TYPE_CODE%TYPE;
M_DRCR_STATUS          DN_ACC_LICEN_INST_GEN_SUM.DRCR_STATUS%TYPE;
M_TRNAMOUNT            DN_ACC_LICEN_INST_GEN_SUM.TRNAMOUNT%TYPE;
M_DRTOT                DN_ACC_LICEN_INST_GEN_SUM.TRNAMOUNT%TYPE;
M_CRTOT                DN_ACC_LICEN_INST_GEN_SUM.TRNAMOUNT%TYPE;
M_COUNT1               DN_ACC_LICEN_INST_GEN_SUM.TRNAMOUNT%TYPE;
M_COUNT2               DN_ACC_LICEN_INST_GEN_SUM.TRNAMOUNT%TYPE;
M_ACC_SYS_REFNO        DN_REF_LICENCEE_SETTLEMENT.ACC_SYS_REFNO%TYPE;
M_ACC_NO               DN_REF_LICENCEE_SETTLEMENT.ACC_NO%TYPE;
M_BRANCH_NAME          DN_REF_BANK.BRANCH_NAME%TYPE;


BEGIN
FOR I IN LICENCEE_SUM
LOOP

 M_PORTFOLIO_CODE:=I.PORTFOLIO_CODE;
 M_ACC_TYPE_CODE:=I.ACC_TYPE_CODE;
 M_DRTOT:=I.DRTOT;
 M_CRTOT:=I.CRTOT;
 M_DRCR_STATUS:=I.DRCR_STATUS;
 M_TRNDATE:=I.TRNDATE;
 M_ACC_SYS_REFNO:=I.ACC_SYS_REFNO;
 M_ACC_NO:=I.ACC_NO;
 M_BRANCH_NAME:=I.BRANCH_NAME;


-------------------(1)-------------------------
IF M_PORTFOLIO_CODE IS NOT NULL AND M_ACC_TYPE_CODE <> 0 THEN
 M_TRNAMOUNT:=0;

  IF(I.ACC_TYPE_CODE<>'800')THEN
  SELECT  COUNT(*)
  INTO    M_COUNT1
  FROM    DN_ACC_LICEN_INST_GEN_SUM
  WHERE   PORTFOLIO_CODE =M_PORTFOLIO_CODE  AND
          TRNDATE        =M_TRNDATE AND
          ACC_TYPE_CODE  =M_ACC_TYPE_CODE AND
          DRCR_STATUS    =M_DRCR_STATUS AND
          TO_DATE(TO_CHAR(ENTDATE,'DD-MM-YYYY'),'DD-MM-YYYY') =TO_DATE(M_ENT_DATE,'DD-MM-YYYY')  ;

   IF  M_COUNT1 > 0    THEN
    SELECT  NVL(TRNAMOUNT,0)
    INTO    M_TRNAMOUNT
    FROM    DN_ACC_LICEN_INST_GEN_SUM
    WHERE   PORTFOLIO_CODE =M_PORTFOLIO_CODE  AND
            TRNDATE        =M_TRNDATE AND
            ACC_TYPE_CODE  =M_ACC_TYPE_CODE AND
            DRCR_STATUS    =M_DRCR_STATUS AND
            TO_DATE(TO_CHAR(ENTDATE,'DD-MM-YYYY'),'DD-MM-YYYY') =TO_DATE(M_ENT_DATE,'DD-MM-YYYY') ;
   ELSE
      M_TRNAMOUNT:=0;
   END IF;

  ELSE

  SELECT  COUNT(*)
  INTO    M_COUNT2
  FROM    DN_ACC_LICEN_INST_GEN_SUM
  WHERE   PORTFOLIO_CODE =M_PORTFOLIO_CODE  AND
          TRNDATE        =M_TRNDATE AND
          ACC_TYPE_CODE  =M_ACC_TYPE_CODE AND
          DRCR_STATUS    =M_DRCR_STATUS AND
          ACC_SYS_REFNO  =M_ACC_SYS_REFNO AND
          ACC_NO         =M_ACC_NO AND
          BRANCH_NAME    =M_BRANCH_NAME AND
          TO_DATE(TO_CHAR(ENTDATE,'DD-MM-YYYY'),'DD-MM-YYYY') =TO_DATE(M_ENT_DATE,'DD-MM-YYYY');

 IF  M_COUNT2 > 0    THEN
    SELECT  NVL(TRNAMOUNT,0)
    INTO    M_TRNAMOUNT
    FROM    DN_ACC_LICEN_INST_GEN_SUM
    WHERE   PORTFOLIO_CODE =M_PORTFOLIO_CODE  AND
            TRNDATE        =M_TRNDATE AND
            ACC_TYPE_CODE  =M_ACC_TYPE_CODE AND
            DRCR_STATUS    =M_DRCR_STATUS AND
            ACC_SYS_REFNO  =M_ACC_SYS_REFNO AND
            ACC_NO         =M_ACC_NO AND
            BRANCH_NAME    =M_BRANCH_NAME AND
            TO_DATE(TO_CHAR(ENTDATE,'DD-MM-YYYY'),'DD-MM-YYYY') =TO_DATE(M_ENT_DATE,'DD-MM-YYYY');
  ELSE
      M_TRNAMOUNT:=0;
  END IF;

END IF;

  IF I.DRCR_STATUS= 'DR' THEN
     M_TRNAMOUNT := M_DRTOT + M_TRNAMOUNT;
  ELSE
     M_TRNAMOUNT := M_CRTOT + M_TRNAMOUNT;
  END IF;


  IF M_TRNAMOUNT > 0 THEN
    UPDATE DN_ACC_LICEN_INST_GEN_SUM
       SET TRNAMOUNT      =M_TRNAMOUNT
     WHERE PORTFOLIO_CODE =M_PORTFOLIO_CODE  AND
           TRNDATE        =M_TRNDATE AND
           ACC_TYPE_CODE  =M_ACC_TYPE_CODE AND
           DRCR_STATUS    =M_DRCR_STATUS AND
           ACC_SYS_REFNO  =M_ACC_SYS_REFNO AND
           ACC_NO         =M_ACC_NO AND
           BRANCH_NAME    =M_BRANCH_NAME AND
           TO_DATE(TO_CHAR(ENTDATE,'DD-MM-YYYY'),'DD-MM-YYYY') =TO_DATE(M_ENT_DATE,'DD-MM-YYYY');

   IF SQL%NOTFOUND THEN
     INSERT INTO DN_ACC_LICEN_INST_GEN_SUM
           (PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,ACC_SYS_REFNO,ACC_NO,BRANCH_NAME,ENTDATE)
     VALUES
           (M_PORTFOLIO_CODE,M_TRNDATE,M_ACC_TYPE_CODE,M_DRCR_STATUS,M_TRNAMOUNT,M_ACC_SYS_REFNO,M_ACC_NO,M_BRANCH_NAME,TO_DATE(M_ENT_DATE,'DD-MM-YYYY'));
   END IF;
  END IF;
 END IF;
END LOOP;

------------------------------------------
DN_ACC_DETAILS(M_ENT_DATE);
--------------------------------------
END DN_ACC_BALANCE;

