  INTO M_GROUP_NET_COUNT
  FROM DN_MAS_SETLE_GROUP_NET A 
  WHERE A.GROUP_NET_NO = M_PAYMENT_NO; 
  
  IF M_GROUP_NET_COUNT > 0 THEN 
  
