set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CHECK_FIGURES_OR" 
(
M_DEAL_NO    DN_TRN_OUTP_SALE.DEAL_NO%TYPE,
M_SECTION    CHAR
)
AS
M_SECURITY_CODE                  DN_TRN_OUTP_SALE.SECURITY_CODE%TYPE;
M_EFF_VALDATE                    DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE;
M_PRICE_CLEAN                    DN_TRN_OUTP_SALE.PRICE_CLEAN%TYPE;
M_FACE_VALUE                     DN_TRN_OUTP_SALE.FACE_VALUE%TYPE;
M_SETTLE_VALUE                   DN_TRN_OUTP_SALE.SETTLE_VALUE%TYPE;
MM_SETTLE_VALUE                  DN_TRN_OUTP_SALE.SETTLE_VALUE%TYPE;
M_STAT1                          VARCHAR2(1);
M_COUNT1                         NUMBER;
M_NO_OF_SETTL_MODES              DN_TRN_OUTP_SALE.NO_OF_SETTL_MODES%TYPE;
M_SETTLE_VALUE1                  NUMBER;
M_SETTLE_VALUE2                  NUMBER;
M_SETTLE_COUNT                   NUMBER;
M_SECTAB_TOT                     DN_TRN_OUTP_SALE.FACE_VALUE%TYPE;
MSL_SCRIPT_STATUS                  DN_TRN_OUTP_SALE.SCRIPT_STATUS%TYPE;
MSL_FACE_VALUE                     DN_TRN_OUTP_SALE.FACE_VALUE%TYPE;
MSL_COUNT                         NUMBER;
MM_PRICE_CLEAN                      DN_TRN_OUTP_SALE.PRICE_CLEAN%TYPE;
M_YIELD                            DN_TRN_OUTP_SALE.YIELD%TYPE;
M_INT_RATE_BASE_CODE               DN_TRN_OUTP_SALE.INT_RATE_BASE_CODE%TYPE;

err_num   varchar2(200);
err_msg   varchar2(200);
M_SL_COUNT2 number;
BEGIN
M_STAT1 :='N';

--IF(M_SECTION = '1')THEN

/*SELECT COUNT(*)
INTO   MSL_COUNT
FROM   DN_TRN_OUTP_SALE
WHERE  APP_STATUS = 'ENT';
*/

SELECT  'Y'------------------------1
INTO    M_STAT1
FROM    DN_TRN_OUTP_SALE
WHERE   DEAL_NO=M_DEAL_NO AND
        FACE_VALUE > 0 AND  COST >0 AND  SETTLE_VALUE > 0 ;

IF(M_STAT1='N')THEN
RAISE_APPLICATION_ERROR(-20201,'FACE_VALUE ,COST ,SETTLE_VALUE SHOULD BE GREATER THAN ZERO !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
END IF;


 SELECT SECURITY_CODE,EFF_VALDATE,PRICE_CLEAN,FACE_VALUE ,SETTLE_VALUE,YIELD,INT_RATE_BASE_CODE-------------------2
 INTO   M_SECURITY_CODE,M_EFF_VALDATE,M_PRICE_CLEAN,M_FACE_VALUE,M_SETTLE_VALUE,M_YIELD,M_INT_RATE_BASE_CODE
 FROM   DN_TRN_OUTP_SALE
 WHERE  DEAL_NO=M_DEAL_NO;

SELECT GET_FIN_COST_ACCINT_SETVAL(M_SECURITY_CODE,M_PRICE_CLEAN,TO_CHAR(M_EFF_VALDATE,'DD-MM-YYYY'),M_FACE_VALUE)
INTO   MM_SETTLE_VALUE
FROM   DUAL;

IF(TO_NUMBER(M_SETTLE_VALUE)<>TO_NUMBER(MM_SETTLE_VALUE))THEN
RAISE_APPLICATION_ERROR(-20201,M_SETTLE_VALUE||'***'||MM_SETTLE_VALUE||' '||M_SECURITY_CODE||' '||M_PRICE_CLEAN||' '||M_EFF_VALDATE||' '||M_FACE_VALUE||'INCORRECT SETTLEMENT VALUE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

SELECT DN_FIN_PRICE_CLEAN_YIELD(M_SECURITY_CODE,M_YIELD,TO_DATE(TO_CHAR(M_EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY'),M_INT_RATE_BASE_CODE)
INTO   MM_PRICE_CLEAN
FROM   DUAL;


IF(ABS(MM_PRICE_CLEAN-M_PRICE_CLEAN)>.1 )THEN
RAISE_APPLICATION_ERROR(-20201,MM_PRICE_CLEAN||'***'||M_PRICE_CLEAN||' '||M_SECURITY_CODE||' '||M_INT_RATE_BASE_CODE||' '||M_EFF_VALDATE||' '||M_FACE_VALUE||'INCORRECT VALUE FOR CLEANPRICE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

--ELSIF (M_SECTION = '2') THEN

SELECT COUNT(*)------------------------1
INTO   M_COUNT1
FROM   DN_TRN_OUTP_SALE_SETTLE
WHERE  DEAL_NO=M_DEAL_NO;

IF M_COUNT1<=0 THEN
RAISE_APPLICATION_ERROR(-20201,'NO RECORD FOUND IN SETTLE TABLE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

SELECT NO_OF_SETTL_MODES -----------------------2
INTO   M_NO_OF_SETTL_MODES
FROM   DN_TRN_OUTP_SALE
WHERE  DEAL_NO=M_DEAL_NO;

IF M_NO_OF_SETTL_MODES <= 0 THEN
RAISE_APPLICATION_ERROR(-20201,'NO_OF_SETTL_MODES SHOULD BE GREATER THAN ZERO!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

SELECT   SETTLE_VALUE
INTO     M_SETTLE_VALUE1
FROM     DN_TRN_OUTP_SALE
WHERE    DEAL_NO=M_DEAL_NO;

SELECT   SUM(SETTLE_AMOUNT),COUNT(*)
INTO     M_SETTLE_VALUE2,M_SETTLE_COUNT
FROM     DN_TRN_OUTP_SALE_SETTLE
WHERE    DEAL_NO=M_DEAL_NO
GROUP BY DEAL_NO ;

IF M_SETTLE_COUNT=0 THEN
  RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN SETTLE_VALUE!! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

IF M_SETTLE_VALUE1 <> M_SETTLE_VALUE2 THEN
  RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN SETTLE_VALUE  !! PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY ');
END IF;

--------------------------FOR SCRIPLESS------------------------------------------------

SELECT  COUNT(*)--$$##SC
INTO    MSL_COUNT
FROM    DN_TRN_OUTP_SALE A,DN_REF_PORTFOLIO B
WHERE   A.DEAL_NO=M_DEAL_NO  AND
        A.SELL_PORTFOLIO_CODE=B.PORTFOLIO_CODE AND
        B.PF_TYPE='P' AND B.ACTIVE_STATUS='Y';


IF MSL_COUNT>0 THEN

SELECT  SCRIPT_STATUS,FACE_VALUE
INTO    MSL_SCRIPT_STATUS,MSL_FACE_VALUE
FROM    DN_TRN_OUTP_SALE
WHERE   DEAL_NO=M_DEAL_NO   ;

IF MSL_SCRIPT_STATUS='SL' THEN


SELECT COUNT(DEAL_NO)
 INTO   M_SL_COUNT2
 FROM   DN_TRN_OUTP_SALE_SEC
 WHERE  DEAL_NO=M_DEAL_NO;
 --GROUP BY DEAL_NO;

 IF M_SL_COUNT2 >0 THEN
 SELECT SUM(FACE_VALUE)
 INTO   M_SECTAB_TOT
 FROM   DN_TRN_OUTP_SALE_SEC
 WHERE  DEAL_NO=M_DEAL_NO
 GROUP BY DEAL_NO;

   IF MSL_FACE_VALUE <> M_SECTAB_TOT THEN
        RAISE_APPLICATION_ERROR(-20201,'MISMATCH IN TOTAL VALUE OF THE DN_TRN_OUTP_SALE_SEC TABLE AND FACE VALUE IN DN_TRN_OUTP_SALE TABLE!! ');
   END IF;

END IF;
END IF;
END IF;--COUNT
