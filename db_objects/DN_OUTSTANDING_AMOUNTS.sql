--------------------------------------------------------
--  DDL for Function DN_OUTSTANDING_AMOUNTS
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_OUTSTANDING_AMOUNTS" 
 (  M_DEALNO   IN VARCHAR2,
    M_TODATE   IN VARCHAR2,
    M_FRMDATE  IN VARCHAR2,
    BORROWER   IN VARCHAR2,
    LENDER     IN VARCHAR2,
    M_TABLE    IN VARCHAR2)
  RETURN  NUMBER IS
    --
    -- Purpose: This function will return the current Outstanding Amount
    --
    -- Created By :
    -- Person      Date           Comments
    -- Siva        28-07-2000
    -- ---------   ----------     -------------------------------------------
   ----------------------------------------------------------------------------------------------
OUTSTANDAMT   NUMBER DEFAULT 0;
LOANTAKE      NUMBER DEFAULT 0;
LOANSETT      NUMBER DEFAULT 0;
PREMATAMT     NUMBER DEFAULT 0;
PREMATLEG1    NUMBER DEFAULT 0;
PREMATEFFDATE DATE;
PREMATCHK     NUMBER;
ORIGDEALNO    VARCHAR2(20);
ORIGEFFDATE   DATE;
ORIGYIELD     NUMBER;
ORIGBASIS     VARCHAR2(10);
M_CNT         NUMBER;

BEGIN
----

SELECT COUNT(*) INTO PREMATCHK FROM(SELECT ORIGINALDEAL_NO FROM DN_TRN_PREMATURE_SETTLE
WHERE (ORIGINALDEAL_NO=M_DEALNO));

 IF PREMATCHK =0 THEN

     IF M_TABLE = 'FRESH' THEN
        LOANTAKE:=0;
        SELECT A.LEG1_VALUE INTO LOANTAKE
        FROM DN_TRN_REPO_FRESH A
        WHERE A.DEAL_NO=M_DEALNO;

        LOANSETT:=0;
/*        SELECT NVL(SUM(LEG1VALUE),0) INTO LOANSETT FROM(
        SELECT NVL(SUM(A.LEG1_VALUE),0) LEG1VALUE
        FROM  CSADMIN.WEBDN_TRN_REPO_FRESH A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA','CS')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY')
        );
*/
    END IF;

     IF M_TABLE = 'ROLLOVER' THEN
        LOANTAKE:=0;
        SELECT A.LEG1_VALUE INTO LOANTAKE
        FROM DN_TRN_REPO_ROLLOVER A
        WHERE A.DEAL_NO =M_DEALNO ;

        LOANSETT:=0;
/*        SELECT NVL(SUM(LEG1VALUE),0) INTO LOANSETT FROM(
        SELECT NVL(SUM(A.LEG1_VALUE),0) LEG1VALUE
        FROM CSADMIN.WEBDN_TRN_REPO_ROLLOVER A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA','CS')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY')
        );
*/
    END IF;
    IF M_TABLE = 'BL_FUND' THEN

        LOANTAKE:=0;

        SELECT A.LEG1_VALUE INTO LOANTAKE
        FROM DN_TRN_BL_FUND A
        WHERE A.DEAL_NO = M_DEALNO ;

        LOANSETT:=0;
/*        SELECT NVL(SUM(LEG1VALUE),0) INTO LOANSETT FROM(
        SELECT NVL(SUM(A.LEG1_VALUE),0) LEG1VALUE
        FROM CSADMIN.WEBDN_TRN_BL_FUND A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA','CS')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY')
        );
*/
        ----
    END IF;
   ELSE
     IF M_TABLE = 'FRESH' THEN
        LOANTAKE:=0;
        SELECT A.LEG1_VALUE INTO LOANTAKE
        FROM DN_TRN_REPO_FRESH A
        WHERE A.DEAL_NO=M_DEALNO;

        ---Pre Mature Calculation
        PREMATAMT:=0;
        FOR PREMATREC IN (SELECT * FROM DN_TRN_PREMATURE_SETTLE
        WHERE (ORIGINALDEAL_NO=M_DEALNO)) LOOP
--        RAISE_APPLICATION_ERROR(-20000,M_DEALNO);

        SELECT COUNT(*) INTO M_CNT FROM(
        SELECT A.LEG1_VALUE,A.EFF_VALDATE
        FROM DN_TRN_REPO_FRESH A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA','CS')
        AND (A.APP_STATUS <> 'CANCEL')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY'));

        IF M_CNT >0 THEN
        SELECT * INTO PREMATLEG1,PREMATEFFDATE FROM (
        SELECT A.LEG1_VALUE,A.EFF_VALDATE
        FROM DN_TRN_REPO_FRESH A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA','CS')
        AND (A.APP_STATUS <> 'CANCEL')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY'));


        SELECT * INTO ORIGEFFDATE,ORIGYIELD,ORIGBASIS FROM (
        SELECT A.EFF_VALDATE,YIELD,INT_RATE_BASE_CODE
        FROM DN_TRN_REPO_FRESH A
        WHERE A.LEND_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE = BORROWER
        AND A.DEAL_NO=PREMATREC.ORIGINALDEAL_NO
        AND A.LEND_PORTFOLIO_CODE  IN('LANDM','CEYLEC','FMA','CS')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY'));
         PREMATAMT:=PREMATAMT+DN_FIN_LEG1_F_LEG2(PREMATLEG1,ORIGYIELD,(PREMATEFFDATE-ORIGEFFDATE),ORIGBASIS,ORIGEFFDATE);
        END IF;

       END LOOP;
       ----End of PreMat Calculation----


    END IF;

     IF M_TABLE = 'ROLLOVER' THEN
        LOANTAKE:=0;
        SELECT A.LEG1_VALUE INTO LOANTAKE
        FROM DN_TRN_REPO_ROLLOVER A
        WHERE A.DEAL_NO =M_DEALNO ;

        ---Pre Mature Calculation
        PREMATAMT:=0;
        FOR PREMATREC IN (SELECT * FROM DN_TRN_PREMATURE_SETTLE
        WHERE (ORIGINALDEAL_NO=M_DEALNO)) LOOP

        SELECT COUNT(*) INTO M_CNT FROM (
        SELECT A.LEG1_VALUE,A.EFF_VALDATE
        FROM DN_TRN_REPO_FRESH A --CHANGED FROM 'ROLLOVER' BECAUSE ALL REPO PRE MAT SETTLEMENTS WILL BE DONE THROUGH THE REPO FRESH TABLE
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA','CS')
        AND (A.APP_STATUS <> 'CANCEL')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY'));

        IF M_CNT>0 THEN
        SELECT A.LEG1_VALUE,A.EFF_VALDATE INTO PREMATLEG1,PREMATEFFDATE
        FROM DN_TRN_REPO_FRESH A --CHANGED FROM 'ROLLOVER' BECAUSE ALL REPO PRE MAT SETTLEMENTS WILL BE DONE THROUGH THE REPO FRESH TABLE
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA','CS')
        AND (A.APP_STATUS <> 'CANCEL')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY');

        SELECT A.EFF_VALDATE,YEILD,INT_RATE_BASE_CODE INTO ORIGEFFDATE,ORIGYIELD,ORIGBASIS
        FROM DN_TRN_REPO_ROLLOVER A
        WHERE A.LEND_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE = BORROWER
        AND A.DEAL_NO=PREMATREC.ORIGINALDEAL_NO
        AND A.LEND_PORTFOLIO_CODE  IN('LANDM','CEYLEC','FMA','CS')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY');

        PREMATAMT:= PREMATAMT+DN_FIN_LEG1_F_LEG2(PREMATLEG1,ORIGYIELD,(PREMATEFFDATE-ORIGEFFDATE),ORIGBASIS,ORIGEFFDATE);
        END IF;
       END LOOP;
      ----End of PreMat Calculation----

    END IF;
    IF M_TABLE = 'BL_FUND' THEN
        LOANTAKE:=0;
        SELECT A.LEG1_VALUE INTO LOANTAKE
        FROM DN_TRN_BL_FUND A
        WHERE A.DEAL_NO=M_DEALNO ;

        ---Pre Mature Calculation
        PREMATAMT:=0;
        FOR PREMATREC IN (SELECT * FROM DN_TRN_PREMATURE_SETTLE
        WHERE (ORIGINALDEAL_NO=M_DEALNO)) LOOP

        SELECT COUNT(*) INTO M_CNT FROM(
        SELECT A.LEG1_VALUE,A.EFF_VALDATE
        FROM DN_TRN_BL_FUND A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA','CS')
        AND (A.APP_STATUS <> 'CANCEL')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY'));

        IF M_CNT>0 THEN
        SELECT A.LEG1_VALUE,A.EFF_VALDATE INTO PREMATLEG1,PREMATEFFDATE
        FROM DN_TRN_BL_FUND A
        WHERE A.LEND_PORTFOLIO_CODE = BORROWER
        AND A.BORR_PORTFOLIO_CODE = LENDER
        AND A.DEAL_NO=PREMATREC.PREMATSETTLEDEAL_NO
        AND A.BORR_PORTFOLIO_CODE IN('LANDM','CEYLEC','FMA','CS')
        AND (A.APP_STATUS <> 'CANCEL')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY');

        SELECT A.EFF_VALDATE,YEILD_PER_NET/100,INT_RATE_BASE_CODE
        INTO ORIGEFFDATE,ORIGYIELD,ORIGBASIS
        FROM DN_TRN_BL_FUND A
        WHERE A.LEND_PORTFOLIO_CODE = LENDER
        AND A.BORR_PORTFOLIO_CODE = BORROWER
        AND A.DEAL_NO=PREMATREC.ORIGINALDEAL_NO
        AND A.LEND_PORTFOLIO_CODE  IN('LANDM','CEYLEC','FMA','CS')
        AND TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD-MON-YYYY'),'DD-MON-YYYY') <= TO_DATE(M_TODATE,'DD-MM-YYYY')
        AND TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY') > TO_DATE(M_FRMDATE,'DD-MM-YYYY');

        PREMATAMT:=PREMATAMT+DN_FIN_LEG1_F_LEG2(PREMATLEG1,ORIGYIELD,(PREMATEFFDATE-ORIGEFFDATE),ORIGBASIS,ORIGEFFDATE);
        END IF;
        END LOOP;
--       RAISE_APPLICATION_ERROR(-20000,M_DEALNO||'-'||LOANTAKE||'-'||LOANSETT||'-'||PREMATAMT);
       ----End of PreMat Calculation----
       ----
    END IF;


   END IF;
     IF LOANTAKE IS NULL THEN
        LOANTAKE:=0;
     END IF;
     IF LOANSETT IS NULL THEN
         LOANSETT:=0;
     END IF;
     IF PREMATAMT IS NULL THEN
         PREMATAMT:=0;
     END IF;

    OUTSTANDAMT:=0;

    OUTSTANDAMT:=LOANTAKE-LOANSETT-PREMATAMT;

    IF ABS(OUTSTANDAMT) < 2 THEN
         OUTSTANDAMT:=0.00;
    END IF;

    RETURN OUTSTANDAMT ;
/*EXCEPTION
   WHEN OTHERS THEN
       NULL;*/
END; -- Function WD_OUTSTANDING_AMOUNTS

