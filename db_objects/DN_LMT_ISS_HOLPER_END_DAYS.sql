  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_LMT_ISS_HOLPER_END_DAYS" 
(
 M_MAT_END_DAYS        LMT_STR_ISSUER_INST_HOL_PERIOD.END_DAYS%TYPE,
 M_ISSUER_CODE           LMT_STR_ISSUER_INST_HOL_PERIOD.ISSUER_CODE%TYPE,
 M_LIAB_TYPE               LMT_STR_ISSUER_INST_HOL_PERIOD.ISSUER_LIABILITY_TYPE%TYPE,
 M_INST_TYPE             LMT_STR_ISSUER_INST_HOL_PERIOD.INST_TYPE%TYPE


 )

 RETURN  INTEGER

IS

          -- FUNCTION     : THIS RETURNS END DAY;
          -- SYSTEM       : DEALNET SYSTEM
          -- CREATED BY   : SUKATHIS
          -- CREATED ON   : 24/01/2000

 M_RETURN_DAYS       INTEGER;

BEGIN
SELECT DISTINCT MIN(END_DAYS) INTO M_RETURN_DAYS
    FROM LMT_STR_ISSUER_INST_HOL_PERIOD
    WHERE END_DAYS>=M_MAT_END_DAYS
    AND ISSUER_CODE=M_ISSUER_CODE AND
                 INST_TYPE=M_INST_TYPE AND
                  ISSUER_LIABILITY_TYPE=M_LIAB_TYPE  ;

RETURN M_RETURN_DAYS;

END DN_LMT_ISS_HOLPER_END_DAYS;

