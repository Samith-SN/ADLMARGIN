  INSERT INTO DN_ACC_PORTF_GEN_ACCOUNT
          (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
  VALUES
          (M_DN_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'123','DR',M_TRNAMOUNT,M_DOCREFNO,'DIVIDEND RECEIVABLE','122');--CHANGED ENTRY NO 2 T 'M_DN_PORTF_CODE' FROM 'M_PORTF_CODE'

  INSERT INTO DN_ACC_PORTF_INST_ACCOUNT
          (PORTFOLIO_CODE,INST_TYPE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
  VALUES
          (M_DN_PORTF_CODE,M_INST,M_TRNDATE,'122','CR',M_TRNAMOUNT,M_DOCREFNO,'DIVIDEND RECEIVABLE','123');  --CHANGED TO "RECEIVABLE" FROM "INCOME" ON 11/02/2005 BY SM




