--------------------------------------------------------
--  DDL for Procedure DN_LIMIT_DAYEND_OVRL_TRA_ISSUE
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_LIMIT_DAYEND_OVRL_TRA_ISSUE" 
 (
	M_ROUTINE_DATE		DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE

	)
	IS

       /*
	   PURPOSE OF THE PROCEDURE : DAY END ROUTINE FOR THE OVRALL_TRADING_BY_ISSUER
	   CREATED BY :DAYAN
       DATE: 2000/01/05
       COMMENT: THIS DOES CONTAIN A CURSOR
	   */

CURSOR ISSUER_CURSOR IS
          SELECT B.ISSUER_CODE,SUM(A.FACE_VALUE)
          FROM   DN_TRN_OUTP_SALE A,
                 DN_REF_SECURITY B
          WHERE  A.SECURITY_CODE=B.SECURITY_CODE  AND
                 A.EFF_VALDATE<=M_ROUTINE_DATE    AND
			     B.MATURITY_DATE>=M_ROUTINE_DATE
          GROUP BY B.ISSUER_CODE;

	 M_FACE_VALUE       NUMBER;
	 M_LIMIT_CODE       VARCHAR2(25);
	 M_COUNT            NUMBER;
	 M_ENTERED_AMT      NUMBER;
	 M_AUCTION_TYPE     VARCHAR2(1);
	 M_ISSUER_CODE	    VARCHAR2(15);
	 M_ISSUER_LIA_TYPE  VARCHAR2(25);
	 M_INST_TYPE 		VARCHAR2(25);
	 M_TOT_FACE         NUMBER;
	 M_LMT_COUNT1		NUMBER;
	 M_LMT_COUNT2		NUMBER;
	 M_COUNT1           NUMBER;

BEGIN
  M_TOT_FACE:=0;
 /*@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@THIS IS TO UPDATE HISTORY TABLE@@@@@@@@@@@@@@@@*/
	INSERT INTO LMT_EXC_HIS
	(LIMIT_CODE,VIOLATED_DATE,VIOLATED_BY,ACTIVATED_TYPE,HIS_ACTIVATED_TYPE)
	SELECT LIMIT_CODE,VIOLATED_DATE,VIOLATED_BY,ACTIVATED_TYPE,ACTIVATED_TYPE
	FROM LMT_EXC_CURRENT
	WHERE SUBSTR(LIMIT_CODE,1,2)='04';

/*$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$THIS IS TO DELETE ACTUAL VIOLATION$$$$$$$$$$$$$$*/

  DELETE LMT_EXC_CURRENT
	WHERE SUBSTR(LIMIT_CODE,1,2)='04';

/*$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$THIS IS TO DELETE POSSIBLE VIOLATION$$$$$$$$$$$$$$*/

	DELETE LMT_EXC_UNCONF
	WHERE SUBSTR(LIMIT_CODE,1,2)='04';

	OPEN ISSUER_CURSOR;
  LOOP
    FETCH ISSUER_CURSOR INTO M_ISSUER_CODE,M_FACE_VALUE ;
	  EXIT WHEN ISSUER_CURSOR%NOTFOUND;

	/* RAISE_APPLICATION_ERROR(-20201,M_ISSUER_CODE||' '|| M_FACE_VALUE);*/

	/*THIS TO SELECT RELEVENT LIMIT CODE FROM THE TABLE*/

	 SELECT  COUNT(*)
     INTO    M_LMT_COUNT1
     FROM    LMT_STR_ISSUER_INST_AMT
     WHERE   M_FACE_VALUE BETWEEN START_AMOUNT AND END_AMOUNT
             AND CONDITION='B'
             AND SUBSTR(LIMIT_CODE,4,4)=M_ISSUER_CODE;

	 IF(M_LMT_COUNT1>0) THEN
	     SELECT LIMIT_CODE
         INTO   M_LIMIT_CODE
         FROM   LMT_STR_ISSUER_INST_AMT
         WHERE  M_FACE_VALUE BETWEEN START_AMOUNT AND END_AMOUNT
                AND CONDITION='B'
                AND SUBSTR(LIMIT_CODE,4,4)=M_ISSUER_CODE;
	 ELSE
	     SELECT COUNT(*)
         INTO   M_LMT_COUNT2
         FROM   LMT_STR_ISSUER_INST_AMT
         WHERE  M_FACE_VALUE BETWEEN START_AMOUNT AND END_AMOUNT
                AND CONDITION='G'
                AND SUBSTR(LIMIT_CODE,4,4)=M_ISSUER_CODE;

	            IF(M_LMT_COUNT2>0)THEN
		              SELECT LIMIT_CODE
                      INTO   M_LIMIT_CODE
                      FROM   LMT_STR_ISSUER_INST_AMT
	                  WHERE  M_FACE_VALUE BETWEEN START_AMOUNT AND END_AMOUNT
                             AND CONDITION='G'
	                         AND SUBSTR(LIMIT_CODE,4,4)=M_ISSUER_CODE;
		        END IF;
	 END IF;


	/*###################################THIS TO CHECK WHETHER SELECTED LMIT_CODE IS ACTIVATED#############*/
	  IF(M_LMT_COUNT1>0 OR M_LMT_COUNT2>0 ) THEN

	/*@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@SELECT NECCESSARY DETAILS FROM THE LMT_STR_ISSUER_INST_AMT#########*/
		SELECT COUNT(*)
        INTO   M_COUNT1
	    FROM   LMT_STR_ISSUER_INST_AMT
	    WHERE  LIMIT_CODE=M_LIMIT_CODE;

		IF(M_COUNT1>0) THEN
             SELECT AUCTION_TYPE,ISSUER_CODE,ISSUER_LIABILITY_TYPE,INST_TYPE
             INTO   M_AUCTION_TYPE,M_ISSUER_CODE,M_ISSUER_LIA_TYPE,M_INST_TYPE
	         FROM   LMT_STR_ISSUER_INST_AMT
	         WHERE  LIMIT_CODE=M_LIMIT_CODE;
        END IF;

		    SELECT COUNT(*)
            INTO   M_COUNT
            FROM   LMT_ACT_DETAILS
            WHERE  LIMIT_CODE=M_LIMIT_CODE
                   AND ACTIVE_STATUS='Y';

	/*$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$*/
	  IF(M_COUNT=0)THEN
	        UPDATE   LMT_EXC_CURRENT
			SET      LIMIT_CODE=M_LIMIT_CODE,
			         VIOLATED_DATE=M_ROUTINE_DATE,
			         ACTIVATED_TYPE='Y'
			WHERE    LIMIT_CODE=M_LIMIT_CODE ;

		    IF SQL%NOTFOUND THEN
			  INSERT INTO LMT_EXC_CURRENT
	            (LIMIT_CODE,VIOLATED_DATE,ACTIVATED_TYPE)
	          VALUES
	            (M_LIMIT_CODE,M_ROUTINE_DATE,'Y');
			END IF;
	  END IF;
  END IF;
	 	M_TOT_FACE:=M_TOT_FACE+M_FACE_VALUE;

  END LOOP;
  CLOSE ISSUER_CURSOR;

 /*@@@@@@@@@@@@@@@@@@@@@@@@@@ THIS IS TO UPDATE LMT_UTL_OVRL_MAT TABLE@@@@@@@@@@@@@@@@@@@ */
  UPDATE LMT_UTL_ISSUER_INST_AMT
	SET
	BF_UTILIZATION=0,
	DEAL_INFLOW=0,
	DEAL_OUTFLOW=0,
	CURRENT_UTILIZATION=M_TOT_FACE,
	ROW_ID=1
  WHERE
	LIMIT_TYPE='04'AND
	AUCTION_TYPE=M_AUCTION_TYPE AND
	ISSUER_CODE=M_ISSUER_CODE AND
	ISSUER_LIABILITY_TYPE=M_ISSUER_LIA_TYPE AND
	INST_TYPE=M_INST_TYPE;

 /*COMMIT;*/
END DN_LIMIT_DAYEND_OVRL_TRA_ISSUE;

