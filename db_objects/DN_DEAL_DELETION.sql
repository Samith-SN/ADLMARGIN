set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_DEAL_DELETION" 
(M_DEAL_NO     DN_TRN_REPO_FRESH.DEAL_NO%TYPE,
 M_USER        DN_TIME_LOG.DN_USER%TYPE
 )

AS


----PROCEDURE TO DELETE DEALS THAT HAVE BEEN ALREADY CONFIRMED
----CREATED TO ELIMITATE THE TIME SPENT BY SASIANET IN RECTIFYING THESE DEALS AS IDENTIFIED IN NUMEROUS REQUEST FORMS
----AND TO ENABLE ANY MEMBER OF SASIANET TO ATTEND TO THESE REQUESTS (TO ELIMINATE THE REQUIREMENT OF DOMAIN KNOWLEDGE)
----PENDING : CUSTODIAL DELETION / ACCOUNTING TABLE ENTRIES
----CREATED BY SM ON 20/08/2003



ERR_NUM             VARCHAR2(200);
ERR_MSG             VARCHAR2(200);
M_PAYMENT_NO        DN_TRN_BO_SETTL_PAYMENT.PAYMENT_NO%TYPE;
M_REC_NO            DN_TRN_BO_SETTL_RECEIPT.REC_NO%TYPE;
M_PRIOR_DEAL_NO     DN_TRN_REPO_ROLLOVER.PRIOR_DEAL_NO%TYPE;
M_BR_INVOICE        DN_TRN_BROKERAGE.INVOICE_NO%TYPE;
M_COUNT1            NUMBER;
M_COUNT2            NUMBER;
M_COUNT3            NUMBER;
M_COUNT4            NUMBER;
M_COUNT_R           NUMBER;
M_COUNT_P           NUMBER;
M_COUNT_PRIOR       NUMBER;
M_COUNT_BR          NUMBER;
M_COUNT_REC         NUMBER;
M_COUNT_HIS_P       NUMBER;
M_COUNT_HIS_S       NUMBER;
M_SELLER            DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE;
M_ROLL_COUNT   NUMBER;
M_FRESH_COUNT   NUMBER;
M_COUNT_CUST_DEALNO NUMBER;--ADDED BY NILU FOR CUSTODIAL DEAL DELETION ON 21.05.04

BEGIN

--DN_VALIDATE_SAVE_RIGHTS(M_USER,'WD_Deal_Deletion');  --added by ashini on 31/10/2005 for sr0509-047


----INITIAL CHECKS PRIOR TO EXECUTING DELETE OPTION


----CHECK 1 - IDENTIFYING WHETHER A REPO DEAL HAS ALREADY BEEN ROLLED OVER OR SETTLED

IF SUBSTR(M_DEAL_NO,1,2) IN ('RF','RR') THEN
SELECT NVL(COUNT(DEAL_NO),0) INTO M_COUNT1
FROM DN_TRN_REPO_ROLLOVER
WHERE PRIOR_DEAL_NO=M_DEAL_NO AND
      APP_STATUS <> 'CANCEL';

SELECT NVL(COUNT(DEAL_NO),0) INTO M_COUNT2
FROM DN_TRN_REPO_SETTLEMENT
WHERE PRIOR_DEAL_NO=M_DEAL_NO AND
      APP_STATUS <> 'CANCEL';

IF M_COUNT1+M_COUNT2>0 THEN
 RAISE_APPLICATION_ERROR(-20201,'THE REPO DEAL YOU ARE ATTEMPTING TO DELETE HAS ALREADY BEEN ROLLED OVER OR SETTLED. PLEASE CONTACT SASIANET FOR ASSISTANCE.');
END IF;

END IF;

----CHECK 2 - IDENTIFYING WHETHER A COUPON OR MATURITY HAS BEEN INITIATED FOR AN OUTRIGHT DEAL

IF SUBSTR(M_DEAL_NO,1,2) ='OR' THEN

SELECT  NVL(SUM(COUP_PAY),0) INTO M_COUNT1
FROM DN_INV_INT_OUTPS_DEAL_SEC
WHERE DEAL_NO=M_DEAL_NO;

SELECT  NVL(SUM(MATURITY_PAY),0) INTO M_COUNT2
FROM DN_INV_INT_OUTPS_DEAL_SEC
WHERE DEAL_NO=M_DEAL_NO;

SELECT  NVL(SUM(COUP_PAY),0) INTO M_COUNT3
FROM DN_INV_INT_OUTPS_DEAL_SERNO
WHERE DEAL_NO=M_DEAL_NO;

SELECT  NVL(SUM(MATURITY_PAY),0) INTO M_COUNT4 ---------changed from COUP_PAY by NM
FROM DN_INV_INT_OUTPS_DEAL_SERNO
WHERE DEAL_NO=M_DEAL_NO;

IF M_COUNT1+M_COUNT2+M_COUNT3+M_COUNT4>0 THEN
 RAISE_APPLICATION_ERROR(-20201,'A COUPON OR MATURITY PAYMENT HAS ALREADY BEEN INITIATED ON THE OUTRIGHT DEAL YOU ARE ATTEMPTING TO DELETE. PLEAE CONTACT SASIANET FOR ASSISTANCE.');
END IF;

END IF;

---- CHECK 3 - ADDED BY NM ON 28-08-2003 TO IDENTIFY WHETHER THE DEAL HAS BEEN TRANSFERED TO THE INV_OUTPS_HISTORY TABLE

IF SUBSTR(M_DEAL_NO,1,2) ='OR' THEN

SELECT  NVL(COUNT(DEAL_NO),0)
INTO M_COUNT_HIS_P
FROM DN_HIS_OUTPS_DEAL_SERIAL_NO
WHERE DEAL_NO=M_DEAL_NO;

SELECT  NVL(COUNT(SALE_DEAL_NO),0)
INTO M_COUNT_HIS_S
FROM DN_HIS_OUTPS_DEAL_SERIAL_NO
WHERE SALE_DEAL_NO=M_DEAL_NO;

IF M_COUNT_HIS_P+M_COUNT_HIS_S>0 THEN
 RAISE_APPLICATION_ERROR(-20201,'THE OUTRIGHT DEAL YOU ARE ATTEMPTING TO DELETE HAS ALREADY BEEN ALLOCATED INVENTORY TO THE EXTENT THAT CANNOT BE REVERSED.');
END IF;

END IF;
--------------------
---- CHECK 4
/*ADDED BY NILU ON 19-05-2004 (VC) */
IF SUBSTR(M_DEAL_NO,1,2) ='OR' THEN
M_COUNT1:=0;
SELECT COUNT(*) INTO M_COUNT1
FROM   DN_INV_OUTPS_DEAL_SERIAL_NO
WHERE  SALE_DEAL_NO = M_DEAL_NO AND COST_TRANS_STATUS='Y' ;

IF M_COUNT1>0 THEN
RAISE_APPLICATION_ERROR(-20201,'COST TRANSFER HAS ALREADY BEING RECORDED.THEREFORE CANNOT DELETE THE DEAL.');
END IF;
END IF;
/*END (VC)*/

----SELECTING SECONDARY REFERENCE NUMBERS

SELECT NVL(COUNT(SUS_REF_NO),0)   -------- THIS COUNT WAS ADDED BY SARANGA AND NM ON 28-08-2003, TO ELIMINATE A ROLLBACK, IF NO DATA WAS FOUND
INTO M_COUNT_P
FROM DN_TRN_BO_SETTL_PAYMENT
WHERE SUS_REF_NO =M_DEAL_NO;

IF M_COUNT_P>0 THEN
SELECT PAYMENT_NO
INTO M_PAYMENT_NO
FROM DN_TRN_BO_SETTL_PAYMENT
WHERE SUS_REF_NO =M_DEAL_NO;

---------CHECK 4 - ADDED BY NM ON 28-08-2003 TO IDENTIFY WHETHER THE PAYMENT HAS BEEN ALREADY RECONCILED

    SELECT NVL(COUNT(SUS_REF_NO),0)
    INTO M_COUNT_REC
    FROM DN_TRN_BO_SETTL_PAYMENT
    WHERE SUS_REF_NO =M_DEAL_NO
          AND RECON_STATUS='Y';

    IF M_COUNT_REC>0 THEN
     RAISE_APPLICATION_ERROR(-20201,'THE PAYMENT ->'||M_PAYMENT_NO||', RELATED TO THE DEAL YOU ARE ATTEMPTING TO DELETE HAS ALREADY BEEN RECONCILED. PLEASE UN-RECONCILE IT FIRST AND THEN DELETE THE DEAL.');
    END IF;
-----------------------------------------

END IF;

SELECT NVL(COUNT(SUS_REF_NO),0)  -------- THIS COUNT WAS ADDED BY SARANGA AND NM ON 28-08-2003, TO ELIMINATE A ROLLBACK, IF NO DATA WAS FOUND
INTO M_COUNT_R
FROM DN_TRN_BO_SETTL_RECEIPT
WHERE SUS_REF_NO =M_DEAL_NO;

IF M_COUNT_R>0 THEN
SELECT REC_NO
INTO M_REC_NO
FROM DN_TRN_BO_SETTL_RECEIPT
WHERE SUS_REF_NO =M_DEAL_NO;

---------CHECK 5 - ADDED BY NM ON 28-08-2003 TO IDENTIFY WHETHER THE RECEIPT HAS BEEN ALREADY RECONCILED

    SELECT NVL(COUNT(SUS_REF_NO),0)
    INTO M_COUNT_REC
    FROM DN_TRN_BO_SETTL_RECEIPT
    WHERE SUS_REF_NO =M_DEAL_NO
          AND RECON_STATUS='Y';

    IF M_COUNT_REC>0 THEN
     RAISE_APPLICATION_ERROR(-20201,'THE RECIEPT ->'||M_REC_NO||', RELATED TO THE DEAL YOU ARE ATTEMPTING TO DELETE HAS ALREADY BEEN RECONCILED. PLEASE UN-RECONCILE IT FIRST AND THEN DELETE THE DEAL.');
    END IF;
-----------------------------------------


END IF;

------added by nirmala and nm on 21-05-2004 to handle custodial deals--------- NILU
SELECT  COUNT(DEAL_NO)
INTO    M_COUNT_CUST_DEALNO
FROM    DN_TRN_BO_CUSTODIAL_DEAL
WHERE   OR_DEAL_NO=M_DEAL_NO;

IF (M_COUNT_CUST_DEALNO > 0 ) THEN

UPDATE DN_INV_CUST_DEAL_SERIAL_NO
SET    DIP_WID_DEAL_NO='WID',
       SERIAL_NO_STATUS='WID',
       DIP_WID_EFF_VALDATE=TO_DATE(TO_CHAR(SYSDATE,'DD-MM-YYYY'),'DD-MM-YYYY')
WHERE  DEAL_NO IN (SELECT DEAL_NO
                   FROM   DN_TRN_BO_CUSTODIAL_DEAL
                   WHERE  OR_DEAL_NO=M_DEAL_NO);

END IF;


IF SUBSTR(M_DEAL_NO,1,2)='RR' THEN

SELECT NVL(COUNT(DEAL_NO),0)    -------- THIS COUNT WAS ADDED BY SARANGA AND NM ON 28-08-2003, TO ELIMINATE A ROLLBACK, IF NO DATA WAS FOUND
INTO M_COUNT_PRIOR
FROM DN_TRN_REPO_ROLLOVER
WHERE DEAL_NO =M_DEAL_NO;

IF M_COUNT_PRIOR>0 THEN
SELECT PRIOR_DEAL_NO
INTO M_PRIOR_DEAL_NO
FROM DN_TRN_REPO_ROLLOVER
WHERE DEAL_NO =M_DEAL_NO;
END IF;
ELSIF SUBSTR(M_DEAL_NO,1,2)='RS' THEN

SELECT NVL(COUNT(DEAL_NO),0)   -------- THIS COUNT WAS ADDED BY SARANGA AND NM ON 28-08-2003, TO ELIMINATE A ROLLBACK, IF NO DATA WAS FOUND
INTO M_COUNT_PRIOR
FROM DN_TRN_REPO_SETTLEMENT
WHERE DEAL_NO =M_DEAL_NO;

IF M_COUNT_PRIOR>0 THEN
SELECT PRIOR_DEAL_NO
INTO M_PRIOR_DEAL_NO
FROM DN_TRN_REPO_SETTLEMENT
WHERE DEAL_NO =M_DEAL_NO;
END IF;
END IF;

SELECT NVL(COUNT(DEAL_NO),0)  -------- THIS COUNT WAS ADDED BY SARANGA AND NM ON 28-08-2003, TO ELIMINATE A ROLLBACK, IF NO DATA WAS FOUND
INTO M_COUNT_BR
FROM DN_TRN_BROKERAGE
WHERE DEAL_NO =M_DEAL_NO;

IF M_COUNT_BR>0 THEN
SELECT INVOICE_NO
INTO M_BR_INVOICE
FROM DN_TRN_BROKERAGE
WHERE DEAL_NO =M_DEAL_NO;
END IF;


--------DELETING ACCOUNTING TABLES
DELETE DN_ACC_COUNTP_GEN_ACCOUNT WHERE DOCREFNO =M_DEAL_NO;

DELETE DN_ACC_LICENCEE_GEN_ACCOUNT WHERE DOCREFNO =M_DEAL_NO;

DELETE DN_ACC_LICENCEE_INST_ACCOUNT WHERE DOCREFNO =M_DEAL_NO;

DELETE DN_ACC_PORTF_GEN_ACCOUNT WHERE DOCREFNO =M_DEAL_NO;

DELETE DN_ACC_PORTF_INST_ACCOUNT WHERE DOCREFNO =M_DEAL_NO;



DELETE DN_ACC_COUNTP_GEN_ACCOUNT WHERE DOCREFNO =M_PAYMENT_NO;

DELETE DN_ACC_LICENCEE_GEN_ACCOUNT WHERE DOCREFNO =M_PAYMENT_NO;

DELETE DN_ACC_LICENCEE_INST_ACCOUNT WHERE DOCREFNO =M_PAYMENT_NO;

DELETE DN_ACC_PORTF_GEN_ACCOUNT WHERE DOCREFNO =M_PAYMENT_NO;

DELETE DN_ACC_PORTF_INST_ACCOUNT WHERE DOCREFNO =M_PAYMENT_NO;



DELETE DN_ACC_COUNTP_GEN_ACCOUNT WHERE DOCREFNO =M_REC_NO;

DELETE DN_ACC_LICENCEE_GEN_ACCOUNT WHERE DOCREFNO =M_REC_NO;

DELETE DN_ACC_LICENCEE_INST_ACCOUNT WHERE DOCREFNO =M_REC_NO;

DELETE DN_ACC_PORTF_GEN_ACCOUNT WHERE DOCREFNO =M_REC_NO;

DELETE DN_ACC_PORTF_INST_ACCOUNT WHERE DOCREFNO =M_REC_NO;



DELETE DN_ACC_COUNTP_GEN_ACCOUNT WHERE DOCREFNO =M_BR_INVOICE;

DELETE DN_ACC_LICENCEE_GEN_ACCOUNT WHERE DOCREFNO =M_BR_INVOICE;

DELETE DN_ACC_LICENCEE_INST_ACCOUNT WHERE DOCREFNO =M_BR_INVOICE;

DELETE DN_ACC_PORTF_GEN_ACCOUNT WHERE DOCREFNO =M_BR_INVOICE;

DELETE DN_ACC_PORTF_INST_ACCOUNT WHERE DOCREFNO =M_BR_INVOICE;



------DELETING PAYMENT TABLES
DELETE DN_TRN_BO_SETTL_CHQ_PAYMENT WHERE PAYMENT_NO =M_PAYMENT_NO;

DELETE DN_TRN_BO_SETTL_TRANS_LETTER WHERE PAYMENT_NO =M_PAYMENT_NO;

DELETE DN_TRN_BO_SETTL_PAYMENT WHERE SUS_REF_NO =M_DEAL_NO;

DELETE DN_ACC_SUS_PAYMENT WHERE SUS_REF_NO =M_DEAL_NO;


------DELETING RECEIPT TABLES
DELETE DN_TRN_BO_SETTL_DEPOSIT WHERE REC_NO =M_REC_NO;

DELETE DN_TRN_BO_SETTL_RECEIPT WHERE SUS_REF_NO =M_DEAL_NO;

DELETE DN_ACC_SUS_RECEIPT WHERE SUS_REF_NO =M_DEAL_NO;


------DELETING AND UPDATING INVENTORY TABLES - MODIFIED BY SM ON 10/09/2003

DELETE DN_INV_INT_OUTPS_DEAL_SEC WHERE DEAL_NO = M_DEAL_NO;

DELETE DN_INV_INT_OUTPS_DEAL_SERNO WHERE DEAL_NO = M_DEAL_NO;
------------------------------------------------------------------------------
--------------------------------------------------------------------------------
------------------------------------------------------------------------------------
DELETE DN_INV_REPO_DEAL_SERNO_ALLO WHERE PREV_DEAL_NO = M_DEAL_NO; -------ADDED BY NIRMALA & NM ON 08-03-2004

SELECT COUNT(*)
INTO   M_ROLL_COUNT
FROM   DN_TRN_REPO_ROLLOVER_SERIAL_NO
WHERE  PREV_DEAL_NO=M_DEAL_NO;
IF M_ROLL_COUNT>0 THEN
--- VC06-002 COMMENTED AND ADDED-------------
DELETE DN_TRN_REPO_ROLLOVER_SERIAL_NO WHERE PREV_DEAL_NO=M_DEAL_NO;

/*UPDATE DN_TRN_REPO_ROLLOVER_SERIAL_NO
