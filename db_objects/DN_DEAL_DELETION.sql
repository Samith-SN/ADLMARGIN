                     FROM   DN_TRN_REPO_ROLLOVER
                     WHERE  DEAL_NO=M_DEAL_NO )
WHERE PREV_DEAL_NO=M_DEAL_NO;
*/END IF;

SELECT COUNT(*)
INTO   M_FRESH_COUNT
FROM   DN_TRN_REPO_FRESH_SERIAL_NO
WHERE  PREV_DEAL_NO=M_DEAL_NO;
IF M_FRESH_COUNT>0 THEN
--- VC06-002 COMMENTED AND ADDED-------------
DELETE DN_TRN_REPO_FRESH_SERIAL_NO WHERE PREV_DEAL_NO=M_DEAL_NO;

/*UPDATE DN_TRN_REPO_FRESH_SERIAL_NO
SET    PREV_DEAL_NO=(SELECT PRIOR_DEAL_NO
                     FROM   DN_TRN_REPO_ROLLOVER
                     WHERE  DEAL_NO=M_DEAL_NO )
WHERE PREV_DEAL_NO=M_DEAL_NO;
*/END IF;
------------------------------------------------------------------------------
--------------------------------------------------------------------------------
------------------------------------------------------------------------------------
DELETE DN_INV_REPO_DEAL_SERNO_ALLO WHERE DEAL_NO = M_DEAL_NO; -------ADDED BY NM ON 28-8-2003
DELETE DN_INV_OUTPS_DEAL_SERNO_ALLO WHERE DEAL_NO = M_DEAL_NO; -------ADDED BY NM ON 28-8-2003


DELETE DN_INV_OUTPS_DEAL_SERIAL_NO --------OUTRIGHT PURCHASES
WHERE   DEAL_NO =M_DEAL_NO AND
        SERIAL_NO_STATUS IN('INV','SSW');--MODIFIED FROM ='INV'  BY NM/NIRMALA ON 12-05-2004 --ADDED BY MANJULA 0N 17.05.04 - (VC 04-141)
     ---   AND  ALLO_REPO=0 ;  COMMENTED BY NM ON 22-01-2004 TO RECTIFY THE ERROR WHERE DEALS GOT DELETED ELSEWHERE EXCEPT THIS TABLE
     ---   AND  ALLO_REPO=0 ;  COMMENTED BY NM ON 22-01-2004 TO RECTIFY THE ERROR WHERE DEALS GOT DELETED ELSEWHERE EXCEPT THIS TABLE


     IF SUBSTR(M_DEAL_NO,1,2) ='OR' THEN --ADDED BY SM ON 10/09/2003 TO RECORD THE LOCATION BACK TO SELLER

        SELECT  SELL_PORTFOLIO_CODE INTO M_SELLER
        FROM DN_TRN_OUTP_SALE
        WHERE DEAL_NO=M_DEAL_NO;


    UPDATE DN_INV_OUTPS_DEAL_SERIAL_NO -------WAS ADDED BY NM ON 28-08-2003 FOR OUTRIGHT SALES
    SET SERIAL_NO_STATUS='INV',
        SALE_EFF_VALDATE='',
        SALE_DEAL_NO='',
        LOCATION=M_SELLER
    WHERE  SALE_DEAL_NO =M_DEAL_NO AND
           SERIAL_NO_STATUS IN ('SAD','SND') AND
           SALE_EFF_VALDATE IS NOT NULL ;
    END IF;

DELETE DN_INV_OUTPS_DEAL_SEC WHERE DEAL_NO = M_DEAL_NO;

DELETE DN_INV_REPO_DEAL_SERIAL_NO WHERE DEAL_NO = M_DEAL_NO;
                                        -- AND ALLO_REPO=0;  COMMENTED BY NM TO RECTIFY THE ERROR WHERE DEALS GOT DELETED ELSEWHERE EXCEPT THIS TABLE

DELETE DN_INV_REPO_DEAL_SEC WHERE DEAL_NO = M_DEAL_NO;

DELETE DN_INV_SUS_ISSUE_SERIAL_NO WHERE DEAL_NO = M_DEAL_NO;

DELETE DN_INV_SUS_ISSUE_SEC WHERE DEAL_NO = M_DEAL_NO;

DELETE DN_INV_SUS_ISSUE_INST WHERE DEAL_NO = M_DEAL_NO;

DELETE DN_INV_SUS_RECEIPT_SERIAL_NO WHERE DEAL_NO = M_DEAL_NO;

DELETE DN_INV_SUS_RECEIPT_SEC WHERE DEAL_NO = M_DEAL_NO;

DELETE DN_INV_SUS_RECEIPT_INST WHERE DEAL_NO = M_DEAL_NO;

DELETE DN_TRN_BO_INV_ISSUE WHERE DEAL_NO = M_DEAL_NO;

DELETE DN_TRN_BO_INV_RECEIPT WHERE DEAL_NO = M_DEAL_NO;



--------"RESTORING" ORIGINAL ON-CALL DEALS TO ORIGINAL STATUS
IF SUBSTR(M_PRIOR_DEAL_NO,1,2)='RF' THEN
UPDATE DN_TRN_REPO_FRESH
SET ON_CALL_DEAL='Y'
WHERE DEAL_NO =M_PRIOR_DEAL_NO
AND ON_CALL_DEAL='S';

ELSIF SUBSTR(M_PRIOR_DEAL_NO,1,2)='RR' THEN
UPDATE DN_TRN_REPO_ROLLOVER
SET ON_CALL_DEAL='Y'
WHERE DEAL_NO =M_PRIOR_DEAL_NO
AND ON_CALL_DEAL='S';
END IF;


--------UPDATING TIME LOG
INSERT INTO DN_TIME_LOG
           (SUS_REF_NO,
            DN_USER,
            ENT_DATE,
            DESCRIPTION)
           VALUES
            (
              M_DEAL_NO,
              M_USER,
              SYSDATE,
              'DELETE OPTION'
             );

IF M_PAYMENT_NO IS NOT NULL THEN
INSERT INTO DN_TIME_LOG
           (SUS_REF_NO,
            DN_USER,
            ENT_DATE,
            DESCRIPTION)
           VALUES
            (
              M_PAYMENT_NO,
              M_USER,
              SYSDATE,
              'DELETE OPTION'
             );
END IF;

IF M_REC_NO IS NOT NULL THEN
INSERT INTO DN_TIME_LOG
           (SUS_REF_NO,
            DN_USER,
            ENT_DATE,
            DESCRIPTION)
           VALUES
            (
              M_REC_NO,
              M_USER,
              SYSDATE,
              'DELETE OPTION'
             );
END IF;


------CHANGING DEAL_STATUS TO "CANCEL"
UPDATE DN_TRN_OUTP_SALE SET APP_STATUS='CANCEL' WHERE DEAL_NO =M_DEAL_NO AND APP_STATUS='CONF';

UPDATE DN_TRN_REPO_FRESH SET APP_STATUS='CANCEL' WHERE DEAL_NO =M_DEAL_NO AND APP_STATUS='CONF';

UPDATE DN_TRN_REPO_ROLLOVER SET PRIOR_DEAL_NO=M_DEAL_NO WHERE DEAL_NO =M_DEAL_NO AND APP_STATUS='CONF';

UPDATE DN_TRN_REPO_ROLLOVER SET APP_STATUS='CANCEL' WHERE DEAL_NO =M_DEAL_NO AND APP_STATUS='CONF';

UPDATE DN_TRN_REPO_SETTLEMENT SET PRIOR_DEAL_NO=M_DEAL_NO WHERE DEAL_NO =M_DEAL_NO AND APP_STATUS='CONF';

UPDATE DN_TRN_REPO_SETTLEMENT SET APP_STATUS='CANCEL' WHERE DEAL_NO =M_DEAL_NO AND APP_STATUS='CONF';

UPDATE DN_TRN_BROKERAGE SET INVOICE_NO=NULL WHERE DEAL_NO =M_DEAL_NO AND INVOICE_NO=M_BR_INVOICE;


--------COMMIT

COMMIT;


--------EXCEPTION
EXCEPTION WHEN OTHERS THEN
ROLLBACK;
   ERR_NUM :=  substr(SQLCODE,1,15);
   ERR_MSG := substr(SQLERRM,1,200) ;
   RAISE_APPLICATION_ERROR(-20201,SQLCODE||SQLERRM);

END DN_DEAL_DELETION;

