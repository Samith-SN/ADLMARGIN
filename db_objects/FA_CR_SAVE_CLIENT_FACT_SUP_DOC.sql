set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."FA_CR_SAVE_CLIENT_FACT_SUP_DOC" 
(
M_FACILITY_NO                   DN_MARGIN_SUP_DOC.FACILITY_NO%TYPE,
M_CLIENT_CODE                   DN_MARGIN_SUP_DOC.CLIENT_CODE%TYPE,
M_DOCUMENT_CODE                 DN_MARGIN_SUP_DOC.DOCUMENT_CODE%TYPE,
M_DOCUMENT_NAME                 DN_MARGIN_SUP_DOC.DOCUMENT_NAME%TYPE,
M_DOC_RECEIVED_DATE             VARCHAR2,
M_DOC_RECEIVED                  DN_MARGIN_SUP_DOC.DOC_RECEIVED%TYPE,
M_SCREEN                        VARCHAR2,
M_USER                          DN_MARGIN_SUP_DOC.ENT_USER%TYPE,
M_NUM                           INT
)

AS
-- CODE BY THAMALI JAYATUNGA ON 2010.05.31

BEGIN

IF UPPER(M_SCREEN)='NEW' THEN

INSERT INTO DN_MARGIN_SUP_DOC
(FACILITY_NO,CLIENT_CODE,DOCUMENT_CODE,DOCUMENT_NAME,DOC_RECEIVED_DATE,DOC_RECEIVED,ENT_USER,ENT_DATE)
VALUES
(M_FACILITY_NO,M_CLIENT_CODE,M_DOCUMENT_CODE,M_DOCUMENT_NAME,TO_DATE(M_DOC_RECEIVED_DATE,'DD-MM-YYYY'),M_DOC_RECEIVED,M_USER,SYSDATE);

ELSE

IF M_NUM=0 THEN

INSERT INTO DN_MARGIN_SUP_DOC_BK
(FACILITY_NO,CLIENT_CODE,DOCUMENT_CODE,DOCUMENT_NAME,DOC_RECEIVED_DATE,DOC_RECEIVED,ENT_USER,ENT_DATE,MOD_USER,MOD_DATE)
SELECT
FACILITY_NO,CLIENT_CODE,DOCUMENT_CODE,DOCUMENT_NAME,DOC_RECEIVED_DATE,DOC_RECEIVED,ENT_USER,ENT_DATE,MOD_USER,MOD_DATE
FROM DN_CLIENT_MARGIN_DOC
WHERE FACILITY_NO=M_FACILITY_NO;

DELETE FROM DN_MARGIN_SUP_DOC
WHERE FACILITY_NO=M_FACILITY_NO;

END IF;

INSERT INTO DN_MARGIN_SUP_DOC
(FACILITY_NO,CLIENT_CODE,DOCUMENT_CODE,DOCUMENT_NAME,DOC_RECEIVED_DATE,DOC_RECEIVED,ENT_USER,ENT_DATE)
VALUES
(M_FACILITY_NO,M_CLIENT_CODE,M_DOCUMENT_CODE,M_DOCUMENT_NAME,TO_DATE(M_DOC_RECEIVED_DATE,'DD-MM-YYYY'),M_DOC_RECEIVED,M_USER,SYSDATE);
END IF;

END;

