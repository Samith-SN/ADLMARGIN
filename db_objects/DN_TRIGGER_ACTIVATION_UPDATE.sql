--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_TRIGGER_ACTIVATION_UPDATE" (
M_PORTFOLIO_CODE     DN_REF_PORTF_SECURITY_RATES.PORTFOLIO_CODE%TYPE,
M_SECURITY_CODE      DN_REF_PORTF_SECURITY_RATES.SECURITY_CODE%TYPE
)

AS

M_COUNT1              NUMBER;
M_COUNT               NUMBER;
--M_SECURITY_CODE      DN_REF_PORTF_SECURITY_RATES.
M_CUT_LOSS           DN_REF_PORTF_SECURITY_RATES.CUT_LOSS%TYPE;
M_TAKE_PROFIT        DN_REF_PORTF_SECURITY_RATES.TAKE_PROFIT%TYPE;
M_CL_STATUS          DN_REF_PORTF_SECURITY_RATES.CL_STATUS%TYPE;
M_TK_STATUS          DN_REF_PORTF_SECURITY_RATES.TK_STATUS%TYPE;
M_DEAL_NO            DN_TRN_TRIGGER_ALERT.DEAL_NO%TYPE;
MM_DEAL_NO           DN_TRN_TRIGGER_ALERT.DEAL_NO%TYPE;
M_FACE_VAL           DN_TEMP_INVENTORY_BYDAYEND.FACE_VAL%TYPE;
M_INITIALCOST_BROK   DN_TEMP_INVENTORY_BYDAYEND.INITIALCOST_BROK%TYPE;
M_TODAYS_CLOSE       DN_TEMP_MARKET_RATES_CSE.TODAYS_CLOSE%TYPE;

BEGIN
-- RAISE_APPLICATION_ERROR(-20001,'');
 SELECT COUNT(*)
 INTO   M_COUNT
 FROM (
 SELECT A.SECURITY_NAME,HIGH,LOW,TODAYS_CLOSE,CHANGE
 FROM   DN_TEMP_MARKET_RATES_CSE A,
        DN_REF_SECURITY_SHARE_NAME B
 WHERE  A.SECURITY_NAME=B.SECURITY_NAME AND
        SECURITY_CODE = M_SECURITY_CODE
 UNION ALL
 SELECT A.SECURITY_NAME,HIGH,LOW,TODAYS_CLOSE,CHANGE
 FROM   DN_TEMP_MARKET_RATES_CSE_BACK A,
        DN_REF_SECURITY_SHARE_NAME B
 WHERE  A.SECURITY_NAME=B.SECURITY_NAME AND
        SECURITY_CODE = M_SECURITY_CODE AND
        A.SECURITY_NAME NOT IN (SELECT SECURITY_NAME
                                FROM   DN_TEMP_MARKET_RATES_CSE));

IF M_COUNT>0 THEN
 SELECT TODAYS_CLOSE
 INTO   M_TODAYS_CLOSE
 FROM (
 SELECT A.SECURITY_NAME,HIGH,LOW,TODAYS_CLOSE,CHANGE
 FROM   DN_TEMP_MARKET_RATES_CSE A,
        DN_REF_SECURITY_SHARE_NAME B
 WHERE  A.SECURITY_NAME=B.SECURITY_NAME AND
        SECURITY_CODE = M_SECURITY_CODE
 UNION ALL
 SELECT A.SECURITY_NAME,HIGH,LOW,TODAYS_CLOSE,CHANGE
 FROM   DN_TEMP_MARKET_RATES_CSE_BACK A,
        DN_REF_SECURITY_SHARE_NAME B
 WHERE  A.SECURITY_NAME=B.SECURITY_NAME AND
        SECURITY_CODE = M_SECURITY_CODE AND
        A.SECURITY_NAME NOT IN (SELECT SECURITY_NAME
                                FROM   DN_TEMP_MARKET_RATES_CSE));


        SELECT CUT_LOSS,TAKE_PROFIT,CL_STATUS,TK_STATUS,DEAL_NO
        INTO   M_CUT_LOSS,M_TAKE_PROFIT,M_CL_STATUS,M_TK_STATUS,MM_DEAL_NO
        FROM   DN_REF_PORTF_SECURITY_RATES
        WHERE  SECURITY_CODE = M_SECURITY_CODE AND PORTFOLIO_CODE=M_PORTFOLIO_CODE;
dbms_output.put_line('Value of M_TODAYS_CLOSE='||M_TODAYS_CLOSE);
dbms_output.put_line('Value of M_TAKE_PROFIT='||M_TAKE_PROFIT);
dbms_output.put_line('Value of M_CUT_LOSS='||M_CUT_LOSS);
dbms_output.put_line('Value of CL_STATUS='||M_CL_STATUS);
dbms_output.put_line('Value of M_TK_STATUS='||M_TK_STATUS);

        IF M_TODAYS_CLOSE >= M_TAKE_PROFIT THEN
           IF M_TK_STATUS='N' THEN

             SELECT COUNT(*)
             INTO   M_COUNT1
             FROM   DN_TEMP_INVENTORY_BYDAYEND
             WHERE  SECURITY_CODE  = M_SECURITY_CODE AND
                    PORTFOLIO_CODE = M_PORTFOLIO_CODE;

             IF M_COUNT1>0 THEN
               SELECT FACE_VAL,INITIALCOST_BROK
               INTO   M_FACE_VAL,M_INITIALCOST_BROK
               FROM   DN_TEMP_INVENTORY_BYDAYEND
               WHERE  SECURITY_CODE  = M_SECURITY_CODE AND
                      PORTFOLIO_CODE = M_PORTFOLIO_CODE;

               SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_TRIGGER.NEXTVAL),3,'0') INTO M_DEAL_NO FROM DUAL;
               M_DEAL_NO:=  'TA'||M_DEAL_NO;

               INSERT INTO DN_TRN_TRIGGER_ALERT(DEAL_NO,PORTFOLIO_CODE,SECURITY_CODE,ACTIVE_DATE,ALERT_TYPE,
                                                TRIGGER_AMOUNT,AMOUNT_ACTIVE,NO_OF_SHARES,COST,ACTIVE_STATUS)
               VALUES(M_DEAL_NO,M_PORTFOLIO_CODE,M_SECURITY_CODE,SYSDATE,
                      'TP',M_TAKE_PROFIT,M_TODAYS_CLOSE,M_FACE_VAL,M_INITIALCOST_BROK,'Y');     --'||M_TAKE_PROFIT||' AND NOW PRICE IS

               UPDATE DN_REF_PORTF_SECURITY_RATES
               SET    TK_STATUS = 'Y',
                      DEAL_NO   = M_DEAL_NO
               WHERE  SECURITY_CODE = M_SECURITY_CODE AND PORTFOLIO_CODE = M_PORTFOLIO_CODE;
             END IF;
           ELSIF M_TK_STATUS='Y' THEN

             UPDATE DN_TRN_TRIGGER_ALERT
             SET    TRIGGER_AMOUNT = M_TAKE_PROFIT
             WHERE  DEAL_NO = MM_DEAL_NO;

           END IF;

           IF M_CL_STATUS='Y' THEN

             UPDATE DN_TRN_TRIGGER_ALERT
             SET    ACTIVE_STATUS   = 'N',
                    AMOUNT_INACTIVE = M_TODAYS_CLOSE
             WHERE  DEAL_NO = MM_DEAL_NO;

             UPDATE DN_REF_PORTF_SECURITY_RATES
             SET    CL_STATUS = 'N'
             WHERE  SECURITY_CODE = M_SECURITY_CODE AND PORTFOLIO_CODE = M_PORTFOLIO_CODE;

           END IF;

        ELSIF M_TODAYS_CLOSE <= M_CUT_LOSS THEN
dbms_output.put_line('Value of M_CL_STATUS='||M_CL_STATUS);
           IF M_CL_STATUS='N' THEN
               SELECT COUNT(*)
               INTO   M_COUNT1
               FROM   DN_TEMP_INVENTORY_BYDAYEND
               WHERE  SECURITY_CODE  = M_SECURITY_CODE AND
                      PORTFOLIO_CODE = M_PORTFOLIO_CODE;
dbms_output.put_line('Value of M_COUNT1='||M_COUNT1);
             IF M_COUNT1>0 THEN
               SELECT FACE_VAL,INITIALCOST_BROK
               INTO   M_FACE_VAL,M_INITIALCOST_BROK
               FROM   DN_TEMP_INVENTORY_BYDAYEND
               WHERE  SECURITY_CODE  = M_SECURITY_CODE AND
                      PORTFOLIO_CODE = M_PORTFOLIO_CODE;

               SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_TRIGGER.NEXTVAL),3,'0') INTO M_DEAL_NO FROM DUAL;
               M_DEAL_NO:=  'TA'||M_DEAL_NO;

               INSERT INTO DN_TRN_TRIGGER_ALERT(DEAL_NO,PORTFOLIO_CODE,SECURITY_CODE,ACTIVE_DATE,ALERT_TYPE,
                                                TRIGGER_AMOUNT,AMOUNT_ACTIVE,NO_OF_SHARES,COST,ACTIVE_STATUS)
               VALUES(M_DEAL_NO,M_PORTFOLIO_CODE,M_SECURITY_CODE,SYSDATE,
                      'CL',M_CUT_LOSS,M_TODAYS_CLOSE,M_FACE_VAL,M_INITIALCOST_BROK,'Y');     --'||M_TAKE_PROFIT||' AND NOW PRICE IS

               UPDATE DN_REF_PORTF_SECURITY_RATES
               SET    CL_STATUS = 'Y',
                      DEAL_NO   = M_DEAL_NO
               WHERE  SECURITY_CODE = M_SECURITY_CODE AND PORTFOLIO_CODE = M_PORTFOLIO_CODE;
              END IF;
           ELSIF M_CL_STATUS='Y' THEN

             UPDATE DN_TRN_TRIGGER_ALERT
             SET    TRIGGER_AMOUNT = M_CUT_LOSS
             WHERE  DEAL_NO = MM_DEAL_NO;

           END IF;

           IF M_TK_STATUS='Y' THEN

             UPDATE DN_TRN_TRIGGER_ALERT
             SET    ACTIVE_STATUS   = 'N',
                    AMOUNT_INACTIVE = M_TODAYS_CLOSE
             WHERE  DEAL_NO = MM_DEAL_NO;

             UPDATE DN_REF_PORTF_SECURITY_RATES
             SET    TK_STATUS = 'N'
             WHERE  SECURITY_CODE = M_SECURITY_CODE AND PORTFOLIO_CODE = M_PORTFOLIO_CODE;

           END IF;

        ELSIF M_TODAYS_CLOSE < M_TAKE_PROFIT AND M_TODAYS_CLOSE > M_CUT_LOSS THEN
           IF M_CL_STATUS='Y' THEN

             UPDATE DN_TRN_TRIGGER_ALERT
             SET    ACTIVE_STATUS   = 'N',
                    AMOUNT_INACTIVE = M_TODAYS_CLOSE
             WHERE  DEAL_NO = MM_DEAL_NO;

             UPDATE DN_REF_PORTF_SECURITY_RATES
             SET    CL_STATUS = 'N',
                    DEAL_NO   = ''
             WHERE  SECURITY_CODE = M_SECURITY_CODE AND PORTFOLIO_CODE = M_PORTFOLIO_CODE;

           END IF;

           IF M_TK_STATUS='Y' THEN

             UPDATE DN_TRN_TRIGGER_ALERT
             SET    ACTIVE_STATUS   = 'N',
                    AMOUNT_INACTIVE = M_TODAYS_CLOSE
             WHERE  DEAL_NO = MM_DEAL_NO;

             UPDATE DN_REF_PORTF_SECURITY_RATES
             SET    TK_STATUS = 'N',
                    DEAL_NO   = ''
             WHERE  SECURITY_CODE = M_SECURITY_CODE AND PORTFOLIO_CODE = M_PORTFOLIO_CODE;

           END IF;

        END IF;
END IF;
COMMIT;
END ;


