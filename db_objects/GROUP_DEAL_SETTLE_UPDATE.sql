--------------------------------------------------------
--  DDL for Procedure GROUP_DEAL_SETTLE_UPDATE
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."GROUP_DEAL_SETTLE_UPDATE" 
(
  M_GDEAL_NO    DN_TRN_OUTP_SALE.DEAL_NO%TYPE,
  M_SETTLE_MODE    DN_TRN_OUTP_SALE_SETTLE.SETTLE_MODE%TYPE
)
AS
   MM_CURRENCY_VALUE       DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE;--CURRENCY
   M_COUNT_ALL             NUMBER;--CURRENCY
   M_CURR_CODE             DN_TRN_OUTP_SALE.CURR_CODE%TYPE;--CURRENCY
   M_NIRCOUNT              NUMBER;

BEGIN


IF (SUBSTR(M_GDEAL_NO,1,2)='GO')THEN--------------------"GO"----------------------------//

SELECT COUNT(*)--CURRENCY
INTO   M_COUNT_ALL
FROM   DN_TRN_OUTP_SALE
WHERE  DEAL_NO=M_GDEAL_NO;

IF(M_COUNT_ALL>0)THEN
SELECT CURR_CODE
INTO   M_CURR_CODE
FROM   DN_TRN_OUTP_SALE
WHERE  DEAL_NO=M_GDEAL_NO;
END IF;
SELECT  CURRENCY_VALUE--CURRENCY
INTO    MM_CURRENCY_VALUE
FROM    DN_REF_EXCHANGE_RATES
WHERE   CURR_CODE=M_CURR_CODE;

IF(M_CURR_CODE<>'SLR')THEN--CURRENCY
INSERT INTO DN_TRN_OUTP_SALE_SETTLE
          (DEAL_NO,SETTLE_MODE,SETTLE_AMOUNT,BUY_PORTFOLIO_CODE,
           SELL_PORTFOLIO_CODE,CURRENCY_SETTLE_AMOUNT)

SELECT  DEAL_NO,M_SETTLE_MODE,SETTLE_VALUE,BUY_PORTFOLIO_CODE,
        SELL_PORTFOLIO_CODE,SETTLE_VALUE*MM_CURRENCY_VALUE
FROM    DN_TRN_OUTP_SALE
WHERE   GROUP_DEALNO=M_GDEAL_NO;
ELSE--CURRENCY
INSERT INTO DN_TRN_OUTP_SALE_SETTLE
          (DEAL_NO,SETTLE_MODE,SETTLE_AMOUNT,BUY_PORTFOLIO_CODE,
           SELL_PORTFOLIO_CODE)

SELECT  DEAL_NO,M_SETTLE_MODE,SETTLE_VALUE,BUY_PORTFOLIO_CODE,
        SELL_PORTFOLIO_CODE
FROM    DN_TRN_OUTP_SALE
WHERE   GROUP_DEALNO=M_GDEAL_NO;
END IF;--CURRENCY









ELSIF (SUBSTR(M_GDEAL_NO,1,2)='GF')THEN----------------------------"GF"----------------//
SELECT COUNT(*)--CURRENCY
INTO   M_COUNT_ALL
FROM   DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_GDEAL_NO;

IF(M_COUNT_ALL>0)THEN
SELECT CURR_CODE
INTO   M_CURR_CODE
FROM   DN_TRN_REPO_FRESH
WHERE  DEAL_NO=M_GDEAL_NO;
END IF;
SELECT  CURRENCY_VALUE--CURRENCY
INTO    MM_CURRENCY_VALUE
FROM    DN_REF_EXCHANGE_RATES
WHERE   CURR_CODE=M_CURR_CODE;

       IF(M_CURR_CODE<>'SLR')THEN--CURRENCY

                 INSERT INTO DN_TRN_REPO_FRESH_SETTLE
                  ( DEAL_NO,SETTLE_MODE,SETTLE_AMOUNT,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE,
                    CURRENCY_SETTLE_AMOUNT--CURRENCY
                  )

                 SELECT  DEAL_NO,M_SETTLE_MODE,LEG1_VALUE,BORR_PORTFOLIO_CODE,
                         LEND_PORTFOLIO_CODE,LEG1_VALUE*MM_CURRENCY_VALUE
                 FROM    DN_TRN_REPO_FRESH
                 WHERE   GROUP_DEALNO=M_GDEAL_NO;

       ELSE--CURRENCY

                 INSERT INTO DN_TRN_REPO_FRESH_SETTLE
                  ( DEAL_NO,SETTLE_MODE,SETTLE_AMOUNT,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE
                  )

                 SELECT  DEAL_NO,M_SETTLE_MODE,LEG1_VALUE,BORR_PORTFOLIO_CODE,
                         LEND_PORTFOLIO_CODE
                 FROM    DN_TRN_REPO_FRESH
                 WHERE   GROUP_DEALNO=M_GDEAL_NO;

       END IF;--CURRENCY

ELSIF (SUBSTR(M_GDEAL_NO,1,2)='GR')THEN----------------------------"GR"----------------//

SELECT COUNT(*)--CURRENCY
INTO   M_COUNT_ALL
FROM   DN_TRN_REPO_ROLLOVER
WHERE  DEAL_NO=M_GDEAL_NO;

IF(M_COUNT_ALL>0)THEN
SELECT CURR_CODE
INTO   M_CURR_CODE
FROM   DN_TRN_REPO_ROLLOVER
WHERE  DEAL_NO=M_GDEAL_NO;
END IF;
SELECT  CURRENCY_VALUE--CURRENCY
INTO    MM_CURRENCY_VALUE
FROM    DN_REF_EXCHANGE_RATES
WHERE   CURR_CODE=M_CURR_CODE;

 IF(M_CURR_CODE<>'SLR')THEN--CURRENCY

            INSERT INTO DN_TRN_REPO_ROLLOVER_SETTLE
              ( DEAL_NO,SETTLE_MODE,SETTLE_AMOUNT,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE,
                CURRENCY_SETTLE_AMOUNT--CURRENCY
               )
                 SELECT  DEAL_NO,'CURR_ACC',
                         DECODE(PAYMENT_TO_BORR,0,PAYMENT_TO_LEND,PAYMENT_TO_BORR),--,NULL,PAYMENT_TO_LEND,PAYMENT_TO_BORR
                         BORR_PORTFOLIO_CODE,
                         LEND_PORTFOLIO_CODE,
                         DECODE(PAYMENT_TO_BORR,0,PAYMENT_TO_LEND,PAYMENT_TO_BORR,NULL,PAYMENT_TO_LEND,PAYMENT_TO_BORR)*MM_CURRENCY_VALUE
                 FROM    DN_TRN_REPO_ROLLOVER
                 WHERE   GROUP_DEALNO=M_GDEAL_NO;
 ELSE--CURRENCY
             INSERT INTO DN_TRN_REPO_ROLLOVER_SETTLE
                (DEAL_NO,SETTLE_MODE, SETTLE_AMOUNT,BORR_PORTFOLIO_CODE,LEND_PORTFOLIO_CODE)

             SELECT  DEAL_NO,'CURR_ACC',
                     DECODE(PAYMENT_TO_BORR,0,PAYMENT_TO_LEND,PAYMENT_TO_BORR),--,NULL,PAYMENT_TO_LEND,PAYMENT_TO_BORR
                     BORR_PORTFOLIO_CODE,
                     LEND_PORTFOLIO_CODE
             FROM    DN_TRN_REPO_ROLLOVER
             WHERE   GROUP_DEALNO=M_GDEAL_NO;

 END IF;--CURRENCY

          SELECT COUNT(*)
          INTO   M_NIRCOUNT
          FROM   DN_TRN_REPO_SETTLEMENT
          WHERE  GROUP_DEALNO=M_GDEAL_NO;

          IF (M_NIRCOUNT > 0 )THEN

          UPDATE DN_TRN_REPO_SETTLEMENT
          SET    GROUP_PORT_TYPE=(SELECT DECODE(A.BORR_PORTFOLIO_CODE,'GROUP','B','L')
                                  FROM    DN_TRN_REPO_ROLLOVER A
                                  WHERE   DEAL_NO=M_GDEAL_NO)
          WHERE  GROUP_DEALNO=M_GDEAL_NO;
          END IF;


END IF;
COMMIT;
END GROUP_DEAL_SETTLE_UPDATE;

