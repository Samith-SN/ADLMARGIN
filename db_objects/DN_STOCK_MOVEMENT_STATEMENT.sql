set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_STOCK_MOVEMENT_STATEMENT" 
(
M_TO_DATE                   VARCHAR2,
M_FROM_DATE                 VARCHAR2,
M_PORTFOLIO_CODE            DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE,
M_USER                      DN_TEMP_INV_STOCK.DN_USER%TYPE
)
AS
M_INST_TYPE                 DN_REF_INSTRUMENT.INST_TYPE%TYPE;
M_F_VALUE                   DN_TEMP_INV_STOCK.FACE_VAL%TYPE;
M_SEC_CODE                  DN_TEMP_STOCK_MOVEMENT.SEC_CODE%TYPE;
M_QTY                       DN_TEMP_STOCK_MOVEMENT.QTY%TYPE;
M_QT                        DN_TEMP_STOCK_MOVEMENT.QTY%TYPE;
M_STATUS                    DN_TEMP_INV_STOCK.STATUS%TYPE;
M_DATE                      VARCHAR2(15);
C_NO                        INTEGER;
M_COUNT                     INTEGER;


--CREATED BY MANJULA ON 07-09-2004
--FOR STOCK MOVEMENT REPORT
--SYSTEM : FCLMGT

CURSOR C1 IS
SELECT P.DT,P.SC,P.QTY,P.PR,P.VAL,P.SD,P.CONT,P.TYP,P.BCOMMENTS,P.SCOMMENTS ----ADDED BY KEITH FOR 0409-071--3BCOMMENTS
FROM ( SELECT A.EFF_VALDATE DT,A.SECURITY_CODE SC,A.FACE_VALUE QTY,
       A.PRICE_CLEAN PR,A.SETTLE_VALUE VAL,B.BUY_SETLE_DATE SD,
       NVL(A.CONTRACT_NO,'-') CONT,'BUY' TYP,C.BUY_SETTLE_COMMENT BCOMMENTS,C.SELL_SETTLE_COMMENT SCOMMENTS --ADDED BY KEITH FOR 0409-071--3BCOMMENTS
  FROM  DN_TRN_OUTP_SALE A,
        DN_TRN_OUTP_SALE_SETTLE_EQUITY B,
        DN_TRN_OUTP_SALE_SETTLE C
  WHERE
  A.DEAL_NO=B.DEAL_NO AND
  A.DEAL_NO=C.DEAL_NO AND
  A.APP_STATUS='CONF' AND
  EFF_VALDATE<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') AND
  EFF_VALDATE>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY') AND
  A.BUY_PORTFOLIO_CODE=M_PORTFOLIO_CODE

  UNION ALL
  SELECT A.EFF_VALDATE DT,A.SECURITY_CODE SC,A.FACE_VALUE QTY,
         A.PRICE_CLEAN PR,A.SETTLE_VALUE VAL,B.SELL_SETLE_DATE SD,
         NVL(A.CONTRACT_NO,'-') CONT,'SELL' TYP,C.BUY_SETTLE_COMMENT BCOMMENTS,C.SELL_SETTLE_COMMENT SCOMMENTS --ADDED BY KEITH FOR 0409-071--3SCOMMENTS
  FROM DN_TRN_OUTP_SALE A,
       DN_TRN_OUTP_SALE_SETTLE_EQUITY B,
       DN_TRN_OUTP_SALE_SETTLE C
  WHERE
  A.DEAL_NO=B.DEAL_NO AND
  A.DEAL_NO=C.DEAL_NO AND
  A.APP_STATUS='CONF' AND
  EFF_VALDATE<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') AND
  EFF_VALDATE>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY') AND
  A.SELL_PORTFOLIO_CODE=M_PORTFOLIO_CODE

/*  UNION ALL
  SELECT EFF_VAL_DATE,SEC_CODE,TRNAMOUNT ,--PRICE,
  --VALUE,
  N/A,N/A,RIGHTS
  FROM DN_TRN_SALE_OF_RIGHTS
  WHERE PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
  EFF_VAL_DATE<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') AND
  EFF_VAL_DATE>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY')*/ )P ORDER BY P.DT,P.SC,P.TYP,P.CONT;

CURSOR C2 IS
SELECT INST_TYPE
FROM DN_REF_INSTRUMENT
WHERE INST_CAT='EQUITY' AND ACTIVE_STATUS='Y';

/*CURSOR C3 IS
 SELECT ROWNUM NO,EFF_DATE DT,SEC_CODE SC,TRN_TYPE TP,CONTR_NO CNO,QTY QT
            FROM DN_TEMP_STOCK_MOVEMENT
            WHERE DN_USER=M_USER
            ORDER BY EFF_DATE,SEC_CODE,TRN_TYPE,CONTR_NO;*/

BEGIN
-- RAISE_APPLICATION_ERROR(-20201,'M_TO_DATE'||M_TO_DATE||'M_FROM_DATE'||M_FROM_DATE||'M_PORTFOLIO_CODE'||M_PORTFOLIO_CODE||'M_USER'||M_USER||'M_DATE'||M_DATE);
   DELETE FROM DN_TEMP_STOCK_MOVEMENT;
   DELETE FROM DN_TEMP_INV_STOCK;
  C_NO:=1;
  FOR I IN C1
  LOOP
  INSERT INTO DN_TEMP_STOCK_MOVEMENT
  (ROW_NO,EFF_DATE,SEC_CODE,QTY,PRICE,SETTL_VALUE,SETTL_DATE,CONTR_NO,TRN_TYPE,DN_USER,BCOMMENTS,SCOMMENTS)--ADDED BY KEITH FOR 0409-071--3BCOMMENTS AND SCOMMENTS
  VALUES
  (C_NO,I.DT,I.SC,I.QTY,I.PR,I.VAL,I.SD,I.CONT,I.TYP,M_USER,I.BCOMMENTS,I.SCOMMENTS);
   C_NO:=C_NO+1;
  COMMIT;
  END LOOP;

  M_DATE:=TO_CHAR(TO_DATE(M_FROM_DATE,'DD/MM/YYYY')-1,'DD/MM/YYYY');


  FOR J IN C2
  LOOP
  DN_INV_BY_DT_FOR_STOCK_MOV(J.INST_TYPE,M_DATE,'NA',M_PORTFOLIO_CODE,M_USER);
  END LOOP;

  FOR K IN (SELECT ROW_NO NO,EFF_DATE DT,SEC_CODE SC,TRN_TYPE TP,CONTR_NO CNO,QTY QT
            FROM DN_TEMP_STOCK_MOVEMENT
            WHERE DN_USER=M_USER
            ORDER BY EFF_DATE,SEC_CODE,TRN_TYPE,CONTR_NO)
  LOOP

  SELECT COUNT(*) INTO M_COUNT
  FROM  DN_TEMP_INV_STOCK
  WHERE SECURITY_CODE=K.SC
  AND DN_USER=M_USER;
  --dbms_output.put_line('Value of M_COUNT='||M_COUNT);
  IF (M_COUNT > 0) THEN

  SELECT SUM(FACE_VAL) INTO M_F_VALUE
  FROM  DN_TEMP_INV_STOCK
  WHERE SECURITY_CODE=K.SC
  AND DN_USER=M_USER;

 ELSE

  M_F_VALUE :=0;

  INSERT INTO DN_TEMP_INV_STOCK
  (SECURITY_CODE,FACE_VAL,PORTFOLIO_CODE,DN_USER)
  VALUES
  (K.SC,M_F_VALUE,M_PORTFOLIO_CODE,M_USER);

  END IF;
  --dbms_output.put_line('Value of ROWNUM='||k.no);
  --dbms_output.put_line('Value of K.QT='||K.QT);

  UPDATE DN_TEMP_STOCK_MOVEMENT
  SET QUANTITY=M_F_VALUE
  WHERE  ROW_NO=K.NO
  AND DN_USER=M_USER;


  IF K.TP LIKE 'SELL%' THEN
  UPDATE DN_TEMP_INV_STOCK
  SET FACE_VAL=FACE_VAL-K.QT
  WHERE SECURITY_CODE=K.SC
  AND DN_USER=M_USER;

  ELSIF K.TP LIKE 'BUY%' THEN
  UPDATE DN_TEMP_INV_STOCK
  SET FACE_VAL=FACE_VAL+K.QT
  WHERE SECURITY_CODE=K.SC
  AND DN_USER=M_USER;
  END IF;

  COMMIT;

  END LOOP;

  END DN_STOCK_MOVEMENT_STATEMENT;


