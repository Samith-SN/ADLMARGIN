set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_F_MAIN_PAYMENT" 
(
M_INVOICE_NO        DN_TRN_BROKERAGE.INVOICE_NO%TYPE
)
AS

/* PROCEDURE  - F_MAIN IS TO LINK ALL THE BROKERAGE PROCEDURES
   SYSTEM     - DEALNET
   CREATED BY - LATHIKA
   CREATED ON - 05/JAN/2000 */

CURSOR BROK_MAIN IS
  SELECT
     DEAL_NO,CP_CODE,BROK_CODE,BROK_FEE_AMOUNT,BROK_GST
  FROM
     DN_TRN_BROKERAGE
  WHERE
     INVOICE_NO=M_INVOICE_NO;

M_DOCREFNO        DN_TRN_BROKERAGE.DEAL_NO%TYPE;
M_PORTF_CODE      DN_TRN_BROKERAGE.BROK_CODE%TYPE;
M_DN_PORTF_CODE   DN_TRN_BROKERAGE.CP_CODE%TYPE;
M_TRNAMOUNT       DN_TRN_BROKERAGE.BROK_FEE_AMOUNT%TYPE;
M_TRNAMOUNT2      DN_TRN_BROKERAGE.BROK_GST%TYPE;

M_TRNDATE         DN_TRN_BL_FUND.EFF_VALDATE%TYPE;
M_TRNDATE2        DN_TRN_BL_FUND.EFF_VALDATE%TYPE;
M_PF_TYPE         DN_REF_PORTFOLIO.PF_TYPE%TYPE;
M_OWNER           DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;
M_OWNER2          DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;

M_BUY_PORTFOLIO_CODE  DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE;
M_SELL_PORTFOLIO_CODE  DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE;
M_COUNT           NUMBER;

BEGIN

OPEN BROK_MAIN;
LOOP

FETCH BROK_MAIN INTO
    M_DOCREFNO,M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNAMOUNT,M_TRNAMOUNT2;

EXIT WHEN BROK_MAIN%NOTFOUND;

M_BUY_PORTFOLIO_CODE := NULL;
M_SELL_PORTFOLIO_CODE := NULL;
--RAISE_APPLICATION_ERROR(-20201,M_DOCREFNO||'   '||M_PORTF_CODE||'   '||M_DN_PORTF_CODE);

M_COUNT:=0;

SELECT COUNT(BUY_PORTFOLIO_CODE)
INTO M_COUNT
FROM DN_TRN_OUTP_SALE
WHERE BUY_PORTFOLIO_CODE=M_PORTF_CODE
AND DEAL_NO=M_DOCREFNO;

IF M_COUNT > 0 THEN

SELECT BUY_PORTFOLIO_CODE
INTO M_BUY_PORTFOLIO_CODE
FROM DN_TRN_OUTP_SALE
WHERE BUY_PORTFOLIO_CODE=M_PORTF_CODE
AND DEAL_NO=M_DOCREFNO;

END IF;

M_COUNT:=0;

SELECT COUNT(SELL_PORTFOLIO_CODE)
INTO M_COUNT
FROM DN_TRN_OUTP_SALE
WHERE SELL_PORTFOLIO_CODE=M_PORTF_CODE
AND DEAL_NO=M_DOCREFNO;

IF M_COUNT > 0 THEN

 SELECT SELL_PORTFOLIO_CODE
 INTO M_SELL_PORTFOLIO_CODE
 FROM DN_TRN_OUTP_SALE
 WHERE SELL_PORTFOLIO_CODE=M_PORTF_CODE
 AND DEAL_NO=M_DOCREFNO;

END IF;

SELECT OWNED_BY_MBFSL,PF_TYPE
INTO M_OWNER,M_PF_TYPE
FROM DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE=M_PORTF_CODE;

----brokerage income from counter parties / portfolios------
SELECT OWNED_BY_MBFSL
INTO M_OWNER2
FROM DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE=M_DN_PORTF_CODE;

  DN_ACC_F_3_1(M_INVOICE_NO,M_DOCREFNO,M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNAMOUNT,M_TRNAMOUNT2);
  DN_ACC_F_4_1(M_INVOICE_NO,M_DOCREFNO,M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNAMOUNT,M_TRNAMOUNT2);
  DN_ACC_F_5_1(M_INVOICE_NO,M_DOCREFNO,M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNAMOUNT,M_TRNAMOUNT2);

END LOOP;
--COMMIT;

END DN_ACC_F_MAIN_PAYMENT;

