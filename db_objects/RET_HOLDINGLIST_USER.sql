  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."RET_HOLDINGLIST_USER" 
(
 M_DEAL_NO        DN_TRN_SCRIPLESS_TRANSFERS.DEAL_NO%TYPE
)
RETURN   DN_TRN_SCRIPLESS_TRANSFERS.DN_USER%TYPE
AS

  --CREATED BY  : NIRMALA FERNANDO
  --CREATED ON  : 10-05-2002
  --PURPOSE     : TO RETURN THE DEAL ENTERED USER TO THE REPORTS

M_DN_USER       DN_TRN_SCRIPLESS_TRANSFERS.DN_USER%TYPE;

BEGIN

  SELECT DN_USER
  INTO   M_DN_USER
  FROM   DN_TRN_SCRIPLESS_TRANSFERS
  WHERE  DEAL_NO=M_DEAL_NO  ;

  RETURN   M_DN_USER;

END RET_HOLDINGLIST_USER;

/
