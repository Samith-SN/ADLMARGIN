  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_REF_BROKER_PORTFOLIO_MAP" 
(
 M_PORTFOLIO_CODE    DN_REF_BROKER_MAP.PORTFOLIO_CODE%TYPE,
 M_BROKER_CODE       DN_REF_BROKER_MAP.BROKER_CODE%TYPE,
 M_USER_NAME         DN_TEMP_TRN_LIST.USER_NAME%TYPE,
 M_SCREEN_NAME       VARCHAR2
)
AS
M_PRICE1              VARCHAR2(50);--DN_TEMP_TRN_LIST.PRICE%TYPE
M_PRICE2              DN_TEMP_TRN_LIST.PRICE%TYPE;
M_COUNT               NUMBER;
BEGIN

DN_VALIDATE_SAVE_RIGHTS(M_USER_NAME,'WD_Broker_Mapping');  --added by ashini on 31/10/2005 for sr0509-047

 -- CAREATED BY SVA ON 16-05-2005 TO MAP THE BROKERS
 --DN_VALIDATE_SAVE_RIGHTS(M_USER_NAME,M_SCREEN_NAME);

 SELECT COUNT(*)
 INTO   M_COUNT
 FROM   DN_REF_BROKER_MAP
 WHERE  PORTFOLIO_CODE = M_PORTFOLIO_CODE;

 IF (M_COUNT) =0 THEN

    INSERT INTO DN_REF_BROKER_MAP
    VALUES (M_PORTFOLIO_CODE,M_BROKER_CODE);

 ELSE

    UPDATE DN_REF_BROKER_MAP
    SET    BROKER_CODE = M_BROKER_CODE
    WHERE  PORTFOLIO_CODE = M_PORTFOLIO_CODE;

 END IF;

--RAISE_APPLICATION_ERROR(-20001,'TRIM(M_TRN_TIME) - '||TRIM(M_TRN_TIME));

COMMIT;
END ;

