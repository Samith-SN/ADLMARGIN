set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CHECK_CONDITIONS_START" 
(
  M_PROCESS_DATE                DATE
)
AS
M_COUNT1   NUMBER;
M_COUNT2   NUMBER;

err_num   varchar2(200);
err_msg   varchar2(200);

 BEGIN

   FOR I IN
   (SELECT   OR_DEAL_NO DEALNO,SUM(FACE_VALUE) FACEVALUE
    FROM     DN_TRN_BO_CUSTODIAL_DEAL
    WHERE    SECURITY_CODE  IN    (SELECT  A.SECURITY_CODE
                                   FROM    DN_REF_SECURITY A,
                                           DN_REF_SECURITY_INT_PAY_DATES B
                                   WHERE   A.COUPON_INT>0    AND
                                           A.SECURITY_CODE=B.SECURITY_CODE   AND
                                           B.INT_PAY_DATE=M_PROCESS_DATE) AND
              OR_DEAL_NO IS NOT NULL
    GROUP BY OR_DEAL_NO

    UNION

    SELECT   OR_DEAL_NO DEALNO,SUM(FACE_VALUE) FACEVALUE
    FROM     DN_TRN_BO_CUSTODIAL_DEAL C,
             DN_REF_SECURITY D
    WHERE    C.EFF_VALDATE<=M_PROCESS_DATE    AND
             C.SECURITY_CODE=D.SECURITY_CODE    AND
             D.MATURITY_DATE=M_PROCESS_DATE  AND
             C.OR_DEAL_NO IS NOT NULL
    GROUP BY OR_DEAL_NO
    )



   LOOP

     SELECT COUNT(*)
     INTO   M_COUNT1
     FROM   DN_TRN_OUTP_SALE
     WHERE  DEAL_NO=I.DEALNO AND
            FACE_VALUE=I.FACEVALUE;

     IF M_COUNT1<> 1 THEN
       RAISE_APPLICATION_ERROR(-20201,I.DEALNO||I.FACEVALUE||'MISMATCH WITH THE ACTUAL FACE VALUE IN DN_TRN_OUTP_SALE IN DN_CHECK_CONDITIONS_START!!');
     END IF;

       /*  SELECT COUNT(SUM(E.FACE_VAL))
     INTO   M_COUNT2
     FROM   DN_INV_CUST_DEAL_SERIAL_NO E,DN_TRN_BO_CUSTODIAL_DEAL F
     WHERE  F.OR_DEAL_NO=I.DEALNO AND F.DEAL_NO=E.DEAL_NO AND
            I.FACEVALUE=(SELECT SUM(A.FACE_VAL)
                         FROM   DN_INV_CUST_DEAL_SERIAL_NO A,DN_TRN_BO_CUSTODIAL_DEAL B
                         WHERE  B.OR_DEAL_NO=I.DEALNO AND B.DEAL_NO=A.DEAL_NO
                         GROUP BY A.DEAL_NO)
     GROUP BY E.DEAL_NO  ;*/

 --CHANGED THE ABOVE QUERY ON 20-02-2004 AS FOLLOWS BY NIRMALA

     SELECT COUNT(SUM(E.FACE_VAL))
     INTO   M_COUNT2
     FROM   DN_INV_CUST_DEAL_SERIAL_NO E,DN_TRN_BO_CUSTODIAL_DEAL F
     WHERE  F.OR_DEAL_NO=I.DEALNO AND F.DEAL_NO=E.DEAL_NO AND
            E.SERIAL_NO_STATUS NOT IN ('TRF') AND
            I.FACEVALUE=(SELECT SUM(A.FACE_VAL)
                         FROM   DN_INV_CUST_DEAL_SERIAL_NO A,DN_TRN_BO_CUSTODIAL_DEAL B
                         WHERE  B.OR_DEAL_NO=I.DEALNO AND A.SERIAL_NO_STATUS NOT IN ('TRF') AND  B.DEAL_NO=A.DEAL_NO
                         GROUP BY B.OR_DEAL_NO)
     GROUP BY F.OR_DEAL_NO  ;




     IF M_COUNT2<> 1 THEN
       RAISE_APPLICATION_ERROR(-20201,'MISMATCH WITH THE ACTUAL FACE VALUE IN DN_INV_CUST_DEAL_SERIAL_NO IN DN_CHECK_CONDITIONS_START!!'||I.DEALNO||I.FACEVALUE||M_COUNT2);
     END IF;





   END LOOP;

 /* EXCEPTION
  WHEN OTHERS THEN
   ROLLBACK;
   err_num :=  substr(SQLCODE,1,15);
   err_msg := substr(SQLERRM,1,200) ;
  --INSERT INTO DN_REF_SEQUENCE_LOG VALUES (M_LAST_DAILY,err_num||''||err_msg,'ERROR WHILE RUNNING CUSTODIAL PROCESS IN DN_CHECK_CONDITIONS_START',SYSDATE);
  --COMMIT;
 RAISE_APPLICATION_ERROR(-20201,SQLCODE||SQLERRM||'ERROR WHILE RUNNING CUSTODIAL PROCESS IN DN_CHECK_CONDITIONS_START'||SYSDATE);
*/
END DN_CHECK_CONDITIONS_START;

