--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_CLIENT_CONCENT_PER_L" 
(
 M_SECURITY_CODE        DN_REF_SECURITY.SECURITY_CODE%TYPE,
 M_FACILITY_NO          DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE  
 )
 RETURN NUMBER
 AS
 M_CONCENTRATION_PERCENT      NUMBER;
 /*
 || CREATED BY : WARUNA SRI JAYANATH
 || CREATEND OM : LBMARGIN 2012-03-02
 ||
 */
 BEGIN
 
 BEGIN  

  SELECT  NVL(A.PERCENTAGE_APP_LAST,0)    INTO M_CONCENTRATION_PERCENT
  FROM FA_PY_INCREASE_AVAILABILITY A 
  WHERE 
  TYPE                                = 'CONCENTRATION_ADJ' 
  AND FACILITY_NO                     = M_FACILITY_NO 
  AND SECURITY_CODE                   = M_SECURITY_CODE
  AND STATUS                          = 'A' 
  AND (THIS_PAYMENT_INCREASE_STATUS   = 'Y' 
       OR PERMANENT_INCREASE_STATUS   = 'Y'  
       OR THIS_PERIOD_INCREASE_DATE >= (SELECT A.LAST_DAILY 
                                          FROM DN_SYS_PARAMETER A)
         );
 
 EXCEPTION
    WHEN OTHERS THEN 
      
   SELECT  A.CONCENTRATION_PERCENT  INTO   M_CONCENTRATION_PERCENT
   FROM DN_REF_SECURITY A 
   WHERE A.SECURITY_CODE=M_SECURITY_CODE;
     
 END ;
 

  
   
   RETURN  M_CONCENTRATION_PERCENT;
--A.SECURITY_CODE, A.EXT_SECURITY_CODE,
 END ; 

/
