--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_TOTAL_RECEIVED" 
(
 PORT           DN_TRN_BO_SETTL_RECEIPT_BULK.SELL_PORTFOLIO_CODE%TYPE,
 CP_CODE        DN_TRN_BO_SETTL_RECEIPT_BULK.ID_PORTFOLIO_CODE%TYPE,
 EFFDATE        VARCHAR2
)
 RETURN NUMBER
 AS
 M_TOTAL_RECEIVED       DN_TRN_BO_SETTL_RECEIPT_BULK.REC_AMOUNT%TYPE;


 BEGIN
                 
  SELECT  SUM(REC_AMOUNT) INTO M_TOTAL_RECEIVED
  FROM DN_TRN_BO_SETTL_RECEIPT_BULK A WHERE 
  SELL_PORTFOLIO_CODE=PORT AND 
  EFF_VALDATE=TO_DATE(EFFDATE,'DD/MM/YYYY')AND 
  ID_PORTFOLIO_CODE=CP_CODE
  AND REC_STATUS='CONF';
                 
                  


 RETURN  NVL(M_TOTAL_RECEIVED,0);

END DN_GET_TOTAL_RECEIVED;

