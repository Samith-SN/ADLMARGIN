  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_REBATE_PAY_PREV_REF_NO" 
 ( 
   M_PAYMENT_NO        DN_TRN_REBATE_PAYMENT.PAYMENT_NO%TYPE
   )

-- FUNCTION     : THIS RETURNS TOTAL  PAYMENTS
-- SYSTEM       : DEALNET SYSTEM
-- CREATED BY   :
-- CREATED ON   :K.M.W.S.JAYANATH
RETURN  VARCHAR

IS
TOTAL NUMBER:=0;
M_PAY_COUNT_1 NUMBER:=0; 
M_PORTFOLIO_CODE      DN_TRN_REBATE_PAYMENT.PORTFOLIO_CODE%TYPE;
M_EFF_VALDATE         DN_TRN_REBATE_PAYMENT.EFF_VALDATE%TYPE;  
MM_PAYMENT_NO         DN_TRN_REBATE_PAYMENT.PAYMENT_NO%TYPE;
M_REF_NO              VARCHAR(15);
M_BROKER              DN_TRN_REBATE_PAYMENT.ID_PORTFOLIO_CODE%TYPE; 
M_ENTDATE             DN_TRN_REBATE_PAYMENT.ENTDATE%TYPE;          
BEGIN


        SELECT COUNT(A.PAYMENT_NO) INTO M_PAY_COUNT_1 
        FROM DN_TRN_REBATE_PAYMENT A
        WHERE A.PAYMENT_NO=M_PAYMENT_NO
        AND A.PAY_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') ;
       
        IF M_PAY_COUNT_1 >0 THEN
        
        SELECT A.PORTFOLIO_CODE,A.EFF_VALDATE,A.ID_PORTFOLIO_CODE,A.ENTDATE INTO M_PORTFOLIO_CODE ,M_EFF_VALDATE,M_BROKER,M_ENTDATE
        FROM DN_TRN_REBATE_PAYMENT A
        WHERE A.PAYMENT_NO=M_PAYMENT_NO
        AND A.PAY_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') ;
        
        
        
        SELECT  A.PAYMENT_NO  INTO MM_PAYMENT_NO   
        FROM DN_TRN_REBATE_PAYMENT A
        WHERE 
      
         A.PORTFOLIO_CODE = M_PORTFOLIO_CODE 
        AND A.EFF_VALDATE    = M_EFF_VALDATE
        AND A.ID_PORTFOLIO_CODE = M_BROKER
        AND A.PAY_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT')
        AND ENTDATE<M_ENTDATE
        AND ENTDATE IN (
                    SELECT  MAX(ENTDATE)   
                    FROM DN_TRN_REBATE_PAYMENT C
                    WHERE 
                     C.PORTFOLIO_CODE = M_PORTFOLIO_CODE 
                    AND C.EFF_VALDATE    = M_EFF_VALDATE
                    AND C.ID_PORTFOLIO_CODE = M_BROKER
                    AND C.PAY_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') 
        )
        ;
       
        M_REF_NO:= MM_PAYMENT_NO;                       
        END IF;
        
        


RETURN M_REF_NO;

END ; 

