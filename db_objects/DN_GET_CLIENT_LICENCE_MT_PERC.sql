--------------------------------------------------------
--  DDL for Function DN_GET_CLIENT_LICENCE_MT_PERC
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_CLIENT_LICENCE_MT_PERC" 
(
 M_SECURITY_CODE        DN_REF_SECURITY.SECURITY_CODE%TYPE,
 M_FACILITY_NO          DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE,
 M_AVAIL_TYPE           VARCHAR
 )
 RETURN NUMBER
 AS
 M_LICENCE_MT_PERCENT      NUMBER;

 BEGIN


--A.SECURITY_CODE, A.EXT_SECURITY_CODE,
IF M_AVAIL_TYPE ='APPROVED' THEN
  BEGIN  

  SELECT  NVL(A.PERCENTAGE_APP,0)    INTO M_LICENCE_MT_PERCENT
  FROM FA_PY_INCREASE_AVAILABILITY A 
  WHERE 
  TYPE                                = 'COMPANY_VALUATION' 
  AND FACILITY_NO                     = M_FACILITY_NO 
  AND SECURITY_CODE                   = M_SECURITY_CODE
  AND STATUS                          = 'A' 
  AND (THIS_PAYMENT_INCREASE_STATUS   = 'Y' 
       OR PERMANENT_INCREASE_STATUS   = 'Y'  
       OR THIS_PERIOD_INCREASE_DATE >= (SELECT A.LAST_DAILY 
                                          FROM DN_SYS_PARAMETER A)
         );
 
 EXCEPTION
    WHEN OTHERS THEN 
      
   SELECT  NVL(A.LICENCE_MT_PERCENT,0)  INTO   M_LICENCE_MT_PERCENT
   FROM DN_REF_SECURITY A 
   WHERE A.SECURITY_CODE=M_SECURITY_CODE;
     
 END ; 
 
 ELSIF  M_AVAIL_TYPE ='RECOMMENDED' THEN
 
    BEGIN  

  SELECT  NVL(A.PERCENTAGE_REC,0)    INTO M_LICENCE_MT_PERCENT
  FROM FA_PY_INCREASE_AVAILABILITY A 
  WHERE 
  TYPE                                = 'COMPANY_VALUATION' 
  AND FACILITY_NO                     = M_FACILITY_NO 
  AND SECURITY_CODE                   = M_SECURITY_CODE
  AND STATUS                          = 'A' 
  AND (THIS_PAYMENT_INCREASE_STATUS   = 'Y' 
       OR PERMANENT_INCREASE_STATUS   = 'Y'  
       OR THIS_PERIOD_INCREASE_DATE >= (SELECT A.LAST_DAILY 
                                          FROM DN_SYS_PARAMETER A)
         );
 
 EXCEPTION
    WHEN OTHERS THEN 
      
   SELECT  NVL(A.LICENCE_MT_PERCENT,0)  INTO   M_LICENCE_MT_PERCENT
   FROM DN_REF_SECURITY A 
   WHERE A.SECURITY_CODE=M_SECURITY_CODE;
     
 END ;
 
 END IF;
 

 RETURN  M_LICENCE_MT_PERCENT;   

 END ; 

/
