set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_MARKET_VALUES_ACCOUNT_ENTRY" 
   (
    M_VALUE_DATE                VARCHAR2
   )
IS


 CURSOR C1 IS
SELECT     PORTFOLIO_CODE,INST_TYPE,GAINLOSS,ENTDATE,
VALUE_DATE,DOCREF_NO AA,DOCREF_NO_REVERSE
FROM DN_TRN_MARKET_RATE_EQUITY WHERE
TO_DATE(TO_CHAR(VALUE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') = TO_DATE(M_VALUE_DATE,'DD-MM-YYYY')
AND INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT
 WHERE INST_CAT ='EQUITY' AND ACC_ENTRY='Y');

  MM_GAINLOSS                 DN_TRN_MARKET_RATE.GAINLOSS%TYPE;
  I                           NUMBER;
  M_CNT                       NUMBER;
  M_CNT1                      NUMBER;
  M_DOC_NO                    DN_TRN_MARKET_RATE_EQUITY.DOCREF_NO%TYPE;
  M_REV_NO                    DN_TRN_MARKET_RATE_EQUITY.DOCREF_NO_REVERSE%TYPE;


BEGIN




FOR I IN C1 LOOP
DN_ACC_MARKET_RATE_EQUITY(I.AA);
END LOOP;




 COMMIT;

END DN_MARKET_VALUES_ACCOUNT_ENTRY;

/
