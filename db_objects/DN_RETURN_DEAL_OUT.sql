--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_RETURN_DEAL_OUT" 
(
  M_DEAL_NO   DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_NO%TYPE,
   M_SERIAL_NO   DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_NO%TYPE
 )RETURN VARCHAR2


AS

  MDEALNO DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_NO%TYPE;
  MENDDATE DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_NO%TYPE;
  MCNT NUMBER ;

BEGIN

 SELECT COUNT(*) INTO MCNT FROM DN_INV_OUTPS_DEAL_SERIAL_NO A, DN_INV_OUTPS_DEAL_SERNO_ALLO B
 WHERE A.DEAL_NO=M_DEAL_NO AND
 A.SERIAL_NO=B.SERIAL_NO AND
 A.SERIAL_NO=M_SERIAL_NO AND
 A.DEAL_NO=B.PREV_DEAL_NO AND A.PORTFOLIO_CODE=B.PORTFOLIO_CODE
 AND A.SECURITY_CODE =B.SECURITY_CODE AND A.SERIAL_NO =B.SERIAL_NO AND A.INST_TYPE=B.INST_TYPE
 AND B.END_DATE > SYSDATE  ;

 IF MCNT > 0 THEN

 SELECT B.DEAL_NO,MAX(B.END_DATE)
 INTO MDEALNO ,MENDDATE
 FROM DN_INV_OUTPS_DEAL_SERIAL_NO A, DN_INV_OUTPS_DEAL_SERNO_ALLO B
 WHERE A.DEAL_NO=M_DEAL_NO  AND
   A.SERIAL_NO=M_SERIAL_NO AND
A.SERIAL_NO=B.SERIAL_NO AND
       A.DEAL_NO=B.PREV_DEAL_NO AND
       A.PORTFOLIO_CODE=B.PORTFOLIO_CODE AND
       A.SECURITY_CODE =B.SECURITY_CODE AND
       A.SERIAL_NO =B.SERIAL_NO AND
       A.INST_TYPE=B.INST_TYPE AND
       B.END_DATE > SYSDATE
  GROUP BY  B.DEAL_NO ;

 END IF;

 RETURN MDEALNO;

END DN_RETURN_DEAL_OUT;


