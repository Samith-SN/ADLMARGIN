  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_LINK_BO_SETTL_REC" 
   (
   M_SUSPENSE_ENTRY_TYPE     DN_TRN_BO_SETTL_RECEIPT.SUSPENSE_ENTRY_TYPE%TYPE,
   M_PORTFOLIO_CODE          DN_ACC_LICENCEE_GEN_ACCOUNT.PORTFOLIO_CODE%TYPE,
   M_ID_PORTFOLIO_CODE       DN_ACC_LICENCEE_GEN_ACCOUNT.DN_PORTFOLIO_CODE%TYPE,
   M_TRNDATE                 DN_ACC_LICENCEE_GEN_ACCOUNT.TRNDATE%TYPE,
   M_TRNAMOUNT               DN_ACC_LICENCEE_GEN_ACCOUNT.TRNAMOUNT%TYPE,
   M_DOCREFNO                DN_ACC_LICENCEE_GEN_ACCOUNT.DOCREFNO%TYPE,
   M_ACC_SYS_REFNO           DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE,
   M_DEALNO                  DN_TRN_BO_SETTL_RECEIPT.SUS_REF_NO%TYPE--CURRENCY

   )

   IS

    -- Procedue     : Link Settlement receipts to the accounting
    -- System       : Dealnet system
    -- Created by   : D.P. Pubudu Thushara
    -- Created on   : 02/09/1999

    M_PORT_CODE_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_PORT_CODE_OWNED_BY_MBFSL     DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;
    M_ID_PORT_CODE_PF_TYPE         DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_ID_PORT_CODE_OWNED_BY_MBFSL  DN_REF_PORTFOLIO.OWNED_BY_MBFSL%TYPE;
    M_COUNT1                       INTEGER;--CURRENCY
BEGIN

--   RAISE_APPLICATION_ERROR(-20201,'M_SUSPENSE_ENTRY_TYPE   '||M_SUSPENSE_ENTRY_TYPE);
--RAISE_APPLICATION_ERROR(-20201,'M_TRNDATE=' || M_TRNDATE);
   SELECT
      B.PF_TYPE,
      B.OWNED_BY_MBFSL,
      C.PF_TYPE,
      C.OWNED_BY_MBFSL
      INTO M_PORT_CODE_PF_TYPE,M_PORT_CODE_OWNED_BY_MBFSL,
           M_ID_PORT_CODE_PF_TYPE,M_ID_PORT_CODE_OWNED_BY_MBFSL
   FROM
      DN_REF_PORTFOLIO B,
      DN_REF_PORTFOLIO C
   WHERE
      B.PORTFOLIO_CODE=M_PORTFOLIO_CODE
      AND
      C.PORTFOLIO_CODE=M_ID_PORTFOLIO_CODE;

  IF M_SUSPENSE_ENTRY_TYPE='D' THEN

      IF M_PORT_CODE_OWNED_BY_MBFSL='Y' AND   M_ID_PORT_CODE_PF_TYPE='C' THEN
       /* -------CURRENCY --------------------------
        SELECT COUNT(*)
        INTO   M_COUNT1
        FROM   DN_ACC_SUS_RECEIPT
        WHERE  SUS_REF_NO=M_DEALNO AND
               REC_FROM_INT_BAL_AMT_CURR > 0 AND
               RECEIVER = M_PORTFOLIO_CODE AND
               PAYER = M_ID_PORTFOLIO_CODE;
        -------CURRENCY --------------------------

        IF(M_COUNT1 > 0 )THEN--CURRENCY
          DN_ACC_A_2_9_CURR(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO,M_DEALNO);--CURRENCY
        ELSE--CURRENCY*/
          DN_ACC_A_2_9(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
       -- END IF; --CURRENCY



      ELSIF M_PORT_CODE_PF_TYPE='C' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='Y' THEN

         DN_ACC_A_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='P' AND M_PORT_CODE_OWNED_BY_MBFSL='N' AND M_ID_PORT_CODE_PF_TYPE='C' THEN

         DN_ACC_B_2_12(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='C' AND M_ID_PORT_CODE_PF_TYPE='P' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='N' THEN

         DN_ACC_B_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='P' AND M_PORT_CODE_OWNED_BY_MBFSL='N' AND  M_ID_PORT_CODE_OWNED_BY_MBFSL='Y' THEN

         DN_ACC_B_2_12(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
         --DN_ACC_A_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_OWNED_BY_MBFSL='Y' AND  M_ID_PORT_CODE_PF_TYPE='P' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='N' THEN

         --DN_ACC_B_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
         DN_ACC_A_2_9(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);


      ELSIF M_PORT_CODE_OWNED_BY_MBFSL='Y' AND   M_ID_PORT_CODE_OWNED_BY_MBFSL='Y' THEN

         --DN_ACC_A_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
         DN_ACC_A_2_9(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);


      ELSIF M_PORT_CODE_PF_TYPE='P' AND M_PORT_CODE_OWNED_BY_MBFSL='N' AND  M_ID_PORT_CODE_PF_TYPE='P' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='N' THEN

         --DN_ACC_B_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
         DN_ACC_B_2_12(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      END IF;

  ------Added by Ruwan liyanage for save periodic interest recods, on 22-03-2001--------------------------------------------

  ELSIF M_SUSPENSE_ENTRY_TYPE='I' THEN

      IF M_PORT_CODE_OWNED_BY_MBFSL='Y' AND   M_ID_PORT_CODE_PF_TYPE='C' THEN

         DN_ACC_A_2_9(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='C' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='Y' THEN

         DN_ACC_A_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='P' AND M_PORT_CODE_OWNED_BY_MBFSL='N' AND M_ID_PORT_CODE_PF_TYPE='C' THEN

         DN_ACC_B_2_12(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='C' AND M_ID_PORT_CODE_PF_TYPE='P' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='N' THEN

         DN_ACC_B_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='P' AND M_PORT_CODE_OWNED_BY_MBFSL='N' AND  M_ID_PORT_CODE_OWNED_BY_MBFSL='Y' THEN

         DN_ACC_B_2_12(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
         --DN_ACC_A_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_OWNED_BY_MBFSL='Y' AND  M_ID_PORT_CODE_PF_TYPE='P' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='N' THEN

         --DN_ACC_B_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
         DN_ACC_A_2_9(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);


      ELSIF M_PORT_CODE_OWNED_BY_MBFSL='Y' AND   M_ID_PORT_CODE_OWNED_BY_MBFSL='Y' THEN

         --DN_ACC_A_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
         DN_ACC_A_2_9(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);


      ELSIF M_PORT_CODE_PF_TYPE='P' AND M_PORT_CODE_OWNED_BY_MBFSL='N' AND  M_ID_PORT_CODE_PF_TYPE='P' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='N' THEN

         --DN_ACC_B_2_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
         DN_ACC_B_2_12(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      END IF;
--                                      end                                 --


ELSIF M_SUSPENSE_ENTRY_TYPE='C' THEN

      IF M_PORT_CODE_OWNED_BY_MBFSL='Y' THEN --AND   M_ID_PORT_CODE_PF_TYPE='C' THEN
       -------CURRENCY --------------------------
        SELECT COUNT(*)
        INTO   M_COUNT1
        FROM   DN_ACC_SUS_RECEIPT
        WHERE  SUS_REF_NO=M_DEALNO AND
               REC_FROM_INT_BAL_AMT_CURR > 0 AND
               RECEIVER = M_PORTFOLIO_CODE AND
               PAYER = M_ID_PORTFOLIO_CODE;
        -------CURRENCY --------------------------

        IF(M_COUNT1 > 0 )THEN--CURRENCY
          DN_ACC_A_2_5_CURR(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO,M_DEALNO);--CURRENCY
        ELSE--CURRENCY
          DN_ACC_A_2_5(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
        END IF;--CURRENCY
          -- DN_ACC_A_2_5(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='P' AND M_PORT_CODE_OWNED_BY_MBFSL='N' THEN --AND M_ID_PORT_CODE_PF_TYPE='C' THEN

         DN_ACC_B_2_6(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      END IF;


ELSIF M_SUSPENSE_ENTRY_TYPE='M' THEN

      IF M_PORT_CODE_OWNED_BY_MBFSL='Y' THEN --AND   M_ID_PORT_CODE_PF_TYPE='C' THEN
        -------CURRENCY --------------------------
        SELECT COUNT(*)
        INTO   M_COUNT1
        FROM   DN_ACC_SUS_RECEIPT
        WHERE  SUS_REF_NO=M_DEALNO AND
               REC_FROM_INT_BAL_AMT_CURR > 0 AND
               RECEIVER = M_PORTFOLIO_CODE AND
               PAYER = M_ID_PORTFOLIO_CODE;
        -------CURRENCY --------------------------

        IF(M_COUNT1 > 0 )THEN--CURRENCY
          DN_ACC_A_2_7_CURR(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO,M_DEALNO);--CURRENCY
        ELSE--CURRENCY
          DN_ACC_A_2_7(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
        END IF;--CURRENCY
          --DN_ACC_A_2_7(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='P' AND M_PORT_CODE_OWNED_BY_MBFSL='N' THEN --AND M_ID_PORT_CODE_PF_TYPE='C' THEN

         DN_ACC_B_2_9(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      END IF;

ELSIF M_SUSPENSE_ENTRY_TYPE='CACC' THEN

      IF M_PORT_CODE_PF_TYPE='P' AND M_PORT_CODE_OWNED_BY_MBFSL='N' AND  M_ID_PORT_CODE_OWNED_BY_MBFSL='Y' THEN

         DN_ACC_B_2_7(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_OWNED_BY_MBFSL='Y' AND  M_ID_PORT_CODE_PF_TYPE='P' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='N' THEN

         DN_ACC_B_2_3(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='P' AND M_PORT_CODE_OWNED_BY_MBFSL='N' AND  M_ID_PORT_CODE_PF_TYPE='P' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='N' THEN

         --DN_ACC_B_2_7(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
         DN_ACC_B_2_3(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_OWNED_BY_MBFSL='Y' AND  M_ID_PORT_CODE_PF_TYPE='C' THEN

         DN_ACC_S_1(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_PF_TYPE='C' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='Y'  THEN

         DN_ACC_S_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      ELSIF M_PORT_CODE_OWNED_BY_MBFSL='Y' AND M_ID_PORT_CODE_OWNED_BY_MBFSL='Y'  THEN

         DN_ACC_S_1(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);
         --DN_ACC_S_2(M_PORTFOLIO_CODE,M_ID_PORTFOLIO_CODE,M_TRNDATE,M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO);

      END IF;

END IF;

END DN_ACC_LINK_BO_SETTL_REC;

