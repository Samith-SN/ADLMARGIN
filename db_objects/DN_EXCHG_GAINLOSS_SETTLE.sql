--------------------------------------------------------
--  DDL for Procedure DN_EXCHG_GAINLOSS_SETTLE
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_EXCHG_GAINLOSS_SETTLE" 
(
    M_DEAL_NO                 DN_TRN_REPO_SETTLEMENT.DEAL_NO%TYPE,
    M_CURR_CODE               DN_TRN_REPO_SETTLEMENT.CURR_CODE%TYPE
)
AS

    M_BORR_PORTFOLIO_CODE     DN_TRN_REPO_ROLLOVER.BORR_PORTFOLIO_CODE%TYPE;
    M_LEND_PORTFOLIO_CODE     DN_TRN_REPO_ROLLOVER.LEND_PORTFOLIO_CODE%TYPE;
    M_BORR_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_LEND_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_PRIOR_DEAL_NO           DN_TRN_REPO_SETTLEMENT.PRIOR_DEAL_NO%TYPE;
    M_PRIOR_DEAL_LEG2_VALUE   DN_TRN_REPO_ROLLOVER.LEG2_VALUE%TYPE;
    M_PAYMENT_TO_LEND         DN_TRN_REPO_SETTLEMENT.PAYMENT_TO_LEND%TYPE;
    M_CURRENCY_VALUE          DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE;
    F1_LEG1_VALUE             DN_TRN_DEAL_CURRENCY.LEG1_VALUE%TYPE;
    F2_LEG1_VALUE             DN_TRN_DEAL_CURRENCY.LEG1_VALUE%TYPE;
    M_GAIN_LOSS               DN_TRN_DEAL_CURRENCY.LEG1_VALUE%TYPE;
    M_EFF_VALDATE              DN_TRN_REPO_SETTLEMENT.SETTLE_DATE%TYPE;
BEGIN

    ---   CREATED BY NIRMALA
    --    ON 19-12-2001
    --    FOR EXCHANGE LOSS/GAIN CALCULATION -REPO SETTLEMENT --CURRENCY


-----------------------------------------------------------------------------------------
 SELECT   A.PRIOR_DEAL_NO,A.PAYMENT_TO_LEND,A.SETTLE_DATE
 INTO     M_PRIOR_DEAL_NO,M_PAYMENT_TO_LEND,M_EFF_VALDATE
 FROM     DN_TRN_REPO_SETTLEMENT A
 WHERE    A.DEAL_NO=M_DEAL_NO ;
------------------------------------------------------------------------------------------
 SELECT  CURRENCY_VALUE
 INTO    M_CURRENCY_VALUE
 FROM    DN_REF_EXCHANGE_RATES
 WHERE   CURR_CODE=M_CURR_CODE;
----------------------------------------------------------------------------------------------

IF SUBSTR(M_PRIOR_DEAL_NO,1,2)='RF' THEN

   SELECT    A.LEG2_VALUE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,B.PF_TYPE,C.PF_TYPE
   INTO      M_PRIOR_DEAL_LEG2_VALUE,M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE,
             M_BORR_PF_TYPE,M_LEND_PF_TYPE

   FROM      DN_TRN_REPO_FRESH A,
             DN_REF_PORTFOLIO B,
             DN_REF_PORTFOLIO C

   WHERE     A.DEAL_NO=M_PRIOR_DEAL_NO  AND
             A.BORR_PORTFOLIO_CODE=B.PORTFOLIO_CODE   AND
             A.LEND_PORTFOLIO_CODE=C.PORTFOLIO_CODE;

ELSIF SUBSTR(M_PRIOR_DEAL_NO,1,2)='RR' THEN


   SELECT    A.LEG2_VALUE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,B.PF_TYPE,C.PF_TYPE
   INTO      M_PRIOR_DEAL_LEG2_VALUE,M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE,
             M_BORR_PF_TYPE,M_LEND_PF_TYPE

   FROM      DN_TRN_REPO_ROLLOVER A,
             DN_REF_PORTFOLIO B,
             DN_REF_PORTFOLIO C

   WHERE     A.DEAL_NO=M_PRIOR_DEAL_NO  AND
             A.BORR_PORTFOLIO_CODE=B.PORTFOLIO_CODE   AND
             A.LEND_PORTFOLIO_CODE=C.PORTFOLIO_CODE;

ELSIF SUBSTR(M_PRIOR_DEAL_NO,1,2)='PI' THEN

   SELECT    A.LEG2_VALUE,A.BORR_PORTFOLIO_CODE,A.LEND_PORTFOLIO_CODE,B.PF_TYPE,C.PF_TYPE
   INTO      M_PRIOR_DEAL_LEG2_VALUE,M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE,
             M_BORR_PF_TYPE,M_LEND_PF_TYPE

   FROM      DN_TRN_REPO_PERIOD_INT A,
             DN_REF_PORTFOLIO B,
             DN_REF_PORTFOLIO C

   WHERE     A.DEAL_NO=M_PRIOR_DEAL_NO  AND
             A.BORR_PORTFOLIO_CODE=B.PORTFOLIO_CODE   AND
             A.LEND_PORTFOLIO_CODE=C.PORTFOLIO_CODE;

END IF;
---------------------------------------------------------------------------------------------
 SELECT LEG1_VALUE --CURRENT CONFIRM DEAL_NO'S LEG1_VALUE IN CURRENCY
 INTO   F2_LEG1_VALUE
 FROM   DN_TRN_DEAL_CURRENCY
 WHERE  DEAL_NO=M_DEAL_NO;

 SELECT LEG2_VALUE --PREVIOUS DEAL_NO'S LEG1_VALUE IN CURRENCY
 INTO   F1_LEG1_VALUE
 FROM   DN_TRN_DEAL_CURRENCY
 WHERE  DEAL_NO=M_PRIOR_DEAL_NO;

 --------------------------------------------------------------------------------------------
 --------------------------------------------------------------------------------------------
 --------------------------------------------------------------------------------------------
 IF M_LEND_PF_TYPE='P' THEN --PORTFOLIO TYPE


       IF M_PAYMENT_TO_LEND<M_PRIOR_DEAL_LEG2_VALUE THEN --LOSS
           M_GAIN_LOSS:=((F2_LEG1_VALUE*M_CURRENCY_VALUE)-M_PRIOR_DEAL_LEG2_VALUE);
           --302  CR
          -- 116  DR
          INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_LEND_PORTFOLIO_CODE,M_BORR_PORTFOLIO_CODE,M_EFF_VALDATE,'302','CR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-LOSS','116');
          ------------
          INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_LEND_PORTFOLIO_CODE,M_BORR_PORTFOLIO_CODE,M_EFF_VALDATE,'116','DR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-LOSS','302');


       ELSE --GAIN
           M_GAIN_LOSS:=((F2_LEG1_VALUE*M_CURRENCY_VALUE)-M_PRIOR_DEAL_LEG2_VALUE);
           --302  DR
           --115  CR
           INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_LEND_PORTFOLIO_CODE,M_BORR_PORTFOLIO_CODE,M_EFF_VALDATE,'302','DR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-GAIN','115');
          ------------
          INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_LEND_PORTFOLIO_CODE,M_BORR_PORTFOLIO_CODE,M_EFF_VALDATE,'115','CR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-GAIN','302');

       END IF;

-------------------------------------------------------------------------------------------
-------------------------------------------------------------------------------------------
ELSIF M_BORR_PF_TYPE='P' THEN --PORTFOLIO TYPE

       IF M_PAYMENT_TO_LEND>M_PRIOR_DEAL_LEG2_VALUE THEN --LOSS
           M_GAIN_LOSS:=((F2_LEG1_VALUE*M_CURRENCY_VALUE)-M_PRIOR_DEAL_LEG2_VALUE);
          -- 302  CR
           --116  DR
           INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE,M_EFF_VALDATE,'302','CR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-LOSS','116');
          ------------
          INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_BORR_PORTFOLIO_CODE,M_LEND_PORTFOLIO_CODE,M_EFF_VALDATE,'116','DR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-LOSS','302');


       ELSE --GAIN
           M_GAIN_LOSS:=((F2_LEG1_VALUE*M_CURRENCY_VALUE)-M_PRIOR_DEAL_LEG2_VALUE);
          -- 302  DR
           --115  CR
          INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_LEND_PORTFOLIO_CODE,M_BORR_PORTFOLIO_CODE,M_EFF_VALDATE,'302','DR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-GAIN','115');
          ------------
          INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_LEND_PORTFOLIO_CODE,M_BORR_PORTFOLIO_CODE,M_EFF_VALDATE,'115','CR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-GAIN','302');


       END IF;

END IF;--PORTFOLIO TYPE
---------------------------------------------------------------------------------------------
---------------------------------------------------------------------------------------------
---------------------------------------------------------------------------------------------
--COMMIT;
END DN_EXCHG_GAINLOSS_SETTLE;

