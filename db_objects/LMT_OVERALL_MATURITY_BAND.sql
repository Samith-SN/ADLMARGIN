set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."LMT_OVERALL_MATURITY_BAND" 
IS
 /*
	PURPOSE OF THE PROCEDURE : DAY END ROUTINE FOR THE OVRALL MATURITY BAND
	CREATED BY :DAYAN
  DATE: 2000/01/03
  COMMENT: THIS DOES CONTAIN A CURSOR
	*/

CURSOR MYCURSOR IS
SELECT CEIL(SYSDATE-B.MATURITY_DATE),SUM(A.FACE_VALUE)
FROM DN_TRN_OUTP_SALE A,
     DN_REF_SECURITY B
WHERE A.SECURITY_CODE=B.SECURITY_CODE AND
      A.EFF_VALDATE<=SYSDATE AND B.MATURITY_DATE<SYSDATE
      GROUP BY CEIL(SYSDATE-B.MATURITY_DATE);
 M_MATURITY_DATE  NUMBER;
 M_FACE_VALUE  NUMBER;
 M_LIMIT_CODE  CHAR;
 M_COUNT       NUMBER;
 M_ENTERED_AMT NUMBER;
BEGIN
  OPEN MYCURSOR;
  LOOP
    FETCH MYCURSOR INTO M_MATURITY_DATE,M_FACE_VALUE ;
    /*THIS TO SELECT RELEVENT LIMIT CODE FROM THE TABLE*/
		SELECT LIMIT_CODE INTO M_LIMIT_CODE FROM LMT_STR_OVRL_MATU
    WHERE M_MATURITY_DATE BETWEEN START_DAYS AND END_DAYS
    AND M_FACE_VALUE BETWEEN  START_AMOUNT AND END_AMOUNT AND CONDITION='B';

		/****************************************************************************/
	  IF(M_LIMIT_CODE IS NULL) THEN
		SELECT LIMIT_CODE INTO M_LIMIT_CODE FROM LMT_STR_OVRL_MATU
    WHERE M_MATURITY_DATE BETWEEN START_DAYS AND END_DAYS AND CONDITION='G';
	 	END IF;

		/*###################################THIS TO CHECK WHETHER SELECTED LMIT_CODE IS ACTIVATED#############*/
	  IF(M_LIMIT_CODE IS NOT NULL) THEN
       M_COUNT:=0;
			SELECT COUNT(*) INTO M_COUNT  FROM LMT_ACT_DETAILS
      WHERE LIMIT_CODE=M_LIMIT_CODE AND ACTIVE_STATUS='Y';
		  /*$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$*/
		  IF(M_COUNT=0)THEN
				INSERT INTO LMT_EXC_HIS
				(LIMIT_CODE,VIOLATED_DATE,VIOLATED_BY,ACTIVATED_TYPE,HIS_ACTIVATED_TYPE)
				SELECT LIMIT_CODE,VIOLATED_DATE,VIOLATED_BY,ACTIVATED_TYPE,ACTIVATED_TYPE
				FROM LMT_EXC_CURRENT;

				DELETE LMT_EXC_CURRENT
			  WHERE LIMIT_CODE=M_LIMIT_CODE;

				INSERT INTO LMT_EXC_CURRENT
			  (LIMIT_CODE,VIOLATED_DATE)
			  VALUES
			  (M_LIMIT_CODE,SYSDATE);
		    NULL;
			ELSIF(M_COUNT>0) THEN
				INSERT INTO LMT_EXC_HIS
				(LIMIT_CODE,VIOLATED_DATE,VIOLATED_BY,ACTIVATED_TYPE,HIS_ACTIVATED_TYPE)
				SELECT LIMIT_CODE,VIOLATED_DATE,VIOLATED_BY,ACTIVATED_TYPE,ACTIVATED_TYPE
				FROM LMT_EXC_CURRENT;

				DELETE LMT_EXC_CURRENT
			  WHERE LIMIT_CODE=M_LIMIT_CODE;

			END IF;
		END IF;

  EXIT WHEN MYCURSOR%NOTFOUND;

  END LOOP;
  CLOSE MYCURSOR;

END LMT_OVERALL_MATURITY_BAND;

/
