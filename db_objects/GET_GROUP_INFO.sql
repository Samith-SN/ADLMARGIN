  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."GET_GROUP_INFO" 
(
M_GROUP_DEALNO       DN_TRN_OUTP_SALE.GROUP_DEALNO%TYPE
)RETURN VARCHAR2
AS
M1 NUMBER;M2 NUMBER;
M3 NUMBER;M4 NUMBER;
M5 NUMBER;M6 NUMBER;
M7 NUMBER;

BEGIN

SELECT  NVL(SUM(H.FACE_VALUE),0), NVL(SUM(J.LEG2_VALUE),0), NVL(SUM(H.COST),0),
        NVL(SUM(J.LEG1_VALUE),0), NVL(SUM(H.ACC_INT),0),
        NVL(SUM(J.ACC_INT),0), NVL(SUM(H.SETTLE_VALUE),0)
INTO    M1,M2,M3,M4,M5,M6,M7
FROM    DN_TRN_OUTP_SALE H,
        DN_TRN_DEAL_CURRENCY J
WHERE   H.GROUP_DEALNO= M_GROUP_DEALNO AND
        H.DEAL_NO=J.DEAL_NO(+);

RETURN  M1||','||M2||','||M3||','||M4||','||M5||','||M6||','||M7 ;

END GET_GROUP_INFO;

