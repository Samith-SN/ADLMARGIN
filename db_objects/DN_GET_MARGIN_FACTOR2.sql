  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_MARGIN_FACTOR2" 
(
  M_PORTFOLIO_CODE IN DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE,
  MM_DATE              VARCHAR2--,
  --M_AMOUNT            NUMBER
 )
  RETURN NUMBER IS

  M_MARGIN_FACTOR            NUMBER;
  M_COUNT                    NUMBER;
M_DATE              VARCHAR2(10);
BEGIN

 SELECT TO_CHAR(MAX(TRN_DATE),'DD-MM-YYYY')
 INTO   M_DATE
 FROM   ADLMARGIN.DN_REP_MARGIN_CALL;

 SELECT COUNT(*)
 INTO   M_COUNT
 FROM   DN_REP_MARGIN_CALL
 WHERE  TRN_DATE       = TO_DATE(M_DATE,'DD-MM-YYYY') AND
        PORTFOLIO_CODE = M_PORTFOLIO_CODE;

 IF M_COUNT>0 THEN
 SELECT SUM(FACE_VAL*MARKET_RATE)
 INTO   M_MARGIN_FACTOR
 FROM   DN_REP_MARGIN_CALL
 WHERE  TRN_DATE       = TO_DATE(M_DATE,'DD-MM-YYYY') AND
        PORTFOLIO_CODE = M_PORTFOLIO_CODE;


 IF M_MARGIN_FACTOR =0 THEN
 M_MARGIN_FACTOR:=0;
 ELSE
 SELECT DISTINCT ((REPO_LEG2+NET_CASHFLOWS+INT_AMOUNT)/M_MARGIN_FACTOR)*100
 INTO   M_MARGIN_FACTOR
 FROM   DN_REP_MARGIN_CALL
 WHERE  TRN_DATE       = TO_DATE(M_DATE,'DD-MM-YYYY') AND
        PORTFOLIO_CODE = M_PORTFOLIO_CODE;
 END IF;
 ELSE
    M_MARGIN_FACTOR:=0;
 END IF;

 RETURN M_MARGIN_FACTOR;

/*EXCEPTION
   WHEN OTHERS THEN
       RAISE_APPLICATION_ERROR(-20001,*/
END; -- Function WD_GET_PORTFOLIO_NAME

