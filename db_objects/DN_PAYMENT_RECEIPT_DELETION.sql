--------------------------------------------------------
--  DDL for Procedure DN_PAYMENT_RECEIPT_DELETION
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_PAYMENT_RECEIPT_DELETION" 
(M_DEAL_NO     DN_TRN_REPO_FRESH.DEAL_NO%TYPE,
 M_USER        DN_TIME_LOG.DN_USER%TYPE
 )

AS

ERR_NUM             VARCHAR2(200);
ERR_MSG             VARCHAR2(200);
/*M_PAYMENT_NO        DN_TRN_BO_SETTL_PAYMENT.PAYMENT_NO%TYPE;
M_REC_NO            DN_TRN_BO_SETTL_RECEIPT.REC_NO%TYPE;
M_PRIOR_DEAL_NO     DN_TRN_REPO_ROLLOVER.PRIOR_DEAL_NO%TYPE;
M_BR_INVOICE        DN_TRN_BROKERAGE.INVOICE_NO%TYPE;
M_COUNT1            NUMBER;
M_COUNT2            NUMBER;
M_COUNT3            NUMBER;
M_COUNT4            NUMBER;
M_COUNT_R           NUMBER;
M_COUNT_P           NUMBER;
M_COUNT_PRIOR       NUMBER;
M_COUNT_BR          NUMBER;
M_COUNT_REC         NUMBER;
M_COUNT_HIS_P       NUMBER;
M_COUNT_HIS_S       NUMBER;
M_SELLER            DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE;*/
M_SUS_REF_NO        DN_TRN_BO_SETTL_RECEIPT.SUS_REF_NO%TYPE;
M_PAY_AMOUNT        DN_TRN_BO_SETTL_PAYMENT.PAY_AMOUNT%TYPE;
M_REC_AMOUNT        DN_TRN_BO_SETTL_RECEIPT.REC_AMOUNT%TYPE;

BEGIN

DN_VALIDATE_SAVE_RIGHTS(M_USER,'WD_Pay_Rec_Deletion');  --added by ashini on 31/10/2005 for sr0509-047


IF SUBSTR(M_DEAL_NO,1,2) = 'SR' THEN
 SELECT SUS_REF_NO,REC_AMOUNT INTO M_SUS_REF_NO,M_REC_AMOUNT
 FROM   DN_TRN_BO_SETTL_RECEIPT
 WHERE  REC_NO = M_DEAL_NO;

ELSIF SUBSTR(M_DEAL_NO,1,2) = 'SP' THEN

 SELECT SUS_REF_NO,PAY_AMOUNT INTO M_SUS_REF_NO,M_PAY_AMOUNT
 FROM   DN_TRN_BO_SETTL_PAYMENT
 WHERE  PAYMENT_NO = M_DEAL_NO;

END IF;


DELETE DN_ACC_COUNTP_GEN_ACCOUNT WHERE DOCREFNO =M_DEAL_NO;
DELETE DN_ACC_LICENCEE_GEN_ACCOUNT WHERE DOCREFNO =M_DEAL_NO;
DELETE DN_ACC_PORTF_GEN_ACCOUNT WHERE DOCREFNO =M_DEAL_NO;

DELETE DN_TRN_BO_SETTL_CHQ_PAYMENT WHERE PAYMENT_NO =M_DEAL_NO;
DELETE DN_TRN_BO_SETTL_TRANS_LETTER WHERE PAYMENT_NO =M_DEAL_NO;
DELETE DN_TRN_BO_SETTL_PAYMENT WHERE PAYMENT_NO =M_DEAL_NO;
DELETE DN_TRN_BO_SETTL_PAYMENT_BULK WHERE PAYMENT_NO =M_DEAL_NO;

DELETE DN_TRN_BO_SETTL_DEPOSIT WHERE REC_NO =M_DEAL_NO;
DELETE DN_TRN_BO_SETTL_RECEIPT WHERE REC_NO =M_DEAL_NO;

IF SUBSTR(M_SUS_REF_NO,1,2) = 'CA' THEN

DELETE DN_ACC_SUS_PAYMENT WHERE SUS_REF_NO =M_SUS_REF_NO;
DELETE DN_ACC_SUS_RECEIPT WHERE SUS_REF_NO =M_SUS_REF_NO;

ELSE


    IF SUBSTR(M_DEAL_NO,1,2) = 'SR' THEN

        UPDATE DN_ACC_SUS_RECEIPT
        SET    REC_FROM_INT_BAL_AMT=REC_FROM_INT_BAL_AMT-M_REC_AMOUNT,
               BAL_TO_BE_RECEIVED=BAL_TO_BE_RECEIVED+M_REC_AMOUNT
        WHERE  SUS_REF_NO =M_SUS_REF_NO;

    ELSIF SUBSTR(M_DEAL_NO,1,2) = 'SP' THEN

        UPDATE DN_ACC_SUS_PAYMENT
        SET    PAY_FROM_INT_BAL_AMT=PAY_FROM_INT_BAL_AMT-M_PAY_AMOUNT,
               BAL_TO_BE_PAID=BAL_TO_BE_PAID+M_PAY_AMOUNT
        WHERE  SUS_REF_NO =M_SUS_REF_NO;

    END IF;


END IF;

--------UPDATING TIME LOG
INSERT INTO DN_TIME_LOG
           (SUS_REF_NO,
            DN_USER,
            ENT_DATE,
            DESCRIPTION)
           VALUES
            (
              M_DEAL_NO,
              M_USER,
              SYSDATE,
              'DELETE OPTION'
             );


COMMIT;


--------EXCEPTION
EXCEPTION WHEN OTHERS THEN
ROLLBACK;
   ERR_NUM :=  substr(SQLCODE,1,15);
   ERR_MSG := substr(SQLERRM,1,200) ;
   RAISE_APPLICATION_ERROR(-20201,SQLCODE||SQLERRM);

END ;

