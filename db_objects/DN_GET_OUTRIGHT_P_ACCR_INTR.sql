  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_OUTRIGHT_P_ACCR_INTR" 
  ( M_TODATE             IN DATE,
    M_EVALDATE           IN DATE,
    M_FACEVAL            IN DN_TRN_OUTP_SALE.FACE_VALUE%TYPE,
    M_SECURITY_CODE      IN DN_TRN_OUTP_SALE.SECURITY_CODE%TYPE,
    M_REQ_YIELD          IN DN_TRN_OUTP_SALE.YIELD%TYPE,
    M_INT_RATE_BASE_CODE IN DN_TRN_OUTP_SALE.INT_RATE_BASE_CODE%TYPE,
    M_INIT_COST          IN DN_INV_OUTPS_DEAL_SERIAL_NO.INITIAL_COST%TYPE)
  RETURN  REAL IS

   FINAL_ACCR_INT   NUMBER DEFAULT 0;
   A_CLEAN_AMT      NUMBER DEFAULT 0;
   A_DIRTY_AMT      NUMBER DEFAULT 0;
   B_CLEAN_AMT      NUMBER DEFAULT 0;
   B_DIRTY_AMT      NUMBER DEFAULT 0;
   CLEAN_AMT        NUMBER DEFAULT 0;
   DIRTY_AMT        NUMBER DEFAULT 0;
   EFFCNT           NUMBER(1) DEFAULT 0;
   TOCNT            NUMBER(1) DEFAULT 0;
BEGIN

   SELECT (NVL(DN_FIN_PRICE_CLEAN_YIELD(M_SECURITY_CODE,M_REQ_YIELD,M_TODATE,M_INT_RATE_BASE_CODE),0)/100*M_FACEVAL)
   INTO A_CLEAN_AMT FROM DUAL;
   SELECT (NVL(DN_FIN_PRICE_DIRTY_YIELD(M_SECURITY_CODE,M_REQ_YIELD,M_TODATE,M_INT_RATE_BASE_CODE),0)/100*M_FACEVAL)
   INTO A_DIRTY_AMT FROM DUAL;

   SELECT (NVL(DN_FIN_PRICE_CLEAN_YIELD(M_SECURITY_CODE,M_REQ_YIELD,M_EVALDATE,M_INT_RATE_BASE_CODE),0)/100*M_FACEVAL)
   INTO B_CLEAN_AMT FROM DUAL;
   SELECT (NVL(DN_FIN_PRICE_DIRTY_YIELD(M_SECURITY_CODE,M_REQ_YIELD,M_EVALDATE,M_INT_RATE_BASE_CODE),0)/100*M_FACEVAL)
   INTO B_DIRTY_AMT FROM DUAL;

   SELECT COUNT(*) INTO EFFCNT
   FROM DN_REF_SECURITY_INT_PAY_DATES
   WHERE (SECURITY_CODE=M_SECURITY_CODE AND INT_PAY_DATE = M_EVALDATE);
   IF (EFFCNT=1) THEN
        B_DIRTY_AMT:=B_CLEAN_AMT;
   END IF;

