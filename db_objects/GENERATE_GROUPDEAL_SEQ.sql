set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."GENERATE_GROUPDEAL_SEQ" 
(
  M_DEAL_NO      IN OUT    DN_TRN_OUTP_SALE.DEAL_NO%TYPE,
  M_DEALTYPE               VARCHAR2,
  M_DEAL_NUMBER            DN_TRN_OUTP_SALE.DEAL_NO%TYPE
)
AS
BEGIN

    IF M_DEAL_NUMBER IS NULL THEN

      IF M_DEALTYPE='OR' THEN
       SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_OUTRIGHT.NEXTVAL),3,'0')
       INTO M_DEAL_NO FROM DUAL;
       M_DEAL_NO:=  'GO'||M_DEAL_NO;
      ELSIF  M_DEALTYPE='RF' THEN
       SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_REPO_FRESH.NEXTVAL),3,'0')
       INTO M_DEAL_NO FROM DUAL;
       M_DEAL_NO:=  'GF'||M_DEAL_NO;
      ELSIF  M_DEALTYPE='RR' THEN
       SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_REPO_ROLLOVER.NEXTVAL),3,'0')
       INTO M_DEAL_NO FROM DUAL;
       M_DEAL_NO:=  'GR'||M_DEAL_NO;

      END IF;

    ELSE
       M_DEAL_NO:=M_DEAL_NUMBER;
    END IF;

END GENERATE_GROUPDEAL_SEQ;

/
