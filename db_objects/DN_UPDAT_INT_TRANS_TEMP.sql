--  DDL for Procedure DN_UPDAT_INT_TRANS_TEMP
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_UPDAT_INT_TRANS_TEMP" 
AS

CURSOR  INT_TRANS IS
   SELECT INT_TRANS_NO
   FROM DN_TRN_BO_SETTL_INT_TRANSFER
   WHERE INT_TRANS_NO NOT IN ('SI20000720-006','SI20000720-007','SI20000721-001',
                                 'SI20000721-002','SI20000721-003','SI20000724-001','SI20000724-002');

    M_INF_BRANCH_CODE          DN_TRN_BO_SETTL_INT_TRANSFER.INF_BRANCH_CODE%TYPE;
    M_INF_ACC_NO               DN_TRN_BO_SETTL_INT_TRANSFER.INF_ACC_NO%TYPE;
    M_OUTF_BRANCH_CODE         DN_TRN_BO_SETTL_INT_TRANSFER.OUTF_BRANCH_CODE%TYPE;
    M_OUTF_ACC_NO              DN_TRN_BO_SETTL_INT_TRANSFER.OUTF_ACC_NO%TYPE;
    MM_ACC_SYS_REFNO_DR        VARCHAR2(20);
    MM_ACC_SYS_REFNO_CR        VARCHAR2(20);
    M_ACC_SYS_REFNO_DR         VARCHAR2(20);
    M_ACC_SYS_REFNO_CR         VARCHAR2(20);
    J                          NUMBER;
    M_COUNT                    NUMBER;
    M_DEAL_NO                  DN_TRN_BO_SETTL_INT_TRANSFER.INT_TRANS_NO%TYPE;

 BEGIN

OPEN INT_TRANS ;
   LOOP
      M_DEAL_NO := NULL;
      FETCH  INT_TRANS INTO
             M_DEAL_NO;

      EXIT WHEN INT_TRANS%NOTFOUND;

    -----------------------------TRANSFER------------------
 SELECT
        INF_BRANCH_CODE,INF_ACC_NO,OUTF_BRANCH_CODE,OUTF_ACC_NO
 INTO
        M_INF_BRANCH_CODE,M_INF_ACC_NO,M_OUTF_BRANCH_CODE,M_OUTF_ACC_NO
 FROM   DN_TRN_BO_SETTL_INT_TRANSFER
 WHERE  INT_TRANS_NO=M_DEAL_NO;


 UPDATE   DN_TRN_BO_SETTL_INT_TRANSFER
 SET      INF_BRANCH_CODE=M_OUTF_BRANCH_CODE,
          INF_ACC_NO=M_OUTF_ACC_NO,
          OUTF_BRANCH_CODE=M_INF_BRANCH_CODE,
          OUTF_ACC_NO=M_INF_ACC_NO
 WHERE    INT_TRANS_NO=M_DEAL_NO;


---------------------------------LICENCEE  dr ---------------

 SELECT  ACC_SYS_REFNO
 INTO    M_ACC_SYS_REFNO_DR
 FROM    DN_ACC_LICENCEE_GEN_ACCOUNT
 WHERE   DOCREFNO=M_DEAL_NO
         AND DRCR_STATUS='DR';

 SELECT    ACC_SYS_REFNO
 INTO      MM_ACC_SYS_REFNO_DR
 FROM      DN_REF_LICENCEE_SETTLEMENT
 WHERE     ACC_NO=M_ACC_SYS_REFNO_DR;

--------------------------------licencee  cr------------------------
 SELECT  ACC_SYS_REFNO
 INTO    M_ACC_SYS_REFNO_CR
 FROM    DN_ACC_LICENCEE_GEN_ACCOUNT
 WHERE   DOCREFNO=M_DEAL_NO
         AND DRCR_STATUS='CR';


 SELECT    ACC_SYS_REFNO
 INTO      MM_ACC_SYS_REFNO_CR
 FROM      DN_REF_LICENCEE_SETTLEMENT
 WHERE     ACC_NO=M_ACC_SYS_REFNO_CR;

-----------------------------------------------------updation---------------------------
 UPDATE   DN_ACC_LICENCEE_GEN_ACCOUNT
 SET      ACC_SYS_REFNO=MM_ACC_SYS_REFNO_CR
 WHERE    DOCREFNO=M_DEAL_NO
          AND DRCR_STATUS='DR';

 UPDATE   DN_ACC_LICENCEE_GEN_ACCOUNT
 SET      ACC_SYS_REFNO=MM_ACC_SYS_REFNO_DR
 WHERE    DOCREFNO=M_DEAL_NO
          AND DRCR_STATUS='CR';

---------------------------------------------------------------------------------------
END LOOP;
--COMMIT;
END  DN_UPDAT_INT_TRANS_TEMP;

