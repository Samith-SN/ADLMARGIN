--  DDL for Procedure DN_MARKET_VALUES_EQUITY
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_MARKET_VALUES_EQUITY" 
   (
    M_VALUE_DATE                VARCHAR2,
    M_USER_NAME                 VARCHAR2

   )
IS


 CURSOR C1 IS
 SELECT A.PORTFOLIO_CODE PORT,A.SECURITY_CODE SEC,A.INST_TYPE INST,
 DN_RETURN_MARKET_RATE(A.SECURITY_CODE,M_VALUE_DATE) MRATE,
 SUM(A.FACE_VAL) NOOFSHARES ,SUM(A.CARR_VAL) COST1
 FROM DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_REF_SECURITY B
 WHERE A.SECURITY_CODE=B.SECURITY_CODE AND
 TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') > TO_DATE(M_VALUE_DATE,'DD-MM-YYYY')
 AND A.SERIAL_NO_STATUS='INV'
 AND A.FACE_VAL>0 AND  A.INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT
 WHERE INST_CAT ='EQUITY' )
 GROUP BY A.PORTFOLIO_CODE,A.SECURITY_CODE,A.INST_TYPE,
 DN_RETURN_MARKET_RATE(A.SECURITY_CODE,M_VALUE_DATE);

 CURSOR C2 IS
 SELECT  A.PORTFOLIO_CODE PORT,A.SECURITY_CODE SEC,A.INST_TYPE INST,
 DN_RETURN_MARKET_RATE(A.SECURITY_CODE,M_VALUE_DATE) MRATE,
 SUM(A.FACE_VAL) NOOFSHARES, SUM(A.CARR_VAL)  COST1
 FROM
 DN_INV_OUTPS_DEAL_SEC A,DN_REF_SECURITY B
 WHERE 	A.SECURITY_CODE=B.SECURITY_CODE AND
 TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') >TO_DATE(M_VALUE_DATE,'DD-MM-YYYY') AND
 (A.FACE_VAL > 0 OR A.FACE_VAL < 0) AND
 (A.TRN_TYPE = 'B' OR A.TRN_TYPE = 'S') AND
 A.INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT   WHERE INST_CAT ='EQUITY')
 GROUP BY A.PORTFOLIO_CODE,A.SECURITY_CODE,A.INST_TYPE,
 DN_RETURN_MARKET_RATE(A.SECURITY_CODE,M_VALUE_DATE) ;



  MM_GAINLOSS                 DN_TRN_MARKET_RATE.GAINLOSS%TYPE;
  I                           NUMBER;
  J                           NUMBER;
  M_CNT                       NUMBER;
  M_CNT1                      NUMBER;
  M_DOC_NO                    DN_TRN_MARKET_RATE_EQUITY.DOCREF_NO%TYPE;
  M_REV_NO                    DN_TRN_MARKET_RATE_EQUITY.DOCREF_NO_REVERSE%TYPE;


BEGIN

--RAISE_APPLICATION_ERROR(-20201,'*************'||M_VALUE_DATE);

DN_VALIDATE_SAVE_RIGHTS(M_USER_NAME,'WD_MARKET_RATE');  --added by ashini on 31/10/2005 for sr0509-047


SELECT TO_DATE(TO_CHAR(LAST_DAILY,'DD-MM-YYYY'),'DD-MM-YYYY') - TO_DATE(M_VALUE_DATE,'DD-MM-YYYY')
INTO M_CNT FROM DN_MARKET_RATE ;
IF M_CNT = 0 THEN

FOR I IN C1 LOOP

 MM_GAINLOSS  := I.NOOFSHARES*I.MRATE-I.COST1;
 SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_MARKET_EQUITY.NEXTVAL),3,'0') INTO M_DOC_NO FROM DUAL;
  M_DOC_NO:='MV'||M_DOC_NO;

 SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_REVERSAL_EQUITY.NEXTVAL),3,'0') INTO M_REV_NO FROM DUAL;
  M_REV_NO:='MR'||M_REV_NO;

 INSERT INTO DN_TRN_MARKET_RATE_EQUITY
  ( PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,MARKET_RATE,NO_SHARES,PRICE_SHARE,COST,GAINLOSS,VALUE_DATE,DOCREF_NO,DOCREF_NO_REVERSE)
  VALUES
  (I.PORT,I.INST,I.SEC,I.MRATE,I.NOOFSHARES,0,I.COST1,MM_GAINLOSS,TO_DATE(M_VALUE_DATE,'DD-MM-YYYY'),M_DOC_NO,M_REV_NO);
 END LOOP;


FOR J IN C1 LOOP

 MM_GAINLOSS  := J.NOOFSHARES*J.MRATE-J.COST1;
 SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_MARKET_EQUITY.NEXTVAL),3,'0') INTO M_DOC_NO FROM DUAL;
  M_DOC_NO:='MV'||M_DOC_NO;

 SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_REVERSAL_EQUITY.NEXTVAL),3,'0') INTO M_REV_NO FROM DUAL;
  M_REV_NO:='MR'||M_REV_NO;

 INSERT INTO DN_TRN_MARKET_RATE_EQUITY
  ( PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,MARKET_RATE,NO_SHARES,PRICE_SHARE,COST,GAINLOSS,VALUE_DATE,DOCREF_NO,DOCREF_NO_REVERSE)
  VALUES
  (J.PORT,J.INST,J.SEC,J.MRATE,J.NOOFSHARES,0,J.COST1,MM_GAINLOSS,TO_DATE(M_VALUE_DATE,'DD-MM-YYYY'),M_DOC_NO,M_REV_NO);

 END LOOP;

 UPDATE DN_MARKET_RATE SET LAST_DAILY= LAST_DAILY+1;

 ELSE

 DELETE FROM DN_TRN_MARKET_RATE_EQUITY WHERE
 TO_DATE(TO_CHAR(VALUE_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') = TO_DATE(M_VALUE_DATE,'DD-MM-YYYY');

 SELECT COUNT(*) INTO M_CNT1 FROM DN_ACC_LICENCEE_GEN_ACCOUNT
 WHERE  DOCREFNO LIKE 'MV%' AND TO_DATE(TO_CHAR(TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY')=TO_DATE(M_VALUE_DATE,'DD-MM-YYYY');

 IF M_CNT1 > 0 THEN

  DELETE FROM DN_ACC_LICENCEE_GEN_ACCOUNT WHERE
  DOCREFNO LIKE 'MV%' AND TO_DATE(TO_CHAR(TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY') =TO_DATE(M_VALUE_DATE,'DD-MM-YYYY');
  DELETE FROM DN_ACC_LICENCEE_GEN_ACCOUNT WHERE
  DOCREFNO LIKE 'MR%' AND TO_DATE(TO_CHAR(TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY') =TO_DATE(M_VALUE_DATE,'DD-MM-YYYY')+1;

 END IF;

 FOR I IN C1 LOOP
 MM_GAINLOSS  := I.NOOFSHARES*I.MRATE-I.COST1;

 SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_MARKET_EQUITY.NEXTVAL),3,'0') INTO M_DOC_NO FROM DUAL;
  M_DOC_NO:='MV'||M_DOC_NO;
 SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_REVERSAL_EQUITY.NEXTVAL),3,'0') INTO M_REV_NO FROM DUAL;
  M_REV_NO:='MR'||M_REV_NO;


 INSERT INTO DN_TRN_MARKET_RATE_EQUITY
  ( PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,MARKET_RATE,NO_SHARES,PRICE_SHARE,COST,GAINLOSS,VALUE_DATE,DOCREF_NO,DOCREF_NO_REVERSE)
  VALUES
  (I.PORT,I.INST,I.SEC,I.MRATE,I.NOOFSHARES,0,I.COST1,MM_GAINLOSS,TO_DATE(M_VALUE_DATE,'DD-MM-YYYY'),M_DOC_NO,M_REV_NO);
 END LOOP;


FOR J IN C1 LOOP
 MM_GAINLOSS  := J.NOOFSHARES*J.MRATE-J.COST1;
 SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_MARKET_EQUITY.NEXTVAL),3,'0') INTO M_DOC_NO FROM DUAL;
  M_DOC_NO:='MV'||M_DOC_NO;

 SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_REVERSAL_EQUITY.NEXTVAL),3,'0') INTO M_REV_NO FROM DUAL;
  M_REV_NO:='MR'||M_REV_NO;

 INSERT INTO DN_TRN_MARKET_RATE_EQUITY
  ( PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,MARKET_RATE,NO_SHARES,PRICE_SHARE,COST,GAINLOSS,VALUE_DATE,DOCREF_NO,DOCREF_NO_REVERSE)
  VALUES
  (J.PORT,J.INST,J.SEC,J.MRATE,J.NOOFSHARES,0,J.COST1,MM_GAINLOSS,TO_DATE(M_VALUE_DATE,'DD-MM-YYYY'),M_DOC_NO,M_REV_NO);
 END LOOP;


 END IF;

 DN_MARKET_VALUES_ACCOUNT_ENTRY(M_VALUE_DATE);


 COMMIT;

END DN_MARKET_VALUES_EQUITY;

