set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."WD_REF_REPO_RATE_INS" 

   (
    M_NEW_RATE           DN_REF_REPO_RATE.RATE%TYPE,
    M_INST_TYPE          DN_REF_REPO_RATE.INST_TYPE%TYPE,
    M_HAIRCUT            DN_REF_REPO_RATE.HAIRCUT%TYPE,
    M_USER               DN_REF_REPO_RATE.ENT_USER%TYPE,
    MSAVE                VARCHAR2
    )

AS

M_COUNT NUMBER;

BEGIN

DN_VALIDATE_SAVE_RIGHTS(M_USER,'WD_REPO_DATA');  --added by ashini on 31/10/2005 for sr0509-047


    SELECT COUNT(*)
    INTO M_COUNT
    FROM DN_REF_REPO_RATE
    WHERE INST_TYPE=M_INST_TYPE;


    IF M_COUNT = 0 /*MSAVE = 'MOD'*/ THEN

         INSERT INTO DN_REF_REPO_RATE
         VALUES (M_INST_TYPE,M_NEW_RATE/100,M_HAIRCUT/100,'Y',M_USER,SYSDATE);

         INSERT INTO DN_REFDATA_LOG_DETAILS
         (DN_USER,DN_TYPE,DN_REF_TYPE,COMMENTS,DN_DATE)
         VALUES
         (M_USER,'MODIFICATION','REFERENCE REPO DATA','REFERENCE REPO MODIFICATION BY USER'||M_USER||'',SYSDATE);


    ELSE

         INSERT INTO DN_REF_REPO_RATE_BACKUP
         SELECT INST_TYPE,RATE,HAIRCUT,'Y',ENT_USER,ENT_DATE,SYSDATE
         FROM DN_REF_REPO_RATE WHERE INST_TYPE=M_INST_TYPE;

         UPDATE DN_REF_REPO_RATE
         SET RATE     = M_NEW_RATE/100,
             ENT_DATE = SYSDATE,
             HAIRCUT  = M_HAIRCUT/100,
             ENT_USER = M_USER,
             STATUS   = 'Y'
         WHERE INST_TYPE=M_INST_TYPE;

         INSERT INTO DN_REFDATA_LOG_DETAILS
         (DN_USER,DN_TYPE,DN_REF_TYPE,COMMENTS,DN_DATE)
         VALUES
         (M_USER,'NEW ENTRY','REFERENCE REPO RATE','REFERENCE REPO NEW ENTRY BY USER'||M_USER||'',SYSDATE);

   END IF;
  /*
        UPDATE DN_REF_REPO_RATE
        SET   STATUS   = 'N'
        WHERE INST_TYPE<>M_INST_TYPE;
  */
   COMMIT;


END ;

