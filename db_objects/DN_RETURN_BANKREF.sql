  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_RETURN_BANKREF" 
(
  M_REF_NO	DN_TEMP_CLIENT_STATEMENT.TRREFNO%TYPE
)
RETURN VARCHAR2

AS
M_BANKREF VARCHAR2(50);

BEGIN
IF (SUBSTR(M_REF_NO,1,2)='SR') THEN
SELECT DISTINCT A.PAYER_REF INTO M_BANKREF FROM DN_TRN_BO_SETTL_RECEIPT A,DN_TEMP_CLIENT_STATEMENT B
WHERE A.REC_NO = M_REF_NO;
END IF;
IF (SUBSTR(M_REF_NO,1,2)='SP') THEN
 SELECT DISTINCT  A.CHQ_NO INTO M_BANKREF FROM DN_TRN_BO_SETTL_CHQ_PAYMENT A,DN_TEMP_CLIENT_STATEMENT B
 WHERE A.PAYMENT_NO = M_REF_NO;
END IF;
RETURN M_BANKREF;

END DN_RETURN_BANKREF;

/
