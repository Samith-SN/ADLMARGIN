  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_CLIENT_PEND_CASH_FLOW_P_1" 
     ( M_PORTFOLIO_CODE    DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE,
       M_FROMDATE      VARCHAR,
       M_TODATE        VARCHAR
      
     )

    -- Function     : This returns TOTAL PENDING PAYMENTS
    -- System       : DEALNET System
    -- Created by   : K.M.W.S.JAYANATH
    -- Created on   : 2011-11-09
  RETURN  REAL



   IS
 TOTAL NUMBER:=0;
 TOTAL_AMOUNT_PAYABLE NUMBER:=0;
 TOTAL_AMOUNT_PAID NUMBER:=0;

BEGIN

SELECT NVL(SUM(A.TRNAMOUNT),0) TRNAMOUNT INTO TOTAL_AMOUNT_PAYABLE
FROM DN_ACC_LICENCEE_GEN_ACCOUNT A, 
DN_REF_PORTFOLIO P, 
DN_TRN_OUTP_SALE S, 
DN_TRN_OUTP_SALE_SETTLE_EQUITY ST 

WHERE ACC_TYPE_CODE=302 
AND DRCR_STATUS='CR' AND DOCREFNO LIKE 'ORMT%' 
AND A.DOCREFNO= S.DEAL_NO 
AND (S.SELL_PORTFOLIO_CODE=P.PORTFOLIO_CODE AND P.PF_TYPE='C') 
AND  ST.DEAL_NO=S.DEAL_NO 
AND  ST.BUY_SETLE_DATE>=TO_DATE(M_FROMDATE,'DD/MM/YYYY')  
AND  ST.BUY_SETLE_DATE<=TO_DATE(M_TODATE,'DD/MM/YYYY')  
AND  ST.SELL_SETLE_DATE>=TO_DATE(M_FROMDATE,'DD/MM/YYYY')  
AND  ST.SELL_SETLE_DATE<=TO_DATE(M_TODATE,'DD/MM/YYYY') 
and S.BUY_PORTFOLIO_CODE=M_PORTFOLIO_CODE ;--change by waruna 2011-09-15 SELL_PORTFOLIO_CODE

dbms_output.put_line(' TOTAL_AMOUNT_PAYABLE='||TOTAL_AMOUNT_PAYABLE);

SELECT NVL( SUM(A.AMOUNT) ,0)REC_AMOUNT INTO TOTAL_AMOUNT_PAID
FROM DN_TRN_BO_SETTL_PAYMENT_BULK A ,DN_TRN_BO_SETTL_PAYMENT b
WHERE B.EFF_VALDATE >= TO_DATE(M_FROMDATE,'DD/MM/YYYY')  
AND B.EFF_VALDATE   <= TO_DATE(M_TODATE,'DD/MM/YYYY')
AND A.PORTFOLIO_CODE=M_PORTFOLIO_CODE 
AND B.PAYMENT_NO=A.PAYMENT_NO
AND B.PAY_STATUS IN ('APPR1','CONF','SIG1','SIG2','PRINT') 
 ;
dbms_output.put_line(' TOTAL_AMOUNT_PAID='||TOTAL_AMOUNT_PAID);

TOTAL:=TOTAL_AMOUNT_PAYABLE-TOTAL_AMOUNT_PAID;



RETURN TOTAL;

END ;

