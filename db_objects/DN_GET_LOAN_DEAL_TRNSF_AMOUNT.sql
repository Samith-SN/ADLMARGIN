  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_LOAN_DEAL_TRNSF_AMOUNT" 
(
 M_ALLO_DOCREFNO_FROM         DN_TEMP_LOAN_DEAL_ALLOCATION.ALLO_DOCREFNO_FROM%TYPE

)
 RETURN NUMBER
 AS
 M_ALLO_AMOUNT           NUMBER(18,4):=0;

 BEGIN

/*
M_VALFROMDATE := TO_DATE(EFFDATE,'DD-MM-YYYY');
M_VALTODATE   := TO_DATE(EFFDATE,'DD-MM-YYYY');
*/
  SELECT SUM(A.ALLO_AMOUNT) INTO  M_ALLO_AMOUNT
  FROM DN_TEMP_LOAN_DEAL_ALLOCATION A
  WHERE ALLO_DOCREFNO_FROM=M_ALLO_DOCREFNO_FROM;

 RETURN  NVL(M_ALLO_AMOUNT,0);

EXCEPTION
 WHEN NO_DATA_FOUND THEN
  RETURN  0;

END ;

/
