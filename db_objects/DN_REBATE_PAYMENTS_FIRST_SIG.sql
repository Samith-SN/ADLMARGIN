*/
        


BEGIN

--RAISE_APPLICATION_ERROR(-20201,'PAYMENT INVALID='||M_PAYMENT_NO||'**'||M_ACTIVE_STATUS);
  
  
 IF M_ACTIVE_STATUS='ENT' THEN
  
  SELECT A.PAY_AMOUNT INTO M_AMT 
  FROM DN_TRN_REBATE_PAYMENT A 
  WHERE PAYMENT_NO = M_PAYMENT_NO;
 
  UPDATE DN_TRN_REBATE_PAYMENT
  SET    PAY_STATUS  = 'SIG1'
  WHERE  PAYMENT_NO  = M_PAYMENT_NO
  AND  PAY_STATUS  = 'APPR1';
  
  
 

            
END IF;




END ; 

