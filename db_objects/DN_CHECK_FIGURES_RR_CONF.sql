INTO     M_LEG1_VALUE1
FROM     DN_TRN_REPO_ROLLOVER
WHERE    DEAL_NO=M_DEAL_NO;

IF (M_LEG1_VALUE1 > 1 ) THEN--(M_LEG1_VALUE1 <> M_LEG1_VALUE2 )
RAISE_APPLICATION_ERROR(-20201,'INCORRECT LEG2 VALUE!! - '||M_DEAL_NO||'- PLEASE RE-ENTER THIS TRANSACTION FROM THE START, AS THIS DEAL WILL BE AUTOMATICALLY DELETED TO PRESERVE DATA INTEGRITY');
