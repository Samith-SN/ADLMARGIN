  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_UNUTILIZED_CASH" 
( M_PORTFOLIO_CODE IN DN_REF_SECURITY.SECURITY_CODE%TYPE,
  M_VALUE_DATE     VARCHAR2 )
  RETURN VARCHAR2 IS


  M_UNUTILIZED_CASH            number;

BEGIN

  SELECT SUM(NVL(TOT,0)-NVL(TRANSFERRED_AMOUNT,0)+NVL(ALLO_AMOUNT,0))*-1 INTO M_UNUTILIZED_CASH
  FROM DN_LOAN_PENDING_ALLO A 
  WHERE A.PORTFOLIO_CODE = M_PORTFOLIO_CODE
  AND A.VALUE_DATE = TO_DATE(M_VALUE_DATE,'DD/MM/YYYY') ; 

   RETURN M_UNUTILIZED_CASH ;

END; 

