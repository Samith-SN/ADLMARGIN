set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_AUTO_ROLLOVER_DAYEND_OLD" 
  (M_E_VAL_DATE       VARCHAR2,
   M_USER             VARCHAR2)
  IS



CURSOR C1 IS
SELECT A.LEND_PORTFOLIO_CODE LENDER,A.DEAL_NO  DEALNO
FROM   DN_TRN_REPO_FRESH  A
WHERE  A.ON_CALL_DEAL = 'Y' AND A.APP_STATUS ='CONF' AND A.LEND_PORTFOLIO_CODE='ADLMT' AND
       TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') = TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
       A.DEAL_NO NOT IN (SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_ROLLOVER WHERE PRIOR_DEAL_NO= A.DEAL_NO) AND
       A.DEAL_NO NOT IN (SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_SETTLEMENT WHERE PRIOR_DEAL_NO= A.DEAL_NO) ;

CURSOR C2 IS
SELECT A.LEND_PORTFOLIO_CODE LENDER,A.DEAL_NO DEALNO
FROM   DN_TRN_REPO_ROLLOVER  A
WHERE  A.ON_CALL_DEAL = 'Y' AND A.APP_STATUS ='CONF' AND A.LEND_PORTFOLIO_CODE='ADLMT' AND
       TO_DATE(TO_CHAR(A.MATURITY_DATE,'DD-MM-YYYY'),'DD-MM-YYYY') = TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
       A.DEAL_NO NOT IN (SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_ROLLOVER WHERE PRIOR_DEAL_NO= A.DEAL_NO) AND
       A.DEAL_NO NOT IN (SELECT PRIOR_DEAL_NO FROM DN_TRN_REPO_SETTLEMENT WHERE PRIOR_DEAL_NO= A.DEAL_NO) ;

 M_MT_PERCENT  DN_REF_INSTRUMENT.MT_PERCENT%TYPE:=0;
 M_RATE_TYPE   DN_REF_PORTFOLIO.RATE_TYPE%TYPE;
 MRATE        NUMBER;--DN_REF_PORTFOLIO.RATE%TYPE;
 MDEAL_NO      VARCHAR2(14) DEFAULT NULL;
 M_TENOR       NUMBER  DEFAULT 0;
 MAT_DATE      VARCHAR2(15);
 LEG2_VAL      NUMBER (18,2);
 INT_AMT       NUMBER (18,2);
 MPRIOR_NO     VARCHAR2(14);
 MLEG1         NUMBER (18,2);
 M_BRANCH      VARCHAR2(30);
 MINST_TYPE    DN_TRN_REPO_FRESH_INST.INST_TYPE%TYPE;
 MHAIRCUT      DN_TRN_REPO_FRESH_INST.RPTRN_HCUT_PER%TYPE;
 M_RATE        DN_REF_REPO_RATE.RATE%TYPE;
 M_RATE_BASE   DN_TRN_REPO_FRESH.INT_RATE_BASE_CODE%TYPE;
 M_BORROWER    DN_TRN_REPO_FRESH.BORR_PORTFOLIO_CODE%TYPE;
 M_YEILD       DN_TRN_REPO_FRESH.YIELD%TYPE;
 I             NUMBER;
 J             NUMBER;
 M_SECURITY           DN_TRN_REPO_ROLLOVER.SEC_ALW_LENDER%TYPE;
 M_PHYSICAL           DN_TRN_REPO_ROLLOVER.PHYSICAL_DELIVERY%TYPE;
 M_EXCHANGEABILITY    DN_TRN_REPO_ROLLOVER.EXCHANGE_SEC%TYPE;
 M_CURRENCY           DN_TRN_REPO_ROLLOVER.CURR_CODE%TYPE;
 M_BASIS              DN_REF_INTR_BASE.INTR_BASE_DESC%TYPE;
 M_VALUE_DATE_TYPE    DN_TRN_REPO_ROLLOVER.EFF_VALDATE_TYPE%TYPE;
 M_SCRIPT_STATUS      DN_TRN_REPO_ROLLOVER.SCRIPT_STATUS%TYPE;
 M_SUM_INT            DN_TRN_REPO_ROLLOVER.INT_AMOUNT%TYPE;
 M_SUM_INT_REPO       DN_TRN_REPO_ROLLOVER.INT_AMOUNT%TYPE;
 M_NET                DN_TRN_REPO_ROLLOVER.INT_AMOUNT%TYPE;

BEGIN

UPDATE DN_SYS_PARAMETER_MONTHEND
SET MONTH_END = TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY');

--dbms_output.put_line('Value of M_E_VAL_DATE='||M_E_VAL_DATE);

FOR I IN C1 LOOP
M_MT_PERCENT:=0;
--M_RATE :=0;
dbms_output.put_line('Value of I.DEALNO='||I.DEALNO);
 SELECT A.DEAL_NO,A.LEG1_VALUE/*A.LEG2_VALUE*/,A.INT_RATE_BASE_CODE,A.BORR_PORTFOLIO_CODE,A.YIELD,--CHANGED BY SVA A.LEG2_VALUE TO A.LEG1_VALUE
        A.SEC_ALW_LENDER,A.PHYSICAL_DELIVERY,A.EXCHANGE_SEC,A.CURR_CODE,
        DN_RETURN_RATE_BASE_CODE(A.INT_RATE_BASE_CODE),A.EFF_VALDATE_TYPE,A.SCRIPT_STATUS
 INTO   MPRIOR_NO,MLEG1,M_RATE_BASE,M_BORROWER,M_YEILD,M_SECURITY,M_PHYSICAL,
        M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,M_VALUE_DATE_TYPE,M_SCRIPT_STATUS
 FROM   DN_TRN_REPO_FRESH A
 WHERE  A.DEAL_NO=I.DEALNO;

 --ADDED BY SVA ON 25-02-2005
 IF TO_CHAR(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY'),'DD')='01' THEN
      SELECT NVL(SUM(INT_AMOUNT),0)
      INTO   M_SUM_INT
      FROM(
      SELECT INT_AMOUNT
      FROM   DN_TRN_REPO_FRESH
      WHERE  BORR_PORTFOLIO_CODE = M_BORROWER AND
             MATURITY_DATE >  ADD_MONTHS(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY'),-1) AND
             MATURITY_DATE <= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
             APP_STATUS    = 'CONF'
      UNION ALL
      SELECT INT_AMOUNT
      FROM   DN_TRN_REPO_ROLLOVER
      WHERE  BORR_PORTFOLIO_CODE = M_BORROWER AND
             MATURITY_DATE >  ADD_MONTHS(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY'),-1) AND
             MATURITY_DATE <= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
             APP_STATUS    = 'CONF');
-----
      SELECT NVL(SUM(INT_AMOUNT),0)
      INTO   M_SUM_INT_REPO
      FROM(
      SELECT INT_AMOUNT
      FROM   DN_TRN_REPO_FRESH
      WHERE  LEND_PORTFOLIO_CODE = M_BORROWER AND
             MATURITY_DATE >  ADD_MONTHS(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY'),-1) AND
             MATURITY_DATE <= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
             APP_STATUS    = 'CONF'
      UNION ALL
      SELECT INT_AMOUNT
      FROM   DN_TRN_REPO_ROLLOVER
      WHERE  LEND_PORTFOLIO_CODE = M_BORROWER AND
             MATURITY_DATE >  ADD_MONTHS(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY'),-1) AND
             MATURITY_DATE <= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
             APP_STATUS    = 'CONF');


      M_NET:=M_SUM_INT-M_SUM_INT_REPO;

      MLEG1 := MLEG1 + M_NET;
 END IF;
 -- END
 IF MLEG1>0 THEN
 SELECT DISTINCT INST_TYPE,RPTRN_HCUT_PER
 INTO   MINST_TYPE,MHAIRCUT
 FROM   DN_TRN_REPO_FRESH_INST
 WHERE  DEAL_NO=I.DEALNO;

--dbms_output.put_line('Value of MINST_TYPE='||MINST_TYPE);
 SELECT NVL(RATE,0),NVL(RATE_TYPE,'-')
 INTO   MRATE,M_RATE_TYPE
 FROM   DN_REF_PORTFOLIO
 WHERE  PORTFOLIO_CODE =M_BORROWER;
--dbms_output.put_line('Value of MRATE='||MRATE);
 IF M_RATE_TYPE<>'-' THEN

   SELECT NVL(BASE_INTEREST_RATE/100,0)--CHANGED ON 17-05-2005 BY SVA BASE_INTEREST_RATE TO BASE_INTEREST_RATE/100 --changed on 17-12-2004 by sva MT_PERCENT to BASE_INTEREST_RATE
   INTO   M_MT_PERCENT
   FROM   DN_REF_INSTRUMENT
   WHERE  INST_TYPE=M_RATE_TYPE;
--dbms_output.put_line('Value of M_MT_PERCENT='||M_MT_PERCENT);
 END IF;

 M_YEILD := M_MT_PERCENT+MRATE;
--dbms_output.put_line('Value of M_YEILD='||M_YEILD);
 --SELECT TO_CHAR(DN_FIN_EFF_VALDATE_MAT('TOM',M_E_VAL_DATE),'DD-MON-YYYY') INTO MAT_DATE FROM DUAL;
 SELECT TO_CHAR(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY')+1,'DD-MM-YYYY')
 INTO   MAT_DATE
 FROM   DUAL;

 M_TENOR :=   TO_DATE(MAT_DATE,'DD-MM-YYYY')- TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY');

 SELECT DN_FIN_LEG2_F_LEG1(MLEG1,M_YEILD,M_TENOR,M_RATE_BASE,TO_DATE(MAT_DATE,'DD/MM/YYYY'))
 INTO   LEG2_VAL
 FROM   DUAL;

 SELECT LEG2_VAL-MLEG1
 INTO   INT_AMT
 FROM   DUAL;

--dbms_output.put_line('Value of MBFSL_REPOROLLOVER_IN1_DAYEND=');
 MBFSL_REPOROLLOVER_IN1_DAYEND(MDEAL_NO,MPRIOR_NO,M_BORROWER,I.LENDER,MINST_TYPE,MHAIRCUT,
                        M_SECURITY,M_PHYSICAL,M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,
                        M_VALUE_DATE_TYPE,M_E_VAL_DATE,M_YEILD,'Y',MLEG1,LEG2_VAL,
                        MAT_DATE,M_TENOR,INT_AMT,0,0,M_USER,'MAIN1',MDEAL_NO,'N',
                        M_SCRIPT_STATUS,NULL);--,'RATE_CHANGE',M_BRANCH
--dbms_output.put_line('Value of MBFSL_REPOROLLOVER_IN2');

 DN_AUTO_REPOROLLOVER_JOB_ROLL(MDEAL_NO,MINST_TYPE,MHAIRCUT,M_BORROWER,0,M_RATE/100);

 MBFSL_DEAL_CONFIRMATION_MT(MDEAL_NO,M_USER);

 --dbms_output.put_line('Value of MBFSL_REPOROLLOVER_IN3');

 MDEAL_NO := NULL;

 UPDATE DN_TRN_REPO_FRESH
 SET    ON_CALL_DEAL='S'
 WHERE  DEAL_NO=I.DEALNO;
 --UPDATE   DN_REF_RATE_CHANGE SET  ROLLOVER_STATUS ='RUN' WHERE TO_DATE(CHANGE_DATE,'DD-MM-YY')= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') ;

END IF;
END LOOP;


FOR J IN C2 LOOP
M_MT_PERCENT:=0;
M_RATE :=0;

--dbms_output.put_line('Value of J.DEALNO='||J.DEALNO);
SELECT A.DEAL_NO,A.LEG1_VALUE/*A.LEG2_VALUE*/,A.INT_RATE_BASE_CODE,A.BORR_PORTFOLIO_CODE,A.YEILD,--CHANGED BY SVA A.LEG2_VALUE TO A.LEG1_VALUE
       A.SEC_ALW_LENDER,A.PHYSICAL_DELIVERY,A.EXCHANGE_SEC,A.CURR_CODE,
       DN_RETURN_RATE_BASE_CODE(A.INT_RATE_BASE_CODE),A.EFF_VALDATE_TYPE,A.SCRIPT_STATUS
INTO MPRIOR_NO,MLEG1,M_RATE_BASE,M_BORROWER,M_YEILD,M_SECURITY,M_PHYSICAL,
     M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,M_VALUE_DATE_TYPE,M_SCRIPT_STATUS
FROM DN_TRN_REPO_ROLLOVER A
WHERE  A.DEAL_NO=J.DEALNO;


 --ADDED BY SVA ON 25-02-2005
 IF TO_CHAR(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY'),'DD')='01' THEN
      SELECT NVL(SUM(INT_AMOUNT),0)
      INTO   M_SUM_INT
      FROM(
      SELECT INT_AMOUNT
      FROM   DN_TRN_REPO_FRESH
      WHERE  BORR_PORTFOLIO_CODE = M_BORROWER AND
             MATURITY_DATE >  ADD_MONTHS(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY'),-1) AND
             MATURITY_DATE <= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
             APP_STATUS    = 'CONF'
      UNION ALL
      SELECT INT_AMOUNT
      FROM   DN_TRN_REPO_ROLLOVER
      WHERE  BORR_PORTFOLIO_CODE = M_BORROWER AND
             MATURITY_DATE >  ADD_MONTHS(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY'),-1) AND
             MATURITY_DATE <= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
             APP_STATUS    = 'CONF');


      SELECT NVL(SUM(INT_AMOUNT),0)
      INTO   M_SUM_INT_REPO
      FROM(
      SELECT INT_AMOUNT
      FROM   DN_TRN_REPO_FRESH
      WHERE  LEND_PORTFOLIO_CODE = M_BORROWER AND
             MATURITY_DATE >  ADD_MONTHS(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY'),-1) AND
             MATURITY_DATE <= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
             APP_STATUS    = 'CONF'
      UNION ALL
      SELECT INT_AMOUNT
      FROM   DN_TRN_REPO_ROLLOVER
      WHERE  LEND_PORTFOLIO_CODE = M_BORROWER AND
             MATURITY_DATE >  ADD_MONTHS(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY'),-1) AND
             MATURITY_DATE <= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') AND
             APP_STATUS    = 'CONF');

    M_NET:=M_SUM_INT-M_SUM_INT_REPO;
      MLEG1 := MLEG1 + M_NET;
 END IF;
 -- END
IF MLEG1 > 0 THEN
SELECT DISTINCT INST_TYPE,RPTRN_HCUT_PER
INTO   MINST_TYPE,MHAIRCUT
FROM   DN_TRN_REPO_ROLLOVER_INST
WHERE  DEAL_NO=J.DEALNO;

--dbms_output.put_line('Value of MINST_TYPE='||MINST_TYPE);

 SELECT NVL(RATE,0),NVL(RATE_TYPE,'-')
 INTO   MRATE,M_RATE_TYPE
 FROM   DN_REF_PORTFOLIO
 WHERE  PORTFOLIO_CODE =M_BORROWER;
--dbms_output.put_line('Value of MRATE='||MRATE);
 IF M_RATE_TYPE<>'-' THEN

   SELECT NVL(BASE_INTEREST_RATE/100,0)--CHANGED ON 17-05-2005 BY SVA BASE_INTEREST_RATE TO BASE_INTEREST_RATE/100--changed on 17-12-2004 by sva MT_PERCENT to BASE_INTEREST_RATE
   INTO   M_MT_PERCENT
   FROM   DN_REF_INSTRUMENT
   WHERE  INST_TYPE=M_RATE_TYPE;
--dbms_output.put_line('Value of M_MT_PERCENT='||M_MT_PERCENT);
 END IF;

 M_YEILD := M_MT_PERCENT+MRATE;
--dbms_output.put_line('Value of M_YEILD='||M_YEILD);
--SELECT TO_CHAR(DN_FIN_EFF_VALDATE_MAT('TOM',M_E_VAL_DATE),'DD-MON-YYYY') INTO MAT_DATE FROM DUAL;
SELECT TO_CHAR(TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY')+1,'DD-MM-YYYY')
INTO   MAT_DATE
FROM   DUAL;
--dbms_output.put_line('Value of MAT_DATE='||MAT_DATE);
M_TENOR :=   TO_DATE(MAT_DATE,'DD-MM-YYYY')- TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY');
--dbms_output.put_line('Value of M_TENOR='||M_TENOR);
SELECT DN_FIN_LEG2_F_LEG1(MLEG1,M_YEILD,M_TENOR,M_RATE_BASE,TO_DATE(MAT_DATE,'DD-MM-YYYY'))
INTO LEG2_VAL
FROM DUAL;
--dbms_output.put_line('Value of LEG2_VAL='||LEG2_VAL);
-- SELECT DN_FIN_INT_AMT_F_LEG1_LEG2(MLEG1,LEG2_VAL,1,M_RATE_BASE) INTO INT_AMT FROM DUAL;
SELECT  LEG2_VAL-MLEG1
INTO INT_AMT
FROM DUAL;
--dbms_output.put_line('Value of INT_AMT='||INT_AMT);

 MBFSL_REPOROLLOVER_IN1_DAYEND(MDEAL_NO,MPRIOR_NO,M_BORROWER,J.LENDER,MINST_TYPE,MHAIRCUT,
                        M_SECURITY,M_PHYSICAL,M_EXCHANGEABILITY,M_CURRENCY,M_BASIS,
                        M_VALUE_DATE_TYPE,M_E_VAL_DATE,M_YEILD,'Y',MLEG1,LEG2_VAL,
                        MAT_DATE,M_TENOR,INT_AMT,0,0,M_USER,'MAIN1',MDEAL_NO,'N',
                        M_SCRIPT_STATUS,NULL);--,'RATE_CHANGE',M_BRANCH
--dbms_output.put_line('Value of MBFSL_REPOROLLOVER_IN1_DAYEND=');
 DN_AUTO_REPOROLLOVER_JOB_ROLL(MDEAL_NO,MINST_TYPE,MHAIRCUT,M_BORROWER,0,M_RATE/100);
--dbms_output.put_line('Value of DN_AUTO_REPOROLLOVER_JOB_ROLL=');
 MBFSL_DEAL_CONFIRMATION_MT(MDEAL_NO,M_USER);
--dbms_output.put_line('Value of MBFSL_DEAL_CONFIRMATION=');
 MDEAL_NO := NULL;

 UPDATE DN_TRN_REPO_ROLLOVER
 SET    ON_CALL_DEAL='S'
 WHERE  DEAL_NO=J.DEALNO;
 --UPDATE   DN_REF_RATE_CHANGE SET  ROLLOVER_STATUS ='RUN' WHERE TO_DATE(CHANGE_DATE,'DD-MM-YY')= TO_DATE(M_E_VAL_DATE,'DD-MM-YYYY') ;
END IF;
END LOOP;

-- AFTER MONTH END INCREASE ON CALL BY 1---
UPDATE DN_SYS_PARAMETER_ONCALL
SET    LAST_DAILY = LAST_DAILY+1;
