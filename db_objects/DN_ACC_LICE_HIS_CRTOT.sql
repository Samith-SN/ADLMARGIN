--  DDL for Function DN_ACC_LICE_HIS_CRTOT
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_ACC_LICE_HIS_CRTOT" (
     M_ACC_TYPE_CODE        DN_ACC_LICEN_INST_GEN_HIS.ACC_TYPE_CODE%TYPE,
     M_PORTFOLIO_CODE       DN_ACC_LICEN_INST_GEN_HIS.PORTFOLIO_CODE%TYPE,
     M_FROM_DATE            VARCHAR2,
     M_TO_DATE              VARCHAR2,
     M_OPTION               VARCHAR2,
     M_MODE                 VARCHAR2
    )
   RETURN  REAL
    IS

    -- Function     : TO RETURN CRTOT FROM HISTORY TABLE
    -- System       : DEALNET
    -- Created by   : LATHIKA
    -- Created on   : 21/01/2000

 M_CRTOT                   NUMBER;
 M_CRTOT2                  NUMBER;
 M_COUNT                   NUMBER;

BEGIN
 M_CRTOT:=0;
 M_CRTOT2:=0;

IF M_OPTION='DATA1' THEN
  IF M_MODE='SUM' THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR';

 SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT2
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR';
ELSIF M_MODE='HIS' THEN
   SELECT COUNT(*)
   INTO   M_COUNT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    IN('CR','DR');

 IF  M_COUNT=0 THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR';

  ELSE
        M_CRTOT:=0;
 END IF;

 END IF;
ELSIF M_OPTION='DATA2' THEN
 IF M_MODE='SUM' THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') ;

SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT2
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') ;

 ELSIF M_MODE='HIS' THEN
   SELECT COUNT(*)
   INTO   M_COUNT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    IN('CR','DR')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') ;


 IF  M_COUNT=0 THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY') ;


  ELSE
        M_CRTOT:=0;
 END IF;

 END IF;

ELSIF M_OPTION='DATA5' THEN
 IF M_MODE='SUM' THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY');

 SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT2
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY');

ELSIF M_MODE='HIS' THEN
   SELECT COUNT(*)
   INTO   M_COUNT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    IN('CR','DR')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY');

 IF  M_COUNT=0 THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) DRTOT
      INTO   M_CRTOT
      FROM   DN_ACC_LICEN_INST_GEN_HIS A
      WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
      AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
      AND    A.DRCR_STATUS    ='CR'
      AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_TO_DATE,'DD/MM/YYYY');

  ELSE
        M_CRTOT:=0;
 END IF;

 END IF;

ELSIF M_OPTION='DATA6' THEN
 IF M_MODE='SUM' THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY');

SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT2
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY');

ELSIF M_MODE='HIS' THEN
   SELECT COUNT(*)
   INTO   M_COUNT
   FROM   DN_ACC_LICEN_INST_GEN_SUM A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    IN('CR','DR')
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY');

 IF  M_COUNT=0 THEN
   SELECT NVL(SUM(DECODE(A.DRCR_STATUS,'CR',A.TRNAMOUNT)),0) CRTOT
   INTO   M_CRTOT
   FROM   DN_ACC_LICEN_INST_GEN_HIS A
   WHERE  A.PORTFOLIO_CODE =M_PORTFOLIO_CODE
   AND    A.ACC_TYPE_CODE  =M_ACC_TYPE_CODE
   AND    A.DRCR_STATUS    ='CR'
   AND    TO_DATE(TO_CHAR(A.TRNDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>=TO_DATE(M_FROM_DATE,'DD/MM/YYYY');

  ELSE
        M_CRTOT:=0;
 END IF;

 END IF;

END IF;
  M_CRTOT:= M_CRTOT+M_CRTOT2;
 RETURN ROUND(M_CRTOT,2);
END DN_ACC_LICE_HIS_CRTOT;

