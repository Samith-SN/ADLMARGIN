                SUM(A.FACE_VAL) NOOFSHARES,DN_GET_DEAL_INV_TYPE_NAME(A.DEAL_NO) INV_TYPE,A.SECURITY_CODE SEC1,A.INST_TYPE INST1,
                C.ACTIVITY ,C.XC_DATE,C.ALLOTMENT_DATE,C.LETTER_DISPATCH,C.ACCEPTANCE_DATE,C.REC_DATE,  --add by waruna 2012-01-18
               --ADD by WARUNA 2012-05-30
                 (SELECT ACTI_REF_NO FROM DN_CORPORATE_ACTIONS E
                  WHERE
                  E.ACTIVITY IN ('RIGHTS','WARRANT') 
                  AND E.ACCEPTANCE_DATE = TRUNC(M_LAST_DAILY,'DD')+1
                  AND E.INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT
                                      WHERE INST_CAT ='EQUITY') 
                  AND E.STATUS = 'PROCESS1' 
                  AND E.SECURITY_CODE       = C.SECURITY_CODE
                  AND E.REL_SECURITY_CODE   = C.REL_SECURITY_CODE
                  ) ACTI_REF_NO                 
                 --ADD by WARUNA 2012-05-30
                
                 
                FROM DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_REF_SECURITY B,DN_CORPORATE_ACTIONS C
                WHERE C.REL_SECURITY_CODE  =  B.SECURITY_CODE
                AND A.SERIAL_NO_STATUS     = 'INV'
                AND A.SECURITY_CODE        = C.REL_SECURITY_CODE  
                AND C.REL_SECURITY_CODE    = M_REL_SECURITY_CODE
                AND C.ACTIVITY             IN ('RIGHTS','WARRANT') 
                AND C.ACCEPTANCE_DATE      =  TRUNC(M_LAST_DAILY,'DD')+1 
                AND C.INST_TYPE IN
                               (SELECT INST_TYPE 
                                FROM DN_REF_INSTRUMENT
                                WHERE INST_CAT ='EQUITY') 
                AND STATUS                 = 'PROCESS1'
                GROUP BY A.DEAL_NO,A.PORTFOLIO_CODE,B.SECURITY_CODE,B.INST_TYPE,
                A.SECURITY_CODE,A.INST_TYPE,DN_GET_DEAL_INV_TYPE_NAME(A.DEAL_NO),
                C.ACTIVITY ,C.XC_DATE,C.ALLOTMENT_DATE,C.LETTER_DISPATCH,C.ACCEPTANCE_DATE,C.REC_DATE,C.REL_SECURITY_CODE,C.SECURITY_CODE  ; 


