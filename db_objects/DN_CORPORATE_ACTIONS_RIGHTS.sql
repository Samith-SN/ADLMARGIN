BEGIN

SELECT  TRUNC(M_LAST_DAILY,'DD')+1 INTO EDATE FROM DUAL;

FOR X IN ( SELECT   C.REL_SECURITY_CODE,C.INST_TYPE
           FROM DN_CORPORATE_ACTIONS C 
           WHERE C.ACTIVITY IN ('RIGHTS','WARRANT')
           AND C.XC_DATE   =  TRUNC(M_LAST_DAILY,'DD')+1 
           AND C.INST_TYPE IN (SELECT INST_TYPE 
                                     FROM DN_REF_INSTRUMENT
                                     WHERE INST_CAT ='EQUITY') 
            AND STATUS = 'ENT') LOOP

FOR I IN C1(X.REL_SECURITY_CODE) LOOP
                        M_DEAL_NO :='';
                        /* CHANGE BY WARUNA 
                        SEC_CODE := I.SEC  ;
                        MINST := I.INST  ;
                        */
                        
                        SEC_CODE := X.REL_SECURITY_CODE  ;
                        MINST    := X.INST_TYPE  ;
                        --RAISE_APPLICATION_ERROR(-20201,'SEC_CODE88'||I.SEC);
                        
                        /*---Comment on 05-06-2012---- by waruna on 05-06-2012
