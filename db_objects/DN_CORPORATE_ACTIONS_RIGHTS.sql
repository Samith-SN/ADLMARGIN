IS

 -- Rights/Warrant  allocate to pf(buy)
 CURSOR C1(M_REL_SECURITY_CODE DN_CORPORATE_ACTIONS.REL_SECURITY_CODE%TYPE) IS
                 SELECT A.PORTFOLIO_CODE PORT,B.SECURITY_CODE SEC,B.INST_TYPE INST,
                 SUM(A.FACE_VAL) NOOFSHARES,DN_GET_DEAL_INV_TYPE_NAME(A.DEAL_NO) INV_TYPE,A.SECURITY_CODE SEC1,A.INST_TYPE INST1,
                 C.ACTIVITY ,C.XC_DATE,C.ALLOTMENT_DATE,C.LETTER_DISPATCH,C.ACCEPTANCE_DATE,C.REC_DATE,GET_PORT_BROKER(A.PORTFOLIO_CODE,A.DEAL_NO) BROKER,--add by waruna 2012-01-18
                 
                 --ADD by WARUNA 2012-05-30
                 (SELECT ACTI_REF_NO FROM DN_CORPORATE_ACTIONS E
                  WHERE
                  E.ACTIVITY IN ('RIGHTS','WARRANT') 
                  AND E.XC_DATE = TRUNC(M_LAST_DAILY,'DD')+1
                  AND E.INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT
                                      WHERE INST_CAT ='EQUITY') 
                  AND E.STATUS = 'ENT' 
                  AND E.SECURITY_CODE       = A.SECURITY_CODE
                  AND E.REL_SECURITY_CODE   = M_REL_SECURITY_CODE
                  ) ACTI_REF_NO                 
                 --ADD by WARUNA 2012-05-30
                 
 
                 FROM DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_REF_SECURITY B,DN_CORPORATE_ACTIONS C
                 WHERE C.REL_SECURITY_CODE = B.SECURITY_CODE
                 AND A.SERIAL_NO_STATUS    = 'INV'
                 AND A.SECURITY_CODE       = C.SECURITY_CODE
                 AND C.REL_SECURITY_CODE   = M_REL_SECURITY_CODE
                 AND C.ACTIVITY            IN ('RIGHTS','WARRANT')
                 AND C.XC_DATE             =  TRUNC(M_LAST_DAILY,'DD')+1 
                 AND C.INST_TYPE IN (SELECT INST_TYPE 
                                     FROM DN_REF_INSTRUMENT
                                     WHERE INST_CAT ='EQUITY') 
                 AND STATUS                = 'ENT'
                 GROUP BY A.PORTFOLIO_CODE, B.SECURITY_CODE,B.INST_TYPE,A.SECURITY_CODE,
                          A.INST_TYPE,DN_GET_DEAL_INV_TYPE_NAME(A.DEAL_NO),
                          C.ACTIVITY ,C.XC_DATE,C.ALLOTMENT_DATE,C.LETTER_DISPATCH,
                          C.ACCEPTANCE_DATE,C.REC_DATE,GET_PORT_BROKER(A.PORTFOLIO_CODE,A.DEAL_NO) ;


 -- Rights/Warrant  convet to odinary  shares
CURSOR C2(M_REL_SECURITY_CODE DN_CORPORATE_ACTIONS.REL_SECURITY_CODE%TYPE) IS
                SELECT A.PORTFOLIO_CODE PORT,B.SECURITY_CODE SEC,B.INST_TYPE INST,
                SUM(A.FACE_VAL) NOOFSHARES,DN_GET_DEAL_INV_TYPE_NAME(A.DEAL_NO) INV_TYPE,A.SECURITY_CODE SEC1,A.INST_TYPE INST1,
                C.ACTIVITY ,C.XC_DATE,C.ALLOTMENT_DATE,C.LETTER_DISPATCH,C.ACCEPTANCE_DATE, --add by waruna 2012-01-18
                C.SECURITY_CODE N_SHARE,C.REC_DATE,GET_PORT_BROKER(A.PORTFOLIO_CODE,A.DEAL_NO) BROKER,
               --ADD by WARUNA 2012-05-30
                 (SELECT ACTI_REF_NO FROM DN_CORPORATE_ACTIONS E
                  WHERE
                  E.ACTIVITY IN ('RIGHTS','WARRANT') 
                  AND E.ACCEPTANCE_DATE = TRUNC(M_LAST_DAILY,'DD')+1
                  AND E.INST_TYPE IN (SELECT INST_TYPE FROM DN_REF_INSTRUMENT
                                      WHERE INST_CAT ='EQUITY') 
                  AND E.STATUS = 'PROCESS1' 
                  AND E.SECURITY_CODE       = C.SECURITY_CODE
                  AND E.REL_SECURITY_CODE   = C.REL_SECURITY_CODE 
                  ) ACTI_REF_NO                 
                 --ADD by WARUNA 2012-05-30
                 
                FROM DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_REF_SECURITY B,DN_CORPORATE_ACTIONS C
                WHERE C.REL_SECURITY_CODE = B.SECURITY_CODE
                AND A.SERIAL_NO_STATUS    = 'INV'
                AND A.SECURITY_CODE       = C.REL_SECURITY_CODE  
                AND C.REL_SECURITY_CODE   = M_REL_SECURITY_CODE
                AND C.ACTIVITY            IN ('RIGHTS','WARRANT') 
                AND C.ACCEPTANCE_DATE     =  TRUNC(M_LAST_DAILY,'DD')+1 
                AND C.INST_TYPE           IN (
                                           SELECT INST_TYPE
                                           FROM DN_REF_INSTRUMENT
                                           WHERE INST_CAT ='EQUITY')
                AND STATUS = 'PROCESS1'
                GROUP BY A.PORTFOLIO_CODE,B.SECURITY_CODE,B.INST_TYPE,A.SECURITY_CODE,
                         A.INST_TYPE,DN_GET_DEAL_INV_TYPE_NAME(A.DEAL_NO),
                         C.ACTIVITY ,C.XC_DATE,C.ALLOTMENT_DATE,C.LETTER_DISPATCH,
                         C.ACCEPTANCE_DATE,C.SECURITY_CODE,C.REC_DATE,GET_PORT_BROKER(A.PORTFOLIO_CODE,A.DEAL_NO),C.REL_SECURITY_CODE  ; 
                 
 -- Rights/Warrant  (sell) from  pf
CURSOR C3(M_REL_SECURITY_CODE DN_CORPORATE_ACTIONS.REL_SECURITY_CODE%TYPE)  IS
