                        SELECT   RATIO1,RATIO2,'0' INTO NR,DR,MPRICE
                        FROM DN_CORPORATE_ACTIONS
                        WHERE ACTIVITY IN ('RIGHTS','WARRANT') AND REL_SECURITY_CODE=I.SEC AND INST_TYPE=I.INST1 
