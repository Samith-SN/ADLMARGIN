set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_RPT_SHARE_PORTFOLIO_SUM" 
(
M_DATE                      VARCHAR2,
--M_PORTFOLIO_CODE            DN_INV_OUTPS_DEAL_SERIAL_NO.PORTFOLIO_CODE%TYPE,
M_USER                      VARCHAR2
)
 AS



 CURSOR SERIAL_NO IS
 SELECT JK.X1,JK.X2,JK.X3,JK.X4,JK.X5,JK.X6,JK.X7,JK.X8,'UPPER' X9,JK.X10,JK.X11,JK.X12,JK.X13,JK.X14
 ------
 FROM
     (SELECT  A.SECURITY_CODE X1 ,TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY')X2,SUM(A.FACE_VAL)X3,
              SUM(A.INITIAL_COST+A.BROKERAGE)X4,
              DECODE(SUM(A.INITIAL_COST+A.BROKERAGE),0,0,SUM((A.INITIAL_COST+A.BROKERAGE)*A.DEAL_YIELD*100)/SUM(A.INITIAL_COST+A.BROKERAGE)) X5,
			  ROUND(TO_NUMBER(B.MATURITY_DATE-TO_DATE(M_DATE,'DD/MM/YYYY')),0)X6,
              DN_GET_COUPON_RATE(B.SECURITY_CODE)X7,
              TO_DATE(B.MATURITY_DATE,'DD-MON-YYYY')X8,PORTFOLIO_CODE X10,--
              SUM(A.PRICE_INT_ACCR) X11,
              SUM(A.TOT_COUP_INT) X12,
              SUM(A.CARR_VAL) X13,
              DN_GET_OR_SELLER(A.DEAL_NO) X14
	  FROM    DN_INV_OUTPS_DEAL_SERIAL_NO A,
              DN_REF_SECURITY B
      WHERE   --A.PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
              TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
              A.INST_TYPE LIKE '%' AND--=M_INST_TYPE AND
              A.SECURITY_CODE=B.SECURITY_CODE  AND
              (A.SERIAL_NO_STATUS='INV' OR ( A.SALE_EFF_VALDATE IS NULL) OR
	              (TO_DATE(TO_CHAR(A.SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_DATE,'DD/MM/YYYY'))  )AND
	          TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_DATE,'DD/MM/YYYY')  AND
	          TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
              A.FACE_VAL>0 AND
              A.FACE_VAL_CURR IS NULL  AND
              A.SCRIP_STATUS LIKE '%'
    GROUP BY  A.PORTFOLIO_CODE,A.SECURITY_CODE,B.MATURITY_DATE,DN_GET_COUPON_RATE(B.SECURITY_CODE),
              DN_GET_OR_SELLER(A.DEAL_NO)

      UNION

      SELECT   C.SECURITY_CODE X1 ,TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),
			   SUM(C.FACE_VAL),SUM(C.INITIAL_COST+C.BROKERAGE),
			   DECODE(SUM(C.INITIAL_COST+C.BROKERAGE),0,0,SUM((C.INITIAL_COST+C.BROKERAGE)*C.DEAL_YIELD*100)/SUM(C.INITIAL_COST+C.BROKERAGE)),
			   ROUND(TO_NUMBER(B.MATURITY_DATE-TO_DATE(M_DATE,'DD/MM/YYYY')),0),DN_GET_COUPON_RATE(B.SECURITY_CODE)  ,TO_DATE(B.MATURITY_DATE,'DD-MON-YYYY'),C.PORTFOLIO_CODE,--
               SUM(C.PRICE_INT_ACCR) X11,
              SUM(C.TOT_COUP_INT) X12,
              SUM(C.CARR_VAL) X13,
              DN_GET_OR_SELLER(C.DEAL_NO) X14

	     FROM  DN_REF_SECURITY B,
               DN_HIS_OUTPS_DEAL_SERIAL_NO C
      WHERE    --C.PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
               TO_DATE(TO_CHAR(C.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
               C.INST_TYPE LIKE '%' AND--=M_INST_TYPE AND
               C.SECURITY_CODE=B.SECURITY_CODE  AND
               (C.SERIAL_NO_STATUS='INV' OR ( C.SALE_EFF_VALDATE IS NULL) OR
			      (TO_DATE(TO_CHAR(C.SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_DATE,'DD/MM/YYYY'))  )AND
			   TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_DATE,'DD/MM/YYYY')  AND
	 		   TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
			   C.FACE_VAL>0 AND
			   C.FACE_VAL_CURR IS NULL AND
               C.SCRIP_STATUS LIKE '%'
	GROUP BY   C.PORTFOLIO_CODE,C.SECURITY_CODE,B.MATURITY_DATE,DN_GET_COUPON_RATE(B.SECURITY_CODE),
              DN_GET_OR_SELLER(C.DEAL_NO)
	) JK

UNION
 SELECT JK.X1,JK.X2,JK.X3,JK.X4,JK.X5,JK.X6,JK.X7,JK.X8,'LOWER' X9,JK.X10,JK.X11,JK.X12,JK.X13,JK.X14
 FROM
    (SELECT T1.sec X1 ,T1.mat X2,
            (T1.a+T2.a) X3 ,--faceval,
            (T1.b+T2.b) X4 ,--cost,
            DECODE((T1.b+T2.b),0,0,(T1.yeild*T1.b+T2.yeild*T2.b)/(T1.b+T2.b) ) X5,
            T1.days X6,
            T1.rate X7,
            T1.mat2 X8,
            T1.port X10,
            T1.X11 X11,
            T1.X12 X12,
            T1.X13 X13,
            T1.X14 X14

     FROM  (SELECT  A.SECURITY_CODE sec,TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY') mat,SUM(A.FACE_VAL) a,SUM(A.INITIAL_COST+A.BROKERAGE) b ,DECODE(SUM(A.INITIAL_COST+A.BROKERAGE),0,0,SUM((A.INITIAL_COST+A.BROKERAGE)*A.DEAL_YIELD*100)/SUM(A.INITIAL_COST+A.BROKERAGE))  yeild,
	                ROUND(TO_NUMBER(B.MATURITY_DATE-TO_DATE(M_DATE,'DD/MM/YYYY')),0) days,DN_GET_COUPON_RATE(B.SECURITY_CODE)rate,TO_DATE(B.MATURITY_DATE,'DD-MON-YYYY') mat2,PORTFOLIO_CODE port,
                    SUM(A.PRICE_INT_ACCR) X11,
              SUM(A.TOT_COUP_INT) X12,
              SUM(A.CARR_VAL) X13,
              DN_GET_OR_SELLER(A.DEAL_NO) X14

            FROM    DN_INV_OUTPS_DEAL_SERIAL_NO A,
                    DN_REF_SECURITY B
           WHERE    --A.PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                    TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
                    A.INST_TYPE LIKE '%' AND--=M_INST_TYPE AND
                    A.SECURITY_CODE=B.SECURITY_CODE  AND
                    (A.SERIAL_NO_STATUS='INV' OR ( A.SALE_EFF_VALDATE IS NULL) OR
	                  (TO_DATE(TO_CHAR(A.SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_DATE,'DD/MM/YYYY')))AND
                    TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_DATE,'DD/MM/YYYY')  AND
                    TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
                    A.FACE_VAL>0 AND
                    A.FACE_VAL_CURR IS NULL  AND
                    A.SCRIP_STATUS LIKE '%'
        GROUP BY    A.PORTFOLIO_CODE,A.SECURITY_CODE,B.MATURITY_DATE,DN_GET_COUPON_RATE(B.SECURITY_CODE),
              DN_GET_OR_SELLER(A.DEAL_NO)
        )T1,

        (SELECT     C.SECURITY_CODE sec,TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),
                    SUM(C.FACE_VAL) a,SUM(C.INITIAL_COST+C.BROKERAGE) b ,
                    DECODE(SUM(C.INITIAL_COST+C.BROKERAGE),0,0,SUM((C.INITIAL_COST+C.BROKERAGE)*C.DEAL_YIELD*100)/SUM(C.INITIAL_COST+C.BROKERAGE)) yeild,
                    ROUND(TO_NUMBER(B.MATURITY_DATE-TO_DATE(M_DATE,'DD/MM/YYYY')),0),DN_GET_COUPON_RATE(B.SECURITY_CODE)rate ,TO_DATE(B.MATURITY_DATE,'DD-MON-YYYY')  mat2,PORTFOLIO_CODE port,
                    SUM(C.PRICE_INT_ACCR) X11,
              SUM(C.TOT_COUP_INT) X12,
              SUM(C.CARR_VAL) X13
            FROM    DN_REF_SECURITY B,
                    DN_HIS_OUTPS_DEAL_SERIAL_NO C
           WHERE    --C.PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                    TO_DATE(TO_CHAR(C.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
                    C.INST_TYPE LIKE '%' AND--=M_INST_TYPE  AND
                    C.SECURITY_CODE=B.SECURITY_CODE   AND
                    (C.SERIAL_NO_STATUS='INV' OR ( C.SALE_EFF_VALDATE IS NULL) OR
                      (TO_DATE(TO_CHAR(C.SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_DATE,'DD/MM/YYYY'))  )AND
                    TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_DATE,'DD/MM/YYYY')  AND
                    TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
                    C.FACE_VAL>0 AND
                    C.FACE_VAL_CURR IS NULL  AND C.SCRIP_STATUS LIKE '%'
          GROUP BY  C.PORTFOLIO_CODE,C.SECURITY_CODE,B.MATURITY_DATE,DN_GET_COUPON_RATE(B.SECURITY_CODE)  )T2

    WHERE T1.sec=T2.sec)JK;


-------------------------------------------------------------------------
CURSOR SECURITY_CODE IS
        SELECT
        A.SECURITY_CODE X1,
        TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY') X2,
        SUM(A.FACE_VAL-NVL(A.FWD_SALE,0)) X3,
        SUM(A.INITIAL_COST+A.BROKERAGE) X4,
        DECODE(	SUM(A.FACE_VAL),0,SUM(A.FACE_VAL),ROUND(SUM(A.FACE_VAL*A.DEAL_YIELD*100)/SUM(A.FACE_VAL),4)) X5,
        ROUND(TO_NUMBER(B.MATURITY_DATE-TO_DATE(M_DATE,'DD/MM/YYYY')),0) X6,
        DN_GET_COUPON_RATE(B.SECURITY_CODE) X7,
        TO_DATE(B.MATURITY_DATE,'DD-MON-YYYY') X8,PORTFOLIO_CODE X10,
           SUM(A.PRICE_INT_ACCR) X11,
              SUM(A.TOT_COUP_INT) X12,
              SUM(A.CARR_VAL) X13,
              DN_GET_OR_SELLER(A.DEAL_NO) X14
        FROM
        DN_INV_OUTPS_DEAL_SEC A,
        DN_REF_SECURITY B
        WHERE
        --A.PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
        A.INST_TYPE LIKE '%' AND--=M_INST_TYPE AND
        A.SECURITY_CODE=B.SECURITY_CODE AND
        TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_DATE,'DD/MM/YYYY') AND
        TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
        TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
        (A.FACE_VAL > 0 OR A.FACE_VAL < 0) AND
        (A.TRN_TYPE = 'B' OR A.TRN_TYPE = 'S') AND
        A.FACE_VAL_CURR IS NULL AND
        A.SCRIP_STATUS LIKE '%'
        GROUP BY A.PORTFOLIO_CODE,A.SECURITY_CODE,B.MATURITY_DATE,DN_GET_COUPON_RATE(B.SECURITY_CODE),
              DN_GET_OR_SELLER(A.DEAL_NO) ;

 --------------------------------------------------------------------------------------------
 CURSOR TXN IS
 SELECT   U X1,V X2,SUM(X) X3,SUM(Y) X4,
          ROUND(DECODE(SUM(X),0,'0',(SUM(Z)/SUM(X))),4) X5,
		  ROUND(TO_NUMBER(TO_DATE(V,'DD-MM-YYYY')-TO_DATE(M_DATE,'DD/MM/YYYY')),0) X6,
		  DN_GET_COUPON_RATE(U) X7 ,Z1 X8,Z2 X10,X14
-------------
  FROM	  (SELECT  A.SECURITY_CODE U,TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY') V,
	  	           SUM(A.FACE_VALUE) X,SUM(A.COST) Y,SUM(A.FACE_VALUE*A.YIELD*100) Z,TO_DATE(B.MATURITY_DATE,'DD-MON-YYYY') Z1,PORTFOLIO_CODE Z2,
                   SELL_PORTFOLIO_CODE X14
		   FROM    DN_TRN_OUTP_SALE A,
	               DN_REF_SECURITY B,
                   DN_REF_PORTFOLIO C
           WHERE   TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
                   A.DEAL_NO NOT IN   (SELECT DEAL_NO
                                       FROM DN_TRN_DEAL_CURRENCY ) AND
                   --A.BUY_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                   A.BUY_PORTFOLIO_CODE=C.PORTFOLIO_CODE AND
                   A.APP_STATUS<>'CANCEL' AND
                   A.APP_STATUS<>'CONF' AND
                   A.SECURITY_CODE=B.SECURITY_CODE AND
                   TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_DATE,'DD/MM/YYYY') AND
                   TO_DATE(TO_CHAR(A.ENT_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
		           TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
		           TO_DATE(TO_CHAR(C.CREATED_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
		           A.FACE_VALUE > 0 AND
		           C.PF_TYPE='P' AND C.OWNED_BY_MBFSL='Y' AND
				   A.INST_TYPE LIKE '%' AND--=M_INST_TYPE AND
                   A.SCRIPT_STATUS LIKE '%'
	     GROUP BY  C.PORTFOLIO_CODE,A.SECURITY_CODE,B.MATURITY_DATE,SELL_PORTFOLIO_CODE
         ---------------

		UNION ALL

		SELECT      A.SECURITY_CODE U,
                    TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY') V,
                    (SUM(A.FACE_VALUE)*-1) X,(SUM(A.COST)*-1) Y,
                    SUM((A.FACE_VALUE*-1)*A.YIELD*100) Z,TO_DATE(B.MATURITY_DATE,'DD-MON-YYYY') Z1,PORTFOLIO_CODE Z2,
                    SELL_PORTFOLIO_CODE X14

		FROM        DN_TRN_OUTP_SALE A,
                    DN_REF_SECURITY B,
                    DN_REF_PORTFOLIO C
		WHERE       TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
                    A.DEAL_NO NOT IN (SELECT DEAL_NO
                                      FROM   DN_TRN_DEAL_CURRENCY ) AND
                    --A.SELL_PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                    A.SELL_PORTFOLIO_CODE=C.PORTFOLIO_CODE AND
                    A.APP_STATUS<>'CANCEL' AND
                    A.APP_STATUS<>'CONF' AND
                    A.SECURITY_CODE=B.SECURITY_CODE AND
                    TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_DATE,'DD/MM/YYYY') AND
                    TO_DATE(TO_CHAR(A.ENT_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
                    TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
                    TO_DATE(TO_CHAR(C.CREATED_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
                    A.FACE_VALUE > 0 AND
                    C.PF_TYPE='P' AND
                    C.OWNED_BY_MBFSL='Y' AND
                    A.INST_TYPE LIKE '%' AND--=M_INST_TYPE AND
                    A.SCRIPT_STATUS LIKE '%'
 	       GROUP BY C.PORTFOLIO_CODE,A.SECURITY_CODE,B.MATURITY_DATE,
           SELL_PORTFOLIO_CODE
           )

 GROUP BY U,V,DN_GET_COUPON_RATE(U),Z1,Z2,X14  ;

---------------------------------------------------------------------
CURSOR UNWANTED_RECS IS
      SELECT T1.sec X1,T1.X14 X11
        FROM
	         (SELECT  A.SECURITY_CODE sec,TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY') mat,SUM(A.FACE_VAL) a,SUM(A.INITIAL_COST+A.BROKERAGE) b ,DECODE(SUM(A.INITIAL_COST+A.BROKERAGE),0,0,SUM((A.INITIAL_COST+A.BROKERAGE)*A.DEAL_YIELD*100)/SUM(A.INITIAL_COST+A.BROKERAGE))  yeild,
	                  ROUND(TO_NUMBER(B.MATURITY_DATE-TO_DATE(M_DATE,'DD/MM/YYYY')),0) days,DN_GET_COUPON_RATE(B.SECURITY_CODE)rate,
                      DN_GET_OR_SELLER(A.DEAL_NO) X14
           FROM    DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_REF_SECURITY B

           WHERE   --A.PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                   TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
                   A.INST_TYPE LIKE '%'  AND
                   A.SECURITY_CODE=B.SECURITY_CODE  AND
                   (A.SERIAL_NO_STATUS='INV' OR ( A.SALE_EFF_VALDATE IS NULL) OR
	                  (TO_DATE(TO_CHAR(A.SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_DATE,'DD/MM/YYYY')))AND
                   TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_DATE,'DD/MM/YYYY')  AND
                   TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
                   A.FACE_VAL>0 AND
                   A.FACE_VAL_CURR IS NULL  AND
                   A.SCRIP_STATUS LIKE '%'
       GROUP BY    A.PORTFOLIO_CODE,A.SECURITY_CODE,B.MATURITY_DATE,DN_GET_COUPON_RATE(B.SECURITY_CODE),
              DN_GET_OR_SELLER(A.DEAL_NO)
        )T1,

           (SELECT  C.SECURITY_CODE sec,TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),
                    SUM(C.FACE_VAL) a,SUM(C.INITIAL_COST+C.BROKERAGE) b ,
                    DECODE(SUM(C.INITIAL_COST+C.BROKERAGE),0,0,SUM((C.INITIAL_COST+C.BROKERAGE)*C.DEAL_YIELD*100)/SUM(C.INITIAL_COST+C.BROKERAGE)) yeild,
                    ROUND(TO_NUMBER(B.MATURITY_DATE-TO_DATE(M_DATE,'DD/MM/YYYY')),0),DN_GET_COUPON_RATE(B.SECURITY_CODE)rate
            FROM    DN_REF_SECURITY B,
                    DN_HIS_OUTPS_DEAL_SERIAL_NO C

            WHERE  --C.PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
                   TO_DATE(TO_CHAR(C.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_DATE,'DD/MM/YYYY') AND
                   C.INST_TYPE LIKE '%' AND--=M_INST_TYPE  AND
                   C.SECURITY_CODE=B.SECURITY_CODE   AND
                   (C.SERIAL_NO_STATUS='INV' OR ( C.SALE_EFF_VALDATE IS NULL) OR
                     (TO_DATE(TO_CHAR(C .SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_DATE,'DD/MM/YYYY'))  )AND
                   TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_DATE,'DD/MM/YYYY')  AND
                   TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_DATE,'DD/MM/YYYY') AND
                   C.FACE_VAL>0 AND
                   C.FACE_VAL_CURR IS NULL AND
                   C.SCRIP_STATUS LIKE '%'
       GROUP BY    C.PORTFOLIO_CODE,C.SECURITY_CODE,B.MATURITY_DATE,DN_GET_COUPON_RATE(B.SECURITY_CODE)  )T2
    WHERE T1.sec=T2.sec;


 BEGIN

  -------------------------------------------------------------------
  DELETE FROM DN_TEMP_SHARE_PORT_SUM WHERE USER_NAME=UPPER(M_USER);
  --------------------------------------------------------------------
  FOR I IN  SERIAL_NO
  LOOP
  INSERT INTO DN_TEMP_SHARE_PORT_SUM
  (STATUS,SECURITY_CODE,CHAR_MAT_DATE,FACE_VAL,INITIALCOST_BROK,INITIALCOST_BROK_YIELD,NOOF_DAYS,COUPON_RATE,
  MATURITY_DATE,POSITION,PORTFOLIO_CODE,PRICE_INT_ACCR,TOT_COUP_INT,CARR_VAL,USER_NAME,SELLER_CODE)
  VALUES
  ('SER',I.X1,I.X2,I.X3,I.X4,I.X5,I.X6,I.X7,I.X8,I.X9,I.X10,I.X11,I.X12,I.X13,UPPER(M_USER),I.X14)
  ;
  COMMIT;
  END LOOP;

  ----------------------------------------------------

  FOR R IN  UNWANTED_RECS
  LOOP

  DELETE FROM DN_TEMP_SHARE_PORT_SUM
  WHERE  SECURITY_CODE=R.X1 AND
         POSITION='UPPER' AND USER_NAME=UPPER(M_USER) /*AND
         SELLER_CODE = R.X11*/
----------------
         ;

  COMMIT;
  END LOOP;

  --------------------------------------------------------------------

  FOR J IN  SECURITY_CODE
  LOOP

  INSERT INTO DN_TEMP_SHARE_PORT_SUM
  (STATUS,SECURITY_CODE,CHAR_MAT_DATE,FACE_VAL,INITIALCOST_BROK,
   INITIALCOST_BROK_YIELD,NOOF_DAYS,COUPON_RATE,MATURITY_DATE,PORTFOLIO_CODE,PRICE_INT_ACCR,
   TOT_COUP_INT,CARR_VAL,USER_NAME,SELLER_CODE)
  VALUES
  ('SEC',J.X1,J.X2,J.X3,J.X4,J.X5,J.X6,J.X7,J.X8,J.X10,J.X11,J.X12,J.X13,UPPER(M_USER),J.X14)
  ;
  COMMIT;
  END LOOP;

  --------------------------------------------------------------------
  FOR K IN  TXN
  LOOP

  INSERT INTO DN_TEMP_SHARE_PORT_SUM
  (STATUS,SECURITY_CODE,CHAR_MAT_DATE,FACE_VAL,INITIALCOST_BROK,
   INITIALCOST_BROK_YIELD,NOOF_DAYS,COUPON_RATE,MATURITY_DATE,PORTFOLIO_CODE,USER_NAME,SELLER_CODE)
  VALUES
  ('TXN',K.X1,K.X2,K.X3,K.X4,K.X5,K.X6,K.X7,K.X8,K.X10,UPPER(M_USER),K.X14)
  ;
  COMMIT;
  END LOOP;
--------------------------------------------------------------------

  UPDATE DN_TEMP_SHARE_PORT_SUM
  SET MARKET_RATE=RETURN_MARKET_VAL(SECURITY_CODE,M_DATE),
        MARKET_VALUE=RETURN_MARKET_VAL(SECURITY_CODE,M_DATE)*FACE_VAL
        WHERE USER_NAME=UPPER(M_USER);

END;

