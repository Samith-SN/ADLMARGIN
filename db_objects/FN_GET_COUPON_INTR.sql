  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."FN_GET_COUPON_INTR" 
(
M_SECURITY_CODE         DN_REF_SECURITY.SECURITY_CODE%TYPE,
M_TOT_FACE              DN_TRN_OUTP_SALE.FACE_VALUE%TYPE
)
RETURN  DN_TRN_OUTP_SALE.FACE_VALUE%TYPE
IS
M_COUPON_INT             DN_REF_SECURITY.COUPON_INT%TYPE;
BEGIN
 SELECT COUPON_INT
 INTO   M_COUPON_INT
 FROM   DN_REF_SECURITY
 WHERE  SECURITY_CODE=M_SECURITY_CODE;

 RETURN (M_TOT_FACE*M_COUPON_INT)/2;

END FN_GET_COUPON_INTR;

