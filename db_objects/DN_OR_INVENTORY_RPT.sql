set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_OR_INVENTORY_RPT" 
(
M_SCRIP_STATUS              DN_INV_OUTPS_DEAL_SERIAL_NO.SCRIP_STATUS%TYPE,
M_PORTFOLIO_CODE            DN_INV_OUTPS_DEAL_SERIAL_NO.PORTFOLIO_CODE%TYPE,
M_PASS_DATE                 VARCHAR2

)
 AS
 --CREATED BY : NIRMALA
 --CREATED ON :25-02-2004

 CURSOR SERIAL_NO IS
 SELECT JK.X1,JK.X2,JK.X3,JK.X4,JK.X5,JK.X6,JK.X7,'UPPER' X8
 FROM
     (SELECT  A.PORTFOLIO_CODE X1,
              A.INST_TYPE X2,
              A.SECURITY_CODE X3,
              NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') X4,
              SUM(A.FACE_VAL)X5,
              NVL(DN_GET_ALLOFACEVAL_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) X6,
              NVL(DN_GET_UNALLOCATED_AMT_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) X7

      FROM    DN_INV_OUTPS_DEAL_SERIAL_NO A,
              DN_REF_SECURITY B
      WHERE   A.PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
              TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
              A.SECURITY_CODE=B.SECURITY_CODE  AND
              (A.SERIAL_NO_STATUS='INV' OR ( A.SALE_EFF_VALDATE IS NULL) OR
	              (TO_DATE(TO_CHAR(A.SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_PASS_DATE,'DD/MM/YYYY'))  )AND
	          TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_PASS_DATE,'DD/MM/YYYY')  AND
	          TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
              A.FACE_VAL>0 AND
              A.FACE_VAL_CURR IS NULL  AND
              A.SCRIP_STATUS=M_SCRIP_STATUS
    GROUP BY  A.PORTFOLIO_CODE ,
              A.INST_TYPE ,
              A.SECURITY_CODE ,
              NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') ,
              NVL(DN_GET_ALLOFACEVAL_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) ,
              NVL(DN_GET_UNALLOCATED_AMT_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0)


      UNION

      SELECT  A.PORTFOLIO_CODE X1,
              A.INST_TYPE X2,
              A.SECURITY_CODE X3,
              NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') X4,
              SUM(A.FACE_VAL)X5,
              NVL(DN_GET_ALLOFACEVAL_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) X6,
              NVL(DN_GET_UNALLOCATED_AMT_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) X7


         FROM  DN_REF_SECURITY B,
               DN_HIS_OUTPS_DEAL_SERIAL_NO A
      WHERE    A.PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
               TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
               A.SECURITY_CODE=B.SECURITY_CODE  AND
               (A.SERIAL_NO_STATUS='INV' OR ( A.SALE_EFF_VALDATE IS NULL) OR
			      (TO_DATE(TO_CHAR(A.SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_PASS_DATE,'DD/MM/YYYY'))  )AND
			   TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_PASS_DATE,'DD/MM/YYYY')  AND
	 		   TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
			   A.FACE_VAL>0 AND
			   A.FACE_VAL_CURR IS NULL AND
               A.SCRIP_STATUS=M_SCRIP_STATUS
	GROUP BY   A.PORTFOLIO_CODE ,
               A.INST_TYPE ,
               A.SECURITY_CODE ,
               NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') ,
               NVL(DN_GET_ALLOFACEVAL_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) ,
               NVL(DN_GET_UNALLOCATED_AMT_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0)


	) JK

UNION
 SELECT JK.X1,JK.X2,JK.X3,JK.X4,JK.X5,JK.X6,JK.X7,'LOWER' X8
 FROM
    (SELECT T1.X1 X1 ,T1.X2 X2,
            T1.X3 X3 ,
            T1.X4 X4 ,
            (T1.X5+T2.X5)X5,
            (T1.X6+T2.X6)X6,
            (T1.X7+T2.X7)X7

     FROM  (SELECT  A.PORTFOLIO_CODE X1,
                    A.INST_TYPE X2,
                    A.SECURITY_CODE X3,
                    NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') X4,
                    SUM(A.FACE_VAL)X5,
                    NVL(DN_GET_ALLOFACEVAL_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) X6,
                    NVL(DN_GET_UNALLOCATED_AMT_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) X7


            FROM    DN_INV_OUTPS_DEAL_SERIAL_NO A,
                    DN_REF_SECURITY B
           WHERE    A.PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
                    TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                    A.SECURITY_CODE=B.SECURITY_CODE  AND
                    (A.SERIAL_NO_STATUS='INV' OR ( A.SALE_EFF_VALDATE IS NULL) OR
	                  (TO_DATE(TO_CHAR(A.SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_PASS_DATE,'DD/MM/YYYY')))AND
                    TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_PASS_DATE,'DD/MM/YYYY')  AND
                    TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                    A.FACE_VAL>0 AND
                    A.FACE_VAL_CURR IS NULL  AND
                    A.SCRIP_STATUS=M_SCRIP_STATUS
        GROUP BY    A.PORTFOLIO_CODE ,
                    A.INST_TYPE ,
                    A.SECURITY_CODE ,
                    NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') ,
                    NVL(DN_GET_ALLOFACEVAL_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) ,
                    NVL(DN_GET_UNALLOCATED_AMT_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS ,M_PASS_DATE),0)  )T1,

        (SELECT     A.PORTFOLIO_CODE X1,
                    A.INST_TYPE X2,
                    A.SECURITY_CODE X3,
                    NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') X4,
                    SUM(A.FACE_VAL)X5,
                    NVL(DN_GET_ALLOFACEVAL_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS ,M_PASS_DATE ),0) X6,
                    NVL(DN_GET_UNALLOCATED_AMT_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) X7


            FROM    DN_REF_SECURITY B,
                    DN_HIS_OUTPS_DEAL_SERIAL_NO A
           WHERE    A.PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
                    TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                    A.SECURITY_CODE=B.SECURITY_CODE   AND
                    (A.SERIAL_NO_STATUS='INV' OR ( A.SALE_EFF_VALDATE IS NULL) OR
                      (TO_DATE(TO_CHAR(A.SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_PASS_DATE,'DD/MM/YYYY'))  )AND
                    TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_PASS_DATE,'DD/MM/YYYY')  AND
                    TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                    A.FACE_VAL>0 AND
                    A.FACE_VAL_CURR IS NULL  AND A.SCRIP_STATUS=M_SCRIP_STATUS
          GROUP BY  A.PORTFOLIO_CODE ,
                    A.INST_TYPE ,
                    A.SECURITY_CODE ,
                    NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') ,
                    NVL(DN_GET_ALLOFACEVAL_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0) ,
                    NVL(DN_GET_UNALLOCATED_AMT_OR(A.SECURITY_CODE,A.PORTFOLIO_CODE,A.INST_TYPE,M_SCRIP_STATUS,M_PASS_DATE ),0)  )T2

    WHERE T1.X1=T2.X1 AND T1.X2=T2.X2 AND T1.X3=T2.X3   )JK;


-------------------------------------------------------------------------
CURSOR SECURITY_CODE IS
 SELECT A.PORTFOLIO_CODE X1,
        A.INST_TYPE X2,
        A.SECURITY_CODE X3,
        NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') X4,
        SUM(A.FACE_VAL) X5,
        0 X6,
        0 X7

        FROM
        DN_INV_OUTPS_DEAL_SEC A,
        DN_REF_SECURITY B
        WHERE
        A.PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
        A.SECURITY_CODE=B.SECURITY_CODE AND
        TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
        TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
        TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
        (A.FACE_VAL > 0 OR A.FACE_VAL < 0) AND
        (A.TRN_TYPE = 'B' OR A.TRN_TYPE = 'S') AND
        A.FACE_VAL_CURR IS NULL AND
        A.SCRIP_STATUS=M_SCRIP_STATUS
        GROUP BY A.PORTFOLIO_CODE ,
                 A.INST_TYPE,
                 A.SECURITY_CODE,
                 NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-');

 --------------------------------------------------------------------------------------------
 CURSOR TXN IS
 SELECT V.X1,V.X2,V.X3,V.X4,SUM(V.X5)X5,V.X6,V.X7
  FROM	  (SELECT  A.BUY_PORTFOLIO_CODE X1,
                   A.INST_TYPE X2,
                   A.SECURITY_CODE X3,
                   NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') X4,
                   SUM(A.FACE_VALUE) X5,
                   0 X6,
                   0 X7
		   FROM    DN_TRN_OUTP_SALE A,
	               DN_REF_SECURITY B,
                   DN_REF_PORTFOLIO C
           WHERE   TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                   A.DEAL_NO NOT IN   (SELECT DEAL_NO
                                       FROM DN_TRN_DEAL_CURRENCY ) AND
                   A.BUY_PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
                   A.BUY_PORTFOLIO_CODE=C.PORTFOLIO_CODE AND
                   A.APP_STATUS<>'CANCEL' AND
                   A.APP_STATUS<>'CONF' AND
                   A.SECURITY_CODE=B.SECURITY_CODE AND
                   TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                   --TO_DATE(TO_CHAR(A.ENT_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
		           TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
		           --TO_DATE(TO_CHAR(C.CREATED_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
		           A.FACE_VALUE > 0 AND
		           C.PF_TYPE='P' AND C.OWNED_BY_MBFSL='Y' AND
                   A.SCRIPT_STATUS=M_SCRIP_STATUS
	     GROUP BY  A.BUY_PORTFOLIO_CODE , A.INST_TYPE, A.SECURITY_CODE, NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-')

		UNION ALL

		SELECT      A.BUY_PORTFOLIO_CODE X1,
                    A.INST_TYPE X2,
                    A.SECURITY_CODE X3,
                    NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') X4,
                    (SUM(A.FACE_VALUE)*-1) X5,
                    0 X6,
                    0 X7
		FROM        DN_TRN_OUTP_SALE A,
                    DN_REF_SECURITY B,
                    DN_REF_PORTFOLIO C
		WHERE       TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                    A.DEAL_NO NOT IN (SELECT DEAL_NO
                                      FROM   DN_TRN_DEAL_CURRENCY ) AND
                    A.SELL_PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
                    A.SELL_PORTFOLIO_CODE=C.PORTFOLIO_CODE AND
                    A.APP_STATUS<>'CANCEL' AND
                    A.APP_STATUS<>'CONF' AND
                    A.SECURITY_CODE=B.SECURITY_CODE AND
                    TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                    --TO_DATE(TO_CHAR(A.ENT_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                    TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                    --TO_DATE(TO_CHAR(C.CREATED_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                    A.FACE_VALUE > 0 AND
                    C.PF_TYPE='P' AND
                    C.OWNED_BY_MBFSL='Y' AND
                    A.SCRIPT_STATUS=M_SCRIP_STATUS
 	      GROUP BY  A.BUY_PORTFOLIO_CODE , A.INST_TYPE, A.SECURITY_CODE, NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-'))V

 GROUP BY V.X1,V.X2,V.X3,V.X4,V.X6,V.X7  ;

CURSOR UNWANTED_RECS IS
      SELECT T1.X3 X1
        FROM
	         (SELECT   A.PORTFOLIO_CODE X1,A.INST_TYPE X2,A.SECURITY_CODE X3,NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') X4,
                       SUM(A.FACE_VAL)X5

           FROM    DN_INV_OUTPS_DEAL_SERIAL_NO A,DN_REF_SECURITY B

           WHERE   A.PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
                   TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                   A.SECURITY_CODE=B.SECURITY_CODE  AND
                   (A.SERIAL_NO_STATUS='INV' OR ( A.SALE_EFF_VALDATE IS NULL) OR
	                  (TO_DATE(TO_CHAR(A.SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_PASS_DATE,'DD/MM/YYYY')))AND
                   TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_PASS_DATE,'DD/MM/YYYY')  AND
                   TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                   A.FACE_VAL>0 AND
                   A.FACE_VAL_CURR IS NULL  AND
                   A.SCRIP_STATUS=M_SCRIP_STATUS
       GROUP BY    A.PORTFOLIO_CODE,A.INST_TYPE,A.SECURITY_CODE,NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') )T1,

           (SELECT  A.PORTFOLIO_CODE X1,A.INST_TYPE X2,A.SECURITY_CODE X3,NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-') X4,
                    SUM(A.FACE_VAL)X5
            FROM    DN_REF_SECURITY B,
                    DN_HIS_OUTPS_DEAL_SERIAL_NO A

            WHERE  A.PORTFOLIO_CODE=M_PORTFOLIO_CODE AND
                   TO_DATE(TO_CHAR(A.EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')<=TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                   A.SECURITY_CODE=B.SECURITY_CODE   AND
                   (A.SERIAL_NO_STATUS='INV' OR ( A.SALE_EFF_VALDATE IS NULL) OR
                     (TO_DATE(TO_CHAR(A .SALE_EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')>TO_DATE(M_PASS_DATE,'DD/MM/YYYY'))  )AND
                   TO_DATE(TO_CHAR(B.MATURITY_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')>= TO_DATE(M_PASS_DATE,'DD/MM/YYYY')  AND
                   TO_DATE(TO_CHAR(B.ISSUE_DATE,'DD-MON-YYYY'),'DD-MON-YYYY')<= TO_DATE(M_PASS_DATE,'DD/MM/YYYY') AND
                   A.FACE_VAL>0 AND
                   A.FACE_VAL_CURR IS NULL AND
                   A.SCRIP_STATUS=M_SCRIP_STATUS
           GROUP BY  A.PORTFOLIO_CODE,A.INST_TYPE,A.SECURITY_CODE,NVL(DN_EXT_SECURITY(A.SECURITY_CODE),'-')  )T2
    WHERE T1.X3=T2.X3;


 BEGIN
  DELETE FROM DN_TEMP_OR_INVENTORY;
  COMMIT;
  --------------------------------------------------------------------

  FOR I IN  SERIAL_NO
  LOOP

  INSERT INTO DN_TEMP_OR_INVENTORY
  (STATUS,PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,EXT_SECURITY_CODE,FACE_VAL,CONF_ALLO,UNCONF_ALLO)
  VALUES
  ('SER',I.X1,I.X2,I.X3,I.X4,I.X5,I.X6,I.X7);
  COMMIT;

  END LOOP;
  --========================================
  FOR R IN  UNWANTED_RECS
  LOOP

  DELETE FROM DN_TEMP_OR_INVENTORY
  WHERE  SECURITY_CODE=R.X1 AND
         POSITION='UPPER';

  COMMIT;

  END LOOP;
   --------------------------------------------------------------------
  FOR J IN  SECURITY_CODE
  LOOP

  INSERT INTO DN_TEMP_OR_INVENTORY
    (STATUS,PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,EXT_SECURITY_CODE,FACE_VAL,CONF_ALLO,UNCONF_ALLO)
  VALUES
  ('SEC',J.X1,J.X2,J.X3,J.X4,J.X5,J.X6,J.X7);
  COMMIT;
  END LOOP;
--------------------------------------------------------------------
  FOR K IN  TXN
  LOOP

  INSERT INTO DN_TEMP_OR_INVENTORY
    (STATUS,PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,EXT_SECURITY_CODE,FACE_VAL,CONF_ALLO,UNCONF_ALLO)
  VALUES
  ('TXN',K.X1,K.X2,K.X3,K.X4,K.X5,K.X6,K.X7);
  COMMIT;
  END LOOP;
--------------------------------------------------------------------

 END DN_OR_INVENTORY_RPT;

