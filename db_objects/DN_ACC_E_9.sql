set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_E_9" 
(
M_DOCREFNO   IN OUT     DN_TRN_BO_CUSTODIAL_FEES.INVOICE_NO%TYPE
)
AS

/* PROCEDURE  - DN_ACC_E_9 CUSTODIAL FEES ACCUMULATION
   SYSTEM     - DEALNET
   CREATED BY - LATHIKA
   CREATED ON - 28/DEC/1999*/


M_PORTF_CODE          DN_TRN_BO_CUSTODIAL_FEES.PORTFOLIO_CODE%TYPE;
M_TRNAMOUNT           DN_TRN_BO_CUSTODIAL_FEES.FEE_AMOUNT%TYPE;
M_INVOICE_DATE        DN_TRN_BO_CUSTODIAL_FEES.INVOICE_DATE%TYPE;
M_TRNAMOUNT2          DN_TRN_BO_CUSTODIAL_FEES.GST_AMOUNT%TYPE;

BEGIN

SELECT DISTINCT PORTFOLIO_CODE,to_char(INVOICE_DATE,'dd-mon-yyyy')
INTO M_PORTF_CODE,M_INVOICE_DATE
FROM DN_TRN_BO_CUSTODIAL_FEES
WHERE INVOICE_NO=M_DOCREFNO;

SELECT SUM(FEE_AMOUNT), SUM(GST_AMOUNT)
INTO M_TRNAMOUNT,M_TRNAMOUNT2
FROM DN_TRN_BO_CUSTODIAL_FEES
WHERE INVOICE_NO=M_DOCREFNO;

-------------------(1)-------------------------
INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_PORTF_CODE,M_INVOICE_DATE,'401','DR',M_TRNAMOUNT,M_DOCREFNO,'ACCUMULATION OF CUSTODIAL FEES','400');

INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
   (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
   VALUES(M_PORTF_CODE,M_PORTF_CODE,M_INVOICE_DATE,'400','CR',M_TRNAMOUNT,M_DOCREFNO,'ACCUMULATION OF CUSTODIAL FEES','401');

END DN_ACC_E_9;

/
