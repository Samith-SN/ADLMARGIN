set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CAP_DIPOSIT_WITH_CONF" 
   (
   M_DOCREFNO           DN_TRN_BO_CAP_DEPOSIT_TEMP.DOCREFNO%TYPE,
   M_TRANSACTION_TYPE   DN_TRN_BO_CAP_DEPOSIT_TEMP.TRANSACTION_TYPE%TYPE,
   M_USER               DN_TRN_REPO_FRESH.DN_USER%TYPE
   )
AS
M_NUMBER        VARCHAR(100);
M_LAST_DAILY    DN_SYS_PARAMETER.LAST_DAILY%TYPE;

CURSOR M_CURSOR IS SELECT A.DOCREFNO, A.PORTFOLIO_CODE, A.TRANSACTION_TYPE, A.PROC_DESC,
       A.LICENCEE_BRANCH_CODE, A.LICENEE_ACCOUNT_NO, A.TRNAMOUNT,
       A.DN_USER, A.TRNDATE, A.RECON_STATUS, A.RECON_DATE, A.RECON_BY,
       TO_CHAR(A.EFF_VAL_DATE,'DD/MM/YYYY') EFF_VAL_DATE , A.REALISED_DATE, A.PAYEE_BANK, A.CHEQUE_NO,
       A.LAST_CHANEGE_USER, A.LAST_CHANEGE_DATE, A.CURRENT_STATUS FROM DN_TRN_BO_CAP_DEPOSIT_TEMP A
   WHERE DOCREFNO = M_DOCREFNO AND CURRENT_STATUS='ENT';

BEGIN


SELECT LAST_DAILY INTO M_LAST_DAILY
FROM DN_SYS_PARAMETER;

IF M_TRANSACTION_TYPE='DEPOSIT' THEN

FOR X IN M_CURSOR LOOP
--RAISE_APPLICATION_ERROR(-20201,'aaaaaa'||M_LAST_DAILY||'bbbbbb'||X.EFF_VAL_DATE||' DAY END ALREADY RUN..!');
  IF TO_DATE(M_LAST_DAILY,'DD-MM-YYYY') < TO_DATE(X.EFF_VAL_DATE,'DD-MM-YYYY') THEN  --ADD BY WARUNA 2013-02-05

   DN_ACC_CAPITAL_DEPOSIT_NEW(X.DOCREFNO,X.PORTFOLIO_CODE ,X.PORTFOLIO_CODE,X.TRNAMOUNT,
                              '',--M_ACC_NO
                              X.LICENCEE_BRANCH_CODE,X.LICENEE_ACCOUNT_NO,
                              M_USER,X.PROC_DESC,
                              X.EFF_VAL_DATE,
                              M_NUMBER,--M_NUMBER
                              X.PAYEE_BANK,X.CHEQUE_NO);

   ELSE
   RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT CONFIRM  ='||X.DOCREFNO||' DAY END ALREADY RUN..!');
   END IF;


END LOOP;

ELSIF M_TRANSACTION_TYPE='WITHDRAWAL' THEN
FOR X IN M_CURSOR LOOP

  IF TO_DATE(M_LAST_DAILY,'DD-MM-YYYY') < TO_DATE(X.EFF_VAL_DATE,'DD-MM-YYYY') THEN  --ADD BY WARUNA 2013-02-05

    DN_ACC_CAPITAL_WITHDRAWAL_NEW(X.DOCREFNO,X.PORTFOLIO_CODE,X.PORTFOLIO_CODE,X.TRNAMOUNT,
                                  '' ,--M_ACC_NO
                                  X.LICENCEE_BRANCH_CODE,X.LICENEE_ACCOUNT_NO,
                                  M_USER,X.PROC_DESC,X.EFF_VAL_DATE,
                                  M_NUMBER,--M_NUMBER,
                                  X.CHEQUE_NO );

   ELSE
   RAISE_APPLICATION_ERROR(-20201,'YOU CAN NOT CONFIRM  ='||X.DOCREFNO||' DAY END ALREADY RUN..!');
   END IF;

END LOOP;
END IF;


COMMIT;



END DN_CAP_DIPOSIT_WITH_CONF; 

