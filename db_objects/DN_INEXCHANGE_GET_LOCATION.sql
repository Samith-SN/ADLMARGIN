  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_INEXCHANGE_GET_LOCATION" 
    (
      M_PORTFOLIO_CODE    DN_INV_REPO_DEAL_SERIAL_NO.PORTFOLIO_CODE%TYPE,
      M_INST_TYPE         DN_INV_REPO_DEAL_SERIAL_NO.INST_TYPE%TYPE,
      M_SECURITY_CODE     DN_INV_REPO_DEAL_SERIAL_NO.SECURITY_CODE%TYPE,
      M_DEAL_NO           DN_INV_REPO_DEAL_SERIAL_NO.DEAL_NO%TYPE,
      M_SERIAL_NO         DN_INV_REPO_DEAL_SERIAL_NO.SERIAL_NO%TYPE,
      M_MODE              VARCHAR2
    )
   RETURN  VARCHAR2
    IS

    -- Function     : TO RETURN ACC_TYPE_DESC
    -- System       : DEALNET
    -- Created by   : LATHIKA
    -- Created on   : 17/01/2000

 M_LOCATION    DN_INV_REPO_DEAL_SERIAL_NO.LOCATION%TYPE;

  BEGIN

 M_LOCATION := '';

 IF  M_MODE ='RP' THEN
     SELECT
      LOCATION
     INTO
      M_LOCATION
     FROM
     DN_INV_REPO_DEAL_SERIAL_NO
     WHERE PORTFOLIO_CODE = M_PORTFOLIO_CODE
     AND   INST_TYPE      = M_INST_TYPE
     AND   SECURITY_CODE  = M_SECURITY_CODE
     AND   DEAL_NO        = M_DEAL_NO
     AND   SERIAL_NO      = M_SERIAL_NO
     AND   RET_DUE_DATE   >SYSDATE-1;

  ELSIF  M_MODE ='BL'  THEN

    SELECT
      LOCATION
     INTO
      M_LOCATION
     FROM
     DN_INV_BL_DEAL_SERIAL_NO
     WHERE PORTFOLIO_CODE = M_PORTFOLIO_CODE
     AND   INST_TYPE      = M_INST_TYPE
     AND   SECURITY_CODE  = M_SECURITY_CODE
     AND   DEAL_NO        = M_DEAL_NO
     AND   SERIAL_NO      = M_SERIAL_NO
     AND   RET_DUE_DATE   >SYSDATE-1;

  ELSIF  M_MODE ='OR'  THEN

    SELECT
      LOCATION
     INTO
      M_LOCATION
     FROM
     DN_INV_OUTPS_DEAL_SERIAL_NO
     WHERE PORTFOLIO_CODE = M_PORTFOLIO_CODE
     AND   INST_TYPE      = M_INST_TYPE
     AND   SECURITY_CODE  = M_SECURITY_CODE
     AND   DEAL_NO        = M_DEAL_NO
     AND   SERIAL_NO      = M_SERIAL_NO;

  END IF;

 RETURN M_LOCATION;

END DN_INEXCHANGE_GET_LOCATION;

