  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_TRN_SETTLEMENT_REC_LOAN" 
   (M_REC_NO    IN OUT DN_TRN_LOAN_SETTL_RECEIPT.REC_NO%TYPE,
