    UPDATE DN_ACC_SUS_RECEIPT
      SET REC_FROM_INT_BAL_AMT = REC_FROM_INT_BAL_AMT+MM_AMT,
          BAL_TO_BE_RECEIVED   = BAL_TO_BE_RECEIVED-MM_AMT,
          LAST_MOD_DATE        = SYSDATE

    WHERE
        SUS_REF_NO=M_DEALNO AND SUSPENSE_ENTRY_TYPE=M_DEAL_TYPE;


  
          INSERT INTO DN_TIME_LOG_SETTLE
          (DOC_REF_NO,
            REL_DEAL_NO,
           DN_USER,
           ENT_DATE,
           DESCRIPTION)
