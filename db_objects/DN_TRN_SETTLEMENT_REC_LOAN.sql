    M_P_BRANCH_CODE    DN_TRN_LOAN_SETTL_RECEIPT.PAYER_BRANCH_CODE%TYPE,--8

    M_PAYER_ACC_NO     DN_TRN_LOAN_SETTL_RECEIPT.PAYER_ACC_NO%TYPE,
    M_PAYER_REF        DN_TRN_LOAN_SETTL_RECEIPT.PAYER_REF%TYPE,
    M_COMMENTS         DN_TRN_LOAN_SETTL_RECEIPT.OTH_COMMENTS%TYPE,
    M_BRANCH_CODE      DN_TRN_LOAN_SETTL_RECEIPT.BRANCH_CODE%TYPE,
    M_ACC_NO           DN_TRN_LOAN_SETTL_RECEIPT.ACC_NO%TYPE,
