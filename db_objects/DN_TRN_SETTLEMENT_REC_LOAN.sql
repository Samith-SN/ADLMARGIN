            ( M_REC_NO,M_DEALNO,
            M_USER,
              SYSDATE,
              'SETTLEMENT RECEIPT'
           );
           
 --*****************************************************************

   --DBMS_OUTPUT.put_line('DOCNO  '||M_REC_NO||'  '||M_DEALNO );
