set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."WF_LOGIN_OK" 
(
 M_USER                 VARCHAR2,
 M_PASSWORD             VARCHAR2,
 M_USER_STATUS          IN OUT NUMBER,
 M_URL                  IN OUT DN_REF_SCREEN_URL.DN_SCREEN_URL%TYPE,
 M_SCRNAME              DN_REF_SCREEN_URL.DN_SCREEN_NAME%TYPE
)

  -- PROCEDURE    : VERIFIY USER LOGIN
  -- SYSTEM       : DEALNET SYSTEM
  -- CREATED BY   : CHARMINDA
  -- CREATED ON   : 20/08/1999

 AS

M_ROLE_NAME          VARCHAR2(40);

BEGIN

    M_USER_STATUS:=0;

    /* VERIFY USER */

IF M_SCRNAME='WD_DN_MAIN'THEN

    SELECT
      DN_SCREEN_URL,1 INTO M_URL,M_USER_STATUS
    FROM
      DN_REF_SCREEN_URL
    WHERE
      DN_SCREEN_NAME=M_SCRNAME;

ELSE

--RAISE_APPLICATION_ERROR(-20201,TO_CHAR(M_USER_STATUS));

    SELECT
    COUNT (*) INTO M_USER_STATUS
    FROM DN_REF_USER_VIEW_ACCESS
    WHERE DN_USER=M_USER AND SCREEN_NAME=M_SCRNAME;

    IF M_USER_STATUS>0 THEN
    SELECT
      DN_SCREEN_URL INTO M_URL
    FROM
      DN_REF_SCREEN_URL
    WHERE
      DN_SCREEN_NAME=M_SCRNAME;
    END IF;

END IF;

COMMIT;

END WF_LOGIN_OK;

