  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_DIVIDEND_INCOME" 
(
M_PORTF_CODE           DN_ACC_LICENCEE_GEN_ACCOUNT.PORTFOLIO_CODE%TYPE,
M_DN_PORTF_CODE        DN_ACC_LICENCEE_GEN_ACCOUNT.DN_PORTFOLIO_CODE%TYPE,
M_TRNAMOUNT            DN_ACC_LICENCEE_GEN_ACCOUNT.TRNAMOUNT%TYPE,
M_ACC_NO               DN_REF_LICENCEE_SETTLEMENT.ACC_NO%TYPE,
M_LICENCEE_BRANCH_CODE DN_TRN_DIVIDEND_INCOME.LICENCEE_BRANCH_CODE%TYPE,
M_LICENCEE_ACCOUNT_NO  DN_TRN_DIVIDEND_INCOME.LICENEE_ACCOUNT_NO%TYPE,
M_DN_USER              DN_TRN_DIVIDEND_INCOME.DN_USER%TYPE,
M_PROC_DESC            DN_TRN_DIVIDEND_INCOME.PROC_DESC%TYPE,
M_EFF_DATE             VARCHAR2,
M_NUMBER               IN OUT VARCHAR,
M_PAYEE_BANK           VARCHAR2,
M_CHEQUE_NO            VARCHAR2,
M_INST                 DN_TRN_DIVIDEND_INCOME.INST_CODE%TYPE,
M_SEC                  DN_TRN_DIVIDEND_INCOME.SEC_CODE%TYPE,
M_TAX                  DN_TRN_DIVIDEND_INCOME.WITHHOLDING_TAX%TYPE, --ADDED BY S.SHANHEETHA ON 14-09-2006 FOR SR0609-014.
M_COMMENTS             DN_TRN_DIVIDEND_INCOME.COMMENTS%TYPE 
)
AS


M_DOCREFNO             DN_TRN_DIVIDEND_INCOME.DOCREFNO%TYPE;
M_ACC_SYS_REFNO        DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE;

BEGIN

DN_VALIDATE_SAVE_RIGHTS(M_DN_USER,'WD_Divi_Income');--ADDED BY AH ON 25-10-2005 FOR SR0510-056


SELECT 'DI'||TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_DIVIDEND_INCOME.NEXTVAL),3,'0')
INTO M_DOCREFNO    FROM DUAL;

 SELECT
 ACC_SYS_REFNO
 INTO M_ACC_SYS_REFNO
 FROM DN_REF_LICENCEE_SETTLEMENT
 WHERE BRANCH_CODE=M_LICENCEE_BRANCH_CODE
 AND ACC_NO = M_LICENCEE_ACCOUNT_NO
 AND ACTIVE_STATUS ='Y';

 INSERT INTO DN_TRN_DIVIDEND_INCOME
               (  DOCREFNO,
                  PORTFOLIO_CODE,
                  PROC_DESC,INST_CODE,
                  SEC_CODE,
                  LICENCEE_BRANCH_CODE,
                  LICENEE_ACCOUNT_NO,
                  TRNAMOUNT,
                  DN_USER,
                  TRNDATE,
                      EFF_VAL_DATE,PAYEE_BANK,CHEQUE_NO,RECEIVED_DATE
                      ,WITHHOLDING_TAX --// ADDED BY S.SHANHEETHA ON 14-09-2006 FOR SR0609-014.
                      ,APP_STATUS
                      ,COMMENTS) -- Added by Prabash on 28-05-2012
                VALUES
                   (  M_DOCREFNO,
                      M_PORTF_CODE,
                      M_PROC_DESC,M_INST,M_SEC,
                      M_LICENCEE_BRANCH_CODE,
                      M_LICENCEE_ACCOUNT_NO,
                      M_TRNAMOUNT,
                      M_DN_USER,
                      SYSDATE,
                      TO_DATE(M_EFF_DATE,'DD/MM/YYYY'),
                      M_PAYEE_BANK,
                       M_CHEQUE_NO ,
                       TO_DATE(M_EFF_DATE,'DD/MM/YYYY'),
                       M_TAX,--// ADDED BY S.SHANHEETHA ON 14-09-2006 FOR SR0609-014.
                       'ENT', --Added ByPrabash on 28-05-2012
                       M_COMMENTS);  --Added ByPrabash on 27-07-2012
                       
/* 
REMARK BY WARUNA 2012-10-10 BECOUSE DIRECT ENTRY GOES TO DIVIDEND RECEIVABLE 
DN_ACC_DIV_INC_ACC('GEN',M_DN_PORTF_CODE,TO_DATE(M_EFF_DATE,'DD/MM/YYYY'),M_TRNAMOUNT,M_DOCREFNO,M_ACC_SYS_REFNO,M_INST,M_TAX) ;--// ADDED M_TAX BY S.SHANHEETHA ON 14-09-2006 FOR SR0609-014.
*/
      INSERT INTO DN_TIME_LOG_SETTLE
          (DOC_REF_NO,
           DN_USER,
           ENT_DATE,
           DESCRIPTION)
           VALUES
            ( M_DOCREFNO,
              M_DN_USER,
              SYSDATE,
              'PORTFOLIO DIVIDEND INCOME ');
M_NUMBER:=M_DOCREFNO;

COMMIT;

END DN_ACC_DIVIDEND_INCOME; 

