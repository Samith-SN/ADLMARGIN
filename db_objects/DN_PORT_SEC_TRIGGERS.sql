set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_PORT_SEC_TRIGGERS" 
   (
    M_PORTFOLI_CODE     DN_REF_PORTF_SECURITY_RATES.PORTFOLIO_CODE%TYPE,
    M_SECURITY_CODE     DN_REF_PORTF_SECURITY_RATES.SECURITY_CODE%TYPE,
    M_CUT_LOSS          DN_REF_PORTF_SECURITY_RATES.CUT_LOSS%TYPE,
    M_TAKE_PROFIT       DN_REF_PORTF_SECURITY_RATES.TAKE_PROFIT%TYPE,
    M_USER              DN_REF_FLOAT_BASE.DN_USER%TYPE,
    M_SCREAN_NAME       VARCHAR2,
    M_COUNT             NUMBER
   )
   IS
    -- Procedue     : Trigger
    -- Created by   : SVA
    -- Created on   : 22-02-2005

   --M_INT_DATE       DN_REF_SECURITY_INT_PAY_DATES.INT_PAY_DATE%TYPE;
   --M_MATURITY_DATE  DN_REF_SECURITY.MATURITY_DATE%TYPE;
   M_COUNT1            NUMBER;

BEGIN

 IF M_COUNT = 1 THEN
  INSERT INTO DN_REF_PORTF_SEC_RATES_BACKUP
  SELECT * FROM DN_REF_PORTF_SECURITY_RATES
  WHERE  PORTFOLIO_CODE    = M_PORTFOLI_CODE ;

  DELETE DN_REF_PORTF_SECURITY_RATES
  WHERE  PORTFOLIO_CODE    = M_PORTFOLI_CODE ;
 END IF;

    SELECT COUNT(*)
    INTO   M_COUNT1
    FROM   DN_REF_PORTF_SECURITY_RATES
    WHERE  SECURITY_CODE = M_SECURITY_CODE AND
           PORTFOLIO_CODE = M_PORTFOLI_CODE;

  IF (M_CUT_LOSS<>0 AND M_TAKE_PROFIT<>0) THEN
   IF(M_CUT_LOSS IS NOT NULL AND M_TAKE_PROFIT IS NOT NULL) THEN
    IF M_COUNT1=0 THEN
      INSERT INTO DN_REF_PORTF_SECURITY_RATES
      (PORTFOLIO_CODE,SECURITY_CODE,CUT_LOSS,TAKE_PROFIT,CL_STATUS,TK_STATUS,USER_NAME,ENT_DATE)
      VALUES
      (M_PORTFOLI_CODE,M_SECURITY_CODE,M_CUT_LOSS,M_TAKE_PROFIT,'N','N',M_USER,SYSDATE);

    ELSE
      UPDATE DN_REF_PORTF_SECURITY_RATES
      SET    CUT_LOSS    = M_CUT_LOSS,
             TAKE_PROFIT = M_TAKE_PROFIT,
             USER_NAME   = M_USER,
             ENT_DATE    = SYSDATE
      WHERE  SECURITY_CODE = M_SECURITY_CODE AND
             PORTFOLIO_CODE = M_PORTFOLI_CODE;
    END IF;
      DN_TRIGGER_ACTIVATION_UPDATE(M_PORTFOLI_CODE,M_SECURITY_CODE);
   END IF;--NOT NULL
  END IF; --NOT 0
      COMMIT;
/*
EXCEPTION
  WHEN OTHERS THEN

RAISE_APPLICATION_ERROR(-20001,'M_COUNT-'||M_COUNT||'M_SECURITY_CODE-'||M_SECURITY_CODE||'M_PORTFOLI_CODE-'||M_PORTFOLI_CODE||'- M_TAKE_PROFIT-'||M_TAKE_PROFIT||' - M_CUT_LOSS--'||M_CUT_LOSS||SQLERRM);
*/
END DN_PORT_SEC_TRIGGERS;

