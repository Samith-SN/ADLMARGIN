  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ISSUER_TO_PORTFOLIO" 
(
    M_ISSUER_CODE                 DN_REF_PRIMARY_ISSUER.ISSUER_CODE%TYPE,
    M_ISSUER_NAME                 DN_REF_PRIMARY_ISSUER.ISSUER_NAME%TYPE,
    M_POSTAL_CODE                 DN_REF_PRIMARY_ISSUER.POSTAL_CODE%TYPE,
    M_MBFSL_SECT_CODE             DN_REF_PRIMARY_ISSUER.MBFSL_SECT_CODE%TYPE
)
AS

M_COUNT NUMBER;

    /* PROCEDURE  -  ADD DEACTIVATED PORTFOLIO WHEN CREATING NEW ISSUER
       SYSTEM     -  DEALNET
       CREATED BY -  MANJULA -- (from hnbam)
       CREATED ON -  2005-07-20
   */

BEGIN

SELECT COUNT(*) INTO M_COUNT
FROM  DN_REF_PORTFOLIO
WHERE PORTFOLIO_CODE=M_ISSUER_CODE;

IF M_COUNT=1 THEN
    RAISE_APPLICATION_ERROR(-20201,'ISSUER CODE ' || M_ISSUER_CODE || ' ALREADY EXSIST IN PORTFOLIO TABLE AS A DEACTIVATED COUNTER PARTY');

ELSE

  INSERT INTO DN_REF_PORTFOLIO
  ( PORTFOLIO_CODE,
    PF_TYPE,
    PF_NAME,
    CREATED_DATE,
    LAST_MODIFIED,
    NEST_REVIEW,
    TOT_EXP_LIMIT,
    PERC_TOT_EXP,
    ACTIVE_STATUS,
    MBFSL_SECT_CODE,
    BUSI_REG_NIC,
    CATEGORY_ENTITY,
    NATURE_OCCUPATION,
    POSTAL_CODE,
    ACC_NO)
    VALUES(
        M_ISSUER_CODE,
        'C',
        M_ISSUER_NAME,
        SYSDATE,
        SYSDATE,
        SYSDATE,
        0,0,'N',
        M_MBFSL_SECT_CODE,
        1,'A','A',M_POSTAL_CODE,'N/A'
        );

END IF;

END ;


