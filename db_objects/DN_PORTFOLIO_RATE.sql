set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_PORTFOLIO_RATE" 
    (   M_PORTFOLIO_CODE            DN_REF_PORTFOLIO_RATES.PORTFOLIO_CODE%TYPE,
        M_EFF_VALDATE               VARCHAR2,
        M_RATE                      DN_REF_PORTFOLIO_RATES.BASE_INTEREST_RATE%TYPE,
        M_USER_NAME                 DN_REF_PORTFOLIO_RATES.USERNAME%TYPE,
        M_OPTION                    VARCHAR2,
        M_SCREEN_NAME               VARCHAR2
   )
AS

M_COUNT      NUMBER;
BEGIN

DN_VALIDATE_SAVE_RIGHTS(M_USER_NAME,'WD_Portfolio_Rates');  --added by ashini on 31/10/2005 for sr0509-047



IF M_OPTION='DEL' THEN

   DELETE DN_REF_PORTFOLIO_RATES
   WHERE PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
         TO_DATE(TO_CHAR(EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')=TO_DATE(M_EFF_VALDATE,'DD/MM/YYYY');


ELSE
   UPDATE DN_REF_PORTFOLIO_RATES
   SET    BASE_INTEREST_RATE = M_RATE/100,
          USERNAME           = M_USER_NAME,
          ENTDATE            = SYSDATE
   WHERE PORTFOLIO_CODE = M_PORTFOLIO_CODE AND
         TO_DATE(TO_CHAR(EFF_VALDATE,'DD/MM/YYYY'),'DD/MM/YYYY')=TO_DATE(M_EFF_VALDATE,'DD/MM/YYYY');

   IF SQL%NOTFOUND THEN
      INSERT INTO DN_REF_PORTFOLIO_RATES
     (PORTFOLIO_CODE,EFF_VALDATE,BASE_INTEREST_RATE,ACTIVE_STATUS,USERNAME,ENTDATE)
     VALUES
     (M_PORTFOLIO_CODE,TO_DATE(M_EFF_VALDATE,'DD/MM/YYYY'),M_RATE/100,'Y',M_USER_NAME,SYSDATE);
   END IF;
/*RAISE_APPLICATION_ERROR(-20201,M_PORTFOLIO_CODE ||' '||M_OWNED_BY_MBFSL||' '||M_CP_PORTFOLIO_CODE||' '||M_PF_NAME||' '||M_ADD_IDENTIFICATION||' '||M_ADD_LOCATION||' '||M_ADD_STREET||' '||M_ADD_CITY||' '||M_ADD_COUNTRY||' ' ||M_POSTAL_CODE||' '||TO_DATE(M_DATE_INC_BIRTH,'DD/MM/YYYY')||' '||M_BUSI_REG_NIC||' '||M_CATEGORY_ENTITY||' '||M_NATURE_OCCUPATION ||' '||M_SECT_CODE ||' '||M_MBFSL_SECT_CODE||' '||TO_DATE(M_NEST_REVIEW,'DD/MM/YYYY')||' '||0||' '||0);*/
END IF;

COMMIT;

END ;

