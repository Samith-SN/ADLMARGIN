set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_A_2_2_CURR" 
(
M_PORTF_CODE      DN_ACC_LICENCEE_GEN_ACCOUNT.PORTFOLIO_CODE%TYPE,
M_DN_PORTF_CODE   DN_ACC_LICENCEE_GEN_ACCOUNT.DN_PORTFOLIO_CODE%TYPE,
M_TRNDATE         DN_ACC_LICENCEE_GEN_ACCOUNT.TRNDATE%TYPE,
M_TRNAMOUNT       DN_ACC_LICENCEE_GEN_ACCOUNT.TRNAMOUNT%TYPE,
M_DOCREFNO        DN_ACC_LICENCEE_GEN_ACCOUNT.DOCREFNO%TYPE,
M_ACC_SYS_REFNO   DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE,
M_DEALNO          DN_TRN_BO_SETTL_PAYMENT.SUS_REF_NO%TYPE

)
AS

/* PROCEDURE  - A_2_2 PAYMENTS (SETTLEMENT) FOR CURRENCY
   SYSTEM     - DEALNET
   CREATED BY - NIRMALA FERNANDO
   CREATED ON - 03-01-2002 */

M_COUNT1                              NUMBER;
M_PAY_FROM_INT_BAL_AMT_CURR           DN_ACC_SUS_PAYMENT.PAY_FROM_INT_BAL_AMT_CURR%TYPE;
M_CURR_CODE                           DN_TRN_DEAL_CURRENCY.CURR_CODE%TYPE;
M_PAY_FROM_INT_BAL_AMT                DN_ACC_SUS_PAYMENT.PAY_FROM_INT_BAL_AMT_CURR%TYPE;
M_FIRST                               DN_ACC_SUS_PAYMENT.PAY_FROM_INT_BAL_AMT_CURR%TYPE;
M_CURRENCY_VALUE                      DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE;

BEGIN

  SELECT PAY_FROM_INT_BAL_AMT_CURR
  INTO   M_PAY_FROM_INT_BAL_AMT_CURR
  FROM   DN_ACC_SUS_PAYMENT
  WHERE  SUS_REF_NO=M_DEALNO AND
         PAY_FROM_INT_BAL_AMT_CURR > 0 AND
         PAYER = M_PORTF_CODE AND
         RECEIVER = M_DN_PORTF_CODE;

   SELECT CURR_CODE
   INTO   M_CURR_CODE
   FROM   DN_TRN_DEAL_CURRENCY
   WHERE  DEAL_NO=M_DEALNO;


  SELECT  CURRENCY_VALUE
  INTO    M_CURRENCY_VALUE
  FROM    DN_REF_EXCHANGE_RATES
  WHERE   CURR_CODE=M_CURR_CODE;

  SELECT PAY_FROM_INT_BAL_AMT
  INTO   M_PAY_FROM_INT_BAL_AMT
  FROM   DN_ACC_SUS_PAYMENT
  WHERE  SUS_REF_NO=M_DEALNO AND
         PAYER = M_PORTF_CODE AND
         RECEIVER = M_DN_PORTF_CODE;

 M_FIRST :=(M_PAY_FROM_INT_BAL_AMT_CURR*M_CURRENCY_VALUE);

 IF ((M_PAY_FROM_INT_BAL_AMT_CURR*M_CURRENCY_VALUE)>M_PAY_FROM_INT_BAL_AMT)THEN

  INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
    (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'404','DR',M_PAY_FROM_INT_BAL_AMT,M_DOCREFNO,'PAYMENTS (SETTLEMENT)','800');
  INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
    (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,ACC_SYS_REFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'800','CR',M_FIRST,M_DOCREFNO,M_ACC_SYS_REFNO,'PAYMENTS (SETTLEMENT)','404');
  INSERT INTO DN_ACC_COUNTP_GEN_ACCOUNT
    (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'116','DR',(M_FIRST-M_PAY_FROM_INT_BAL_AMT),M_DOCREFNO,'EXCHANGE-LOSS','800');

ELSIF ((M_PAY_FROM_INT_BAL_AMT_CURR*M_CURRENCY_VALUE)<M_PAY_FROM_INT_BAL_AMT)THEN

  INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
    (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'404','DR',M_PAY_FROM_INT_BAL_AMT,M_DOCREFNO,'PAYMENTS (SETTLEMENT)','800');
  INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
    (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,ACC_SYS_REFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'800','CR',M_FIRST,M_DOCREFNO,M_ACC_SYS_REFNO,'PAYMENTS (SETTLEMENT)','404');
  INSERT INTO DN_ACC_COUNTP_GEN_ACCOUNT
    (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,proc_desc,corr_acc_no)
    VALUES(M_PORTF_CODE,M_DN_PORTF_CODE,M_TRNDATE,'115','CR',(M_PAY_FROM_INT_BAL_AMT-(M_PAY_FROM_INT_BAL_AMT_CURR*M_CURRENCY_VALUE)),M_DOCREFNO,'EXCHANGE-GAIN','800');

END IF;
END DN_ACC_A_2_2_CURR;

