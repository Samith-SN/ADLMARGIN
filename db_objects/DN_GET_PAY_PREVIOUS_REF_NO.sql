  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_PAY_PREVIOUS_REF_NO" 
 ( 
   M_PAYMENT_NO        DN_TRN_BO_SETTL_PAYMENT.PAYMENT_NO%TYPE
   )

-- FUNCTION     : THIS RETURNS TOTAL  PAYMENTS
-- SYSTEM       : DEALNET SYSTEM
-- CREATED BY   :
-- CREATED ON   :K.M.W.S.JAYANATH
RETURN  VARCHAR

IS
TOTAL NUMBER:=0;
M_PAY_COUNT_1 NUMBER:=0; 
M_PORTFOLIO_CODE      DN_TRN_BO_SETTL_PAYMENT_BULK.PORTFOLIO_CODE%TYPE;
M_EFF_VALDATE         DN_TRN_BO_SETTL_PAYMENT.EFF_VALDATE%TYPE;  
MM_PAYMENT_NO         DN_TRN_BO_SETTL_PAYMENT.PAYMENT_NO%TYPE;
M_REF_NO              VARCHAR(15);
M_BROKER              DN_TRN_BO_SETTL_PAYMENT.ID_PORTFOLIO_CODE%TYPE; 
M_ENTDATE             DN_TRN_BO_SETTL_PAYMENT.ENTDATE%TYPE;          
BEGIN


        SELECT COUNT(B.PAYMENT_NO) INTO M_PAY_COUNT_1 
        FROM DN_TRN_BO_SETTL_PAYMENT_BULK A , DN_TRN_BO_SETTL_PAYMENT B
        WHERE A.PAYMENT_NO=M_PAYMENT_NO
        AND A.PAYMENT_NO=B.PAYMENT_NO 
        AND B.PAY_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') ;
       
        IF M_PAY_COUNT_1 >0 THEN
        
        SELECT A.PORTFOLIO_CODE,B.EFF_VALDATE,B.ID_PORTFOLIO_CODE,B.ENTDATE INTO M_PORTFOLIO_CODE ,M_EFF_VALDATE,M_BROKER,M_ENTDATE
        FROM DN_TRN_BO_SETTL_PAYMENT_BULK A , DN_TRN_BO_SETTL_PAYMENT B
        WHERE A.PAYMENT_NO=M_PAYMENT_NO
        AND A.PAYMENT_NO=B.PAYMENT_NO 
        AND B.PAY_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') ;
        
        
        
        SELECT  B.PAYMENT_NO  INTO MM_PAYMENT_NO   
        FROM DN_TRN_BO_SETTL_PAYMENT_BULK A , DN_TRN_BO_SETTL_PAYMENT B
        WHERE 
        A.PAYMENT_NO=B.PAYMENT_NO
        AND A.PORTFOLIO_CODE = M_PORTFOLIO_CODE 
        AND B.EFF_VALDATE    = M_EFF_VALDATE
        AND B.ID_PORTFOLIO_CODE = M_BROKER
        AND B.PAY_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT')
        AND ENTDATE<M_ENTDATE
        AND ENTDATE IN (
                    SELECT  MAX(ENTDATE)   
                    FROM DN_TRN_BO_SETTL_PAYMENT_BULK A , DN_TRN_BO_SETTL_PAYMENT B
                    WHERE 
                    A.PAYMENT_NO=B.PAYMENT_NO
                    AND A.PORTFOLIO_CODE = M_PORTFOLIO_CODE 
                    AND B.EFF_VALDATE    = M_EFF_VALDATE
                    AND B.ID_PORTFOLIO_CODE = M_BROKER
                    AND B.PAY_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') 
        )
        ;
       
        M_REF_NO:= MM_PAYMENT_NO;                       
        END IF;
        
        

  
        SELECT COUNT(A.GROUP_NET_NO) INTO M_PAY_COUNT_1 
        FROM DN_MAS_SETLE_GROUP_NET a
        WHERE A.GROUP_NET_NO=M_PAYMENT_NO
        AND A.APP_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') ;
       
        IF M_PAY_COUNT_1 >0 THEN
        
             
        SELECT FACILITY_NO,TRNDATE,BROKE_CODE,ENTDATE  INTO M_PORTFOLIO_CODE ,M_EFF_VALDATE,M_BROKER,M_ENTDATE 
        FROM DN_MAS_SETLE_GROUP_NET a
        WHERE A.GROUP_NET_NO=M_PAYMENT_NO
        AND A.APP_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') ;
        
        SELECT  A.GROUP_NET_NO  INTO MM_PAYMENT_NO   
         FROM DN_MAS_SETLE_GROUP_NET a
        WHERE A.FACILITY_NO = M_PORTFOLIO_CODE
        AND   BROKE_CODE    = M_BROKER
        AND   TRNDATE       = M_EFF_VALDATE
        AND A.APP_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') 
        AND ENTDATE<M_ENTDATE
        AND ENTDATE IN (
                  SELECT max(ENTDATE)  
        FROM DN_MAS_SETLE_GROUP_NET a
        WHERE A.FACILITY_NO = M_PORTFOLIO_CODE
        AND   BROKE_CODE    = M_BROKER
        AND   TRNDATE       = M_EFF_VALDATE
        AND A.APP_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') 
       
        )
        ;
       
        M_REF_NO:= MM_PAYMENT_NO;                       
        END IF;

        /*SELECT SUM(A.AMOUNT) INTO TOTAL 
        FROM DN_TRN_BO_SETTL_PAYMENT_BULK A , DN_TRN_BO_SETTL_PAYMENT B
        WHERE A.PORTFOLIO_CODE=M_PORTFOLIO_CODE
        AND A.PAYMENT_NO=B.PAYMENT_NO 
        AND B.PAY_STATUS IN('CONF','APPR1','SIG1','SIG2','PRINT') 
       --  AND  A.TRNDATE<=TO_DATE(M_END_DATE,'DD/MM/YYYY')  
       -- AND  A.TRNDATE>=TO_DATE(M_START_DATE,'DD/MM/YYYY')
        ; */


RETURN M_REF_NO;

END ;

