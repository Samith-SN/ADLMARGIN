--  DDL for Procedure DN_SAVE_ALLO_SCRIPLESS_CALL
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_SAVE_ALLO_SCRIPLESS_CALL" 
(
M_DEAL_NO            DN_TRN_BO_INV_PARTALLO.DEAL_NO%TYPE,
M_SECURITY_CODE      DN_TRN_BO_INV_PARTALLO.SECURITY_CODE%TYPE,
MM_ORG_SERNO1        DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE,--YIELD
MM_PA_SERNO          DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE,--YIELD
M_PA_INVAMT1         DN_TRN_BO_INV_PARTALLO.FACE_VALUE%TYPE,
M_SELL_AMT           DN_TRN_BO_INV_PARTALLO.FACE_VALUE%TYPE,
M_CURRENCY_VALUE     DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE,
M_DN_USER            DN_TRN_BO_INV_PARTALLO.DN_USER%TYPE,
M_TOT_AMT            DN_TRN_BO_INV_PARTALLO.FACE_VALUE%TYPE,
M_CURR_CODE          DN_TRN_OUTP_SALE.CURR_CODE%TYPE,
STATUS               VARCHAR2
)
AS
M_SERIAL_NO          DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;
M_ORG_SERNO          DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_YIELD%TYPE;--YIELD
M_PA_INVAMT          DN_TRN_BO_INV_PARTALLO.FACE_VALUE%TYPE;
M_PA_SERNO           DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_YIELD%TYPE;--YIELD

M_SELL_PF_CODE       DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE;
M_YIELD_TYPE         DN_REF_INSTRUMENT.YIELD_TYPE%TYPE;
M_EFF_VALDATE        DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE;
M_INST_TYPE          DN_TRN_OUTP_SALE.INST_TYPE%TYPE;
M_COUNT              NUMBER;
M_FACE_VALUE         DN_TRN_OUTP_SALE.FACE_VALUE%TYPE;
MM_ORG_SERNO         DN_INV_OUTPS_DEAL_SERIAL_NO.SERIAL_NO%TYPE;--YIELD
M_TOT_VALUE          DN_TRN_OUTP_SALE.FACE_VALUE%TYPE:=0;
M_SUM_FACE_VALUE     DN_TRN_OUTP_SALE.FACE_VALUE%TYPE;
M_INVENTORY_TYPE     DN_TRN_OUTP_SALE.INVENTORY_TYPE%TYPE;
M_BUY_PORTFOLIO_CODE DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE;
M_INST_CAT           DN_REF_INSTRUMENT.INST_CAT%TYPE;

BEGIN
--RAISE_APPLICATION_ERROR(-20001,STATUS);
--dbms_output.put_line(' DN_SAVE_ALLO_SCRIPLESS_CALL-->call');
IF SUBSTR(M_DEAL_NO,1,2)='OR' THEN
  --GET OR DETAILS

  SELECT DN_GET_INSTRUMENT_YIELD_TYPE(INST_TYPE),SELL_PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,
         FACE_VALUE,INVENTORY_TYPE,BUY_PORTFOLIO_CODE,DN_GET_INSTRUMENT_CAT(INST_TYPE)
  INTO   M_YIELD_TYPE,M_SELL_PF_CODE,M_EFF_VALDATE,M_INST_TYPE,
  M_FACE_VALUE,M_INVENTORY_TYPE,M_BUY_PORTFOLIO_CODE,M_INST_CAT
  FROM   DN_TRN_OUTP_SALE
  WHERE  DEAL_NO=M_DEAL_NO;
  --RAISE_APPLICATION_ERROR(-20001,M_SECURITY_CODE||'-'||M_SELL_PF_CODE||'-'||M_EFF_VALDATE||'-'||M_INST_TYPE||'-'||M_FACE_VALUE);

  SELECT COUNT(*)
  INTO   M_COUNT
  FROM   DN_TRN_OUTP_SALE_SEC
  WHERE  DEAL_NO =M_DEAL_NO;

  IF M_COUNT>0 THEN
    SELECT SUM(FACE_VALUE)
    INTO   M_TOT_VALUE
    FROM   DN_TRN_OUTP_SALE_SEC
    WHERE  DEAL_NO =M_DEAL_NO;
  END IF;
--RAISE_APPLICATION_ERROR(-20001,'M_YIELD_TYPE='||M_YIELD_TYPE);

  IF M_YIELD_TYPE = 'W' THEN
 --dbms_output.put_line('Value of M_EFF_VALDATE='||M_EFF_VALDATE);
   SELECT COUNT(*)
   INTO   M_COUNT
   FROM   DN_SYS_PARAMETER
   WHERE  LAST_DAILY+1>=M_EFF_VALDATE;
--dbms_output.put_line('V11111alue of M_COUNT='||M_COUNT);
--RAISE_APPLICATION_ERROR(-20001,'V11111alue of M_COUNT='||M_COUNT||M_BUY_PORTFOLIO_CODE||'=M_COUNT DATE='||M_SECURITY_CODE||' - M_EFF_VALDATE'||M_EFF_VALDATE||'=M_INVENTORY_TYPE='||M_INVENTORY_TYPE);

   IF M_COUNT > 0 THEN

    SELECT SUM(SCRIP_FACE_VAL)
    INTO   M_SUM_FACE_VALUE
    FROM   DN_INV_OUTPS_DEAL_SERIAL_NO X   --ADD X BY WARUNA 2011-09-08
	WHERE  FACE_VAL>0 AND PORTFOLIO_CODE=M_SELL_PF_CODE  AND
		     INST_TYPE=M_INST_TYPE  AND SECURITY_CODE=M_SECURITY_CODE AND
		     SERIAL_NO_STATUS='INV' AND
		     SCRIP_STATUS='SL'   AND LOCATION =M_SELL_PF_CODE  AND
             --TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=TO_DATE(TO_CHAR(M_EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') AND
		     --- COMMENTED ABOVE AND ADDED THE BELOW CONDTIONS BY WARUNA ON 25-05-2011.
             EFF_VALDATE <= M_EFF_VALDATE 
            /* commented by WARUNA on 25-05-2010 for performance issue
            SERIAL_NO NOT IN (SELECT SERIAL_NO
		                       FROM   DN_TRN_OUTP_SALE_SEC A,DN_TRN_OUTP_SALE B
		                       WHERE  A.DEAL_NO=B.DEAL_NO AND B.APP_STATUS NOT IN ('CONF','CANCEL')
                               UNION
							   SELECT J.SERIAL_NO
                               FROM   DN_TRN_REPO_FRESH_SERIAL_NO J,
                                      DN_TRN_REPO_FRESH B
                               WHERE  J.DEAL_NO=B.DEAL_NO AND B.APP_STATUS NOT IN ('CONF','CANCEL')
	  						   UNION
                               SELECT J.SERIAL_NO
	                           FROM   DN_TRN_REPO_ROLLOVER_SERIAL_NO J,
	                                  DN_TRN_REPO_ROLLOVER B
                               WHERE  J.DEAL_NO=B.DEAL_NO AND
                                   	  B.APP_STATUS NOT IN ('CONF','CANCEL') ) 
                                         */
                                         AND
             ---- commented by WARUNA on 25-05-2011 forperformance issue                            
           --  RETURN_ALLO_STATUS(SERIAL_NO,SECURITY_CODE,' ',' ',TO_CHAR(M_EFF_VALDATE,'DD-MM-YYYY'),'OR') = 'Y'  AND
             --RETURN_ALLO_STATUS(SERIAL_NO,SECURITY_CODE,' ',' ',TO_CHAR(M_EFF_VALDATE,'DD-MM-YYYY'),'OR',M_SELL_PF_CODE)='Y' AND
             DN_GET_DEAL_INVENTORY_TYPE(DEAL_NO,M_INVENTORY_TYPE,M_BUY_PORTFOLIO_CODE)='YES'  --ADDED BY SVA ON 23-03-2005 FOR CUSTODIAN INVENTORY
             --ADDD BY WARUNA GET FROM FCLMGT
              AND    (SELECT COUNT(SERIAL_NO)
		                       FROM   DN_TRN_OUTP_SALE_SEC A,DN_TRN_OUTP_SALE B
		                       --WHERE  A.DEAL_NO=B.DEAL_NO AND B.APP_STATUS NOT IN ('CONF','CANCEL')
                               --- COMMENTED ABOVE AND ADDED THE BELOW CONDTIONS BY MANULA ON 27-04-2010.
                               WHERE  A.DEAL_NO=B.DEAL_NO AND B.APP_STATUS IN ('ENT','VERI','APPRO1','APPRO2','PROC')
                                      AND A.SERIAL_NO=X.SERIAL_NO) =0
             ;
dbms_output.put_line('M_INVENTORY_TYPE -->'||M_INVENTORY_TYPE||'--'||M_INST_TYPE||'--'||M_SELL_PF_CODE||'--'||M_SECURITY_CODE||'--'||M_EFF_VALDATE||'--'||M_BUY_PORTFOLIO_CODE);

   IF M_SUM_FACE_VALUE>=M_FACE_VALUE THEN
     M_COUNT := 1;
   ELSE
     M_COUNT := 0;
   END IF;
dbms_output.put_line('DN_SAVE_ALLO_SCRIPLESS_CALL -->M_COUNT '||M_COUNT);
    --RAISE_APPLICATION_ERROR(-20001,'M_COUNT FAC='||M_COUNT);
   IF M_COUNT>0 THEN

   --RAISE_APPLICATION_ERROR(-20001,'M_SELL_AMT='||M_SELL_AMT||'-M_EFF_VALDATE-'||M_EFF_VALDATE||'-M_SECURITY_CODE-'||M_SECURITY_CODE||'-M_SELL_PF_CODE-'||M_SELL_PF_CODE);

     FOR X IN  (SELECT SECURITY_CODE SECURITY_CODE,YIELD_WITH_BROKERAGE, SUM(SCRIP_FACE_VAL) SCRIP_FACE_VAL, SCRIP_STATUS SCRIP_STATUS--,TO_CHAR(SUM(SCRIP_FACE_VAL),'FM999G999G999G999G999G999G999G999G999G999G999G990')
                FROM   DN_INV_OUTPS_DEAL_SERIAL_NO
            	WHERE  FACE_VAL>0 AND PORTFOLIO_CODE=M_SELL_PF_CODE  AND
		         INST_TYPE=M_INST_TYPE  AND SECURITY_CODE=M_SECURITY_CODE AND
    		     SERIAL_NO_STATUS='INV' AND
	       	     SCRIP_STATUS='SL'   AND LOCATION =M_SELL_PF_CODE  AND
                 TO_DATE(TO_CHAR(EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY')<=TO_DATE(TO_CHAR(M_EFF_VALDATE,'DD-MM-YYYY'),'DD-MM-YYYY') AND
		         SERIAL_NO NOT IN (SELECT SERIAL_NO
		                       FROM   DN_TRN_OUTP_SALE_SEC A,DN_TRN_OUTP_SALE B
		                       WHERE  A.DEAL_NO=B.DEAL_NO AND B.APP_STATUS NOT IN ('CONF','CANCEL')
                               UNION
							   SELECT J.SERIAL_NO
                               FROM   DN_TRN_REPO_FRESH_SERIAL_NO J,
                                      DN_TRN_REPO_FRESH B
                               WHERE  J.DEAL_NO=B.DEAL_NO AND B.APP_STATUS NOT IN ('CONF','CANCEL')
	  						   UNION
                               SELECT J.SERIAL_NO
	                           FROM   DN_TRN_REPO_ROLLOVER_SERIAL_NO J,
	                                  DN_TRN_REPO_ROLLOVER B
                               WHERE  J.DEAL_NO=B.DEAL_NO AND
                                   	  B.APP_STATUS NOT IN ('CONF','CANCEL') ) AND
                 RETURN_ALLO_STATUS(SERIAL_NO,SECURITY_CODE,' ',' ',TO_CHAR(M_EFF_VALDATE,'DD-MM-YYYY'),'OR') = 'Y'  AND
                 --RETURN_ALLO_STATUS(SERIAL_NO,SECURITY_CODE,' ',' ',TO_CHAR(M_EFF_VALDATE,'DD-MM-YYYY'),'OR',M_SELL_PF_CODE)='Y' AND
                 DN_GET_DEAL_INVENTORY_TYPE(DEAL_NO,M_INVENTORY_TYPE,M_BUY_PORTFOLIO_CODE)='YES'  --ADDED BY SVA ON 23-03-2005 FOR CUSTODIAN INVENTORY
                 GROUP BY SECURITY_CODE,YIELD_WITH_BROKERAGE,SCRIP_STATUS ) LOOP

     IF (M_FACE_VALUE-M_TOT_VALUE) >0 THEN

       MM_ORG_SERNO := X.YIELD_WITH_BROKERAGE;
       --dbms_output.put_line('Value of MM_ORG_SERNO='||MM_ORG_SERNO);
       IF X.SCRIP_FACE_VAL>(M_FACE_VALUE-M_TOT_VALUE) THEN

          M_PA_INVAMT :=X.SCRIP_FACE_VAL-(M_FACE_VALUE-M_TOT_VALUE);
          --RAISE_APPLICATION_ERROR(-20001,'DN_SAVE_ALLO_SCRIPLESS('||M_DEAL_NO||','||M_SECURITY_CODE||','||MM_ORG_SERNO||','||MM_ORG_SERNO||','||M_PA_INVAMT||','||M_FACE_VALUE||','||M_CURRENCY_VALUE||','||M_DN_USER||','||M_TOT_AMT||','||M_CURR_CODE||','||STATUS||');');
          DN_SAVE_ALLO_SCRIPLESS(M_DEAL_NO,M_SECURITY_CODE,MM_ORG_SERNO,MM_ORG_SERNO,M_PA_INVAMT,(M_FACE_VALUE-M_TOT_VALUE),(M_FACE_VALUE-M_TOT_VALUE),M_DN_USER,M_TOT_AMT,M_CURR_CODE,STATUS);
          EXIT;

       ELSIF X.SCRIP_FACE_VAL<(M_FACE_VALUE-M_TOT_VALUE) THEN

          M_PA_INVAMT :=0;
          --RAISE_APPLICATION_ERROR(-20001,'DN_SAVE_ALLO_SCRIPLESS('||M_DEAL_NO||','||M_SECURITY_CODE||','||MM_ORG_SERNO||','||M_PA_SERNO||','||M_PA_INVAMT||','||X.SCRIP_FACE_VAL||','||M_CURRENCY_VALUE||','||M_DN_USER||','||M_TOT_AMT||','||M_CURR_CODE||','||STATUS||');');
          DN_SAVE_ALLO_SCRIPLESS(M_DEAL_NO,M_SECURITY_CODE,MM_ORG_SERNO,M_PA_SERNO,M_PA_INVAMT,X.SCRIP_FACE_VAL,X.SCRIP_FACE_VAL,M_DN_USER,M_TOT_AMT,M_CURR_CODE,STATUS);
          M_TOT_VALUE := M_TOT_VALUE+X.SCRIP_FACE_VAL;

        ELSIF X.SCRIP_FACE_VAL=(M_FACE_VALUE-M_TOT_VALUE) THEN

         M_PA_INVAMT :=0;
         --RAISE_APPLICATION_ERROR(-20001,'DN_SAVE_ALLO_SCRIPLESS('||M_DEAL_NO||','||M_SECURITY_CODE||','||MM_ORG_SERNO||','||M_PA_SERNO||','||M_PA_INVAMT||','||M_FACE_VALUE||','||M_CURRENCY_VALUE||','||M_DN_USER||','||M_TOT_AMT||','||M_CURR_CODE||','||STATUS||');');
         DN_SAVE_ALLO_SCRIPLESS(M_DEAL_NO,M_SECURITY_CODE,MM_ORG_SERNO,M_PA_SERNO,M_PA_INVAMT,(M_FACE_VALUE-M_TOT_VALUE),(M_FACE_VALUE-M_TOT_VALUE),M_DN_USER,M_TOT_AMT,M_CURR_CODE,STATUS);
         EXIT;

        END IF;

       ELSE

        EXIT;

       END IF;
     END LOOP;
  END IF;
 END IF;
END IF;
END IF;
--RAISE_APPLICATION_ERROR(-20201,'**'||M_ORG_SERNO||M_PA_SERNO);

END DN_SAVE_ALLO_SCRIPLESS_CALL;

