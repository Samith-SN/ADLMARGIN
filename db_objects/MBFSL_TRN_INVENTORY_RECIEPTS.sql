set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."MBFSL_TRN_INVENTORY_RECIEPTS" 
   (M_REC_NO    IN OUT DN_TRN_BO_SETTL_RECEIPT.REC_NO%TYPE,
    --M_PORT_CODE        DN_TRN_BO_SETTL_RECEIPT.PORTFOLIO_CODE%TYPE,
    --M_DEAL_TYPE        DN_TRN_BO_SETTL_RECEIPT.SUSPENSE_ENTRY_TYPE%TYPE,
    M_DEALNO           DN_TRN_BO_SETTL_RECEIPT.SUS_REF_NO%TYPE,
    M_ID_PORTCODE      DN_TRN_BO_SETTL_RECEIPT.ID_PORTFOLIO_CODE%TYPE,
    M_SETTLEMENT       DN_TRN_BO_SETTL_RECEIPT.SETTLE_MODE%TYPE,
    MM_AMT              DN_TRN_BO_SETTL_RECEIPT.REC_AMOUNT%TYPE,--CURRENCY
    M_P_BRANCH_CODE    DN_TRN_BO_SETTL_RECEIPT.PAYER_BRANCH_CODE%TYPE,

    M_PAYER_ACC_NO     DN_TRN_BO_SETTL_RECEIPT.PAYER_ACC_NO%TYPE,
    M_PAYER_REF        DN_TRN_BO_SETTL_RECEIPT.PAYER_REF%TYPE,
    --M_COMMENTS         DN_TRN_BO_SETTL_RECEIPT.OTH_COMMENTS%TYPE,
    M_BRANCH_CODE      DN_TRN_BO_SETTL_RECEIPT.BRANCH_CODE%TYPE,
    M_ACC_NO           DN_TRN_BO_SETTL_RECEIPT.ACC_NO%TYPE,
    --M_STATUS           DN_TRN_BO_SETTL_RECEIPT.STATUS%TYPE,
    M_USER             DN_TRN_BO_SETTL_RECEIPT.DN_USER%TYPE,
    M_EFF_VALDATE      VARCHAR2,
    M_DUMMY_NO         DN_TRN_BO_SETTL_RECEIPT.REC_NO%TYPE

   )
AS


M_ACC_SYS_REFNO   DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE;
M_CACC_SEQNO      DN_ACC_SUS_RECEIPT.SUS_REF_NO%TYPE;

NN_BAL_TO_BE_RECEIVED_CURR    DN_ACC_SUS_RECEIPT.BAL_TO_BE_RECEIVED_CURR%TYPE;--CURRENCY
NN_BAL_TO_BE_RECEIVED   DN_ACC_SUS_RECEIPT.BAL_TO_BE_RECEIVED%TYPE;--CURRENCY
NN_COUNT_ALL       NUMBER;--CURRENCY
M_COUNT_ALL     NUMBER;--CURRENCY
M_AMT            DN_TRN_BO_SETTL_RECEIPT.REC_AMOUNT%TYPE;--CURRENCY
M_PORT_CODE        DN_TRN_BO_SETTL_RECEIPT.PORTFOLIO_CODE%TYPE:='GEN';
M_COMMENTS         DN_TRN_BO_SETTL_RECEIPT.OTH_COMMENTS%TYPE:='INTEREST SETTLEMENT';

BEGIN

DN_VALIDATE_SAVE_RIGHTS(M_USER,'WD_Interest_Receipt');  --added by ashini on 31/10/2005 for sr0509-047

--RAISE_APPLICATION_ERROR(-20201,'MM_AMT'||MM_AMT);--600
M_AMT:=MM_AMT;--CURRENCY

      --SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_SET_CURR_ACC.NEXTVAL),3,'0') INTO M_CACC_SEQNO FROM DUAL;
      M_CACC_SEQNO:=M_DEALNO;--'CA'||M_CACC_SEQNO;

     IF M_DUMMY_NO IS NULL THEN
         SELECT TO_CHAR(SYSDATE,'YY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_SET_REC.NEXTVAL),3,'0') INTO M_REC_NO FROM DUAL;
        M_REC_NO:='SRMT'||M_REC_NO;
     ELSE
       M_REC_NO:=M_DUMMY_NO;


     END IF;


   INSERT INTO DN_ACC_SUS_RECEIPT
         (SUS_REF_NO, SUSPENSE_ENTRY_TYPE, RECEIVER, PAYER, TOT_SETTLE_AMOUNT, INT_BAL_SETTLE_AMOUNT, REC_FROM_INT_BAL_AMT, BAL_TO_BE_RECEIVED, ENT_DATE,LAST_MOD_DATE)
   VALUES
       (M_CACC_SEQNO,'A',M_PORT_CODE,M_ID_PORTCODE,M_AMT,0,0,M_AMT,SYSDATE,SYSDATE);


   INSERT INTO DN_TRN_BO_SETTL_RECEIPT
    ( REC_NO, PORTFOLIO_CODE,SUS_REF_NO, SETTLE_MODE, SUSPENSE_ENTRY_TYPE,ID_PORTFOLIO_CODE,REC_AMOUNT,PAYER_BRANCH_CODE,PAYER_ACC_NO, PAYER_REF, OTH_COMMENTS, BRANCH_CODE, ACC_NO, STATUS, DN_USER, ENTDATE,EFF_VALDATE)

   VALUES
     (M_REC_NO,M_PORT_CODE,M_CACC_SEQNO,M_SETTLEMENT,'A',M_ID_PORTCODE,M_AMT, M_p_BRANCH_CODE,M_PAYER_ACC_NO,M_PAYER_REF,M_COMMENTS,M_BRANCH_CODE,M_ACC_NO,'CRD', M_USER,SYSDATE,TO_DATE(M_EFF_VALDATE,'DD-MM-YYYY'));

--RAISE_APPLICATION_ERROR(-20201,'M_CACC_SEQNO'||M_CACC_SEQNO);
   UPDATE DN_ACC_SUS_RECEIPT
   SET    REC_FROM_INT_BAL_AMT=REC_FROM_INT_BAL_AMT+M_AMT,
          BAL_TO_BE_RECEIVED  =BAL_TO_BE_RECEIVED-M_AMT,
          LAST_MOD_DATE       =SYSDATE
   WHERE  SUS_REF_NO=M_CACC_SEQNO AND SUSPENSE_ENTRY_TYPE='A';

    UPDATE DN_TRN_MARGIN_TRADING_INTEREST
    SET    AMOUNT_PAID        = NVL(AMOUNT_PAID,0)+M_AMT,
           BALANCE_TO_BE_PAID = BALANCE_TO_BE_PAID-M_AMT
    WHERE  DOCREFNO           = M_CACC_SEQNO;

    UPDATE DN_TRN_MARGIN_TRADING_INTEREST
    SET    STATUS             = 'PROCESSED'
    WHERE  DOCREFNO           = M_CACC_SEQNO AND
           BALANCE_TO_BE_PAID = 0;

   ------------------------------------------------------
   -- Added by Pubudu Thushara on 02/09/1999
  SELECT
     ACC_SYS_REFNO
     INTO M_ACC_SYS_REFNO
  FROM
     DN_REF_LICENCEE_SETTLEMENT
  WHERE
     BRANCH_CODE=M_BRANCH_CODE
     AND
     ACC_NO=M_ACC_NO;

      --DN_ACC_LINK_CURR_ACCOUNT_REC(M_DEAL_TYPE,M_PORT_CODE,M_ID_PORTCODE,TO_DATE(M_EFF_VALDATE,'DD-MM-YYYY'),M_AMT,M_REC_NO,M_ACC_SYS_REFNO);
      DN_ACC_B_2_3_1(M_PORT_CODE,M_ID_PORTCODE,TO_DATE(M_EFF_VALDATE,'DD-MM-YYYY'),M_AMT,M_REC_NO,M_ACC_SYS_REFNO);


    -- ADDED FOR TIME LOG MANAGEMENT BY YASODHA ON 10-09-2000--
          INSERT INTO DN_TIME_LOG_SETTLE
          (DOC_REF_NO,
            REL_DEAL_NO,
           DN_USER,
           ENT_DATE,
           DESCRIPTION)
           VALUES
            ( M_REC_NO,M_DEALNO,
            M_USER,
              SYSDATE,
              'SETTLEMENT RECEIPT'
           );
 --*****************************************************************

   --DBMS_OUTPUT.put_line('DOCNO  '||M_REC_NO||'  '||M_DEALNO );
   COMMIT;

 END MBFSL_TRN_INVENTORY_RECIEPTS;

