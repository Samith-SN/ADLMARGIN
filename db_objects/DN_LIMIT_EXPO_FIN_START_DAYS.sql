--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_LIMIT_EXPO_FIN_START_DAYS" 
(
 M_MAT_START_DAYS        LMT_STR_OVRL_EXPO.START_DAYS%TYPE
 )

 RETURN  INTEGER

IS

    -- FUNCTION     : THIS RETURNS START DAY;
    -- SYSTEM       : DEALNET SYSTEM
    -- CREATED BY   : SUKATHIS
    -- CREATED ON   : 24/01/2000

M_RETURN_DAYS       INTEGER;

BEGIN
SELECT DISTINCT MAX(START_DAYS) INTO M_RETURN_DAYS
    FROM LMT_STR_OVRL_EXPO
    WHERE START_DAYS <= M_MAT_START_DAYS;

RETURN M_RETURN_DAYS;

END DN_LIMIT_EXPO_FIN_START_DAYS;

