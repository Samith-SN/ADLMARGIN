  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_GET_CLOSING_BALANCE_BF" 
(
 M_DATE                  VARCHAR2,
 M_PORTFOLIO_CODE        DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE
 )
 RETURN NUMBER
 AS
 M_PF_TYPE          DN_REF_PORTFOLIO.PF_TYPE%TYPE;
 M_MAT_DATE_REPO    DATE;
 M_MAT_DATE_SETE    DATE;
 M_MAT_DATE_SETE1   DATE;
 M_AMOUNT           NUMBER;
 
 
M_OPEN_BALANCE            NUMBER;
M_INT_AMOUNT_LAST_MONTH  NUMBER;
M_LAST_MONTH_LAST_DAY    DATE;
M_COUNT                  NUMBER;
M_COUNT_DEAL             NUMBER;
M_EFF_VALDATE            DATE;
M_DEAL_NO                DN_TRN_REPO_FRESH.DEAL_NO%TYPE;
IS_FIRST_OF_MONTH        VARCHAR(25);

M_LEG1_VALUE            DN_TRN_REPO_FRESH.LEG1_VALUE%TYPE;
M_LEG2_VALUE            DN_TRN_REPO_FRESH.LEG2_VALUE%TYPE;
M_BORR_PORTFOLIO_CODE   DN_TRN_REPO_FRESH.BORR_PORTFOLIO_CODE%TYPE;
M_LEND_PORTFOLIO_CODE   DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE;
 BEGIN

SELECT SUM(AMOUNT) INTO M_AMOUNT  FROM (
SELECT DN_GET_OPENING_BALANCE_BF(M_DATE,M_PORTFOLIO_CODE)   AMOUNT   FROM DUAL
UNION ALL
SELECT DN_GET_CLIENT_PAYMENT(M_PORTFOLIO_CODE,M_DATE,M_DATE) AMOUNT FROM DUAL
UNION ALL
SELECT  DN_GET_CLIENT_RECEIPT(M_PORTFOLIO_CODE,M_DATE,M_DATE) AMOUNT FROM DUAL
UNION ALL
SELECT  DN_GET_CLIENT_DIVIDEND(M_PORTFOLIO_CODE,M_DATE,M_DATE) AMOUNT FROM DUAL
UNION ALL
SELECT DN_GET_CLIENT_DEPOSIT(M_PORTFOLIO_CODE,M_DATE,M_DATE) AMOUNT FROM DUAL
UNION ALL
SELECT DN_GET_CLIENT_WITHDRAWAL(M_PORTFOLIO_CODE,M_DATE,M_DATE) AMOUNT FROM DUAL
UNION ALL
SELECT DN_GET_MONTH_INTEREST(M_DATE,M_PORTFOLIO_CODE) AMOUNT FROM DUAL
UNION ALL
SELECT DN_GET_OD_ACCRUED_INTEREST(M_PORTFOLIO_CODE,TRUNC(TO_DATE(M_DATE,'DD/MM/YYYY'), 'MONTH'),TO_DATE(M_DATE,'DD/MM/YYYY')) AMOUNT FROM DUAL
);
   RETURN  M_AMOUNT;

 END ; 

