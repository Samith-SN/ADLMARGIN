--------------------------------------------------------
--  DDL for Procedure DN_EXCHG_GAINLOSS_OUTRIGHT
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_EXCHG_GAINLOSS_OUTRIGHT" 
(
    M_DEAL_NO                 DN_TRN_REPO_SETTLEMENT.DEAL_NO%TYPE,
    M_CURR_CODE               DN_TRN_REPO_SETTLEMENT.CURR_CODE%TYPE
)
AS

    CURSOR MY_CUR IS
      SELECT   FACE_VAL_CURR,FACE_VAL
      FROM     DN_INV_OUTPS_DEAL_SERIAL_NO
      WHERE    SALE_DEAL_NO=M_DEAL_NO ;





    M_BUY_PORTFOLIO_CODE      DN_TRN_OUTP_SALE.BUY_PORTFOLIO_CODE%TYPE;
    M_SELL_PORTFOLIO_CODE     DN_TRN_OUTP_SALE.SELL_PORTFOLIO_CODE%TYPE;
    M_BUY_PF_TYPE             DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_SELL_PF_TYPE            DN_REF_PORTFOLIO.PF_TYPE%TYPE;
    M_CURRENCY_VALUE          DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE;
    M_GAIN_LOSS               DN_TRN_DEAL_CURRENCY.LEG1_VALUE%TYPE;
    M_EFF_VALDATE             DN_TRN_OUTP_SALE.EFF_VALDATE%TYPE;
    M_SETTLE_VALUE            DN_TRN_OUTP_SALE.SETTLE_VALUE%TYPE;
    M_FACE_VAL_CURR           DN_INV_OUTPS_DEAL_SERIAL_NO.FACE_VAL_CURR%TYPE;
    M_FACE_VAL                DN_INV_OUTPS_DEAL_SERIAL_NO.FACE_VAL%TYPE;
    M_PREV_RATE               DN_REF_EXCHANGE_RATES.CURRENCY_VALUE%TYPE;



BEGIN

    ---   CREATED BY NIRMALA
    --    ON 19-12-2001
    --    FOR EXCHANGE LOSS/GAIN CALCULATION -OUTRIGHTS --CURRENCY


-----------------------------------------------------------------------------------------
   SELECT    A.SETTLE_VALUE,A.SELL_PORTFOLIO_CODE,A.BUY_PORTFOLIO_CODE,B.PF_TYPE,C.PF_TYPE,
             A.EFF_VALDATE
   INTO      M_SETTLE_VALUE,M_SELL_PORTFOLIO_CODE,M_BUY_PORTFOLIO_CODE,
             M_SELL_PF_TYPE,M_BUY_PF_TYPE,M_EFF_VALDATE

   FROM      DN_TRN_OUTP_SALE A,
             DN_REF_PORTFOLIO B,
             DN_REF_PORTFOLIO C

   WHERE     A.DEAL_NO=M_DEAL_NO  AND
             A.SELL_PORTFOLIO_CODE=B.PORTFOLIO_CODE   AND
             A.BUY_PORTFOLIO_CODE=C.PORTFOLIO_CODE;
------------------------------------------------------------------------------------------

 SELECT  CURRENCY_VALUE
 INTO    M_CURRENCY_VALUE
 FROM    DN_REF_EXCHANGE_RATES
 WHERE   CURR_CODE=M_CURR_CODE;
----------------------------------------------------------------------------------------------
IF (M_SELL_PF_TYPE='P') THEN

OPEN MY_CUR;
LOOP
FETCH MY_CUR INTO M_FACE_VAL_CURR,M_FACE_VAL;
EXIT WHEN MY_CUR%NOTFOUND;

 M_PREV_RATE:=(M_FACE_VAL/M_FACE_VAL_CURR);

  IF(((M_SETTLE_VALUE*M_CURRENCY_VALUE)-(M_SETTLE_VALUE*M_PREV_RATE))>0 )THEN --EXCHANGE GAIN
  --CR 115
  --DR 302

   M_GAIN_LOSS:=((M_SETTLE_VALUE*M_CURRENCY_VALUE)-(M_SETTLE_VALUE*M_PREV_RATE));

         UPDATE DN_ACC_LICENCEE_GEN_ACCOUNT
         SET    TRNAMOUNT=TRNAMOUNT+M_GAIN_LOSS
         WHERE  DOCREFNO=M_DEAL_NO AND
                DRCR_STATUS='DR' AND
                TRNDATE=M_EFF_VALDATE AND
                PORTFOLIO_CODE=M_SELL_PORTFOLIO_CODE AND
                DN_PORTFOLIO_CODE=M_BUY_PORTFOLIO_CODE AND
                PROC_DESC='EXCHANGE-GAIN' AND
                CORR_ACC_NO='115' AND
                ACC_TYPE_CODE='302';

         UPDATE DN_ACC_LICENCEE_GEN_ACCOUNT
         SET    TRNAMOUNT=TRNAMOUNT+M_GAIN_LOSS
         WHERE  DOCREFNO=M_DEAL_NO AND
                DRCR_STATUS='CR' AND
                TRNDATE=M_EFF_VALDATE AND
                PORTFOLIO_CODE=M_SELL_PORTFOLIO_CODE AND
                DN_PORTFOLIO_CODE=M_BUY_PORTFOLIO_CODE AND
                PROC_DESC='EXCHANGE-GAIN' AND
                CORR_ACC_NO='302' AND
                ACC_TYPE_CODE='115';

        IF SQL%NOTFOUND THEN
          INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_SELL_PORTFOLIO_CODE,M_BUY_PORTFOLIO_CODE,M_EFF_VALDATE,'302','DR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-GAIN','115');
          ------------

          INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_SELL_PORTFOLIO_CODE,M_BUY_PORTFOLIO_CODE,M_EFF_VALDATE,'115','CR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-GAIN','302');
        END IF;




  ELSIF (((M_SETTLE_VALUE*M_CURRENCY_VALUE)-(M_SETTLE_VALUE*M_PREV_RATE))<0 )THEN --EXCHANGE LOSS
  --DR 116
  --CR  302
   M_GAIN_LOSS:=ABS((M_SETTLE_VALUE*M_CURRENCY_VALUE)-(M_SETTLE_VALUE*M_PREV_RATE));

         UPDATE DN_ACC_LICENCEE_GEN_ACCOUNT
         SET    TRNAMOUNT=TRNAMOUNT+M_GAIN_LOSS
         WHERE  DOCREFNO=M_DEAL_NO AND
                DRCR_STATUS='CR' AND
                TRNDATE=M_EFF_VALDATE AND
                PORTFOLIO_CODE=M_SELL_PORTFOLIO_CODE AND
                DN_PORTFOLIO_CODE=M_BUY_PORTFOLIO_CODE AND
                PROC_DESC='EXCHANGE-LOSS' AND
                CORR_ACC_NO='116' AND
                ACC_TYPE_CODE='302';

         UPDATE DN_ACC_LICENCEE_GEN_ACCOUNT
         SET    TRNAMOUNT=TRNAMOUNT+M_GAIN_LOSS
         WHERE  DOCREFNO=M_DEAL_NO AND
                DRCR_STATUS='DR' AND
                TRNDATE=M_EFF_VALDATE AND
                PORTFOLIO_CODE=M_SELL_PORTFOLIO_CODE AND
                DN_PORTFOLIO_CODE=M_BUY_PORTFOLIO_CODE AND
                PROC_DESC='EXCHANGE-LOSS' AND
                CORR_ACC_NO='302' AND
                ACC_TYPE_CODE='116';

        IF SQL%NOTFOUND THEN
          INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_SELL_PORTFOLIO_CODE,M_BUY_PORTFOLIO_CODE,M_EFF_VALDATE,'116','DR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-LOSS','302');
          ------------

          INSERT INTO DN_ACC_LICENCEE_GEN_ACCOUNT
             (PORTFOLIO_CODE,DN_PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,PROC_DESC,CORR_ACC_NO)
          VALUES(M_SELL_PORTFOLIO_CODE,M_BUY_PORTFOLIO_CODE,M_EFF_VALDATE,'302','CR',M_GAIN_LOSS,M_DEAL_NO,'EXCHANGE-LOSS','116');
        END IF;


  END IF;

END LOOP;
CLOSE  MY_CUR;
END IF;
--COMMIT;
END DN_EXCHG_GAINLOSS_OUTRIGHT;

