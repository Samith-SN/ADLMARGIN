set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_MARKET_VALUES" 
   (M_LEVEL_STATUS              DN_TRN_MARKET_RATE.LEVEL_STATUS%TYPE,
    M_PORTFOLIO_CODE            DN_TRN_MARKET_RATE.PORTFOLIO_CODE%TYPE,
    M_INST_TYPE                 DN_TRN_MARKET_RATE.INST_TYPE%TYPE,
    M_SECURITY_CODE             DN_TRN_MARKET_RATE.SECURITY_CODE%TYPE,
    M_MATURITY_DATE             VARCHAR2,

    M_MATURITY_DAYS             DN_TRN_MARKET_RATE.MATURITY_DAYS%TYPE,
    M_FACE_VALUE                DN_TRN_MARKET_RATE.FACE_VALUE%TYPE,
    M_TOT_CARR_VAL              DN_TRN_MARKET_RATE.TOT_CARR_VAL%TYPE,
    M_PURCHASE_YIELD            DN_TRN_MARKET_RATE.PURCHASE_YIELD%TYPE,
    M_MARKET_RATE               DN_TRN_MARKET_RATE.MARKET_RATE%TYPE,
    M_ENTDATE                   VARCHAR2
  )
AS

   MM_MARKET_VALUE             DN_TRN_MARKET_RATE.MARKET_VALUE%TYPE;
   MM_GAINLOSS                 DN_TRN_MARKET_RATE.GAINLOSS%TYPE;
   M_MARKET_RATE2              DN_TRN_MARKET_RATE.MARKET_RATE%TYPE;
BEGIN
--RAISE_APPLICATION_ERROR(-20201,M_LEVEL_STATUS||'M_PORTFOLIO_CODEM_PORTFOLIO_CODE '||M_PORTFOLIO_CODE||' '||M_INST_TYPE||' '|| M_SECURITY_CODE||' '||M_MATURITY_DATE||' '||M_MATURITY_DAYS||' '||M_FACE_VALUE||' '||M_TOT_CARR_VAL||' '||M_PURCHASE_YIELD||' '||M_MARKET_RATE);

    /* PROCEDURE  -  MARKET VALUE REPORT
       SYSTEM     -  DEALNET
       CREATED BY -  NIRMALA
       CREATED ON -  28/05/2000 */
   ----------------------CALCULATION-------------------------------------------------
   M_MARKET_RATE2:=(M_MARKET_RATE/100);

   IF(M_MARKET_RATE2<>' ') THEN
   MM_MARKET_VALUE:=((M_FACE_VALUE/100)*(DN_FIN_PRICE_CLEAN_YIELD(M_SECURITY_CODE,M_MARKET_RATE2,M_ENTDATE,'AA')));
   END IF;

   INSERT INTO DN_TRN_MARKET_RATE
    ( PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,MATURITY_DATE,FACE_VALUE,PURCHASE_YIELD,
        MARKET_RATE,LEVEL_STATUS,TOT_CARR_VAL, MATURITY_DAYS,ENTDATE,MARKET_VALUE,GAINLOSS)

   VALUES
     (M_PORTFOLIO_CODE,M_INST_TYPE,M_SECURITY_CODE,TO_DATE(M_MATURITY_DATE,'DD/MM/YYYY'),M_FACE_VALUE,M_PURCHASE_YIELD,
        M_MARKET_RATE,M_LEVEL_STATUS,M_TOT_CARR_VAL, M_MATURITY_DAYS,TO_DATE(M_ENTDATE,'DD/MM/YYYY'),MM_MARKET_VALUE,(MM_MARKET_VALUE-M_TOT_CARR_VAL));


   COMMIT;

END DN_MARKET_VALUES;

