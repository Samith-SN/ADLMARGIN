--------------------------------------------------------
--  DDL for Function DN_RETURN_ENDATE_REPO
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."DN_RETURN_ENDATE_REPO" 
(
  M_DEAL_NO   DN_INV_REPO_DEAL_SERIAL_NO.DEAL_NO%TYPE
 )RETURN VARCHAR2


AS

  MENDDATE DN_INV_REPO_DEAL_SERIAL_NO.DEAL_NO%TYPE;
  MCNT NUMBER ;

BEGIN

 SELECT COUNT(*) INTO MCNT FROM DN_INV_REPO_DEAL_SERIAL_NO A, DN_INV_REPO_DEAL_SERNO_ALLO B
 WHERE A.DEAL_NO=M_DEAL_NO  AND A.DEAL_NO=B.PREV_DEAL_NO AND A.PORTFOLIO_CODE=B.PORTFOLIO_CODE
 AND A.SECURITY_CODE =B.SECURITY_CODE AND A.SERIAL_NO =B.SERIAL_NO AND A.INST_TYPE=B.INST_TYPE
 AND B.END_DATE > SYSDATE  ;

 IF MCNT > 0 THEN

 SELECT TO_CHAR(MAX(B.END_DATE),'DD-MM-YYYY')    INTO MENDDATE FROM DN_INV_REPO_DEAL_SERIAL_NO A, DN_INV_REPO_DEAL_SERNO_ALLO B
 WHERE A.DEAL_NO=M_DEAL_NO  AND A.DEAL_NO=B.PREV_DEAL_NO AND A.PORTFOLIO_CODE=B.PORTFOLIO_CODE
 AND A.SECURITY_CODE =B.SECURITY_CODE AND A.SERIAL_NO =B.SERIAL_NO AND A.INST_TYPE=B.INST_TYPE
 AND B.END_DATE > SYSDATE  ;

 END IF;

 RETURN MENDDATE;

END DN_RETURN_ENDATE_REPO;

/
