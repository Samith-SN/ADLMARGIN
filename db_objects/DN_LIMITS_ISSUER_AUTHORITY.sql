set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_LIMITS_ISSUER_AUTHORITY" 
(
M_limit_code       LMT_STR_AUTHORITY.limit_code%TYPE,
M_dn_user          LMT_STR_AUTHORITY.dn_user%TYPE,
M_limit_level      LMT_STR_AUTHORITY.limit_level%TYPE,
M_STATUS           VARCHAR
)
AS

M_identity VARCHAR(2);

   /*  PROCEDURE  - DN_LIMITS_ISSUER_AUTHORITY  SAVING LIMITS/ISSUER TO LMT_STR_AUTHORITY table
   SYSTEM     - DEALNET
   CREATED BY - SUKATHISVARAN
   CREATED ON - 25/OCTOBER/1999 */


BEGIN
--RAISE_APPLICATION_ERROR(-20201,M_limit_code||' '||M_dn_user||' '||M_limit_level);

SELECT SUBSTR(M_limit_code,1,2) INTO M_identity FROM DUAL;

/*	DELETING ALL EXISTING DATA PERTAINING TO THE SCREEN 	*/


IF (M_STATUS='Y') THEN
      IF  (M_identity=02) THEN
          DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '02-%';
					DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE '02-%';
					DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE '02-%';
      ELSIF (M_identity=03) THEN
          DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '03-%';
					DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE '03-%';
					DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE '03-%';
      ELSIF (M_identity=04) THEN
          DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '04-%';
					DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE '04-%';
					DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE '04-%';
      ELSIF (M_identity=05) THEN
          DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '05-%';
					DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE '05-%';
					DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE '05-%';
      ELSIF (M_identity=06) THEN
          DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '06-%';
					DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE '06-%';
					DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE '06-%';
      ELSIF (M_identity=07) THEN
          DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '07-%';
					DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE '07-%';
					DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE '07-%';
      ELSIF (M_identity=08) THEN
            --DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '08-%';
			--DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE '08-%';
			--DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE '08-%';
      --------modified by nirmala on 19-03-2001--------------------------
        DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE SUBSTR(M_limit_code,1,(INSTR(M_limit_code,'-',1,3)+6))||'%';
		DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE SUBSTR(M_limit_code,1,(INSTR(M_limit_code,'-',1,3)+6))||'%';
		DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE SUBSTR(M_limit_code,1,(INSTR(M_limit_code,'-',1,3)+6))||'%';


      ELSIF (M_identity=09) THEN
          DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '09-%';
					DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE '09-%';
					DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE '09-%';
      ELSIF (M_identity=10) THEN
          DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '10-%';
					DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE '10-%';
					DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE '10-%';
      ELSIF (M_identity=11) THEN
          DELETE LMT_STR_AUTHORITY WHERE LIMIT_CODE LIKE '11-%';
					DELETE LMT_ACT_AUTHORITY WHERE LIMIT_CODE LIKE '11-%';
					DELETE LMT_ACT_DETAILS WHERE LIMIT_CODE LIKE '11-%';
      END IF;
END IF;

INSERT INTO LMT_STR_AUTHORITY
             (limit_code , dn_user , limit_level )
     VALUES  (M_limit_code , M_dn_user , M_limit_level );

COMMIT;

END DN_LIMITS_ISSUER_AUTHORITY;

