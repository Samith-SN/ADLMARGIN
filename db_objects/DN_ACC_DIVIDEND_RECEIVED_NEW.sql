set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_DIVIDEND_RECEIVED_NEW" 
(
M_PORTF_CODE           DN_ACC_LICENCEE_GEN_ACCOUNT.PORTFOLIO_CODE%TYPE,
M_DN_PORTF_CODE        DN_ACC_LICENCEE_GEN_ACCOUNT.DN_PORTFOLIO_CODE%TYPE,
M_TRNAMOUNT            DN_ACC_LICENCEE_GEN_ACCOUNT.TRNAMOUNT%TYPE,
M_ACC_NO               DN_REF_LICENCEE_SETTLEMENT.ACC_NO%TYPE,
M_LICENCEE_BRANCH_CODE DN_TRN_DIVIDEND_INCOME.LICENCEE_BRANCH_CODE%TYPE,
M_LICENCEE_ACCOUNT_NO  DN_TRN_DIVIDEND_INCOME.LICENEE_ACCOUNT_NO%TYPE,
M_DN_USER              DN_TRN_DIVIDEND_INCOME.DN_USER%TYPE,
M_PROC_DESC            DN_TRN_DIVIDEND_INCOME.PROC_DESC%TYPE,
M_EFF_DATE             VARCHAR2,
M_NUMBER               VARCHAR,
M_PAYEE_BANK           VARCHAR2,
M_CHEQUE_NO            VARCHAR2,
M_INST                 DN_TRN_DIVIDEND_INCOME.INST_CODE%TYPE,
M_SEC                  DN_TRN_DIVIDEND_INCOME.SEC_CODE%TYPE,
M_TAX                  DN_TRN_DIVIDEND_INCOME.WITHHOLDING_TAX%TYPE, --ADDED BY SVA ON 27-12-2005
M_TRNDATE              VARCHAR2  --add by waruna 2011-06-10
)
AS


M_DOCREFNO             DN_TRN_DIVIDEND_INCOME.DOCREFNO%TYPE;
M_ACC_SYS_REFNO        DN_ACC_LICENCEE_GEN_ACCOUNT.ACC_SYS_REFNO%TYPE;

BEGIN

  -- CREATED BY : S.SHANHEETHA 
  -- DATE : 14-09-2006 

 DN_VALIDATE_SAVE_RIGHTS(M_DN_USER,'WD_Divi_Receive');


 SELECT ACC_SYS_REFNO
 INTO   M_ACC_SYS_REFNO
 FROM   DN_REF_LICENCEE_SETTLEMENT
 WHERE  BRANCH_CODE=M_LICENCEE_BRANCH_CODE AND
        ACC_NO = M_LICENCEE_ACCOUNT_NO AND
        ACTIVE_STATUS ='Y';


 UPDATE  DN_TRN_DIVIDEND_INCOME
 SET     LICENCEE_BRANCH_CODE=M_LICENCEE_BRANCH_CODE ,
         LICENEE_ACCOUNT_NO=M_LICENCEE_ACCOUNT_NO ,
         PAYEE_BANK=M_PAYEE_BANK ,
         CHEQUE_NO=M_CHEQUE_NO,
         RECEIVED_DATE=TO_DATE(M_EFF_DATE,'DD/MM/YYYY'),
         WITHHOLDING_TAX = M_TAX 
 WHERE   DOCREFNO= M_NUMBER AND
         SEC_CODE=M_SEC AND
         INST_CODE=M_INST AND
         PROC_DESC='DAYENDROUTINE' ;


 DN_ACC_DIV_RECEIVED('GEN',M_DN_PORTF_CODE,TO_DATE(M_TRNDATE,'DD/MM/YYYY') ,--TO_DATE(M_EFF_DATE,'DD/MM/YYYY'),-->TO_DATE(M_TRNDATE,'DD/MM/YYYY') by waruna 2011-06-10
                      M_TRNAMOUNT,M_NUMBER,M_ACC_SYS_REFNO,M_INST,
                      M_TAX ) ;

      INSERT INTO DN_TIME_LOG_SETTLE
          (DOC_REF_NO,
           DN_USER,
           ENT_DATE,
           DESCRIPTION)
           VALUES
            ( M_DOCREFNO,
              M_DN_USER,
              SYSDATE,
              'PORTFOLIO DIVIDEND RECEIVED ');
--M_NUMBER:=M_DOCREFNO;

COMMIT;

END DN_ACC_DIVIDEND_RECEIVED_NEW;

