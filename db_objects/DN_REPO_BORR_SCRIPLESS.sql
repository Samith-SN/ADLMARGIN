--------------------------------------------------------
--  DDL for Procedure DN_REPO_BORR_SCRIPLESS
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_REPO_BORR_SCRIPLESS" 
(
  M_DEALNO           DN_TRN_REPO_FRESH.DEAL_NO%TYPE,
  M_USER             DN_TRN_REPO_FRESH.DN_USER%TYPE
 )
AS



 CURSOR MY_CUR_BORR IS
    SELECT  X.DEAL_NO DEAL_NO,X.SERIAL_NO SERIAL_NO,X.FACE_VAL FACE_VAL,
            C.SECURITY_CODE SECURITY_CODE,'OR',
            X.INST_TYPE,X.DEAL_YIELD,X.YIELD_WITH_BROKERAGE,
            X.INITIAL_COST,X.BROKERAGE,X.PRICE_INT_ACCR,
            X.CARR_VAL,X.COUP_INT_PURCH,X.COUP_INT_ACCR,X.TOT_COUP_INT,X.EFF_VALDATE

    FROM    DN_INV_OUTPS_DEAL_SERIAL_NO X,
            DN_TRN_REPO_FRESH A ,
            DN_REF_PORTFOLIO B,
            DN_TRN_REPO_FRESH_SEC C

    WHERE   A.DEAL_NO=M_DEALNO  AND
            A.BORR_PORTFOLIO_CODE=B.PORTFOLIO_CODE  AND
            A.DEAL_NO=C.DEAL_NO AND
            B.PF_TYPE='P' AND
            A.BORR_PORTFOLIO_CODE=X.PORTFOLIO_CODE  AND
            X.SECURITY_CODE=C.SECURITY_CODE AND
            X.SCRIP_STATUS='SL' AND
            X.SERIAL_NO_STATUS='INV' AND
            X.FACE_VAL>0 AND
            X.ALLO_REPO=0 AND X.ALLO_BL=0
UNION

    SELECT  X.DEAL_NO DEAL_NO,X.SERIAL_NO SERIAL_NO,X.FACE_VAL FACE_VAL,
            C.SECURITY_CODE SECURITY_CODE,'RF',
            X.INST_TYPE,0,0,0,0,0,0,0,0,0,X.RET_DUE_DATE


    FROM    DN_INV_REPO_DEAL_SERIAL_NO X,
            DN_TRN_REPO_FRESH A ,
            DN_REF_PORTFOLIO B,
            DN_TRN_REPO_FRESH_SEC C
    WHERE  A.DEAL_NO=M_DEALNO AND
           A.BORR_PORTFOLIO_CODE=B.PORTFOLIO_CODE  AND
            A.DEAL_NO=C.DEAL_NO AND
           B.PF_TYPE='P' AND
            A.BORR_PORTFOLIO_CODE=X.PORTFOLIO_CODE  AND
            X.SECURITY_CODE=C.SECURITY_CODE AND
            X.SCRIPT_STATUS='SL' AND
            X.FACE_VAL>0 AND
            X.ALLO_REPO=0 AND X.ALLO_BL=0
   ORDER BY 4,5 ;



 CURSOR MY_CUR_TEST IS
  SELECT  SUM(A.FACE_VALUE),B.EFF_VALDATE,B.LEND_PORTFOLIO_CODE,B.BORR_PORTFOLIO_CODE,
          A.SECURITY_CODE
  FROM    DN_TRN_REPO_FRESH B,
          DN_TRN_REPO_FRESH_SEC A
  WHERE   B.DEAL_NO=M_DEALNO AND
          B.DEAL_NO=A.DEAL_NO
  GROUP BY  A.SECURITY_CODE,B.EFF_VALDATE,B.LEND_PORTFOLIO_CODE,B.BORR_PORTFOLIO_CODE
  ORDER BY 5;


  M_LEG1_VALUE                 DN_TRN_REPO_FRESH_SEC.FACE_VALUE%TYPE;
  MM_SWAP_DEAL                 DN_TRN_REPO_FRESH.DEAL_NO%TYPE;
  M_FACE_VALUE                 DN_TRN_REPO_FRESH_SEC.FACE_VALUE%TYPE;
  M_EFF_VALDATE                DN_TRN_REPO_FRESH.EFF_VALDATE%TYPE;
  M_LEND_PORTFOLIO_CODE        DN_TRN_REPO_FRESH.LEND_PORTFOLIO_CODE%TYPE;
  M_BORR_PORTFOLIO_CODE        DN_TRN_REPO_FRESH.BORR_PORTFOLIO_CODE%TYPE;
  M_SECURITY_CODE              DN_TRN_REPO_FRESH_SERIAL_NO.SECURITY_CODE%TYPE;
  MM_DEAL_NO                   DN_TRN_REPO_FRESH.DEAL_NO%TYPE;
  MM_SERIAL_NO                 DN_TRN_REPO_FRESH_SERIAL_NO.SERIAL_NO%TYPE;
  MM_FACE_VAL                  DN_TRN_REPO_FRESH_SERIAL_NO.FACE_VALUE%TYPE;
  MM_SECURITY_CODE             DN_TRN_REPO_FRESH_SERIAL_NO.SECURITY_CODE%TYPE;
  MM_STATUS                    VARCHAR2(2);
  MM_INST_TYPE                 DN_TRN_REPO_FRESH_SERIAL_NO.INST_TYPE%TYPE;
  MM_DEAL_YIELD                DN_INV_OUTPS_DEAL_SERIAL_NO.DEAL_YIELD%TYPE;
  MM_YIELD_WITH_BROKERAGE      DN_INV_OUTPS_DEAL_SERIAL_NO.YIELD_WITH_BROKERAGE%TYPE;
  MM_INITIAL_COST              DN_INV_OUTPS_DEAL_SERIAL_NO.INITIAL_COST%TYPE;
  MM_BROKERAGE                 DN_INV_OUTPS_DEAL_SERIAL_NO.BROKERAGE%TYPE;
  MM_PRICE_INT_ACCR            DN_INV_OUTPS_DEAL_SERIAL_NO.PRICE_INT_ACCR%TYPE;
  MM_CARR_VAL                  DN_INV_OUTPS_DEAL_SERIAL_NO.CARR_VAL%TYPE;
  MM_COUP_INT_PURCH            DN_INV_OUTPS_DEAL_SERIAL_NO.COUP_INT_PURCH%TYPE;
  MM_COUP_INT_ACCR             DN_INV_OUTPS_DEAL_SERIAL_NO.COUP_INT_ACCR%TYPE;
  MM_TOT_COUP_INT              DN_INV_OUTPS_DEAL_SERIAL_NO.TOT_COUP_INT %TYPE;
  M_TOTAL_FACE_VAL             DN_INV_OUTPS_DEAL_SERIAL_NO.FACE_VAL%TYPE;
  M_SWAP_SERNO1                DN_TRN_REPO_FRESH_SERIAL_NO.SERIAL_NO%TYPE;
  M_SWAP_SERNO2                DN_TRN_REPO_FRESH_SERIAL_NO.SERIAL_NO%TYPE;
  M_SWAP_SERNO3                DN_TRN_REPO_FRESH_SERIAL_NO.SERIAL_NO%TYPE;
  M_SWAP_SERNO4                DN_TRN_REPO_FRESH_SERIAL_NO.SERIAL_NO%TYPE;
  M_NEW_DATE                   DATE;


BEGIN

    -- CREATED ON :06-09-2001
    -- CREATED BY :NIRMALA
    -- SYSTEM     :DEALNET(MBFSL)

------------------------------------------------------------------------------------------------------------
--------------------------------BORROWER (PORTFOLIO) INFORMATION------------------------------------------
OPEN MY_CUR_TEST;
LOOP
FETCH MY_CUR_TEST INTO
  M_LEG1_VALUE,M_EFF_VALDATE,M_LEND_PORTFOLIO_CODE,M_BORR_PORTFOLIO_CODE,M_SECURITY_CODE;
EXIT WHEN MY_CUR_TEST%NOTFOUND;

    SELECT SUM(FACE_VAL)
    INTO   M_TOTAL_FACE_VAL
    FROM
    (SELECT  X.DEAL_NO DEAL_NO,X.SERIAL_NO SERIAL_NO,X.FACE_VAL FACE_VAL,C.SECURITY_CODE SECURITY_CODE,'OR'
     FROM    DN_INV_OUTPS_DEAL_SERIAL_NO X,
             DN_TRN_REPO_FRESH A ,
             DN_REF_PORTFOLIO B,
             DN_TRN_REPO_FRESH_SEC C
     WHERE   A.DEAL_NO=M_DEALNO AND
             A.BORR_PORTFOLIO_CODE=B.PORTFOLIO_CODE  AND
             A.DEAL_NO=C.DEAL_NO AND
             B.PF_TYPE='P' AND
             A.BORR_PORTFOLIO_CODE=X.PORTFOLIO_CODE  AND
             C.SECURITY_CODE=M_SECURITY_CODE AND
             X.SECURITY_CODE=C.SECURITY_CODE AND
             X.SCRIP_STATUS='SL' AND
             X.SERIAL_NO_STATUS='INV' AND
             X.FACE_VAL>0 AND
             X.ALLO_REPO=0 AND X.ALLO_BL=0
    UNION
    SELECT  X.DEAL_NO DEAL_NO,X.SERIAL_NO SERIAL_NO,X.FACE_VAL FACE_VAL,C.SECURITY_CODE SECURITY_CODE,'RF'
    FROM    DN_INV_REPO_DEAL_SERIAL_NO X,
            DN_TRN_REPO_FRESH A ,
            DN_REF_PORTFOLIO B,
            DN_TRN_REPO_FRESH_SEC C
    WHERE   A.DEAL_NO=M_DEALNO  AND
            A.BORR_PORTFOLIO_CODE=B.PORTFOLIO_CODE  AND
            A.DEAL_NO=C.DEAL_NO AND
            B.PF_TYPE='P' AND
            A.BORR_PORTFOLIO_CODE=X.PORTFOLIO_CODE  AND
            C.SECURITY_CODE=M_SECURITY_CODE AND
            X.SECURITY_CODE=C.SECURITY_CODE AND
            X.SCRIPT_STATUS='SL' AND
            X.FACE_VAL>0 AND
            X.ALLO_REPO=0 AND X.ALLO_BL=0);


 --CHECK FOR SUFFICIENT INVENTORY
IF(M_TOTAL_FACE_VAL<M_LEG1_VALUE)THEN
     ROLLBACK;
     RAISE_APPLICATION_ERROR(-20201,'INSUFFICIENT INVENTORY!!!!!!!');
     --EXIT;
ELSE
  OPEN MY_CUR_BORR;
  LOOP
      FETCH MY_CUR_BORR INTO
              MM_DEAL_NO ,MM_SERIAL_NO ,MM_FACE_VAL ,MM_SECURITY_CODE,MM_STATUS,
              MM_INST_TYPE,MM_DEAL_YIELD,MM_YIELD_WITH_BROKERAGE,
              MM_INITIAL_COST,MM_BROKERAGE,MM_PRICE_INT_ACCR,
              MM_CARR_VAL,MM_COUP_INT_PURCH,MM_COUP_INT_ACCR,MM_TOT_COUP_INT,M_NEW_DATE;

  EXIT WHEN MY_CUR_BORR%NOTFOUND;

     IF(MM_SECURITY_CODE=M_SECURITY_CODE) THEN

       IF(MM_FACE_VAL=M_LEG1_VALUE)THEN
         EXIT;
       ELSIF(MM_FACE_VAL>M_LEG1_VALUE ) THEN

           SELECT TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||'-'||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS_BORR_DEALNO.NEXTVAL),3,'0')
           INTO   MM_SWAP_DEAL
           FROM DUAL;
           MM_SWAP_DEAL:='SS'||MM_SWAP_DEAL;


            IF(MM_STATUS='OR')THEN

                 UPDATE  DN_INV_OUTPS_DEAL_SERIAL_NO
                 SET     SALE_EFF_VALDATE=M_EFF_VALDATE,
                         SALE_DEAL_NO=MM_SWAP_DEAL,
                         SERIAL_NO_STATUS='SWP'
                 WHERE   DEAL_NO=MM_DEAL_NO AND
                         SERIAL_NO =MM_SERIAL_NO AND
                         FACE_VAL=MM_FACE_VAL AND
                         SECURITY_CODE=MM_SECURITY_CODE;

                 SELECT  'S'||TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS_BORR.NEXTVAL),3,'0')
                 INTO    M_SWAP_SERNO1
                 FROM    DUAL;



                     INSERT INTO DN_INV_OUTPS_DEAL_SEC
                     (PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,DEAL_NO,EFF_VALDATE,TRN_TYPE,LOCATION,SCRIP_STATUS)
                     VALUES
                     (M_BORR_PORTFOLIO_CODE,MM_INST_TYPE,MM_SECURITY_CODE,MM_SWAP_DEAL,M_EFF_VALDATE,'B',M_LEND_PORTFOLIO_CODE,'SL');



                  INSERT INTO DN_INV_OUTPS_DEAL_SERIAL_NO
                   (PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,SECURITY_CODE,DEAL_NO,
                    SERIAL_NO,
                    DEAL_YIELD,
                    YIELD_WITH_BROKERAGE,SCRIP_FACE_VAL,FACE_VAL,INITIAL_COST, BROKERAGE, PRICE_INT_ACCR,
                    CARR_VAL,COUP_INT_PURCH,COUP_INT_ACCR,TOT_COUP_INT,FWD_SALE,FWD_PURCHASE,LOCATION,
                    ALLO_REPO,ALLO_BL,FWD_ALLO_REPO,FWD_ALLO_BL,SALE_DEAL_NO,SERIAL_NO_STATUS,
                    SALE_EFF_VALDATE,RET_DUE_DATE,COST_TRANS_STATUS,SCRIP_STATUS)
                  VALUES
                   (M_BORR_PORTFOLIO_CODE,M_EFF_VALDATE,
                    MM_INST_TYPE,MM_SECURITY_CODE,
                    MM_SWAP_DEAL,
                    M_SWAP_SERNO1,
                    MM_DEAL_YIELD,
                    MM_YIELD_WITH_BROKERAGE,M_LEG1_VALUE,M_LEG1_VALUE,
                    MM_INITIAL_COST*(M_LEG1_VALUE/MM_FACE_VAL),
                    MM_BROKERAGE*(M_LEG1_VALUE/MM_FACE_VAL),
                    MM_PRICE_INT_ACCR*(M_LEG1_VALUE/MM_FACE_VAL),
                    MM_CARR_VAL*(M_LEG1_VALUE/MM_FACE_VAL),
                    MM_COUP_INT_PURCH*(M_LEG1_VALUE/MM_FACE_VAL),
                    MM_COUP_INT_ACCR*(M_LEG1_VALUE/MM_FACE_VAL),
                    MM_TOT_COUP_INT*(M_LEG1_VALUE/MM_FACE_VAL),
                    0,0,M_LEND_PORTFOLIO_CODE,M_LEG1_VALUE,0,0,0,
                    NULL,'INV',NULL,NULL,NULL,'SL');

                     INSERT INTO DN_TRN_REPO_SCRIPLESS_SWAPS
                      (SCRIPLESS_SWAP_NO,PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,DEAL_NO,
                       SERIAL_NO,TRANS_TYPE,FACE_VALUE,DN_USER,ENTDATE)
                     VALUES
                      (MM_SWAP_DEAL,M_BORR_PORTFOLIO_CODE,MM_INST_TYPE,MM_SECURITY_CODE,MM_SWAP_DEAL,
                       M_SWAP_SERNO1,'R',M_LEG1_VALUE,M_USER,SYSDATE);


                     SELECT  'S'||TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS_BORR.NEXTVAL),3,'0')
                     INTO    M_SWAP_SERNO2
                     FROM    DUAL;


                    /*INSERT INTO DN_INV_OUTPS_DEAL_SEC
                     (PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,DEAL_NO,EFF_VALDATE,TRN_TYPE,LOCATION,SCRIP_STATUS)
                     VALUES
                     (M_BORR_PORTFOLIO_CODE,MM_INST_TYPE,MM_SECURITY_CODE,MM_SWAP_DEAL,M_EFF_VALDATE,'B',M_LEND_PORTFOLIO_CODE,'SL');
                    */

                  INSERT INTO DN_INV_OUTPS_DEAL_SERIAL_NO
                   (PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,SECURITY_CODE,DEAL_NO, SERIAL_NO,DEAL_YIELD,
                    YIELD_WITH_BROKERAGE,SCRIP_FACE_VAL,FACE_VAL,INITIAL_COST, BROKERAGE, PRICE_INT_ACCR,
                    CARR_VAL,COUP_INT_PURCH,COUP_INT_ACCR,TOT_COUP_INT,FWD_SALE,FWD_PURCHASE,LOCATION,
                    ALLO_REPO,ALLO_BL,FWD_ALLO_REPO,FWD_ALLO_BL,SALE_DEAL_NO,SERIAL_NO_STATUS,
                    SALE_EFF_VALDATE,RET_DUE_DATE,COST_TRANS_STATUS,SCRIP_STATUS)
                  VALUES
                   (M_BORR_PORTFOLIO_CODE,M_EFF_VALDATE,
                   MM_INST_TYPE,MM_SECURITY_CODE,
                    MM_SWAP_DEAL,
                    M_SWAP_SERNO2,
                    MM_DEAL_YIELD,
                    MM_YIELD_WITH_BROKERAGE,(MM_FACE_VAL-M_LEG1_VALUE),
                   (MM_FACE_VAL-M_LEG1_VALUE),
                    MM_INITIAL_COST*((MM_FACE_VAL-M_LEG1_VALUE)/MM_FACE_VAL),
                    MM_BROKERAGE*((MM_FACE_VAL-M_LEG1_VALUE)/MM_FACE_VAL),
                    MM_PRICE_INT_ACCR*((MM_FACE_VAL-M_LEG1_VALUE)/MM_FACE_VAL),
                    MM_CARR_VAL*((MM_FACE_VAL-M_LEG1_VALUE)/MM_FACE_VAL),
                    MM_COUP_INT_PURCH*((MM_FACE_VAL-M_LEG1_VALUE)/MM_FACE_VAL),
                    MM_COUP_INT_ACCR*((MM_FACE_VAL-M_LEG1_VALUE)/MM_FACE_VAL),
                    MM_TOT_COUP_INT*((MM_FACE_VAL-M_LEG1_VALUE)/MM_FACE_VAL),
                    0,0,M_LEND_PORTFOLIO_CODE,0,0,0,0,
                    NULL,'INV',NULL,NULL,NULL,'SL');


                    INSERT INTO DN_TRN_REPO_SCRIPLESS_SWAPS
                      (SCRIPLESS_SWAP_NO,PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,DEAL_NO,
                       SERIAL_NO,TRANS_TYPE,FACE_VALUE,DN_USER,ENTDATE)
                    VALUES
                      (MM_SWAP_DEAL,M_BORR_PORTFOLIO_CODE,MM_INST_TYPE,MM_SECURITY_CODE,MM_SWAP_DEAL,
                       M_SWAP_SERNO2,'R',(MM_FACE_VAL-M_LEG1_VALUE),M_USER,SYSDATE);


        ELSE --MM_STATUS='RF'

             UPDATE   DN_INV_REPO_DEAL_SERIAL_NO
             SET      SWAP_STATUS='Y',
                      RET_DUE_DATE=SYSDATE
             WHERE    DEAL_NO=MM_DEAL_NO AND
                      SERIAL_NO =MM_SERIAL_NO AND
                      FACE_VAL=MM_FACE_VAL AND
                      SECURITY_CODE=MM_SECURITY_CODE;


               SELECT  'S'||TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS_BORR.NEXTVAL),3,'0')
               INTO    M_SWAP_SERNO3
               FROM    DUAL;


                INSERT INTO  DN_INV_REPO_DEAL_SERIAL_NO
                  (PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,SECURITY_CODE,DEAL_NO,SERIAL_NO,SCRIP_FACE_VAL,
                   FACE_VAL,FWD_RECEIPT,LOCATION,ALLO_REPO,ALLO_BL,FWD_ALLO_REPO,FWD_ALLO_BL,RET_DUE_DATE,
                   SCRIPT_STATUS,SWAP_STATUS)
                 VALUES
                 (M_BORR_PORTFOLIO_CODE,M_EFF_VALDATE,MM_INST_TYPE,MM_SECURITY_CODE,M_DEALNO,M_SWAP_SERNO3,
                 M_LEG1_VALUE,M_LEG1_VALUE,0,M_BORR_PORTFOLIO_CODE,M_LEG1_VALUE,0,0,0,M_NEW_DATE,'SL','N');



                   INSERT INTO DN_TRN_REPO_SCRIPLESS_SWAPS
                      (SCRIPLESS_SWAP_NO,PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,DEAL_NO,
                       SERIAL_NO,TRANS_TYPE,FACE_VALUE,DN_USER,ENTDATE)
                    VALUES
                      (MM_SWAP_DEAL,M_BORR_PORTFOLIO_CODE,MM_INST_TYPE,MM_SECURITY_CODE,MM_SWAP_DEAL,
                       M_SWAP_SERNO3,'R',M_LEG1_VALUE,M_USER,SYSDATE);



                      SELECT  'S'||TO_CHAR(SYSDATE,'YYYY')||TO_CHAR(SYSDATE,'MM')||TO_CHAR(SYSDATE,'DD')||LPAD(TO_CHAR(DN_SEQ_SCRIPLESS_BORR.NEXTVAL),3,'0')
                      INTO    M_SWAP_SERNO4
                      FROM    DUAL;

                       INSERT INTO  DN_INV_REPO_DEAL_SERIAL_NO
                        (PORTFOLIO_CODE,EFF_VALDATE,INST_TYPE,SECURITY_CODE,DEAL_NO,SERIAL_NO,SCRIP_FACE_VAL,
                         FACE_VAL,FWD_RECEIPT,LOCATION,ALLO_REPO,ALLO_BL,FWD_ALLO_REPO,FWD_ALLO_BL,RET_DUE_DATE,
                         SCRIPT_STATUS,SWAP_STATUS)
                       VALUES
                       (M_BORR_PORTFOLIO_CODE,M_EFF_VALDATE,MM_INST_TYPE,MM_SECURITY_CODE,M_DEALNO,M_SWAP_SERNO4,
                       (MM_FACE_VAL-M_LEG1_VALUE),(MM_FACE_VAL-M_LEG1_VALUE),0,M_BORR_PORTFOLIO_CODE,(MM_FACE_VAL-M_LEG1_VALUE),0,0,0,M_NEW_DATE,'SL','N');




                         INSERT INTO DN_TRN_REPO_SCRIPLESS_SWAPS
                            (SCRIPLESS_SWAP_NO,PORTFOLIO_CODE,INST_TYPE,SECURITY_CODE,DEAL_NO,
                             SERIAL_NO,TRANS_TYPE,FACE_VALUE,DN_USER,ENTDATE)
                          VALUES
                            (MM_SWAP_DEAL,M_BORR_PORTFOLIO_CODE,MM_INST_TYPE,MM_SECURITY_CODE,MM_SWAP_DEAL,
                             M_SWAP_SERNO4,'R',(MM_FACE_VAL-M_LEG1_VALUE),M_USER,SYSDATE);



  END IF;--MM_STATUS='OR' AND 'RF'
  EXIT;

ELSIF (MM_FACE_VAL<M_LEG1_VALUE ) THEN
     M_LEG1_VALUE:=(M_LEG1_VALUE-MM_FACE_VAL);
END IF;

END IF;--CHECKS SECURITY CODES ARE SAME
END LOOP;
CLOSE MY_CUR_BORR;

END IF;--CHECK FOR SUFFICIENT INVENTORY VALUE

END LOOP;
CLOSE MY_CUR_TEST;


-------------------------------------------END-----------------------------------------------------
COMMIT;
END DN_REPO_BORR_SCRIPLESS;

