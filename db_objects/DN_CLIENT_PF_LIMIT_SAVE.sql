  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_CLIENT_PF_LIMIT_SAVE" 
   (
 
  M_PORTFOLIO_CODE            DN_CLIENT_PF_LIMIT.PORTFOLIO_CODE%TYPE ,
  M_LIMIT                     DN_CLIENT_PF_LIMIT.LIMIT%TYPE ,    
  M_ENT_USER                  DN_CLIENT_PF_LIMIT.ENT_USER%TYPE,
  M_OPTION1                   VARCHAR2 ,
  M_RATE                      DN_CLIENT_PF_LIMIT.Rate%TYPE,
  M_RATE_Type                 DN_CLIENT_PF_LIMIT.Rate%TYPE,
  M_EFF_VALDATE               varchar
   )

   IS

    -- Procedue     : DN_CLIENT_PF_LIMIT_SAVE
    -- System       : Dealnet system
    -- Created by   : K.m.w.s waruna sri jayanath
    -- Created on   : 2010-12-28

   M_COUNT    NUMBER;
   M_OPTION  VARCHAR2(3);
BEGIN
  M_OPTION := M_OPTION1;

 /* 
  SELECT COUNT(*) INTO M_COUNT
  FROM   DN_TRN_SECURITY_LIMIT
  WHERE  SECURITY_CODE  = M_SECURITY_CODE AND
         PORTFOLIO_CODE = M_PORT_CODE  ;

 IF M_COUNT>0 AND M_OPTION ='NEW' THEN
    M_OPTION :='MOD';
 END IF ;
 
 IF M_COUNT=0 AND M_OPTION ='MOD' THEN
    M_OPTION :='NEW';
 END IF ;
*/
IF M_OPTION ='NEW' THEN
 
 INSERT INTO DN_CLIENT_PF_LIMIT(PORTFOLIO_CODE, LIMIT, ENT_DATE, ENT_USER,LIMIT_STATUS,RATE,RATE_TYPE,EFF_VALDATE)
 VALUES(M_PORTFOLIO_CODE,M_LIMIT,SYSDATE,  M_ENT_USER,'ENT',M_RATE/100,M_RATE_TYPE,to_date(M_EFF_VALDATE,'dd/mm/yyyy'));      

INSERT INTO dn_doc_status_log( DOC_REF_NO,DOC_TYPE,DOC_STATUS,DN_USER,ENT_DATE,DESCRIPTION)
 VALUES(M_PORTFOLIO_CODE,'CLIENT_LIMIT','ENT',M_ENT_USER,SYSDATE,'ENTERED CLIENT LIMIT-'||M_LIMIT||',RATE-'||M_RATE/100||'-'||M_EFF_VALDATE);


ELSIF M_OPTION = 'MOD' THEN
  INSERT INTO DN_CLIENT_PF_LIMIT_BK(PORTFOLIO_CODE, LIMIT, ENT_DATE, ENT_USER,
        LIMIT_STATUS, MOD_DATE, MOD_USER,RATE,RATE_TYPE,EFF_VALDATE)
  SELECT A.PORTFOLIO_CODE, A.LIMIT, A.ENT_DATE, A.ENT_USER,
        A.LIMIT_STATUS, sysdate, M_ENT_USER,RATE,RATE_TYPE,EFF_VALDATE
  FROM   DN_CLIENT_PF_LIMIT A
  WHERE  PORTFOLIO_CODE = M_PORTFOLIO_CODE;   

  UPDATE DN_CLIENT_PF_LIMIT
  SET    LIMIT        = M_LIMIT,
         ENT_DATE       = SYSDATE ,
         ENT_USER       = M_ENT_USER,
         LIMIT_STATUS='MOD',
         rATE=m_RATE/100,
         RATE_TYPE=M_RATE_TYPE,
         EFF_VALDATE=to_date(M_EFF_VALDATE,'dd/mm/yyyy')
  WHERE  PORTFOLIO_CODE  = M_PORTFOLIO_CODE 
  and (LIMIT_STATUS='ENT' OR LIMIT_STATUS='MOD')
  ; 
      
 INSERT INTO dn_doc_status_log( DOC_REF_NO,DOC_TYPE,DOC_STATUS,DN_USER,ENT_DATE,DESCRIPTION)
 VALUES(M_PORTFOLIO_CODE,'CLIENT_LIMIT','MOD',M_ENT_USER,SYSDATE,'MODIFIED CLIENT LIMIT-'||M_LIMIT||',RATE-'||M_RATE/100||'-'||M_EFF_VALDATE);     
         
ELSIF M_OPTION = 'DEL' THEN
 

  INSERT INTO DN_CLIENT_PF_LIMIT_BK(PORTFOLIO_CODE, LIMIT, ENT_DATE, ENT_USER,
       LIMIT_STATUS, MOD_DATE, MOD_USER,RATE,RATE_TYPE,EFF_VALDATE)
  SELECT PORTFOLIO_CODE,LIMIT, ENT_DATE, ENT_USER,
       LIMIT_STATUS, sysdate, M_ENT_USER,RATE,RATE_TYPE,EFF_VALDATE
  FROM   DN_CLIENT_PF_LIMIT a
  WHERE  PORTFOLIO_CODE = M_PORTFOLIO_CODE; 
  
  UPDATE DN_CLIENT_PF_LIMIT
  SET   LIMIT_STATUS='DEL'
         -- LIMIT        = M_LIMIT,
         -- ENT_DATE       = SYSDATE ,
         --ENT_USER       = M_ENT_USER,
         --rATE=m_RATE/100,
         --RATE_TYPE=M_RATE_TYPE,
         --EFF_VALDATE=M_EFF_VALDATE
  WHERE  PORTFOLIO_CODE  = M_PORTFOLIO_CODE 
  and (LIMIT_STATUS='ENT' OR LIMIT_STATUS='MOD')
  
  /*DELETE DN_CLIENT_PF_LIMIT
  WHERE  PORTFOLIO_CODE = M_PORTFOLIO_CODE
  and (LIMIT_STATUS='ENT' OR LIMIT_STATUS='MOD')
  */
  ;  
       
INSERT INTO dn_doc_status_log( DOC_REF_NO,DOC_TYPE,DOC_STATUS,DN_USER,ENT_DATE,DESCRIPTION)
VALUES(M_PORTFOLIO_CODE,'CLIENT_LIMIT','DEL',M_ENT_USER,SYSDATE,'DELETED CLIENT LIMIT-'||M_LIMIT||',RATE-'||M_RATE/100||'-'||M_EFF_VALDATE);  

END IF;



END ;

