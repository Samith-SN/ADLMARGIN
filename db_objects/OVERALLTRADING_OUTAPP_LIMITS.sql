--  DDL for Procedure OVERALLTRADING_OUTAPP_LIMITS
--------------------------------------------------------
set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."OVERALLTRADING_OUTAPP_LIMITS" 
(
 M_LIMIT_CODE      LMT_ACT_DETAILS.LIMIT_CODE%TYPE,
 M_VALDATE_FROM    VARCHAR,
 M_VALDATE_TO      VARCHAR,
 M_LMT_LEVEL       LMT_ACT_DETAILS.LIMIT_LEVEL%TYPE,
 M_USER            LMT_ACT_AUTHORITY.APPROVED_BY%TYPE,
 M_LMT_TYPE        LMT_ACT_DETAILS.LIMIT_TYPE%TYPE

 )
AS
    /* PROCEDURE  - TO APPROVE LIMIT IN OVERALL TRADING
       SYSTEM     - DEALNET
       CREATED BY - dayan
       CREATED ON - 10/12/1999 */

 M_VALDATE_FROM_V1    LMT_ACT_DETAILS.VALID_DATE_FROM%TYPE;
 M_VALDATE_TO_V1      LMT_ACT_DETAILS.VALID_DATE_TO%TYPE;
 M_LEVLES             LMT_STR_OVRL_AMT.NO_OF_APP_LEVELS%TYPE;
 M_STATUS             LMT_ACT_DETAILS.ACTIVE_STATUS%TYPE;
 M_LAST_DAILY         DN_SYS_PARAMETER.LAST_DAILY%TYPE;

BEGIN
--GETTING SELECTED NUMBER OF LEVELS FROM APPROPRIATE TABLE
IF (SUBSTR(M_LIMIT_CODE,1,2)='01') THEN
 SELECT
     NO_OF_APP_LEVELS INTO M_LEVLES
     FROM LMT_STR_OVRL_AMT
     WHERE LIMIT_CODE=M_LIMIT_CODE;
ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='02') THEN
 SELECT
     NO_OF_APP_LEVELS INTO M_LEVLES
     FROM LMT_STR_OVRL_MATU
     WHERE LIMIT_CODE=M_LIMIT_CODE;

ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='03') THEN
 SELECT
     NO_OF_APP_LEVELS INTO M_LEVLES
     FROM LMT_STR_OVRL_EXPO
     WHERE LIMIT_CODE=M_LIMIT_CODE;

ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='04') THEN
 SELECT
     NO_OF_APP_LEVELS INTO M_LEVLES
     FROM LMT_STR_ISSUER_INST_AMT
     WHERE LIMIT_CODE=M_LIMIT_CODE;

ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='05') THEN
 SELECT
     NO_OF_APP_LEVELS INTO M_LEVLES
     FROM LMT_STR_ISSUER_INST_MATU
     WHERE LIMIT_CODE=M_LIMIT_CODE;

ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='06') THEN
 SELECT
     NO_OF_APP_LEVELS INTO M_LEVLES
     FROM LMT_STR_ISSUER_INST_HOL_PERIOD
     WHERE LIMIT_CODE=M_LIMIT_CODE;
-----------------------------------------------------------@@@@@@@@@@@@@@@@@@@@
ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='07') THEN
 SELECT
     NO_OF_APP_LEVELS INTO M_LEVLES
     FROM LMT_STR_OVRL_AMT
     WHERE LIMIT_CODE=M_LIMIT_CODE;
-----------------------------------------------------------@@@@@@@@@@@@@@@@@@@@

ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='08') THEN
 SELECT
     NO_OF_APP_LEVELS INTO M_LEVLES
     FROM LMT_STR_DEALER_INST_OVRL_AMT
     WHERE LIMIT_CODE=M_LIMIT_CODE;

ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='09') THEN
 SELECT
     NO_OF_APP_LEVELS INTO M_LEVLES
     FROM LMT_STR_DEALER_INST_MATU
     WHERE LIMIT_CODE=M_LIMIT_CODE;

ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='10') THEN
 SELECT
     NO_OF_APP_LEVELS INTO M_LEVLES
     FROM LMT_STR_DEALER_INST_HOL_PERIOD
     WHERE LIMIT_CODE=M_LIMIT_CODE;

END IF;

 SELECT
      TO_DATE(M_VALDATE_FROM,'DD/MM/YYYY')
    INTO
      M_VALDATE_FROM_V1
    FROM DUAL;

 SELECT
      TO_DATE(M_VALDATE_TO,'DD/MM/YYYY')
    INTO
      M_VALDATE_TO_V1
    FROM DUAL;

 IF (M_LEVLES=M_LMT_LEVEL) THEN
    M_STATUS:='Y';
 ELSIF(M_LEVLES>M_LMT_LEVEL) THEN
    M_STATUS:=M_LMT_LEVEL;
 END IF;

UPDATE  LMT_ACT_DETAILS SET
      ACTIVE_STATUS=M_STATUS,
      LIMIT_LEVEL=M_LMT_LEVEL
WHERE LIMIT_CODE=M_LIMIT_CODE AND
      LIMIT_TYPE=M_LMT_TYPE AND
      VALID_DATE_FROM =M_VALDATE_FROM_V1 AND
      VALID_DATE_TO=M_VALDATE_TO_V1 ;

INSERT INTO LMT_ACT_AUTHORITY
    (LIMIT_CODE, LIMIT_TYPE, VALID_DATE_FROM, VALID_DATE_TO, APPROVED_BY, LIMIT_LEVEL)
  VALUES
    (M_LIMIT_CODE,M_LMT_TYPE,M_VALDATE_FROM_V1,M_VALDATE_TO_V1,M_USER,M_LMT_LEVEL);


IF (SUBSTR(M_LIMIT_CODE,1,2)='01') THEN
    SELECT TO_DATE(TO_CHAR(SYSDATE, 'DD/MON/YYYY '),'DD/MM/YYYY') INTO M_LAST_DAILY FROM DUAL;
    DN_LIMIT_DAYEND_OVRL(M_LAST_DAILY);

ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='02') THEN
    SELECT TO_DATE(TO_CHAR(SYSDATE, 'DD/MON/YYYY '),'DD/MM/YYYY') INTO M_LAST_DAILY FROM DUAL;
    DN_LIMIT_DAYEND_OVRL_MATU(M_LAST_DAILY);

ELSIF (SUBSTR(M_LIMIT_CODE,1,2)='03') THEN
    SELECT TO_DATE(TO_CHAR(SYSDATE, 'DD/MON/YYYY '),'DD/MM/YYYY') INTO M_LAST_DAILY FROM DUAL;
    DN_LIMIT_DAYEND_OVRL_EXPO(M_LAST_DAILY);

END IF;


COMMIT;
END OVERALLTRADING_OUTAPP_LIMITS;

