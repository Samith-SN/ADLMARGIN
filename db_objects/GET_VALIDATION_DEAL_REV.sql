  CREATE OR REPLACE EDITIONABLE FUNCTION "ADLMARGIN"."GET_VALIDATION_DEAL_REV" 
(
 M_VAL_DATE        VARCHAR2-- DN_REF_PORTFOLIO.PORTFOLIO_CODE%TYPE
 )
 RETURN VARCHAR2
 AS
 M_RETURN      VARCHAR2(10);
 M_STATUS      VARCHAR2(10);
 MT_ACTIVITY   DATE;
 DR_ACTIVITY   DATE;
 MM_VAL_DATE   DATE;

 BEGIN
 
    -- Created by Udara on 03-10-2011
    
    MM_VAL_DATE := TO_DATE(M_VAL_DATE,'DD-MM-YYYY');
 
    SELECT  TO_DATE(TO_CHAR(TRUNC(A.LAST_DAILY),'DD-MM-YYYY'),'DD-MM-YYYY') MT_ACTIVITY, 
            TO_DATE(TO_CHAR(TRUNC(B.LAST_DAILY),'DD-MM-YYYY'),'DD-MM-YYYY') DR_ACTIVITY
            INTO MT_ACTIVITY,DR_ACTIVITY
    FROM ADLMARGIN.DN_SYS_DAILY_MARGIN_TRADING A, ADLMARGIN.DN_SYS_PARAMETER B;
    
    IF MM_VAL_DATE > MT_ACTIVITY AND MM_VAL_DATE > DR_ACTIVITY THEN
        M_RETURN := 'YES';
    ELSE
        M_RETURN := 'NO';
    END IF;
    
    RETURN M_RETURN; 

 END;

/
