set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "ADLMARGIN"."DN_ACC_YEAR_BACKUP" 
(
M_TRNDATE2        VARCHAR2
)
AS

/* PROCEDURE  - DN_ACC_TEST_MON_BACKUP MONTH END ROUTINE
   CREATED BY - LATHIKA
   CREATED ON - 24/01/2000*/
M_TRNDATE        DN_ACC_LICEN_INST_GEN_SUM.TRNDATE%TYPE;
BEGIN
--RAISE_APPLICATION_ERROR(-20201,'DATE'||''||M_ENT_DATE);

--M_TRNDATE :=LTRIM(RTRIM ( TO_DATE( TO_DATE(M_TRNDATE2,'DD-MM-YYYY'),'DD-MON-YYYY')  ));
-------------------(1)-------------------------
IF M_TRNDATE IS NOT NULL  THEN

INSERT INTO DN_ACC_LICEN_DETAIL_HIS
    (PORTFOLIO_CODE,TRNDATE,ACC_TYPE_CODE,DRCR_STATUS,TRNAMOUNT,DOCREFNO,ENTDATE,PROC_DESC,CORR_ACC_NO)
   SELECT
     A.PORTFOLIO_CODE,A.TRNDATE,A.ACC_TYPE_CODE,NVL(A.DRCR_STATUS,' '),NVL(A.TRNAMOUNT,0),A.DOCREFNO,A.ENTDATE,A.PROC_DESC,NVL(A.CORR_ACC_NO,' ')
   FROM
      DN_ACC_LICEN_INST_GEN_DETAIL A
   WHERE
     -- LTRIM(RTRIM(M_TRNDATE,'DD-MON-YYYY') )>LTRIM(RTRIM(TO_CHAR(A.TRNDATE,'DD-MON-YYYY')));
      TO_DATE(M_TRNDATE2,'DD-MM-YYYY') > TO_DATE(TO_CHAR(A.TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY');

 DELETE FROM DN_ACC_LICEN_INST_GEN_DETAIL B
 WHERE
   --LTRIM(RTRIM(M_TRNDATE,'DD-MON-YYYY') )>LTRIM(RTRIM(TO_CHAR(B.TRNDATE,'DD-MON-YYYY')));
    TO_DATE(M_TRNDATE2,'DD-MM-YYYY') > TO_DATE(TO_CHAR(B.TRNDATE,'DD-MM-YYYY'),'DD-MM-YYYY');
 END IF;

COMMIT;
END DN_ACC_YEAR_BACKUP;

/
